"""Multi-vertex group-lift search for the bipartite degree-diameter problem (d = 6, D = 5).

A lift with k vertices per side over a finite group G: A-vertices (i, x) and B-vertices (j, y), x, y in G,
i, j in 0..k-1.  A base multigraph M (k x k, row and column sums 6) gives each dart a voltage t in G, and the
edges are (A_i, x) ~ (B_j, x*t).  Left multiplication by G is an automorphism that is transitive on each
fibre, so the diameter is at most 5 iff every base vertex at the identity reaches all vertices within 5 steps.
That is 2k BFS runs, vectorised below.  Voltages are annealed; a found lift is checked with lib.is_valid.
Groups: SL(2,5), S5, A5 x Z3, SL(2,5) x Z3, Heisenberg(7), metacyclic Z_m x| Z_k.  If nothing is found, a
valid smaller Haar graph is returned.
"""
import math
import time

import numpy as np

import lib

TARGET = (6, 5)
DEG = 6
DIAM = 5
PATIENCE = 300
KMOVE = 6
TEMP = 1.0


def trivial(d, D):
    """Always-valid small graph for any other (d, D)."""
    if D == 3 and d >= 3 and lib.is_prime_power(d - 1) and d - 1 <= 8:
        return lib.projective_plane_incidence(d - 1)
    return lib.haar_graph(d, range(d))


def _finish(MT):
    MT = np.ascontiguousarray(MT, dtype=np.int32)
    inv = np.argmax(MT == 0, axis=1).astype(np.int64)
    return MT, inv


def closure_group(gens, mul, ident, limit=400):
    """Multiplication table of the group generated by gens (identity is element 0)."""
    elems = [ident]
    idx = {ident: 0}
    i = 0
    while i < len(elems):
        g = elems[i]
        i += 1
        for s in gens:
            h = mul(g, s)
            if h not in idx:
                idx[h] = len(elems)
                elems.append(h)
                if len(elems) > limit:
                    raise ValueError("group too large")
    N = len(elems)
    MT = np.empty((N, N), dtype=np.int32)
    for a in range(N):
        ea = elems[a]
        MT[a] = [idx[mul(ea, eb)] for eb in elems]
    return _finish(MT)


def group_meta(m, k, lam):
    """Z_m x|_lam Z_k, element (a, j) -> a*k + j, (a, j)(b, l) = (a + lam^j b, j + l)."""
    pw = np.array([pow(lam, j, m) for j in range(k)], dtype=np.int64)
    N = m * k
    g = np.arange(N, dtype=np.int64)
    a, j = g // k, g % k
    MT = np.empty((N, N), dtype=np.int32)
    for lo in range(0, N, 256):
        hi = min(N, lo + 256)
        MT[lo:hi] = ((a[lo:hi, None] + pw[j[lo:hi], None] * a[None, :]) % m) * k \
            + (j[lo:hi, None] + j[None, :]) % k
    return _finish(MT)


def _sl2_mul(p):
    def mul(x, y):
        a, b, c, d = x
        e, f, g, h = y
        return ((a * e + b * g) % p, (a * f + b * h) % p, (c * e + d * g) % p, (c * f + d * h) % p)
    return mul


def group_sl25():
    return closure_group([(1, 1, 0, 1), (0, 4, 1, 0)], _sl2_mul(5), (1, 0, 0, 1))


def group_sl25_z3():
    m2 = _sl2_mul(5)

    def mul(x, y):
        return (m2(x[0], y[0]), (x[1] + y[1]) % 3)
    return closure_group([((1, 1, 0, 1), 0), ((0, 4, 1, 0), 0), ((1, 0, 0, 1), 1)],
                         mul, ((1, 0, 0, 1), 0), limit=400)


def _perm_mul(p, q):
    return tuple(p[i] for i in q)


def group_s5():
    return closure_group([(1, 0, 2, 3, 4), (1, 2, 3, 4, 0)], _perm_mul, (0, 1, 2, 3, 4))


def group_a5_z3():
    def mul(x, y):
        return (_perm_mul(x[0], y[0]), (x[1] + y[1]) % 3)
    return closure_group([((1, 2, 0, 3, 4), 0), ((1, 2, 3, 4, 0), 0), ((0, 1, 2, 3, 4), 1)],
                         mul, ((0, 1, 2, 3, 4), 0), limit=400)


def group_heis(p):
    def mul(x, y):
        return ((x[0] + y[0]) % p, (x[1] + y[1]) % p, (x[2] + y[2] + x[0] * y[1]) % p)
    return closure_group([(1, 0, 0), (0, 1, 0), (0, 0, 1)], mul, (0, 0, 0), limit=400)


def _roots(m, k):
    return [l for l in range(2, m) if math.gcd(l, m) == 1 and pow(l, k, m) == 1 % m]


def _neighbours(MT, inv, k, di, dj, dt, idxA, idxB):
    """(2kN, DEG) neighbour array. A_i,x = i*N + x; B_j,y = k*N + j*N + y."""
    N = MT.shape[0]
    T = dt[idxA]
    J = dj[idxA]
    V = MT[:, T].transpose(1, 0, 2).astype(np.int64)          # (k, N, DEG): x*t
    nbA = k * N + J[:, None, :] * N + V
    Tb = dt[idxB]
    I = di[idxB]
    W = MT[:, inv[Tb]].transpose(1, 0, 2).astype(np.int64)    # (k, N, DEG): y*t^-1
    nbB = I[:, None, :] * N + W
    return np.concatenate([nbA.reshape(k * N, DEG), nbB.reshape(k * N, DEG)])


def _unreached(MT, inv, k, di, dj, dt, idxA, idxB, sources):
    """Number of (base source, vertex) pairs at distance > DIAM. Zero means valid."""
    N = MT.shape[0]
    nb = _neighbours(MT, inv, k, di, dj, dt, idxA, idxB)
    n = 2 * k * N
    R = np.zeros((2 * k, n), dtype=bool)
    R[np.arange(2 * k), sources] = True
    for _ in range(DIAM):
        new = R.copy()
        for c in range(DEG):
            new |= R[:, nb[:, c]]
        R = new
    return 2 * k * n - int(R.sum())


def _anneal(MT, inv, k, M, deadline, rng):
    """Anneal voltages for multiplicity matrix M. Returns the voltage array with cost 0, or None."""
    N = MT.shape[0]
    if any(sum(r) != DEG for r in M) or any(sum(M[i][j] for i in range(k)) != DEG for j in range(k)):
        return None
    di_l, dj_l = [], []
    for i in range(k):
        for j in range(k):
            di_l += [i] * M[i][j]
            dj_l += [j] * M[i][j]
    di = np.array(di_l, dtype=np.int64)
    dj = np.array(dj_l, dtype=np.int64)
    nd = len(di_l)
    idxA = np.array([np.nonzero(di == i)[0] for i in range(k)], dtype=np.int64)
    idxB = np.array([np.nonzero(dj == j)[0] for j in range(k)], dtype=np.int64)
    sources = np.array([i * N for i in range(k)] + [k * N + j * N for j in range(k)], dtype=np.int64)
    pairs = {}
    for e in range(nd):
        pairs.setdefault((int(di[e]), int(dj[e])), []).append(e)

    def cost(dt):
        return _unreached(MT, inv, k, di, dj, dt, idxA, idxB, sources)

    while time.monotonic() < deadline:
        dt = np.zeros(nd, dtype=np.int64)
        for ds in pairs.values():
            dt[ds] = rng.choice(N, size=len(ds), replace=False)   # distinct voltages inside a pair
        cur = cost(dt)
        run_best = cur
        stall = 0
        while cur > 0 and stall < PATIENCE and time.monotonic() < deadline:
            best_c, best_t = None, None
            for _ in range(KMOVE):
                e = int(rng.integers(nd))
                used = {int(dt[f]) for f in pairs[(int(di[e]), int(dj[e]))] if f != e}
                t = int(rng.integers(N))
                while t in used:
                    t = int(rng.integers(N))
                trial = dt.copy()
                trial[e] = t
                c = cost(trial)
                if best_c is None or c < best_c:
                    best_c, best_t = c, trial
            delta = best_c - cur
            if delta <= 0 or rng.random() < math.exp(-delta / TEMP):
                dt, cur = best_t, best_c
            if cur < run_best:
                run_best = cur
                stall = 0
            else:
                stall += 1
        if cur == 0:
            return dt
    return None


def _build(MT, k, M, dt):
    N = MT.shape[0]
    edges = []
    e = 0
    for i in range(k):
        for j in range(k):
            for _ in range(M[i][j]):
                t = int(dt[e])
                e += 1
                col = MT[:, t].tolist()
                for x in range(N):
                    edges.append((i * N + x, k * N + j * N + col[x]))
    return 2 * k * N, edges


def _fallback_graph():
    """Valid Haar graph of order 660 (group Z_33 x| Z_10), checked by the caller."""
    MT, _ = group_meta(33, 10, 26)
    S = [0, 179, 116, 180, 47, 306]
    N = MT.shape[0]
    g = np.arange(N)
    edges = [(int(a), int(N + b)) for s in sorted(set(S)) for a, b in zip(g, MT[s])]
    return 2 * N, edges


def _jobs():
    m2a = [[3, 3], [3, 3]]
    m2b = [[2, 4], [4, 2]]
    m3a = [[2, 2, 2], [2, 2, 2], [2, 2, 2]]
    m3b = [[4, 1, 1], [1, 4, 1], [1, 1, 4]]
    m3c = [[3, 2, 1], [2, 1, 3], [1, 3, 2]]
    jobs = [
        ("A5xZ3 k2 33", group_a5_z3, 2, m2a, 3.0),
        ("A5xZ3 k2 24", group_a5_z3, 2, m2b, 2.0),
        ("SL25 k3 222", group_sl25, 3, m3a, 3.0),
        ("SL25 k3 411", group_sl25, 3, m3b, 2.0),
        ("S5 k3 321", group_s5, 3, m3c, 2.0),
        ("Heis7 k1", lambda: group_heis(7), 1, [[6]], 3.0),
        ("SL25xZ3 k1", group_sl25_z3, 1, [[6]], 1.0),
    ]
    for N in range(172, 181, 2):          # k = 2, n = 4N in 688..720
        m = N // 2
        for idx, lam in enumerate(_roots(m, 2)[:2]):
            M = m2a if idx == 0 else m2b
            jobs.append((f"meta {m}x|2 lam{lam}", (lambda m=m, lam=lam: group_meta(m, 2, lam)),
                         2, M, 1.0))
    for N in (117, 120):                  # k = 3, n = 6N in 702..720
        m = N // 3
        for idx, lam in enumerate(_roots(m, 3)[:2]):
            M = [m3a, m3b, m3c][idx % 3]
            jobs.append((f"meta {m}x|3 lam{lam}", (lambda m=m, lam=lam: group_meta(m, 3, lam)),
                         3, M, 1.0))
    return jobs


def build(d, D, seed, time_limit):
    if (d, D) != TARGET:
        return trivial(d, D)
    t0 = time.monotonic()
    deadline_all = t0 + max(1.0, 0.8 * time_limit - 2.0)
    rng = np.random.default_rng(seed)
    jobs = _jobs()
    total_w = sum(job[-1] for job in jobs)
    for name, builder, k, M, w in jobs:
        now = time.monotonic()
        if now >= deadline_all:
            break
        end = now + (deadline_all - now) * w / total_w
        total_w -= w
        try:
            MT, inv = builder()
            dt = _anneal(MT, inv, k, M, end, rng)
        except Exception:
            continue
        if dt is not None:
            try:
                n, edges = _build(MT, k, M, dt)
                if lib.is_valid(n, edges, d, D):
                    return n, edges
            except Exception:
                pass
    try:
        n, edges = _fallback_graph()
        if lib.is_valid(n, edges, d, D):
            return n, edges
    except Exception:
        pass
    return trivial(d, D)
