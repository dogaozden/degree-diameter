def _random_lift2(n, edges, rng):
    """Random Z_2 lift: edge (u, v) becomes (u, i)-(v, i XOR s) for i in {0, 1}."""
    out = []
    for u, v in edges:
        s = rng.randrange(2)
        for i in range(2):
            out.append((u + n * i, v + n * (i ^ s)))
    return 2 * n, out


def _lift_search(n, edges, d, D, deadline, rng, consider):
    """Repeatedly lift the current graph, repair it, and keep any valid enlargement."""
    cur_n, cur_e = n, list(edges)
    while time.monotonic() < deadline:
        n2, e2 = _random_lift2(cur_n, cur_e, rng)
        adj = _to_sets(n2, e2)
        color = _bipartition(n2, adj)
        _fill(adj, color, d, rng)
        if not _anneal(adj, color, d, D, rng, 400, deadline):
            continue
        e3 = [(u, v) for u in range(n2) for v in adj[u] if u < v]
        n4, e4 = _grow(n2, e3, d, D, deadline, rng, attempts=16)
        consider(n4, e4)
        if n4 > cur_n and lib.is_valid(n4, e4, d, D):
            cur_n, cur_e = n4, e4


def _repair(d, D, n, edges, deadline, rng, consider):
    """Repeatedly try to add one vertex to the current valid graph, repairing with annealing."""
    adj = _to_sets(n, edges)
    color = _bipartition(n, adj)
    while time.monotonic() < deadline:
        snap_adj = [set(s) for s in adj]
        snap_color = list(color)
        side = rng.randrange(2)
        _add_vertex(adj, color, d, D, side, rng)
        _fill(adj, color, d, rng)
        if _anneal(adj, color, d, D, rng, 1500, deadline):
            m = len(adj)
            e = [(u, v) for u in range(m) for v in adj[u] if u < v]
            consider(m, e)
        else:
            adj[:] = snap_adj
            color[:] = snap_color


def build(d, D, seed, time_limit):
    start = time.monotonic()
    deadline = start + 0.85 * time_limit
    rng = random.Random(seed)

    if D == 1 and d >= 1:
        return 2, [(0, 1)]
    if d < 1 or D < 1:
        return 1, []

    # Safe fallback: K_{d,d}, valid for D >= 2.
    n0, e0 = lib.haar_graph(d, range(d))
    state = {'n': n0, 'e': list(e0)}

    def size():
        return state['n']

    def consider(n, e):
        if n > state['n'] and lib.is_valid(n, e, d, D):
            state['n'] = n
            state['e'] = list(e)

    # Structured bases: generalized quadrangle for D >= 4, projective plane for D = 3.
    base_n, base_e = state['n'], list(state['e'])
    if D >= 3:
        base = _best_gq(d) if D >= 4 else None
        if base is None:
            base = _best_pg(d)
        if base is not None:
            bn, be = base
            consider(bn, be)
            base_n, base_e = bn, list(be)
            grow_end = start + 0.15 * time_limit
            n1, e1 = _grow(bn, be, d, D, grow_end, rng)
            consider(n1, e1)

    # Bold stage: group-lift search for graphs larger than the current best.
    if D >= 2 and time.monotonic() < deadline:
        group_end = start + 0.40 * time_limit
        _group_search(d, D, group_end, rng, consider, size)

    # Randomized twin-duplication pipelines from the structured base.
    if D >= 2 and time.monotonic() < deadline:
        trial_end = start + 0.48 * time_limit
        while time.monotonic() < trial_end:
            n, e = _trial(base_n, base_e, d, D, rng, trial_end)
            consider(n, e)

    # Kill-repair-regrow search from the best valid graph found so far.
    if D >= 2 and time.monotonic() < deadline:
        lns_end = start + 0.62 * time_limit
        _lns(state['n'], state['e'], d, D, lns_end, rng, consider)

    # Random 2-lifts of the best graph, repaired by annealing.
    if D >= 2 and time.monotonic() < deadline:
        lift_end = start + 0.78 * time_limit
        _lift_search(state['n'], state['e'], d, D, lift_end, rng, consider)

    # Add-and-repair from the largest valid graph found so far.
    if D >= 2 and time.monotonic() < deadline:
        _repair(d, D, state['n'], state['e'], deadline, rng, consider)

    best_n, best_e = state['n'], state['e']
    if not lib.is_valid(best_n, best_e, d, D):
        return lib.haar_graph(d, range(d))
    return best_n, list(best_e)
