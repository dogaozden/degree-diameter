# Twin duplication.
# ----------------------------------------------------------------------------

def _duplicate_twins(n, edges, d, rng):
    """Greedily add twins in random order while neighbours have spare degree."""
    adj = [set() for _ in range(n)]
    for u, v in edges:
        adj[u].add(v)
        adj[v].add(u)
    changed = True
    while changed:
        changed = False
        order = list(range(len(adj)))
        rng.shuffle(order)
        for v in order:
            nb = adj[v]
            if not nb or len(nb) > d:
                continue
            if any(len(adj[u]) >= d for u in nb):
                continue
            w = len(adj)
            adj.append(set(nb))
            for u in nb:
                adj[u].add(w)
            changed = True
    out = [(u, v) for u in range(len(adj)) for v in adj[u] if u < v]
    return len(adj), out


def _trial(base_n, base_e, d, D, rng, deadline):
    """One randomized pipeline: mix twin duplication with cover growth and saturation."""
    mode = rng.randrange(3)
    n, e = base_n, list(base_e)
    if mode == 0:
        n, e = _duplicate_twins(n, e, d, rng)
        e = _saturate_edges(n, e, d, rng)
        n, e = _grow(n, e, d, D, deadline, rng)
    elif mode == 1:
        n, e = _grow(n, e, d, D, deadline, rng)
        n, e = _duplicate_twins(n, e, d, rng)
        e = _saturate_edges(n, e, d, rng)
        n, e = _grow(n, e, d, D, deadline, rng)
    else:
        e = _saturate_edges(n, e, d, rng)
        n, e = _duplicate_twins(n, e, d, rng)
        e = _saturate_edges(n, e, d, rng)
        n, e = _grow(n, e, d, D, deadline, rng)
    return n, e


# ----------------------------------------------------------------------------
# Thin a dense structured graph into a valid one.
# ----------------------------------------------------------------------------

def _reduce_degree(n, edges, d, rng):
    adj = [set() for _ in range(n)]
    for u, v in edges:
        adj[u].add(v)
        adj[v].add(u)
    over = [v for v in range(n) if len(adj[v]) > d]
    while over:
        v = over.pop()
        while len(adj[v]) > d:
            u = max(adj[v], key=lambda x: (len(adj[x]), rng.random()))
            adj[v].discard(u)
            adj[u].discard(v)
            if len(adj[u]) > d:
                over.append(u)
    return [(u, v) for u in range(n) for v in adj[u] if u < v]


def _delete_to_valid(n, edges, d, D, rng, deadline):
    """Delete the worst vertices in batches until the diameter bound holds. Returns (n, edges) or None."""
    adj = {v: set() for v in range(n)}
    for u, v in edges:
        adj[u].add(v)
        adj[v].add(u)
    while time.monotonic() < deadline:
        verts = sorted(adj)
        m = len(verts)
        if m == 0:
            return None
        idx = {v: i for i, v in enumerate(verts)}
        nbr = [[idx[u] for u in adj[v]] for v in verts]
        ball = _balls_radius(m, nbr, D)
        bad = [m - b.bit_count() for b in ball]
        if sum(bad) == 0:
            out = [(idx[v], idx[u]) for v in verts for u in adj[v] if v < u]
            return m, out
        order = sorted(range(m), key=lambda i: (-bad[i], rng.random()))
        k = max(1, m // 50)
        for i in order[:k]:
            v = verts[i]
            if v not in adj:
                continue
            for u in adj[v]:
                adj[u].discard(v)
            del adj[v]
    return None


def _deletion_trial(d, D, raw_n, raw_e, rng, deadline):
    """One thinning trial from the dense raw graph. Returns (n, edges) valid, or None."""
    e = _reduce_degree(raw_n, raw_e, d, rng)
    r = _delete_to_valid(raw_n, e, d, D, rng, deadline)
    if r is None:
        return None
    n2, e2 = r
    return _grow(n2, e2, d, D, deadline, rng)


# ----------------------------------------------------------------------------
# Large-neighbourhood search (kill, repair, regrow).
# ----------------------------------------------------------------------------

def _cost(adj, D):
    """Number of vertex pairs at distance more than D (unreachable pairs count)."""
    n = len(adj)
    ball = _balls_radius(n, adj, D)
    return sum(n - b.bit_count() for b in ball) // 2


def _fill(adj, color, d, rng):
    """Add cross-side edges between deficient vertices (only helps the diameter)."""
    n = len(adj)
    left = [v for v in range(n) if color[v] == 0 and len(adj[v]) < d]
    right = [v for v in range(n) if color[v] == 1 and len(adj[v]) < d]
    pairs = [(a, b) for a in left for b in right if b not in adj[a]]
    rng.shuffle(pairs)
    for a, b in pairs:
        if len(adj[a]) < d and len(adj[b]) < d and b not in adj[a]:
            adj[a].add(b)
            adj[b].add(a)


def _anneal(adj, color, d, D, rng, iters, deadline):
    """Bipartite double-edge switches (degrees unchanged) minimising bad pairs. True if cost reaches 0."""
    cur = _cost(adj, D)
    side0 = [v for v in range(len(adj)) if color[v] == 0]
    for _ in range(iters):
        if cur == 0 or time.monotonic() > deadline:
            break
        a = rng.choice(side0)
        if not adj[a]:
            continue
        b = rng.choice(tuple(adj[a]))
        c = rng.choice(side0)
        if c == a or not adj[c]:
            continue
        e = rng.choice(tuple(adj[c]))
        if e in adj[a] or b in adj[c]:
            continue
        adj[a].discard(b)
        adj[b].discard(a)
        adj[c].discard(e)
        adj[e].discard(c)
        adj[a].add(e)
        adj[e].add(a)
        adj[c].add(b)
        adj[b].add(c)
        new = _cost(adj, D)
        if new <= cur or (new == cur + 1 and rng.random() < 0.1):
            cur = new
        else:
            adj[a].discard(e)
            adj[e].discard(a)
            adj[c].discard(b)
            adj[b].discard(c)
            adj[a].add(b)
            adj[b].add(a)
            adj[c].add(e)
            adj[e].add(c)
    return cur == 0


def _lns(n, edges, d, D, deadline, rng, consider):
    """Kill-repair-regrow large-neighbourhood search from a valid graph, anchored to its best."""
    cur_n, cur_e = n, list(edges)
    best_n, best_e = n, list(edges)
    while time.monotonic() < deadline:
        k = rng.choice((1, 1, 2, 2, 3, 4))
        if k >= cur_n:
            break
        kill = set(rng.sample(range(cur_n), k))
        keep = [v for v in range(cur_n) if v not in kill]
        remap = {v: i for i, v in enumerate(keep)}
        m = len(keep)
        e2 = [(remap[u], remap[v]) for u, v in cur_e if u not in kill and v not in kill]
        adj = _to_sets(m, e2)
        color = _bipartition(m, adj)
        _fill(adj, color, d, rng)
        if not _anneal(adj, color, d, D, rng, 150, deadline):
            continue
        e3 = [(u, v) for u in range(m) for v in adj[u] if u < v]
        n4, e4 = _grow(m, e3, d, D, deadline, rng)
        consider(n4, e4)
        if n4 > best_n:
            best_n, best_e = n4, list(e4)
        if n4 >= cur_n - 1:
            cur_n, cur_e = n4, e4
        elif n4 < best_n - 3:
            cur_n, cur_e = best_n, list(best_e)


def _prune_redundant(n, edges, D, rng, deadline, max_tests):
    """Delete random redundant edges (keeping diameter <= D). Returns the pruned edge list."""
    adj = _to_sets(n, edges)
    cand = list(edges)
    rng.shuffle(cand)
    tests = 0
    for u, v in cand:
        if tests >= max_tests or time.monotonic() > deadline:
            break
        if v not in adj[u]:
            continue
        tests += 1
        adj[u].discard(v)
        adj[v].discard(u)
        if _cost(adj, D) != 0:
            adj[u].add(v)
            adj[v].add(u)
    return [(a, b) for a in range(n) for b in adj[a] if a < b]


def _prune_regrow(n, edges, d, D, deadline, rng, consider):
    """Repeatedly prune redundant edges, regrow with cover vertices, keep the best."""
    best_n, best_e = n, list(edges)
    cur_n, cur_e = n, list(edges)
    while time.monotonic() < deadline:
        pe = _prune_redundant(cur_n, cur_e, D, rng, deadline, 160)
        n2, e2 = _grow(cur_n, pe, d, D, deadline, rng)
        consider(n2, e2)
        if n2 > best_n:
            best_n, best_e = n2, list(e2)
        if n2 >= cur_n - 1:
            cur_n, cur_e = n2, list(e2)
        elif n2 < best_n - 2 or rng.random() < 0.3:
            cur_n, cur_e = best_n, list(best_e)


# ----------------------------------------------------------------------------
# NEW: bi-Cayley (group lift) search.
# Vertices A = {a_x} and B = {b_y} for x, y in a finite group G of order M.
# Each a_x is joined to b_{x*g} for g in a connection set S of size d.
# Left multiplication is an automorphism acting regularly on A and on B, so the
# diameter is determined by BFS from a_identity and b_identity alone. A valid
# S gives a d-regular bipartite graph on 2M vertices.
# ----------------------------------------------------------------------------

def _group_specs(M):
    """Candidate groups of order M: the cyclic group, and semidirect products Z_m x| Z_k."""
    specs = [('c', M)]
    for k in range(2, 13):
        if M % k:
            continue
        m = M // k
        if m < 3:
            continue
        for r in range(2, m):
            if math.gcd(r, m) == 1 and pow(r, k, m) == 1 % m:
                specs.append(('s', m, k, r))
    return specs


def _group_tables(spec):
    """Return (M, T, inv): T[x, y] = x*y as an int64 table, inv[x] = x^{-1}. Identity is element 0."""
    if spec[0] == 'c':
        M = spec[1]
        X = np.arange(M, dtype=np.int64)
        T = (X[:, None] + X[None, :]) % M
        inv = (-X) % M
        return M, T, inv
    _, m, k, r = spec
    M = m * k
    X = np.arange(M, dtype=np.int64)
    a = X // k
    b = X % k
    pw = np.array([pow(r, j, m) for j in range(k)], dtype=np.int64)
    T = ((a[:, None] + pw[b][:, None] * a[None, :]) % m) * k + (b[:, None] + b[None, :]) % k
    nb = (-b) % k
    inv = ((-pw[nb] * a) % m) * k + nb
    return M, T.astype(np.int64), inv.astype(np.int64)


def _lift_cost(T, inv, S, M, D):
    """Number of (root, vertex) pairs not within distance D, for roots a_0 and b_0 (0 means valid)."""
    iS = [int(inv[g]) for g in S]
    total = 0
    for rootA in (True, False):
        A = np.zeros(M, dtype=bool)
        B = np.zeros(M, dtype=bool)
        if rootA:
            A[0] = True
        else:
            B[0] = True
        for _ in range(D):
            nA = A.copy()
            nB = B.copy()
            ai = np.flatnonzero(A)
            if ai.size:
                for g in S:
                    nB[T[ai, g]] = True
            bi = np.flatnonzero(B)
            if bi.size:
                for h in iS:
                    nA[T[bi, h]] = True
            A, B = nA, nB
        total += 2 * M - int(A.sum()) - int(B.sum())
    return total


def _sa_lift(T, inv, M, d, D, rng, iters, deadline):
    """Simulated annealing over connection sets S of size d. Returns S with cost 0, or None."""
    S = rng.sample(range(M), d)
    cur = _lift_cost(T, inv, S, M, D)
    for it in range(iters):
        if cur == 0:
            return S
        if (it & 31) == 0 and time.monotonic() >= deadline:
            break
        temp = 2.0 * (0.05 ** (it / max(1, iters)))
        i = rng.randrange(d)
        g = rng.randrange(M)
        if g in S:
            continue
        trial = S[:]
        trial[i] = g
        c = _lift_cost(T, inv, trial, M, D)
        if c <= cur or rng.random() < math.exp(-(c - cur) / temp):
            S, cur = trial, c
    return S if cur == 0 else None


def _consider(state, d, D, n, e):
    if n > state['n'] and lib.is_valid(n, e, d, D):
        state['n'] = n
        state['e'] = list(e)


def _lift_phase(d, D, lo, hi, deadline, rng, state):
    """Search bi-Cayley graphs of degree d on 2M vertices, for M in [lo, hi], in growing passes."""
    cands = list(range(lo, hi + 1))
    specs = {}
    pas = 0
    while cands and time.monotonic() < deadline:
        pas += 1
        iters = min(4000, 300 * pas)
        for M in list(cands):
            if time.monotonic() >= deadline:
                break
            if M not in cands:
                continue
            if M not in specs:
                sp = _group_specs(M)
                rng.shuffle(sp)
                specs[M] = sp
            sp = specs[M]
            spec = sp[(pas - 1) % len(sp)]
            Mm, T, inv = _group_tables(spec)
            S = _sa_lift(T, inv, Mm, d, D, rng, iters, deadline)
            if S is None:
                continue
            edges = []
            for g in S:
                col = T[:, g].tolist()
                edges.extend((x, Mm + col[x]) for x in range(Mm))
            _consider(state, d, D, 2 * Mm, edges)
            # Success: only larger orders are worth pursuing now.
            cands = [c for c in cands if c > Mm]


# ----------------------------------------------------------------------------
# Parent pipeline (unchanged search phases, now writing into `state`).
# ----------------------------------------------------------------------------

def _run_parent(d, D, rng, start, T, state):
    def at(f):
        return start + f * T

    def consider(n, e):
        _consider(state, d, D, n, e)

    base_n, base_e = state['n'], list(state['e'])
    if D >= 3:
        base = _best_gq(d) if D >= 4 else None
        if base is None:
            base = _best_pg(d)
        if base is not None:
            n0, e0 = base
            consider(n0, e0)
            base_n, base_e = n0, list(e0)
            n1, e1 = _grow(n0, e0, d, D, at(0.10), rng)
            consider(n1, e1)
    if D >= 2:
        trial_end = at(0.20)
        while time.monotonic() < trial_end:
            n, e = _trial(base_n, base_e, d, D, rng, trial_end)
            consider(n, e)
        _lns(state['n'], list(state['e']), d, D, at(0.40), rng, consider)

    if D >= 2 and time.monotonic() < at(0.55):
        raw = _raw_big(d, D)
        if raw is not None:
            rn, re = raw
            while time.monotonic() < at(0.55):
                r = _deletion_trial(d, D, rn, re, rng, at(0.55))
                if r is None:
                    break
                consider(*r)

    if D >= 2 and time.monotonic() < at(0.75):
        _lns(state['n'], list(state['e']), d, D, at(0.75), rng, consider)

    if D >= 2 and time.monotonic() < at(1.0):
        _prune_regrow(state['n'], list(state['e']), d, D, at(1.0), rng, consider)


# ----------------------------------------------------------------------------
# Driver. Budget T = 0.85 * time_limit.
#   For d >= 4 and D >= 4: parent pipeline gets the first half, then the bi-Cayley
#   group-lift search gets the rest, aimed at orders above the parent's.
#   Otherwise the parent pipeline gets the whole budget.
# Every candidate passes lib.is_valid before it is kept; K_{d,d}-style haar graph is the fallback.
# ----------------------------------------------------------------------------

def build(d, D, seed, time_limit):
    start = time.monotonic()
    T = 0.85 * time_limit
    rng = random.Random(seed)

    if D == 1 and d >= 1:
        return 2, [(0, 1)]
    if d < 1 or D < 1:
        return 1, []

    fallback = lib.haar_graph(d, range(d))
    state = {'n': fallback[0], 'e': list(fallback[1])}

    use_lift = D >= 4 and d >= 4
    T_par = (0.5 if use_lift else 1.0) * T

    try:
        _run_parent(d, D, rng, start, T_par, state)
    except Exception:
        pass

    if use_lift and time.monotonic() < start + T:
        lo = state['n'] // 2 + 1
        hi = sum((d - 1) ** i for i in range(D))
        if lo <= hi:
            try:
                _lift_phase(d, D, lo, hi, start + T, rng, state)
            except Exception:
                pass

    if not lib.is_valid(state['n'], state['e'], d, D):
        return fallback
    return state['n'], list(state['e'])
