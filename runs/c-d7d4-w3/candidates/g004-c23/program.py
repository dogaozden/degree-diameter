def _balls_radius(n, adj, r):
    """Bitmask per vertex of all vertices within distance r."""
    ball = [1 << v for v in range(n)]
    for _ in range(r):
        new = []
        for v in range(n):
            x = ball[v]
            for u in adj[v]:
                x |= ball[u]
            new.append(x)
        ball = new
    return ball


def _bipartition(n, adj):
    """Two-colouring of a bipartite graph given by adjacency lists or sets."""
    color = [-1] * n
    for s in range(n):
        if color[s] != -1:
            continue
        color[s] = 0
        stack = [s]
        while stack:
            u = stack.pop()
            for v in adj[u]:
                if color[v] == -1:
                    color[v] = 1 - color[u]
                    stack.append(v)
    return color


def _greedy_cover(cands, ball, full, d, rng, randomize):
    """Greedy set cover of `full` by at most d candidate vertices. Returns list or None."""
    pool = list(cands)
    if randomize:
        rng.shuffle(pool)
    covered = 0
    chosen = []
    while covered != full and len(chosen) < d and pool:
        gains = [(ball[s] & ~covered).bit_count() for s in pool]
        best_g = max(gains, default=0)
        if best_g == 0:
            break
        thr = best_g
        if randomize and rng.random() < 0.5:
            thr = best_g - 1
        opts = [i for i, g in enumerate(gains) if g >= thr and g > 0]
        i = rng.choice(opts) if randomize else opts[0]
        s = pool.pop(i)
        chosen.append(s)
        covered |= ball[s]
    return chosen if covered == full else None


def _extend_cover(n, edges, d, D, deadline, rng):
    """Greedily add vertices whose neighbourhoods cover all vertices within D-1 of a side."""
    if D < 2:
        return n, edges
    edges = list(edges)
    adj = [[] for _ in range(n)]
    for u, v in edges:
        adj[u].append(v)
        adj[v].append(u)
    deg = [len(a) for a in adj]
    color = _bipartition(n, adj)

    while time.monotonic() < deadline:
        ball = _balls_radius(n, adj, D - 1)
        full = (1 << n) - 1
        added = False
        for c in (0, 1):
            cands = [s for s in range(n) if color[s] == c and deg[s] < d]
            if not cands:
                continue
            chosen = None
            for attempt in range(60):
                if time.monotonic() >= deadline:
                    break
                chosen = _greedy_cover(cands, ball, full, d, rng, attempt > 0)
                if chosen:
                    break
            if chosen:
                v = n
                n += 1
                color.append(1 - c)
                adj.append([])
                deg.append(0)
                for s in chosen:
                    edges.append((s, v))
                    adj[s].append(v)
                    adj[v].append(s)
                    deg[s] += 1
                    deg[v] += 1
                added = True
                break
        if not added:
            break
    return n, edges


def _saturate_edges(n, edges, d, rng):
    """Greedily join deficient opposite-side vertices in random order. Keeps validity."""
    edges = list(edges)
    adj = [[] for _ in range(n)]
    existing = set()
    for u, v in edges:
        adj[u].append(v)
        adj[v].append(u)
        existing.add((min(u, v), max(u, v)))
    deg = [len(a) for a in adj]
    color = _bipartition(n, adj)
    left = [v for v in range(n) if color[v] == 0 and deg[v] < d]
    right = [v for v in range(n) if color[v] == 1 and deg[v] < d]
    pairs = [(a, b) for a in left for b in right
             if (min(a, b), max(a, b)) not in existing]
    rng.shuffle(pairs)
    for a, b in pairs:
        if deg[a] < d and deg[b] < d:
            edges.append((a, b))
            deg[a] += 1
            deg[b] += 1
    return edges


def _grow(n, edges, d, D, deadline, rng):
    """Extend by cover vertices, then saturate edges with the remaining spare degree."""
    cur_n, cur_e = n, list(edges)
    for _ in range(6):
        if time.monotonic() >= deadline:
            break
        n2, e2 = _extend_cover(cur_n, cur_e, d, D, deadline, rng)
        grew = n2 != cur_n
        cur_n = n2
        cur_e = _saturate_edges(cur_n, e2, d, rng)
        if not grew:
            break
    return cur_n, cur_e


# ----------------------------------------------------------------------------
# New construction: cyclic voltage lifts of small bipartite base multigraphs,
# found by annealing the voltages (not by growing a fixed structure).
#
# Base: p "A" vertices and p "B" vertices. Each base vertex has degree d; the
# darts come from d random permutations (dart (i, p + sigma(i), voltage)).
# Lift: order 2*p*m. Fibres are Z_m-symmetric, so the diameter check only needs
# one BFS source per base vertex.
# ----------------------------------------------------------------------------

def _lift_adj(n, edges):
    adj = [[] for _ in range(n)]
    for u, v in edges:
        adj[u].append(v)
        adj[v].append(u)
    return adj


def _ball_count(adj, s, D):
    """Number of vertices within distance D of s."""
    seen = {s}
    frontier = [s]
    for _ in range(D):
        nxt = []
        for u in frontier:
            for v in adj[u]:
                if v not in seen:
                    seen.add(v)
                    nxt.append(v)
        if not nxt:
            break
        frontier = nxt
    return len(seen)


def _voltage_cost(p, m, darts, D):
    """(bad pairs per fibre sum, n, edges) for the lift. Cost 0 means diameter <= D."""
    n, edges = lib.voltage_lift(2 * p, darts, m)
    adj = _lift_adj(n, edges)
    cost = 0
    for i in range(2 * p):
        cost += n - _ball_count(adj, i * m, D)
    return cost, n, edges


def _random_darts(p, d, m, rng):
    darts = []
    for _ in range(d):
        perm = list(range(p))
        rng.shuffle(perm)
        for i in range(p):
            darts.append([i, p + perm[i], rng.randrange(m)])
    return darts


def _anneal_lift(p, m, d, D, rng, deadline):
    """Anneal voltages of a random base until the lift has diameter <= D. Returns (n, edges) or None."""
    darts = _random_darts(p, d, m, rng)
    cur_cost, cur_n, cur_e = _voltage_cost(p, m, darts, D)
    while cur_cost > 0 and time.monotonic() < deadline:
        k = rng.randrange(len(darts))
        old = darts[k][2]
        darts[k][2] = rng.randrange(m)
        c2, n2, e2 = _voltage_cost(p, m, darts, D)
        if c2 <= cur_cost or rng.random() < 0.02:
            cur_cost, cur_n, cur_e = c2, n2, e2
        else:
            darts[k][2] = old
    if cur_cost == 0:
        return cur_n, cur_e
    return None


# ----------------------------------------------------------------------------
# Driver.
#   A  structured base (W(q) or PG(2,q)) grown with covers (safe, about 0.12 T)
#   B  voltage-lift annealing with random small bases and grow on each hit
# Every candidate passes lib.is_valid before it is kept. K_{d,d} is the fallback.
# ----------------------------------------------------------------------------

def build(d, D, seed, time_limit):
    start = time.monotonic()
    T = 0.85 * time_limit

    def at(f):
        return start + f * T

    rng = random.Random(seed)

    if D == 1 and d >= 1:
        return 2, [(0, 1)]
    if d < 1 or D < 1:
        return 1, []

    best_n, best_e = lib.haar_graph(d, range(d))
    moore = lib.moore_bound(d, D)
    if best_n >= moore:
        return best_n, list(best_e)

    def consider(n, e):
        nonlocal best_n, best_e
        if n > best_n and lib.is_valid(n, e, d, D):
            best_n, best_e = n, list(e)

    # Phase A: structured base, grown.
    if D >= 3:
        base = _best_gq(d) if D >= 4 else None
        if base is None:
            base = _best_pg(d)
        if base is not None:
            n0, e0 = base
            consider(n0, e0)
            n1, e1 = _grow(n0, e0, d, D, at(0.12), rng)
            consider(n1, e1)

    # Phase B: voltage-lift annealing over small bases, grown when a lift works.
    if D >= 2:
        lift_end = at(0.95)
        while time.monotonic() < lift_end:
            options = [p for p in (2, 3, 4, 5, 6)
                       if 2 * p * (best_n // (2 * p) + 1) <= moore]
            if not options:
                break
            p = rng.choice(options)
            need = best_n // (2 * p) + 1
            m = need + rng.randrange(3)
            if 2 * p * m > moore:
                m = need
            sub_end = min(lift_end, time.monotonic() + 3.0)
            res = _anneal_lift(p, m, d, D, rng, sub_end)
            if res is None:
                continue
            n, e = res
            consider(n, e)
            n2, e2 = _grow(n, e, d, D, min(lift_end, time.monotonic() + 4.0), rng)
            consider(n2, e2)

    if not lib.is_valid(best_n, best_e, d, D):
        return lib.haar_graph(d, range(d))
    return best_n, list(best_e)
