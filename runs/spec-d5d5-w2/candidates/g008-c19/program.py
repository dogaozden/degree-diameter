import math
import random
import time

import lib


# ----------------------------------------------------------------------------
# Tunables.
# ----------------------------------------------------------------------------

MAX_GROUPS = 4        # groups tried per bi-Cayley order N
ANNEAL_ITERS = 200    # annealing steps per (group, connection set) try
SEMI_SAMPLE = 8       # semidirect parameter sets sampled per order
_MAX_ELEMS = 400      # give up on permutation groups larger than this


# ----------------------------------------------------------------------------
# D = 3 baseline: projective plane incidence graph.
# ----------------------------------------------------------------------------

def _best_pg(d):
    """Incidence graph of PG(2, q) for the largest prime power q with q + 1 <= d."""
    for q in range(d - 1, 1, -1):
        if lib.is_prime_power(q):
            return lib.projective_plane_incidence(q)
    return None


# ----------------------------------------------------------------------------
# New: permutation-group bi-Cayley lifts.
#
# Groups are generated as permutation groups from small generator sets, so
# non-abelian groups that are not semidirect products of a cyclic group by a
# cyclic group become available: A5 x Z_k, S4 x Z_k, A4 x Z_k, SL(2,5) x Z_k,
# S4 x A4, and so on. Each group gives a bi-Cayley graph on A_x, B_y (x, y in G)
# with edges A_x -- B_{x s} for s in S, |S| = d. Left multiplication is an
# automorphism, so the diameter check only needs BFS from A_e and B_e.
# ----------------------------------------------------------------------------

def _compose(p, q):
    """Permutation p followed by q, so (p*q)[i] = q[p[i]]."""
    return tuple(q[i] for i in p)


def _closure(gens):
    """Return (elements, index) of the permutation group generated by gens, identity first; None if too big."""
    n = len(gens[0])
    e = tuple(range(n))
    elems = [e]
    idx = {e: 0}
    i = 0
    while i < len(elems):
        cur = elems[i]
        for g in gens:
            h = _compose(cur, g)
            if h not in idx:
                if len(elems) >= _MAX_ELEMS:
                    return None
                idx[h] = len(elems)
                elems.append(h)
        i += 1
    return elems, idx


def _product(factors):
    """Generators of the direct product of permutation groups; factors = [(size, local_gens), ...]."""
    total = sum(size for size, _ in factors)
    gens = []
    off = 0
    for size, lg in factors:
        for g in lg:
            p = list(range(total))
            for i, v in enumerate(g):
                p[off + i] = off + v
            gens.append(tuple(p))
        off += size
    return gens


def _cyc(k):
    """Cyclic group Z_k acting on k points."""
    return (k, [tuple((i + 1) % k for i in range(k))])


def _sl25():
    """SL(2,5) acting on the 24 nonzero vectors of GF(5)^2."""
    pts = [(a, b) for a in range(5) for b in range(5) if (a, b) != (0, 0)]
    pid = {p: i for i, p in enumerate(pts)}

    def mat(p, q, r, s):
        return tuple(pid[((p * x + q * y) % 5, (r * x + s * y) % 5)] for x, y in pts)

    return (24, [mat(1, 1, 0, 1), mat(0, 4, 1, 0)])


_A5 = (5, [(1, 2, 3, 4, 0), (1, 2, 0, 3, 4)])
_S4 = (4, [(1, 2, 3, 0), (1, 0, 2, 3)])
_A4 = (4, [(1, 2, 0, 3), (1, 0, 3, 2)])


def _finish(T):
    """Return (T, inv) for a multiplication table T with identity at index 0."""
    N = len(T)
    inv = [0] * N
    for x in range(N):
        row = T[x]
        for y in range(N):
            if row[y] == 0:
                inv[x] = y
                break
    return T, inv


def _perm_builder(elems, idx):
    """Deferred builder of the multiplication table of a permutation group."""
    def build():
        N = len(elems)
        T = [[idx[_compose(elems[x], elems[y])] for y in range(N)] for x in range(N)]
        return _finish(T)
    return build


def _perm_groups(hi):
    """Return dict order -> [builder] for direct products of small permutation groups with order <= hi."""
    bases = [_A5, _S4, _A4, _sl25()]
    specs = []
    for base in bases:
        bo = len(_closure(_product([base]))[0])
        for k in range(1, hi // bo + 1):
            specs.append([base] if k == 1 else [base, _cyc(k)])
    specs.append([_A5, _cyc(2), _cyc(2)])
    specs.append([_S4, _A4])
    specs.append([_A4, _cyc(2), _cyc(2)])
    table = {}
    for spec in specs:
        cl = _closure(_product(spec))
        if cl is None:
            continue
        order = len(cl[0])
        if order < 6 or order > hi:
            continue
        table.setdefault(order, []).append(_perm_builder(*cl))
    return table


# ----------------------------------------------------------------------------
# Semidirect groups Z_m x|_r Z_k, as in the parent program.
# ----------------------------------------------------------------------------

def _semi_build(m, k, r):
    """Deferred builder of the multiplication table of Z_m x|_r Z_k."""
    order, mul, _ = lib.semidirect_group(m, k, r)

    def build():
        T = [[mul(x, y) for y in range(order)] for x in range(order)]
        return _finish(T)
    return build


def _semi_params(N, rng):
    """Sampled (m, k, r) with m*k = N giving valid semidirect products."""
    out = []
    for k in range(1, N + 1):
        if N % k:
            continue
        m = N // k
        for r in range(m):
            if math.gcd(r, m) == 1 and pow(r, k, m) == 1 % m:
                out.append((m, k, r))
    rng.shuffle(out)
    return out[:SEMI_SAMPLE]


def _groups_of_order(N, perm, rng):
    """Candidate group builders of order N: a few permutation products, then semidirect products."""
    builds = list(perm.get(N, []))
    rng.shuffle(builds)
    builds = builds[:2]
    builds += [_semi_build(*p) for p in _semi_params(N, rng)]
    return builds[:MAX_GROUPS]


# ----------------------------------------------------------------------------
# Bi-Cayley annealing over a group given by its multiplication table.
# ----------------------------------------------------------------------------

def _cost(N, T, inv, S, D):
    """Vertex pairs not within distance D, counted from A_e and B_e. Zero means valid."""
    invS = [inv[s] for s in S]
    total = 0
    for src in (0, N):
        seen = bytearray(2 * N)
        seen[src] = 1
        cnt = 1
        frontier = [src]
        for _ in range(D):
            nxt = []
            for u in frontier:
                if u < N:
                    row = T[u]
                    for s in S:
                        v = N + row[s]
                        if not seen[v]:
                            seen[v] = 1
                            nxt.append(v)
                else:
                    row = T[u - N]
                    for si in invS:
                        v = row[si]
                        if not seen[v]:
                            seen[v] = 1
                            nxt.append(v)
            cnt += len(nxt)
            frontier = nxt
            if not frontier:
                break
        total += 2 * N - cnt
    return total


def _anneal(N, T, inv, d, D, rng, iters, deadline):
    """Anneal a connection set S of size d containing the identity; return S with cost 0, else None."""
    S = [0] + rng.sample(range(1, N), d - 1)
    cur = _cost(N, T, inv, S, D)
    for it in range(iters):
        if cur == 0:
            break
        if (it & 15) == 0 and time.monotonic() > deadline:
            break
        i = rng.randrange(1, d)
        c = rng.randrange(1, N)
        if c in S:
            continue
        S2 = S[:]
        S2[i] = c
        v = _cost(N, T, inv, S2, D)
        temp = 0.3 + 1.5 * (1.0 - it / iters)
        if v <= cur or rng.random() < math.exp(-(v - cur) / temp):
            S, cur = S2, v
    return S if cur == 0 else None


# ----------------------------------------------------------------------------
# Main entry point.
# ----------------------------------------------------------------------------

def build(d, D, seed, time_limit):
    start = time.monotonic()
    budget = max(0.5, min(0.8 * time_limit, time_limit - 4.0))
    deadline = start + budget
    rng = random.Random(seed)

    if d < 1 or D < 1:
        return 1, []
    if D == 1:
        return 2, [(0, 1)]

    # Safe fallback: K_{d,d}, which has diameter 2.
    best = lib.haar_graph(d, range(d))
    if D == 2:
        return best

    moore = lib.moore_bound(d, D)

    def consider(n, e):
        nonlocal best
        if n > best[0] and lib.is_valid(n, e, d, D):
            best = (n, e)

    if D == 3:
        pg = _best_pg(d)
        if pg is not None:
            consider(pg[0], pg[1])

    if best[0] >= moore or d < 2:
        return best

    perm = _perm_groups(moore // 2)

    # Ascending sweep over bi-Cayley orders N, aiming above the current best.
    sweep = max(d, 2)
    while time.monotonic() < deadline:
        lo = best[0] // 2 + 1
        if sweep < lo:
            sweep = lo
        if sweep > moore // 2:
            break
        N = sweep
        sweep += 1
        if N < d:
            continue
        for build_fn in _groups_of_order(N, perm, rng):
            if time.monotonic() >= deadline:
                break
            T, inv = build_fn()
            S = _anneal(N, T, inv, d, D, rng, ANNEAL_ITERS, deadline)
            if S is not None:
                consider(2 * N, [(x, N + T[x][s]) for x in range(N) for s in S])
                break

    if not lib.is_valid(best[0], best[1], d, D):
        return lib.haar_graph(d, range(d))
    return best
