import math
import random
import time

import lib

# ----------------------------------------------------------------------------
# Strategy.
#
# The parent's weakest case is d=5, D=5 (record 336, Moore-type ceiling 676).
# Here the search moves to bi-Cayley graphs over concrete permutation groups of
# order 336 (PGL(2,7) and PSL(2,7) x Z2). The bipartite double cover of a
# Cayley graph Cay(G, S) with |G| = N has 2N vertices, and 2N = 672 would sit
# just under the ceiling. PSL(2,7) (order 168) reproduces the record size, so
# it is kept as a fallback. Generic semidirect-product bi-Cayley search then
# covers the other orders and all other (d, D) cases. Every returned graph is
# checked with lib.is_valid, and K_{d,d} (diameter 2) is the final fallback.
# ----------------------------------------------------------------------------

CLIMB_ITERS = 400
MAX_GROUPS = 8
_TABLE_CACHE = {}


# ----------------------------------------------------------------------------
# Permutation groups.
# ----------------------------------------------------------------------------

def _compose(a, b):
    """(a*b)(i) = a(b(i))."""
    return tuple(a[i] for i in b)


def _inverse(p):
    q = [0] * len(p)
    for i, v in enumerate(p):
        q[v] = i
    return tuple(q)


def _perm_group(gens, cap=400):
    """Group generated by permutation tuples; returns (N, T, invs) or None if |G| > cap.

    Identity has index 0. T[x][g] = index of x*g, invs[g] = index of g^-1.
    """
    k = len(gens[0])
    ident = tuple(range(k))
    elems = [ident]
    index = {ident: 0}
    frontier = [ident]
    while frontier:
        nxt = []
        for x in frontier:
            for g in gens:
                y = _compose(g, x)
                if y not in index:
                    if len(elems) >= cap:
                        return None
                    index[y] = len(elems)
                    elems.append(y)
                    nxt.append(y)
        frontier = nxt
    N = len(elems)
    T = [[index[_compose(elems[x], elems[g])] for g in range(N)] for x in range(N)]
    invs = [index[_inverse(elems[g])] for g in range(N)]
    return N, T, invs


def _pgl27_gens():
    """PGL(2,7) on the projective line {0..6, inf=7}: x->x+1, x->3x, x->-1/x."""
    t = tuple([(x + 1) % 7 for x in range(7)] + [7])
    m3 = tuple([(3 * x) % 7 for x in range(7)] + [7])
    iv = tuple([7] + [(-pow(x, 5, 7)) % 7 for x in range(1, 7)] + [0])
    return [t, m3, iv]


def _psl27_gens():
    """PSL(2,7) on the same line: x->x+1, x->2x, x->-1/x (all determinants are squares)."""
    t = tuple([(x + 1) % 7 for x in range(7)] + [7])
    m2 = tuple([(2 * x) % 7 for x in range(7)] + [7])
    iv = tuple([7] + [(-pow(x, 5, 7)) % 7 for x in range(1, 7)] + [0])
    return [t, m2, iv]


def _target_families():
    """Groups of order 336 first, then PSL(2,7) of order 168 as a record-size fallback."""
    psl = _psl27_gens()
    pgl = _pgl27_gens()
    swap = tuple(list(range(8)) + [9, 8])
    psl_z2 = [g + (8, 9) for g in psl] + [swap]
    return [("PGL27", pgl), ("PSL27xZ2", psl_z2), ("PSL27", psl)]


# ----------------------------------------------------------------------------
# Bi-Cayley hill climb (generic over any group given by T and invs).
# ----------------------------------------------------------------------------

def _unreached(N, T, invs, S, D):
    """Pairs (source, target) not within distance D, from A_0 and B_0.

    A_x ~ B_{x g} for g in S. Left translation is an automorphism, so these two
    eccentricity checks cover the whole graph.
    """
    Sinv = [invs[g] for g in S]
    total = 0
    for src in (0, N):
        seen = bytearray(2 * N)
        seen[src] = 1
        count = 1
        frontier = [src]
        for _ in range(D):
            nxt = []
            for u in frontier:
                if u < N:
                    row = T[u]
                    for g in S:
                        v = N + row[g]
                        if not seen[v]:
                            seen[v] = 1
                            nxt.append(v)
                else:
                    row = T[u - N]
                    for h in Sinv:
                        v = row[h]
                        if not seen[v]:
                            seen[v] = 1
                            nxt.append(v)
            count += len(nxt)
            frontier = nxt
            if not frontier:
                break
        total += 2 * N - count
    return total


def _climb(N, T, invs, d, D, rng, iters, deadline):
    """Anneal-like climb on S (identity fixed as one dart, WLOG). Returns S or None."""
    S = [0] + rng.sample(range(1, N), d - 1)
    cur = _unreached(N, T, invs, S, D)
    temp = 1.0
    for _ in range(iters):
        if cur == 0 or time.monotonic() > deadline:
            break
        i = rng.randrange(1, d)
        c = rng.randrange(1, N)
        if c in S:
            continue
        S2 = S[:]
        S2[i] = c
        v = _unreached(N, T, invs, S2, D)
        if v <= cur or rng.random() < math.exp(-(v - cur) / temp):
            S, cur = S2, v
        temp = max(0.05, temp * 0.995)
    return S if cur == 0 else None


def _graph_from(N, T, S):
    return 2 * N, [(x, N + T[x][g]) for x in range(N) for g in S]


# ----------------------------------------------------------------------------
# Generic semidirect products Z_m x|_r Z_k (used for other orders and cases).
# ----------------------------------------------------------------------------

def _groups(N):
    out = []
    for k in range(1, N + 1):
        if N % k:
            continue
        m = N // k
        for r in range(m):
            if math.gcd(r, m) == 1 and pow(r, k, m) == 1 % m:
                out.append((m, k, r))
    return out


def _semidirect_tables(m, k, r):
    key = (m, k, r)
    hit = _TABLE_CACHE.get(key)
    if hit is not None:
        return hit
    order, mul, inv = lib.semidirect_group(m, k, r)
    T = [[mul(x, g) for g in range(order)] for x in range(order)]
    invs = [inv(g) for g in range(order)]
    if len(_TABLE_CACHE) >= 24:
        _TABLE_CACHE.clear()
    _TABLE_CACHE[key] = (order, T, invs)
    return order, T, invs


# ----------------------------------------------------------------------------
# Searches.
# ----------------------------------------------------------------------------

def _perm_search(d, D, moore, best_n, deadline, rng):
    """Try permutation-group bi-Cayley lifts; return the largest valid (n, edges) or None."""
    result = None
    fams = _target_families()
    for idx, (name, gens) in enumerate(fams):
        now = time.monotonic()
        if now > deadline:
            break
        share = (deadline - now) / (len(fams) - idx)
        fam_deadline = now + share
        grp = _perm_group(gens)
        if grp is None:
            continue
        N, T, invs = grp
        if 2 * N > moore or 2 * N <= best_n:
            continue
        while time.monotonic() < fam_deadline:
            S = _climb(N, T, invs, d, D, rng, CLIMB_ITERS, fam_deadline)
            if S is not None:
                n, e = _graph_from(N, T, S)
                if lib.is_valid(n, e, d, D):
                    result = (n, e)
                    best_n = n
                break
    return result


def _generic_search(d, D, moore, best, deadline, rng):
    """Sweep bi-Cayley orders N upward over semidirect products; returns best (n, edges)."""
    best_n, best_e = best
    N = best_n // 2 + 1
    while time.monotonic() < deadline and 2 * N <= moore:
        groups = _groups(N)
        rng.shuffle(groups)
        for m, k, r in groups[:MAX_GROUPS]:
            if time.monotonic() > deadline:
                break
            order, T, invs = _semidirect_tables(m, k, r)
            S = _climb(order, T, invs, d, D, rng, CLIMB_ITERS, deadline)
            if S is not None:
                n, e = _graph_from(order, T, S)
                if n > best_n and lib.is_valid(n, e, d, D):
                    best_n, best_e = n, e
                break
        N += 1
    return best_n, best_e


def _pg_best(d):
    """Incidence graph of PG(2, q) for the largest prime power q with q + 1 <= d (diameter 3)."""
    for q in range(d - 1, 1, -1):
        if lib.is_prime_power(q):
            return lib.projective_plane_incidence(q)
    return None


# ----------------------------------------------------------------------------
# Entry point.
# ----------------------------------------------------------------------------

def build(d, D, seed, time_limit):
    start = time.monotonic()
    budget = max(0.5, min(0.8 * time_limit, time_limit - 5.0))
    deadline = start + budget
    rng = random.Random(seed)

    if d < 1 or D < 1:
        return 1, []
    if D == 1:
        return 2, [(0, 1)]

    # Safe fallback: K_{d,d} has diameter 2 and is bipartite.
    fb_n, fb_e = lib.haar_graph(d, range(d))
    if D == 2:
        return fb_n, fb_e
    best = (fb_n, fb_e)
    moore = lib.moore_bound(d, D)

    def consider(n, e):
        nonlocal best
        if n > best[0] and lib.is_valid(n, e, d, D):
            best = (n, e)

    if D == 3:
        pg = _pg_best(d)
        if pg is not None:
            consider(pg[0], pg[1])

    if best[0] < moore and d == 5 and D == 5:
        # Bold bet: bi-Cayley lifts over order-336 permutation groups (672 vertices).
        res = _perm_search(d, D, moore, best[0], start + 0.6 * budget, rng)
        if res is not None:
            consider(res[0], res[1])

    if best[0] < moore and time.monotonic() < deadline:
        n2, e2 = _generic_search(d, D, moore, best, deadline, rng)
        consider(n2, e2)

    if not lib.is_valid(best[0], best[1], d, D):
        best = (fb_n, fb_e)
    return best
