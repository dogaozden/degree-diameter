import itertools
import math
import random
import time

import lib

MAX_GROUPS_PER_ATTEMPT = 12   # groups tried per order N within one attempt
ITERS = 600                   # annealing steps per (group, connection set) try
T_HOT = 1.5                   # initial annealing temperature (in unreached-pair units)
T_COLD = 0.15                 # final annealing temperature
BUDGET_START = 0.4            # seconds per (N) attempt in the first pass
BUDGET_CAP = 3.0              # cap on per-attempt seconds as passes fail
PERM_CAP = 400                # reject permutation-generated groups larger than this
CACHE_LIMIT = 40              # max cached group multiplication tables


# ----------------------------------------------------------------------------
# Baseline families (fast, always valid when they pass lib.is_valid).
# ----------------------------------------------------------------------------

def _best_pg(d):
    """Incidence graph of PG(2, q) for the largest prime power q with q + 1 <= d."""
    for q in range(d - 1, 1, -1):
        if lib.is_prime_power(q):
            return lib.projective_plane_incidence(q)
    return None


def _gq_w(q):
    """Incidence graph of points and lines of the generalized quadrangle W(q); diameter 4."""
    F = lib.GF(q)
    pts = [v for v in itertools.product(range(q), repeat=4)
           if any(v) and next(c for c in v if c) == 1]
    index = {v: i for i, v in enumerate(pts)}
    P = len(pts)

    def norm(v):
        c = next(x for x in v if x)
        inv = F.inv(c)
        return tuple(F.mul(inv, x) for x in v)

    def form(x, y):
        t = F.sub(F.mul(x[0], y[1]), F.mul(x[1], y[0]))
        return F.add(t, F.sub(F.mul(x[2], y[3]), F.mul(x[3], y[2])))

    covered = set()
    lines = []
    for i in range(P):
        x = pts[i]
        for j in range(i + 1, P):
            if (i, j) in covered:
                continue
            y = pts[j]
            if form(x, y) != 0:
                continue
            L = set()
            for a in range(q):
                for b in range(q):
                    if a == 0 and b == 0:
                        continue
                    v = tuple(F.add(F.mul(a, x[k]), F.mul(b, y[k])) for k in range(4))
                    if any(v):
                        L.add(index[norm(v)])
            L = sorted(L)
            lines.append(L)
            for p in L:
                for r in L:
                    if p < r:
                        covered.add((p, r))

    edges = []
    for j, L in enumerate(lines):
        for p in L:
            edges.append((p, P + j))
    return 2 * P, edges


def _best_gq(d):
    """W(q) for the largest prime power q with q + 1 <= d, restricted to small q for speed."""
    for q in range(min(d - 1, 5), 1, -1):
        if lib.is_prime_power(q):
            return _gq_w(q)
    return None


# ----------------------------------------------------------------------------
# NEW: non-metacyclic groups from permutation generators.
#
# A finite group is given by permutation generators; its elements are found
# by closure (BFS of products with generators), starting from the identity,
# which becomes index 0. Direct products are formed by placing permutations on
# disjoint supports. This reaches groups such as A5 x Z3, S4 x Z8 and PSL(2,7),
# which the metacyclic family Z_m x| Z_k cannot produce.
# ----------------------------------------------------------------------------

def _pmul(a, b):
    """Composition of permutations: (a*b)(i) = a(b(i))."""
    return tuple(a[i] for i in b)


def _perm_closure(gens, cap):
    """Return (elements, index) of the group generated by gens, or None if it exceeds cap."""
    n = len(gens[0])
    ident = tuple(range(n))
    elems = [ident]
    index = {ident: 0}
    frontier = [ident]
    while frontier:
        nxt = []
        for x in frontier:
            for g in gens:
                y = _pmul(x, g)
                if y not in index:
                    if len(elems) >= cap:
                        return None
                    index[y] = len(elems)
                    elems.append(y)
                    nxt.append(y)
        frontier = nxt
    return elems, index


def _perm_tables(gens, cap=PERM_CAP):
    """Return (N, T, invs) with T[x][g] = x*g and identity at index 0, or None."""
    res = _perm_closure(gens, cap)
    if res is None:
        return None
    elems, index = res
    N = len(elems)
    T = [[index[_pmul(elems[x], elems[g])] for g in range(N)] for x in range(N)]
    invs = [0] * N
    for x in range(N):
        row = T[x]
        for g in range(N):
            if row[g] == 0:
                invs[x] = g
                break
    return N, T, invs


def _dsum(gens_a, na, gens_b, nb):
    """Generators of the direct product: gens_a act on the first na points, gens_b on the next nb."""
    out = []
    for g in gens_a:
        out.append(tuple(g) + tuple(range(na, na + nb)))
    for h in gens_b:
        out.append(tuple(range(na)) + tuple(na + x for x in h))
    return out


def _a5():
    return 5, [(1, 2, 0, 3, 4), (1, 2, 3, 4, 0)]


def _s4():
    return 4, [(1, 0, 2, 3), (1, 2, 3, 0)]


def _a4():
    return 4, [(1, 2, 0, 3), (1, 0, 3, 2)]


def _s3():
    return 3, [(1, 0, 2), (1, 2, 0)]


def _d5():
    return 5, [(1, 2, 3, 4, 0), (0, 4, 3, 2, 1)]


def _d7():
    return 7, [(1, 2, 3, 4, 5, 6, 0), (0, 6, 5, 4, 3, 2, 1)]


def _psl27():
    """PSL(2,7) acting on the projective line over GF(7); point 7 is infinity."""
    inf = 7
    f1 = tuple([(t + 1) % 7 for t in range(7)] + [inf])
    f2 = tuple([(2 * t) % 7 for t in range(7)] + [inf])
    f3 = [inf]
    for t in range(1, 7):
        f3.append((-pow(t, 5, 7)) % 7)   # t -> -1/t, with t^(-1) = t^5 mod 7
    f3.append(0)
    return 8, [f1, f2, tuple(f3)]


# (order, generator builder); orders are checked against the built group.
BASES = [
    (60, _a5),
    (24, _s4),
    (168, _psl27),
    (12, _a4),
    (6, _s3),
    (10, _d5),
    (14, _d7),
]

_GROUP_CACHE = {}
_GROUPS_CACHE = {}


def _groups(N):
    """Return semidirect parameters (m, k, r) with m*k = N, giving Z_m x|_r Z_k."""
    if N in _GROUPS_CACHE:
        return _GROUPS_CACHE[N]
    out = []
    for k in range(1, N + 1):
        if N % k:
            continue
        m = N // k
        for r in range(m):
            if math.gcd(r, m) == 1 and pow(r, k, m) == 1 % m:
                out.append((m, k, r))
    _GROUPS_CACHE[N] = out
    return out


def _descs(N):
    """Group descriptors of order N: metacyclic groups plus base x cyclic products."""
    out = [('meta', m, k, r) for (m, k, r) in _groups(N)]
    for bi, (order, _) in enumerate(BASES):
        if N % order:
            continue
        rem = N // order
        if rem == 1:
            out.append(('prod', bi, ()))
            continue
        out.append(('prod', bi, (rem,)))
        for a in range(2, rem):
            if rem % a == 0 and rem // a >= 2 and a <= rem // a:
                out.append(('prod', bi, (a, rem // a)))
    return out


def _build_group(desc):
    """Return (order, T, invs) for a group descriptor, or None on failure."""
    if desc[0] == 'meta':
        _, m, k, r = desc
        order, mul, inv = lib.semidirect_group(m, k, r)
        T = [[mul(x, g) for g in range(order)] for x in range(order)]
        invs = [inv(g) for g in range(order)]
        return order, T, invs
    _, bi, cyc = desc
    npts, gens = BASES[bi][1]()
    for k in cyc:
        cycle = [tuple((i + 1) % k for i in range(k))]
        gens = _dsum(gens, npts, cycle, k)
        npts += k
    return _perm_tables(gens)


def _get_group(desc):
    """Build a group with a small cache of tables."""
    if desc in _GROUP_CACHE:
        return _GROUP_CACHE[desc]
    built = _build_group(desc)
    if len(_GROUP_CACHE) >= CACHE_LIMIT:
        _GROUP_CACHE.clear()
    _GROUP_CACHE[desc] = built
    return built


# ----------------------------------------------------------------------------
# Bi-Cayley search over groups of order N.
#
# Vertices A_x and B_y (x, y in G). Edge A_x -- B_{x s} for s in S, |S| = d.
# Left multiplication is an automorphism, so eccentricities from A_0 and B_0
# decide the diameter. Identity is WLOG in S.
# ----------------------------------------------------------------------------

def _unreached(N, T, invs, S, D):
    """Count (source, vertex) pairs not within distance D, for sources A_0 and B_0."""
    Sinv = [invs[g] for g in S]
    total = 0
    for src in (0, N):
        seen = bytearray(2 * N)
        seen[src] = 1
        count = 1
        frontier = [src]
        for _ in range(D):
            nxt = []
            for u in frontier:
                if u < N:
                    row = T[u]
                    for g in S:
                        v = N + row[g]
                        if not seen[v]:
                            seen[v] = 1
                            nxt.append(v)
                else:
                    row = T[u - N]
                    for h in Sinv:
                        v = row[h]
                        if not seen[v]:
                            seen[v] = 1
                            nxt.append(v)
            count += len(nxt)
            frontier = nxt
            if not frontier:
                break
        total += 2 * N - count
    return total


def _anneal(N, T, invs, d, D, rng, iters, deadline):
    """Simulated annealing over S = {0, s_1, ..., s_{d-1}} to zero unreached pairs."""
    S = [0] + rng.sample(range(1, N), d - 1)
    cur = _unreached(N, T, invs, S, D)
    for it in range(iters):
        if cur == 0:
            return S
        if time.monotonic() > deadline:
            break
        temp = T_HOT * (T_COLD / T_HOT) ** (it / iters)
        i = rng.randrange(1, d)
        c = rng.randrange(1, N)
        if c in S:
            continue
        S2 = S[:]
        S2[i] = c
        v = _unreached(N, T, invs, S2, D)
        if v <= cur or rng.random() < math.exp(-(v - cur) / temp):
            S, cur = S2, v
    if cur == 0:
        return S
    return None


def _attempt(N, d, D, rng, deadline):
    """Try group descriptors of order N until one yields a valid connection set or time runs out."""
    descs = _descs(N)
    rng.shuffle(descs)
    for desc in descs[:MAX_GROUPS_PER_ATTEMPT]:
        if time.monotonic() > deadline:
            return None
        built = _get_group(desc)
        if built is None:
            continue
        order, T, invs = built
        if order != N:
            continue
        S = _anneal(N, T, invs, d, D, rng, ITERS, deadline)
        if S is not None:
            return T, S
    return None


def build(d, D, seed, time_limit):
    start = time.monotonic()
    deadline = start + 0.85 * time_limit - 1.0
    rng = random.Random(seed)

    if d < 1 or D < 1:
        return 1, []

    best = (1, [])
    best_n = 1

    def consider(n, e):
        nonlocal best, best_n
        if n > best_n and lib.is_valid(n, e, d, D):
            best = (n, e)
            best_n = n

    # Record-matching case: incidence graph of PG(2, d-1).
    if D == 3 and lib.is_prime_power(d - 1):
        n, e = lib.projective_plane_incidence(d - 1)
        consider(n, e)
        return best

    if D >= 2 and d >= 1:
        consider(*lib.haar_graph(d, range(d)))
    if D >= 3:
        pg = _best_pg(d)
        if pg is not None:
            consider(pg[0], pg[1])
    if D >= 4 and time.monotonic() < deadline:
        gq = _best_gq(d)
        if gq is not None:
            consider(gq[0], gq[1])

    if d < 2 or D < 2:
        return best

    Nmax = lib._moore_bound(d, D) // 2   # bi-Cayley graph has 2N vertices
    top = min(Nmax, max(Nmax // 2 + 6, int(0.75 * Nmax)))
    if top < d + 1:
        return best

    # Search a sliding window just above the best order found so far. The window
    # widens when a whole pass finds nothing, once per-attempt budgets are maxed.
    lo_base = max(d + 1, int(0.6 * top))
    bestN = best_n // 2
    budget = BUDGET_START
    width = 12

    while time.monotonic() < deadline:
        lo = max(lo_base, bestN + 1)
        if lo > top:
            break
        hi = min(top, lo + width - 1)
        cands = list(range(lo, hi + 1))
        rng.shuffle(cands)
        success = False
        for N in cands:
            now = time.monotonic()
            if now >= deadline:
                break
            att_deadline = min(deadline, now + budget)
            res = _attempt(N, d, D, rng, att_deadline)
            if res is None:
                continue
            T, S = res
            edges = [(x, N + T[x][g]) for x in range(N) for g in S]
            consider(2 * N, edges)
            bestN = max(bestN, N)
            success = True
            break
        if not success:
            if budget < BUDGET_CAP:
                budget = min(BUDGET_CAP, budget * 1.5)
            else:
                width += 4
                if lo_base > d + 1:
                    lo_base = max(d + 1, lo_base - 4)

    if not lib.is_valid(best[0], best[1], d, D):
        return 1, []
    return best
