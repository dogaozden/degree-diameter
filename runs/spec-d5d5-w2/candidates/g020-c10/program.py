import math
import random
import time

import numpy as np

import lib

T_HOT = 1.5          # initial annealing temperature (unreached-pair units)
T_COLD = 0.15        # final annealing temperature
TARGET_FRAC = 0.4955 # lowest order searched, as a fraction of (Moore bound / 2)
HI_FACTOR = 1.3      # highest order searched, as a multiple of the lowest
ITERS0 = 300         # annealing steps per group in the first pass
ITERS_CAP = 4800

_CACHE = {}

# Non-metacyclic base groups, given as permutation or matrix generators.
PERM_DEFS = {
    "A4": (4, [(1, 2, 0, 3), (1, 0, 3, 2)]),
    "S4": (4, [(1, 0, 2, 3), (1, 2, 3, 0)]),
    "A5": (5, [(1, 2, 0, 3, 4), (0, 1, 3, 4, 2)]),
}
MAT_DEFS = {
    "SL23": (3, 2, "sl"),
    "GL23": (3, 2, "gl"),
}
NONABELIAN = [(2 * n, ("dih", n)) for n in range(3, 13)] + [
    (12, ("perm", "A4")),
    (24, ("perm", "S4")),
    (60, ("perm", "A5")),
    (24, ("mat", "SL23")),
    (48, ("mat", "GL23")),
]


# ----------------------------------------------------------------- group tables

def _pmul(p, q):
    """Composition of permutation tuples: result[i] = p[q[i]]."""
    return tuple(p[i] for i in q)


def _closure(gens, mulf, ident, cap):
    """All elements generated by gens (identity first), or None if more than cap."""
    elems = [ident]
    seen = {ident}
    frontier = [ident]
    while frontier:
        nxt = []
        for x in frontier:
            for g in gens:
                y = mulf(x, g)
                if y not in seen:
                    if len(elems) >= cap:
                        return None
                    seen.add(y)
                    elems.append(y)
                    nxt.append(y)
        frontier = nxt
    return elems


def _table(elems, mulf):
    """Multiplication table M[i, j] = index of elems[i] * elems[j]."""
    idx = {e: i for i, e in enumerate(elems)}
    n = len(elems)
    M = np.empty((n, n), dtype=np.int64)
    for i, a in enumerate(elems):
        for j, b in enumerate(elems):
            M[i, j] = idx[mulf(a, b)]
    return M


def _perm_table(gens, ident):
    elems = _closure(gens, _pmul, ident, 400)
    if elems is None:
        raise ValueError("permutation closure failed")
    return _table(elems, _pmul)


def _mat_table(p, dim, mode):
    ident = tuple(int(i == j) for i in range(dim) for j in range(dim))

    def mm(A, B):
        return tuple(
            sum(A[i * dim + k] * B[k * dim + j] for k in range(dim)) % p
            for i in range(dim) for j in range(dim)
        )

    gens = []
    for i in range(dim):
        for j in range(dim):
            if i != j:
                e = list(ident)
                e[i * dim + j] = 1
                gens.append(tuple(e))
    if mode == "gl":
        e = list(ident)
        e[0] = 2 % p
        gens.append(tuple(e))
    elems = _closure(gens, mm, ident, 400)
    if elems is None:
        raise ValueError("matrix closure failed")
    return _table(elems, mm)


def _factor(spec):
    if spec in _CACHE:
        return _CACHE[spec]
    kind = spec[0]
    if kind == "cyc":
        a = spec[1]
        idx = np.arange(a, dtype=np.int64)
        M = (idx[:, None] + idx[None, :]) % a
    elif kind == "dih":
        n = spec[1]
        gens = [tuple((i + 1) % n for i in range(n)), tuple((-i) % n for i in range(n))]
        M = _perm_table(gens, tuple(range(n)))
    elif kind == "perm":
        n, gens = PERM_DEFS[spec[1]]
        M = _perm_table(gens, tuple(range(n)))
    elif kind == "mat":
        M = _mat_table(*MAT_DEFS[spec[1]])
    else:
        raise ValueError(kind)
    _CACHE[spec] = M
    return M


def _kron(M1, M2):
    """Direct product; element (x1, x2) is coded as x1 * N2 + x2, identity stays 0."""
    N1, N2 = M1.shape[0], M2.shape[0]
    return (M1[:, None, :, None] * N2 + M2[None, :, None, :]).reshape(N1 * N2, N1 * N2)


def _meta(m, k, r):
    """Table of Z_m x|_r Z_k, element (a, b) coded as a*k + b."""
    N = m * k
    x = np.arange(N, dtype=np.int64)
    a = x // k
    b = x % k
    pw = np.array([pow(r, t, m) for t in range(k)], dtype=np.int64)
    return ((a[:, None] + pw[b][:, None] * a[None, :]) % m) * k + (b[:, None] + b[None, :]) % k


def _build_spec(spec):
    if spec[0] == "meta":
        _, m, k, r = spec
        return _meta(m, k, r)
    if spec[0] == "prod":
        M = None
        for s in spec[1]:
            F = _factor(s)
            M = F if M is None else _kron(M, F)
        return M
    return _factor(spec)


def _groups(N):
    """Semidirect parameters (m, k, r) with m * k = N."""
    out = []
    for k in range(1, N + 1):
        if N % k:
            continue
        m = N // k
        for r in range(m):
            if math.gcd(r, m) == 1 and pow(r, k, m) == 1 % m:
                out.append((m, k, r))
    return out


def _pool(lo, hi):
    """(order, spec) candidates with lo <= order <= hi."""
    out = []
    for N in range(lo, hi + 1):
        for m, k, r in _groups(N):
            out.append((N, ("meta", m, k, r)))
    for o, s in NONABELIAN:
        for a in range(1, hi // o + 1):
            N = o * a
            if lo <= N <= hi:
                spec = (s,) if a == 1 else (s, ("cyc", a))
                out.append((N, ("prod", spec)))
    for i, (o1, s1) in enumerate(NONABELIAN):
        for o2, s2 in NONABELIAN[i:]:
            for a in range(1, hi // (o1 * o2) + 1):
                N = o1 * o2 * a
                if lo <= N <= hi:
                    spec = (s1, s2) if a == 1 else (s1, s2, ("cyc", a))
                    out.append((N, ("prod", spec)))
    return out


# ------------------------------------------------------------ bi-Cayley search

def _unreached(Cols, S, Sinv, N, D):
    """Pairs (source, vertex) not within distance D, for sources A_0 and B_0.

    A_x ~ B_{x s} for s in S. Cols[g][x] = x * g. From B_y, the A-neighbours are y * h for h in Sinv.
    """
    total = 0
    for start_a in (True, False):
        visA = np.zeros(N, dtype=bool)
        visB = np.zeros(N, dtype=bool)
        front = np.zeros(1, dtype=np.int64)
        if start_a:
            visA[0] = True
        else:
            visB[0] = True
        on_a = start_a
        for _ in range(D):
            new = np.zeros(N, dtype=bool)
            if on_a:
                for g in S:
                    new[Cols[g][front]] = True
                new &= ~visB
                visB |= new
            else:
                for h in Sinv:
                    new[Cols[h][front]] = True
                new &= ~visA
                visA |= new
            front = np.flatnonzero(new)
            on_a = not on_a
            if front.size == 0:
                break
        total += 2 * N - int(visA.sum()) - int(visB.sum())
    return total


def _anneal(Cols, invs, N, d, D, rng, iters, deadline):
    """Anneal S = {0, s_1, ..., s_{d-1}} to zero unreached pairs."""
    def cost(S):
        return _unreached(Cols, S, [invs[g] for g in S], N, D)

    S = [0] + rng.sample(range(1, N), d - 1)
    cur = cost(S)
    for it in range(iters):
        if cur == 0 or time.monotonic() > deadline:
            break
        temp = T_HOT * (T_COLD / T_HOT) ** (it / iters)
        i = rng.randrange(1, d)
        c = rng.randrange(1, N)
        if c in S:
            continue
        S2 = S[:]
        S2[i] = c
        v = cost(S2)
        if v <= cur or rng.random() < math.exp(-(v - cur) / temp):
            S, cur = S2, v
    return S if cur == 0 else None


def _try(spec, N, d, D, rng, iters, deadline):
    M = _build_spec(spec)
    if M is None or M.shape != (N, N):
        return None
    Cols = np.ascontiguousarray(M.T)
    invs = np.empty(N, dtype=np.int64)
    r, c = np.nonzero(M == 0)
    invs[r] = c
    S = _anneal(Cols, invs.tolist(), N, d, D, rng, iters, deadline)
    if S is None:
        return None
    return M, S


# ------------------------------------------------------------- baseline families

def _best_pg(d):
    """Incidence graph of PG(2, q) for the largest prime power q <= d - 1."""
    for q in range(d - 1, 1, -1):
        if lib.is_prime_power(q):
            return lib.projective_plane_incidence(q)
    return None


# ------------------------------------------------------------------- build

def build(d, D, seed, time_limit):
    start = time.monotonic()
    deadline = start + max(1.0, 0.8 * time_limit - 1.5)
    rng = random.Random(seed)

    if d < 1 or D < 1:
        return 1, []

    if D == 3 and lib.is_prime_power(d - 1):
        n, e = lib.projective_plane_incidence(d - 1)
        if lib.is_valid(n, e, d, D):
            return n, e
        return 1, []

    best = [1, []]

    def consider(n, e):
        if n > best[0] and lib.is_valid(n, e, d, D):
            best[0], best[1] = n, e

    if d >= 2 and D >= 2:
        consider(*lib.haar_graph(d, range(d)))
    if D >= 3:
        pg = _best_pg(d)
        if pg is not None:
            consider(pg[0], pg[1])

    if d < 2 or D < 2:
        return best[0], best[1]

    Nmax = lib.moore_bound(d, D) // 2   # bi-Cayley graph has 2N vertices
    if Nmax < d + 1:
        return best[0], best[1]

    lo = max(d + 1, best[0] // 2 + 1, math.ceil(TARGET_FRAC * Nmax))
    lo = min(lo, Nmax)
    hi = min(Nmax, math.ceil(lo * HI_FACTOR))

    floor = lo
    iters = ITERS0
    pool_cache = {}

    while time.monotonic() < deadline and floor <= hi:
        if floor not in pool_cache:
            pool_cache[floor] = _pool(floor, hi)
        pool = pool_cache[floor]
        if not pool:
            if floor <= d + 1:
                break
            floor = max(d + 1, floor - max(1, floor // 50))
            continue

        order = pool[:]
        rng.shuffle(order)
        order.sort(key=lambda t: t[0])

        found = None
        for N, spec in order:
            if time.monotonic() >= deadline:
                break
            res = _try(spec, N, d, D, rng, iters, deadline)
            if res is not None:
                found = (N, res[0], res[1])
                break

        if found is not None:
            N, M, S = found
            edges = [(x, N + int(M[x, g])) for x in range(N) for g in S]
            consider(2 * N, edges)
            floor = N + 1
        elif iters < ITERS_CAP:
            iters *= 2
        elif floor > d + 1:
            floor = max(d + 1, floor - max(1, floor // 50))
        else:
            break

    n, e = best[0], best[1]
    if not lib.is_valid(n, e, d, D):
        return 1, []
    return n, e
