import itertools
import math
import random
import time

import lib


# ----------------------------------------------------------------------------
# Strategy:
#   * Trivial exact cases (D <= 2, d <= 2) and the projective-plane family for D = 3.
#   * For D >= 4 (the target D = 5 among them): bi-Cayley graphs B(G, S) on
#     finite groups G of order N, with A_x ~ B_{xg} for g in S, |S| = d.
#     Bi-Cayley graphs are bipartite, d-regular and have 2N vertices. Diameter
#     is checked from A_0 and B_0 only, since left translation is an automorphism.
#   * The group catalogue deliberately leans on NON-metacyclic groups (S4, A4,
#     S5, A5, PSL(2,7), affine groups AGL(1,q) / AGammaL(1,q) over GF(8), GF(9),
#     GF(16)), plus direct products with cyclic groups, alongside the semidirect
#     Z_m x| Z_k family.
#   * Search: simulated annealing over the connection set S with restarts. Specs
#     are scheduled by fewest attempts first, then smallest order above the
#     current best, so the search sweeps upward from the frontier.
#   * Every returned graph is verified with lib.is_valid; K_{d,d} (diameter 2)
#     is the safe fallback.
# ----------------------------------------------------------------------------

RESTART = 1500          # annealing steps before a random restart
TABLE_CACHE_MAX = 24    # cached multiplication tables


# ----------------------------------------------------------------- fallbacks

def _cycle_graph(D):
    """C_{2D}: bipartite, 2-regular, diameter D. Moore-optimal for d = 2."""
    n = 2 * D
    return n, [(i, (i + 1) % n) for i in range(n)]


def _complete_bip(d):
    """K_{d,d}: diameter 2, degree d, 2d vertices."""
    return lib.haar_graph(d, range(d))


def _pg_candidates(d):
    """Diameter-3 candidates: PG(2,q) incidence with q the largest prime power <= d-1,
    and the Araujo-Lopez graph when d-2 is a prime power >= 3."""
    out = []
    for q in range(d - 1, 1, -1):
        if lib.is_prime_power(q):
            out.append(lib.projective_plane_incidence(q))
            break
    if d - 2 >= 3 and lib.is_prime_power(d - 2):
        try:
            out.append(lib.araujo_lopez_graph(d - 2))
        except Exception:
            pass
    return out


# ------------------------------------------------------------ permutation groups

def _perm_mul(a, b):
    """Composition a o b as permutation tuples."""
    return tuple(a[j] for j in b)


def _closure(gens, cap):
    """Elements of the group generated by permutation tuples gens (identity first),
    or None if the order exceeds cap."""
    n = len(gens[0])
    ident = tuple(range(n))
    elems = [ident]
    seen = {ident}
    i = 0
    while i < len(elems):
        x = elems[i]
        i += 1
        for g in gens:
            y = _perm_mul(x, g)
            if y not in seen:
                if len(elems) >= cap:
                    return None
                seen.add(y)
                elems.append(y)
    return elems


def _perm_table(elems):
    """(N, T, invs) with T[x][y] = index of elems[x] o elems[y]; identity has index 0."""
    idx = {p: i for i, p in enumerate(elems)}
    T = [[idx[_perm_mul(a, b)] for b in elems] for a in elems]
    invs = []
    for a in elems:
        inv = [0] * len(a)
        for i, x in enumerate(a):
            inv[x] = i
        invs.append(idx[tuple(inv)])
    return len(elems), T, invs


def _gl32_gens():
    """GL(3,2) = PSL(2,7) acting on the 7 nonzero vectors of GF(2)^3."""
    A = [[1, 1, 0], [0, 1, 0], [0, 0, 1]]
    B = [[0, 0, 1], [1, 0, 0], [0, 1, 0]]
    vecs = [v for v in itertools.product(range(2), repeat=3) if any(v)]
    idx = {v: i for i, v in enumerate(vecs)}

    def perm(M):
        out = []
        for v in vecs:
            w = tuple(sum(M[r][c] * v[c] for c in range(3)) % 2 for r in range(3))
            out.append(idx[w])
        return tuple(out)

    return [perm(A), perm(B)], 7


def _affine_gens(q, semilinear):
    """Generators of AGL(1,q), or AGammaL(1,q) when semilinear, acting on GF(q)."""
    F = lib.GF(q)
    gens = []
    e = 1
    for _ in range(F.k):
        gens.append(tuple(F.add(x, e) for x in range(q)))
        e *= F.p
    g = F.primitive_element()
    gens.append(tuple(F.mul(g, x) for x in range(q)))
    if semilinear:
        gens.append(tuple(F.pow(x, F.p) for x in range(q)))
    return gens, q


def _base_groups():
    """Non-metacyclic base groups as (name, generators, degree)."""
    out = [
        ("S4", [(1, 0, 2, 3), (1, 2, 3, 0)], 4),
        ("A4", [(1, 2, 0, 3), (0, 2, 3, 1)], 4),
        ("S5", [(1, 0, 2, 3, 4), (1, 2, 3, 4, 0)], 5),
        ("A5", [(1, 2, 0, 3, 4), (1, 2, 3, 4, 0)], 5),
    ]
    g, n = _gl32_gens()
    out.append(("PSL27", g, n))
    for q, sl in ((8, False), (8, True), (9, False), (9, True), (16, False)):
        g, n = _affine_gens(q, sl)
        out.append((f"AG{q}{int(sl)}", g, n))
    return out


# ------------------------------------------------------------- group catalogue

def _semi_list(N):
    """All semidirect parameters (m, k, r) with m*k = N giving Z_m x|_r Z_k."""
    out = []
    for k in range(1, N + 1):
        if N % k:
            continue
        m = N // k
        for r in range(m):
            if math.gcd(r, m) == 1 and pow(r, k, m) == 1 % m:
                out.append((m, k, r))
    return out


def _specs(d, hi, rng):
    """Candidate groups of order in [d, hi] as (N, kind, data) triples."""
    specs = []
    for _name, gens, deg in _base_groups():
        elems = _closure(gens, 400)
        if elems is None:
            continue
        B = len(elems)
        m = 1
        while B * m <= hi:
            if B * m >= d:
                if m == 1:
                    g2 = list(gens)
                else:
                    g2 = [g + tuple(range(deg, deg + m)) for g in gens]
                    g2.append(tuple(range(deg))
                              + tuple(deg + (j + 1) % m for j in range(m)))
                specs.append((B * m, "perm", g2))
            m += 1
    for N in range(max(d, 3), hi + 1):
        lst = _semi_list(N)
        rng.shuffle(lst)
        for mkr in lst[:2]:
            specs.append((N, "semi", mkr))
    return specs


def _table(spec):
    """Build (N, T, invs) for a spec, or None if the group fails to match its order."""
    N, kind, data = spec
    if kind == "perm":
        elems = _closure(data, 400)
        if elems is None or len(elems) != N:
            return None
        return _perm_table(elems)
    m, k, r = data
    order, mul, inv = lib.semidirect_group(m, k, r)
    T = [[mul(x, y) for y in range(order)] for x in range(order)]
    invs = [inv(g) for g in range(order)]
    return order, T, invs


# --------------------------------------------------------- bi-Cayley search

def _cost(N, T, invs, S, D):
    """Pairs (source, vertex) not within distance D, sources A_0 and B_0.
    Zero iff the bi-Cayley graph B(G, S) has diameter <= D."""
    Sinv = [invs[g] for g in S]
    N2 = 2 * N
    total = 0
    for src in (0, N):
        seen = bytearray(N2)
        seen[src] = 1
        count = 1
        frontier = [src]
        for _ in range(D):
            nxt = []
            for u in frontier:
                if u < N:
                    row = T[u]
                    for g in S:
                        v = N + row[g]
                        if not seen[v]:
                            seen[v] = 1
                            nxt.append(v)
                else:
                    row = T[u - N]
                    for h in Sinv:
                        v = row[h]
                        if not seen[v]:
                            seen[v] = 1
                            nxt.append(v)
            if not nxt:
                break
            count += len(nxt)
            frontier = nxt
        total += N2 - count
    return total


def _anneal(N, T, invs, d, D, rng, deadline):
    """Anneal a connection set S (identity fixed in position 0, WLOG) to zero cost.
    Random restarts within the deadline. Returns S or None."""
    while time.monotonic() < deadline:
        S = [0] + rng.sample(range(1, N), d - 1)
        cur = _cost(N, T, invs, S, D)
        for it in range(RESTART):
            if cur == 0:
                return S
            if (it & 15) == 0 and time.monotonic() > deadline:
                return None
            temp = 0.1 + 1.2 * (1.0 - it / RESTART)
            i = rng.randrange(1, d)
            c = rng.randrange(1, N)
            if c in S:
                continue
            old = S[i]
            S[i] = c
            v = _cost(N, T, invs, S, D)
            if v <= cur or rng.random() < math.exp(-(v - cur) / temp):
                cur = v
            else:
                S[i] = old
        if cur == 0:
            return S
    return None


# ------------------------------------------------------------------ main entry

def build(d, D, seed, time_limit):
    start = time.monotonic()
    budget = max(1.0, min(0.8 * time_limit, time_limit - 5.0))
    deadline = start + budget
    rng = random.Random(seed)

    if d < 1 or D < 1:
        return 1, []
    if D == 1 or d == 1:
        return 2, [(0, 1)]
    if d == 2:
        return _cycle_graph(D)

    best = _complete_bip(d)          # valid for D >= 2 (diameter 2)
    if D == 2:
        return best

    moore = lib.moore_bound(d, D)

    def consider(n, e):
        nonlocal best
        if n > best[0] and lib.is_valid(n, e, d, D):
            best = (n, e)

    try:
        if D == 3:
            for n, e in _pg_candidates(d):
                consider(n, e)
            if best[0] >= moore:
                return best
        if D >= 4 or best[0] < moore:
            hi = min(moore // 2, 400)
            if hi >= max(d, 3):
                specs = _specs(d, hi, rng)
                attempts = [0] * len(specs)
                cache = {}
                slice_s = max(0.5, min(4.0, budget / 12.0))
                while time.monotonic() < deadline:
                    lo = best[0] // 2 + 1
                    cand = [i for i, s in enumerate(specs) if s[0] >= lo]
                    if not cand:
                        break
                    i = min(cand, key=lambda j: (attempts[j], specs[j][0]))
                    attempts[i] += 1
                    tab = cache.get(i)
                    if tab is None:
                        tab = _table(specs[i])
                        if tab is None:
                            continue
                        if len(cache) >= TABLE_CACHE_MAX:
                            cache.clear()
                        cache[i] = tab
                    N, T, invs = tab
                    end = min(deadline, time.monotonic() + slice_s)
                    S = _anneal(N, T, invs, d, D, rng, end)
                    if S is not None:
                        edges = [(x, N + T[x][g]) for x in range(N) for g in S]
                        consider(2 * N, edges)
    except Exception:
        pass

    if not lib.is_valid(best[0], best[1], d, D):
        best = _complete_bip(d)
    return best
