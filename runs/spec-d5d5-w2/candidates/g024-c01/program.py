import math
import random
import time

import lib

MAX_ORDER = 400       # largest group order (bi-Cayley order N) we build tables for
MAX_GROUPS = 3        # groups tried per order N
ANNEAL_ITERS = 300    # annealing steps per group
HINT_FRAC = 0.44      # upward sweep starts at this fraction of moore/2
_TABLE_CACHE = {}

# Non-metacyclic base groups (name spec, order). Products with cyclic groups are generated below.
BASE_SPECS = [
    (('pgl', 3), 24), (('psl', 3), 12),
    (('pgl', 5), 120), (('psl', 5), 60),
    (('pgl', 7), 336), (('psl', 7), 168),
    (('S4',), 24), (('A4',), 12),
    (('S5',), 120), (('A5',), 60),
]


# ----------------------------------------------------------------------------
# Group tables: permutation groups (PGL/PSL(2,p), S_n, A_n), direct products
# with cyclic groups, and semidirect products from lib.
# ----------------------------------------------------------------------------

def _prim_root(p):
    for g in range(2, p):
        x, o = g, 1
        while x != 1:
            x = x * g % p
            o += 1
        if o == p - 1:
            return g
    return 1


def _pgl_gens(p, psl):
    """Generators of PGL(2,p) (or PSL(2,p)) acting on the projective line 0..p (p = infinity)."""
    a = _prim_root(p)
    mult = a * a % p if psl else a
    t = tuple([(x + 1) % p for x in range(p)] + [p])
    s = tuple([(mult * x) % p for x in range(p)] + [p])
    w = tuple([p if x == 0 else (-pow(x, p - 2, p)) % p for x in range(p)] + [0])
    return [t, s, w]


def _gens_for(spec):
    kind = spec[0]
    if kind == 'pgl':
        return _pgl_gens(spec[1], False)
    if kind == 'psl':
        return _pgl_gens(spec[1], True)
    if kind == 'S4':
        return [(1, 0, 2, 3), (1, 2, 3, 0)]
    if kind == 'A4':
        return [(1, 2, 0, 3), (1, 0, 3, 2)]
    if kind == 'S5':
        return [(1, 0, 2, 3, 4), (1, 2, 3, 4, 0)]
    if kind == 'A5':
        return [(1, 2, 0, 3, 4), (1, 2, 3, 4, 0)]
    return None


def _perm_table(gens):
    """Multiplication table of the permutation group generated by gens; identity is index 0."""
    n = len(gens[0])
    ident = tuple(range(n))
    elems = [ident]
    idx = {ident: 0}
    i = 0
    while i < len(elems):
        g = elems[i]
        i += 1
        for s in gens:
            h = tuple(s[g[j]] for j in range(n))
            if h not in idx:
                idx[h] = len(elems)
                elems.append(h)
                if len(elems) > MAX_ORDER:
                    return None
    N = len(elems)
    T = [[idx[tuple(elems[y][elems[x][j]] for j in range(n))] for y in range(N)]
         for x in range(N)]
    return N, T


def _invs(T):
    out = []
    for row in T:
        try:
            out.append(row.index(0))
        except ValueError:
            return None
    return out


def _table(spec):
    """Return (N, T, invs) for a group spec, or None. T[x][y] = x*y, identity = 0."""
    hit = _TABLE_CACHE.get(spec)
    if hit is not None:
        return hit
    kind = spec[0]
    if kind == 'prod':
        b = _table(spec[1])
        if b is None:
            return None
        Nb, Tb, _ = b
        k = spec[2]
        N = Nb * k
        T = [[0] * N for _ in range(N)]
        for x in range(N):
            gx, cx = divmod(x, k)
            row = T[x]
            for y in range(N):
                gy, cy = divmod(y, k)
                row[y] = Tb[gx][gy] * k + (cx + cy) % k
        pt = (N, T)
    elif kind == 'semi':
        _, m, k, r = spec
        order, mul, _ = lib.semidirect_group(m, k, r)
        T = [[mul(x, y) for y in range(order)] for x in range(order)]
        pt = (order, T)
    else:
        gens = _gens_for(spec)
        if gens is None:
            return None
        pt = _perm_table(gens)
        if pt is None:
            return None
    N, T = pt
    invs = _invs(T)
    if invs is None:
        return None
    val = (N, T, invs)
    if len(_TABLE_CACHE) >= 24:
        _TABLE_CACHE.clear()
    _TABLE_CACHE[spec] = val
    return val


def _spec_index():
    """Map order -> list of group specs (base groups and their cyclic direct products)."""
    idx = {}
    for base, bo in BASE_SPECS:
        for k in range(1, MAX_ORDER // bo + 1):
            spec = base if k == 1 else ('prod', base, k)
            idx.setdefault(bo * k, []).append(spec)
    return idx


def _groups(N):
    """Semidirect parameters (m, k, r) with m*k = N, giving Z_m x|_r Z_k."""
    out = []
    for k in range(1, N + 1):
        if N % k:
            continue
        m = N // k
        for r in range(m):
            if math.gcd(r, m) == 1 and pow(r, k, m) == 1 % m:
                out.append((m, k, r))
    return out


# ----------------------------------------------------------------------------
# Bi-Cayley search: A_x ~ B_{x g} for g in S, |S| = d, on a group of order N.
# Left translation is an automorphism, so eccentricities of A_0 and B_0 suffice.
# WLOG S[0] = identity (right-multiply S).
# ----------------------------------------------------------------------------

def _unreached(N, T, invs, S, D):
    Sinv = [invs[g] for g in S]
    total = 0
    for src in (0, N):
        seen = bytearray(2 * N)
        seen[src] = 1
        count = 1
        frontier = [src]
        for _ in range(D):
            nxt = []
            for u in frontier:
                if u < N:
                    row = T[u]
                    for g in S:
                        v = N + row[g]
                        if not seen[v]:
                            seen[v] = 1
                            nxt.append(v)
                else:
                    row = T[u - N]
                    for h in Sinv:
                        v = row[h]
                        if not seen[v]:
                            seen[v] = 1
                            nxt.append(v)
            count += len(nxt)
            frontier = nxt
            if not frontier:
                break
        total += 2 * N - count
    return total


def _bc_search(N, T, invs, d, D, rng, iters, deadline):
    if d < 2 or N < d:
        return None
    S = [0] + rng.sample(range(1, N), d - 1)
    cur = _unreached(N, T, invs, S, D)
    for it in range(iters):
        if cur == 0:
            break
        if (it & 15) == 0 and time.monotonic() > deadline:
            break
        i = rng.randrange(1, d)
        c = rng.randrange(1, N)
        if c in S:
            continue
        S2 = S[:]
        S2[i] = c
        v = _unreached(N, T, invs, S2, D)
        temp = 0.5 * (1.0 - it / iters) + 0.01
        if v <= cur or rng.random() < math.exp(-(v - cur) / (temp * max(cur, 1))):
            S, cur = S2, v
    return S if cur == 0 else None


# ----------------------------------------------------------------------------
# Main entry point.
# ----------------------------------------------------------------------------

def build(d, D, seed, time_limit):
    start = time.monotonic()
    deadline = start + max(0.5, min(0.85 * time_limit, time_limit - 3.0))
    rng = random.Random(seed)

    if d < 1 or D < 1:
        return 1, []
    if D == 1 or d == 1:
        return 2, [(0, 1)]

    # Safe fallback: K_{d,d} has diameter 2 (valid for every D >= 2).
    best = lib.haar_graph(d, range(d))
    if D == 2:
        return best

    moore = lib.moore_bound(d, D)
    if best[0] >= moore:
        return best

    def consider(n, e):
        nonlocal best
        if n > best[0] and lib.is_valid(n, e, d, D):
            best = (n, e)

    # D = 3: projective plane incidence graph when d - 1 is a prime power.
    if D == 3:
        for q in range(d - 1, 1, -1):
            if lib.is_prime_power(q):
                n, e = lib.projective_plane_incidence(q)
                consider(n, e)
                break
        if best[0] >= moore:
            return best

    # Bi-Cayley sweep over non-abelian and semidirect groups.
    try:
        hi = min(moore // 2, MAX_ORDER)
        hint = max(2, int(HINT_FRAC * (moore // 2)))
        seq = list(range(hint, hi + 1)) + list(range(2, min(hint, hi + 1)))
        specs_by_order = _spec_index()
        for N in seq:
            if time.monotonic() > deadline:
                break
            if N <= best[0] // 2 or N < d:
                continue  # cannot beat the current best
            named = list(specs_by_order.get(N, []))
            rng.shuffle(named)
            sem = _groups(N)
            rng.shuffle(sem)
            pool = named[:2] + [('semi', m, k, r) for (m, k, r) in sem[:MAX_GROUPS]]
            for spec in pool:
                if time.monotonic() > deadline:
                    break
                tab = _table(spec)
                if tab is None:
                    continue
                NN, T, invs = tab
                if NN != N:
                    continue
                S = _bc_search(N, T, invs, d, D, rng, ANNEAL_ITERS, deadline)
                if S is not None:
                    edges = [(x, N + T[x][g]) for x in range(N) for g in S]
                    consider(2 * N, edges)
                    break
            if best[0] >= moore:
                break
    except Exception:
        pass  # keep the best valid graph found so far

    if not lib.is_valid(best[0], best[1], d, D):
        return lib.haar_graph(d, range(d))
    return best
