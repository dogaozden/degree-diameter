import itertools
import math
import random
import time

import lib


# ----------------------------------------------------------------------------
# Tunables.
# ----------------------------------------------------------------------------

CLIMB_ITERS = 500      # annealing steps per bi-Cayley connection-set attempt
CLIMB_TRIES = 2        # attempts per sampled group
ANNEAL_ITERS = 900     # annealing steps for multi-base voltage lifts
_CACHE = {}
_POOLS = {}

# Building blocks for groups. Non-cyclic factors are small permutation groups,
# affine groups AGL(1,q) over GF(q), and cyclic groups C_m. Direct products of up
# to three factors give nonabelian groups of many orders, which the parent never tried.
TOKENS = (["A5", "S5", "A4", "S4", "AFF7", "AFF8", "AFF9", "AFF11", "AFF13", "AFF16", "AFF17"]
          + ["C%d" % m for m in range(2, 41)])
PERM_SPECS = {
    "A5": (5, [(1, 2, 3, 4, 0), (1, 2, 0, 3, 4)]),
    "S5": (5, [(1, 2, 3, 4, 0), (1, 0, 2, 3, 4)]),
    "A4": (4, [(1, 2, 0, 3), (1, 0, 3, 2)]),
    "S4": (4, [(1, 2, 3, 0), (1, 0, 2, 3)]),
}
TOKEN_ORDER = {"A5": 60, "S5": 120, "A4": 12, "S4": 24}


# ----------------------------------------------------------------------------
# D = 3 and D = 4 baselines (projective plane, generalized quadrangle).
# ----------------------------------------------------------------------------

def _best_pg(d):
    """Incidence graph of PG(2, q) for the largest prime power q with q + 1 <= d."""
    for q in range(d - 1, 1, -1):
        if lib.is_prime_power(q):
            return lib.projective_plane_incidence(q)
    return None


def _gq_w(q):
    """Incidence graph of points and lines of the generalized quadrangle W(q); diameter 4."""
    F = lib.GF(q)
    pts = [v for v in itertools.product(range(q), repeat=4)
           if any(v) and next(c for c in v if c) == 1]
    index = {v: i for i, v in enumerate(pts)}
    P = len(pts)

    def norm(v):
        c = next(x for x in v if x)
        inv = F.inv(c)
        return tuple(F.mul(inv, x) for x in v)

    def form(x, y):
        t = F.sub(F.mul(x[0], y[1]), F.mul(x[1], y[0]))
        return F.add(t, F.sub(F.mul(x[2], y[3]), F.mul(x[3], y[2])))

    covered = set()
    lines = []
    for i in range(P):
        x = pts[i]
        for j in range(i + 1, P):
            if (i, j) in covered:
                continue
            y = pts[j]
            if form(x, y) != 0:
                continue
            L = set()
            for a in range(q):
                for b in range(q):
                    if a == 0 and b == 0:
                        continue
                    v = tuple(F.add(F.mul(a, x[k]), F.mul(b, y[k])) for k in range(4))
                    if any(v):
                        L.add(index[norm(v)])
            L = sorted(L)
            lines.append(L)
            for p in L:
                for r in L:
                    if p < r:
                        covered.add((p, r))

    edges = []
    for j, L in enumerate(lines):
        for p in L:
            edges.append((p, P + j))
    return 2 * P, edges


def _best_gq(d):
    """W(q) for the largest prime power q with q + 1 <= d, capped at q = 5 for speed."""
    for q in range(min(d - 1, 5), 1, -1):
        if lib.is_prime_power(q):
            return _gq_w(q)
    return None


# ----------------------------------------------------------------------------
# Finite groups as multiplication tables. Element 0 is the identity.
# ----------------------------------------------------------------------------

class Grp:
    __slots__ = ("n", "T", "inv")

    def __init__(self, n, T, inv):
        self.n = n
        self.T = T        # T[x][g] = x*g
        self.inv = inv    # inv[g] = g^-1


def _store(key, val):
    if len(_CACHE) >= 40:
        _CACHE.clear()
    _CACHE[key] = val


def _closure(gens, mulf, e, limit=400):
    """Elements generated by right-multiplying from e by gens; e comes first."""
    elems = [e]
    seen = {e}
    i = 0
    while i < len(elems):
        x = elems[i]
        i += 1
        for g in gens:
            y = mulf(x, g)
            if y not in seen:
                if len(elems) >= limit:
                    return None
                seen.add(y)
                elems.append(y)
    return elems


def _table(elems, mulf):
    index = {x: i for i, x in enumerate(elems)}
    T = [[index[mulf(x, y)] for y in elems] for x in elems]
    inv = [row.index(0) for row in T]
    return Grp(len(elems), T, inv)


def _pmul(a, b):
    return tuple(a[x] for x in b)


def _factor(t):
    """Return (elements with identity first, multiplication) for a single token."""
    if t in PERM_SPECS:
        k, gens = PERM_SPECS[t]
        elems = _closure(gens, _pmul, tuple(range(k)))
        return elems, _pmul
    if t.startswith("AFF"):
        q = int(t[3:])
        F = lib.GF(q)
        g = F.primitive_element()

        def mulf(x, y):
            return (F.mul(x[0], y[0]), F.add(F.mul(x[0], y[1]), x[1]))

        elems = _closure([(g, 0), (1, 1)], mulf, (1, 0))
        return elems, mulf
    m = int(t[1:])

    def cmul(a, b, m=m):
        return (a + b) % m

    return list(range(m)), cmul


def _build_group(combo):
    key = ("g",) + tuple(combo)
    hit = _CACHE.get(key)
    if hit is not None:
        return hit
    facs = [_factor(t) for t in combo]
    if len(facs) == 1:
        elems, mulf = facs[0]
    else:
        fs = [f[1] for f in facs]

        def mulf(x, y):
            return tuple(f(a, b) for f, a, b in zip(fs, x, y))

        elems = [tuple(p) for p in itertools.product(*[f[0] for f in facs])]
    grp = _table(elems, mulf)
    _store(key, grp)
    return grp


def _sd_group(m, k, r):
    key = ("sd", m, k, r)
    hit = _CACHE.get(key)
    if hit is not None:
        return hit
    order, mul, _ = lib.semidirect_group(m, k, r)
    grp = _table(list(range(order)), mul)
    _store(key, grp)
    return grp


def _tok_order(t):
    if t in TOKEN_ORDER:
        return TOKEN_ORDER[t]
    if t.startswith("AFF"):
        q = int(t[3:])
        return q * (q - 1)
    return int(t[1:])


def _pool(lo, hi):
    """Token combinations (up to 3 factors) whose product order lies in [lo, hi]."""
    key = (lo, hi)
    hit = _POOLS.get(key)
    if hit is not None:
        return hit
    out = []
    for r in (1, 2, 3):
        for combo in itertools.combinations_with_replacement(TOKENS, r):
            o = 1
            for t in combo:
                o *= _tok_order(t)
            if lo <= o <= hi:
                out.append(combo)
    _POOLS[key] = out
    return out


def _groups(N):
    """Semidirect parameters (m, k, r) with m*k = N, giving Z_m x|_r Z_k."""
    out = []
    for k in range(1, N + 1):
        if N % k:
            continue
        m = N // k
        for r in range(m):
            if math.gcd(r, m) == 1 and pow(r, k, m) == 1 % m:
                out.append((m, k, r))
    return out


# ----------------------------------------------------------------------------
# Bi-Cayley lifts over a group G: A_x -- B_{x s} for s in S, |S| = d.
# Left multiplication is an automorphism, so BFS from A_e and B_e decides diameter.
# ----------------------------------------------------------------------------

def _unreached(grp, S, D):
    N = grp.n
    T = grp.T
    Sinv = [grp.inv[s] for s in S]
    total = 0
    for src in (0, N):
        seen = bytearray(2 * N)
        seen[src] = 1
        count = 1
        frontier = [src]
        for _ in range(D):
            nxt = []
            for u in frontier:
                if u < N:
                    row = T[u]
                    for s in S:
                        v = N + row[s]
                        if not seen[v]:
                            seen[v] = 1
                            nxt.append(v)
                else:
                    row = T[u - N]
                    for h in Sinv:
                        v = row[h]
                        if not seen[v]:
                            seen[v] = 1
                            nxt.append(v)
            count += len(nxt)
            frontier = nxt
            if not frontier:
                break
        total += 2 * N - count
    return total


def _climb(grp, d, D, rng, iters, deadline):
    N = grp.n
    S = [0] + rng.sample(range(1, N), d - 1)
    cur = _unreached(grp, S, D)
    for it in range(iters):
        if cur == 0:
            break
        if (it & 15) == 0 and time.monotonic() > deadline:
            break
        i = rng.randrange(1, d)
        c = rng.randrange(1, N)
        if c in S:
            continue
        S2 = S[:]
        S2[i] = c
        v = _unreached(grp, S2, D)
        temp = 0.3 + 1.5 * (1.0 - it / iters)
        if v <= cur or rng.random() < math.exp(-(v - cur) / temp):
            S, cur = S2, v
    return S if cur == 0 else None


def _bicayley(grp, d, D, rng, deadline):
    for _ in range(CLIMB_TRIES):
        if time.monotonic() > deadline:
            break
        S = _climb(grp, d, D, rng, CLIMB_ITERS, deadline)
        if S is not None:
            return S
    return None


def _bc_edges(grp, S):
    N = grp.n
    T = grp.T
    return 2 * N, [(x, N + T[x][g]) for x in range(N) for g in S]


# ----------------------------------------------------------------------------
# Multi-base voltage lifts over a group, annealed. Each of the d layers is a
# perfect matching between k A-base and k B-base vertices with one voltage per dart.
# ----------------------------------------------------------------------------

def _right_perm(T, s):
    return [row[s] for row in T]


def _cost(k, G, D, darts, perms):
    """Number of (representative, vertex) pairs not reached within D. Zero means valid."""
    if len({(i, j, s) for i, j, s in darts}) < len(darts):
        return 10 ** 9
    N = 2 * k * G
    adj = [[] for _ in range(N)]
    for (i, j, _s), pm in zip(darts, perms):
        base_a = i * G
        base_b = (k + j) * G
        for g in range(G):
            a = base_a + g
            b = base_b + pm[g]
            adj[a].append(b)
            adj[b].append(a)
    reps = [i * G for i in range(k)] + [(k + j) * G for j in range(k)]
    total = 0
    for src in reps:
        seen = [False] * N
        seen[src] = True
        frontier = [src]
        count = 1
        for _ in range(D):
            nxt = []
            for u in frontier:
                for v in adj[u]:
                    if not seen[v]:
                        seen[v] = True
                        nxt.append(v)
            count += len(nxt)
            frontier = nxt
            if not frontier:
                break
        total += N - count
    return total


def _lift_edges(k, G, darts, perms):
    E = set()
    for (i, j, _s), pm in zip(darts, perms):
        for g in range(G):
            E.add((i * G + g, (k + j) * G + pm[g]))
    return 2 * k * G, sorted(E)


def _anneal(d, D, k, grp, rng, deadline, iters):
    G = grp.n
    T = grp.T
    darts = []
    for _ in range(d):
        p = rng.sample(range(k), k)
        for i in range(k):
            darts.append([i, p[i], rng.randrange(G)])
    perms = [_right_perm(T, s) for _, _, s in darts]
    cost = _cost(k, G, D, darts, perms)

    T0 = max(1.0, 0.05 * cost) if cost < 10 ** 9 else 1.0
    T_end = 0.5
    decay = (T_end / T0) ** (1.0 / max(1, iters)) if T0 > T_end else 1.0
    temp = T0

    for _ in range(iters):
        if cost == 0 or time.monotonic() > deadline:
            break
        temp = max(T_end, temp * decay)

        if rng.random() < 0.7 or k == 1:
            idx = rng.randrange(len(darts))
            old_s = darts[idx][2]
            new_s = rng.randrange(G)
            if new_s == old_s:
                continue
            old_perm = perms[idx]
            darts[idx][2] = new_s
            perms[idx] = _right_perm(T, new_s)
            c2 = _cost(k, G, D, darts, perms)
            delta = c2 - cost
            if delta <= 0 or rng.random() < math.exp(-delta / temp):
                cost = c2
            else:
                darts[idx][2] = old_s
                perms[idx] = old_perm
        else:
            L = rng.randrange(d)
            a, b = rng.sample(range(k), 2)
            ia, ib = L * k + a, L * k + b
            darts[ia][1], darts[ib][1] = darts[ib][1], darts[ia][1]
            c2 = _cost(k, G, D, darts, perms)
            delta = c2 - cost
            if delta <= 0 or rng.random() < math.exp(-delta / temp):
                cost = c2
            else:
                darts[ia][1], darts[ib][1] = darts[ib][1], darts[ia][1]

    if cost == 0:
        return _lift_edges(k, G, darts, perms)
    return None


# ----------------------------------------------------------------------------
# Main entry point.
# ----------------------------------------------------------------------------

def build(d, D, seed, time_limit):
    start = time.monotonic()
    budget = max(0.5, min(0.85 * time_limit, time_limit - 3.0))
    deadline = start + budget
    rng = random.Random(seed)

    if d < 1 or D < 1:
        return 1, []
    if D == 1:
        return 2, [(0, 1)]

    # Safe fallback: K_{d,d}, diameter 2, order 2d.
    best = lib.haar_graph(d, range(d))
    if D == 2 or d < 2:
        return best

    moore = lib.moore_bound(d, D)

    def consider(n, e):
        nonlocal best
        if n > best[0] and lib.is_valid(n, e, d, D):
            best = (n, e)

    # Structured baselines.
    if D == 3:
        pg = _best_pg(d)
        if pg is not None:
            consider(pg[0], pg[1])
    if D >= 4:
        gq = _best_gq(d)
        if gq is not None:
            consider(gq[0], gq[1])

    # Main search: strictly above the current best order.
    while best[0] < moore and time.monotonic() < deadline:
        n_best = best[0]
        lo = n_best // 2 + 1
        hi = moore // 2
        if lo > hi:
            break

        r = rng.random()
        if r < 0.45:
            # Bi-Cayley over a random group from token products (mostly nonabelian).
            pool = _pool(lo, hi)
            if not pool:
                break
            grp = _build_group(rng.choice(pool))
            S = _bicayley(grp, d, D, rng, deadline)
            if S is not None:
                consider(*_bc_edges(grp, S))
        elif r < 0.65:
            # Bi-Cayley over semidirect products Z_m x|_r Z_k (the parent's family).
            N = rng.randint(lo, min(hi, lo + 15))
            groups = _groups(N)
            if not groups:
                continue
            grp = _sd_group(*rng.choice(groups))
            S = _bicayley(grp, d, D, rng, deadline)
            if S is not None:
                consider(*_bc_edges(grp, S))
        else:
            # Multi-base voltage lift over a random group of suitable order.
            k = rng.choice((2, 3))
            glo = n_best // (2 * k) + 1
            ghi = moore // (2 * k)
            if glo > ghi:
                continue
            pool = _pool(glo, ghi)
            if not pool:
                continue
            grp = _build_group(rng.choice(pool))
            res = _anneal(d, D, k, grp, rng, deadline, ANNEAL_ITERS)
            if res is not None:
                consider(res[0], res[1])

    if not lib.is_valid(best[0], best[1], d, D):
        best = lib.haar_graph(d, range(d))
    return best
