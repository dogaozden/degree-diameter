class _Stop(Exception):
    """Raised inside exact search when its node or time budget runs out."""


def _gq_w(q):
    """Incidence graph of points and lines of the generalized quadrangle W(q).

    Degree q + 1, diameter 4, order 2(q+1)(q^2+1).
    """
    F = lib.GF(q)
    pts = [v for v in itertools.product(range(q), repeat=4)
           if any(v) and next(c for c in v if c) == 1]
    index = {v: i for i, v in enumerate(pts)}
    P = len(pts)

    def norm(v):
        c = next(x for x in v if x)
        inv = F.inv(c)
        return tuple(F.mul(inv, x) for x in v)

    def form(x, y):
        t = F.sub(F.mul(x[0], y[1]), F.mul(x[1], y[0]))
        return F.add(t, F.sub(F.mul(x[2], y[3]), F.mul(x[3], y[2])))

    covered = set()
    lines = []
    for i in range(P):
        x = pts[i]
        for j in range(i + 1, P):
            if (i, j) in covered:
                continue
            y = pts[j]
            if form(x, y) != 0:
                continue
            L = set()
            for a in range(q):
                for b in range(q):
                    if a == 0 and b == 0:
                        continue
                    v = tuple(F.add(F.mul(a, x[k]), F.mul(b, y[k])) for k in range(4))
                    if any(v):
                        L.add(index[norm(v)])
            L = sorted(L)
            lines.append(L)
            for p in L:
                for r in L:
                    if p < r:
                        covered.add((p, r))

    edges = []
    for j, L in enumerate(lines):
        for p in L:
            edges.append((p, P + j))
    return 2 * P, edges


def _best_gq(d):
    """W(q) for the largest prime power q with q + 1 <= d (q <= 16), or None."""
    for q in range(d - 1, 1, -1):
        if q <= 16 and lib.is_prime_power(q):
            return _gq_w(q)
    return None


def _bipartition(n, adj):
    """Two-colouring of a bipartite graph given by adjacency lists."""
    color = [-1] * n
    for s in range(n):
        if color[s] != -1:
            continue
        color[s] = 0
        stack = [s]
        while stack:
            u = stack.pop()
            for v in adj[u]:
                if color[v] == -1:
                    color[v] = 1 - color[u]
                    stack.append(v)
    return color


def _balls_radius(n, adj, r):
    """Bitmask per vertex of all vertices within distance r."""
    ball = [1 << v for v in range(n)]
    for _ in range(r):
        new = []
        for v in range(n):
            x = ball[v]
            for u in adj[v]:
                x |= ball[u]
            new.append(x)
        ball = new
    return ball


def _twin_grow(n, edges, d, rng, deadline):
    """Add twin vertices (same side, same neighbourhood) while all neighbours have spare degree.

    A twin keeps every old distance and preserves bipartiteness.
    """
    edges = list(edges)
    adj = [[] for _ in range(n)]
    for u, v in edges:
        adj[u].append(v)
        adj[v].append(u)
    deg = [len(a) for a in adj]
    changed = True
    while changed and time.monotonic() < deadline:
        changed = False
        order = list(range(n))
        rng.shuffle(order)
        for x in order:
            if time.monotonic() >= deadline:
                break
            nb = adj[x]
            if not nb or any(deg[y] >= d for y in nb):
                continue
            v = n
            n += 1
            adj.append(list(nb))
            deg.append(len(nb))
            for y in nb:
                adj[y].append(v)
                deg[y] += 1
                edges.append((y, v))
            changed = True
    return n, edges


def _greedy_cover(cands, ball, full, d, rng, randomize):
    """Randomised greedy set cover of `full` by at most d candidate vertices, or None."""
    pool = list(cands)
    if randomize:
        rng.shuffle(pool)
    covered = 0
    chosen = []
    while covered != full and len(chosen) < d and pool:
        gains = [(ball[s] & ~covered).bit_count() for s in pool]
        best_g = max(gains, default=0)
        if best_g == 0:
            break
        thr = best_g
        if randomize and rng.random() < 0.5:
            thr = best_g - 1
        opts = [i for i, g in enumerate(gains) if g >= thr and g > 0]
        i = rng.choice(opts) if randomize else opts[0]
        s = pool.pop(i)
        chosen.append(s)
        covered |= ball[s]
    return chosen if covered == full else None


def _exact_cover(cands, ball, full, budget, deadline, rng, node_cap=800, branch=6):
    """Depth-limited exact search for a cover of `full` by at most `budget` candidates.

    Branches on the lowest uncovered element, trying its best-gaining coverers first.
    Pruned when the uncovered count exceeds what the remaining picks can cover.
    Returns a list of chosen candidates, or None when none is found within the caps.
    """
    order = list(cands)
    rng.shuffle(order)
    cache = {}
    nodes = [0]

    def coverers(e):
        lst = cache.get(e)
        if lst is None:
            bit = 1 << e
            lst = [s for s in order if ball[s] & bit]
            cache[e] = lst
        return lst

    def rec(U, depth, chosen):
        if U == 0:
            return list(chosen)
        left = budget - depth
        if left <= 0:
            return None
        nodes[0] += 1
        if nodes[0] > node_cap or time.monotonic() > deadline:
            raise _Stop()
        need = U.bit_count()
        max_gain = max(((ball[s] & U).bit_count() for s in order), default=0)
        if max_gain * left < need:
            return None
        e = (U & -U).bit_length() - 1
        opts = coverers(e)
        if not opts:
            return None
        top = sorted(opts, key=lambda s: (ball[s] & U).bit_count(), reverse=True)[:branch]
        for s in top:
            chosen.append(s)
            r = rec(U & ~ball[s], depth + 1, chosen)
            if r is not None:
                return r
            chosen.pop()
        return None

    try:
        return rec(full, 0, [])
    except _Stop:
        return None


def _extend_exact(n, edges, d, D, deadline, rng):
    """Add vertices whose neighbourhoods exactly (or greedily) cover all old vertices within D.

    A new vertex v joined to S has dist(v, x) <= D for every x iff S's radius-(D-1) balls
    cover all vertices. Old distances are unchanged, so validity is kept at every step.
    """
    if D < 2:
        return n, edges
    edges = list(edges)
    adj = [[] for _ in range(n)]
    for u, v in edges:
        adj[u].append(v)
        adj[v].append(u)
    deg = [len(a) for a in adj]
    color = _bipartition(n, adj)
    while time.monotonic() < deadline:
        ball = _balls_radius(n, adj, D - 1)
        full = (1 << n) - 1
        added = False
        sides = [0, 1]
        rng.shuffle(sides)
        for c in sides:
            cands = [s for s in range(n) if color[s] == 1 - c and deg[s] < d]
            if not cands:
                continue
            chosen = _exact_cover(cands, ball, full, d, deadline, rng)
            if chosen is None and time.monotonic() < deadline:
                chosen = _greedy_cover(cands, ball, full, d, rng, True)
            if chosen:
                v = n
                n += 1
                color.append(c)
                adj.append([])
                deg.append(0)
                for s in chosen:
                    edges.append((s, v))
                    adj[s].append(v)
                    adj[v].append(s)
                    deg[s] += 1
                    deg[v] += 1
                added = True
                break
        if not added:
            break
    return n, edges


def _saturate_edges(n, edges, d, rng):
    """Greedily join deficient opposite-side vertices in random order (keeps diameter and bipartiteness)."""
    edges = list(edges)
    adj = [[] for _ in range(n)]
    existing = set()
    for u, v in edges:
        adj[u].append(v)
        adj[v].append(u)
        existing.add((min(u, v), max(u, v)))
    deg = [len(a) for a in adj]
    color = _bipartition(n, adj)
    left = [v for v in range(n) if color[v] == 0 and deg[v] < d]
    right = [v for v in range(n) if color[v] == 1 and deg[v] < d]
    pairs = [(a, b) for a in left for b in right
             if (min(a, b), max(a, b)) not in existing]
    rng.shuffle(pairs)
    for a, b in pairs:
        if deg[a] < d and deg[b] < d:
            edges.append((a, b))
            deg[a] += 1
            deg[b] += 1
    return edges


def _grow_all(n, edges, d, D, deadline, rng):
    """Alternate twin growth, exact cover extension and saturation until nothing grows.

    Every intermediate graph is valid, so stopping at any deadline is safe.
    """
    cur_n, cur_e = n, list(edges)
    for _ in range(6):
        if time.monotonic() >= deadline:
            break
        before = cur_n
        cur_n, cur_e = _twin_grow(cur_n, cur_e, d, rng, deadline)
        cur_n, cur_e = _extend_exact(cur_n, cur_e, d, D, deadline, rng)
        cur_e = _saturate_edges(cur_n, cur_e, d, rng)
        if cur_n == before:
            break
    return cur_n, cur_e


def _run_c(d, D, seed, graph, budget, stall=1500):
    """Run the C annealer from `graph` for `budget` seconds; return the parsed (n, edges)."""
    out = lib.run_c(C_SOURCE, [d, D, seed, f"{budget:.2f}", stall],
                    stdin_graph=graph, timeout=budget + 4.0)
    return lib.parse_graph_text(out)


def build(d, D, seed, time_limit):
    start = time.monotonic()
    tl = float(time_limit)
    rng = random.Random(seed)

    # Trivial cases.
    if D == 1 and d >= 1:
        return 2, [(0, 1)]
    if d < 1 or D < 1:
        return 1, []

    # Calibration: D = 3 with d - 1 a prime power is the Moore-optimal incidence graph.
    if D == 3 and d >= 3 and lib.is_prime_power(d - 1):
        n0, e0 = lib.projective_plane_incidence(d - 1)
        if lib.is_valid(n0, e0, d, D):
            return n0, e0

    # Safe fallback: K_{d,d}, valid for D >= 2.
    best = lib.haar_graph(d, range(d))
    best_n = best[0]

    def consider(n, e):
        nonlocal best, best_n
        if n > best_n and lib.is_valid(n, e, d, D):
            best = (n, e)
            best_n = n

    # Base construction: PG(2, q) for D = 3, W(q) for D >= 4.
    base = None
    if D == 3:
        for q in range(d - 1, 1, -1):
            if lib.is_prime_power(q):
                base = lib.projective_plane_incidence(q)
                break
    elif D >= 4:
        base = _best_gq(d)
    if base is not None:
        consider(base[0], base[1])
    else:
        base = best

    # Exact-cover growth: randomised rebuilds from the base and from the best graph so far.
    use_c = d >= 3 and D >= 2
    build_end = start + (0.42 * tl if use_c else 0.85 * tl)
    first = True
    cycles = 0
    while time.monotonic() < build_end and cycles < 40:
        src = base if (first or rng.random() < 0.5) else best
        first = False
        pn, pe = _grow_all(src[0], src[1], d, D, build_end, rng)
        consider(pn, pe)
        cycles += 1

    # C annealing from the best valid graph; the second run continues from its output.
    if use_c:
        end = start + 0.86 * tl - 1.0
        cur = best
        for idx in range(2):
            remaining = end - time.monotonic()
            if remaining < 2.0:
                break
            budget = remaining * 0.7 if idx == 0 else remaining
            try:
                n2, e2 = _run_c(d, D, seed + idx, cur, budget)
                consider(n2, e2)
                cur = best
            except Exception:
                pass

    if not lib.is_valid(best[0], best[1], d, D):
        best = lib.haar_graph(d, range(d))
    return best
