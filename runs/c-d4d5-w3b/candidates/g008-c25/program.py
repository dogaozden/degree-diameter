"""Non-cyclic group lifts plus grow/ruin search for the d=4, D=5 target.

Change from the parent: the lift stage no longer uses only semidirect products Z_m x| Z_k.
The C engine now builds a pool of finite groups in two ways:
  (a) one semidirect product Z_m x|_r Z_k per order N in 6..256, chosen at random;
  (b) permutation groups generated by 2-3 random permutations on 4..8 points, kept when the
      closure has order 6..256 (these include non-metacyclic groups such as S4, S5, A5, PSL(2,7)).
Each group is stored as a full multiplication table. A voltage lift over a group G of order N is
a bi-Cayley-type graph with 2pN vertices, p <= 4 base vertices per side, and a d-regular base
multigraph. The orbit-reduced diameter test only needs BFS from the 2p fibre representatives,
because left multiplication by G is an automorphism for any group.

The parent's grow-by-two and ruin-and-regrow searches then run from the best lift.
Every output is validated in C and again in Python before it is returned, and K_{d,d} or the
algebraic start is kept as a fallback."""
