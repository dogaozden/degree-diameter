def _run_c(n0, e0, d, D, seed, budget):
    text = lib.run_c(C_SOURCE, [d, D, seed, f"{budget:.2f}"],
                     stdin_graph=(n0, e0), timeout=budget + 10.0)
    return lib.parse_graph_text(text)


def build(d, D, seed, time_limit):
    """Return the best valid (n, edges) found, using about 80% of time_limit."""
    t0 = time.monotonic()
    hard_end = t0 + 0.80 * time_limit
    if d < 1 or D < 1:
        return 1, []
    if D == 1:
        return 2, [(0, 1)]

    # K_{d,d} has diameter 2, so it is valid for every D >= 2.
    fallback = lib.haar_graph(d, range(d))
    if D == 2:
        return fallback

    rng = random.Random(seed * 7919 + d)
    cands = [fallback]
    cands.extend(_starts(d, D, t0 + 0.20 * time_limit, rng))

    valid = []
    for g in cands:
        try:
            if lib.is_valid(g[0], g[1], d, D):
                valid.append(g)
        except Exception:
            pass
    if not valid:
        return fallback
    best = max(valid, key=lambda g: g[0])
    best_n = best[0]

    # Group-lift search, only where it can help (D >= 4).
    if D >= 4:
        lift_end = time.monotonic() + 0.25 * (hard_end - time.monotonic())
        ks = [1, 2, 2, 3, 4] if D >= 5 else [1, 1, 2, 3]
        while time.monotonic() < lift_end:
            k = rng.choice(ks)
            base = best_n // (2 * k)
            G = max(2, base + 1 + rng.randrange(0, max(3, base // 8 + 1)))
            g = _sample_group(G, rng)
            if g is None:
                continue
            order, mul = g
            res = _anneal(d, D, k, order, mul, rng, lift_end, iters=400)
            if res is not None and res[0] > best_n:
                try:
                    if lib.is_valid(res[0], res[1], d, D):
                        best = res
                        best_n = res[0]
                except Exception:
                    pass

    # Main phase: C vertex-addition and two-vertex growth from the best start.
    remaining = hard_end - time.monotonic()
    budget = remaining - 1.5
    if budget > 1.0:
        try:
            n2, e2 = _run_c(best[0], best[1], d, D, seed * 31 + 5, budget)
            if n2 > best[0] and lib.is_valid(n2, e2, d, D):
                best = (n2, e2)
        except Exception:
            pass

    if not lib.is_valid(best[0], best[1], d, D):
        best = fallback
    return best
