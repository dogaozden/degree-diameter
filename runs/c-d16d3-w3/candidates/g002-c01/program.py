def _run_add(n0, e0, d, D, seed, budget):
    text = lib.run_c(C_ADD, [d, D, seed, f"{budget:.2f}"],
                     stdin_graph=(n0, e0), timeout=budget + 5.0)
    return lib.parse_graph_text(text)


def _run_kick(n0, e0, d, D, seed, budget):
    text = lib.run_c(C_KICK, [d, D, seed, f"{budget:.2f}"],
                     stdin_graph=(n0, e0), timeout=budget + 5.0)
    return lib.parse_graph_text(text)


def build(d, D, seed, time_limit):
    """Return the best valid (n, edges) found within about 85% of time_limit."""
    t0 = time.monotonic()
    hard_end = t0 + 0.85 * time_limit
    if d < 1 or D < 1:
        return 1, []
    if D == 1:
        return 2, [(0, 1)]
    rng = random.Random(seed * 7919 + d)

    fallback = lib.haar_graph(d, range(d))  # K_{d,d}: valid for D >= 2
    cands = []
    for g in starts(d, D, t0 + 0.12 * time_limit, rng):
        try:
            if lib.is_valid(g[0], g[1], d, D):
                cands.append(g)
        except Exception:
            pass
    if lib.is_valid(fallback[0], fallback[1], d, D):
        cands.append(fallback)
    if not cands:
        return 1, []
    best = max(cands, key=lambda g: g[0])

    # Phase A: vertex-addition engine from the best start.
    remaining = hard_end - time.monotonic()
    if remaining > 3.0:
        try:
            n1, e1 = _run_add(best[0], best[1], d, D, seed * 31 + 1,
                              max(0.5, 0.2 * remaining))
            if n1 > best[0] and lib.is_valid(n1, e1, d, D):
                best = (n1, e1)
        except Exception:
            pass

    # Phase B: kick-annealed insertion engine (uses nearly all remaining time).
    remaining = hard_end - time.monotonic()
    if remaining > 3.0:
        try:
            n2, e2 = _run_kick(best[0], best[1], d, D, seed * 31 + 2,
                               max(0.5, remaining - 1.5))
            if n2 > best[0] and lib.is_valid(n2, e2, d, D):
                best = (n2, e2)
        except Exception:
            pass

    if not lib.is_valid(best[0], best[1], d, D):
        best = fallback
    return best
