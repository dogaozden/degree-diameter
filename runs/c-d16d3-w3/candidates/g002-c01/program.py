"""Diameter-3 search: structured starts, then a vertex-addition engine and a new kick-annealed insertion engine.

Starts (all validated with lib.is_valid):
  - conic blow-up of PG(2,q) (q = d-3 odd), arc-extended PG(2,q) incidence graphs
    (arc refined by a plateau local search), Araujo-Pardo/Lopez graphs and projective planes,
    W(q) for D >= 4 with small q, and K_{d,d} as the always-valid fallback.

Engines (each returns a valid graph or is discarded):
  1. ADD engine (C_ADD): adds one vertex joined to a greedy cover of spare vertices on the other side,
     accepted only if every pair stays within D.
  2. KICK engine (C_KICK, new): inserts one vertex x on a random side, joined to up to d spare vertices
     of the other side (no distance check). The resulting bad-pair count is then driven to zero by
     degree-preserving 2-switches on the existing edges, annealed on the number of bad pairs.
     Each switch keeps every degree fixed, so the degree bound is never violated. The insertion is
     accepted only if the final graph is valid. This lets the search reshape the neighbourhoods
     of the spare-degree vertices instead of requiring an immediate cover.

The best valid graph is kept at every step, so a failing engine can only waste time.
"""
