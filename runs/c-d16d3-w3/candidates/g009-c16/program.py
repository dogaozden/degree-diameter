"""Combined diameter-3 search.

Python builds the strongest closed-form or arc-extended start it can:
  - projective planes and Araujo-Pardo/Lopez graphs when they apply,
  - arc-extended PG(2,q) with independent A and B sides (plateau local search plus conic init),
    then greedy extra A-B edges on the spare degree,
  - conic blow-up of PG(2,q), and W(q) for D >= 4,
  - K_{d,d} as the always-valid fallback.

C then refines the best start:
  1. ADD engine: adds one vertex joined to a greedy cover, accepted only if all distances stay <= D.
  2. SQUEEZE engine: grows by two vertices with annealed degree-preserving swaps.

Every C result is validated with lib.is_valid before it replaces the current best.
"""
