# C driver and build.
# ----------------------------------------------------------------------------

def _safe(fn, *args):
    """Call fn and return None on any failure, so a broken step never breaks the answer."""
    try:
        return fn(*args)
    except Exception:
        return None


def _c_run(source, args, graph, budget):
    """Run one C engine on graph for about budget seconds; return (n, edges) or None."""
    text = lib.run_c(source, [str(a) for a in args] + [f"{budget:.2f}"],
                     stdin_graph=graph, timeout=budget + 3.0)
    return lib.parse_graph_text(text)


def build(d, D, seed, time_limit):
    """Return the best valid (n, edges) found within about 80% of time_limit."""
    t0 = time.monotonic()
    if d < 1 or D < 1:
        return 1, []
    if D == 1:
        return 2, [(0, 1)]

    best = lib.haar_graph(d, range(d))   # K_{d,d}: valid for D >= 2
    moore = lib.moore_bound(d, D)

    def consider(cand):
        nonlocal best
        if cand is None:
            return
        n, e = cand
        if n > best[0] and lib.is_valid(n, e, d, D):
            best = (n, e)

    # Phase 0: constructions.
    if D >= 3:
        consider(_safe(known_start, d, D))
        consider(_safe(_conic_blowup, d, D))
        rng = random.Random(seed * 7919 + d)
        cands = _safe(_arc_candidates, d, t0 + 0.12 * time_limit, rng) or []
        for cand in sorted(cands, key=lambda t: -t[0]):
            consider(cand)
    if D >= 4 and time.monotonic() < t0 + 0.2 * time_limit:
        consider(_safe(_best_gq, d))

    # Phase A: vertex-addition engine.
    hard_end = t0 + 0.80 * time_limit
    if best[0] < moore:
        rem = hard_end - time.monotonic()
        if rem > 1.5:
            res = _safe(_c_run, C_ADD, [d, D, seed * 31 + 1], best,
                        max(0.5, 0.35 * rem - 0.5))
            consider(res)

    # Phase B: squeeze-by-two engine from the current best.
    if best[0] < moore:
        rem = hard_end - time.monotonic()
        if rem > 1.5:
            res = _safe(_c_run, C_SQUEEZE, [d, D, seed * 31 + 2], best,
                        max(0.5, rem - 1.0))
            consider(res)

    if not lib.is_valid(best[0], best[1], d, D):
        best = lib.haar_graph(d, range(d))
    return best
