class _Best:
    def __init__(self, n, e):
        self.n = n
        self.e = e

    def offer(self, n, e, d, D):
        """Keep (n, e) if it is valid and strictly larger than the current best."""
        if n > self.n and lib.is_valid(n, e, d, D):
            self.n, self.e = n, e


# ----------------------------------------------------------------------------
# Generalized quadrangle W(q) (fast version using list-based field tables).
# ----------------------------------------------------------------------------

def _gq_fast(q):
    """Incidence graph of points and lines of W(q). Degree q + 1, diameter 4, order 2(q+1)(q^2+1)."""
    F = lib.GF(q)
    A = F.add_table.tolist()
    M = F.mul_table.tolist()
    NEG = [F.neg(a) for a in range(q)]
    INV = [0] + [F.inv(a) for a in range(1, q)]
    pts = [v for v in itertools.product(range(q), repeat=4)
           if any(v) and next(c for c in v if c) == 1]
    index = {v: i for i, v in enumerate(pts)}
    P = len(pts)

    def norm(v):
        inv = INV[next(c for c in v if c)]
        return tuple(M[inv][t] for t in v)

    def form(x, y):
        t = A[M[x[0]][y[1]]][NEG[M[x[1]][y[0]]]]
        u = A[M[x[2]][y[3]]][NEG[M[x[3]][y[2]]]]
        return A[t][u]

    covered = [bytearray(P) for _ in range(P)]
    lines = []
    for i in range(P):
        x = pts[i]
        row = covered[i]
        for j in range(i + 1, P):
            if row[j]:
                continue
            y = pts[j]
            if form(x, y) != 0:
                continue
            L = set()
            for a in range(q):
                Ma = M[a]
                for b in range(q):
                    if a == 0 and b == 0:
                        continue
                    Mb = M[b]
                    v = tuple(A[Ma[x[k]]][Mb[y[k]]] for k in range(4))
                    if any(v):
                        L.add(index[norm(v)])
            L = sorted(L)
            lines.append(L)
            for p in L:
                rp = covered[p]
                for r in L:
                    rp[r] = 1
    edges = [(p, P + j) for j, L in enumerate(lines) for p in L]
    return 2 * P, edges


def _best_gq(d):
    """W(q) for the largest prime power q with q + 1 <= d (q <= 13 for speed)."""
    for q in range(d - 1, 1, -1):
        if q <= 13 and lib.is_prime_power(q):
            return _gq_fast(q)
    return None


# ----------------------------------------------------------------------------
# NEW construction: deletion from a larger quadrangle.
#
# Take W(q) with q + 1 > d (degree q + 1, so excess = q + 1 - d). Remove a
# small set of vertices that dominates every remaining vertex (each remaining
# vertex loses at least `excess` neighbours), so the induced subgraph has max
# degree d. Then add edges among spare-degree vertices and hand the result to
# the C annealer, which repairs the diameter and grows the graph.
# ----------------------------------------------------------------------------

def _dominate_removal(nbr, d, nrng):
    """Greedy removal of vertices until every survivor has degree <= d. Returns alive mask or None."""
    n, k = nbr.shape
    alive = np.ones(n, dtype=bool)
    need = np.full(n, k - d, dtype=np.int64)
    while True:
        act = need > 0
        if not (alive & act).any():
            break
        hit = (alive[nbr] & act[nbr]).sum(axis=1).astype(np.float64)
        gain = hit + nrng.random(n) * 0.5
        gain[~alive] = -1.0
        w = int(np.argmax(gain))
        if hit[w] < 1:
            return None
        alive[w] = False
        need[nbr[w]] -= 1
        need[w] = 0
    return alive


def _induced(n, edges, alive):
    """Induced subgraph on the alive vertices, relabelled 0..m-1."""
    idx = np.cumsum(alive) - 1
    E = np.asarray(edges, dtype=np.int64).reshape(-1, 2)
    keep = alive[E[:, 0]] & alive[E[:, 1]]
    S = idx[E[keep]]
    return int(alive.sum()), [(int(a), int(b)) for a, b in S]


def _deletion_start(d, D, rng, deadline):
    """Build a valid-degree subgraph of W(q) for the smallest prime power q in [d, d+2], q <= 11."""
    q = None
    for cand in range(d, d + 3):
        if cand <= 11 and lib.is_prime_power(cand):
            q = cand
            break
    if q is None:
        return None
    n0, e0 = _gq_fast(q)
    if time.monotonic() > deadline:
        return None
    adj = [[] for _ in range(n0)]
    for u, v in e0:
        adj[u].append(v)
        adj[v].append(u)
    if len({len(a) for a in adj}) != 1:
        return None
    nbr = np.array(adj, dtype=np.int64)
    nrng = np.random.default_rng(rng.randrange(1 << 30))
    best = None
    for _ in range(3):
        if best is not None and time.monotonic() > deadline:
            break
        alive = _dominate_removal(nbr, d, nrng)
        if alive is None:
            continue
        n1, e1 = _induced(n0, e0, alive)
        e1 = _saturate_edges(n1, e1, d, rng)
        cost = lib.bad_pairs(n1, e1, D)
        if best is None or cost < best[0]:
            best = (cost, n1, e1)
    if best is None:
        return None
    return best[1], best[2]


# ----------------------------------------------------------------------------
# Twin extension: a twin v of x (same side, N(v) = N(x)) keeps old distances,
# has dist(v, x) = 2, and preserves bipartiteness.
# ----------------------------------------------------------------------------

def _twin_grow(n, edges, d, rng, deadline):
    """Add twin vertices while every neighbour of the original vertex has spare degree."""
    edges = list(edges)
    adj = [[] for _ in range(n)]
    for u, v in edges:
        adj[u].append(v)
        adj[v].append(u)
    deg = [len(a) for a in adj]
    changed = True
    while changed and time.monotonic() < deadline:
        changed = False
        order = list(range(n))
        rng.shuffle(order)
        for x in order:
            if time.monotonic() >= deadline:
                break
            nb = adj[x]
            if not nb or any(deg[y] >= d for y in nb):
                continue
            v = n
            n += 1
            adj.append(list(nb))
            deg.append(len(nb))
            for y in nb:
                adj[y].append(v)
                deg[y] += 1
                edges.append((y, v))
            changed = True
    return n, edges


