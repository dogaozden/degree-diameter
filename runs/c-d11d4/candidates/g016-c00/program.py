def _run_c(d, D, seed, graph, budget, stall=1500):
    """Run the C annealer from `graph` for `budget` seconds; return the parsed (n, edges)."""
    out = lib.run_c(C_SOURCE, [d, D, seed, f"{budget:.2f}", stall],
                    stdin_graph=graph, timeout=budget + 4.0)
    return lib.parse_graph_text(out)


def build(d, D, seed, time_limit):
    start = time.monotonic()
    tl = float(time_limit)
    rng = random.Random(seed)

    # Trivial cases.
    if d >= 1 and D == 1:
        return 2, [(0, 1)]
    if d < 1 or D < 1:
        return 1, []

    # Calibration: D = 3 with d - 1 a prime power is the Moore-optimal incidence graph.
    if D == 3 and d >= 3 and lib.is_prime_power(d - 1):
        n0, e0 = lib.projective_plane_incidence(d - 1)
        if lib.is_valid(n0, e0, d, D):
            return n0, e0

    # Safe fallback: K_{d,d}, valid for D >= 2.
    best = _Best(*lib.haar_graph(d, range(d)))
    end = start + 0.9 * tl - 1.5
    target = D >= 4 and d >= 5

    # Starting constructions.
    if D == 3:
        pg_qs = [q for q in range(d - 1, 1, -1) if lib.is_prime_power(q)][:3]
        t0 = time.monotonic()
        span = max(0.0, 0.3 * tl)
        for i, q in enumerate(pg_qs):
            pg_n, pg_e = lib.projective_plane_incidence(q)
            best.offer(pg_n, pg_e, d, D)
            slice_end = t0 + span * (i + 1) / len(pg_qs)
            n2, e2 = _pipeline(pg_n, pg_e, d, D, slice_end, rng)
            best.offer(n2, e2, d, D)
    elif D >= 4:
        gq = _best_gq(d)
        if gq is not None:
            best.offer(gq[0], gq[1], d, D)
            sat = (gq[0], _saturate_edges(gq[0], gq[1], d, rng))
            best.offer(sat[0], sat[1], d, D)
            pipe_end = start + (0.12 if target else 0.2) * tl
            first = True
            while time.monotonic() < pipe_end:
                if first:
                    src = gq
                else:
                    src = rng.choice([gq, sat, (best.n, best.e)])
                first = False
                pn, pe = _pipeline(src[0], src[1], d, D, pipe_end, rng)
                best.offer(pn, pe, d, D)

    # NEW for targets: deletion from a larger quadrangle, annealed by C.
    del_start = None
    if target and time.monotonic() < start + 0.3 * tl:
        try:
            del_start = _deletion_start(d, D, rng, start + 0.3 * tl)
        except Exception:
            del_start = None

    if del_start is not None:
        remaining = end - time.monotonic()
        if remaining > 4.0:
            try:
                n2, e2 = _run_c(d, D, seed, del_start, remaining * 0.5)
                best.offer(n2, e2, d, D)
            except Exception:
                pass

    # C annealing in chained rounds, each starting from the best valid graph so far.
    rounds = 3
    for idx in range(rounds):
        remaining = end - time.monotonic()
        if remaining < 2.0:
            break
        budget = remaining / (rounds - idx)
        try:
            n2, e2 = _run_c(d, D, seed + idx + 1, (best.n, best.e), budget)
            best.offer(n2, e2, d, D)
        except Exception:
            pass

    if not lib.is_valid(best.n, best.e, d, D):
        return lib.haar_graph(d, range(d))
    return best.n, best.e
