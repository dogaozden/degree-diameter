def _gq_w(q):
    """Incidence graph of points and lines of W(q): degree q+1, diameter 4.

    Points are 0..P-1, lines are P..2P-1.
    """
    F = lib.GF(q)
    pts = [v for v in itertools.product(range(q), repeat=4)
           if any(v) and next(c for c in v if c) == 1]
    index = {v: i for i, v in enumerate(pts)}
    P = len(pts)

    def norm(v):
        c = next(x for x in v if x)
        inv = F.inv(c)
        return tuple(F.mul(inv, x) for x in v)

    def form(x, y):
        t = F.sub(F.mul(x[0], y[1]), F.mul(x[1], y[0]))
        return F.add(t, F.sub(F.mul(x[2], y[3]), F.mul(x[3], y[2])))

    covered = set()
    lines = []
    for i in range(P):
        x = pts[i]
        for j in range(i + 1, P):
            if (i, j) in covered:
                continue
            y = pts[j]
            if form(x, y) != 0:
                continue
            L = set()
            for a in range(q):
                for b in range(q):
                    if a == 0 and b == 0:
                        continue
                    v = tuple(F.add(F.mul(a, x[k]), F.mul(b, y[k])) for k in range(4))
                    if any(v):
                        L.add(index[norm(v)])
            L = sorted(L)
            lines.append(L)
            for p in L:
                for r in L:
                    if p < r:
                        covered.add((p, r))

    edges = []
    for j, L in enumerate(lines):
        for p in L:
            edges.append((p, P + j))
    return 2 * P, edges


def _best_gq(d):
    """W(q) for the largest prime power q with q + 1 <= d (q <= 16)."""
    for q in range(d - 1, 1, -1):
        if q <= 16 and lib.is_prime_power(q):
            return _gq_w(q)
    return None


def _saturate(n, edges, d, color, rng):
    """Greedily join deficient opposite-colour vertices in random order."""
    edges = list(edges)
    deg = [0] * n
    existing = set()
    for u, v in edges:
        deg[u] += 1
        deg[v] += 1
        existing.add((min(u, v), max(u, v)))
    left = [v for v in range(n) if color[v] == 0 and deg[v] < d]
    right = [v for v in range(n) if color[v] == 1 and deg[v] < d]
    pairs = [(a, b) for a in left for b in right
             if (min(a, b), max(a, b)) not in existing]
    rng.shuffle(pairs)
    for a, b in pairs:
        if deg[a] < d and deg[b] < d:
            edges.append((a, b))
            deg[a] += 1
            deg[b] += 1
    return edges


def _run_c(d, D, seed, graph, budget, stall=1500):
    """Run the C annealer from `graph` for `budget` seconds; return parsed (n, edges)."""
    out = lib.run_c(C_SOURCE, [d, D, seed, f"{budget:.2f}", stall],
                    stdin_graph=graph, timeout=budget + 4.0)
    return lib.parse_graph_text(out)


# ----------------------------------------------------------------------------
# Bi-Cayley graphs over finite groups (a substantially different construction).
#
# Vertices a_x and b_y for x, y in G (|G| = N). Edge a_x -- b_{x*s} for s in S,
# |S| = d distinct. Left multiplication by g is an automorphism, so the graph is
# of diameter <= D iff every vertex is within D of a_e and of b_e. The cost is
# the number of unreached vertices from those two sources, searched by
# hill-climbing over S inside a random semidirect product Z_m x| Z_k.
# ----------------------------------------------------------------------------

def _random_group(N, rng):
    """Return (order, mul, inv) for a random semidirect product Z_m x| Z_k of order N, or None."""
    opts = []
    for k in range(1, 13):
        if N % k:
            continue
        m = N // k
        if m < 2:
            continue
        if k == 1:
            opts.append((m, 1, 1))
            continue
        for r in range(1, m):
            if math.gcd(r, m) == 1 and pow(r, k, m) == 1 % m:
                opts.append((m, k, r))
    if not opts:
        return None
    if len(opts) > 60:
        opts = rng.sample(opts, 60)
    m, k, r = rng.choice(opts)
    order, mul, inv = lib.semidirect_group(m, k, r)
    return order, mul, inv


def _bicayley_try(N, d, D, rng, deadline, iters):
    """Search a connection set of size d in a random group of order N; return (2N, edges) or None."""
    g = _random_group(N, rng)
    if g is None:
        return None
    _, mul, inv = g
    Rc = {}

    def R(t):
        r = Rc.get(t)
        if r is None:
            r = [mul(x, t) for x in range(N)]
            Rc[t] = r
        return r

    def cost(S):
        Rf = [R(s) for s in S]
        Ri = [R(inv(s)) for s in S]
        total = 0
        for src in (0, N):
            seen = bytearray(2 * N)
            seen[src] = 1
            frontier = [src]
            for _ in range(D):
                nxt = []
                for v in frontier:
                    if v < N:
                        for Rr in Rf:
                            w = N + Rr[v]
                            if not seen[w]:
                                seen[w] = 1
                                nxt.append(w)
                    else:
                        y = v - N
                        for Rr in Ri:
                            w = Rr[y]
                            if not seen[w]:
                                seen[w] = 1
                                nxt.append(w)
                frontier = nxt
                if not frontier:
                    break
            total += 2 * N - sum(seen)
        return total

    S = rng.sample(range(N), d)
    c = cost(S)
    for _ in range(iters):
        if c == 0 or time.monotonic() >= deadline:
            break
        i = rng.randrange(d)
        x = rng.randrange(N)
        if x in S:
            continue
        T = S[:]
        T[i] = x
        ct = cost(T)
        if ct <= c or rng.random() < 0.03:
            S, c = T, ct
    if c != 0:
        return None
    edges = []
    for s in S:
        Rs = R(s)
        for x in range(N):
            edges.append((x, N + Rs[x]))
    return 2 * N, edges


def _bicayley_phase(d, D, floor_n, rng, deadline):
    """Try bi-Cayley graphs of order 2N for N = floor_n, floor_n+1, ... while they succeed."""
    found = None
    N = max(floor_n, d + 1)
    while time.monotonic() < deadline:
        res = None
        for _ in range(3):
            if time.monotonic() >= deadline:
                break
            res = _bicayley_try(N, d, D, rng, deadline, 400)
            if res is not None:
                break
        if res is None:
            break
        found = res
        N += 1
    return found


# ----------------------------------------------------------------------------
# Build.
# ----------------------------------------------------------------------------

def build(d, D, seed, time_limit):
    t0 = time.monotonic()
    tl = float(time_limit)
    rng = random.Random(seed)

    def at(frac):
        return t0 + frac * tl

    if D == 1 and d >= 1:
        return 2, [(0, 1)]
    if d < 1 or D < 1:
        return 1, []

    # Calibration: incidence graph of PG(2, d-1) meets the Moore bound.
    if D == 3 and d >= 3 and lib.is_prime_power(d - 1):
        n0, e0 = lib.projective_plane_incidence(d - 1)
        if lib.is_valid(n0, e0, d, D):
            return n0, e0

    # Safe fallback: K_{d,d} (valid for D >= 2).
    best = lib.haar_graph(d, range(d))
    best_n = best[0]

    def consider(n, e):
        nonlocal best, best_n
        if lib.is_valid(n, e, d, D):
            if n > best_n or (n == best_n and len(e) > len(best[1])):
                best = (n, e)
                best_n = n

    if D == 3 and d >= 3:
        for q in range(d - 1, 1, -1):
            if lib.is_prime_power(q):
                try:
                    n1, e1 = lib.projective_plane_incidence(q)
                    consider(n1, e1)
                except Exception:
                    pass
                break

    use_bi = D >= 4 and d >= 5
    if use_bi:
        try:
            gq = _best_gq(d)
            if gq is not None:
                n_gq, e_gq = gq
                consider(n_gq, e_gq)
                color = [0] * (n_gq // 2) + [1] * (n_gq // 2)
                e_sat = _saturate(n_gq, e_gq, d, color, rng)
                consider(n_gq, e_sat)
        except Exception:
            pass

    def run_c_until(end, s):
        if d < 3:
            return
        remaining = end - time.monotonic()
        if remaining < 2.0:
            return
        try:
            n2, e2 = _run_c(d, D, s, best, remaining)
            consider(n2, e2)
        except Exception:
            pass

    if use_bi:
        # Stage 1: anneal-grow the current best (saturated quadrangle).
        run_c_until(at(0.55), seed)
        # Stage 2: bi-Cayley search for orders above the current best.
        try:
            floor_n = best_n // 2 + 1
            res = _bicayley_phase(d, D, floor_n, rng, at(0.78))
            if res is not None:
                consider(res[0], res[1])
        except Exception:
            pass
        # Stage 3: anneal-grow the largest valid graph found.
        run_c_until(min(at(0.90), t0 + tl - 1.5), seed + 1)
    else:
        run_c_until(min(at(0.90), t0 + tl - 1.5), seed)

    if not lib.is_valid(best[0], best[1], d, D):
        best = lib.haar_graph(d, range(d))
    return best
