def _run_c(d, D, seed, graph, budget, stall=1500):
    """Run the C annealer from `graph` for `budget` seconds; return the parsed (n, edges)."""
    out = lib.run_c(C_SOURCE, [d, D, seed, f"{budget:.2f}", stall],
                    stdin_graph=graph, timeout=budget + 4.0)
    return lib.parse_graph_text(out)


def build(d, D, seed, time_limit):
    start = time.monotonic()
    tl = float(time_limit)
    rng = random.Random(seed)

    # Trivial cases.
    if d >= 1 and D == 1:
        return 2, [(0, 1)]
    if d < 1 or D < 1:
        return 1, []

    # Calibration: D = 3 with d - 1 a prime power is the Moore-optimal incidence graph.
    if D == 3 and d >= 3 and lib.is_prime_power(d - 1):
        n0, e0 = lib.projective_plane_incidence(d - 1)
        if lib.is_valid(n0, e0, d, D):
            return n0, e0

    # Safe fallback: K_{d,d}, valid for D >= 2.
    best = lib.haar_graph(d, range(d))
    best_n = best[0]

    def consider(n, e):
        nonlocal best, best_n
        if n > best_n and lib.is_valid(n, e, d, D):
            best = (n, e)
            best_n = n

    # Stage A: algebraic starts and quadrangle / plane growth (about 12% of budget).
    sat = None
    pipe_end = start + 0.12 * tl
    try:
        if D == 3:
            for q in [x for x in range(d - 1, 1, -1) if lib.is_prime_power(x)][:2]:
                pn, pe = lib.projective_plane_incidence(q)
                consider(pn, pe)
                if time.monotonic() < pipe_end:
                    n2, e2 = _pipeline(pn, pe, d, D, pipe_end, rng)
                    consider(n2, e2)
        elif D >= 4:
            gq = _best_gq(d)
            if gq is not None:
                consider(gq[0], gq[1])
                sat = (gq[0], _saturate_edges(gq[0], gq[1], d, rng))
                consider(sat[0], sat[1])
                if time.monotonic() < pipe_end:
                    n2, e2 = _pipeline(gq[0], gq[1], d, D, pipe_end, rng)
                    consider(n2, e2)
    except Exception:
        pass

    # Stage B: C voltage-lift search over semidirect products (until 42% of budget).
    if D >= 3:
        try:
            res = _lift_stage(d, D, best_n, rng, start + 0.42 * tl)
            if res is not None:
                consider(res[0], res[1])
        except Exception:
            pass

    # Stage C: C annealing growth, first from the best graph, then from the saturated quadrangle.
    if D >= 3 and d >= 3:
        try:
            end = start + 0.9 * tl - 1.0
            starts_c = [best]
            if sat is not None:
                starts_c.append(sat)
            for idx, g in enumerate(starts_c):
                remaining = end - time.monotonic()
                if remaining < 2.0:
                    break
                share = 0.6 if (idx == 0 and len(starts_c) > 1) else 1.0
                n2, e2 = _run_c(d, D, seed + idx, g, remaining * share)
                consider(n2, e2)
        except Exception:
            pass

    if not lib.is_valid(best[0], best[1], d, D):
        best = lib.haar_graph(d, range(d))
    return best
