# ----------------------------------------------------------------------------
# Strategy (bold change for the weak target d=11, D=4):
#
#   1. Keep a valid fallback (K_{d,d}, or a projective plane / W(q) when available).
#   2. Quadrangle growth (twin, cover and saturation steps) from W(q).
#   3. NEW: a C voltage-lift search over semidirect products Z_M x| Z_K2 with a
#      small base graph of K + K vertices per side. Each attempt is a short C run
#      that hill-climbs the voltages until the lift has diameter <= D. The lift
#      order is 2*K*|G|, so the search aims just above the current best order.
#   4. C simulated annealing (from the best graph and the saturated quadrangle)
#      grows the best valid graph by one vertex whenever it has zero bad pairs.
#
# Every returned graph passes lib.is_valid, with K_{d,d} as the final fallback.
# ----------------------------------------------------------------------------

