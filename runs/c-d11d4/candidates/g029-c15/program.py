def _lift_once(d, D, K, G, rng, budget):
    """Run C_LIFT for a random group of order G = M*T (semidirect Z_M x| Z_T) on K+K base vertices."""
    T = rng.choice([t for t in range(1, G + 1) if G % t == 0])
    M = G // T
    if T == 1 or M == 1:
        R = 1
    else:
        cands = [r for r in range(1, M)
                 if math.gcd(r, M) == 1 and pow(r, T, M) == 1 % M]
        if not cands:
            return None
        R = rng.choice(cands)
    out = lib.run_c(C_LIFT, [d, D, rng.randrange(1, 1 << 30), f"{budget:.2f}", K, M, T, R],
                    timeout=budget + 4.0)
    n, edges = lib.parse_graph_text(out)
    if n == 0 or not edges:
        return None
    return n, edges


def _run_c(d, D, seed, graph, budget, stall=1500):
    """Run the C annealer from `graph` for `budget` seconds; return the parsed (n, edges)."""
    out = lib.run_c(C_SOURCE, [d, D, seed, f"{budget:.2f}", stall],
                    stdin_graph=graph, timeout=budget + 4.0)
    return lib.parse_graph_text(out)


def build(d, D, seed, time_limit):
    start = time.monotonic()
    tl = float(time_limit)
    rng = random.Random(seed)

    # Trivial cases.
    if d >= 1 and D == 1:
        return 2, [(0, 1)]
    if d < 1 or D < 1:
        return 1, []

    # Calibration: D = 3 with d - 1 a prime power is the Moore-optimal incidence graph.
    if D == 3 and d >= 3 and lib.is_prime_power(d - 1):
        n0, e0 = lib.projective_plane_incidence(d - 1)
        if lib.is_valid(n0, e0, d, D):
            return n0, e0

    # Safe fallback: K_{d,d}, valid for D >= 2.
    best = lib.haar_graph(d, range(d))
    best_n = best[0]

    def consider(n, e):
        nonlocal best, best_n
        if n > best_n and lib.is_valid(n, e, d, D):
            best = (n, e)
            best_n = n

    # Stage 1: Python constructions (projective planes or generalized quadrangle + growth).
    py_end = start + 0.25 * tl
    sat = None
    if D == 3:
        pg_qs = [q for q in range(d - 1, 1, -1) if lib.is_prime_power(q)][:3]
        t0 = time.monotonic()
        span = max(0.0, py_end - t0)
        for i, q in enumerate(pg_qs):
            pg_n, pg_e = lib.projective_plane_incidence(q)
            consider(pg_n, pg_e)
            slice_end = t0 + span * (i + 1) / len(pg_qs)
            n2, e2 = _pipeline(pg_n, pg_e, d, D, slice_end, rng)
            consider(n2, e2)
    elif D >= 4:
        gq = _best_gq(d)
        if gq is not None:
            consider(gq[0], gq[1])
            sat = (gq[0], _saturate_edges(gq[0], gq[1], d, rng))
            consider(sat[0], sat[1])
            first = True
            while time.monotonic() < py_end:
                src = gq if first else rng.choice([gq, sat, best])
                first = False
                pn, pe = _pipeline(src[0], src[1], d, D, py_end, rng)
                consider(pn, pe)

    # Stage 2: C voltage-lift search over random semidirect groups, aiming above best_n.
    # Each run targets order 2*K*G > best_n, so every success strictly improves the result.
    lift_end = start + 0.72 * tl
    if d >= 3 and D >= 2:
        tries = 0
        while tries < 400:
            tries += 1
            remaining = lift_end - time.monotonic()
            if remaining < 1.0:
                break
            K = rng.choice([1, 2, 3, 4, 5, 6, 8])
            G = best_n // (2 * K) + 1 + rng.choice([0, 0, 1, 2])
            if 2 * K * G > 4000:
                continue
            budget = min(6.0, remaining - 0.5)
            try:
                res = _lift_once(d, D, K, G, rng, budget)
            except Exception:
                res = None
            if res is not None:
                consider(res[0], res[1])

    # Stage 3: C annealing that grows the best graph by one vertex at a time.
    # Starts from the best valid graph (70% of the remaining budget), then from
    # the saturated quadrangle for diversity. Any failure keeps the current result.
    if d >= 3 and D >= 2:
        end = start + 0.88 * tl - 1.0
        starts_c = [best] + ([sat] if sat is not None else [])
        for idx, g in enumerate(starts_c):
            remaining = end - time.monotonic()
            if remaining < 2.0:
                break
            share = 0.7 if (idx == 0 and len(starts_c) > 1) else 1.0
            try:
                n2, e2 = _run_c(d, D, seed + idx, g, remaining * share)
                consider(n2, e2)
            except Exception:
                pass

    if not lib.is_valid(best[0], best[1], d, D):
        best = lib.haar_graph(d, range(d))
    return best
