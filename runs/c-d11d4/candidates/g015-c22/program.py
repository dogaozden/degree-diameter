def _gq_w(q):
    """Incidence graph of points and lines of the generalized quadrangle W(q).

    Degree q + 1, diameter 4, order 2(q+1)(q^2+1).
    """
    F = lib.GF(q)
    pts = [v for v in itertools.product(range(q), repeat=4)
           if any(v) and next(c for c in v if c) == 1]
    index = {v: i for i, v in enumerate(pts)}
    P = len(pts)

    def norm(v):
        c = next(x for x in v if x)
        inv = F.inv(c)
        return tuple(F.mul(inv, x) for x in v)

    def form(x, y):
        t = F.sub(F.mul(x[0], y[1]), F.mul(x[1], y[0]))
        return F.add(t, F.sub(F.mul(x[2], y[3]), F.mul(x[3], y[2])))

    covered = set()
    lines = []
    for i in range(P):
        x = pts[i]
        for j in range(i + 1, P):
            if (i, j) in covered:
                continue
            y = pts[j]
            if form(x, y) != 0:
                continue
            L = set()
            for a in range(q):
                for b in range(q):
                    if a == 0 and b == 0:
                        continue
                    v = tuple(F.add(F.mul(a, x[k]), F.mul(b, y[k])) for k in range(4))
                    if any(v):
                        L.add(index[norm(v)])
            L = sorted(L)
            lines.append(L)
            for p in L:
                for r in L:
                    if p < r:
                        covered.add((p, r))

    edges = []
    for j, L in enumerate(lines):
        for p in L:
            edges.append((p, P + j))
    return 2 * P, edges


def _best_gq(d):
    """W(q) incidence graph for the largest prime power q <= 16 with q + 1 <= d, or None."""
    for q in range(d - 1, 1, -1):
        if q <= 16 and lib.is_prime_power(q):
            return _gq_w(q)
    return None


def _bipartition(n, adj):
    """Two-colouring of a bipartite graph given by adjacency lists."""
    color = [-1] * n
    for s in range(n):
        if color[s] != -1:
            continue
        color[s] = 0
        stack = [s]
        while stack:
            u = stack.pop()
            for v in adj[u]:
                if color[v] == -1:
                    color[v] = 1 - color[u]
                    stack.append(v)
    return color


def _saturate_edges(n, edges, d, rng):
    """Greedily join deficient opposite-side vertices (adding edges never breaks diameter)."""
    edges = list(edges)
    adj = [[] for _ in range(n)]
    existing = set()
    for u, v in edges:
        adj[u].append(v)
        adj[v].append(u)
        existing.add((min(u, v), max(u, v)))
    deg = [len(a) for a in adj]
    color = _bipartition(n, adj)
    left = [v for v in range(n) if color[v] == 0 and deg[v] < d]
    right = [v for v in range(n) if color[v] == 1 and deg[v] < d]
    pairs = [(a, b) for a in left for b in right if (min(a, b), max(a, b)) not in existing]
    rng.shuffle(pairs)
    for a, b in pairs:
        if deg[a] < d and deg[b] < d:
            edges.append((a, b))
            deg[a] += 1
            deg[b] += 1
    return edges


# ----------------------------------------------------------------------------
# A different starting construction: a random d-regular bipartite graph on
# 2h vertices (union of d matchings with collisions repaired by swaps). The
# annealer then has to drive the bad-pair cost to zero from scratch.
# ----------------------------------------------------------------------------

def _random_biregular(h, d, rng):
    """Edges of a d-regular simple bipartite graph with parts 0..h-1 and h..2h-1, or None."""
    if d > h:
        return None
    used = [set() for _ in range(h)]
    for _ in range(d):
        p = list(range(h))
        rng.shuffle(p)
        for _it in range(20000):
            bad = [i for i in range(h) if p[i] in used[i]]
            if not bad:
                break
            i = rng.choice(bad)
            j = rng.randrange(h)
            p[i], p[j] = p[j], p[i]
        else:
            return None
        for i in range(h):
            used[i].add(p[i])
    return [(i, h + x) for i in range(h) for x in used[i]]


def _add_extra(n, edges, d, k, rng):
    """Append k vertices, each joined to d opposite-side vertices; full ones give up a random edge."""
    adj = [[] for _ in range(n)]
    for u, v in edges:
        adj[u].append(v)
        adj[v].append(u)
    deg = [len(a) for a in adj]
    color = _bipartition(n, adj)
    for _ in range(k):
        c = rng.randrange(2)
        v = n
        n += 1
        adj.append([])
        deg.append(0)
        color.append(c)
        opp = [w for w in range(v) if color[w] == 1 - c]
        rng.shuffle(opp)
        opp.sort(key=lambda w: deg[w] >= d)
        for w in opp[:d]:
            if deg[w] >= d:
                x = rng.choice(adj[w])
                adj[w].remove(x)
                adj[x].remove(w)
                deg[w] -= 1
                deg[x] -= 1
            adj[v].append(w)
            adj[w].append(v)
            deg[v] += 1
            deg[w] += 1
    out = [(u, v) for u in range(n) for v in adj[u] if u < v]
    return n, out


def _anneal(graph, d, D, seed, budget):
    """Run the C annealer from `graph` for `budget` CPU seconds; return parsed (n, edges)."""
    out = lib.run_c(C_SOURCE, [d, D, seed, f"{budget:.2f}", 1500],
                    stdin_graph=graph, timeout=budget + 6.0)
    return lib.parse_graph_text(out)


EXTRA = 96


def build(d, D, seed, time_limit):
    start = time.monotonic()
    tl = float(time_limit)
    rng = random.Random(seed)

    # Trivial cases.
    if d >= 1 and D == 1:
        return 2, [(0, 1)]
    if d < 1 or D < 1:
        return 1, []

    # Calibration: D = 3 with d - 1 a prime power is the Moore-optimal incidence graph.
    if D == 3 and d >= 3 and lib.is_prime_power(d - 1):
        n0, e0 = lib.projective_plane_incidence(d - 1)
        if lib.is_valid(n0, e0, d, D):
            return n0, e0

    # Safe fallback: K_{d,d}, valid for D >= 2.
    best = lib.haar_graph(d, range(d))
    best_n = best[0]

    def consider(n, e):
        nonlocal best, best_n
        if n > best_n and lib.is_valid(n, e, d, D):
            best = (n, e)
            best_n = n

    # All C work must finish before this point.
    deadline = start + 0.9 * tl - 2.0

    sat = None
    if D == 3:
        for q in [q for q in range(d - 1, 1, -1) if lib.is_prime_power(q)][:3]:
            try:
                pn, pe = lib.projective_plane_incidence(q)
                consider(pn, pe)
            except Exception:
                pass

    if D == 4 and d >= 3:
        try:
            gq = _best_gq(d)
        except Exception:
            gq = None
        if gq is not None:
            consider(gq[0], gq[1])
            sat_e = _saturate_edges(gq[0], gq[1], d, rng)
            sat = (gq[0], sat_e)
            consider(sat[0], sat[1])

    # Plan the C runs. For D = 4 with a W(q) base, try a different construction
    # first: extend the saturated base by EXTRA vertices, then a random
    # biregular start of about the same size, then continue from the best valid graph.
    if D == 4 and sat is not None and d >= 5:
        plan = [("extra", 0.45), ("random", 0.25), ("best", 1.0)]
    else:
        plan = [("best", 1.0)]

    avail0 = deadline - time.monotonic()
    used_frac = 0.0
    for idx, (kind, frac) in enumerate(plan):
        room = deadline - time.monotonic()
        if room < 3.0:
            break
        if kind == "best":
            budget = room - 1.0
        else:
            budget = min(frac * avail0, room - 1.0)
        if budget < 2.0:
            continue
        try:
            if kind == "extra":
                g = _add_extra(sat[0], sat[1], d, EXTRA, rng)
            elif kind == "random":
                h = (best_n + EXTRA) // 2
                e = _random_biregular(h, d, rng)
                if e is None:
                    continue
                g = (2 * h, e)
            else:
                g = best
            n2, e2 = _anneal(g, d, D, seed + idx, budget)
            consider(n2, e2)
        except Exception:
            pass
        used_frac += frac

    if not lib.is_valid(best[0], best[1], d, D):
        best = lib.haar_graph(d, range(d))
    return best
