def build(d, D, seed, time_limit):
    start = time.monotonic()
    deadline = start + 0.85 * time_limit
    rng = random.Random(seed)

    if D == 1 and d >= 1:
        return 2, [(0, 1)]
    if d < 1 or D < 1:
        return 1, []

    # Safe fallback: K_{d,d}, valid for D >= 2.
    best_n, best_e = lib.haar_graph(d, range(d))

    def consider(n, e):
        nonlocal best_n, best_e
        if n > best_n and lib.is_valid(n, e, d, D):
            best_n, best_e = n, list(e)

    # Stage 1 (new construction): trim an oversized W(q) / PG(2,q) to degree d,
    # delete bad-pair vertices, then regrow. Several randomized attempts.
    if D >= 3:
        for base in (_best_gq(d) if D >= 4 else None, _best_pg(d)):
            if base is not None:
                consider(*base)
                n1, e1 = _grow(base[0], base[1], d, D, start + 0.15 * time_limit, rng)
                consider(n1, e1)

        attempt_end = start + 0.40 * time_limit
        while time.monotonic() < attempt_end:
            s = _structured_start(d, D)
            if s is None:
                break
            res = _trim_and_repair(s[0], s[1], d, D, attempt_end, rng)
            if res is None:
                continue
            n2, e2 = res
            consider(n2, e2)
            n3, e3 = _grow(n2, e2, d, D, attempt_end, rng)
            consider(n3, e3)

    # Stage 2: kill-repair-regrow from the best valid graph found so far.
    if D >= 2 and time.monotonic() < deadline:
        _lns(best_n, best_e, d, D, start + 0.60 * time_limit, rng, consider)

    # Stage 3: prune redundant edges and regrow.
    if D >= 2 and time.monotonic() < deadline:
        _prune_regrow(best_n, best_e, d, D, start + 0.75 * time_limit, rng, consider)

    # Stage 4: add-and-repair from the largest valid graph.
    if D >= 2 and time.monotonic() < deadline:
        _repair(d, D, best_n, best_e, deadline, rng, consider)

    if not lib.is_valid(best_n, best_e, d, D):
        return lib.haar_graph(d, range(d))
    return best_n, list(best_e)
