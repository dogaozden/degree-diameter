def _balls_radius(n, adj, r):
    """Bitmask per vertex of all vertices within distance r."""
    ball = [1 << v for v in range(n)]
    for _ in range(r):
        new = []
        for v in range(n):
            x = ball[v]
            for u in adj[v]:
                x |= ball[u]
            new.append(x)
        ball = new
    return ball


def _bipartition(n, adj):
    """Two-colouring of a bipartite graph given by adjacency lists or sets."""
    color = [-1] * n
    for s in range(n):
        if color[s] != -1:
            continue
        color[s] = 0
        stack = [s]
        while stack:
            u = stack.pop()
            for v in adj[u]:
                if color[v] == -1:
                    color[v] = 1 - color[u]
                    stack.append(v)
    return color


def _to_sets(n, edges):
    adj = [set() for _ in range(n)]
    for u, v in edges:
        adj[u].add(v)
        adj[v].add(u)
    return adj


def _greedy_cover(cands, ball, full, d, rng, randomize):
    """Greedy set cover of `full` by at most d candidate vertices. Returns list or None."""
    pool = list(cands)
    if randomize:
        rng.shuffle(pool)
    covered = 0
    chosen = []
    while covered != full and len(chosen) < d and pool:
        gains = [(ball[s] & ~covered).bit_count() for s in pool]
        best_g = max(gains, default=0)
        if best_g == 0:
            break
        thr = best_g
        if randomize and rng.random() < 0.5:
            thr = best_g - 1
        opts = [i for i, g in enumerate(gains) if g >= thr and g > 0]
        i = rng.choice(opts) if randomize else opts[0]
        s = pool.pop(i)
        chosen.append(s)
        covered |= ball[s]
    return chosen if covered == full else None


def _extend_cover(n, edges, d, D, deadline, rng=None):
    """Greedily add vertices whose neighbourhoods are cover sets of deficient vertices."""
    if D < 2:
        return n, edges
    if rng is None:
        rng = random.Random(0)
    edges = list(edges)
    adj = [[] for _ in range(n)]
    for u, v in edges:
        adj[u].append(v)
        adj[v].append(u)
    deg = [len(a) for a in adj]
    color = _bipartition(n, adj)

    while time.monotonic() < deadline:
        ball = _balls_radius(n, adj, D - 1)
        full = (1 << n) - 1
        added = False
        for c in (0, 1):
            cands = [s for s in range(n) if color[s] == c and deg[s] < d]
            if not cands:
                continue
            chosen = None
            for attempt in range(200):
                if time.monotonic() >= deadline:
                    break
                chosen = _greedy_cover(cands, ball, full, d, rng, attempt > 0)
                if chosen:
                    break
            if chosen:
                v = n
                n += 1
                color.append(1 - c)
                adj.append([])
                deg.append(0)
                for s in chosen:
                    edges.append((s, v))
                    adj[s].append(v)
                    adj[v].append(s)
                    deg[s] += 1
                    deg[v] += 1
                added = True
                break
        if not added:
            break
    return n, edges


def _saturate_edges(n, edges, d, rng):
    """Greedily join deficient opposite-side vertices in random order (only shortens distances)."""
    edges = list(edges)
    adj = [[] for _ in range(n)]
    existing = set()
    for u, v in edges:
        adj[u].append(v)
        adj[v].append(u)
        existing.add((min(u, v), max(u, v)))
    deg = [len(a) for a in adj]
    color = _bipartition(n, adj)
    left = [v for v in range(n) if color[v] == 0 and deg[v] < d]
    right = [v for v in range(n) if color[v] == 1 and deg[v] < d]
    pairs = [(a, b) for a in left for b in right
             if (min(a, b), max(a, b)) not in existing]
    rng.shuffle(pairs)
    for a, b in pairs:
        if deg[a] < d and deg[b] < d:
            edges.append((a, b))
            deg[a] += 1
            deg[b] += 1
    return edges


def _grow(n, edges, d, D, deadline, rng):
    """Extend by cover vertices, then saturate edges with the remaining spare degree."""
    cur_n, cur_e = n, list(edges)
    for _ in range(8):
        if time.monotonic() >= deadline:
            break
        n2, e2 = _extend_cover(cur_n, cur_e, d, D, deadline, rng)
        grew = n2 != cur_n
        cur_n = n2
        cur_e = _saturate_edges(cur_n, e2, d, rng)
        if not grew:
            break
    return cur_n, cur_e


def _spare_matching_base(n0, e0, d, rng, keep_free):
    """Add cross-side edges to a point-line base, leaving keep_free points with spare slots."""
    n = n0
    half = n // 2
    adj = _to_sets(n, e0)
    rounds = d - max(len(a) for a in adj)
    for _ in range(max(0, rounds)):
        order = [p for p in range(half) if len(adj[p]) < d]
        rng.shuffle(order)
        target = max(0, len(order) - keep_free)
        count = 0
        for p in order:
            if count >= target:
                break
            cands = [L for L in range(half, n) if len(adj[L]) < d and L not in adj[p]]
            if not cands:
                continue
            L = rng.choice(cands)
            adj[p].add(L)
            adj[L].add(p)
            count += 1
    return n, [(u, v) for u in range(n) for v in adj[u] if u < v]


def _duplicate_twins(n, edges, d, rng):
    """Greedily add non-adjacent twins (same neighbourhood) while neighbours have spare degree."""
    adj = [set() for _ in range(n)]
    for u, v in edges:
        adj[u].add(v)
        adj[v].add(u)
    changed = True
    while changed:
        changed = False
        order = list(range(len(adj)))
        rng.shuffle(order)
        for v in order:
            nb = adj[v]
            if not nb or len(nb) > d:
                continue
            if any(len(adj[u]) >= d for u in nb):
                continue
            w = len(adj)
            adj.append(set(nb))
            for u in nb:
                adj[u].add(w)
            changed = True
    out = [(u, v) for u in range(len(adj)) for v in adj[u] if u < v]
    return len(adj), out


def _trial(base_n, base_e, d, D, rng, deadline):
    """One randomized pipeline: mix twin duplication with cover growth and saturation."""
    mode = rng.randrange(3)
    n, e = base_n, list(base_e)
    if mode == 0:
        n, e = _duplicate_twins(n, e, d, rng)
        e = _saturate_edges(n, e, d, rng)
        n, e = _grow(n, e, d, D, deadline, rng)
    elif mode == 1:
        n, e = _grow(n, e, d, D, deadline, rng)
        n, e = _duplicate_twins(n, e, d, rng)
        e = _saturate_edges(n, e, d, rng)
        n, e = _grow(n, e, d, D, deadline, rng)
    else:
        e = _saturate_edges(n, e, d, rng)
        n, e = _duplicate_twins(n, e, d, rng)
        e = _saturate_edges(n, e, d, rng)
        n, e = _grow(n, e, d, D, deadline, rng)
    return n, e


# ----------------------------------------------------------------------------
# Large-neighbourhood search (kill, repair by bipartite switches, regrow).
# ----------------------------------------------------------------------------

def _cost(adj, D):
    """Number of vertex pairs at distance more than D (unreachable pairs count)."""
    n = len(adj)
    ball = _balls_radius(n, adj, D)
    return sum(n - b.bit_count() for b in ball) // 2


def _fill(adj, color, d, rng):
    """Add cross-side edges between deficient vertices (only helps the diameter)."""
    n = len(adj)
    left = [v for v in range(n) if color[v] == 0 and len(adj[v]) < d]
    right = [v for v in range(n) if color[v] == 1 and len(adj[v]) < d]
    pairs = [(a, b) for a in left for b in right if b not in adj[a]]
    rng.shuffle(pairs)
    for a, b in pairs:
        if len(adj[a]) < d and len(adj[b]) < d and b not in adj[a]:
            adj[a].add(b)
            adj[b].add(a)


def _anneal(adj, color, d, D, rng, iters, deadline):
    """Bipartite double-edge switches (degrees unchanged) minimising bad pairs. True if cost reaches 0."""
    cur = _cost(adj, D)
    side0 = [v for v in range(len(adj)) if color[v] == 0]
    for _ in range(iters):
        if cur == 0 or time.monotonic() > deadline:
            break
        a = rng.choice(side0)
        if not adj[a]:
            continue
        b = rng.choice(tuple(adj[a]))
        c = rng.choice(side0)
        if c == a or not adj[c]:
            continue
        e = rng.choice(tuple(adj[c]))
        if e in adj[a] or b in adj[c]:
            continue
        adj[a].discard(b)
        adj[b].discard(a)
        adj[c].discard(e)
        adj[e].discard(c)
        adj[a].add(e)
        adj[e].add(a)
        adj[c].add(b)
        adj[b].add(c)
        new = _cost(adj, D)
        if new <= cur or (new == cur + 1 and rng.random() < 0.1):
            cur = new
        else:
            adj[a].discard(e)
            adj[e].discard(a)
            adj[c].discard(b)
            adj[b].discard(c)
            adj[a].add(b)
            adj[b].add(a)
            adj[c].add(e)
            adj[e].add(c)
    return cur == 0


def _lns(n, edges, d, D, deadline, rng, consider):
    """Kill-repair-regrow large-neighbourhood search from a valid graph, anchored to its best."""
    cur_n, cur_e = n, list(edges)
    best_n, best_e = n, list(edges)
    while time.monotonic() < deadline:
        k = rng.choice((1, 1, 2, 2, 3, 4))
        if k >= cur_n:
            break
        if rng.random() < 0.5:
            cadj = _to_sets(cur_n, cur_e)
            s0 = rng.randrange(cur_n)
            near = [s0] + list(cadj[s0])
            rng.shuffle(near)
            kill = set(near[:k])
        else:
            kill = set(rng.sample(range(cur_n), k))
        keep = [v for v in range(cur_n) if v not in kill]
        remap = {v: i for i, v in enumerate(keep)}
        m = len(keep)
        e2 = [(remap[u], remap[v]) for u, v in cur_e if u not in kill and v not in kill]
        adj = _to_sets(m, e2)
        color = _bipartition(m, adj)
        _fill(adj, color, d, rng)
        if not _anneal(adj, color, d, D, rng, 150, deadline):
            continue
        e3 = [(u, v) for u in range(m) for v in adj[u] if u < v]
        n4, e4 = _grow(m, e3, d, D, deadline, rng)
        consider(n4, e4)
        if n4 > best_n:
            best_n, best_e = n4, list(e4)
        if n4 >= cur_n - 1:
            cur_n, cur_e = n4, e4
        elif n4 < best_n - 3:
            cur_n, cur_e = best_n, list(best_e)


# ----------------------------------------------------------------------------
# NEW CONSTRUCTION: Z-lifts over small (semi)direct product groups.
#
# A base bipartite multigraph with parts A_0..A_{p-1}, B_0..B_{p-1} and a
# degree-d block matrix c (c[i][j] darts from A_i to B_j, row and column sums d).
# Each dart is labelled by a group element g; the lift joins (A_i, x) to
# (B_j, x*g) for all x in G. Every vertex has degree exactly d, the graph is
# bipartite by construction, and the group is nonabelian for r != 1 (abelian
# lifts stall well below the record). Voltages are found by hill-climbing the
# number of pairs at distance > D, with equal-cost moves accepted.
# ----------------------------------------------------------------------------

def _groups(lo, hi):
    """All Z_m x|_r Z_k with order in [lo, hi], as tuples (order, m, k, r)."""
    out = []
    for m in range(2, hi + 1):
        k0 = max(1, -(-lo // m))
        for k in range(k0, hi // m + 1):
            order = m * k
            if order < lo or order > hi:
                continue
            for r in range(1, m):
                if math.gcd(r, m) == 1 and pow(r, k, m) == 1 % m:
                    out.append((order, m, k, r))
    return out


def _lift_cost(n, adj, D):
    """Pairs at distance > D in the lifted graph."""
    reach = [1 << v for v in range(n)]
    for _ in range(D):
        nr = []
        for v in range(n):
            x = reach[v]
            for u in adj[v]:
                x |= reach[u]
            nr.append(x)
        reach = nr
    return sum(n - r.bit_count() for r in reach) // 2


def _set_dart(adj, p, order, mul, i, j, g, add):
    """Add or remove the lifted edges of dart (A_i, B_j, g)."""
    for x in range(order):
        a = i * order + x
        b = (p + j) * order + mul(x, g)
        if add:
            adj[a].append(b)
            adj[b].append(a)
        else:
            adj[a].remove(b)
            adj[b].remove(a)


def _climb(p, order, mul, c, D, deadline, rng):
    """Hill-climb voltages for block matrix c. Returns (success, n, edges)."""
    vol = {key: rng.sample(range(order), cnt) for key, cnt in c.items()}
    n = 2 * p * order
    adj = [[] for _ in range(n)]
    for (i, j), gs in vol.items():
        for g in gs:
            _set_dart(adj, p, order, mul, i, j, g, True)
    cur = _lift_cost(n, adj, D)
    keys = list(c.keys())
    while cur > 0 and time.monotonic() < deadline:
        key = rng.choice(keys)
        i, j = key
        gs = vol[key]
        idx = rng.randrange(len(gs))
        old = gs[idx]
        while True:
            new = rng.randrange(order)
            if new not in gs:
                break
        _set_dart(adj, p, order, mul, i, j, old, False)
        _set_dart(adj, p, order, mul, i, j, new, True)
        gs[idx] = new
        nc = _lift_cost(n, adj, D)
        if nc <= cur:
            cur = nc
        else:
            _set_dart(adj, p, order, mul, i, j, new, False)
            _set_dart(adj, p, order, mul, i, j, old, True)
            gs[idx] = old
    if cur != 0:
        return False, n, None
    edges = [(u, v) for u in range(n) for v in adj[u] if u < v]
    return True, n, edges


def _lift_stage(d, D, rng, deadline, state, consider):
    """Repeatedly try group lifts whose order gives more vertices than the current best."""
    if d < 2 or D < 2:
        return
    while time.monotonic() < deadline:
        p = rng.choice((1, 2))
        if p == 1:
            c = {(0, 0): d}
        else:
            a = rng.randint(1, d - 1)
            c = {(0, 0): a, (0, 1): d - a, (1, 0): d - a, (1, 1): a}
        lo = state['n'] // (2 * p) + 1
        groups = [g for g in _groups(lo, lo + 80) if g[0] > max(c.values())]
        if not groups:
            break
        order, m, k, r = rng.choice(groups)
        _, mul, _ = lib.semidirect_group(m, k, r)
        slice_end = min(deadline, time.monotonic() + 8.0)
        ok, n, edges = _climb(p, order, mul, c, D, slice_end, rng)
        if ok:
            consider(n, edges)


# ----------------------------------------------------------------------------
# Classic pipeline (parent's search), run on its own time share.
# ----------------------------------------------------------------------------

def _classic(d, D, rng, start, budget, state, consider):
    def at(f):
        return start + f * budget

    base_n, base_e = state['n'], list(state['e'])
    base_is_gq = False
    if D >= 3:
        base = _best_gq(d) if D >= 4 else None
        if base is not None:
            base_is_gq = True
        if base is None:
            base = _best_pg(d)
        if base is not None:
            n0, e0 = base
            consider(n0, e0)
            base_n, base_e = n0, list(e0)
            n1, e1 = _grow(n0, e0, d, D, at(0.2), rng)
            consider(n1, e1)

    trial_end = at(0.10)
    while time.monotonic() < trial_end:
        n, e = _trial(base_n, base_e, d, D, rng, trial_end)
        consider(n, e)

    if base_is_gq and D >= 4:
        spare_end = at(0.20)
        while time.monotonic() < spare_end:
            keep = rng.choice((0, 2, 4, 8, 12, 20))
            sn, se = _spare_matching_base(base_n, base_e, d, rng, keep)
            gn, ge = _grow(sn, se, d, D, spare_end, rng)
            consider(gn, ge)

    if D >= 2:
        _lns(state['n'], state['e'], d, D, at(0.85), rng, consider)


def build(d, D, seed, time_limit):
    start = time.monotonic()
    deadline = start + 0.88 * time_limit
    rng = random.Random(seed)

    if D == 1 and d >= 1:
        return 2, [(0, 1)]
    if d < 1 or D < 1:
        return 1, []

    # Safe fallback: K_{d,d}, valid for D >= 2.
    fb_n, fb_e = lib.haar_graph(d, range(d))
    state = {'n': fb_n, 'e': list(fb_e)}

    def consider(n, e):
        if n > state['n'] and lib.is_valid(n, e, d, D):
            state['n'] = n
            state['e'] = list(e)

    # Stage 1: parent's structured search (GQ / PG base, growth, LNS).
    _classic(d, D, rng, start, 0.42 * time_limit, state, consider)

    # Stage 2: new group-lift voltage search, aiming above the current best.
    _lift_stage(d, D, rng, deadline, state, consider)

    if not lib.is_valid(state['n'], state['e'], d, D):
        return fb_n, list(fb_e)
    return state['n'], list(state['e'])
