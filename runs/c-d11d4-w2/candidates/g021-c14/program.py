# Bi-Cayley group choices for the C lift engine.
# ----------------------------------------------------------------------------

def _group_options(G, rng):
    """(M, KK, r) triples with M * KK = G and r^KK = 1 mod M, gcd(r, M) = 1."""
    opts = []
    for KK in range(1, 13):
        if G % KK:
            continue
        M = G // KK
        if M < 2:
            continue
        if KK == 1:
            rs = [1]
        else:
            rs = [r for r in range(1, M)
                  if math.gcd(r, M) == 1 and pow(r, KK, M) == 1 % M]
            if not rs:
                continue
            rng.shuffle(rs)
            rs = rs[:2]
        for r in rs:
            opts.append((M, KK, r))
    rng.shuffle(opts)
    return opts


def build(d, D, seed, time_limit):
    start = time.monotonic()
    tl = float(time_limit)
    rng = random.Random(seed)

    if d >= 1 and D == 1:
        return 2, [(0, 1)]
    if d < 1 or D < 1:
        return 1, []

    # Calibration: D = 3 and d - 1 a prime power gives the Moore-optimal incidence graph.
    if D == 3 and d >= 3 and lib.is_prime_power(d - 1):
        n0, e0 = lib.projective_plane_incidence(d - 1)
        if lib.is_valid(n0, e0, d, D):
            return n0, e0

    # Safe fallback: K_{d,d}, valid for D >= 2.
    best = lib.haar_graph(d, range(d))
    best_n = best[0]

    def consider(n, e):
        nonlocal best, best_n
        if n > best_n and lib.is_valid(n, e, d, D):
            best = (n, e)
            best_n = n

    if D == 3:
        for q in [q for q in range(d - 1, 1, -1) if lib.is_prime_power(q)][:2]:
            pn, pe = lib.projective_plane_incidence(q)
            consider(pn, pe)
        n2, e2 = _pipeline(best[0], best[1], d, D, start + 0.5 * tl, rng)
        consider(n2, e2)

    # Stage 1 (D >= 4): W(q) baseline, saturated, then growth.
    if D >= 4:
        gq = _best_gq(d)
        if gq is not None:
            consider(gq[0], gq[1])
            sat = (gq[0], _saturate_edges(gq[0], gq[1], d, rng))
            consider(sat[0], sat[1])
            first = True
            pipe_end = start + 0.10 * tl
            while time.monotonic() < pipe_end:
                src = gq if first else rng.choice([gq, sat, best])
                first = False
                try:
                    pn, pe = _pipeline(src[0], src[1], d, D, pipe_end, rng)
                    consider(pn, pe)
                except Exception:
                    break

    # Stage 2 (D >= 4, d >= 5): bold bi-Cayley voltage lift search in C.
    if D >= 4 and d >= 5:
        deadline = start + 0.66 * tl
        KBS = (1, 1, 2, 3)
        Gs = {kb: 0 for kb in (1, 2, 3)}
        miss = {kb: 0 for kb in (1, 2, 3)}
        while True:
            remaining = deadline - time.monotonic()
            if remaining < 3.0:
                break
            kb = rng.choice(KBS)
            G = max(Gs[kb], best_n // (2 * kb) + 1)
            if 2 * kb * G > 4000 or G > 3000:
                continue
            opts = _group_options(G, rng)
            if not opts:
                Gs[kb] = G + 1
                continue
            M, KK, r = opts[0]
            budget = min(remaining - 1.5, 12.0)
            if budget < 2.0:
                break
            try:
                out = lib.run_c(BI_SOURCE,
                                [d, D, rng.randrange(1 << 30), f"{budget:.2f}",
                                 kb, M, KK, r],
                                timeout=budget + 3.0)
                n2, e2 = lib.parse_graph_text(out)
            except Exception:
                n2, e2 = 0, []
            if n2 > best_n:
                consider(n2, e2)
                Gs[kb] = G + 1
                miss[kb] = 0
            else:
                miss[kb] += 1
                if miss[kb] >= 2:
                    Gs[kb] = G + 1
                    miss[kb] = 0

    # Stage 3: grow the best valid graph with twins and covers.
    end = start + 0.92 * tl - 1.0
    if time.monotonic() < end - 1.0:
        try:
            pn, pe = _pipeline(best[0], best[1], d, D, end, rng)
            consider(pn, pe)
        except Exception:
            pass

    if not lib.is_valid(best[0], best[1], d, D):
        best = lib.haar_graph(d, range(d))
    return best
