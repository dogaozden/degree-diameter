def build(d, D, seed, time_limit):
    t0 = time.monotonic()
    budget = max(1.0, min(0.85 * time_limit, time_limit - 8.0))
    deadline = t0 + budget
    rng = random.Random(seed)
    nprng = np.random.default_rng(abs(int(seed)) % (2 ** 32))

    if d < 1 or D < 1:
        return 1, []
    if D == 1:
        return 2, [(0, 1)]

    # Safe fallback: K_{d,d}, diameter 2.
    best = lib.haar_graph(d, range(d))

    def consider(n, edges):
        nonlocal best
        if n > best[0] and lib.is_valid(n, edges, d, D):
            best = (n, edges)

    if D == 2:
        return best

    # Projective plane incidence graph: diameter 3.
    if D >= 3:
        try:
            pg = _pg(d)
            if pg is not None:
                consider(*pg)
        except Exception:
            pass

    # Generalized quadrangle W(d-1): degree d, diameter 4.
    if D >= 4 and 2 <= d - 1 <= 11 and lib.is_prime_power(d - 1):
        try:
            consider(*_gq(d - 1))
        except Exception:
            pass

    # Blow-up of a base of degree d-1 (q = d-2 prime power), then extension.
    q = d - 2
    if 2 <= q <= 11 and lib.is_prime_power(q) and time.monotonic() < deadline - 2.0:
        base = None
        if D >= 4:
            base = _gq(q)
        elif D == 3:
            base = lib.projective_plane_incidence(q)
        if base is not None:
            try:
                n0, e0 = base
                res = _blowup(n0, e0, d, deadline, rng, nprng)
                if res is not None:
                    consider(*res)
                    n1, e1 = res
                    n2, e2 = _extend(n1, e1, d, D - 1, deadline, rng)
                    consider(n2, e2)
            except Exception:
                pass

    if not lib.is_valid(best[0], best[1], d, D):
        best = lib.haar_graph(d, range(d))
    return best
