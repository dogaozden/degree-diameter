# ----------------------------------------------------------------------------
# Generalized quadrangle W(q) as a point/line list (table-based, pure Python).
# ----------------------------------------------------------------------------

def _gq_w(q):
    """Return (P, lines): points of W(q) indexed 0..P-1 and each totally isotropic line as a sorted point list."""
    F = lib.GF(q)
    mul = F.mul_table.tolist()
    add = F.add_table.tolist()
    neg = [next(b for b in range(q) if add[a][b] == 0) for a in range(q)]
    inv = [0] * q
    for a in range(1, q):
        inv[a] = next(b for b in range(1, q) if mul[a][b] == 1)
    pts = [v for v in itertools.product(range(q), repeat=4)
           if any(v) and next(c for c in v if c) == 1]
    index = {v: i for i, v in enumerate(pts)}
    P = len(pts)

    def norm(v):
        c = next(x for x in v if x)
        ic = inv[c]
        return tuple(mul[ic][x] for x in v)

    def form(x, y):
        t = add[mul[x[0]][y[1]]][neg[mul[x[1]][y[0]]]]
        u = add[mul[x[2]][y[3]]][neg[mul[x[3]][y[2]]]]
        return add[t][u]

    covered = set()
    lines = []
    for i in range(P):
        x = pts[i]
        for j in range(i + 1, P):
            if (i * P + j) in covered:
                continue
            y = pts[j]
            if form(x, y):
                continue
            Lset = set()
            for a in range(q):
                for b in range(q):
                    if a == 0 and b == 0:
                        continue
                    v = tuple(add[mul[a][x[k]]][mul[b][y[k]]] for k in range(4))
                    if any(v):
                        Lset.add(index[norm(v)])
            Ls = sorted(Lset)
            lines.append(Ls)
            for p in Ls:
                for r in Ls:
                    if p < r:
                        covered.add(p * P + r)
    return P, lines


def _gq_incidence(q):
    """Incidence graph of W(q): (n, edges), points 0..P-1, lines P..P+L-1; degree q+1, diameter 4."""
    P, lines = _gq_w(q)
    L = len(lines)
    return P + L, [(p, P + j) for j, Ls in enumerate(lines) for p in Ls]


# ----------------------------------------------------------------------------
# Maximum independent set by k-fixed tabu search (pure Python).
# ----------------------------------------------------------------------------

def _mis(n, adj, deadline, rng):
    """Return a large independent set of the graph (n vertices, adj neighbour lists) found before deadline."""
    inS = [False] * n
    c = [0] * n
    S = []

    def add(v):
        inS[v] = True
        S.append(v)
        for w in adj[v]:
            c[w] += 1

    def remove(u):
        inS[u] = False
        S.remove(u)
        for w in adj[u]:
            c[w] -= 1

    order = list(range(n))
    rng.shuffle(order)
    for v in order:
        if c[v] == 0:
            add(v)
    best = list(S)
    tab_add = [0] * n
    tab_rem = [0] * n
    it = 0
    stuck = 0
    while time.monotonic() < deadline:
        it += 1
        cost = sum(c[v] for v in S)
        if cost == 0:
            if len(S) > len(best):
                best = list(S)
                stuck = 0
            cands = [v for v in range(n) if not inS[v] and tab_add[v] <= it] \
                or [v for v in range(n) if not inS[v]]
            if not cands:
                break
            mn = min(c[v] for v in cands)
            add(rng.choice([v for v in cands if c[v] == mn]))
            continue
        stuck += 1
        if stuck > 3000:
            for v in list(S):
                remove(v)
            for v in best:
                add(v)
            stuck = 0
            continue
        ok = [u for u in S if tab_rem[u] <= it] or list(S)
        mx = max(c[u] for u in ok)
        u = rng.choice([x for x in ok if c[x] == mx])
        remove(u)
        tab_add[u] = it + rng.randint(5, 15)
        cands = [v for v in range(n) if not inS[v] and tab_add[v] <= it] \
            or [v for v in range(n) if not inS[v]]
        mn = min(c[v] for v in cands)
        v = rng.choice([x for x in cands if c[x] == mn])
        add(v)
        tab_rem[v] = it + rng.randint(5, 15)
    return best


# ----------------------------------------------------------------------------
# NEW (bold): Haar-type group lifts of the 2-vertex base with d parallel darts.
#
# Vertices a_x, b_y (x, y in G, |G| = N). Edge a_x -- b_{x*s} for s in S,
# |S| = d. This is bipartite, d-regular, and both sides are transitive under
# left translation, so diameter <= D is equivalent to a BFS from a_e and from
# b_e reaching all 2N vertices within D steps. We hill-climb on S to minimise
# the number of unreached vertices, over cyclic and semidirect groups of order N.
# ----------------------------------------------------------------------------

def _uncovered(T, S, Sinv, N, D):
    """Total number of (source, vertex) pairs unreached within D steps from a_e and from b_e."""
    total = 0
    for src in (0, N):
        seen = bytearray(2 * N)
        seen[src] = 1
        frontier = [src]
        for _ in range(D):
            nxt = []
            for v in frontier:
                if v < N:
                    row = T[v]
                    for s in S:
                        w = N + row[s]
                        if not seen[w]:
                            seen[w] = 1
                            nxt.append(w)
                else:
                    row = T[v - N]
                    for t in Sinv:
                        w = row[t]
                        if not seen[w]:
                            seen[w] = 1
                            nxt.append(w)
            frontier = nxt
            if not frontier:
                break
        total += 2 * N - seen.count(1)
    return total


def _haar_search(N, T, inv, d, D, deadline, rng):
    """Hill-climb a connection set S of size d in the group; return S with diameter <= D, or None."""
    S = rng.sample(range(N), d)
    Sinv = [inv[s] for s in S]
    cur = _uncovered(T, S, Sinv, N, D)
    while cur > 0:
        if time.monotonic() > deadline:
            return None
        i = rng.randrange(d)
        x = rng.randrange(N)
        if x in S:
            continue
        S2 = S[:]
        S2[i] = x
        Sinv2 = Sinv[:]
        Sinv2[i] = inv[x]
        val = _uncovered(T, S2, Sinv2, N, D)
        if val <= cur or rng.random() < 0.02:
            S, Sinv, cur = S2, Sinv2, val
    return S


def _group_options(N, rng):
    """Candidate groups of order N: the cyclic group plus up to two semidirect products."""
    opts = [("c", N, 0, 0)]
    ks = [k for k in range(2, N) if N % k == 0 and N // k >= 2]
    rng.shuffle(ks)
    picked = 0
    for k in ks:
        if picked >= 2:
            break
        m = N // k
        rs = [r for r in range(1, m) if math.gcd(r, m) == 1 and pow(r, k, m) == 1 % m]
        if rs:
            opts.append(("s", m, k, rng.choice(rs)))
            picked += 1
    return opts


def _build_group(opt, N):
    """Return (T, inv, mul) for the group option, with T[x][y] = x*y and inv[x] = x^{-1}."""
    if opt[0] == "c":
        T = [[(x + y) % N for y in range(N)] for x in range(N)]
        inv = [(-x) % N for x in range(N)]

        def mul(x, y):
            return (x + y) % N
        return T, inv, mul
    _, m, k, r = opt
    order, mulf, invf = lib.semidirect_group(m, k, r)
    T = [[mulf(x, y) for y in range(order)] for x in range(order)]
    inv = [invf(x) for x in range(order)]
    return T, inv, mulf


def _haar_phase(d, D, deadline, rng, consider):
    """Search Haar-type group lifts over increasing orders N, passing any valid graph to consider()."""
    moore = lib.moore_bound(d, D)
    n_hi = moore // 2
    N = max(d + 1, (moore // 2) * 4 // 5)
    slice_s = 1.0
    while N <= n_hi and time.monotonic() < deadline:
        for opt in _group_options(N, rng):
            if time.monotonic() >= deadline:
                return
            T, inv, mul = _build_group(opt, N)
            end = min(deadline, time.monotonic() + slice_s)
            S = _haar_search(N, T, inv, d, D, end, rng)
            if S is not None:
                n, edges = lib.group_lift(2, [(0, 1, s) for s in S], N, mul)
                consider(n, edges)
                break
        N += 1


# ----------------------------------------------------------------------------
# Twin construction on W(q), degree q+2 (for d = q+2, D = 4).
# ----------------------------------------------------------------------------

def _twin_graph(q, deadline, rng):
    P, lines = _gq_w(q)
    L = len(lines)
    pl = [[] for _ in range(P)]
    for j, Ls in enumerate(lines):
        for p in Ls:
            pl[p].append(j)
    padj = [set() for _ in range(P)]
    for Ls in lines:
        for p in Ls:
            for r in Ls:
                if p != r:
                    padj[p].add(r)
    ladj = [set() for _ in range(L)]
    for p in range(P):
        for a in pl[p]:
            for b in pl[p]:
                if a != b:
                    ladj[a].add(b)

    now = time.monotonic()
    mid = now + (deadline - now) / 2.0
    I = _mis(P, [sorted(s) for s in padj], mid, rng)
    J = _mis(L, [sorted(s) for s in ladj], deadline, rng)

    edges = [(p, P + j) for j, Ls in enumerate(lines) for p in Ls]
    n = P + L
    for p in I:
        for j in pl[p]:
            edges.append((n, P + j))
        n += 1
    for j in J:
        for p in lines[j]:
            edges.append((p, n))
        n += 1
    return n, edges


