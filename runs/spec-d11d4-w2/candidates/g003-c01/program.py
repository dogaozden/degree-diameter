def build(d, D, seed, time_limit):
    t0 = time.monotonic()
    budget = max(1.0, 0.8 * time_limit - 4.0)
    deadline = t0 + budget
    rng = random.Random(seed)
    nprng = np.random.default_rng(abs(int(seed)) % (2 ** 32))

    if d < 1 or D < 1:
        return 1, []
    if D == 1:
        return 2, [(0, 1)]

    # Safe fallback: K_{d,d} has diameter 2.
    best = lib.haar_graph(d, range(d))

    def consider(n, edges):
        nonlocal best
        if n > best[0] and lib.is_valid(n, edges, d, D):
            best = (n, edges)

    if D == 2:
        return best

    # Projective plane incidence graph: degree d, diameter 3.
    if D >= 3 and lib.is_prime_power(d - 1):
        try:
            consider(*lib.projective_plane_incidence(d - 1))
        except Exception:
            pass

    # Generalized quadrangle W(d-1): degree d, diameter 4.
    if D >= 4 and lib.is_prime_power(d - 1) and 2 <= d - 1 <= 11:
        try:
            consider(*_gq(d - 1))
        except Exception:
            pass

    # Twin blow-up of a base of degree d-1 (q = d-2 prime power), then greedy extension.
    q = d - 2
    if 2 <= q <= 11 and lib.is_prime_power(q) and time.monotonic() < deadline - 2.0:
        try:
            if D >= 4:
                n0, e0 = _gq(q)
            else:
                n0, e0 = lib.projective_plane_incidence(q)
            consider(n0, e0)
            now = time.monotonic()
            tw_deadline = now + 0.4 * max(0.0, deadline - now)
            res = _twin(n0, e0, d, tw_deadline, rng, nprng)
            if res is not None:
                n2, e2 = res
                consider(n2, e2)
            else:
                n2, e2 = n0, e0
            n3, e3 = _extend(n2, e2, d, D, deadline, rng)
            consider(n3, e3)
        except Exception:
            pass

    if not lib.is_valid(best[0], best[1], d, D):
        best = lib.haar_graph(d, range(d))
    return best
