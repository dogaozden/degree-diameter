"""Two-family search for the bipartite degree-diameter problem.

Family A: affine-group Haar graphs (L_g ~ R_{g s}, s in S), searched by simulated annealing.
Family B (new): multi-orbit lifts. Take a base bipartite graph with B left and B right
vertices, each of degree d (the darts are a sum of d permutation matrices). Give each dart a
group element g in the affine group G = F_q x| H. The lift has vertices L_{i,x} and R_{j,y}
for x, y in G, with edges L_{i,x} ~ R_{j,x*g}. Left multiplication is an automorphism, so the
diameter check needs only 2B BFS runs, one from each class representative. Every candidate is
checked with lib.is_valid before it is returned, and the C output is re-verified before printing.
"""
