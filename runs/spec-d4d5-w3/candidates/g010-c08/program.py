import itertools
import math
import random
import time

import lib


# ----------------------------------------------------------------------------
# Projective plane, generalized quadrangle and arc-extended bases.
# ----------------------------------------------------------------------------

def _best_pg(d):
    """Incidence graph of PG(2, q) for the largest prime power q with q + 1 <= d."""
    for q in range(d - 1, 1, -1):
        if lib.is_prime_power(q):
            return lib.projective_plane_incidence(q)
    return None


def _gq_w(q):
    """Incidence graph of points and lines of the generalized quadrangle W(q); diameter 4."""
    F = lib.GF(q)
    pts = [v for v in itertools.product(range(q), repeat=4)
           if any(v) and next(c for c in v if c) == 1]
    index = {v: i for i, v in enumerate(pts)}
    P = len(pts)

    def norm(v):
        c = next(x for x in v if x)
        inv = F.inv(c)
        return tuple(F.mul(inv, x) for x in v)

    def form(x, y):
        t = F.sub(F.mul(x[0], y[1]), F.mul(x[1], y[0]))
        return F.add(t, F.sub(F.mul(x[2], y[3]), F.mul(x[3], y[2])))

    covered = set()
    lines = []
    for i in range(P):
        x = pts[i]
        for j in range(i + 1, P):
            if (i, j) in covered:
                continue
            y = pts[j]
            if form(x, y) != 0:
                continue
            L = set()
            for a in range(q):
                for b in range(q):
                    if a == 0 and b == 0:
                        continue
                    v = tuple(F.add(F.mul(a, x[k]), F.mul(b, y[k])) for k in range(4))
                    if any(v):
                        L.add(index[norm(v)])
            L = sorted(L)
            lines.append(L)
            for p in L:
                for r in L:
                    if p < r:
                        covered.add((p, r))

    edges = []
    for j, L in enumerate(lines):
        for p in L:
            edges.append((p, P + j))
    return 2 * P, edges


def _best_gq(d):
    """W(q) for the largest prime power q with q + 1 <= d, restricted to small q for speed."""
    for q in range(min(d - 1, 9), 1, -1):
        if lib.is_prime_power(q):
            return _gq_w(q)
    return None


def _pg_data(q):
    """Return (m, edges, point_lines, line_points, index, pts) for PG(2, q)."""
    pts = lib.projective_points(q)
    n2, edges = lib.projective_plane_incidence(q)
    m = n2 // 2
    point_lines = [[] for _ in range(m)]
    line_points = [[] for _ in range(m)]
    for u, v in edges:
        point_lines[u].append(v - m)
        line_points[v - m].append(u)
    index = {p: i for i, p in enumerate(pts)}
    return m, edges, point_lines, line_points, index, pts


def _loads_ok(S, s, m, point_lines, line_points):
    """True if every line holds <= s points of S and every point lies on <= s lines indexed by S."""
    cl = [0] * m
    cp = [0] * m
    for P in S:
        for L in point_lines[P]:
            cl[L] += 1
        for Q in line_points[P]:
            cp[Q] += 1
    return max(cl, default=0) <= s and max(cp, default=0) <= s


def _greedy_arc(m, s, point_lines, line_points, rng, trials, deadline):
    """Randomized greedy choice of S with all loads <= s; returns the largest found."""
    best = []
    order = list(range(m))
    for _ in range(trials):
        if time.monotonic() > deadline:
            break
        rng.shuffle(order)
        cl = [0] * m
        cp = [0] * m
        S = []
        for P in order:
            if all(cl[L] < s for L in point_lines[P]) and all(cp[Q] < s for Q in line_points[P]):
                S.append(P)
                for L in point_lines[P]:
                    cl[L] += 1
                for Q in line_points[P]:
                    cp[Q] += 1
        if len(S) > len(best):
            best = S
    return best


def _local_improve(m, s, point_lines, line_points, S, rng, deadline, iters):
    """Plateau-walking 1-swap local search that grows a feasible load-bounded set S."""
    cl = [0] * m
    cp = [0] * m
    inS = [False] * m

    def add(P):
        inS[P] = True
        for L in point_lines[P]:
            cl[L] += 1
        for Q in line_points[P]:
            cp[Q] += 1

    def rem(P):
        inS[P] = False
        for L in point_lines[P]:
            cl[L] -= 1
        for Q in line_points[P]:
            cp[Q] -= 1

    def fits(P):
        return (all(cl[L] < s for L in point_lines[P])
                and all(cp[Q] < s for Q in line_points[P]))

    cur = list(S)
    for P in cur:
        add(P)
    best = list(cur)
    for it in range(iters):
        if (it & 63) == 0 and time.monotonic() > deadline:
            break
        P = rng.randrange(m)
        if inS[P]:
            continue
        if fits(P):
            add(P)
            cur.append(P)
            if len(cur) > len(best):
                best = list(cur)
            continue
        if not cur:
            continue
        idx = rng.randrange(len(cur))
        R = cur[idx]
        rem(R)
        if fits(P):
            add(P)
            cur[idx] = P
        else:
            add(R)
    return best


def _conic_set(q, index, F):
    """Conic (plus nucleus for even q) as a point-index set: an arc with no three collinear."""
    S = [index[(1, t, F.mul(t, t))] for t in range(q)]
    S.append(index[(0, 0, 1)])
    if q % 2 == 0:
        S.append(index[(0, 1, 0)])
    return S


def _arc_graph(m, edges, point_lines, line_points, S):
    """Old PG incidence plus a new A and a new B vertex per element of S."""
    k = len(S)
    n = 2 * m + 2 * k
    E = list(edges)
    for t, P in enumerate(S):
        x = 2 * m + t
        for L in point_lines[P]:
            E.append((x, m + L))
    for t, j in enumerate(S):
        b = 2 * m + k + t
        for Q in line_points[j]:
            E.append((Q, b))
    return n, E


def _arc_extensions(d, deadline, rng):
    """Return a list of (n, edges) candidates, one per prime power q with q + 1 <= d."""
    out = []
    for q in range(2, min(d - 1, 23) + 1):
        if not lib.is_prime_power(q):
            continue
        if time.monotonic() > deadline:
            break
        s = d - q - 1
        m, edges, point_lines, line_points, index, pts = _pg_data(q)
        cands = []
        if s >= 1:
            g = _greedy_arc(m, s, point_lines, line_points, rng, 40, deadline)
            g = _local_improve(m, s, point_lines, line_points, g, rng, deadline, 3000)
            cands.append(g)
        if s >= 2:
            F = lib.GF(q)
            cs = _conic_set(q, index, F)
            if _loads_ok(cs, s, m, point_lines, line_points):
                cands.append(cs)
        S = max(cands, key=len, default=[])
        if not S or not _loads_ok(S, s, m, point_lines, line_points):
            continue
        out.append(_arc_graph(m, edges, point_lines, line_points, S))
    return out


# ----------------------------------------------------------------------------
# Bipartite utilities and unstructured repair search (main family for D >= 3).
# ----------------------------------------------------------------------------

def _bipartition(n, adj):
    """Two-colouring of a bipartite graph given by adjacency lists."""
    color = [-1] * n
    for s in range(n):
        if color[s] != -1:
            continue
        color[s] = 0
        stack = [s]
        while stack:
            u = stack.pop()
            for v in adj[u]:
                if color[v] == -1:
                    color[v] = 1 - color[u]
                    stack.append(v)
    return color


def _bad_adj(n, adj, D):
    """Number of unordered vertex pairs at distance > D (adj: sequences of neighbour sets/lists)."""
    reach = [1 << v for v in range(n)]
    for _ in range(D):
        new = [0] * n
        for v in range(n):
            r = reach[v]
            for u in adj[v]:
                r |= reach[u]
            new[v] = r
        reach = new
    return sum(n - r.bit_count() for r in reach) // 2


def _repair(n, edges, d, D, color, deadline, rng):
    """Simulated annealing on a bipartite graph with max degree d.

    Moves: degree-preserving 2-switches, and endpoint shifts onto deficient vertices.
    Adding an edge never increases distances, so deficient pairs are filled greedily.
    Returns the edge list (a, b) with zero bad pairs, or None if the deadline passes.
    """
    adj = [set() for _ in range(n)]
    L = []
    for u, v in edges:
        a, b = (u, v) if color[u] == 0 else (v, u)
        L.append((a, b))
        adj[a].add(b)
        adj[b].add(a)
    A = [v for v in range(n) if color[v] == 0]
    B = [v for v in range(n) if color[v] == 1]

    def fill():
        cand = [(a, b) for a in A if len(adj[a]) < d for b in B
                if len(adj[b]) < d and b not in adj[a]]
        rng.shuffle(cand)
        for a, b in cand:
            if len(adj[a]) < d and len(adj[b]) < d and b not in adj[a]:
                adj[a].add(b)
                adj[b].add(a)
                L.append((a, b))

    def swap(old, new):
        for a, b in old:
            adj[a].discard(b)
            adj[b].discard(a)
        for a, b in new:
            adj[a].add(b)
            adj[b].add(a)

    fill()
    cost = _bad_adj(n, adj, D)
    t0 = time.monotonic()
    span = max(1e-3, deadline - t0)
    T0, Te = 1.5, 0.05
    while cost > 0:
        now = time.monotonic()
        if now >= deadline or not L:
            break
        T = T0 * (Te / T0) ** min(1.0, (now - t0) / span)
        i = rng.randrange(len(L))
        a1, b1 = L[i]
        r = rng.random()
        if r < 0.6:
            j = rng.randrange(len(L))
            a2, b2 = L[j]
            if a1 == a2 or b1 == b2 or b2 in adj[a1] or b1 in adj[a2]:
                continue
            old = [(a1, b1), (a2, b2)]
            new = [(a1, b2), (a2, b1)]
            idx = [(i, new[0]), (j, new[1])]
        elif r < 0.8:
            defB = [b for b in B if len(adj[b]) < d]
            if not defB:
                continue
            b2 = rng.choice(defB)
            if b2 in adj[a1]:
                continue
            old = [(a1, b1)]
            new = [(a1, b2)]
            idx = [(i, new[0])]
        else:
            defA = [a for a in A if len(adj[a]) < d]
            if not defA:
                continue
            a2 = rng.choice(defA)
            if b1 in adj[a2]:
                continue
            old = [(a1, b1)]
            new = [(a2, b1)]
            idx = [(i, new[0])]
        swap(old, new)
        c2 = _bad_adj(n, adj, D)
        if c2 <= cost or rng.random() < math.exp(-(c2 - cost) / T):
            for k, e in idx:
                L[k] = e
            if c2 < cost:
                fill()
                c2 = _bad_adj(n, adj, D)
            cost = c2
        else:
            swap(new, old)
    if cost == 0:
        return list(L)
    return None


def _grow_search(n, edges, d, D, deadline, rng, consider_fn):
    """Repeatedly add two vertices (one per side) and repair until the deadline."""
    cur_n, cur_e = n, list(edges)
    while True:
        now = time.monotonic()
        if now >= deadline:
            break
        adj = [[] for _ in range(cur_n)]
        for u, v in cur_e:
            adj[u].append(v)
            adj[v].append(u)
        color = _bipartition(cur_n, adj)
        n2 = cur_n + 2
        color2 = color + [0, 1]
        seg = min(deadline, now + max(3.0, 0.4 * (deadline - now)))
        res = _repair(n2, cur_e, d, D, color2, seg, rng)
        if res is not None:
            cur_n, cur_e = n2, res
            consider_fn(cur_n, cur_e)


