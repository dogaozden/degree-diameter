def _gq_w(q):
    """Incidence graph of points and lines of W(q): degree q+1, diameter 4."""
    F = lib.GF(q)
    pts = [v for v in itertools.product(range(q), repeat=4)
           if any(v) and next(c for c in v if c) == 1]
    index = {v: i for i, v in enumerate(pts)}
    P = len(pts)

    def norm(v):
        c = next(x for x in v if x)
        inv = F.inv(c)
        return tuple(F.mul(inv, x) for x in v)

    def form(x, y):
        t = F.sub(F.mul(x[0], y[1]), F.mul(x[1], y[0]))
        return F.add(t, F.sub(F.mul(x[2], y[3]), F.mul(x[3], y[2])))

    covered = set()
    lines = []
    for i in range(P):
        x = pts[i]
        for j in range(i + 1, P):
            if (i, j) in covered:
                continue
            y = pts[j]
            if form(x, y) != 0:
                continue
            L = set()
            for a in range(q):
                for b in range(q):
                    if a == 0 and b == 0:
                        continue
                    v = tuple(F.add(F.mul(a, x[k]), F.mul(b, y[k])) for k in range(4))
                    if any(v):
                        L.add(index[norm(v)])
            L = sorted(L)
            lines.append(L)
            for p in L:
                for r in L:
                    if p < r:
                        covered.add((p, r))

    edges = []
    for j, L in enumerate(lines):
        for p in L:
            edges.append((p, P + j))
    return 2 * P, edges


def _gh_h3():
    """Incidence graph of the split Cayley hexagon H(3): 364 + 364 vertices, degree 4, diameter 6.

    Returns None if no sign convention verifies with lib.is_valid.
    """
    q = 3

    def norm(v):
        c = next(x for x in v if x)
        inv = 1 if c == 1 else 2
        return tuple((x * inv) % q for x in v)

    vecs = itertools.product(range(q), repeat=7)
    pts = sorted({norm(v) for v in vecs if any(v) and
                  (v[0] * v[4] + v[1] * v[5] + v[2] * v[6] - v[3] * v[3]) % q == 0})
    P = len(pts)
    index = {p: i for i, p in enumerate(pts)}

    def bil(x, y):
        return (x[0] * y[4] + x[4] * y[0] + x[1] * y[5] + x[5] * y[1] +
                x[2] * y[6] + x[6] * y[2] + x[3] * y[3]) % q

    def pl(x, y, i, j):
        return (x[i] * y[j] - x[j] * y[i]) % q

    conds = [((1, 2), (3, 4)), ((5, 4), (3, 2)), ((2, 0), (3, 5)),
             ((6, 5), (3, 0)), ((0, 1), (3, 6)), ((4, 6), (3, 1))]
    combos = ((1, 0), (0, 1), (1, 1), (1, 2))
    for s in (1, -1):
        lines = set()
        for i in range(P):
            x = pts[i]
            for j in range(i + 1, P):
                y = pts[j]
                if bil(x, y):
                    continue
                if any((pl(x, y, *a) - s * pl(x, y, *b)) % q for a, b in conds):
                    continue
                L = frozenset(index[norm(tuple((a * x[k] + b * y[k]) % q for k in range(7)))]
                              for a, b in combos)
                lines.add(L)
        if len(lines) != P or any(len(L) != 4 for L in lines):
            continue
        ordered = sorted(lines, key=sorted)
        edges = [(p, P + j) for j, L in enumerate(ordered) for p in L]
        n = P + len(ordered)
        if lib.is_valid(n, edges, 4, 6):
            return n, edges
    return None


def _largest_prime_power_le(x):
    for q in range(x, 1, -1):
        if lib.is_prime_power(q):
            return q
    return None


def known_starts(d, D):
    """Algebraic candidates valid for diameter D (may be empty)."""
    out = []
    if D >= 3 and d - 1 >= 2 and lib.is_prime_power(d - 1):
        out.append(lib.projective_plane_incidence(d - 1))
    if D == 3 and d - 2 >= 3 and lib.is_prime_power(d - 2):
        out.append(lib.araujo_lopez_graph(d - 2))
    if D >= 4:
        q = _largest_prime_power_le(min(d - 1, 9))
        if q is not None and q >= 2:
            out.append(_gq_w(q))
    if d == 4 and D >= 6:
        try:
            gh = _gh_h3()
        except Exception:
            gh = None
        if gh is not None:
            out.append(gh)
    return out


# ------------------------------------------------ permutation groups for the C engine
# Each group is (s, gens): s points, gens a list of permutations (lists of length s).

def _mobius_gens(F, a):
    """Generators of PGL(2,q) type acting on P^1(F_q) = {0..q-1, inf=q}: translation, x -> a x, x -> -1/x."""
    q = F.q
    inf = q
    t = [F.add(x, 1) if x < q else inf for x in range(q + 1)]
    s = [F.mul(a, x) if x < q else inf for x in range(q + 1)]
    r = []
    for x in range(q + 1):
        if x == inf:
            r.append(0)
        elif x == 0:
            r.append(inf)
        else:
            r.append(F.neg(F.inv(x)))
    return [t, s, r]


def _psl2_gens(q):
    """PSL(2,q) on q+1 points (q odd: squares scaling; q even: PSL = PGL)."""
    F = lib.GF(q)
    g = F.primitive_element()
    a = F.mul(g, g) if q % 2 == 1 else g
    return q + 1, _mobius_gens(F, a)


def _pgl2_gens(q):
    """PGL(2,q) on q+1 points."""
    F = lib.GF(q)
    return q + 1, _mobius_gens(F, F.primitive_element())


def _alt_gens(n):
    """A_n for odd n: a 3-cycle and an n-cycle."""
    c3 = [1, 2, 0] + list(range(3, n))
    cn = [(x + 1) % n for x in range(n)]
    return n, [c3, cn]


def _sym_gens(n):
    """S_n: a transposition and an n-cycle."""
    tr = [1, 0] + list(range(2, n))
    cyc = [(x + 1) % n for x in range(n)]
    return n, [tr, cyc]


def _dihedral_gens(n):
    """Dihedral group of order 2n acting on the n vertices of an n-gon."""
    rot = [(x + 1) % n for x in range(n)]
    refl = [(-x) % n for x in range(n)]
    return n, [rot, refl]


def _direct(*specs):
    """Direct product of permutation groups with disjoint supports."""
    total = sum(s for s, _ in specs)
    gens = []
    off = 0
    for s, gs in specs:
        for g in gs:
            perm = list(range(total))
            for x in range(s):
                perm[off + x] = off + g[x]
            gens.append(perm)
        off += s
    return total, gens


def _group_specs(d, D):
    """Ordered list of base groups to try; None means the semidirect-only run."""
    specs = []
    builders = [
        lambda: _psl2_gens(8),                                              # order 504
        lambda: _psl2_gens(7),                                              # order 168, times Z_3
        lambda: _pgl2_gens(5),                                              # order 120, times Z_4
        lambda: _direct(_alt_gens(5), _dihedral_gens(4)),                   # order 480
        lambda: _direct(_sym_gens(4), _dihedral_gens(10)),                  # order 480
    ]
    for b in builders:
        try:
            specs.append(b())
        except Exception:
            pass
    specs.append(None)
    return specs


def build(d, D, seed, time_limit):
    t0 = time.monotonic()
    if d < 1 or D < 1:
        return 1, []
    if d == 1 or D == 1:
        return 2, [(0, 1)]
    if d == 2:
        L = 2 * D
        return L, [(i, (i + 1) % L) for i in range(L)]

    best = lib.haar_graph(d, range(d))  # K_{d,d}: always valid for D >= 2
    for cand in known_starts(d, D):
        n, e = cand
        if n > best[0] and lib.is_valid(n, e, d, D):
            best = (n, e)

    if d > 31 or best[0] >= lib.moore_bound(d, D):
        return best

    # Keep a margin for compilation, startup and output.
    deadline = t0 + 0.9 * time_limit - 2.0
    specs = _group_specs(d, D)
    for i, spec in enumerate(specs):
        left = deadline - time.monotonic()
        if left < 1.0:
            break
        budget = left / (len(specs) - i)
        args = [d, D, seed + i, budget]
        if spec is not None:
            s, gens = spec
            args += [s, len(gens)] + [x for g in gens for x in g]
        try:
            text = lib.run_c(C_SOURCE, args, stdin_graph=best, timeout=budget + 6)
            out = lib.parse_graph_text(text)
            if out[0] > best[0] and lib.is_valid(out[0], out[1], d, D):
                best = out
        except Exception:
            pass
    return best
