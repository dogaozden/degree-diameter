import math
import random
import time

import lib


def _color(n, adj):
    """Two-colour a bipartite graph given as adjacency sets."""
    col = [-1] * n
    for s in range(n):
        if col[s] != -1:
            continue
        col[s] = 0
        stack = [s]
        while stack:
            u = stack.pop()
            for v in adj[u]:
                if col[v] == -1:
                    col[v] = 1 - col[u]
                    stack.append(v)
    return col


def _bad_count(n, adj, D):
    """Ordered count of vertex pairs at distance > D, via bitmask BFS."""
    reach = [1 << v for v in range(n)]
    for _ in range(D):
        new = []
        for v in range(n):
            r = reach[v]
            for u in adj[v]:
                r |= reach[u]
            new.append(r)
        reach = new
    return sum(n - r.bit_count() for r in reach)


def _moore(d, D):
    """Moore-type upper bound on the order of a bipartite graph with max degree d and diameter D."""
    if D == 0 or d == 0:
        return 1
    if d == 1:
        return min(2, D + 1)
    if d == 2:
        return 2 * D
    return 2 * sum((d - 1) ** i for i in range(D))


def _augment(n, edges, d, D, rng, deadline, T=1.0):
    """Add two vertices P (colour 1) and L (colour 0) by degree-preserving switches.

    A matching of d edges (a_i, b_i) is replaced by (a_i, P) and (b_i, L), so every
    old vertex keeps its degree and P, L get degree d. Then anneal with 2-switches
    that keep degrees and bipartiteness, minimising pairs at distance > D.
    Returns (n + 2, edges) with diameter <= D, or None if the search fails by the deadline.
    """
    adj = [set() for _ in range(n)]
    for u, v in edges:
        adj[u].add(v)
        adj[v].add(u)
    col = _color(n, adj)

    P, L = n, n + 1
    adj.append(set())
    adj.append(set())
    N = n + 2

    oriented = [((u, v) if col[u] == 0 else (v, u)) for u, v in edges]  # (colour0, colour1)
    rng.shuffle(oriented)
    used, pick = set(), []
    for idx, (a, b) in enumerate(oriented):
        if a not in used and b not in used:
            pick.append(idx)
            used.add(a)
            used.add(b)
            if len(pick) == d:
                break
    if len(pick) < d:
        return None

    picked = set(pick)
    E = [oriented[i] for i in range(len(oriented)) if i not in picked]
    for idx in pick:
        a, b = oriented[idx]
        adj[a].discard(b)
        adj[b].discard(a)
        adj[a].add(P)
        adj[P].add(a)
        adj[b].add(L)
        adj[L].add(b)
        E.append((a, P))
        E.append((L, b))

    M = len(E)
    cur = _bad_count(N, adj, D)
    while cur > 0:
        if time.monotonic() >= deadline:
            return None
        i = rng.randrange(M)
        j = rng.randrange(M)
        if i == j:
            continue
        a, b = E[i]
        c, e = E[j]
        if a == c or b == e or e in adj[a] or b in adj[c]:
            continue
        # 2-switch: (a,b),(c,e) -> (a,e),(c,b); orientation (colour0, colour1) is preserved.
        adj[a].discard(b); adj[b].discard(a)
        adj[c].discard(e); adj[e].discard(c)
        adj[a].add(e); adj[e].add(a)
        adj[c].add(b); adj[b].add(c)
        new = _bad_count(N, adj, D)
        if new <= cur or rng.random() < math.exp((cur - new) / T):
            cur = new
            E[i] = (a, e)
            E[j] = (c, b)
        else:
            adj[a].discard(e); adj[e].discard(a)
            adj[c].discard(b); adj[b].discard(c)
            adj[a].add(b); adj[b].add(a)
            adj[c].add(e); adj[e].add(c)
    return N, list(E)


def _base_d3(d):
    """Best structured diameter-3 base for degree d, or None."""
    if lib.is_prime_power(d - 1):
        # Moore-optimal: PG(2, d-1) incidence graph.
        return lib.projective_plane_incidence(d - 1)
    if d - 2 >= 3 and lib.is_prime_power(d - 2):
        # Araujo-Pardo & Lopez record family: order 2(q^2+q+5), degree q+2 = d.
        try:
            return lib.araujo_lopez_graph(d - 2)
        except (ValueError, StopIteration, KeyError):
            pass
    for q in range(d - 1, 1, -1):
        if lib.is_prime_power(q):
            return lib.projective_plane_incidence(q)
    return None


def build(d, D, seed, time_limit):
    start = time.monotonic()
    deadline = start + 0.8 * time_limit
    rng = random.Random(seed)

    if d < 1 or D < 1:
        return 1, []
    if D == 1:
        return 2, [(0, 1)]

    # K_{d,d} has diameter 2, bipartite, degree d: safe fallback for any D >= 2.
    best = lib.haar_graph(d, range(d))
    if D != 3:
        return best

    base = _base_d3(d)
    if base is not None and base[0] > best[0] and lib.is_valid(base[0], base[1], d, D):
        best = base

    cur = best
    mb = _moore(d, D)
    while time.monotonic() < deadline and cur[0] + 2 <= mb:
        sub = min(deadline, time.monotonic() + max(2.0, 0.2 * time_limit))
        res = _augment(cur[0], cur[1], d, D, rng, sub)
        if res is not None and lib.is_valid(res[0], res[1], d, D):
            cur = res
            best = res
    return best
