def _araujo(d):
    """Araujo-Pardo & Lopez record graph (degree q+2) when q = d-2 is a prime power >= 3."""
    q = d - 2
    if q < 3 or not lib.is_prime_power(q):
        return None
    try:
        return lib.araujo_lopez_graph(q)
    except (ValueError, AssertionError):
        return None


# ----------------------------------------------------------------------------
# Bipartition helper.
# ----------------------------------------------------------------------------

def _bipartition(n, adj):
    """Two-colouring of a bipartite graph given by adjacency lists."""
    color = [-1] * n
    for s in range(n):
        if color[s] != -1:
            continue
        color[s] = 0
        stack = [s]
        while stack:
            u = stack.pop()
            for v in adj[u]:
                if color[v] == -1:
                    color[v] = 1 - color[u]
                    stack.append(v)
    return color


# ----------------------------------------------------------------------------
# NEW: two-vertex switch insertion for diameter-3 bipartite graphs.
#
# Given a valid graph with all degrees <= d, add two new vertices x (side c)
# and y (side 1-c) with a degree-preserving rewiring:
#   * x is joined to d distinct opposite-side vertices S;
#   * every b in S that is already saturated (degree d) first loses one edge
#     (a, b) to a same-side partner a; partners are distinct;
#   * y is joined to all partners.
# Every existing vertex keeps degree <= d. The move is kept only if the new
# graph still has diameter <= D (checked with lib.bad_pairs). Accepted moves
# grow the graph by 2 vertices, so the search walks upward in order.
# ----------------------------------------------------------------------------

def _insert_trial(n, E, color, d, D, rng):
    """One random switch insertion. Returns (n2, E2, color2) if valid, else None."""
    adj = [[] for _ in range(n)]
    for u, v in E:
        adj[u].append(v)
        adj[v].append(u)
    c = rng.randrange(2)
    opp = 1 - c
    opp_vs = [v for v in range(n) if color[v] == opp]
    if len(opp_vs) < d:
        return None
    S = rng.sample(opp_vs, d)
    removed = set()
    partners = []
    used = set()
    for b in S:
        if len(adj[b]) < d:
            continue
        opts = [a for a in adj[b] if color[a] == c and a not in used]
        if not opts:
            return None
        a = rng.choice(opts)
        used.add(a)
        partners.append(a)
        removed.add((min(a, b), max(a, b)))
    if not partners:
        return None
    x, y = n, n + 1
    E2 = [e for e in E if e not in removed]
    for b in S:
        E2.append((min(x, b), max(x, b)))
    for a in partners:
        E2.append((min(y, a), max(y, a)))
    n2 = n + 2
    if lib.bad_pairs(n2, E2, D) != 0:
        return None
    return n2, E2, color + [c, opp]


def _switch_search(n, E, d, D, deadline, rng):
    """Repeatedly apply successful switch insertions; return the largest valid (n, E)."""
    color = _bipartition(n, _adj_from(n, E))
    cur = (n, E, color)
    best = (n, E)
    while time.monotonic() < deadline:
        r = _insert_trial(cur[0], cur[1], cur[2], d, D, rng)
        if r is not None:
            cur = r
            if cur[0] > best[0]:
                best = (cur[0], cur[1])
    return best


def _adj_from(n, E):
    adj = [[] for _ in range(n)]
    for u, v in E:
        adj[u].append(v)
        adj[v].append(u)
    return adj


