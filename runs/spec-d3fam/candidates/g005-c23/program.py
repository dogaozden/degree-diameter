# ----------------------------------------------------------------------------
# Projective plane base and cover-based growth (general D >= 3).
# ----------------------------------------------------------------------------

def _best_pg(d):
    """Incidence graph of PG(2, q) for the largest prime power q with q + 1 <= d."""
    for q in range(d - 1, 1, -1):
        if lib.is_prime_power(q):
            return lib.projective_plane_incidence(q)
    return None


def _balls_radius(n, adj, r):
    """Bitmask per vertex of all vertices within distance r."""
    ball = [1 << v for v in range(n)]
    for _ in range(r):
        new = []
        for v in range(n):
            x = ball[v]
            for u in adj[v]:
                x |= ball[u]
            new.append(x)
        ball = new
    return ball


def _bipartition(n, adj):
    """Two-colouring of a bipartite graph given by adjacency collections."""
    color = [-1] * n
    for s in range(n):
        if color[s] != -1:
            continue
        color[s] = 0
        stack = [s]
        while stack:
            u = stack.pop()
            for v in adj[u]:
                if color[v] == -1:
                    color[v] = 1 - color[u]
                    stack.append(v)
    return color


def _greedy_cover(cands, ball, full, d, rng, randomize):
    """Greedy set cover of `full` by at most d candidate vertices; None if it fails."""
    pool = list(cands)
    if randomize:
        rng.shuffle(pool)
    covered = 0
    chosen = []
    while covered != full and len(chosen) < d and pool:
        gains = [(ball[s] & ~covered).bit_count() for s in pool]
        best_g = max(gains, default=0)
        if best_g == 0:
            break
        thr = best_g
        if randomize and rng.random() < 0.5:
            thr = best_g - 1
        opts = [i for i, g in enumerate(gains) if g >= thr and g > 0]
        i = rng.choice(opts) if randomize else opts[0]
        s = pool.pop(i)
        chosen.append(s)
        covered |= ball[s]
    return chosen if covered == full else None


def _extend_cover(n, edges, d, D, deadline, rng):
    """Greedily add vertices whose neighbourhoods cover all vertices within D-1 of the graph."""
    if D < 2:
        return n, edges
    edges = list(edges)
    adj = [[] for _ in range(n)]
    for u, v in edges:
        adj[u].append(v)
        adj[v].append(u)
    deg = [len(a) for a in adj]
    color = _bipartition(n, adj)

    while time.monotonic() < deadline:
        ball = _balls_radius(n, adj, D - 1)
        full = (1 << n) - 1
        added = False
        for c in (0, 1):
            cands = [s for s in range(n) if color[s] == c and deg[s] < d]
            if not cands:
                continue
            chosen = None
            for attempt in range(200):
                if time.monotonic() >= deadline:
                    break
                chosen = _greedy_cover(cands, ball, full, d, rng, attempt > 0)
                if chosen:
                    break
            if chosen:
                v = n
                n += 1
                color.append(1 - c)
                adj.append([])
                deg.append(0)
                for s in chosen:
                    edges.append((s, v))
                    adj[s].append(v)
                    adj[v].append(s)
                    deg[s] += 1
                    deg[v] += 1
                added = True
                break
        if not added:
            break
    return n, edges


def _saturate_edges(n, edges, d, rng):
    """Greedily join deficient opposite-side vertices in random order."""
    edges = list(edges)
    adj = [[] for _ in range(n)]
    existing = set()
    for u, v in edges:
        adj[u].append(v)
        adj[v].append(u)
        existing.add((min(u, v), max(u, v)))
    deg = [len(a) for a in adj]
    color = _bipartition(n, adj)
    left = [v for v in range(n) if color[v] == 0 and deg[v] < d]
    right = [v for v in range(n) if color[v] == 1 and deg[v] < d]
    pairs = [(a, b) for a in left for b in right
             if (min(a, b), max(a, b)) not in existing]
    rng.shuffle(pairs)
    for a, b in pairs:
        if deg[a] < d and deg[b] < d:
            edges.append((a, b))
            deg[a] += 1
            deg[b] += 1
    return edges


def _grow(n, edges, d, D, deadline, rng):
    """Extend by cover vertices first, then saturate edges with the leftover spare degree."""
    cur_n, cur_e = n, list(edges)
    for _ in range(8):
        if time.monotonic() >= deadline:
            break
        n2, e2 = _extend_cover(cur_n, cur_e, d, D, deadline, rng)
        grew = n2 != cur_n
        cur_n = n2
        cur_e = _saturate_edges(cur_n, e2, d, rng)
        if not grew:
            break
    return cur_n, cur_e


# ----------------------------------------------------------------------------
# NEW: diameter-3 annealed vertex growth with degree-preserving rewiring.
#
# Starting from a valid bipartite graph, repeatedly attach one new vertex on a
# chosen side to up to d opposite-side vertices (stealing one edge from any
# saturated neighbour). The defect is then repaired by annealing over two
# moves: adding an edge between two spare-degree opposite vertices, and a
# degree-preserving double-edge swap (a-b, c-e -> a-e, c-b). The cost is the
# number of ordered vertex pairs at distance > D. A step is kept only when the
# cost reaches zero, so every stored state is a valid graph.
# ----------------------------------------------------------------------------

def _bad_count(n, adj, D):
    """Number of ordered vertex pairs at distance > D (unreachable pairs included)."""
    reach = [1 << v for v in range(n)]
    for _ in range(D):
        new = []
        for v in range(n):
            r = reach[v]
            for u in adj[v]:
                r |= reach[u]
            new.append(r)
        reach = new
    return sum(n - r.bit_count() for r in reach)


def _rewire(adj, a, b, c2, e):
    """Replace edges a-b and c2-e by a-e and c2-b (a, c2 on one side; b, e on the other)."""
    adj[a].discard(b)
    adj[b].discard(a)
    adj[c2].discard(e)
    adj[e].discard(c2)
    adj[a].add(e)
    adj[e].add(a)
    adj[c2].add(b)
    adj[b].add(c2)


def _anneal_grow(n, edges, d, D, deadline, rng, iters=800, max_fail=3):
    """Grow a valid diameter-D bipartite graph one vertex at a time by annealed repair."""
    adj = [set() for _ in range(n)]
    for u, v in edges:
        adj[u].add(v)
        adj[v].add(u)
    color = _bipartition(n, adj)
    E = [(u, v) if color[u] == 0 else (v, u) for u, v in edges]
    best_n, best_e = n, list(E)
    fails = 0

    while fails < max_fail and time.monotonic() < deadline:
        snap_adj = [set(s) for s in adj]
        snap_color = list(color)
        snap_E = list(E)
        n_old = n

        # Attach a new vertex v on a random side.
        c = rng.randrange(2)
        v = n
        n += 1
        color.append(c)
        adj.append(set())
        targets = [u for u in range(v) if color[u] != c]
        rng.shuffle(targets)
        targets.sort(key=lambda u: len(adj[u]) >= d)  # spare vertices first
        for u in targets[:d]:
            if len(adj[u]) >= d:
                w = rng.choice(list(adj[u]))
                adj[u].discard(w)
                adj[w].discard(u)
                a, b = (u, w) if color[u] == 0 else (w, u)
                E.remove((a, b))
            adj[u].add(v)
            adj[v].add(u)
            E.append((v, u) if c == 0 else (u, v))

        # Anneal the defect away.
        cost = _bad_count(n, adj, D)
        it = 0
        while cost and it < iters:
            if (it & 15) == 0 and time.monotonic() > deadline:
                break
            it += 1
            T = max(0.2, 2.0 * (1.0 - it / iters))
            if rng.random() < 0.4:
                # Spare-degree edge addition.
                A_sp = [x for x in range(n) if color[x] == 0 and len(adj[x]) < d]
                B_sp = [x for x in range(n) if color[x] == 1 and len(adj[x]) < d]
                if not A_sp or not B_sp:
                    continue
                a = rng.choice(A_sp)
                b = rng.choice(B_sp)
                if b in adj[a]:
                    continue
                adj[a].add(b)
                adj[b].add(a)
                E.append((a, b))
                new = _bad_count(n, adj, D)
                if new <= cost or rng.random() < math.exp(-(new - cost) / T):
                    cost = new
                else:
                    adj[a].discard(b)
                    adj[b].discard(a)
                    E.pop()
            else:
                # Degree-preserving double-edge swap.
                if len(E) < 2:
                    continue
                i, j = rng.sample(range(len(E)), 2)
                a, b = E[i]
                c2, e = E[j]
                if a == c2 or b == e or e in adj[a] or b in adj[c2]:
                    continue
                _rewire(adj, a, b, c2, e)
                new = _bad_count(n, adj, D)
                if new <= cost or rng.random() < math.exp(-(new - cost) / T):
                    cost = new
                    E[i] = (a, e)
                    E[j] = (c2, b)
                else:
                    _rewire(adj, a, e, c2, b)

        if cost == 0:
            best_n, best_e = n, list(E)
            fails = 0
        else:
            n = n_old
            adj = snap_adj
            color = snap_color
            E = snap_E
            fails += 1
    return best_n, best_e


