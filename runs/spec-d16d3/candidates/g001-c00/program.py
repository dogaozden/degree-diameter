import lib


# ----------------------------------------------------------------------------
# Arc-extended projective plane incidence graphs (diameter 3).
#
# Start from the incidence graph of PG(2, q). Every old vertex has degree q+1,
# so with degree cap d it has spare s = d - q - 1. Choose a point set S whose
# every line and every point meets S in at most s elements. For each P in S add
# an A-vertex on the lines through P, and for each j in S add a B-vertex on the
# points of line j.
# ----------------------------------------------------------------------------

def _pg_data(q):
    """Return (m, edges, point_lines, line_points, index) for PG(2, q)."""
    pts = lib.projective_points(q)
    n2, edges = lib.projective_plane_incidence(q)
    m = n2 // 2
    point_lines = [[] for _ in range(m)]
    line_points = [[] for _ in range(m)]
    for u, v in edges:
        point_lines[u].append(v - m)
        line_points[v - m].append(u)
    index = {p: i for i, p in enumerate(pts)}
    return m, edges, point_lines, line_points, index


def _loads_ok(S, s, m, point_lines, line_points):
    """True if every line holds <= s points of S and every point lies on <= s lines indexed by S."""
    cl = [0] * m
    cp = [0] * m
    for P in S:
        for L in point_lines[P]:
            cl[L] += 1
        for Q in line_points[P]:
            cp[Q] += 1
    return max(cl, default=0) <= s and max(cp, default=0) <= s


def _greedy_arc(m, s, point_lines, line_points, rng, trials):
    """Randomized greedy choice of S with all loads <= s; returns the largest found."""
    best = []
    order = list(range(m))
    for _ in range(trials):
        rng.shuffle(order)
        cl = [0] * m
        cp = [0] * m
        S = []
        for P in order:
            if all(cl[L] < s for L in point_lines[P]) and all(cp[Q] < s for Q in line_points[P]):
                S.append(P)
                for L in point_lines[P]:
                    cl[L] += 1
                for Q in line_points[P]:
                    cp[Q] += 1
        if len(S) > len(best):
            best = S
    return best


def _conic_set(q, index, F):
    """Conic (plus nucleus for even q): an arc with no three collinear."""
    S = [index[(1, t, F.mul(t, t))] for t in range(q)]
    S.append(index[(0, 0, 1)])
    if q % 2 == 0:
        S.append(index[(0, 1, 0)])
    return S


def _arc_graph(m, edges, point_lines, line_points, S):
    """Old PG incidence plus a new A-vertex per element of S (on its lines) and a new B-vertex (on its points)."""
    k = len(S)
    n = 2 * m + 2 * k
    E = list(edges)
    for t, P in enumerate(S):
        x = 2 * m + t
        for L in point_lines[P]:
            E.append((x, m + L))
    for t, j in enumerate(S):
        b = 2 * m + k + t
        for Q in line_points[j]:
            E.append((Q, b))
    return n, E


def _arc_candidates(d, D, rng):
    """Valid arc-extended graphs for each prime power q with q + 1 <= d and spare s >= 1."""
    out = []
    for q in range(2, min(d - 1, 23) + 1):
        if not lib.is_prime_power(q):
            continue
        s = d - q - 1
        if s < 1:
            continue
        m, edges, point_lines, line_points, index = _pg_data(q)
        cands = [_greedy_arc(m, s, point_lines, line_points, rng, 30)]
        if s >= 2:
            cands.append(_conic_set(q, index, lib.GF(q)))
        for S in cands:
            if not S or not _loads_ok(S, s, m, point_lines, line_points):
                continue
            n_c, e_c = _arc_graph(m, edges, point_lines, line_points, S)
            if lib.is_valid(n_c, e_c, d, D):
                out.append((n_c, e_c))
    return out


# ----------------------------------------------------------------------------
# NEW helper: slack filling by ball-cover.
#
# Adding a vertex x adjacent to a set T (all on the opposite colour class, each
# of degree < d) keeps diameter <= D, provided every vertex lies within distance
# D-1 of some t in T. For D = 3 this is: the union of radius-2 balls of T covers
# the whole graph. Old distances can only shrink, so only pairs involving x need
# checking. A greedy set cover over radius-2 balls (bitmasks) finds such T.
# ----------------------------------------------------------------------------

def _masks(n, adj):
    """Return (b2, full): b2[v] is a bitmask of all vertices within distance 2 of v."""
    b1 = [0] * n
    for v in range(n):
        r = 1 << v
        for u in adj[v]:
            r |= 1 << u
        b1[v] = r
    b2 = [0] * n
    for v in range(n):
        r = b1[v]
        for u in adj[v]:
            r |= b1[u]
        b2[v] = r
    return b2, (1 << n) - 1


def _bipartition(n, adj):
    """2-colouring of a bipartite graph given as adjacency sets."""
    color = [-1] * n
    for s in range(n):
        if color[s] != -1:
            continue
        color[s] = 0
        stack = [s]
        while stack:
            u = stack.pop()
            for v in adj[u]:
                if color[v] == -1:
                    color[v] = 1 - color[u]
                    stack.append(v)
    return color


def _slack_fill(n, edges, d, deadline, rng, max_fail):
    """Greedily add new vertices whose neighbourhoods cover all radius-2 balls (diameter preserved)."""
    adj = [set() for _ in range(n)]
    for u, v in edges:
        adj[u].add(v)
        adj[v].add(u)
    color = _bipartition(n, adj)
    b2, full = _masks(n, adj)
    fails = 0
    while time.monotonic() < deadline and fails < max_fail:
        c = rng.randrange(2)
        cands = [v for v in range(n) if color[v] != c and len(adj[v]) < d]
        rng.shuffle(cands)
        covered = 0
        T = []
        while covered != full and len(T) < d and cands:
            best, gain = -1, 0
            for t in cands:
                g = (b2[t] & ~covered).bit_count()
                if g > gain:
                    gain, best = g, t
            if best < 0:
                break
            T.append(best)
            covered |= b2[best]
            cands.remove(best)
        if covered == full:
            x = n
            n += 1
            adj.append(set())
            color.append(c)
            for t in T:
                adj[t].add(x)
                adj[x].add(t)
            b2, full = _masks(n, adj)
            fails = 0
        else:
            fails += 1
    out = [(u, v) for u in range(n) for v in adj[u] if u < v]
    return n, out


# ----------------------------------------------------------------------------
# Generalized quadrangle baseline (D = 4).
# ----------------------------------------------------------------------------

def _gq_w(q):
    """Incidence graph of points and lines of the generalized quadrangle W(q); diameter 4."""
    F = lib.GF(q)
    pts = [v for v in itertools.product(range(q), repeat=4)
           if any(v) and next(c for c in v if c) == 1]
    index = {v: i for i, v in enumerate(pts)}
    P = len(pts)

    def norm(v):
        c = next(x for x in v if x)
        inv = F.inv(c)
        return tuple(F.mul(inv, x) for x in v)

    def form(x, y):
        t = F.sub(F.mul(x[0], y[1]), F.mul(x[1], y[0]))
        return F.add(t, F.sub(F.mul(x[2], y[3]), F.mul(x[3], y[2])))

    covered = set()
    lines = []
    for i in range(P):
        x = pts[i]
        for j in range(i + 1, P):
            if (i, j) in covered:
                continue
            y = pts[j]
            if form(x, y) != 0:
                continue
            L = set()
            for a in range(q):
                for b in range(q):
                    if a == 0 and b == 0:
                        continue
                    v = tuple(F.add(F.mul(a, x[k]), F.mul(b, y[k])) for k in range(4))
                    if any(v):
                        L.add(index[norm(v)])
            L = sorted(L)
            lines.append(L)
            for p in L:
                for r in L:
                    if p < r:
                        covered.add((p, r))

    edges = []
    for j, L in enumerate(lines):
        for p in L:
            edges.append((p, P + j))
    return 2 * P, edges


def _best_gq(d):
    """W(q) for the largest prime power q with q + 1 <= d, restricted to small q for speed."""
    for q in range(min(d - 1, 9), 1, -1):
        if lib.is_prime_power(q):
            return _gq_w(q)
    return None


