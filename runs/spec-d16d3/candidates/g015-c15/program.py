# ----------------------------------------------------------------------------
# New construction: arc-extended projective plane incidence graphs (diameter 3).
#
# Start from the incidence graph of PG(2, q) (points 0..m-1, lines m..2m-1).
# Every old vertex has degree q+1, so with d >= q+1 it has spare capacity
# s = d - q - 1. Choose a point set S such that every line contains at most s
# points of S and every point lies on at most s lines indexed by S (the same
# condition, by polarity). For each P in S add a new A-vertex joined to all
# q+1 lines through P; for each j in S add a new B-vertex joined to all q+1
# points on line j. Old lines and points stay within capacity d.
# ----------------------------------------------------------------------------

def _pg_data(q):
    """Return (m, edges, point_lines, line_points, index, pts) for PG(2, q)."""
    pts = lib.projective_points(q)
    n2, edges = lib.projective_plane_incidence(q)
    m = n2 // 2
    point_lines = [[] for _ in range(m)]
    line_points = [[] for _ in range(m)]
    for u, v in edges:
        point_lines[u].append(v - m)
        line_points[v - m].append(u)
    index = {p: i for i, p in enumerate(pts)}
    return m, edges, point_lines, line_points, index, pts


def _loads_ok(S, s, m, point_lines, line_points):
    """True if every line holds <= s points of S and every point lies on <= s lines indexed by S."""
    cl = [0] * m
    cp = [0] * m
    for P in S:
        for L in point_lines[P]:
            cl[L] += 1
        for Q in line_points[P]:
            cp[Q] += 1
    return max(cl, default=0) <= s and max(cp, default=0) <= s


def _greedy_arc(m, s, point_lines, line_points, rng, trials, deadline):
    """Randomized greedy choice of S with all loads <= s; returns the largest found."""
    best = []
    order = list(range(m))
    for _ in range(trials):
        if time.monotonic() > deadline:
            break
        rng.shuffle(order)
        cl = [0] * m
        cp = [0] * m
        S = []
        for P in order:
            if all(cl[L] < s for L in point_lines[P]) and all(cp[Q] < s for Q in line_points[P]):
                S.append(P)
                for L in point_lines[P]:
                    cl[L] += 1
                for Q in line_points[P]:
                    cp[Q] += 1
        if len(S) > len(best):
            best = S
    return best


def _conic_set(q, index, F):
    """Conic (plus nucleus for even q) as a point-index set: an arc with no three collinear."""
    S = [index[(1, t, F.mul(t, t))] for t in range(q)]
    S.append(index[(0, 0, 1)])
    if q % 2 == 0:
        S.append(index[(0, 1, 0)])
    return S


def _arc_graph(m, edges, point_lines, S, line_points):
    """Build the extended graph: old PG incidence plus a new A and a new B vertex per element of S."""
    k = len(S)
    n = 2 * m + 2 * k
    E = list(edges)
    for t, P in enumerate(S):
        x = 2 * m + t
        for L in point_lines[P]:
            E.append((x, m + L))
    for t, j in enumerate(S):
        b = 2 * m + k + t
        for Q in line_points[j]:
            E.append((Q, b))
    return n, E


def _arc_extensions(d, deadline, rng):
    """Return (n, edges) candidates for each prime power q with q + 1 <= d."""
    out = []
    for q in range(2, min(d - 1, 23) + 1):
        if not lib.is_prime_power(q):
            continue
        if time.monotonic() > deadline:
            break
        s = d - q - 1
        m, edges, point_lines, line_points, index, pts = _pg_data(q)
        cands = []
        if s >= 1:
            cands.append(_greedy_arc(m, s, point_lines, line_points, rng, 40, deadline))
        if s >= 2:
            F = lib.GF(q)
            cs = _conic_set(q, index, F)
            if _loads_ok(cs, s, m, point_lines, line_points):
                cands.append(cs)
        S = max(cands, key=len, default=[])
        if not _loads_ok(S, s, m, point_lines, line_points):
            continue
        n_c, e_c = _arc_graph(m, edges, point_lines, S, line_points)
        out.append((n_c, e_c))
    return out


# ----------------------------------------------------------------------------
# NEW (focused change): cyclic Haar graphs from difference covers (diameter 3).
#
# Haar graph H(Z_m, S): a_i ~ b_{i+s} for s in S, |S| = d, so it is d-regular
# and bipartite. Two A-vertices (or two B-vertices) are at distance 2 iff
# their index difference lies in S - S, and every A-to-B pair is within
# distance 3 when S - S covers all of Z_m (then S - S + S = Z_m too). So any
# set S of d residues whose pairwise differences cover Z_m gives a valid graph
# on 2m vertices with diameter 3. Since |S - S| <= d(d-1)+1, m can reach
# d(d-1)+1, i.e. order up to 2(d^2-d+1), the Moore bound. For d = 16 this is
# 482, and the arc construction gives 394 = 2*197, so we search for covers with
# m = 198, 199, ... by simulated annealing that minimises uncovered differences.
# ----------------------------------------------------------------------------

def _diff_cover(m, k, rng, deadline):
    """Find k residues mod m whose pairwise differences cover all nonzero residues, or None."""

    def recount(S):
        cnt = [0] * m
        for i, x in enumerate(S):
            for y in S[:i]:
                cnt[(x - y) % m] += 1
                cnt[(y - x) % m] += 1
        return cnt

    while time.monotonic() < deadline:
        S = [0] + rng.sample(range(1, m), k - 1)
        cnt = recount(S)
        unc = sum(1 for x in range(1, m) if cnt[x] == 0)
        best_unc = unc
        stall = 0
        while unc and stall < 40000:
            if time.monotonic() > deadline:
                return None
            stall += 1
            i = rng.randrange(1, k)
            old = S[i]
            y = rng.randrange(1, m)
            if y in S:
                continue
            others = S[:i] + S[i + 1:]
            for b in others:
                cnt[(old - b) % m] -= 1
                cnt[(b - old) % m] -= 1
                cnt[(y - b) % m] += 1
                cnt[(b - y) % m] += 1
            new_unc = sum(1 for x in range(1, m) if cnt[x] == 0)
            if new_unc <= unc or rng.random() < math.exp(-(new_unc - unc) / 0.4):
                S[i] = y
                unc = new_unc
                if unc < best_unc:
                    best_unc = unc
                    stall = 0
            else:
                for b in others:
                    cnt[(y - b) % m] -= 1
                    cnt[(b - y) % m] -= 1
                    cnt[(old - b) % m] += 1
                    cnt[(b - old) % m] += 1
        if unc == 0:
            return S
    return None


# ----------------------------------------------------------------------------
# Generalized quadrangle baseline (D = 4).
# ----------------------------------------------------------------------------

def _gq_w(q):
    """Incidence graph of points and lines of the generalized quadrangle W(q); diameter 4."""
    F = lib.GF(q)
    pts = [v for v in itertools.product(range(q), repeat=4)
           if any(v) and next(c for c in v if c) == 1]
    index = {v: i for i, v in enumerate(pts)}
    P = len(pts)

    def norm(v):
        c = next(x for x in v if x)
        inv = F.inv(c)
        return tuple(F.mul(inv, x) for x in v)

    def form(x, y):
        t = F.sub(F.mul(x[0], y[1]), F.mul(x[1], y[0]))
        return F.add(t, F.sub(F.mul(x[2], y[3]), F.mul(x[3], y[2])))

    covered = set()
    lines = []
    for i in range(P):
        x = pts[i]
        for j in range(i + 1, P):
            if (i, j) in covered:
                continue
            y = pts[j]
            if form(x, y) != 0:
                continue
            L = set()
            for a in range(q):
                for b in range(q):
                    if a == 0 and b == 0:
                        continue
                    v = tuple(F.add(F.mul(a, x[k]), F.mul(b, y[k])) for k in range(4))
                    if any(v):
                        L.add(index[norm(v)])
            L = sorted(L)
            lines.append(L)
            for p in L:
                for r in L:
                    if p < r:
                        covered.add((p, r))

    edges = []
    for j, L in enumerate(lines):
        for p in L:
            edges.append((p, P + j))
    return 2 * P, edges


def _best_gq(d):
    """W(q) for the largest prime power q with q + 1 <= d, restricted to small q for speed."""
    for q in range(min(d - 1, 9), 1, -1):
        if lib.is_prime_power(q):
            return _gq_w(q)
    return None


