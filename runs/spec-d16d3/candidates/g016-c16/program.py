import itertools
import math
import random
import time

import lib


# ----------------------------------------------------------------------------
# Arc-extended projective plane incidence graphs (diameter 3).
#
# Start from the incidence graph of PG(2, q). For each point P in an arc S,
# add an A-vertex joined to the q+1 lines through P; for each line j in S, add
# a B-vertex joined to the q+1 points on j. The spare-degree condition is that
# every line/point meets at most s = d-q-1 elements of S.
# ----------------------------------------------------------------------------

def _pg_data(q):
    """Return (m, edges, point_lines, line_points, index) for PG(2, q)."""
    pts = lib.projective_points(q)
    n2, edges = lib.projective_plane_incidence(q)
    m = n2 // 2
    point_lines = [[] for _ in range(m)]
    line_points = [[] for _ in range(m)]
    for u, v in edges:
        point_lines[u].append(v - m)
        line_points[v - m].append(u)
    index = {p: i for i, p in enumerate(pts)}
    return m, edges, point_lines, line_points, index


def _loads_ok(S, s, m, point_lines, line_points):
    """True if every line holds <= s points of S and every point lies on <= s lines indexed by S."""
    cl = [0] * m
    cp = [0] * m
    for P in S:
        for L in point_lines[P]:
            cl[L] += 1
        for Q in line_points[P]:
            cp[Q] += 1
    return max(cl, default=0) <= s and max(cp, default=0) <= s


def _greedy_arc(m, s, point_lines, line_points, rng, trials, deadline):
    """Randomized greedy choice of S with all loads <= s; returns the largest found."""
    best = []
    order = list(range(m))
    for _ in range(trials):
        if time.monotonic() > deadline:
            break
        rng.shuffle(order)
        cl = [0] * m
        cp = [0] * m
        S = []
        for P in order:
            if all(cl[L] < s for L in point_lines[P]) and all(cp[Q] < s for Q in line_points[P]):
                S.append(P)
                for L in point_lines[P]:
                    cl[L] += 1
                for Q in line_points[P]:
                    cp[Q] += 1
        if len(S) > len(best):
            best = S
    return best


def _conic_set(q, index, F):
    """Conic (plus nucleus for even q) as a point-index set: an arc with no three collinear."""
    S = [index[(1, t, F.mul(t, t))] for t in range(q)]
    S.append(index[(0, 0, 1)])
    if q % 2 == 0:
        S.append(index[(0, 1, 0)])
    return S


def _arc_graph(m, edges, point_lines, line_points, S):
    """Old PG incidence plus a new A and a new B vertex per element of S."""
    k = len(S)
    n = 2 * m + 2 * k
    E = list(edges)
    for t, P in enumerate(S):
        x = 2 * m + t
        for L in point_lines[P]:
            E.append((x, m + L))
    for t, j in enumerate(S):
        b = 2 * m + k + t
        for Q in line_points[j]:
            E.append((Q, b))
    return n, E


def _arc_extensions(d, deadline, rng):
    """Return a list of (n, edges) candidates, one per prime power q with q + 1 <= d."""
    out = []
    for q in range(2, min(d - 1, 23) + 1):
        if not lib.is_prime_power(q):
            continue
        if time.monotonic() > deadline:
            break
        s = d - q - 1
        m, edges, point_lines, line_points, index = _pg_data(q)
        cands = []
        if s >= 1:
            cands.append(_greedy_arc(m, s, point_lines, line_points, rng, 40, deadline))
        if s >= 2:
            cs = _conic_set(q, index, lib.GF(q))
            if _loads_ok(cs, s, m, point_lines, line_points):
                cands.append(cs)
        S = max(cands, key=len, default=[])
        if not _loads_ok(S, s, m, point_lines, line_points):
            continue
        out.append(_arc_graph(m, edges, point_lines, line_points, S))
    return out


# ----------------------------------------------------------------------------
# NEW helper: greedy pencil-cover augmentation.
#
# Try to add one vertex v on side `side` whose neighbours lie on the other
# side (with spare degree). For bipartite diameter 3, every same-side vertex
# must share a neighbour with v, so the chosen neighbours must cover all
# same-side vertices. We search greedily with randomized restarts and accept
# only if lib.is_valid confirms the result. Adding edges to spare vertices
# cannot break existing distances, so only v's distances need checking.
#
# Caveat: for arc-extended PG(2,q) graphs, covering all points by lines needs
# a pencil, which is generally blocked by the spare-degree pattern. The helper
# is therefore expected to succeed rarely; it is kept because it is cheap and
# verified.
# ----------------------------------------------------------------------------

def _two_colour(n, edges):
    """Return (colour, adjacency) for a bipartite graph; colour is 0/1 per vertex."""
    adj = lib.adjacency(n, edges)
    color = [-1] * n
    for s0 in range(n):
        if color[s0] != -1:
            continue
        color[s0] = 0
        stack = [s0]
        while stack:
            u = stack.pop()
            for v in adj[u]:
                if color[v] == -1:
                    color[v] = 1 - color[u]
                    stack.append(v)
    return color, adj


def _cover_pick(cands, nb, target, d, rng):
    """Greedily pick <= d candidates whose neighbourhood masks cover target; None if it fails."""
    chosen = []
    covered = 0
    pool = list(cands)
    rng.shuffle(pool)
    while target & ~covered:
        if len(chosen) == d:
            return None
        best, gain = None, 0
        for y in pool:
            g = (nb[y] & target & ~covered).bit_count()
            if g > gain:
                best, gain = y, g
        if best is None:
            return None
        chosen.append(best)
        pool.remove(best)
        covered |= nb[best]
    return chosen


def _try_add(n, edges, d, D, color, adj, side, rng, attempts, deadline):
    """Try to add one vertex on `side`; return (n+1, new_edges) if valid, else None."""
    nb = [0] * n
    for y in range(n):
        mask = 0
        for u in adj[y]:
            mask |= 1 << u
        nb[y] = mask
    target = 0
    for v in range(n):
        if color[v] == side:
            target |= 1 << v
    cands = [y for y in range(n) if color[y] != side and len(adj[y]) < d]
    for _ in range(attempts):
        if time.monotonic() > deadline:
            break
        chosen = _cover_pick(cands, nb, target, d, rng)
        if chosen is None:
            continue
        new_edges = edges + [(n, y) for y in chosen]
        if lib.is_valid(n + 1, new_edges, d, D):
            return n + 1, new_edges
    return None


def _augment(n, edges, d, D, deadline, rng):
    """Repeatedly add single vertices while the cover search succeeds."""
    while time.monotonic() < deadline:
        color, adj = _two_colour(n, edges)
        sides = [0, 1]
        rng.shuffle(sides)
        grew = False
        for side in sides:
            res = _try_add(n, edges, d, D, color, adj, side, rng, 200, deadline)
            if res is not None:
                n, edges = res
                grew = True
                break
        if not grew:
            break
    return n, edges


# ----------------------------------------------------------------------------
# Generalized quadrangle baseline (D = 4).
# ----------------------------------------------------------------------------

def _gq_w(q):
    """Incidence graph of points and lines of the generalized quadrangle W(q); diameter 4."""
    F = lib.GF(q)
    pts = [v for v in itertools.product(range(q), repeat=4)
           if any(v) and next(c for c in v if c) == 1]
    index = {v: i for i, v in enumerate(pts)}
    P = len(pts)

    def norm(v):
        c = next(x for x in v if x)
        inv = F.inv(c)
        return tuple(F.mul(inv, x) for x in v)

    def form(x, y):
        t = F.sub(F.mul(x[0], y[1]), F.mul(x[1], y[0]))
        return F.add(t, F.sub(F.mul(x[2], y[3]), F.mul(x[3], y[2])))

    covered = set()
    lines = []
    for i in range(P):
        x = pts[i]
        for j in range(i + 1, P):
            if (i, j) in covered:
                continue
            y = pts[j]
            if form(x, y) != 0:
                continue
            L = set()
            for a in range(q):
                for b in range(q):
                    if a == 0 and b == 0:
                        continue
                    v = tuple(F.add(F.mul(a, x[k]), F.mul(b, y[k])) for k in range(4))
                    if any(v):
                        L.add(index[norm(v)])
            L = sorted(L)
            lines.append(L)
            for p in L:
                for r in L:
                    if p < r:
                        covered.add((p, r))

    edges = []
    for j, L in enumerate(lines):
        for p in L:
            edges.append((p, P + j))
    return 2 * P, edges


def _best_gq(d):
    """W(q) for the largest prime power q with q + 1 <= d, restricted to small q for speed."""
    for q in range(min(d - 1, 9), 1, -1):
        if lib.is_prime_power(q):
            return _gq_w(q)
    return None


