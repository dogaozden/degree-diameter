# ----------------------------------------------------------------------------
# Helpers: projective plane and generalized quadrangle bases.
# ----------------------------------------------------------------------------

def _best_pg(d):
    """Incidence graph of PG(2, q) for the largest prime power q with q + 1 <= d."""
    for q in range(d - 1, 1, -1):
        if lib.is_prime_power(q):
            return lib.projective_plane_incidence(q)
    return None


def _gq_w(q):
    """Incidence graph of points and lines of the generalized quadrangle W(q); diameter 4."""
    F = lib.GF(q)
    pts = [v for v in itertools.product(range(q), repeat=4)
           if any(v) and next(c for c in v if c) == 1]
    index = {v: i for i, v in enumerate(pts)}
    P = len(pts)

    def norm(v):
        c = next(x for x in v if x)
        inv = F.inv(c)
        return tuple(F.mul(inv, x) for x in v)

    def form(x, y):
        t = F.sub(F.mul(x[0], y[1]), F.mul(x[1], y[0]))
        return F.add(t, F.sub(F.mul(x[2], y[3]), F.mul(x[3], y[2])))

    covered = set()
    lines = []
    for i in range(P):
        x = pts[i]
        for j in range(i + 1, P):
            if (i, j) in covered:
                continue
            y = pts[j]
            if form(x, y) != 0:
                continue
            L = set()
            for a in range(q):
                for b in range(q):
                    if a == 0 and b == 0:
                        continue
                    v = tuple(F.add(F.mul(a, x[k]), F.mul(b, y[k])) for k in range(4))
                    if any(v):
                        L.add(index[norm(v)])
            L = sorted(L)
            lines.append(L)
            for p in L:
                for r in L:
                    if p < r:
                        covered.add((p, r))

    edges = []
    for j, L in enumerate(lines):
        for p in L:
            edges.append((p, P + j))
    return 2 * P, edges


def _best_gq(d):
    """W(q) for the largest prime power q with q + 1 <= d, restricted to small q for speed."""
    for q in range(min(d - 1, 9), 1, -1):
        if lib.is_prime_power(q):
            return _gq_w(q)
    return None


# ----------------------------------------------------------------------------
# Arc-extended projective plane graphs (diameter 3).
#
# From PG(2, q) incidence, with spare capacity s = d - q - 1 on each vertex,
# pick a point set S with every line holding <= s points of S and every point
# on <= s lines of S. Add an A-vertex per point of S (joined to its q+1 lines)
# and a B-vertex per line of S (joined to its q+1 points). Diameter stays 3.
# ----------------------------------------------------------------------------

def _pg_data(q):
    """Return (m, edges, point_lines, line_points, index, pts) for PG(2, q)."""
    pts = lib.projective_points(q)
    n2, edges = lib.projective_plane_incidence(q)
    m = n2 // 2
    point_lines = [[] for _ in range(m)]
    line_points = [[] for _ in range(m)]
    for u, v in edges:
        point_lines[u].append(v - m)
        line_points[v - m].append(u)
    index = {p: i for i, p in enumerate(pts)}
    return m, edges, point_lines, line_points, index, pts


def _loads_ok(S, s, m, point_lines, line_points):
    """True if every line holds <= s points of S and every point lies on <= s lines indexed by S."""
    cl = [0] * m
    cp = [0] * m
    for P in S:
        for L in point_lines[P]:
            cl[L] += 1
        for Q in line_points[P]:
            cp[Q] += 1
    return max(cl, default=0) <= s and max(cp, default=0) <= s


def _greedy_arc(m, s, point_lines, line_points, rng, trials, deadline):
    """Randomized greedy choice of S with all loads <= s; returns the largest found."""
    best = []
    order = list(range(m))
    for _ in range(trials):
        if time.monotonic() > deadline:
            break
        rng.shuffle(order)
        cl = [0] * m
        cp = [0] * m
        S = []
        for P in order:
            if all(cl[L] < s for L in point_lines[P]) and all(cp[Q] < s for Q in line_points[P]):
                S.append(P)
                for L in point_lines[P]:
                    cl[L] += 1
                for Q in line_points[P]:
                    cp[Q] += 1
        if len(S) > len(best):
            best = S
    return best


def _local_arc(m, s, point_lines, line_points, S0, rng, deadline):
    """Iterated local search for a large S with all loads <= s, starting from feasible S0."""
    cl = [0] * m
    cp = [0] * m
    inS = [False] * m
    S = []

    def add(P):
        inS[P] = True
        S.append(P)
        for L in point_lines[P]:
            cl[L] += 1
        for Q in line_points[P]:
            cp[Q] += 1

    def remove(P):
        inS[P] = False
        S.remove(P)
        for L in point_lines[P]:
            cl[L] -= 1
        for Q in line_points[P]:
            cp[Q] -= 1

    def blockers(P):
        satL = {L for L in point_lines[P] if cl[L] >= s}
        satQ = {Q for Q in line_points[P] if cp[Q] >= s}
        if not satL and not satQ:
            return []
        return [R for R in S
                if any(L in satL for L in point_lines[R])
                or any(Q in satQ for Q in line_points[R])]

    for P in S0:
        add(P)
    best = list(S)
    it = 0
    while True:
        it += 1
        if (it & 255) == 0 and time.monotonic() > deadline:
            break
        P = rng.randrange(m)
        if inS[P]:
            continue
        B = blockers(P)
        if not B:
            add(P)
        elif len(B) == 1 or (len(B) == 2 and rng.random() < 0.1):
            for R in B:
                remove(R)
            add(P)
        else:
            continue
        if len(S) > len(best):
            best = list(S)
    return best


def _conic_set(q, index, F):
    """Conic (plus nucleus for even q) as a point-index set: an arc with no three collinear."""
    S = [index[(1, t, F.mul(t, t))] for t in range(q)]
    S.append(index[(0, 0, 1)])
    if q % 2 == 0:
        S.append(index[(0, 1, 0)])
    return S


def _arc_graph(m, edges, point_lines, line_points, S):
    """Old PG incidence plus a new A and a new B vertex per element of S.

    Layout: ids 0..m-1 are points (colour 0), m..2m-1 lines (colour 1),
    then k A-clones (colour 0), then k B-clones (colour 1).
    """
    k = len(S)
    n = 2 * m + 2 * k
    E = list(edges)
    for t, P in enumerate(S):
        x = 2 * m + t
        for L in point_lines[P]:
            E.append((x, m + L))
    for t, j in enumerate(S):  # S is also a set of line indices (same vectors)
        b = 2 * m + k + t
        for Q in line_points[j]:
            E.append((Q, b))
    return n, E


def _arc_extensions(d, deadline, rng, threshold):
    """Return (n, edges, base) candidates for prime powers q with q + 1 <= d.

    `base` = 2m is the number of original PG vertices; every vertex with id >= base
    is an added clone, so only those can be removed without breaking old pairs.
    """
    qs = []
    for q in range(2, min(d - 1, 23) + 1):
        if not lib.is_prime_power(q):
            continue
        s = d - q - 1
        if s < 1:
            continue
        m = q * q + q + 1
        kmax = s * m // (q + 1)
        if 2 * m + 2 * kmax <= threshold:
            continue
        qs.append((q, s))

    out = []
    for idx, (q, s) in enumerate(qs):
        now = time.monotonic()
        if now > deadline:
            break
        share = (deadline - now) / (len(qs) - idx)
        q_deadline = now + share
        m, edges, point_lines, line_points, index, pts = _pg_data(q)
        cands = []
        if s >= 1:
            cands.append(_greedy_arc(m, s, point_lines, line_points, rng, 40,
                                     now + 0.3 * share))
        if s >= 2:
            F = lib.GF(q)
            cs = _conic_set(q, index, F)
            if _loads_ok(cs, s, m, point_lines, line_points):
                cands.append(cs)
        S0 = max(cands, key=len, default=[])
        if not _loads_ok(S0, s, m, point_lines, line_points):
            S0 = []
        S = _local_arc(m, s, point_lines, line_points, S0, rng, q_deadline)
        if not S or not _loads_ok(S, s, m, point_lines, line_points):
            continue
        n_c, E_c = _arc_graph(m, edges, point_lines, line_points, S)
        out.append((n_c, E_c, 2 * m))
    return out


# ----------------------------------------------------------------------------
# NEW: ruin-and-recreate search over clone vertices with cover-based insertion.
#
# A mutable bipartite graph keeps vertex ids stable. The search removes a few
# added (clone) vertices, then re-inserts vertices one by one. A new vertex of
# colour 1 - c is joined to a set of colour-c vertices whose radius-(D-1) balls
# cover every live vertex, so every pair involving it stays within distance D.
# Removing only added vertices never breaks a pair between surviving vertices
# (they do not use the removed clones), so the invariant "valid" is preserved.
# Equal-size moves are accepted as a plateau walk.
# ----------------------------------------------------------------------------

class _Mut:
    def __init__(self, n, edges, color, base, d):
        self.adj = [set() for _ in range(n)]
        for u, v in edges:
            self.adj[u].add(v)
            self.adj[v].add(u)
        self.color = list(color)
        self.alive = [True] * n
        self.base = base
        self.d = d
        self.free = []

    def copy(self):
        o = _Mut.__new__(_Mut)
        o.adj = [set(a) for a in self.adj]
        o.color = self.color[:]
        o.alive = self.alive[:]
        o.base = self.base
        o.d = self.d
        o.free = self.free[:]
        return o

    def count(self):
        return sum(self.alive)

    def remove(self, v):
        for u in self.adj[v]:
            self.adj[u].discard(v)
        self.adj[v] = set()
        self.alive[v] = False
        self.free.append(v)

    def insert(self, color, nbrs):
        if self.free:
            v = self.free.pop()
            self.color[v] = color
            self.alive[v] = True
        else:
            v = len(self.adj)
            self.adj.append(set())
            self.color.append(color)
            self.alive.append(True)
        for u in nbrs:
            self.adj[u].add(v)
            self.adj[v].add(u)
        return v

    def reach(self, r):
        """Bitmask per vertex of live vertices within distance r (dead vertices get 0)."""
        n = len(self.adj)
        alive = self.alive
        reach = [(1 << v) if alive[v] else 0 for v in range(n)]
        for _ in range(r):
            new = reach[:]
            for v in range(n):
                if alive[v]:
                    x = reach[v]
                    for u in self.adj[v]:
                        x |= reach[u]
                    new[v] = x
            reach = new
        return reach

    def full_mask(self):
        mask = 0
        for v, a in enumerate(self.alive):
            if a:
                mask |= 1 << v
        return mask

    def cover(self, c, reach, full, rng, tries):
        """Neighbour set of colour c (size <= d) whose balls cover `full`, or None."""
        d = self.d
        cands = [s for s in range(len(self.adj))
                 if self.alive[s] and self.color[s] == c and len(self.adj[s]) < d]
        if not cands:
            return None
        for t in range(tries):
            pool = cands[:]
            if t:
                rng.shuffle(pool)
            covered = 0
            chosen = []
            while covered != full and len(chosen) < d and pool:
                gains = [(reach[s] & ~covered).bit_count() for s in pool]
                bg = max(gains, default=0)
                if bg == 0:
                    break
                if t and rng.random() < 0.5:
                    opts = [i for i, g in enumerate(gains) if g >= bg - 1 and g > 0]
                else:
                    opts = [i for i, g in enumerate(gains) if g == bg]
                i = rng.choice(opts)
                s = pool.pop(i)
                chosen.append(s)
                covered |= reach[s]
            if covered == full:
                return chosen
        return None


def _mut_edges(mut):
    return [(u, v) for u in range(len(mut.adj)) if mut.alive[u]
            for v in mut.adj[u] if u < v]


def _lns(mut, d, D, deadline, rng, floor_n):
    """Ruin-and-recreate over added vertices; returns the best valid (n, edges) above floor_n, or None."""
    cur = mut
    best = None
    best_cnt = floor_n
    while time.monotonic() < deadline:
        cand = cur.copy()
        added = [v for v in range(cand.base, len(cand.adj)) if cand.alive[v]]
        r = 0
        if added:
            r = rng.randint(1, min(len(added), 8))
            for v in rng.sample(added, r):
                cand.remove(v)
        got = 0
        for _ in range(r + 1):
            if time.monotonic() > deadline:
                break
            reach = cand.reach(D - 1)
            full = cand.full_mask()
            cols = [0, 1]
            rng.shuffle(cols)
            placed = False
            for c in cols:
                nb = cand.cover(c, reach, full, rng, 6)
                if nb:
                    cand.insert(1 - c, nb)
                    got += 1
                    placed = True
                    break
            if not placed:
                break
        if got < r:
            continue
        cur = cand
        if cur.count() > best_cnt:
            n, e = lib.relabel(_mut_edges(cur))
            if lib.is_valid(n, e, d, D):
                best = (n, e)
                best_cnt = n
    return best


# ----------------------------------------------------------------------------
# Cover-based vertex extension (diameter-preserving growth).
# ----------------------------------------------------------------------------

def _balls_radius(n, adj, r):
    """Bitmask per vertex of all vertices within distance r."""
    ball = [1 << v for v in range(n)]
    for _ in range(r):
        new = []
        for v in range(n):
            x = ball[v]
            for u in adj[v]:
                x |= ball[u]
            new.append(x)
        ball = new
    return ball


def _bipartition(n, adj):
    """Two-colouring of a bipartite graph given by adjacency lists."""
    color = [-1] * n
    for s in range(n):
        if color[s] != -1:
            continue
        color[s] = 0
        stack = [s]
        while stack:
            u = stack.pop()
            for v in adj[u]:
                if color[v] == -1:
                    color[v] = 1 - color[u]
                    stack.append(v)
    return color


def _greedy_cover(cands, ball, full, d, rng, randomize):
    """Greedy set cover of `full` by at most d candidate vertices; None if it fails."""
    pool = list(cands)
    if randomize:
        rng.shuffle(pool)
    covered = 0
    chosen = []
    while covered != full and len(chosen) < d and pool:
        gains = [(ball[s] & ~covered).bit_count() for s in pool]
        best_g = max(gains, default=0)
        if best_g == 0:
            break
        thr = best_g
        if randomize and rng.random() < 0.5:
            thr = best_g - 1
        opts = [i for i, g in enumerate(gains) if g >= thr and g > 0]
        i = rng.choice(opts) if randomize else opts[0]
        s = pool.pop(i)
        chosen.append(s)
        covered |= ball[s]
    return chosen if covered == full else None


def _extend_cover(n, edges, d, D, deadline, rng):
    """Greedily add vertices whose neighbourhoods cover all vertices within D-1 of the graph."""
    if D < 2:
        return n, edges
    edges = list(edges)
    adj = [[] for _ in range(n)]
    for u, v in edges:
        adj[u].append(v)
        adj[v].append(u)
    deg = [len(a) for a in adj]
    color = _bipartition(n, adj)

    while time.monotonic() < deadline:
        ball = _balls_radius(n, adj, D - 1)
        full = (1 << n) - 1
        added = False
        for c in (0, 1):
            cands = [s for s in range(n) if color[s] == c and deg[s] < d]
            if not cands:
                continue
            chosen = None
            for attempt in range(200):
                if time.monotonic() >= deadline:
                    break
                chosen = _greedy_cover(cands, ball, full, d, rng, attempt > 0)
                if chosen:
                    break
            if chosen:
                v = n
                n += 1
                color.append(1 - c)
                adj.append([])
                deg.append(0)
                for s in chosen:
                    edges.append((s, v))
                    adj[s].append(v)
                    adj[v].append(s)
                    deg[s] += 1
                    deg[v] += 1
                added = True
                break
        if not added:
            break
    return n, edges


def _saturate_edges(n, edges, d, rng):
    """Greedily join deficient opposite-side vertices in random order."""
    edges = list(edges)
    adj = [[] for _ in range(n)]
    existing = set()
    for u, v in edges:
        adj[u].append(v)
        adj[v].append(u)
        existing.add((min(u, v), max(u, v)))
    deg = [len(a) for a in adj]
    color = _bipartition(n, adj)
    left = [v for v in range(n) if color[v] == 0 and deg[v] < d]
    right = [v for v in range(n) if color[v] == 1 and deg[v] < d]
    pairs = [(a, b) for a in left for b in right
             if (min(a, b), max(a, b)) not in existing]
    rng.shuffle(pairs)
    for a, b in pairs:
        if deg[a] < d and deg[b] < d:
            edges.append((a, b))
            deg[a] += 1
            deg[b] += 1
    return edges


def _grow(n, edges, d, D, deadline, rng):
    """Extend by cover vertices first, then saturate edges with the leftover spare degree."""
    cur_n, cur_e = n, list(edges)
    for _ in range(8):
        if time.monotonic() >= deadline:
            break
        n2, e2 = _extend_cover(cur_n, cur_e, d, D, deadline, rng)
        grew = n2 != cur_n
        cur_n = n2
        cur_e = _saturate_edges(cur_n, e2, d, rng)
        if not grew:
            break
    return cur_n, cur_e


