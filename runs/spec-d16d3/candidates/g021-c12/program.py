import itertools
import math
import random
import time

import lib


# ----------------------------------------------------------------------------
# Arc-extended projective plane incidence graphs (diameter 3, parent construction).
#
# Start from the incidence graph of PG(2, q). Old vertices have degree q+1, so
# with d >= q+1 each has spare s = d - q - 1. A new A-vertex joined to all lines
# through a point P (and a new B-vertex joined to all points of a line j) keeps
# the diameter at 3 and every degree within d, provided no line carries more
# than s A-apexes and no point lies on more than s B-lines.
# ----------------------------------------------------------------------------

def _pg_data(q):
    """Return (m, edges, point_lines, line_points, index, pts) for PG(2, q)."""
    pts = lib.projective_points(q)
    n2, edges = lib.projective_plane_incidence(q)
    m = n2 // 2
    point_lines = [[] for _ in range(m)]
    line_points = [[] for _ in range(m)]
    for u, v in edges:
        point_lines[u].append(v - m)
        line_points[v - m].append(u)
    index = {p: i for i, p in enumerate(pts)}
    return m, edges, point_lines, line_points, index, pts


def _loads_ok(S, s, m, point_lines, line_points):
    """True if every line holds <= s points of S and every point lies on <= s lines indexed by S."""
    cl = [0] * m
    cp = [0] * m
    for P in S:
        for L in point_lines[P]:
            cl[L] += 1
        for Q in line_points[P]:
            cp[Q] += 1
    return max(cl, default=0) <= s and max(cp, default=0) <= s


def _greedy_arc(m, s, point_lines, line_points, rng, trials, deadline):
    """Randomized greedy choice of S with all loads <= s; returns the largest found."""
    best = []
    order = list(range(m))
    for _ in range(trials):
        if time.monotonic() > deadline:
            break
        rng.shuffle(order)
        cl = [0] * m
        cp = [0] * m
        S = []
        for P in order:
            if all(cl[L] < s for L in point_lines[P]) and all(cp[Q] < s for Q in line_points[P]):
                S.append(P)
                for L in point_lines[P]:
                    cl[L] += 1
                for Q in line_points[P]:
                    cp[Q] += 1
        if len(S) > len(best):
            best = S
    return best


def _conic_set(q, index, F):
    """Conic (plus nucleus for even q) as a point-index set: an arc with no three collinear."""
    S = [index[(1, t, F.mul(t, t))] for t in range(q)]
    S.append(index[(0, 0, 1)])
    if q % 2 == 0:
        S.append(index[(0, 1, 0)])
    return S


_LP = None  # line_points for the current q, set in _arc_extensions


def _arc_graph(m, edges, point_lines, S):
    """Build the extended graph: old PG incidence plus a new A and a new B vertex per element of S."""
    k = len(S)
    n = 2 * m + 2 * k
    E = list(edges)
    for t, P in enumerate(S):
        x = 2 * m + t
        for L in point_lines[P]:
            E.append((x, m + L))
    for t, j in enumerate(S):
        b = 2 * m + k + t
        for Q in _LP[j]:
            E.append((Q, b))
    return n, E


def _arc_extensions(d, deadline, rng):
    """Return (n, edges) candidates for each prime power q with q + 1 <= d."""
    global _LP
    out = []
    for q in range(2, min(d - 1, 23) + 1):
        if not lib.is_prime_power(q):
            continue
        if time.monotonic() > deadline:
            break
        s = d - q - 1
        m, edges, point_lines, line_points, index, pts = _pg_data(q)
        _LP = line_points
        cands = []
        if s >= 1:
            cands.append(_greedy_arc(m, s, point_lines, line_points, rng, 40, deadline))
        if s >= 2:
            F = lib.GF(q)
            cs = _conic_set(q, index, F)
            if _loads_ok(cs, s, m, point_lines, line_points):
                cands.append(cs)
        S = max(cands, key=len, default=[])
        if not _loads_ok(S, s, m, point_lines, line_points):
            continue
        n_c, e_c = _arc_graph(m, edges, point_lines, S)
        out.append((n_c, e_c))
    return out


# ----------------------------------------------------------------------------
# NEW: greedy set-cover vertex insertion ("grow").
#
# A new vertex z on side c with neighbour set T is valid (diameter <= D kept)
# iff every vertex lies within distance D-1 of some t in T. Old pairs never get
# longer when a vertex is added. So we repeatedly build T greedily as a
# set cover over the (D-1)-balls of spare-capacity vertices on the opposite
# side, with random tie-breaking. Every accepted state is valid by construction.
# ----------------------------------------------------------------------------

def _adj_from(n, edges):
    adj = [set() for _ in range(n)]
    for u, v in edges:
        adj[u].add(v)
        adj[v].add(u)
    return adj


def _two_color(n, adj):
    """2-colouring of a bipartite graph given by adjacency sets."""
    col = [-1] * n
    for s in range(n):
        if col[s] != -1:
            continue
        col[s] = 0
        stack = [s]
        while stack:
            u = stack.pop()
            for v in adj[u]:
                if col[v] == -1:
                    col[v] = 1 - col[u]
                    stack.append(v)
    return col


def _closed_balls(n, adj, r):
    """Bitmask of all vertices within distance r of each vertex."""
    b = [1 << v for v in range(n)]
    for _ in range(r):
        nb = [0] * n
        for v in range(n):
            x = b[v]
            for u in adj[v]:
                x |= b[u]
            nb[v] = x
        b = nb
    return b


def _cover_neighbors(n, adj, color, bk, side, d, rng):
    """Greedy set cover: neighbours (opposite colour, spare degree) whose (D-1)-balls cover everything."""
    full = (1 << n) - 1
    cand = [u for u in range(n) if color[u] != side and len(adj[u]) < d]
    covered = 0
    T = []
    used = set()
    while covered != full and len(T) < d:
        best_u = -1
        best_key = 0.0
        for u in cand:
            if u in used:
                continue
            g = (bk[u] & ~covered).bit_count()
            if g == 0:
                continue
            key = g + 0.99 * rng.random()
            if key > best_key:
                best_key = key
                best_u = u
        if best_u < 0:
            return None
        used.add(best_u)
        T.append(best_u)
        covered |= bk[best_u]
    return T if covered == full else None


def _grow_from(n, edges, color, d, D, rng, deadline):
    """Repeatedly insert vertices with greedy covering neighbourhoods; returns a valid (n, edges)."""
    adj = _adj_from(n, edges)
    color = list(color)
    bk = _closed_balls(n, adj, D - 1)
    fails = 0
    while fails < 40 and time.monotonic() < deadline:
        side = rng.randrange(2)
        T = _cover_neighbors(n, adj, color, bk, side, d, rng)
        if T is None:
            fails += 1
            continue
        fails = 0
        z = n
        n += 1
        adj.append(set(T))
        for u in T:
            adj[u].add(z)
        color.append(side)
        bk = _closed_balls(n, adj, D - 1)
    out = [(u, v) for u in range(n) for v in adj[u] if u < v]
    return n, out


def _make_bases(d, D, arcs):
    """Starting graphs for growth: arc-extensions plus a few PG(2,q) incidence graphs."""
    out = []
    for n_c, e_c in arcs:
        out.append((n_c, e_c, _two_color(n_c, _adj_from(n_c, e_c))))
    qs = sorted((q for q in range(2, d) if lib.is_prime_power(q)), reverse=True)[:3]
    for q in qs:
        n_p, e_p = lib.projective_plane_incidence(q)
        m = n_p // 2
        out.append((n_p, e_p, [0] * m + [1] * m))
    return out


# ----------------------------------------------------------------------------
# Generalized quadrangle baseline (D = 4).
# ----------------------------------------------------------------------------

def _gq_w(q):
    """Incidence graph of points and lines of the generalized quadrangle W(q); diameter 4."""
    F = lib.GF(q)
    pts = [v for v in itertools.product(range(q), repeat=4)
           if any(v) and next(c for c in v if c) == 1]
    index = {v: i for i, v in enumerate(pts)}
    P = len(pts)

    def norm(v):
        c = next(x for x in v if x)
        inv = F.inv(c)
        return tuple(F.mul(inv, x) for x in v)

    def form(x, y):
        t = F.sub(F.mul(x[0], y[1]), F.mul(x[1], y[0]))
        return F.add(t, F.sub(F.mul(x[2], y[3]), F.mul(x[3], y[2])))

    covered = set()
    lines = []
    for i in range(P):
        x = pts[i]
        for j in range(i + 1, P):
            if (i, j) in covered:
                continue
            y = pts[j]
            if form(x, y) != 0:
                continue
            L = set()
            for a in range(q):
                for b in range(q):
                    if a == 0 and b == 0:
                        continue
                    v = tuple(F.add(F.mul(a, x[k]), F.mul(b, y[k])) for k in range(4))
                    if any(v):
                        L.add(index[norm(v)])
            L = sorted(L)
            lines.append(L)
            for p in L:
                for r in L:
                    if p < r:
                        covered.add((p, r))

    edges = []
    for j, L in enumerate(lines):
        for p in L:
            edges.append((p, P + j))
    return 2 * P, edges


def _best_gq(d):
    """W(q) for the largest prime power q with q + 1 <= d, restricted to small q for speed."""
    for q in range(min(d - 1, 9), 1, -1):
        if lib.is_prime_power(q):
            return _gq_w(q)
    return None


