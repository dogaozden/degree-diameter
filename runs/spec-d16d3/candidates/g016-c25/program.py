# ----------------------------------------------------------------------------
# Arc-extended projective plane incidence graphs (diameter 3).
#
# Start from the incidence graph of PG(2, q) (points 0..m-1, lines m..2m-1).
# Every old vertex has degree q+1, so with d >= q+1 it has spare capacity
# s = d - q - 1. Choose a point set S such that every line contains at most s
# points of S and every point lies on at most s lines indexed by S. For each P
# in S add a new A-vertex joined to all q+1 lines through P; for each j in S add
# a new B-vertex joined to all q+1 points on line j. Diameter stays 3.
# ----------------------------------------------------------------------------

def _pg_data(q):
    """Return (m, edges, point_lines, line_points, index, pts) for PG(2, q)."""
    pts = lib.projective_points(q)
    n2, edges = lib.projective_plane_incidence(q)
    m = n2 // 2
    point_lines = [[] for _ in range(m)]
    line_points = [[] for _ in range(m)]
    for u, v in edges:
        point_lines[u].append(v - m)
        line_points[v - m].append(u)
    index = {p: i for i, p in enumerate(pts)}
    return m, edges, point_lines, line_points, index, pts


def _loads_ok(S, s, m, point_lines, line_points):
    """True if every line holds <= s points of S and every point lies on <= s lines indexed by S."""
    cl = [0] * m
    cp = [0] * m
    for P in S:
        for L in point_lines[P]:
            cl[L] += 1
        for Q in line_points[P]:
            cp[Q] += 1
    return max(cl, default=0) <= s and max(cp, default=0) <= s


def _greedy_arc(m, s, point_lines, line_points, rng, trials, deadline):
    """Randomized greedy choice of S with all loads <= s; returns the largest found."""
    best = []
    order = list(range(m))
    for _ in range(trials):
        if time.monotonic() > deadline:
            break
        rng.shuffle(order)
        cl = [0] * m
        cp = [0] * m
        S = []
        for P in order:
            if all(cl[L] < s for L in point_lines[P]) and all(cp[Q] < s for Q in line_points[P]):
                S.append(P)
                for L in point_lines[P]:
                    cl[L] += 1
                for Q in line_points[P]:
                    cp[Q] += 1
        if len(S) > len(best):
            best = S
    return best


def _conic_set(q, index, F):
    """Conic (plus nucleus for even q) as a point-index set: an arc with no three collinear."""
    S = [index[(1, t, F.mul(t, t))] for t in range(q)]
    S.append(index[(0, 0, 1)])
    if q % 2 == 0:
        S.append(index[(0, 1, 0)])
    return S


def _arc_graph(m, edges, point_lines, line_points, S):
    """Build the extended graph: old PG incidence plus a new A and a new B vertex per element of S."""
    k = len(S)
    n = 2 * m + 2 * k
    E = list(edges)
    for t, P in enumerate(S):
        x = 2 * m + t
        for L in point_lines[P]:
            E.append((x, m + L))
    for t, j in enumerate(S):  # S is also a set of line indices (same vectors)
        b = 2 * m + k + t
        for Q in line_points[j]:
            E.append((Q, b))
    return n, E


def _arc_extensions(d, deadline, rng):
    """Return (n, edges) candidates for each prime power q with q + 1 <= d."""
    out = []
    for q in range(2, min(d - 1, 23) + 1):
        if not lib.is_prime_power(q):
            continue
        if time.monotonic() > deadline:
            break
        s = d - q - 1
        m, edges, point_lines, line_points, index, pts = _pg_data(q)
        cands = []
        if s >= 1:
            cands.append(_greedy_arc(m, s, point_lines, line_points, rng, 40, deadline))
        if s >= 2:
            F = lib.GF(q)
            cs = _conic_set(q, index, F)
            if _loads_ok(cs, s, m, point_lines, line_points):
                cands.append(cs)
        S = max(cands, key=len, default=[])
        if not _loads_ok(S, s, m, point_lines, line_points):
            continue
        n_c, e_c = _arc_graph(m, edges, point_lines, line_points, S)
        out.append((n_c, e_c))
    return out


# ----------------------------------------------------------------------------
# NEW: repair search that inserts one X-vertex and one Y-vertex into a valid
# diameter-3 bipartite graph with max degree d.
#
# State: graph on n0+2 vertices, with x = n0 (colour 0) and y = n0+1 (colour 1)
# joined to each other. A move picks a colour-0 vertex u and colour-1 vertex v
# that are not adjacent, removes one random edge at u and at v if either is
# full, then adds u-v. Degrees stay <= d and the graph stays bipartite. The cost
# is the number of vertex pairs at distance > D (lib.bad_pairs). Simulated
# annealing accepts or reverts each move.
# ----------------------------------------------------------------------------

def _two_color(n, adj):
    """Proper 2-colouring of a graph given as adjacency sets; None if not bipartite."""
    col = [-1] * n
    for s in range(n):
        if col[s] != -1:
            continue
        col[s] = 0
        stack = [s]
        while stack:
            u = stack.pop()
            for v in adj[u]:
                if col[v] == -1:
                    col[v] = 1 - col[u]
                    stack.append(v)
                elif col[v] == col[u]:
                    return None
    return col


def _extend_by_repair(n0, E0, d, D, deadline, rng):
    """Try to insert two vertices into the graph (n0, E0); return (n, edges) if valid, else None."""
    n = n0 + 2
    x, y = n0, n0 + 1
    adj = [set() for _ in range(n)]
    for u, v in E0:
        adj[u].add(v)
        adj[v].add(u)
    col = _two_color(n0, adj)
    if col is None:
        return None
    col = col + [0, 1]
    adj[x].add(y)
    adj[y].add(x)
    zeros = [v for v in range(n) if col[v] == 0]
    ones = [v for v in range(n) if col[v] == 1]

    def edges_now():
        return [(u, v) for u in range(n) for v in adj[u] if u < v]

    cur = lib.bad_pairs(n, edges_now(), D)
    T = 1.5
    while cur > 0 and time.monotonic() < deadline:
        u = rng.choice(zeros)
        v = rng.choice(ones)
        if v in adj[u]:
            continue
        undo = []
        if len(adj[u]) >= d:
            w = rng.choice(sorted(adj[u]))
            adj[u].discard(w)
            adj[w].discard(u)
            undo.append((u, w))
        if len(adj[v]) >= d:
            z = rng.choice(sorted(adj[v]))
            adj[z].discard(v)
            adj[v].discard(z)
            undo.append((z, v))
        adj[u].add(v)
        adj[v].add(u)
        c2 = lib.bad_pairs(n, edges_now(), D)
        if c2 <= cur or rng.random() < math.exp(-(c2 - cur) / T):
            cur = c2
        else:
            adj[u].discard(v)
            adj[v].discard(u)
            for a, b in undo:
                adj[a].add(b)
                adj[b].add(a)
        T = max(0.2, T * 0.9995)
    if cur == 0:
        return n, edges_now()
    return None


