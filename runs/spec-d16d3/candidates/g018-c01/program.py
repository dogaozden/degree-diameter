"""Arc-extended projective plane graphs plus a validated clone-augmentation search (D = 3).

Base: incidence graph of PG(2, q) with q the largest usable prime power, plus a new
A-vertex per point of an arc S and a new B-vertex per line of S. For d = 16 this is
q = 13 with a conic S of size 14, giving the record order 394.

Bold step (D = 3, d >= 8): clone old vertices. A clone of an old vertex v copies
v's point/line neighbourhood. Each neighbour w is used directly if it has spare
degree, otherwise it is itself cloned (the copy takes w's neighbourhood). Every
candidate is checked with lib.is_valid and kept only if valid. Beating the record
needs a construction this search may not find. If it does not, the 394 base is
returned unchanged.
"""
import math
import random
import time

import lib


# ----------------------------------------------------------------------------
# Projective plane and arc-extension baseline (D = 3).
# ----------------------------------------------------------------------------

def _pg_data(q):
    """Return (m, edges, point_lines, line_points, index, pts) for PG(2, q)."""
    pts = lib.projective_points(q)
    n2, edges = lib.projective_plane_incidence(q)
    m = n2 // 2
    point_lines = [[] for _ in range(m)]
    line_points = [[] for _ in range(m)]
    for u, v in edges:
        point_lines[u].append(v - m)
        line_points[v - m].append(u)
    index = {p: i for i, p in enumerate(pts)}
    return m, edges, point_lines, line_points, index, pts


def _loads_ok(S, s, m, point_lines, line_points):
    """True if every line holds <= s points of S and every point lies on <= s lines indexed by S."""
    cl = [0] * m
    cp = [0] * m
    for P in S:
        for L in point_lines[P]:
            cl[L] += 1
        for Q in line_points[P]:
            cp[Q] += 1
    return max(cl, default=0) <= s and max(cp, default=0) <= s


def _greedy_arc(m, s, point_lines, line_points, rng, trials, deadline):
    """Randomized greedy choice of S with all loads <= s; returns the largest found."""
    best = []
    order = list(range(m))
    for _ in range(trials):
        if time.monotonic() > deadline:
            break
        rng.shuffle(order)
        cl = [0] * m
        cp = [0] * m
        S = []
        for P in order:
            if all(cl[L] < s for L in point_lines[P]) and all(cp[Q] < s for Q in line_points[P]):
                S.append(P)
                for L in point_lines[P]:
                    cl[L] += 1
                for Q in line_points[P]:
                    cp[Q] += 1
        if len(S) > len(best):
            best = S
    return best


def _conic_set(q, index, F):
    """Conic (plus nucleus for even q) as a point-index set: an arc with no three collinear."""
    S = [index[(1, t, F.mul(t, t))] for t in range(q)]
    S.append(index[(0, 0, 1)])
    if q % 2 == 0:
        S.append(index[(0, 1, 0)])
    return S


def _arc_graph(m, edges, point_lines, line_points, S):
    """PG incidence plus a new A-vertex per point of S (joined to its lines) and a new B-vertex per line of S."""
    k = len(S)
    n = 2 * m + 2 * k
    E = list(edges)
    for t, P in enumerate(S):
        x = 2 * m + t
        for L in point_lines[P]:
            E.append((x, m + L))
    for t, j in enumerate(S):
        b = 2 * m + k + t
        for Q in line_points[j]:
            E.append((Q, b))
    return n, E


def _best_arc(d, deadline, rng):
    """Return (n, edges, geo) for the best arc-extended graph over admissible q, or None."""
    best = None
    for q in range(2, min(d - 1, 23) + 1):
        if not lib.is_prime_power(q):
            continue
        if best is not None and time.monotonic() > deadline:
            break
        m, edges, point_lines, line_points, index, pts = _pg_data(q)
        s = d - q - 1
        cands = []
        if s >= 1:
            cands.append(_greedy_arc(m, s, point_lines, line_points, rng, 40, deadline))
        if s >= 2:
            F = lib.GF(q)
            cs = _conic_set(q, index, F)
            if _loads_ok(cs, s, m, point_lines, line_points):
                cands.append(cs)
        S = max(cands, key=len, default=[])
        if not _loads_ok(S, s, m, point_lines, line_points):
            continue
        n_c, e_c = _arc_graph(m, edges, point_lines, line_points, S)
        if best is None or n_c > best[0]:
            best = (n_c, e_c, (m, point_lines, line_points))
    return best


# ----------------------------------------------------------------------------
# Clone augmentation (D = 3). Only new vertices are appended, so old labels stay fixed.
# ----------------------------------------------------------------------------

def _clone_plan(v0, x, nxt, N0, deg, d):
    """Edges for a clone x of old vertex v0, or None if degree capacity is exceeded.

    Each neighbour w of v0 is used directly when it has spare degree. Otherwise w is
    cloned: a new vertex c takes N0[w] as its neighbourhood and is joined to x.
    Returns (pending_edges, next_free_id) or None.
    """
    if len(N0[v0]) > d:
        return None
    inc = {}
    pending = []
    for w in N0[v0]:
        if deg[w] + inc.get(w, 0) < d:
            inc[w] = inc.get(w, 0) + 1
            pending.append((x, w))
            continue
        if len(N0[w]) > d:
            return None
        for u in N0[w]:
            if deg[u] + inc.get(u, 0) >= d:
                return None
        c = nxt
        nxt += 1
        for u in N0[w]:
            inc[u] = inc.get(u, 0) + 1
            pending.append((c, u))
        pending.append((x, c))
    return pending, nxt


def _augment(n, E, geo, d, D, deadline, rng):
    """Greedily add validated clones of old vertices until the deadline. Returns (n, E)."""
    m, point_lines, line_points = geo
    N0 = [[m + L for L in point_lines[P]] for P in range(m)]
    N0 += [list(line_points[L]) for L in range(m)]
    deg = [0] * n
    for u, v in E:
        deg[u] += 1
        deg[v] += 1
    while time.monotonic() < deadline:
        v0 = rng.randrange(2 * m)
        plan = _clone_plan(v0, n, n + 1, N0, deg, d)
        if plan is None:
            continue
        pending, n2 = plan
        E2 = E + pending
        if not lib.is_valid(n2, E2, d, D):
            continue
        deg.extend([0] * (n2 - len(deg)))
        for u, v in pending:
            deg[u] += 1
            deg[v] += 1
        n, E = n2, E2
    return n, E


# ----------------------------------------------------------------------------
# Generalized quadrangle baseline (D = 4).
# ----------------------------------------------------------------------------

def _gq_w(q):
    """Incidence graph of points and lines of the generalized quadrangle W(q); diameter 4."""
    F = lib.GF(q)
    pts = [v for v in itertools.product(range(q), repeat=4)
           if any(v) and next(c for c in v if c) == 1]
    index = {v: i for i, v in enumerate(pts)}
    P = len(pts)

    def norm(v):
        c = next(x for x in v if x)
        inv = F.inv(c)
        return tuple(F.mul(inv, x) for x in v)

    def form(x, y):
        t = F.sub(F.mul(x[0], y[1]), F.mul(x[1], y[0]))
        return F.add(t, F.sub(F.mul(x[2], y[3]), F.mul(x[3], y[2])))

    covered = set()
    lines = []
    for i in range(P):
        x = pts[i]
        for j in range(i + 1, P):
            if (i, j) in covered:
                continue
            y = pts[j]
            if form(x, y) != 0:
                continue
            L = set()
            for a in range(q):
                for b in range(q):
                    if a == 0 and b == 0:
                        continue
                    v = tuple(F.add(F.mul(a, x[k]), F.mul(b, y[k])) for k in range(4))
                    if any(v):
                        L.add(index[norm(v)])
            L = sorted(L)
            lines.append(L)
            for p in L:
                for r in L:
                    if p < r:
                        covered.add((p, r))

    edges = []
    for j, L in enumerate(lines):
        for p in L:
            edges.append((p, P + j))
    return 2 * P, edges


def _best_gq(d):
    """W(q) for the largest prime power q with q + 1 <= d, restricted to small q for speed."""
    for q in range(min(d - 1, 9), 1, -1):
        if lib.is_prime_power(q):
            return _gq_w(q)
    return None


