import itertools
import math
import random
import time

import lib


# ----------------------------------------------------------------------------
# Arc-extended projective plane incidence graphs (diameter 3).
#
# Start from the incidence graph of PG(2, q). Every old vertex has degree q+1,
# so with d >= q+1 it has spare capacity s = d - q - 1. Choose a point set S
# with every line holding <= s points of S and every point on <= s lines of S.
# For each P in S add a new A-vertex joined to the q+1 lines through P; for each
# j in S add a new B-vertex joined to the q+1 points on line j.
# Order is 2(q^2+q+1) + 2|S|.
# ----------------------------------------------------------------------------

def _pg_data(q):
    """Return (m, edges, point_lines, line_points, index, pts) for PG(2, q)."""
    pts = lib.projective_points(q)
    n2, edges = lib.projective_plane_incidence(q)
    m = n2 // 2
    point_lines = [[] for _ in range(m)]
    line_points = [[] for _ in range(m)]
    for u, v in edges:
        point_lines[u].append(v - m)
        line_points[v - m].append(u)
    index = {p: i for i, p in enumerate(pts)}
    return m, edges, point_lines, line_points, index, pts


def _loads_ok(S, s, m, point_lines, line_points):
    """True if every line holds <= s points of S and every point lies on <= s lines indexed by S."""
    cl = [0] * m
    cp = [0] * m
    for P in S:
        for L in point_lines[P]:
            cl[L] += 1
        for Q in line_points[P]:
            cp[Q] += 1
    return max(cl, default=0) <= s and max(cp, default=0) <= s


def _greedy_arc(m, s, point_lines, line_points, rng, trials, deadline):
    """Randomized greedy choice of S with all loads <= s; returns the largest found."""
    best = []
    order = list(range(m))
    for _ in range(trials):
        if time.monotonic() > deadline:
            break
        rng.shuffle(order)
        cl = [0] * m
        cp = [0] * m
        S = []
        for P in order:
            if all(cl[L] < s for L in point_lines[P]) and all(cp[Q] < s for Q in line_points[P]):
                S.append(P)
                for L in point_lines[P]:
                    cl[L] += 1
                for Q in line_points[P]:
                    cp[Q] += 1
        if len(S) > len(best):
            best = S
    return best


def _conic_set(q, index, F):
    """Conic (plus nucleus for even q) as a point-index set: an arc with no three collinear."""
    S = [index[(1, t, F.mul(t, t))] for t in range(q)]
    S.append(index[(0, 0, 1)])
    if q % 2 == 0:
        S.append(index[(0, 1, 0)])
    return S


_LP = None  # line_points for the current q, set in _arc_extensions


def _arc_graph(m, edges, point_lines, S):
    """Build the extended graph: old PG incidence plus a new A and a new B vertex per element of S."""
    k = len(S)
    n = 2 * m + 2 * k
    E = list(edges)
    for t, P in enumerate(S):
        x = 2 * m + t
        for L in point_lines[P]:
            E.append((x, m + L))
    for t, j in enumerate(S):
        b = 2 * m + k + t
        for Q in _LP[j]:
            E.append((Q, b))
    return n, E


def _arc_extensions(d, deadline, rng):
    """Return (n, edges) candidates for each prime power q with q + 1 <= d."""
    global _LP
    out = []
    for q in range(2, min(d - 1, 23) + 1):
        if not lib.is_prime_power(q):
            continue
        if time.monotonic() > deadline:
            break
        s = d - q - 1
        m, edges, point_lines, line_points, index, pts = _pg_data(q)
        _LP = line_points
        cands = []
        if s >= 1:
            cands.append(_greedy_arc(m, s, point_lines, line_points, rng, 40, deadline))
        if s >= 2:
            F = lib.GF(q)
            cs = _conic_set(q, index, F)
            if _loads_ok(cs, s, m, point_lines, line_points):
                cands.append(cs)
        S = max(cands, key=len, default=[])
        if not _loads_ok(S, s, m, point_lines, line_points):
            continue
        n_c, e_c = _arc_graph(m, edges, point_lines, S)
        out.append((n_c, e_c))
    return out


# ----------------------------------------------------------------------------
# Growth by local search: add one vertex at a time to a valid diameter-3
# bipartite graph, then repair with degree-preserving double-edge swaps,
# edge additions and edge removals, minimizing the number of pairs at
# distance > 3 (simulated annealing).
# ----------------------------------------------------------------------------

def _two_color(n, edges):
    """Bipartition colours (0/1) of a bipartite graph."""
    adj = lib.adjacency(n, edges)
    side = [-1] * n
    for s in range(n):
        if side[s] != -1:
            continue
        side[s] = 0
        stack = [s]
        while stack:
            u = stack.pop()
            for v in adj[u]:
                if side[v] == -1:
                    side[v] = 1 - side[u]
                    stack.append(v)
    return side


def _bad_count(n, adj, D):
    """Ordered count of vertex pairs at distance > D, using bitset balls."""
    reach = [1 << v for v in range(n)]
    for _ in range(D):
        new = [0] * n
        for v in range(n):
            r = reach[v]
            for u in adj[v]:
                r |= reach[u]
            new[v] = r
        reach = new
    return sum(n - r.bit_count() for r in reach)


def _sa_add_vertex(n, edges, side, new_side, d, D, deadline, rng):
    """Try to add one vertex of colour new_side and repair. Returns (n+1, edges, side) or None."""
    N = n + 1
    side2 = list(side) + [new_side]
    adj = [set() for _ in range(N)]
    deg = [0] * N
    el = []
    pos = {}

    def add_e(e):
        a, b = e
        pos[e] = len(el)
        el.append(e)
        adj[a].add(b)
        adj[b].add(a)
        deg[a] += 1
        deg[b] += 1

    def rem_e(e):
        i = pos.pop(e)
        last = el.pop()
        if i < len(el):
            el[i] = last
            pos[last] = i
        a, b = e
        adj[a].discard(b)
        adj[b].discard(a)
        deg[a] -= 1
        deg[b] -= 1

    for u, v in edges:
        e = (u, v) if side2[u] == 0 else (v, u)
        add_e(e)

    S0 = [v for v in range(N) if side2[v] == 0]
    S1 = [v for v in range(N) if side2[v] == 1]
    opposite = S1 if new_side == 0 else S0
    if not any(deg[v] < d for v in opposite):
        return None

    cost = _bad_count(N, adj, D)
    T = 1.0
    while cost > 0:
        if time.monotonic() > deadline:
            return None
        T = max(0.1, T * 0.999)
        r = rng.random()
        ops = None
        if r < 0.5 and len(el) >= 2:
            i = rng.randrange(len(el))
            j = rng.randrange(len(el))
            (u1, v1) = el[i]
            (u2, v2) = el[j]
            if u1 == u2 or v1 == v2 or v2 in adj[u1] or v1 in adj[u2]:
                continue
            ops = [(0, (u1, v1)), (0, (u2, v2)), (1, (u1, v2)), (1, (u2, v1))]
        elif r < 0.85:
            u = rng.choice(S0)
            v = rng.choice(S1)
            if deg[u] >= d or deg[v] >= d or v in adj[u]:
                continue
            ops = [(1, (u, v))]
        else:
            if not el:
                continue
            ops = [(0, el[rng.randrange(len(el))])]

        for kind, e in ops:
            if kind == 0:
                rem_e(e)
            else:
                add_e(e)
        c2 = _bad_count(N, adj, D)
        if c2 <= cost or rng.random() < math.exp(-(c2 - cost) / T):
            cost = c2
        else:
            for kind, e in reversed(ops):
                if kind == 0:
                    add_e(e)
                else:
                    rem_e(e)

    return N, list(el), side2


def _grow(n0, e0, d, D, deadline, rng):
    """Repeatedly add a vertex with local repair while possible. Returns (n, edges) or None."""
    side = _two_color(n0, e0)
    n, edges = n0, list(e0)
    grew = False
    while time.monotonic() < deadline:
        step_deadline = min(deadline, time.monotonic() + 8.0)
        new_side = rng.randrange(2)
        res = _sa_add_vertex(n, edges, side, new_side, d, D, step_deadline, rng)
        if res is None:
            break
        n, edges, side = res
        grew = True
    return (n, edges) if grew else None


# ----------------------------------------------------------------------------
# Generalized quadrangle baseline (D = 4).
# ----------------------------------------------------------------------------

def _gq_w(q):
    """Incidence graph of points and lines of the generalized quadrangle W(q); diameter 4."""
    F = lib.GF(q)
    pts = [v for v in itertools.product(range(q), repeat=4)
           if any(v) and next(c for c in v if c) == 1]
    index = {v: i for i, v in enumerate(pts)}
    P = len(pts)

    def norm(v):
        c = next(x for x in v if x)
        inv = F.inv(c)
        return tuple(F.mul(inv, x) for x in v)

    def form(x, y):
        t = F.sub(F.mul(x[0], y[1]), F.mul(x[1], y[0]))
        return F.add(t, F.sub(F.mul(x[2], y[3]), F.mul(x[3], y[2])))

    covered = set()
    lines = []
    for i in range(P):
        x = pts[i]
        for j in range(i + 1, P):
            if (i, j) in covered:
                continue
            y = pts[j]
            if form(x, y) != 0:
                continue
            L = set()
            for a in range(q):
                for b in range(q):
                    if a == 0 and b == 0:
                        continue
                    v = tuple(F.add(F.mul(a, x[k]), F.mul(b, y[k])) for k in range(4))
                    if any(v):
                        L.add(index[norm(v)])
            L = sorted(L)
            lines.append(L)
            for p in L:
                for r in L:
                    if p < r:
                        covered.add((p, r))

    edges = []
    for j, L in enumerate(lines):
        for p in L:
            edges.append((p, P + j))
    return 2 * P, edges


def _best_gq(d):
    """W(q) for the largest prime power q with q + 1 <= d, restricted to small q for speed."""
    for q in range(min(d - 1, 9), 1, -1):
        if lib.is_prime_power(q):
            return _gq_w(q)
    return None


