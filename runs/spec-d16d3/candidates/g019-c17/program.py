import itertools
import math
import random
import time

import lib


# ----------------------------------------------------------------------------
# Arc-extended projective plane graphs (diameter 3).
#
# Start from the incidence graph of PG(2, q). Each old vertex has degree q+1,
# so with d >= q+1 it has spare capacity s = d-q-1. Choose a point set S such
# that every line holds at most s points of S and every point lies on at most
# s lines indexed by S. Add an A-vertex for each P in S (joined to the q+1 lines
# through P) and a B-vertex for each j in S (joined to the q+1 points on j).
#
# NEW in this version: S is found by a plateau local search (one-for-one swaps
# plus free insertions) instead of only random greedy restarts, and the
# candidate list also includes the conic / hyperoval for s >= 2.
#
# Why 394 is locally tight for d=16, q=13: any new X-side vertex must reach
# every old point within distance 2, so its line neighbourhood must cover all
# points of PG(2,13). A line cover of size <= 16 is a dual blocking set of size
# <= 16, and for prime q=13 a blocking set of size < 21 contains a full line.
# So every new X-vertex is a pencil through some point, which is exactly the
# A-vertex of the construction. The only freedom left is the choice of S.
# ----------------------------------------------------------------------------


def _pg(q):
    """Return (m, edges, point_lines, line_points, index, pts) for PG(2, q)."""
    pts = lib.projective_points(q)
    n2, edges = lib.projective_plane_incidence(q)
    m = n2 // 2
    point_lines = [[] for _ in range(m)]
    line_points = [[] for _ in range(m)]
    for u, v in edges:
        point_lines[u].append(v - m)
        line_points[v - m].append(u)
    index = {p: i for i, p in enumerate(pts)}
    return m, edges, point_lines, line_points, index, pts


def _loads_ok(S, s, m, point_lines, line_points):
    """True if every line holds <= s points of S and every point lies on <= s lines indexed by S."""
    cl = [0] * m
    cp = [0] * m
    for P in S:
        for L in point_lines[P]:
            cl[L] += 1
        for Q in line_points[P]:
            cp[Q] += 1
    return max(cl, default=0) <= s and max(cp, default=0) <= s


def _local_arc(m, s, point_lines, line_points, rng, deadline, iters):
    """Plateau local search for a large S with all loads <= s.

    Free insertions are always taken. A candidate whose insertion would
    overload at most one member of S is accepted as a swap (so the size is
    kept). Every move is checked and reverted if it breaks feasibility.
    """
    pl = [set(x) for x in point_lines]
    lp = [set(x) for x in line_points]
    cl = [0] * m
    cp = [0] * m
    S = set()

    def fits(P):
        return all(cl[L] < s for L in point_lines[P]) and all(cp[Q] < s for Q in line_points[P])

    def add(P):
        S.add(P)
        for L in point_lines[P]:
            cl[L] += 1
        for Q in line_points[P]:
            cp[Q] += 1

    def drop(P):
        S.discard(P)
        for L in point_lines[P]:
            cl[L] -= 1
        for Q in line_points[P]:
            cp[Q] -= 1

    order = list(range(m))
    rng.shuffle(order)
    for P in order:
        if fits(P):
            add(P)
    best = list(S)

    for it in range(iters):
        if (it & 63) == 0 and time.monotonic() > deadline:
            break
        P = rng.randrange(m)
        if P in S:
            continue
        conf = set()
        for L in point_lines[P]:
            if cl[L] >= s:
                conf.update(x for x in S if L in pl[x])
        for Q in line_points[P]:
            if cp[Q] >= s:
                conf.update(x for x in S if Q in lp[x])
        if len(conf) == 0:
            add(P)
        elif len(conf) == 1 or (len(conf) == 2 and rng.random() < 0.05):
            removed = list(conf)
            for x in removed:
                drop(x)
            if fits(P):
                add(P)
            else:
                for x in removed:
                    add(x)
        if len(S) > len(best):
            best = list(S)
    return best


def _conic_set(q, index, F):
    """Conic (plus nucleus for even q): an arc with no three collinear."""
    S = [index[(1, t, F.mul(t, t))] for t in range(q)]
    S.append(index[(0, 0, 1)])
    if q % 2 == 0:
        S.append(index[(0, 1, 0)])
    return S


def _arc_graph(m, edges, point_lines, line_points, S):
    """Old PG incidence plus a new A and a new B vertex per element of S."""
    k = len(S)
    n = 2 * m + 2 * k
    E = list(edges)
    for t, P in enumerate(S):
        x = 2 * m + t
        for L in point_lines[P]:
            E.append((x, m + L))
    for t, j in enumerate(S):
        b = 2 * m + k + t
        for Q in line_points[j]:
            E.append((Q, b))
    return n, E


def _arc_candidates(d, deadline, rng):
    """(n, edges) candidates for each prime power q with q + 1 <= d and s >= 1."""
    out = []
    for q in range(2, min(d - 1, 23) + 1):
        if not lib.is_prime_power(q):
            continue
        if time.monotonic() > deadline:
            break
        s = d - q - 1
        if s < 1:
            continue
        m, edges, point_lines, line_points, index, pts = _pg(q)
        cands = [_local_arc(m, s, point_lines, line_points, rng, deadline, 6000)]
        if s >= 2:
            F = lib.GF(q)
            cs = _conic_set(q, index, F)
            if _loads_ok(cs, s, m, point_lines, line_points):
                cands.append(cs)
        S = max(cands, key=len, default=[])
        if not S or not _loads_ok(S, s, m, point_lines, line_points):
            continue
        out.append(_arc_graph(m, edges, point_lines, line_points, S))
    return out


# ----------------------------------------------------------------------------
# Generalized quadrangle W(q) (D = 4), small q only for speed.
# ----------------------------------------------------------------------------

def _gq_w(q):
    """Incidence graph of points and lines of W(q); diameter 4."""
    F = lib.GF(q)
    pts = [v for v in itertools.product(range(q), repeat=4)
           if any(v) and next(c for c in v if c) == 1]
    index = {v: i for i, v in enumerate(pts)}
    P = len(pts)

    def norm(v):
        c = next(x for x in v if x)
        inv = F.inv(c)
        return tuple(F.mul(inv, x) for x in v)

    def form(x, y):
        t = F.sub(F.mul(x[0], y[1]), F.mul(x[1], y[0]))
        return F.add(t, F.sub(F.mul(x[2], y[3]), F.mul(x[3], y[2])))

    covered = set()
    lines = []
    for i in range(P):
        x = pts[i]
        for j in range(i + 1, P):
            if (i, j) in covered:
                continue
            y = pts[j]
            if form(x, y) != 0:
                continue
            L = set()
            for a in range(q):
                for b in range(q):
                    if a == 0 and b == 0:
                        continue
                    v = tuple(F.add(F.mul(a, x[k]), F.mul(b, y[k])) for k in range(4))
                    if any(v):
                        L.add(index[norm(v)])
            L = sorted(L)
            lines.append(L)
            for p in L:
                for r in L:
                    if p < r:
                        covered.add((p, r))

    edges = []
    for j, L in enumerate(lines):
        for p in L:
            edges.append((p, P + j))
    return 2 * P, edges


def _best_gq(d):
    for q in range(min(d - 1, 7), 1, -1):
        if lib.is_prime_power(q):
            return _gq_w(q)
    return None


