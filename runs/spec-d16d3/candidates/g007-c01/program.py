import itertools
import math
import random
import time

import lib


# ----------------------------------------------------------------------------
# Arc-extended projective plane incidence graphs (diameter 3).
#
# Start from the incidence graph of PG(2, q). Each old vertex has degree q+1,
# so with d >= q+1 it has spare capacity s = d - q - 1. Choose S with every
# line holding <= s points of S (and dually). Add an A-vertex per P in S joined
# to the lines through P, and a B-vertex per j in S joined to the points on j.
# ----------------------------------------------------------------------------

def _pg_data(q):
    """Return (m, edges, point_lines, line_points, index, pts) for PG(2, q)."""
    pts = lib.projective_points(q)
    n2, edges = lib.projective_plane_incidence(q)
    m = n2 // 2
    point_lines = [[] for _ in range(m)]
    line_points = [[] for _ in range(m)]
    for u, v in edges:
        point_lines[u].append(v - m)
        line_points[v - m].append(u)
    index = {p: i for i, p in enumerate(pts)}
    return m, edges, point_lines, line_points, index, pts


def _loads_ok(S, s, m, point_lines, line_points):
    """True if every line holds <= s points of S and every point lies on <= s lines indexed by S."""
    cl = [0] * m
    cp = [0] * m
    for P in S:
        for L in point_lines[P]:
            cl[L] += 1
        for Q in line_points[P]:
            cp[Q] += 1
    return max(cl, default=0) <= s and max(cp, default=0) <= s


def _greedy_arc(m, s, point_lines, line_points, rng, trials, deadline):
    """Randomized greedy choice of S with all loads <= s; returns the largest found."""
    best = []
    order = list(range(m))
    for _ in range(trials):
        if time.monotonic() > deadline:
            break
        rng.shuffle(order)
        cl = [0] * m
        cp = [0] * m
        S = []
        for P in order:
            if all(cl[L] < s for L in point_lines[P]) and all(cp[Q] < s for Q in line_points[P]):
                S.append(P)
                for L in point_lines[P]:
                    cl[L] += 1
                for Q in line_points[P]:
                    cp[Q] += 1
        if len(S) > len(best):
            best = S
    return best


def _conic_set(q, index, F):
    """Conic (plus nucleus for even q) as a point-index set: an arc with no three collinear."""
    S = [index[(1, t, F.mul(t, t))] for t in range(q)]
    S.append(index[(0, 0, 1)])
    if q % 2 == 0:
        S.append(index[(0, 1, 0)])
    return S


def _arc_graph(m, edges, point_lines, S, line_points):
    """Build the extended graph: old PG incidence plus a new A and a new B vertex per element of S."""
    k = len(S)
    n = 2 * m + 2 * k
    E = list(edges)
    for t, P in enumerate(S):
        x = 2 * m + t
        for L in point_lines[P]:
            E.append((x, m + L))
    for t, j in enumerate(S):
        b = 2 * m + k + t
        for Q in line_points[j]:
            E.append((Q, b))
    return n, E


def _arc_extensions(d, deadline, rng):
    """Return (n, edges) candidates for each prime power q with q + 1 <= d."""
    out = []
    for q in range(2, min(d - 1, 23) + 1):
        if not lib.is_prime_power(q):
            continue
        if time.monotonic() > deadline:
            break
        s = d - q - 1
        m, edges, point_lines, line_points, index, pts = _pg_data(q)
        cands = []
        if s >= 1:
            cands.append(_greedy_arc(m, s, point_lines, line_points, rng, 40, deadline))
        if s >= 2:
            F = lib.GF(q)
            cs = _conic_set(q, index, F)
            if _loads_ok(cs, s, m, point_lines, line_points):
                cands.append(cs)
        S = max(cands, key=len, default=[])
        if not _loads_ok(S, s, m, point_lines, line_points):
            continue
        n_c, e_c = _arc_graph(m, edges, point_lines, S, line_points)
        out.append((n_c, e_c))
    return out


# ----------------------------------------------------------------------------
# Generalized quadrangle baseline (D = 4).
# ----------------------------------------------------------------------------

def _gq_w(q):
    """Incidence graph of points and lines of the generalized quadrangle W(q); diameter 4."""
    F = lib.GF(q)
    pts = [v for v in itertools.product(range(q), repeat=4)
           if any(v) and next(c for c in v if c) == 1]
    index = {v: i for i, v in enumerate(pts)}
    P = len(pts)

    def norm(v):
        c = next(x for x in v if x)
        inv = F.inv(c)
        return tuple(F.mul(inv, x) for x in v)

    def form(x, y):
        t = F.sub(F.mul(x[0], y[1]), F.mul(x[1], y[0]))
        return F.add(t, F.sub(F.mul(x[2], y[3]), F.mul(x[3], y[2])))

    covered = set()
    lines = []
    for i in range(P):
        x = pts[i]
        for j in range(i + 1, P):
            if (i, j) in covered:
                continue
            y = pts[j]
            if form(x, y) != 0:
                continue
            L = set()
            for a in range(q):
                for b in range(q):
                    if a == 0 and b == 0:
                        continue
                    v = tuple(F.add(F.mul(a, x[k]), F.mul(b, y[k])) for k in range(4))
                    if any(v):
                        L.add(index[norm(v)])
            L = sorted(L)
            lines.append(L)
            for p in L:
                for r in L:
                    if p < r:
                        covered.add((p, r))

    edges = []
    for j, L in enumerate(lines):
        for p in L:
            edges.append((p, P + j))
    return 2 * P, edges


def _best_gq(d):
    """W(q) for the largest prime power q with q + 1 <= d, restricted to small q for speed."""
    for q in range(min(d - 1, 9), 1, -1):
        if lib.is_prime_power(q):
            return _gq_w(q)
    return None


# ----------------------------------------------------------------------------
# Vertex growth by simulated annealing (diameter 3, bipartite, degree <= d).
#
# Given a valid graph, add one new vertex on one side and anneal the edge set
# with degree-preserving 2-switches, edge moves and edge additions, minimising
# the number of vertex pairs at distance > D. Success gives a larger valid graph.
# ----------------------------------------------------------------------------

def _bad_count(nb, n, D):
    """Number of unordered vertex pairs at distance > D (bit-parallel BFS)."""
    reach = [1 << v for v in range(n)]
    for _ in range(D):
        new = []
        for v in range(n):
            r = reach[v]
            for u in nb[v]:
                r |= reach[u]
            new.append(r)
        if new == reach:
            break
        reach = new
    return sum(n - r.bit_count() for r in reach) // 2


def _colour(n, nb):
    """Proper 2-colouring of vertices 0..n-1 as a list, or None if not bipartite."""
    col = [-1] * n
    for s in range(n):
        if col[s] != -1:
            continue
        col[s] = 0
        stack = [s]
        while stack:
            u = stack.pop()
            for v in nb[u]:
                if col[v] == -1:
                    col[v] = 1 - col[u]
                    stack.append(v)
                elif col[v] == col[u]:
                    return None
    return col


def _apply(nb, rem, add):
    for u, v in rem:
        nb[u].discard(v)
        nb[v].discard(u)
    for u, v in add:
        nb[u].add(v)
        nb[v].add(u)


def _try_add_vertex(n, edges, d, D, deadline, rng):
    """Try to extend a valid graph on n vertices to n+1 vertices; return (n+1, edges) or None."""
    N = n + 1
    nb = [set() for _ in range(N)]
    for u, v in edges:
        nb[u].add(v)
        nb[v].add(u)
    col = _colour(n, nb)
    if col is None:
        return None
    options = []
    for c in (0, 1):
        cand = [v for v in range(n) if col[v] == 1 - c and len(nb[v]) < d]
        if cand:
            options.append((c, cand))
    if not options:
        return None
    c, cand = rng.choice(options)
    col.append(c)
    for v in rng.sample(cand, min(d, len(cand))):
        nb[N - 1].add(v)
        nb[v].add(N - 1)

    cost = _bad_count(nb, N, D)
    t0 = time.monotonic()
    span = max(1e-3, deadline - t0)
    while cost > 0:
        now = time.monotonic()
        if now > deadline:
            return None
        T = max(0.15, 1.0 - 0.85 * (now - t0) / span)

        rem, add = [], []
        r = rng.random()
        if r < 0.35:
            u = rng.randrange(N)
            if len(nb[u]) >= d:
                continue
            cs = [v for v in range(N) if col[v] != col[u] and len(nb[v]) < d and v not in nb[u]]
            if not cs:
                continue
            add = [(u, rng.choice(cs))]
        elif r < 0.7:
            a = rng.randrange(N)
            if not nb[a]:
                continue
            b = rng.choice(tuple(nb[a]))
            a2 = rng.randrange(N)
            if a2 == a or col[a2] != col[a] or not nb[a2]:
                continue
            b2 = rng.choice(tuple(nb[a2]))
            if b2 == b or b2 in nb[a] or b in nb[a2]:
                continue
            rem = [(a, b), (a2, b2)]
            add = [(a, b2), (a2, b)]
        else:
            a = rng.randrange(N)
            if not nb[a]:
                continue
            b = rng.choice(tuple(nb[a]))
            cs = [x for x in range(N) if col[x] == col[b] and x != b
                  and x not in nb[a] and len(nb[x]) < d]
            if not cs:
                continue
            rem = [(a, b)]
            add = [(a, rng.choice(cs))]

        _apply(nb, rem, add)
        c2 = _bad_count(nb, N, D)
        delta = c2 - cost
        if delta <= 0 or rng.random() < math.exp(-delta / T):
            cost = c2
        else:
            _apply(nb, add, rem)

    out = [(u, v) for u in range(N) for v in nb[u] if u < v]
    return N, out


def _grow(best, d, D, deadline, rng):
    """Repeatedly add vertices by annealing while successful and time remains."""
    n, e = best
    while time.monotonic() < deadline:
        res = _try_add_vertex(n, e, d, D, deadline, rng)
        if res is None:
            break
        if not lib.is_valid(res[0], res[1], d, D):
            break
        n, e = res
    return n, e


