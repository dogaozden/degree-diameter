# Driver: baselines, then voltage lifts of PG / AL bases, then the group engine.
# ----------------------------------------------------------------------------

def build(d, D, seed, time_limit):
    start = time.monotonic()
    if d < 1 or D < 1:
        return 1, []
    if D == 1:
        return 2, [(0, 1)]

    total = 0.88 * time_limit - 1.0

    def left():
        return total - (time.monotonic() - start)

    # Safe fallback: K_{d,d}, valid for D >= 2.
    best = lib.haar_graph(d, range(d))
    best_n = best[0]

    def consider(n, e):
        nonlocal best, best_n
        if n > best_n and lib.is_valid(n, e, d, D):
            best = (n, e)
            best_n = n

    if D >= 3:
        pg = _best_pg(d)
        if pg is not None:
            consider(pg[0], pg[1])

    if D >= 4 and time.monotonic() - start < 0.3 * time_limit:
        gq = _best_gq(d)
        if gq is not None:
            consider(gq[0], gq[1])

    if best_n >= lib.moore_bound(d, D):
        return best

    # Stage 1: voltage lifts of non-complete bipartite bases (PG / Araujo-Pardo-Lopez).
    bases = _lift_bases(d) if D >= 3 else []
    lift_stop = time.monotonic() + 0.4 * max(left(), 0.0)
    tried = set()
    while bases:
        room = lift_stop - time.monotonic()
        if room < 2.0:
            break
        plan = [p for p in _lift_plan(bases, d, D, best_n) if (p[1], p[2]) not in tried]
        if not plan:
            break
        _, bi, MM = plan[0]
        tried.add((bi, MM))
        n0, edges = bases[bi]
        budget = min(room, max(3.0, 0.5 * room))
        try:
            out = lib.run_c(C_LIFT, [d, D, seed, f"{budget:.2f}", MM],
                            stdin_graph=(n0, edges), timeout=budget + 10.0)
            n, e = lib.parse_graph_text(out)
            consider(n, e)
        except Exception:
            pass

    # Stage 2: group-lift annealer with the remaining budget.
    remaining = left() - 1.0
    if remaining >= 1.0:
        try:
            out = lib.run_c(C_SOURCE, [d, D, seed, f"{remaining:.2f}", best_n],
                            timeout=remaining + 10.0)
            n, e = lib.parse_graph_text(out)
            consider(n, e)
        except Exception:
            pass

    if not lib.is_valid(best[0], best[1], d, D):
        best = lib.haar_graph(d, range(d))
    return best
