def _lift_plan(bases, d, D, best_n):
    """Candidate lifts (N, base index, M) with N > best_n, smallest N first."""
    cap = lib.moore_bound(d, D)
    plan = []
    for bi, (n0, _) in enumerate(bases):
        M = best_n // n0 + 1
        for MM in (M, M + 1):
            N = n0 * MM
            if best_n < N <= cap:
                plan.append((N, bi, MM))
    plan.sort()
    return plan


