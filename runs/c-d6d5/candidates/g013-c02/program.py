# ----------------------------------------------------------------------------
# Engine 2 (unchanged from parent): voltage lifts of semidirect products
# Z_m x| Z_k over a base of K A-vertices and K B-vertices, with simulated
# annealing, breakout weights and an elite pool (ILS).
