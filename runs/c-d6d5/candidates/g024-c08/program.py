# ----------------------------------------------------------------------------
# Python: baselines, group candidates, Cayley tables.
# ----------------------------------------------------------------------------

def _best_pg(d):
    """Incidence graph of PG(2, q) for the largest prime power q with q + 1 <= d."""
    for q in range(d - 1, 1, -1):
        if lib.is_prime_power(q):
            return lib.projective_plane_incidence(q)
    return None


def _group_candidates(lo, hi, rng):
    """Group specs with order in [lo, hi]: affine groups AGL(1,q) and nonabelian semidirect Z_m x| Z_k."""
    cands = []
    for q in range(3, 40):
        if lib.is_prime_power(q) and lo <= q * (q - 1) <= hi:
            cands.append(("agl", q))
    tries = 0
    while tries < 400 and len(cands) < 80:
        tries += 1
        k = rng.randint(2, 12)
        m_lo, m_hi = max(2, lo // k), max(2, hi // k)
        if m_hi < m_lo:
            continue
        m = rng.randint(m_lo, m_hi)
        if not lo <= m * k <= hi:
            continue
        rs = [r for r in range(2, m) if math.gcd(r, m) == 1 and pow(r, k, m) == 1 % m]
        if rs:
            cands.append(("sd", m, k, rs[rng.randrange(len(rs))]))
    return cands


def _group_table(spec):
    """Cayley table of the group with identity relabelled to 0: returns (order, rows)."""
    if spec[0] == "agl":
        q = spec[1]
        F = lib.GF(q)
        elems = [(a, b) for a in range(1, q) for b in range(q)]
        index = {el: i for i, el in enumerate(elems)}

        def mul(x, y):
            a, b = elems[x]
            c, dd = elems[y]
            # f(t) = a t + b composed with g(t) = c t + dd.
            return index[(F.mul(a, c), F.add(F.mul(a, dd), b))]

        order = len(elems)
        ident = index[(1, 0)]
    else:
        _, m, k, r = spec
        order, mul, _inv = lib.semidirect_group(m, k, r)
        ident = 0
    seq = [ident] + [x for x in range(order) if x != ident]
    pos = {x: i for i, x in enumerate(seq)}
    rows = [[pos[mul(x, y)] for y in seq] for x in seq]
    return order, rows


def _table_graph(order, rows):
    """Encode a Cayley table as the stdin graph the C engine reads: n = order, edges (x*order+y, x*y)."""
    edges = [(i * order + j, rows[i][j]) for i in range(order) for j in range(order)]
    return order, edges


# ----------------------------------------------------------------------------
# Driver.
# ----------------------------------------------------------------------------

def build(d, D, seed, time_limit):
    start = time.monotonic()
    if d < 1 or D < 1:
        return 1, []
    if D == 1:
        return 2, [(0, 1)]

    # Safe fallback: K_{d,d} has diameter 2, so it is valid for D >= 2.
    best = lib.haar_graph(d, range(d))
    best_n = best[0]

    def consider(n, e):
        nonlocal best, best_n
        if n > best_n and lib.is_valid(n, e, d, D):
            best = (n, e)
            best_n = n

    if D >= 3:
        pg = _best_pg(d)
        if pg is not None:
            consider(pg[0], pg[1])

    moore = lib.moore_bound(d, D)
    if best_n >= moore:
        return best

    rng = random.Random(1000003 * seed + 97 * d + D)
    lo = max(4, moore // 12)
    hi = min(600, max(lo + 1, moore // 4))
    cands = _group_candidates(lo, hi, rng)
    rng.shuffle(cands)
    runs = min(2, len(cands))
    for idx in range(runs):
        try:
            order, rows = _group_table(cands[idx])
            gorder, edges = _table_graph(order, rows)
        except Exception:
            continue
        share = (0.88 * time_limit - (time.monotonic() - start) - 1.0) / (runs - idx)
        if share < 2.0:
            break
        try:
            out = lib.run_c(C_SOURCE, [d, D, seed + idx, f"{share:.2f}", best_n],
                            stdin_graph=(gorder, edges), timeout=share + 10.0)
            n, e = lib.parse_graph_text(out)
            consider(n, e)
        except Exception:
            pass

    if not lib.is_valid(best[0], best[1], d, D):
        best = lib.haar_graph(d, range(d))
    return best
