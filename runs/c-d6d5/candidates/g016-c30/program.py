"""Cayley-table lifts over general finite groups, searched by simulated annealing.

Idea: a bipartite graph with parts A = {i*G + g} and B = {(K+j)*G + h} is a voltage
lift over a finite group G. Dart (i, j, s) joins A_{i,g} to B_{j,g*s} for all g. Each
layer is a permutation of the K base vertices, so every vertex has degree DEG. Left
multiplication is an automorphism, so the diameter is at most D iff a BFS of depth D
from each of the 2K block representatives (identity of each block) covers everything.

Unlike the earlier metacyclic-only search, the group is an arbitrary finite group given
as a full multiplication table. Python builds these tables from several families:
affine groups Z_p^k x| <A>, unitriangular groups UT(3,p) with a diagonal extension,
dihedral groups, abelian groups and metacyclic groups. Groups are generated by
right-multiplication closure, and each table is built with numpy from a BFS tree.

C side: simulated annealing with breakout weights, plus an elite pool that is
re-annealed (iterated local search). The pool stores the group index with each
configuration. A fresh start picks a group whose order makes 2*K*G beat the current
record, biased toward smaller orders.

Fallback: K_{d,d} (diameter 2), or PG(2,q) incidence graphs for D >= 3. Every result
is checked with lib.is_valid before it is returned.
"""
import math
import random
import time

import numpy as np

import lib


# ----------------------------------------------------------------------------
# C engine: SA over voltage lifts on a group table supplied on stdin.
#
# stdin: header "1 m", then 2m integers forming a flat stream
#   [ng, G_1, table_1 (G_1*G_1 ints, row-major, entry x*G+y = x*y, identity = 0), G_2, ...]
# (the stream is padded with a 0 when its length is odd).
# argv: d D seed time_limit [start_n]
# ----------------------------------------------------------------------------

C_SOURCE = r"""
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>
#include <math.h>
#include <time.h>

#define BIGC 1000000000LL
#define ITERS 6000
#define ILS_ITERS 3000
#define POOLMAX 48
#define POOLP 0.6
#define BRK 150
#define MAXK 3
#define MAXG 512

static uint64_t rs[2];
static struct timespec T0;
static double DEADLINE;

static uint64_t splitmix(uint64_t *x) {
    uint64_t z = (*x += 0x9E3779B97F4A7C15ULL);
    z = (z ^ (z >> 30)) * 0xBF58476D1CE4E5B9ULL;
    z = (z ^ (z >> 27)) * 0x94D049BB133111EBULL;
    return z ^ (z >> 31);
}

static uint64_t rnd64(void) {
    uint64_t s1 = rs[0];
    const uint64_t s0 = rs[1];
    rs[0] = s0;
    s1 ^= s1 << 23;
    rs[1] = s1 ^ s0 ^ (s1 >> 18) ^ (s0 >> 5);
    return rs[1] + s0;
}

static int rnd_int(int n) { return (int)(rnd64() % (uint64_t)n); }
static double rnd_unit(void) { return (double)(rnd64() >> 11) * (1.0 / 9007199254740992.0); }

static double elapsed(void) {
    struct timespec ts;
    timespec_get(&ts, TIME_UTC);
    return (double)(ts.tv_sec - T0.tv_sec) + 1e-9 * (double)(ts.tv_nsec - T0.tv_nsec);
}

static int DEG, DIAM;
static int NGRP = 0, GMAX = 0, MAXT = 0, NNMAX = 0;
static int *gorder = NULL, *gsorted = NULL;
static int **gmul = NULL;

/* Current configuration. */
static int K, G, T, N, CUR_GI;
static const int *MT;
static int *dI, *dJ, *dS, *bestJ, *bestS, *perm, *adj, *cnt, *stamp, *fr, *nx;
static long long wt[2 * MAXK], unc[2 * MAXK];
static long long wsum_w, last_w;
static int curstamp;
static int best_n, best_m;
static int *best_e = NULL;

typedef struct {
    int gi, k;
    long long cost;
    int *J, *S;
} Cfg;
static Cfg pool[POOLMAX];
static int npool = 0;

static int read_input(void) {
    int n, m;
    if (scanf("%d %d", &n, &m) != 2 || m < 1) return 0;
    long long total = 2LL * m;
    int *buf = malloc(sizeof(int) * (size_t)total);
    long long got = 0;
    for (; got < total; got++)
        if (scanf("%d", &buf[got]) != 1) break;
    if (got < 1) { free(buf); return 0; }
    int ng = buf[0];
    if (ng < 1) { free(buf); return 0; }
    gorder = malloc(sizeof(int) * (size_t)ng);
    gmul = malloc(sizeof(int *) * (size_t)ng);
    long long pos = 1;
    int cntg = 0;
    for (int i = 0; i < ng; i++) {
        if (pos >= got) break;
        long long g = buf[pos++];
        if (g < 1 || g > MAXG || pos + g * g > got) break;
        int *tab = malloc(sizeof(int) * (size_t)(g * g));
        memcpy(tab, buf + pos, sizeof(int) * (size_t)(g * g));
        pos += g * g;
        gorder[cntg] = (int)g;
        gmul[cntg] = tab;
        cntg++;
        if (g > GMAX) GMAX = (int)g;
    }
    free(buf);
    NGRP = cntg;
    return NGRP > 0;
}

static void sort_groups(void) {
    gsorted = malloc(sizeof(int) * (size_t)NGRP);
    for (int i = 0; i < NGRP; i++) gsorted[i] = i;
    for (int i = 1; i < NGRP; i++) {
        int v = gsorted[i];
        int j = i - 1;
        while (j >= 0 && gorder[gsorted[j]] > gorder[v]) {
            gsorted[j + 1] = gsorted[j];
            j--;
        }
        gsorted[j + 1] = v;
    }
}

static void alloc_work(void) {
    MAXT = MAXK * DEG;
    NNMAX = 2 * MAXK * GMAX;
    dI = malloc(sizeof(int) * (size_t)MAXT);
    dJ = malloc(sizeof(int) * (size_t)MAXT);
    dS = malloc(sizeof(int) * (size_t)MAXT);
    bestJ = malloc(sizeof(int) * (size_t)MAXT);
    bestS = malloc(sizeof(int) * (size_t)MAXT);
    perm = malloc(sizeof(int) * (size_t)MAXT * GMAX);
    adj = malloc(sizeof(int) * (size_t)NNMAX * DEG);
    cnt = malloc(sizeof(int) * (size_t)NNMAX);
    stamp = calloc((size_t)NNMAX, sizeof(int));
    fr = malloc(sizeof(int) * (size_t)NNMAX);
    nx = malloc(sizeof(int) * (size_t)NNMAX);
    curstamp = 0;
    for (int i = 0; i < POOLMAX; i++) {
        pool[i].J = malloc(sizeof(int) * (size_t)MAXT);
        pool[i].S = malloc(sizeof(int) * (size_t)MAXT);
        pool[i].cost = BIGC;
        pool[i].gi = 0;
        pool[i].k = 1;
    }
}

static void setup(int gi, int k) {
    K = k;
    G = gorder[gi];
    MT = gmul[gi];
    CUR_GI = gi;
    N = 2 * K * G;
    T = DEG * K;
    for (int t = 0; t < T; t++) dI[t] = t % K;
    for (int b = 0; b < 2 * K; b++) wt[b] = 1;
    wsum_w = 2 * K;
}

/* Right multiplication by the voltage: pm[g] = g * s. */
static void build_perm(int t) {
    int s = dS[t];
    int *pm = perm + (size_t)t * G;
    for (int g = 0; g < G; g++) pm[g] = MT[g * G + s];
}

/* Returns sum of uncovered ordered pairs over block representatives (0 means valid). */
static long long eval_cost(void) {
    for (int t1 = 0; t1 < T; t1++)
        for (int t2 = t1 + 1; t2 < T; t2++)
            if (dI[t1] == dI[t2] && dJ[t1] == dJ[t2] && dS[t1] == dS[t2]) {
                for (int r = 0; r < 2 * K; r++) unc[r] = 0;
                last_w = BIGC;
                return BIGC;
            }
    memset(cnt, 0, sizeof(int) * (size_t)N);
    for (int t = 0; t < T; t++) {
        int ai = dI[t] * G, bj = (K + dJ[t]) * G;
        const int *pm = perm + (size_t)t * G;
        for (int g = 0; g < G; g++) {
            int a = ai + g, b = bj + pm[g];
            adj[(size_t)a * DEG + cnt[a]++] = b;
            adj[(size_t)b * DEG + cnt[b]++] = a;
        }
    }
    long long total = 0;
    for (int r = 0; r < 2 * K; r++) {
        int src = r * G;
        if (curstamp >= 2000000000) {
            memset(stamp, 0, sizeof(int) * (size_t)NNMAX);
            curstamp = 0;
        }
        curstamp++;
        int *f = fr, *h = nx;
        int fsz = 1, count = 1;
        f[0] = src;
        stamp[src] = curstamp;
        for (int lvl = 0; lvl < DIAM && fsz > 0; lvl++) {
            int nsz = 0;
            for (int q = 0; q < fsz; q++) {
                const int *au = adj + (size_t)f[q] * DEG;
                for (int e = 0; e < DEG; e++) {
                    int v = au[e];
                    if (stamp[v] != curstamp) {
                        stamp[v] = curstamp;
                        h[nsz++] = v;
                    }
                }
            }
            count += nsz;
            int *tmp = f; f = h; h = tmp;
            fsz = nsz;
        }
        unc[r] = N - count;
        total += N - count;
    }
    long long w = 0;
    for (int r = 0; r < 2 * K; r++) w += wt[r] * unc[r];
    last_w = w;
    return total;
}

static void random_init(void) {
    int p[MAXK];
    for (int l = 0; l < DEG; l++) {
        for (int i = 0; i < K; i++) p[i] = i;
        for (int i = K - 1; i > 0; i--) {
            int j = rnd_int(i + 1);
            int tmp = p[i]; p[i] = p[j]; p[j] = tmp;
        }
        for (int i = 0; i < K; i++) {
            int t = l * K + i;
            dJ[t] = p[i];
            dS[t] = rnd_int(G);
        }
    }
    for (int t = 0; t < T; t++) build_perm(t);
}

static void perturb(int nmoves) {
    for (int s = 0; s < nmoves; s++) {
        if (K > 1 && rnd_unit() < 0.3) {
            int l = rnd_int(DEG);
            int i1 = rnd_int(K), i2 = rnd_int(K);
            if (i1 == i2) continue;
            int t1 = l * K + i1, t2 = l * K + i2;
            int tmp = dJ[t1]; dJ[t1] = dJ[t2]; dJ[t2] = tmp;
        } else {
            int t = rnd_int(T);
            dS[t] = rnd_int(G);
            build_perm(t);
        }
    }
}

/* Annealing on the weighted cost with breakout weight bumps. The caller has just
   called eval_cost(). Returns the best true cost; bestJ/bestS hold that state. */
static long long run_sa(int iters, double tscale, long long cost) {
    long long bestc = cost;
    long long wcur = last_w;
    long long prevc = cost;
    memcpy(bestJ, dJ, sizeof(int) * (size_t)T);
    memcpy(bestS, dS, sizeof(int) * (size_t)T);
    for (int it = 0; it < iters && bestc > 0; it++) {
        if ((it & 63) == 0 && elapsed() > DEADLINE) break;
        if (it > 0 && it % BRK == 0) {
            if (cost < BIGC && cost >= prevc) {
                eval_cost();
                for (int r = 0; r < 2 * K; r++)
                    if (unc[r] > 0) { wt[r]++; wsum_w++; }
                wcur = 0;
                for (int r = 0; r < 2 * K; r++) wcur += wt[r] * unc[r];
            }
            prevc = cost;
        }
        double sc = (double)wsum_w / (2.0 * K);
        double temp = tscale * (3.0 * (1.0 - (double)it / iters) + 0.05) * sc;
        if (K > 1 && rnd_unit() < 0.25) {
            int l = rnd_int(DEG);
            int i1 = rnd_int(K), i2 = rnd_int(K);
            if (i1 == i2) continue;
            int t1 = l * K + i1, t2 = l * K + i2;
            int tmp = dJ[t1]; dJ[t1] = dJ[t2]; dJ[t2] = tmp;
            long long c2 = eval_cost();
            long long w2 = last_w;
            if (w2 <= wcur || rnd_unit() < exp(-(double)(w2 - wcur) / temp)) {
                cost = c2;
                wcur = w2;
            } else {
                tmp = dJ[t1]; dJ[t1] = dJ[t2]; dJ[t2] = tmp;
            }
        } else {
            int t = rnd_int(T);
            int olds = dS[t];
            int news = rnd_int(G);
            if (news == olds) continue;
            dS[t] = news;
            build_perm(t);
            long long c2 = eval_cost();
            long long w2 = last_w;
            if (w2 <= wcur || rnd_unit() < exp(-(double)(w2 - wcur) / temp)) {
                cost = c2;
                wcur = w2;
            } else {
                dS[t] = olds;
                build_perm(t);
            }
        }
        if (cost < bestc) {
            bestc = cost;
            memcpy(bestJ, dJ, sizeof(int) * (size_t)T);
            memcpy(bestS, dS, sizeof(int) * (size_t)T);
        }
    }
    return bestc;
}

static void emit(void) {
    int m = T * G;
    free(best_e);
    best_e = malloc(sizeof(int) * 2 * (size_t)m);
    int idx = 0;
    for (int t = 0; t < T; t++) {
        for (int g = 0; g < G; g++) {
            best_e[idx++] = dI[t] * G + g;
            best_e[idx++] = (K + dJ[t]) * G + perm[(size_t)t * G + g];
        }
    }
    best_m = m;
    best_n = N;
}

/* A zero-cost run is a valid graph: reload it and emit if it beats the record. */
static void finish_run(long long bc) {
    if (bc == 0) {
        memcpy(dJ, bestJ, sizeof(int) * (size_t)T);
        memcpy(dS, bestS, sizeof(int) * (size_t)T);
        for (int t = 0; t < T; t++) build_perm(t);
        if (N > best_n) emit();
    }
}

/* Elite pool: positive-cost configurations of the current setup. */
static void pool_add(long long cost) {
    if (cost <= 0 || cost >= BIGC) return;
    int slot;
    if (npool < POOLMAX) {
        slot = npool++;
    } else {
        slot = 0;
        for (int i = 1; i < POOLMAX; i++)
            if (pool[i].cost > pool[slot].cost) slot = i;
        if (pool[slot].cost <= cost) return;
    }
    Cfg *c = &pool[slot];
    c->gi = CUR_GI;
    c->k = K;
    c->cost = cost;
    memcpy(c->J, bestJ, sizeof(int) * (size_t)T);
    memcpy(c->S, bestS, sizeof(int) * (size_t)T);
}

static int pick_pool(void) {
    int cand[POOLMAX], nc = 0;
    for (int i = 0; i < npool; i++) {
        long long nn = 2LL * pool[i].k * gorder[pool[i].gi];
        if (nn > best_n) cand[nc++] = i;
    }
    if (nc == 0) return -1;
    int bi = cand[rnd_int(nc)];
    for (int s = 0; s < 2; s++) {
        int c = cand[rnd_int(nc)];
        if (pool[c].cost < pool[bi].cost) bi = c;
    }
    return bi;
}

/* Group index whose order makes 2*k*G beat the record; biased toward small orders. */
static int pick_group(int k) {
    int lo = -1;
    for (int i = 0; i < NGRP; i++) {
        int gi = gsorted[i];
        if (2LL * k * gorder[gi] > best_n) { lo = i; break; }
    }
    if (lo < 0) return -1;
    int span = NGRP - lo;
    int idx;
    if (rnd_unit() < 0.5) {
        idx = lo + rnd_int(span);
    } else {
        int a = rnd_int(span), b = rnd_int(span);
        idx = lo + (a < b ? a : b);
    }
    return gsorted[idx];
}

int main(int argc, char **argv) {
    if (argc < 5) {
        fprintf(stderr, "usage: prog d D seed time_limit [start_n]\n");
        return 1;
    }
    timespec_get(&T0, TIME_UTC);
    DEG = atoi(argv[1]);
    DIAM = atoi(argv[2]);
    uint64_t sd = strtoull(argv[3], NULL, 10);
    DEADLINE = atof(argv[4]);
    best_n = argc > 5 ? atoi(argv[5]) : 0;
    best_m = 0;
    best_e = NULL;
    if (DEG < 1 || DIAM < 1 || !read_input()) {
        printf("0 0\n");
        return 0;
    }
    sort_groups();
    alloc_work();

    uint64_t sm = sd * 2654435761ULL + 12345ULL;
    rs[0] = splitmix(&sm);
    rs[1] = splitmix(&sm);

    static const int kc[5] = {1, 1, 2, 2, 3};
    while (elapsed() < DEADLINE) {
        int pi = -1;
        if (rnd_unit() < POOLP) pi = pick_pool();
        if (pi >= 0) {
            /* Iterated local search: perturb an elite configuration and re-anneal. */
            Cfg *c = &pool[pi];
            setup(c->gi, c->k);
            memcpy(dJ, c->J, sizeof(int) * (size_t)T);
            memcpy(dS, c->S, sizeof(int) * (size_t)T);
            for (int t = 0; t < T; t++) build_perm(t);
            perturb(2 + rnd_int(4));
            for (int t = 0; t < T; t++) build_perm(t);
            long long cst = eval_cost();
            long long bc = run_sa(ILS_ITERS, 0.35, cst);
            finish_run(bc);
            pool_add(bc);
            continue;
        }

        int k = kc[rnd_int(5)];
        int gi = pick_group(k);
        if (gi < 0) {
            int any = 0;
            for (int kk = 1; kk <= MAXK && !any; kk++) {
                int g2 = pick_group(kk);
                if (g2 >= 0) { k = kk; gi = g2; any = 1; }
            }
            if (!any) break;
        }
        setup(gi, k);
        random_init();
        long long cost = eval_cost();
        long long bc = run_sa(ITERS, 1.0, cost);
        finish_run(bc);
        pool_add(bc);
    }

    if (best_m > 0) {
        printf("%d %d\n", best_n, best_m);
        for (int i = 0; i < best_m; i++)
            printf("%d %d\n", best_e[2 * i], best_e[2 * i + 1]);
    } else {
        printf("0 0\n");
    }
    return 0;
}
"""


# ----------------------------------------------------------------------------
# Python: group families, closure, tables, and the C launcher.
# ----------------------------------------------------------------------------

MAXG = 420
PRIMES = (2, 3, 5, 7, 11, 13)
# (lo, hi, how many groups to supply) per order window.
WINDOWS = [(343, 420, 6), (172, 342, 4), (86, 171, 3), (30, 85, 3), (6, 29, 2)]


def _window_of(g):
    for lo, hi, _ in WINDOWS:
        if lo <= g <= hi:
            return (lo, hi)
    return None


def _eye(n):
    return tuple(1 if i == j else 0 for i in range(n) for j in range(n))


def _mat_mul_fn(p, n):
    """Multiplication of flattened n x n matrices over Z_p."""
    rn = range(n)

    def mul(a, b):
        return tuple(sum(a[i * n + k] * b[k * n + j] for k in rn) % p
                     for i in rn for j in rn)
    return mul


def _closure(gens, mul, ident, cap):
    """Elements generated from ident by right multiplication; None if more than cap.

    Elements are listed in BFS order, so every element's BFS parent has a smaller index.
    """
    elems = [ident]
    idx = {ident: 0}
    parent = [-1]
    pgen = [-1]
    i = 0
    while i < len(elems):
        x = elems[i]
        for si, s in enumerate(gens):
            y = mul(x, s)
            if y not in idx:
                if len(elems) >= cap:
                    return None
                idx[y] = len(elems)
                elems.append(y)
                parent.append(i)
                pgen.append(si)
        i += 1
    return elems, idx, parent, pgen


def _build_table(gens, mul, cl):
    """Multiplication table tab[x, y] = index of elems[x] * elems[y], built column by column."""
    elems, idx, parent, pgen = cl
    G = len(elems)
    R = [np.fromiter((idx[mul(x, s)] for x in elems), dtype=np.int64, count=G) for s in gens]
    tab = np.zeros((G, G), dtype=np.int64)
    tab[:, 0] = np.arange(G)
    for y in range(1, G):
        # elems[y] = elems[parent] * s, so column y is column parent with s applied on the right.
        tab[:, y] = R[pgen[y]][tab[:, parent[y]]]
    return tab


def _small_order(A, p, k, L):
    """Order of the k x k matrix A over Z_p if it is at most L, else None."""
    I = [[int(i == j) for j in range(k)] for i in range(k)]
    P = [row[:] for row in A]
    for m in range(1, L + 1):
        if P == I:
            return m
        P = [[sum(P[i][t] * A[t][j] for t in range(k)) % p for j in range(k)]
             for i in range(k)]
    return None


def _sample_affine(rng):
    """Z_p^k x| <A> embedded as affine matrices in GL(k+1, p). Order = p^k * ord(A)."""
    p = rng.choice(PRIMES)
    k = rng.choice((1, 2, 3, 4))
    pk = p ** k
    if pk > MAXG // 2:
        return None
    L = MAXG // pk
    A = [[rng.randrange(p) for _ in range(k)] for _ in range(k)]
    m = _small_order(A, p, k, L)
    if m is None or m * pk < 6:
        return None
    n = k + 1
    gens = []
    for i in range(k):
        M = [1 if a == b else 0 for a in range(n) for b in range(n)]
        M[i * n + k] = 1  # translation by e_i
        gens.append(tuple(M))
    M = [0] * (n * n)
    for i in range(k):
        for j in range(k):
            M[i * n + j] = A[i][j]
    M[k * n + k] = 1
    gens.append(tuple(M))
    return gens, _mat_mul_fn(p, n), _eye(n)


def _sample_ut(rng):
    """Upper unitriangular 3x3 over Z_p (order p^3), optionally extended by a diagonal."""
    p = rng.choice((3, 5, 7))
    n = 3
    e12 = [1 if a == b else 0 for a in range(n) for b in range(n)]
    e12[0 * n + 1] = 1
    e23 = [1 if a == b else 0 for a in range(n) for b in range(n)]
    e23[1 * n + 2] = 1
    gens = [tuple(e12), tuple(e23)]
    if rng.random() < 0.5:
        diag = [rng.randrange(1, p) for _ in range(n)]
        dm = [0] * (n * n)
        for i in range(n):
            dm[i * n + i] = diag[i]
        gens.append(tuple(dm))
    return gens, _mat_mul_fn(p, n), _eye(n)


def _sample_dihedral(rng):
    """Dihedral group of order 2n, elements (r, f) with f in {0, 1}."""
    n = rng.randrange(3, MAXG // 2 + 1)

    def mul(x, y):
        r1, f1 = x
        r2, f2 = y
        return ((r1 + (r2 if f1 == 0 else -r2)) % n, f1 ^ f2)

    return [(1, 0), (0, 1)], mul, (0, 0)


def _sample_abelian(rng):
    """Z_a x Z_b with a * b at most MAXG."""
    a = rng.randrange(2, MAXG + 1)
    b = rng.randrange(2, MAXG // a + 1) if a <= MAXG // 2 else 1

    def mul(x, y):
        return ((x[0] + y[0]) % a, (x[1] + y[1]) % b)

    return [(1, 0), (0, 1)], mul, (0, 0)


def _sample_semidirect(rng):
    """Z_m x| Z_k with r^k = 1 mod m (element (a, b) coded as a*k + b, identity 0)."""
    m = rng.randrange(2, 61)
    k = rng.randrange(2, 13)
    r = rng.randrange(1, m)
    if math.gcd(r, m) != 1 or pow(r, k, m) != 1 % m:
        return None
    try:
        order, mul, _ = lib.semidirect_group(m, k, r)
    except ValueError:
        return None
    if order > MAXG:
        return None
    return [k, 1], mul, 0


SAMPLERS = [_sample_affine, _sample_ut, _sample_dihedral, _sample_abelian, _sample_semidirect]
SAMPLER_W = [3, 1, 1, 1, 2]


def _group_library(rng, t_end):
    """Sample groups until every order window is filled or time runs out. Returns [(G, table)]."""
    need = {(lo, hi): c for lo, hi, c in WINDOWS}
    out = []
    while time.monotonic() < t_end and any(v > 0 for v in need.values()):
        sampler = rng.choices(SAMPLERS, weights=SAMPLER_W)[0]
        spec = sampler(rng)
        if spec is None:
            continue
        gens, mul, ident = spec
        cl = _closure(gens, mul, ident, MAXG)
        if cl is None:
            continue
        G = len(cl[0])
        if G < 6:
            continue
        w = _window_of(G)
        if w is None or need[w] <= 0:
            continue
        need[w] -= 1
        out.append((G, _build_table(gens, mul, cl)))
    return out


def _encode(groups):
    """Flat stream [ng, G1, table1, G2, table2, ...] packed as (u, v) pairs for lib.run_c."""
    flat = [len(groups)]
    for G, tab in groups:
        flat.append(G)
        flat.extend(tab.ravel().tolist())
    if len(flat) % 2:
        flat.append(0)
    return list(zip(flat[0::2], flat[1::2]))


def _best_pg(d):
    """Incidence graph of PG(2, q) for the largest prime power q with q + 1 <= d."""
    for q in range(d - 1, 1, -1):
        if lib.is_prime_power(q):
            return lib.projective_plane_incidence(q)
    return None


# ----------------------------------------------------------------------------
# Driver.
# ----------------------------------------------------------------------------

def build(d, D, seed, time_limit):
    start = time.monotonic()
    if d < 1 or D < 1:
        return 1, []
    if D == 1:
        return 2, [(0, 1)]

    # Safe fallback: K_{d,d} has diameter 2, so it is valid for D >= 2.
    best = lib.haar_graph(d, range(d))
    best_n = best[0]

    def consider(n, e):
        nonlocal best, best_n
        if n > best_n and lib.is_valid(n, e, d, D):
            best = (n, e)
            best_n = n

    if D >= 3:
        pg = _best_pg(d)
        if pg is not None:
            consider(pg[0], pg[1])

    if best_n >= lib.moore_bound(d, D):
        return best

    # Reserve about 7% of the limit plus 2 s for compile, parsing and validation.
    budget = 0.93 * time_limit - (time.monotonic() - start) - 2.0
    if budget >= 2.0:
        rng = random.Random(seed * 1000003 + d * 1009 + D)
        gen_end = time.monotonic() + min(4.0, 0.1 * budget)
        groups = _group_library(rng, gen_end)
        budget = 0.93 * time_limit - (time.monotonic() - start) - 2.0
        if groups and budget >= 1.0:
            try:
                out = lib.run_c(C_SOURCE, [d, D, seed, f"{budget:.2f}", best_n],
                                stdin_graph=(1, _encode(groups)),
                                timeout=budget + 8.0)
                n, e = lib.parse_graph_text(out)
                consider(n, e)
            except Exception:
                pass

    if not lib.is_valid(best[0], best[1], d, D):
        best = lib.haar_graph(d, range(d))
    return best
