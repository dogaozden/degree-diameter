def _c_engine(d, D, seed, n, edges, budget):
    """Run the C insertion-and-anneal engine from a valid graph. Returns (n, edges)."""
    out = lib.run_c(C_SOURCE, [d, D, seed, round(budget, 2)],
                    stdin_graph=(n, edges), timeout=budget + 15)
    return lib.parse_graph_text(out)


# ----------------------------------------------------------------------------
# Driver. Phases (fractions of T = 0.85 * time_limit):
#   A  structured small base (W(q) or PG(2,q)) grown, twin trials, LNS
#   B  thinned dense graph (degree reduction + vertex deletion)
#   C  LNS from the best valid graph
#   D  redundant-edge pruning and regrowth
#   E  C engine: insert a vertex pair, anneal switches to zero bad pairs
# Every candidate passes lib.is_valid before it is kept; K_{d,d}-like Haar graph is the fallback.
# ----------------------------------------------------------------------------

def build(d, D, seed, time_limit):
    start = time.monotonic()
    T = 0.85 * time_limit

    def at(f):
        return start + f * T

    rng = random.Random(seed)

    if D == 1 and d >= 1:
        return 2, [(0, 1)]
    if d < 1 or D < 1:
        return 1, []

    best_n, best_e = lib.haar_graph(d, range(d))

    def consider(n, e):
        nonlocal best_n, best_e
        if n > best_n and lib.is_valid(n, e, d, D):
            best_n, best_e = n, list(e)

    # Phase A: structured small base.
    base_n, base_e = best_n, list(best_e)
    if D >= 3:
        base = _best_gq(d) if D >= 4 else None
        if base is None:
            base = _best_pg(d)
        if base is not None:
            n0, e0 = base
            consider(n0, e0)
            base_n, base_e = n0, list(e0)
            n1, e1 = _grow(n0, e0, d, D, at(0.10), rng)
            consider(n1, e1)
    if D >= 2:
        trial_end = at(0.20)
        while time.monotonic() < trial_end:
            n, e = _trial(base_n, base_e, d, D, rng, trial_end)
            consider(n, e)
        _lns(best_n, best_e, d, D, at(0.30), rng, consider)

    # Phase B: thinned dense graph.
    if D >= 2 and time.monotonic() < at(0.36):
        raw = _raw_big(d, D)
        if raw is not None:
            rn, re = raw
            while time.monotonic() < at(0.36):
                r = _deletion_trial(d, D, rn, re, rng, at(0.36))
                if r is None:
                    break
                consider(*r)

    # Phase C: LNS from the best valid graph.
    if D >= 2 and time.monotonic() < at(0.42):
        _lns(best_n, best_e, d, D, at(0.42), rng, consider)

    # Phase D: prune redundant edges and regrow.
    if D >= 2 and time.monotonic() < at(0.48):
        _prune_regrow(best_n, best_e, d, D, at(0.48), rng, consider)

    # Phase E: C engine from the best valid graph (vertex-pair insertion + annealing).
    if D >= 2:
        budget = start + 0.88 * time_limit - time.monotonic() - 1.0
        if budget > 2.0:
            try:
                n5, e5 = _c_engine(d, D, seed, best_n, best_e, budget)
                consider(n5, e5)
            except Exception:
                pass

    if not lib.is_valid(best_n, best_e, d, D):
        return lib.haar_graph(d, range(d))
    return best_n, list(best_e)
