def _duplicate_twins(n, edges, d, rng):
    """Greedily add twins in random order while neighbours have spare degree."""
    adj = [set() for _ in range(n)]
    for u, v in edges:
        adj[u].add(v)
        adj[v].add(u)
    changed = True
    while changed:
        changed = False
        order = list(range(len(adj)))
        rng.shuffle(order)
        for v in order:
            nb = adj[v]
            if not nb or len(nb) > d:
                continue
            if any(len(adj[u]) >= d for u in nb):
                continue
            w = len(adj)
            adj.append(set(nb))
            for u in nb:
                adj[u].add(w)
            changed = True
    out = [(u, v) for u in range(len(adj)) for v in adj[u] if u < v]
    return len(adj), out


def _trial(base_n, base_e, d, D, rng, deadline):
    """One randomized pipeline: mix twin duplication with cover growth and saturation."""
    mode = rng.randrange(3)
    n, e = base_n, list(base_e)
    if mode == 0:
        n, e = _duplicate_twins(n, e, d, rng)
        e = _saturate_edges(n, e, d, rng)
        n, e = _grow(n, e, d, D, deadline, rng, attempts=30)
    elif mode == 1:
        n, e = _grow(n, e, d, D, deadline, rng, attempts=30)
        n, e = _duplicate_twins(n, e, d, rng)
        e = _saturate_edges(n, e, d, rng)
        n, e = _grow(n, e, d, D, deadline, rng, attempts=30)
    else:
        e = _saturate_edges(n, e, d, rng)
        n, e = _duplicate_twins(n, e, d, rng)
        e = _saturate_edges(n, e, d, rng)
        n, e = _grow(n, e, d, D, deadline, rng, attempts=30)
    return n, e


# ----------------------------------------------------------------------------
# NEW: bipartite group-voltage lifts searched by local search on bad pairs.
#
# Base graph: k vertices A_0..A_{k-1} and k vertices B_0..B_{k-1}, built as the
# union of d random perfect matchings between A and B, so the base is d-regular.
# Each base dart gets a random voltage in a finite group G of order N. The lift
# has 2*k*N vertices, is bipartite by construction, and has degree <= d. We
# hill-climb on the voltages to minimise the number of pairs at distance > D.
# The group is cyclic Z_N or a semidirect product Z_m x| Z_kk with a random r.
# ----------------------------------------------------------------------------

def _semidirect_options(N, rng):
    """Groups of order N: cyclic Z_N, plus Z_m x| Z_kk with a random nontrivial r."""
    opts = [("cyc", N)]
    for kk in range(2, N + 1):
        if N % kk:
            continue
        m = N // kk
        if m < 3:
            continue
        rs = [r for r in range(2, m)
              if math.gcd(r, m) == 1 and pow(r, kk, m) == 1 % m]
        if rs:
            opts.append(("sd", m, kk, rng.choice(rs)))
    return opts


def _group(opt):
    """Return (order, mul) for a group option from _semidirect_options."""
    if opt[0] == "cyc":
        order, mul, _ = lib.cyclic_group(opt[1])
    else:
        order, mul, _ = lib.semidirect_group(opt[1], opt[2], opt[3])
    return order, mul


def _lift_search(k, order, mul, d, D, rng, deadline):
    """Hill-climb voltages on a random d-regular base. Returns (n, edges) with diameter <= D, or None."""
    darts = []
    for _ in range(d):
        perm = list(range(k))
        rng.shuffle(perm)
        for i in range(k):
            darts.append((i, k + perm[i], rng.randrange(order)))
    n, e = lib.group_lift(2 * k, darts, order, mul)
    cur = lib.bad_pairs(n, e, D)
    while cur > 0 and time.monotonic() < deadline:
        j = rng.randrange(len(darts))
        u, v, g_old = darts[j]
        darts[j] = (u, v, rng.randrange(order))
        n2, e2 = lib.group_lift(2 * k, darts, order, mul)
        new = lib.bad_pairs(n2, e2, D)
        if new <= cur:
            cur = new
            n, e = n2, e2
        else:
            darts[j] = (u, v, g_old)
    if cur == 0:
        return n, e
    return None


def _lift_stage(d, D, rng, end, state, consider):
    """Repeatedly try voltage lifts whose order is just above the current best."""
    while time.monotonic() < end:
        k = rng.choice((2, 2, 3, 3, 4, 5, 6))
        N = state[0] // (2 * k) + 1 + rng.randrange(3)
        opt = rng.choice(_semidirect_options(N, rng))
        order, mul = _group(opt)
        slice_end = min(end, time.monotonic() + 3.0)
        res = _lift_search(k, order, mul, d, D, rng, slice_end)
        if res is not None:
            consider(res[0], res[1])


# ----------------------------------------------------------------------------
# Large-neighbourhood search (kill, repair, regrow).
# ----------------------------------------------------------------------------

def _cost(adj, D):
    """Number of vertex pairs at distance more than D (unreachable pairs count)."""
    n = len(adj)
    ball = _balls_radius(n, adj, D)
    return sum(n - b.bit_count() for b in ball) // 2


def _add_vertex(adj, color, d, D, side, rng):
    """Append a vertex on the opposite side of `side`, joined to a greedy cover of `side`."""
    n = len(adj)
    ball = _balls_radius(n, adj, D - 1)
    covered = 0
    chosen = []
    cands = [s for s in range(n) if color[s] == side]
    for _ in range(d):
        best_s, best_g = None, -1.0
        for s in cands:
            if s in chosen:
                continue
            g = (ball[s] & ~covered).bit_count() + 0.5 * rng.random()
            if g > best_g:
                best_s, best_g = s, g
        if best_s is None:
            break
        chosen.append(best_s)
        covered |= ball[best_s]
    v = n
    adj.append(set())
    color.append(1 - side)
    for s in chosen:
        if len(adj[s]) >= d:
            t = rng.choice(tuple(adj[s]))
            adj[s].discard(t)
            adj[t].discard(s)
        adj[s].add(v)
        adj[v].add(s)
    return v


def _fill(adj, color, d, rng):
    """Add cross-side edges between deficient vertices (only helps the diameter)."""
    n = len(adj)
    left = [v for v in range(n) if color[v] == 0 and len(adj[v]) < d]
    right = [v for v in range(n) if color[v] == 1 and len(adj[v]) < d]
    pairs = [(a, b) for a in left for b in right if b not in adj[a]]
    rng.shuffle(pairs)
    for a, b in pairs:
        if len(adj[a]) < d and len(adj[b]) < d and b not in adj[a]:
            adj[a].add(b)
            adj[b].add(a)


def _anneal(adj, color, d, D, rng, iters, deadline):
    """Bipartite double-edge switches (degrees unchanged) minimising bad pairs. True if cost reaches 0."""
    cur = _cost(adj, D)
    side0 = [v for v in range(len(adj)) if color[v] == 0]
    for _ in range(iters):
        if cur == 0 or time.monotonic() > deadline:
            break
        a = rng.choice(side0)
        if not adj[a]:
            continue
        b = rng.choice(tuple(adj[a]))
        c = rng.choice(side0)
        if c == a or not adj[c]:
            continue
        e = rng.choice(tuple(adj[c]))
        if e in adj[a] or b in adj[c]:
            continue
        adj[a].discard(b)
        adj[b].discard(a)
        adj[c].discard(e)
        adj[e].discard(c)
        adj[a].add(e)
        adj[e].add(a)
        adj[c].add(b)
        adj[b].add(c)
        new = _cost(adj, D)
        if new <= cur or (new == cur + 1 and rng.random() < 0.1):
            cur = new
        else:
            adj[a].discard(e)
            adj[e].discard(a)
            adj[c].discard(b)
            adj[b].discard(c)
            adj[a].add(b)
            adj[b].add(a)
            adj[c].add(e)
            adj[e].add(c)
    return cur == 0


def _lns(n, edges, d, D, deadline, rng, consider):
    """Kill-repair-regrow large-neighbourhood search from a valid graph, anchored to its best."""
    cur_n, cur_e = n, list(edges)
    best_n, best_e = n, list(edges)
    while time.monotonic() < deadline:
        k = rng.choice((1, 1, 2, 3))
        if k >= cur_n:
            break
        kill = set(rng.sample(range(cur_n), k))
        keep = [v for v in range(cur_n) if v not in kill]
        remap = {v: i for i, v in enumerate(keep)}
        m = len(keep)
        e2 = [(remap[u], remap[v]) for u, v in cur_e if u not in kill and v not in kill]
        adj = _to_sets(m, e2)
        color = _bipartition(m, adj)
        _fill(adj, color, d, rng)
        if not _anneal(adj, color, d, D, rng, 150, deadline):
            continue
        e3 = [(u, v) for u in range(m) for v in adj[u] if u < v]
        n4, e4 = _grow(m, e3, d, D, deadline, rng, attempts=16)
        consider(n4, e4)
        if n4 > best_n:
            best_n, best_e = n4, list(e4)
        if n4 >= cur_n - 1:
            cur_n, cur_e = n4, e4
        elif n4 < best_n - 3:
            cur_n, cur_e = best_n, list(best_e)


def _repair(d, D, n, edges, deadline, rng, consider):
    """Repeatedly try to add one vertex to the current valid graph, repairing with annealing."""
    adj = _to_sets(n, edges)
    color = _bipartition(n, adj)
    while time.monotonic() < deadline:
        snap_adj = [set(s) for s in adj]
        snap_color = list(color)
        side = rng.randrange(2)
        _add_vertex(adj, color, d, D, side, rng)
        _fill(adj, color, d, rng)
        if _anneal(adj, color, d, D, rng, 1500, deadline):
            m = len(adj)
            e = [(u, v) for u in range(m) for v in adj[u] if u < v]
            consider(m, e)
        else:
            adj[:] = snap_adj
            color[:] = snap_color


def build(d, D, seed, time_limit):
    start = time.monotonic()
    deadline = start + 0.85 * time_limit
    rng = random.Random(seed)

    if D == 1 and d >= 1:
        return 2, [(0, 1)]
    if d < 1 or D < 1:
        return 1, []

    # Safe fallback: K_{d,d}, valid for D >= 2.
    fb_n, fb_e = lib.haar_graph(d, range(d))
    state = [fb_n, list(fb_e)]

    def consider(n, e):
        if n > state[0] and lib.is_valid(n, e, d, D):
            state[0], state[1] = n, list(e)

    # Structured base: generalized quadrangle for D >= 4, projective plane for D = 3.
    base_n, base_e = state[0], list(state[1])
    if D >= 3:
        base = _best_gq(d) if D >= 4 else None
        if base is None:
            base = _best_pg(d)
        if base is not None:
            n0, e0 = base
            consider(n0, e0)
            base_n, base_e = n0, list(e0)
            n1, e1 = _grow(n0, e0, d, D, start + 0.12 * time_limit, rng)
            consider(n1, e1)

    # Calibration cases already at the Moore bound return immediately.
    if state[0] >= lib.moore_bound(d, D):
        return state[0], list(state[1])

    # NEW stage: group-voltage lift search (different construction family).
    if d >= 3 and D >= 2:
        lift_end = start + 0.45 * time_limit
        _lift_stage(d, D, rng, min(lift_end, deadline), state, consider)

    # Randomized twin-duplication pipelines from the structured base.
    if D >= 2 and time.monotonic() < deadline:
        trial_end = start + 0.6 * time_limit
        while time.monotonic() < trial_end:
            n, e = _trial(base_n, base_e, d, D, rng, trial_end)
            consider(n, e)

    # Kill-repair-regrow search from the best valid graph found so far.
    if D >= 2 and time.monotonic() < deadline:
        lns_end = start + 0.8 * time_limit
        _lns(state[0], state[1], d, D, min(lns_end, deadline), rng, consider)

    # Bold stage: repeated add-and-repair from the largest valid graph found so far.
    if D >= 2 and time.monotonic() < deadline:
        _repair(d, D, state[0], state[1], deadline, rng, consider)

    if not lib.is_valid(state[0], state[1], d, D):
        return fb_n, list(fb_e)
    return state[0], list(state[1])
