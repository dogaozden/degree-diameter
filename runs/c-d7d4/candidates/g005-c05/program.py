def _duplicate_twins(n, edges, d, rng):
    """Greedily add twins in random order while neighbours have spare degree."""
    adj = [set() for _ in range(n)]
    for u, v in edges:
        adj[u].add(v)
        adj[v].add(u)
    changed = True
    while changed:
        changed = False
        order = list(range(len(adj)))
        rng.shuffle(order)
        for v in order:
            nb = adj[v]
            if not nb or len(nb) > d:
                continue
            if any(len(adj[u]) >= d for u in nb):
                continue
            w = len(adj)
            adj.append(set(nb))
            for u in nb:
                adj[u].add(w)
            changed = True
    out = [(u, v) for u in range(len(adj)) for v in adj[u] if u < v]
    return len(adj), out


def _trial(base_n, base_e, d, D, rng, deadline):
    """One randomized pipeline: mix twin duplication with cover growth and saturation."""
    mode = rng.randrange(3)
    n, e = base_n, list(base_e)
    if mode == 0:
        n, e = _duplicate_twins(n, e, d, rng)
        e = _saturate_edges(n, e, d, rng)
        n, e = _grow(n, e, d, D, deadline, rng)
    elif mode == 1:
        n, e = _grow(n, e, d, D, deadline, rng)
        n, e = _duplicate_twins(n, e, d, rng)
        e = _saturate_edges(n, e, d, rng)
        n, e = _grow(n, e, d, D, deadline, rng)
    else:
        e = _saturate_edges(n, e, d, rng)
        n, e = _duplicate_twins(n, e, d, rng)
        e = _saturate_edges(n, e, d, rng)
        n, e = _grow(n, e, d, D, deadline, rng)
    return n, e


# ----------------------------------------------------------------------------
# Kill / repair / regrow search (parent pipeline).
# ----------------------------------------------------------------------------

def _cost(adj, D):
    """Number of vertex pairs at distance more than D (unreachable pairs count)."""
    n = len(adj)
    ball = _balls_radius(n, adj, D)
    return sum(n - b.bit_count() for b in ball) // 2


def _add_vertex(adj, color, d, D, side, rng):
    """Append a vertex on the opposite side of `side`, joined to a greedy cover of `side`."""
    n = len(adj)
    ball = _balls_radius(n, adj, D - 1)
    covered = 0
    chosen = []
    cands = [s for s in range(n) if color[s] == side]
    for _ in range(d):
        best_s, best_g = None, -1.0
        for s in cands:
            if s in chosen:
                continue
            g = (ball[s] & ~covered).bit_count() + 0.5 * rng.random()
            if g > best_g:
                best_s, best_g = s, g
        if best_s is None:
            break
        chosen.append(best_s)
        covered |= ball[best_s]
    v = n
    adj.append(set())
    color.append(1 - side)
    for s in chosen:
        if len(adj[s]) >= d:
            t = rng.choice(tuple(adj[s]))
            adj[s].discard(t)
            adj[t].discard(s)
        adj[s].add(v)
        adj[v].add(s)
    return v


def _fill(adj, color, d, rng):
    """Add cross-side edges between deficient vertices (only helps the diameter)."""
    n = len(adj)
    left = [v for v in range(n) if color[v] == 0 and len(adj[v]) < d]
    right = [v for v in range(n) if color[v] == 1 and len(adj[v]) < d]
    pairs = [(a, b) for a in left for b in right if b not in adj[a]]
    rng.shuffle(pairs)
    for a, b in pairs:
        if len(adj[a]) < d and len(adj[b]) < d and b not in adj[a]:
            adj[a].add(b)
            adj[b].add(a)


def _anneal(adj, color, d, D, rng, iters, deadline):
    """Bipartite double-edge switches (degrees unchanged) minimising bad pairs. True if cost reaches 0."""
    cur = _cost(adj, D)
    side0 = [v for v in range(len(adj)) if color[v] == 0]
    for _ in range(iters):
        if cur == 0 or time.monotonic() > deadline:
            break
        a = rng.choice(side0)
        if not adj[a]:
            continue
        b = rng.choice(tuple(adj[a]))
        c = rng.choice(side0)
        if c == a or not adj[c]:
            continue
        e = rng.choice(tuple(adj[c]))
        if e in adj[a] or b in adj[c]:
            continue
        adj[a].discard(b)
        adj[b].discard(a)
        adj[c].discard(e)
        adj[e].discard(c)
        adj[a].add(e)
        adj[e].add(a)
        adj[c].add(b)
        adj[b].add(c)
        new = _cost(adj, D)
        if new <= cur or (new == cur + 1 and rng.random() < 0.1):
            cur = new
        else:
            adj[a].discard(e)
            adj[e].discard(a)
            adj[c].discard(b)
            adj[b].discard(c)
            adj[a].add(b)
            adj[b].add(a)
            adj[c].add(e)
            adj[e].add(c)
    return cur == 0


def _lns(n, edges, d, D, deadline, rng, consider):
    """Kill-repair-regrow large-neighbourhood search from a valid graph."""
    cur_n, cur_e = n, list(edges)
    while time.monotonic() < deadline:
        k = rng.choice((1, 1, 2, 3))
        if k >= cur_n:
            break
        kill = set(rng.sample(range(cur_n), k))
        keep = [v for v in range(cur_n) if v not in kill]
        remap = {v: i for i, v in enumerate(keep)}
        m = len(keep)
        e2 = [(remap[u], remap[v]) for u, v in cur_e if u not in kill and v not in kill]
        adj = _to_sets(m, e2)
        color = _bipartition(m, adj)
        _fill(adj, color, d, rng)
        if not _anneal(adj, color, d, D, rng, 150, deadline):
            continue
        e3 = [(u, v) for u in range(m) for v in adj[u] if u < v]
        n4, e4 = _grow(m, e3, d, D, deadline, rng)
        consider(n4, e4)
        if n4 >= cur_n - 1:
            cur_n, cur_e = n4, e4


def _repair(d, D, n, edges, deadline, rng, consider):
    """Repeatedly try to add one vertex to the current valid graph, repairing with annealing."""
    adj = _to_sets(n, edges)
    color = _bipartition(n, adj)
    while time.monotonic() < deadline:
        snap_adj = [set(s) for s in adj]
        snap_color = list(color)
        side = rng.randrange(2)
        _add_vertex(adj, color, d, D, side, rng)
        _fill(adj, color, d, rng)
        if _anneal(adj, color, d, D, rng, 1500, deadline):
            m = len(adj)
            e = [(u, v) for u in range(m) for v in adj[u] if u < v]
            consider(m, e)
        else:
            adj[:] = snap_adj
            color[:] = snap_color


def _parent(d, D, rng, budget):
    """The previous pipeline (structured base, twin trials, LNS, repair) within `budget` seconds."""
    start = time.monotonic()
    deadline = start + 0.85 * budget
    best_n, best_e = lib.haar_graph(d, range(d))

    def consider(n, e):
        nonlocal best_n, best_e
        if n > best_n and lib.is_valid(n, e, d, D):
            best_n, best_e = n, list(e)

    base_n, base_e = best_n, list(best_e)
    if D >= 3:
        base = _best_gq(d) if D >= 4 else None
        if base is None:
            base = _best_pg(d)
        if base is not None:
            n0, e0 = base
            consider(n0, e0)
            base_n, base_e = n0, list(e0)
            n1, e1 = _grow(n0, e0, d, D, start + 0.2 * budget, rng)
            consider(n1, e1)

    if D >= 2:
        trial_end = start + 0.45 * budget
        while time.monotonic() < trial_end:
            n, e = _trial(base_n, base_e, d, D, rng, trial_end)
            consider(n, e)

    if D >= 2 and time.monotonic() < deadline:
        _lns(best_n, best_e, d, D, start + 0.75 * budget, rng, consider)

    if D >= 2 and time.monotonic() < deadline:
        _repair(d, D, best_n, best_e, deadline, rng, consider)

    return best_n, list(best_e)


# ----------------------------------------------------------------------------
# NEW construction: hill-climbed voltage lifts over small (semi)direct groups.
#
# Base: K vertices per side, d layers, each layer a permutation of the K
# A-vertices to the K B-vertices, so every vertex has degree d. Each base dart
# (i, j, g) lifts to the matching a_{i,x} ~ b_{j, x*g} over a group G of order M.
# The lift has 2*K*M vertices, is bipartite by construction, and is d-regular
# when there are no duplicate edges. Voltages are hill-climbed to minimise the
# number of pairs farther than D apart, which is a different search space from
# the parent's random twin/cover growth.
# ----------------------------------------------------------------------------

def _groups(M):
    """All (m, k, r) with m*k = M giving Z_m semidirect Z_k (r^k = 1 mod m, gcd(r, m) = 1)."""
    out = []
    for k in range(1, M + 1):
        if M % k:
            continue
        m = M // k
        for r in range(m):
            if math.gcd(r, m) == 1 and pow(r, k, m) == 1 % m:
                out.append((m, k, r))
    return out


def _lift_graph(K, M, mt, darts):
    """Return (n, sorted edge list) for the lift; A ids 0..K*M-1, B ids K*M..2*K*M-1."""
    base = K * M
    edges = set()
    for i, j, g in darts:
        for x in range(M):
            edges.add((i * M + x, base + j * M + mt[x][g]))
    return 2 * base, sorted(edges)


def _bad_pairs(n, adj, D):
    ball = _balls_radius(n, adj, D)
    return sum(n - b.bit_count() for b in ball) // 2


def _lift_cost(K, M, mt, darts, D):
    n, e = _lift_graph(K, M, mt, darts)
    dup = len(darts) * M - len(e)
    adj = [[] for _ in range(n)]
    for a, b in e:
        adj[a].append(b)
        adj[b].append(a)
    return _bad_pairs(n, adj, D) + 50 * dup


def _try_lift(K, M, d, D, rng, until):
    """Hill-climb voltages for a K-vertex base over a group of order M. Returns (n, edges) or None."""
    groups = _groups(M)
    rng.shuffle(groups)
    perms = list(itertools.permutations(range(K)))
    for m, k, r in groups[:4]:
        now = time.monotonic()
        if now >= until:
            return None
        local_until = min(until, now + 1.5)
        _, mul, _ = lib.semidirect_group(m, k, r)
        mt = [[mul(x, g) for g in range(M)] for x in range(M)]
        layers = [rng.choice(perms) for _ in range(d)]
        darts = [[i, layers[l][i], rng.randrange(M)] for l in range(d) for i in range(K)]
        cost = _lift_cost(K, M, mt, darts, D)
        while cost > 0 and time.monotonic() < local_until:
            idx = rng.randrange(len(darts))
            old = darts[idx][2]
            darts[idx][2] = rng.randrange(M)
            c2 = _lift_cost(K, M, mt, darts, D)
            if c2 <= cost:
                cost = c2
            else:
                darts[idx][2] = old
        if cost == 0:
            return _lift_graph(K, M, mt, darts)
    return None


def _lift_search(d, D, rng, deadline, n0):
    """Search lifts of increasing order. Returns the best valid (n, edges) found, or None."""
    best = None
    bestn = n0
    Ks = (1, 2, 3)
    nextM = {K: bestn // (2 * K) + 1 for K in Ks}
    while time.monotonic() < deadline - 0.5:
        K = min(Ks, key=lambda k: 2 * k * nextM[k])
        M = nextM[K]
        nextM[K] = M + 1
        if 2 * K * M <= bestn:
            nextM[K] = bestn // (2 * K) + 1
            continue
        until = min(deadline, time.monotonic() + 3.0)
        res = _try_lift(K, M, d, D, rng, until)
        if res is None:
            continue
        n, e = res
        if not lib.is_valid(n, e, d, D):
            continue
        n2, e2 = _grow(n, e, d, D, deadline, rng)
        if n2 > n and lib.is_valid(n2, e2, d, D):
            n, e = n2, e2
        if n > bestn:
            bestn, best = n, (n, list(e))
        for k in Ks:
            nextM[k] = max(nextM[k], bestn // (2 * k) + 1)
    return best


def build(d, D, seed, time_limit):
    start = time.monotonic()
    total = 0.85 * time_limit
    deadline = start + total
    rng = random.Random(seed)

    if D == 1 and d >= 1:
        return 2, [(0, 1)]
    if d < 1 or D < 1:
        return 1, []

    # Safe fallback: K_{d,d}, valid for D >= 2.
    best_n, best_e = lib.haar_graph(d, range(d))

    if D < 2:
        return best_n, list(best_e)

    # Stage 1: previous pipeline (structured base plus randomized growth), shorter budget.
    try:
        pn, pe = _parent(d, D, rng, 0.35 * total)
        if pn > best_n and lib.is_valid(pn, pe, d, D):
            best_n, best_e = pn, list(pe)
    except Exception:
        pass

    # Stage 2 (bold): voltage lifts over small groups, hill-climbed for diameter.
    try:
        res = _lift_search(d, D, rng, deadline, best_n)
        if res is not None:
            ln, le = res
            if ln > best_n and lib.is_valid(ln, le, d, D):
                best_n, best_e = ln, list(le)
    except Exception:
        pass

    if not lib.is_valid(best_n, best_e, d, D):
        return lib.haar_graph(d, range(d))
    return best_n, list(best_e)
