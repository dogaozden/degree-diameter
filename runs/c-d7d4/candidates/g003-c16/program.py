# Voltage lifts over semidirect products and cyclic groups.
# ----------------------------------------------------------------------------

def _sample_group(G, rng):
    for _ in range(60):
        k2 = rng.randint(1, 12)
        if G % k2:
            continue
        m = G // k2
        if m < 2:
            continue
        if k2 == 1:
            r = 1
        else:
            cands = [r for r in rng.sample(range(1, m), min(m - 1, 40))
                     if math.gcd(r, m) == 1 and pow(r, k2, m) == 1 % m]
            if not cands:
                continue
            r = rng.choice(cands)
        try:
            order, mul, _ = lib.semidirect_group(m, k2, r)
        except ValueError:
            continue
        return order, mul
    return None


def _group_search(d, D, k, G, rng, iters, deadline):
    """Hill-climb dart voltages in a group of order about G over a random d-regular base."""
    g = _sample_group(G, rng)
    if g is None:
        return None
    order, mul = g
    if order < 2:
        return None
    perms = [rng.sample(range(k), k) for _ in range(d)]
    darts = [[i, k + p[i], rng.randrange(order)] for p in perms for i in range(k)]

    def evaluate():
        n, e = lib.group_lift(2 * k, [tuple(x) for x in darts], order, mul)
        return n, e, lib.bad_pairs(n, e, D)

    n, e, c = evaluate()
    for _ in range(iters):
        if c == 0 or time.monotonic() > deadline:
            break
        j = rng.randrange(len(darts))
        old = darts[j][2]
        darts[j][2] = (old + rng.randrange(1, order)) % order
        n2, e2, c2 = evaluate()
        if c2 <= c:
            n, e, c = n2, e2, c2
        else:
            darts[j][2] = old
    if c == 0:
        return n, e
    return None


def _search_lift(d, D, k, m, rng, iters, deadline):
    """Hill-climb Z_m voltages on a random d-regular bipartite base with k+k vertices."""
    if m < 2:
        return None
    perms = [rng.sample(range(k), k) for _ in range(d)]
    darts = [[i, k + p[i], rng.randrange(m)] for p in perms for i in range(k)]

    def evaluate():
        n, e = lib.voltage_lift(2 * k, [tuple(x) for x in darts], m)
        return n, e, lib.bad_pairs(n, e, D)

    n, e, c = evaluate()
    for _ in range(iters):
        if c == 0 or time.monotonic() > deadline:
            break
        j = rng.randrange(len(darts))
        old = darts[j][2]
        darts[j][2] = (old + rng.randrange(1, m)) % m
        n2, e2, c2 = evaluate()
        if c2 <= c:
            n, e, c = n2, e2, c2
        else:
            darts[j][2] = old
    if c == 0:
        return n, e
    return None


# ----------------------------------------------------------------------------
# Driver.
# ----------------------------------------------------------------------------

def build(d, D, seed, time_limit):
    t0 = time.monotonic()
    rng = random.Random(seed)

    if d < 1 or D < 1:
        return 1, []
    if D == 1:
        return 2, [(0, 1)]

    best = lib.haar_graph(d, range(d))   # K_{d,d}: valid for D >= 2
    best_n = best[0]

    def consider(n, e):
        nonlocal best, best_n
        if n > best_n and lib.is_valid(n, e, d, D):
            best = (n, list(e))
            best_n = n

    moore = lib.moore_bound(d, D)
    total = 0.8 * time_limit - 2.0   # usable wall-clock after safety margin and compile
    if best_n >= moore or total <= 0.5:
        return best

    # Structured starts, each grown by cover extension (largest first).
    pg = _best_pg(d) if D >= 3 else None
    cands = []
    if D == 3 and d - 2 >= 3 and lib.is_prime_power(d - 2):
        try:
            cands.append(lib.araujo_lopez_graph(d - 2))
        except ValueError:
            pass
    if pg is not None:
        cands.append(pg)
    if D >= 4:
        gq = _best_gq(d)
        if gq is not None:
            cands.append(gq)
    cands.sort(key=lambda g: -g[0])
    grow_deadline = t0 + 0.2 * total
    for c in cands:
        consider(c[0], c[1])
        if time.monotonic() < grow_deadline:
            n2, e2 = _grow(c[0], c[1], d, D, grow_deadline, rng)
            consider(n2, e2)

    # 2-lift chain from the projective plane (only proceeds while 2n is within the Moore bound).
    if D >= 4 and pg is not None and time.monotonic() < grow_deadline:
        chain_deadline = t0 + 0.32 * total
        cn, ce = _lift_chain(pg[0], pg[1], d, D, chain_deadline, rng)
        consider(cn, ce)

    # Python voltage-lift search (group lifts dominate for D >= 4).
    py_end = t0 + 0.42 * total
    while time.monotonic() < py_end and best_n < moore:
        k = rng.randint(1, 4)
        floor = best_n // (2 * k) + 1
        if D >= 4 or rng.random() < 0.7:
            G = max(floor + rng.randrange(3), 2)
            res = _group_search(d, D, k, G, rng, 200, py_end)
        else:
            m = max(floor + rng.randrange(2), 2)
            res = _search_lift(d, D, k, m, rng, 250, py_end)
        if res is not None:
            consider(res[0], res[1])

    # Saturate the current best (a valid graph stays valid when edges are added).
    if best_n < moore:
        sat = _saturate_edges(best_n, best[1], d, rng)
        if lib.is_valid(best_n, sat, d, D):
            best = (best_n, sat)

    # C engine: lift search, saturation, then grow by two from the best graph.
    end_all = t0 + total
    c_budget = end_all - time.monotonic() - 1.0
    if best_n < moore and D >= 2 and c_budget > 1.0:
        try:
            text = lib.run_c(C_SOURCE, [d, D, seed, round(c_budget, 2)],
                             stdin_graph=best, timeout=c_budget + 4)
            out = lib.parse_graph_text(text)
            consider(out[0], out[1])
        except (RuntimeError, ValueError):
            pass   # keep the valid Python fallback

    if not lib.is_valid(best[0], best[1], d, D):
        best = lib.haar_graph(d, range(d))
    return best
