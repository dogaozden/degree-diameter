# ----------------------------------------------------------------------------
# NEW (bold): cyclic difference-cover Haar graphs (diameter 3).
#
# The Haar graph H(m, S) has parts a_i, b_j (i, j in Z_m) with a_i ~ b_{i+s}
# for s in S. With |S| = d it is d-regular and bipartite on 2m vertices.
#
#   * a-a pairs: a_i and a_{i+delta} share a neighbour iff delta = s - t with
#     s != t in S. So S - S must cover every nonzero residue mod m.
#   * a-b pairs: distance 1 if j - i in S, else j - i = (s - t) + u, a path of
#     length 3. The covering condition gives this for every residue.
#   * b-b pairs follow from the same covering condition.
#
# So diameter <= 3 holds exactly when S is a difference cover of Z_m. Since
# d(d-1) >= m - 1 is necessary, m <= d(d-1) + 1 gives the Moore-type bound
# 2(d^2 - d + 1). A perfect difference set would meet it, but none exists for
# d = 16. A simulated-annealing search for a covering S can find m above the
# record's m = 197.
#
# Parent construction (arc-extended projective planes, GQ, voltage lifts) is
# kept as a second source. The best valid graph of all candidates is returned.
# ----------------------------------------------------------------------------

_LS_ITERS = 30000


def _pg_data(q):
    """Return (m, edges, point_lines, line_points, index, pts) for PG(2, q)."""
    pts = lib.projective_points(q)
    n2, edges = lib.projective_plane_incidence(q)
    m = n2 // 2
    point_lines = [[] for _ in range(m)]
    line_points = [[] for _ in range(m)]
    for u, v in edges:
        point_lines[u].append(v - m)
        line_points[v - m].append(u)
    index = {p: i for i, p in enumerate(pts)}
    return m, edges, point_lines, line_points, index, pts


def _loads_ok(S, s, m, nbr):
    """True if every target t is hit by <= s elements of S, where element x hits nbr[x]."""
    load = [0] * m
    for x in S:
        for t in nbr[x]:
            load[t] += 1
    return max(load, default=0) <= s


def _greedy_side(m, s, nbr, rng, trials, deadline):
    """Randomized greedy: choose elements x so that every target is hit by <= s chosen elements."""
    best = []
    order = list(range(m))
    for _ in range(trials):
        if time.monotonic() > deadline:
            break
        rng.shuffle(order)
        load = [0] * m
        S = []
        for x in order:
            if all(load[t] < s for t in nbr[x]):
                S.append(x)
                for t in nbr[x]:
                    load[t] += 1
        if len(S) > len(best):
            best = S
    return best


def _local_search(m, s, nbr, S, rng, deadline, iters):
    """Plateau/improvement local search for the same load-constrained set problem."""
    if s < 1:
        return list(S)
    inS = [False] * m
    hits = [set() for _ in range(m)]
    for x in S:
        inS[x] = True
        for t in nbr[x]:
            hits[t].add(x)
    size = len(S)
    best = list(S)
    best_size = size
    for it in range(iters):
        if (it & 1023) == 0 and time.monotonic() > deadline:
            break
        x = rng.randrange(m)
        if inS[x]:
            continue
        rem = set()
        ok = True
        for t in nbr[x]:
            cur = [y for y in hits[t] if y not in rem]
            if len(cur) >= s:
                rem.add(rng.choice(cur))
                if len(rem) > 2:
                    ok = False
                    break
        if not ok:
            continue
        if len(rem) == 2 and rng.random() > 0.03:
            continue
        for y in rem:
            inS[y] = False
            for t in nbr[y]:
                hits[t].discard(y)
        inS[x] = True
        for t in nbr[x]:
            hits[t].add(x)
        size += 1 - len(rem)
        if size > best_size:
            best_size = size
            best = [i for i in range(m) if inS[i]]
    return best


def _conic_set(q, index, F):
    """Conic (plus nucleus for even q) as a point-index set: an arc with no three collinear."""
    S = [index[(1, t, F.mul(t, t))] for t in range(q)]
    S.append(index[(0, 0, 1)])
    if q % 2 == 0:
        S.append(index[(0, 1, 0)])
    return S


def _arc_graph(m, edges, point_lines, line_points, SA, SB):
    """Old PG incidence plus one new A-vertex per SA point and one new B-vertex per SB line."""
    na, nb = len(SA), len(SB)
    n = 2 * m + na + nb
    E = list(edges)
    for t, P in enumerate(SA):
        x = 2 * m + t
        for L in point_lines[P]:
            E.append((x, m + L))
    for t, j in enumerate(SB):
        b = 2 * m + na + t
        for Q in line_points[j]:
            E.append((Q, b))
    return n, E


def _arc_extensions(d, deadline, rng):
    """Yield (n, edges) candidates for each prime power q with q + 1 <= d."""
    qs = [q for q in range(2, min(d - 1, 23) + 1) if lib.is_prime_power(q)]

    def bound(q):
        s = d - q - 1
        mm = q * q + q + 1
        return 2 * mm + 2 * s * mm // (q + 1)

    qs.sort(key=lambda q: -bound(q))
    out = []
    for q in qs:
        if time.monotonic() > deadline:
            break
        s = d - q - 1
        m, edges, point_lines, line_points, index, pts = _pg_data(q)

        SA = _greedy_side(m, s, point_lines, rng, 40, deadline)
        SB = _greedy_side(m, s, line_points, rng, 40, deadline)
        if s >= 2:
            cs = _conic_set(q, index, lib.GF(q))
            if len(cs) > len(SA) and _loads_ok(cs, s, m, point_lines):
                SA = cs
            if len(cs) > len(SB) and _loads_ok(cs, s, m, line_points):
                SB = cs

        SA = _local_search(m, s, point_lines, SA, rng, deadline, _LS_ITERS)
        SB = _local_search(m, s, line_points, SB, rng, deadline, _LS_ITERS)

        if not (_loads_ok(SA, s, m, point_lines) and _loads_ok(SB, s, m, line_points)):
            continue
        n_c, e_c = _arc_graph(m, edges, point_lines, line_points, SA, SB)
        out.append((n_c, e_c))
    return out


# ----------------------------------------------------------------------------
# Difference-cover search for Haar graphs.
# ----------------------------------------------------------------------------

def _change(S, i, x, cnt, m, sign):
    """Add (sign=+1) or remove (sign=-1) the differences that element x at slot i
    creates with the other slots. Returns the change in the number of uncovered
    nonzero residues."""
    du = 0
    for j, y in enumerate(S):
        if j == i:
            continue
        for a in ((x - y) % m, (y - x) % m):
            if sign > 0:
                if cnt[a] == 0:
                    du -= 1
                cnt[a] += 1
            else:
                cnt[a] -= 1
                if cnt[a] == 0:
                    du += 1
    return du


def _cover_search(m, k, rng, iters, deadline):
    """Find a k-subset S of Z_m whose nonzero differences cover all of Z_m \\ {0}.

    Returns the subset as a list, or None if the budget runs out first.
    """
    if m - 1 > k * (k - 1):
        return None
    S = rng.sample(range(m), k)
    cnt = [0] * m
    unc = m - 1
    for i in range(k):
        for j in range(k):
            if i != j:
                a = (S[i] - S[j]) % m
                if cnt[a] == 0:
                    unc -= 1
                cnt[a] += 1
    if unc == 0:
        return list(S)
    for it in range(iters):
        if (it & 1023) == 0 and time.monotonic() > deadline:
            break
        T = 0.5 * (1.0 - it / iters) + 0.05
        i = rng.randrange(k)
        x = rng.randrange(m)
        if x in S:
            continue
        old = S[i]
        d1 = _change(S, i, old, cnt, m, -1)
        S[i] = x
        d2 = _change(S, i, x, cnt, m, +1)
        delta = d1 + d2
        if delta <= 0 or rng.random() < math.exp(-delta / T):
            unc += delta
            if unc == 0:
                return list(S)
        else:
            _change(S, i, x, cnt, m, -1)
            S[i] = old
            _change(S, i, old, cnt, m, +1)
    return None


def _haar_search(d, deadline, rng):
    """Ascend over m; for each m try to find a difference cover of size d.

    Returns (m, S) for the largest m that succeeded (or (0, None))."""
    best_m, best_S = 0, None
    m = max(d, 3)
    hi = d * (d - 1) + 1
    while m <= hi and time.monotonic() < deadline:
        found = None
        for _ in range(2):
            if time.monotonic() > deadline:
                break
            found = _cover_search(m, d, rng, 40000, deadline)
            if found is not None:
                break
        if found is not None:
            best_m, best_S = m, found
        m += 1
    return best_m, best_S


