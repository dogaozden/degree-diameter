def build(d, D, seed, time_limit):
    t0 = time.monotonic()
    total = max(2.0, 0.80 * time_limit - 2.0)
    end = t0 + total
    rng = random.Random(seed)

    if d < 1 or D < 1:
        return 1, []
    if D == 1:
        return 2, [(0, 1)]

    # Safe fallback: K_{d,d} has diameter 2.
    best = lib.haar_graph(d, range(d))

    def consider(g):
        nonlocal best
        if g[0] > best[0] and lib.is_valid(g[0], g[1], d, D):
            best = (g[0], list(g[1]))

    if D == 2 or d < 2:
        return best[0], list(best[1])

    # Arc-extended projective plane graphs (diameter 3, and valid for D >= 3).
    if D >= 3:
        arcs = _arc_extensions(d, t0 + 0.10 * total, random.Random(seed * 7919 + d))
        for g in sorted(arcs, key=lambda t: -t[0])[:2]:
            consider(g)

    # D = 3: cyclic difference-cover Haar graph H(m, S), |S| = d, found in C.
    if D == 3:
        tl = 0.5 * (end - time.monotonic())
        if tl > 1.0:
            try:
                out = lib.run_c(C_SOURCE, ["0", d, D, seed, round(tl, 2)],
                                stdin_graph=None, timeout=tl + 8)
                consider(lib.parse_graph_text(out))
            except Exception:
                pass

    # D >= 4: generalized quadrangle and voltage-lift annealing.
    if D >= 4:
        if time.monotonic() < t0 + 0.30 * total:
            gq = _best_gq(d)
            if gq is not None:
                consider(gq)
        vend = t0 + 0.55 * total
        ks = [1, 2, 2, 3, 4] if D >= 5 else [1, 1, 2, 3]
        while time.monotonic() < vend:
            k = rng.choice(ks)
            base = best[0] // (2 * k)
            G = max(2, base + 1 + rng.randrange(0, max(3, base // 8 + 1)))
            g = _sample_group(G, rng)
            if g is None:
                continue
            order, mul = g
            res = _anneal(d, D, k, order, mul, rng, vend, iters=400)
            if res is not None:
                consider(res)

    # Augmentation: C search adds vertices to the best graph found so far.
    rem = end - time.monotonic()
    if rem > 2.0:
        try:
            out = lib.run_c(C_SOURCE, ["1", d, D, seed, round(rem - 1.0, 2)],
                            stdin_graph=best, timeout=rem + 8)
            consider(lib.parse_graph_text(out))
        except Exception:
            pass

    if not lib.is_valid(best[0], best[1], d, D):
        best = lib.haar_graph(d, range(d))
    return best[0], list(best[1])
