def build(d, D, seed, time_limit):
    start = time.monotonic()
    T = float(time_limit)
    rng = random.Random(seed)

    if d < 1 or D < 1:
        return 1, []
    if D == 1:
        return 2, [(0, 1)]

    # Safe fallback: K_{d,d} has diameter 2, so it is valid for D >= 2.
    best = lib.haar_graph(d, range(d))
    best_n = best[0]

    def consider(n, e):
        nonlocal best, best_n
        if n > best_n and lib.is_valid(n, e, d, D):
            best = (n, e)
            best_n = n

    arc_best = None
    if D >= 3:
        arcs = _arc_extensions(d, start + 0.20 * T, random.Random(seed * 7919 + d))
        arcs.sort(key=lambda t: -t[0])
        for n_c, e_c in arcs[:3]:
            consider(n_c, e_c)
        if arcs:
            arc_best = arcs[0]

    if D == 3:
        # Main search: difference-cover Haar graphs, climbing m above the arc baseline.
        hg = _difference_graph(d, start + 0.80 * T, seed, lo=best_n // 2 - 5)
        if hg is not None:
            consider(hg[0], hg[1])
        # Extra vertices on the arc graph, if its spare degree allows.
        if arc_best is not None and time.monotonic() < start + 0.90 * T:
            n2, e2 = _augment(arc_best[0], arc_best[1], d, D, rng, start + 0.90 * T)
            consider(n2, e2)
    else:
        if arc_best is not None and time.monotonic() < start + 0.30 * T:
            n2, e2 = _augment(arc_best[0], arc_best[1], d, D, rng, start + 0.30 * T)
            consider(n2, e2)

        if D >= 4 and time.monotonic() < start + 0.35 * T:
            gq = _best_gq(d)
            if gq is not None:
                consider(gq[0], gq[1])

        search_end = start + 0.80 * T
        ks = [1, 2, 2, 3, 4] if D >= 5 else [1, 1, 2, 3]
        while time.monotonic() < search_end:
            k = rng.choice(ks)
            base = best_n // (2 * k)
            G = max(2, base + 1 + rng.randrange(0, max(3, base // 8 + 1)))
            g = _sample_group(G, rng)
            if g is None:
                continue
            order, mul = g
            res = _anneal(d, D, k, order, mul, rng, search_end, iters=400)
            if res is not None:
                consider(res[0], res[1])

        if time.monotonic() < start + 0.90 * T:
            n_f, e_f = _augment(best[0], best[1], d, D, rng, start + 0.90 * T)
            consider(n_f, e_f)

    if not lib.is_valid(best[0], best[1], d, D):
        best = lib.haar_graph(d, range(d))
    return best
