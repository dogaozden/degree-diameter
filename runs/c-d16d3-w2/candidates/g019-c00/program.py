def build(d, D, seed, time_limit):
    start = time.monotonic()
    rng = random.Random(seed)

    if d < 1 or D < 1:
        return 1, []
    if D == 1:
        return 2, [(0, 1)]

    # Safe fallback: K_{d,d} has diameter 2, valid for D >= 2.
    best = lib.haar_graph(d, range(d))
    best_n = best[0]

    def consider(n, e):
        nonlocal best, best_n
        if n > best_n and lib.is_valid(n, e, d, D):
            best = (n, e)
            best_n = n

    if D == 3:
        # 1. Arc-extended projective plane graphs (about 2(q^2+q+5) for d=q+2 cases).
        arcs = _arc_extensions(d, start + 0.12 * time_limit, random.Random(seed * 7919 + d))
        arcs.sort(key=lambda t: -t[0])
        for n_c, e_c in arcs[:3]:
            consider(n_c, e_c)
        # 2. Greedy spare-degree fill on the best arc graph.
        if arcs and time.monotonic() < start + 0.3 * time_limit:
            n_a, e_a = arcs[0]
            n_f, e_f = _fill(n_a, e_a, d, D, start + 0.3 * time_limit,
                             random.Random(seed * 104729 + d))
            consider(n_f, e_f)
        # 3. Cyclic Haar graphs from difference covers of size d (m may exceed the arc size).
        hg = _difference_graph(d, start + 0.92 * time_limit, rng)
        if hg is not None:
            consider(hg[0], hg[1])
    else:
        if D >= 4 and time.monotonic() < start + 0.3 * time_limit:
            gq = _best_gq(d)
            if gq is not None:
                consider(gq[0], gq[1])

        search_end = start + 0.75 * time_limit
        ks = [1, 2, 2, 3, 4] if D >= 5 else [1, 1, 2, 3]
        while time.monotonic() < search_end:
            k = rng.choice(ks)
            base = best_n // (2 * k)
            G = max(2, base + 1 + rng.randrange(0, max(3, base // 8 + 1)))
            g = _sample_group(G, rng)
            if g is None:
                continue
            order, mul = g
            res = _anneal(d, D, k, order, mul, rng, search_end, iters=400)
            if res is not None:
                consider(res[0], res[1])

    if not lib.is_valid(best[0], best[1], d, D):
        best = lib.haar_graph(d, range(d))
    return best
