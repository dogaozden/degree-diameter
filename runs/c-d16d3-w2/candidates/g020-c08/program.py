# C annealing wrapper.
# ----------------------------------------------------------------------------

def _c_anneal(graph, d, D, seed, budget):
    """Run the C annealer from graph; return (n, edges) or None on any failure."""
    if graph is None or budget < 0.5 or d > 32:
        return None
    try:
        out = lib.run_c(C_SOURCE, [d, D, seed, round(budget, 2)],
                        stdin_graph=(graph[0], graph[1]), timeout=budget + 8.0)
        n2, e2 = lib.parse_graph_text(out)
    except Exception:
        return None
    if n2 < 1:
        return None
    return n2, e2


# ----------------------------------------------------------------------------
# Driver.
#   D == 3: best of arc-extended PG graphs and cyclic Haar graphs from
#           difference covers, augmented greedily; then C annealing.
#   D == 4: generalized quadrangle W(q) start; then C annealing.
#   else  : K_{d,d} start; then C annealing.
# Every result is checked with lib.is_valid; K_{d,d} is the always-valid fallback.
# ----------------------------------------------------------------------------

def build(d, D, seed, time_limit):
    start = time.monotonic()
    rng = random.Random(seed)

    if d < 1 or D < 1:
        return 1, []
    if D == 1:
        return 2, [(0, 1)]

    def elapsed():
        return time.monotonic() - start

    T = time_limit

    # Safe fallback: K_{d,d} has diameter 2, so it is valid for D >= 2.
    best = lib.haar_graph(d, range(d))

    def consider(g):
        nonlocal best
        if g is None:
            return
        n, e = g
        if n > best[0] and lib.is_valid(n, e, d, D):
            best = (n, e)

    try:
        if D == 3:
            arcs = _arc_extensions(d, start + 0.06 * T,
                                   random.Random(seed * 7919 + d))
            arcs.sort(key=lambda t: -t[0])
            for g in arcs[:3]:
                consider(g)

            hg = _difference_graph(d, start + 0.30 * T, rng)
            if hg is not None:
                consider(hg)

            if arcs and elapsed() < 0.38 * T:
                n_a, e_a = arcs[0]
                n2, e2 = _augment(n_a, e_a, d, D, rng, start + 0.38 * T)
                consider((n2, e2))
            if elapsed() < 0.42 * T:
                n_b, e_b = _augment(best[0], best[1], d, D, rng, start + 0.42 * T)
                consider((n_b, e_b))
        elif D == 4:
            consider(_best_gq(d))
    except Exception:
        pass

    budget = 0.85 * T - elapsed() - 1.0
    if budget >= 0.5:
        consider(_c_anneal(best, d, D, seed, budget))

    if not lib.is_valid(best[0], best[1], d, D):
        best = lib.haar_graph(d, range(d))
    return best
