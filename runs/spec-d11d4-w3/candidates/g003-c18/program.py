def build(d, D, seed, time_limit):
    start = time.monotonic()
    deadline = start + max(0.5, 0.88 * time_limit - 5.0)
    rng = random.Random(seed)
    nprng = np.random.default_rng(abs(int(seed)) % (2 ** 32))

    if d < 1 or D < 1:
        return 1, []
    if D == 1:
        return 2, [(0, 1)]

    # Safe fallback: K_{d,d} has diameter 2.
    best = lib.haar_graph(d, range(d))
    best_n = best[0]

    def consider(n, e):
        nonlocal best, best_n
        if n > best_n and lib.is_valid(n, e, d, D):
            best = (n, e)
            best_n = n

    if D == 2:
        return best

    pg = _pg(d)
    if pg is not None:
        consider(pg[0], pg[1])

    # Blow-up of W(q) (D >= 4) or PG(2,q) (D = 3), base degree d-1, q = d-2.
    q = d - 2
    if 2 <= q <= 11 and lib.is_prime_power(q):
        if D >= 4:
            n0, e0 = _gq(q)
        else:
            n0, e0 = lib.projective_plane_incidence(q)
        consider(n0, e0)

        now = time.monotonic()
        span = max(0.0, deadline - now)
        blow_dl = now + 0.55 * span if D >= 4 else deadline
        res = _blowup(n0, e0, d, blow_dl, rng, nprng)
        if res is not None:
            consider(res[0], res[1])

        # Spare-degree extension (diameter-4 cover argument), run on the best blow-up.
        if D >= 4:
            src = res if res is not None else (n0, e0)
            try:
                ext = _extend(src[0], src[1], d, deadline, rng)
                consider(ext[0], ext[1])
            except Exception:
                pass

    if not lib.is_valid(best[0], best[1], d, D):
        best = lib.haar_graph(d, range(d))
    return best
