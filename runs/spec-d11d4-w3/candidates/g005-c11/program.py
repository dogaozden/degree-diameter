def build(d, D, seed, time_limit):
    t0 = time.monotonic()
    budget = max(1.0, min(0.92 * time_limit, time_limit - 5.0))
    deadline = t0 + budget
    rng = random.Random(seed)
    nprng = np.random.default_rng(abs(int(seed)) % (2 ** 32))

    if d < 1 or D < 1:
        return 1, []
    if D == 1:
        return 2, [(0, 1)]

    # Safe fallback: K_{d,d}, valid for D >= 2.
    best = lib.haar_graph(d, range(d))

    def consider(n, edges):
        nonlocal best
        if n > best[0] and lib.is_valid(n, edges, d, D):
            best = (n, edges)
            return True
        return False

    if D == 2:
        return best

    structured = False

    # Projective plane incidence graph: degree d, diameter 3.
    if D >= 3:
        pg = _pg(d)
        if pg is not None and consider(*pg):
            structured = True
    if D == 3 and structured:
        return best

    q = d - 2
    if D >= 4 and 2 <= q <= 11 and lib.is_prime_power(q) and time.monotonic() < deadline - 2.0:
        geo = None
        try:
            geo = _symplectic_quadrangle(q)
        except Exception:
            geo = None

        if geo is not None:
            # Route A: exact spread on lines side, searched partial ovoid on points side,
            # then greedy extension into the remaining spare line slots.
            try:
                npts, lines, spread = geo
                n0 = npts + len(lines)
                edges0 = [(p, npts + j) for j, L in enumerate(lines) for p in L]
                if consider(n0, edges0):
                    structured = True
                now = time.monotonic()
                ov_dl = now + 0.5 * max(0.0, deadline - now)
                O = _ovoid_search(npts, lines, rng, nprng, ov_dl)
                S = list(O) + [npts + j for j in spread]
                n1, e1 = _blow(n0, edges0, S)
                if consider(n1, e1):
                    structured = True
                n2, e2 = _extend(n1, e1, d, deadline, rng)
                if consider(n2, e2):
                    structured = True
            except Exception:
                pass
        else:
            # Route B: twin construction on W(q), then extension.
            try:
                now = time.monotonic()
                n2, e2 = _twin_graph(q, now + 0.4 * max(0.0, deadline - now), rng)
                if consider(n2, e2):
                    structured = True
                n3, e3 = _extend(n2, e2, d, deadline, rng)
                if consider(n3, e3):
                    structured = True
            except Exception:
                pass

    # Generalized quadrangle W(d-1): degree d, diameter 4.
    if D >= 4 and 2 <= d - 1 <= 11 and lib.is_prime_power(d - 1) and time.monotonic() < deadline:
        try:
            if consider(*_gq_incidence(d - 1)):
                structured = True
        except Exception:
            pass

    # Nothing structured beat K_{d,d}: spend remaining time on cyclic Haar lifts.
    if not structured and time.monotonic() < deadline:
        _haar_search(d, deadline, D, rng, consider)

    if not lib.is_valid(best[0], best[1], d, D):
        return 2, [(0, 1)]
    return best
