def _known_start(d, D):
    """Best directly constructible graph for (d, D), or None."""
    if D == 3 and lib.is_prime_power(d - 1):
        return lib.projective_plane_incidence(d - 1)   # Moore graph: optimal
    if D == 3 and d - 2 >= 3 and lib.is_prime_power(d - 2):
        return lib.araujo_lopez_graph(d - 2)           # record family 2(q^2+q+5)
    return None


def build(d, D, seed, time_limit):
    t0 = time.monotonic()

    def remaining():
        return 0.85 * time_limit - (time.monotonic() - t0) - 2.0

    if d < 1 or D < 1:
        return (1, [])
    if D == 1:
        return (2, [(0, 1)])

    best = lib.haar_graph(d, range(d))   # K_{d,d}: valid for D >= 2

    def consider(cand):
        nonlocal best
        if cand is not None and cand[0] > best[0] and lib.is_valid(cand[0], cand[1], d, D):
            best = cand

    start = _known_start(d, D)
    if start is not None:
        consider(start)

    if best[0] >= lib.moore_bound(d, D):
        return best
    if remaining() < 2.0:
        return best

    # Stage 1: bi-Cayley lift + grow engine, seeded with the best known graph.
    b1 = remaining() * 0.5
    if b1 >= 1.0:
        try:
            text = lib.run_c(C_SOURCE, [d, D, seed, round(b1, 2)],
                             stdin_graph=best, timeout=b1 + 4)
            consider(lib.parse_graph_text(text))
        except (RuntimeError, ValueError):
            pass

    # Stage 2: Haar graphs of non-abelian groups, starting at one vertex per side
    # above the current best (so the search only accepts strict improvements).
    b2 = remaining()
    if b2 >= 1.0:
        try:
            n_lo = best[0] // 2 + 1
            text = lib.run_c(HAAR_SOURCE, [d, D, seed, round(b2, 2), n_lo],
                             stdin_graph=None, timeout=b2 + 3)
            consider(lib.parse_graph_text(text))
        except (RuntimeError, ValueError):
            pass

    if not lib.is_valid(best[0], best[1], d, D):
        best = lib.haar_graph(d, range(d))
    return best
