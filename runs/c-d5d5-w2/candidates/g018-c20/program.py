"""Two-engine program for the weak d=5, D=5 regime.

Stage 1 runs the bi-Cayley lift engine (C_SOURCE) on the best known start.
Stage 2 runs a new engine (HAAR_SOURCE) that searches Haar graphs of non-abelian
groups Z_m x|_r Z_k. A Haar graph on a group G of order N has sides G and G, with
a_g ~ b_{gs} for s in S, |S| = d. Left multiplication is an automorphism, so the
diameter test needs only two BFS runs, from a_e and b_e. Stage 2 is seeded with the
best graph so far, and every output is checked before it is accepted.
"""
