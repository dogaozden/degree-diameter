"""Bi-Cayley (Haar-type) lift search over group families that the parent never tried.

Construction: for a finite group G of order N and a connection set S of size d,
vertices a_g and b_g (g in G) with a_g ~ b_{g s} for s in S. This is a bipartite
d-regular graph on 2N vertices. Left multiplication is an automorphism, so diameter
<= D reduces to two BFS runs, from a_e and from b_e.

Groups: random subgroups of PGL(2, q) for prime q <= 13 (generated by 2-3 random
projective maps, so the group is non-abelian and often PGL(2,7) of order 336, which
gives 672 vertices), and random semidirect products Z_m x| Z_k.

Search: simulated annealing over S, with cost = unreached (source, vertex) pairs.
The best valid graph found is returned. Python keeps K_{d,d} or the known
projective-plane / Araujo-Pardo-Lopez start as a fallback and only accepts valid output.
"""
import time

import lib

C_SOURCE = r'''
/* Bi-Cayley (Haar-type) lift search.
 * Usage: prog d D seed time_limit     (stdin is ignored)
 * stdout: "n m" then m lines "u v".
 *
 * Vertices a_g = g and b_g = N + g for g in G, |G| = N.
 * Edges: a_g ~ b_{g*s} for each s in S, |S| = d (distinct elements).
 * Cost(S) = (2N - |ball_D(a_e)|) + (2N - |ball_D(b_e)|); cost 0 <=> diameter <= D.
 */
#define _POSIX_C_SOURCE 200809L
#include <math.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <time.h>

#define MAXG 512
#define MAXD 32
#define MAXP 14
#define HSIZE 4096
#define MAXE 20000
#define MAXV (2 * MAXG)

static int d, D;
static long moore;
static double t_start, t_end;

static int best_n = 0, best_m = 0;
static int BE_U[MAXE], BE_V[MAXE];

/* ------------------------------------------------------------ utilities */

static double now(void) {
    struct timespec ts;
    clock_gettime(CLOCK_MONOTONIC, &ts);
    return ts.tv_sec + ts.tv_nsec * 1e-9;
}

static uint64_t rng_state = 88172645463325252ULL;
static uint64_t rnd(void) {
    rng_state ^= rng_state << 13;
    rng_state ^= rng_state >> 7;
    rng_state ^= rng_state << 17;
    return rng_state;
}
static int rndint(int k) { return (int)(rnd() % (uint64_t)k); }
static double rnd01(void) { return (rnd() >> 11) * (1.0 / 9007199254740992.0); }

static int gcd_i(int a, int b) {
    while (b) { int t = a % b; a = b; b = t; }
    return a;
}

static long powmod(long b, long e, long m) {
    long r = 1 % m;
    b %= m;
    if (b < 0) b += m;
    while (e > 0) {
        if (e & 1) r = r * b % m;
        b = b * b % m;
        e >>= 1;
    }
    return r;
}

static int minv(int y, int q) { return (int)powmod(y, q - 2, q); }

static long compute_moore(void) {
    if (D <= 0 || d <= 0) return 1;
    if (d == 1) return 2;
    long s = 0, p = 1;
    for (int i = 0; i < D; i++) {
        s += p;
        p *= (d - 1);
        if (s > 100000000L) break;
    }
    return 2 * s;
}

/* ------------------------------------------------------------ group storage */

static int G_N;
static int MUL[MAXG * MAXG];          /* MUL[x*N+y] = index of x*y, identity = 0 */
static int G_INV[MAXG];
static unsigned char PERM[MAXG][MAXP];
static uint64_t HK[HSIZE];
static int HV[HSIZE];

static uint64_t pack(const unsigned char *p, int P) {
    uint64_t k = 0;
    for (int i = 0; i < P; i++) k |= (uint64_t)p[i] << (4 * i);
    return k;
}

static int hslot(uint64_t k) {
    uint64_t h = k * 0x9E3779B97F4A7C15ULL;
    return (int)(h >> 52) & (HSIZE - 1);
}

static int hfind(uint64_t k) {
    int s = hslot(k);
    while (HV[s] >= 0) {
        if (HK[s] == k) return HV[s];
        s = (s + 1) & (HSIZE - 1);
    }
    return -1;
}

static void hinsert(uint64_t k, int v) {
    int s = hslot(k);
    while (HV[s] >= 0) s = (s + 1) & (HSIZE - 1);
    HK[s] = k;
    HV[s] = v;
}

/* Subgroup generated by gens (permutations of P points), by BFS from the identity.
 * Returns the order, or 0 if the order would exceed cap. */
static int closure_gen(unsigned char gens[][MAXP], int ng, int P, int cap) {
    memset(HV, -1, sizeof HV);
    for (int p = 0; p < P; p++) PERM[0][p] = (unsigned char)p;
    hinsert(pack(PERM[0], P), 0);
    int N = 1;
    for (int h = 0; h < N; h++) {
        for (int g = 0; g < ng; g++) {
            unsigned char c[MAXP];
            for (int p = 0; p < P; p++) c[p] = gens[g][PERM[h][p]];
            uint64_t k = pack(c, P);
            if (hfind(k) < 0) {
                if (N >= cap) return 0;
                for (int p = 0; p < P; p++) PERM[N][p] = c[p];
                hinsert(k, N);
                N++;
            }
        }
    }
    return N;
}

static int fill_inverses(void) {
    int N = G_N;
    for (int x = 0; x < N; x++) {
        G_INV[x] = -1;
        for (int y = 0; y < N; y++)
            if (MUL[x * N + y] == 0) { G_INV[x] = y; break; }
        if (G_INV[x] < 0) return 0;
    }
    return 1;
}

/* Multiplication table from the permutations stored by closure_gen. */
static int build_mul(int N, int P) {
    G_N = N;
    for (int x = 0; x < N; x++)
        for (int y = 0; y < N; y++) {
            unsigned char c[MAXP];
            for (int p = 0; p < P; p++) c[p] = PERM[x][PERM[y][p]];
            int z = hfind(pack(c, P));
            if (z < 0) return 0;
            MUL[x * N + y] = z;
        }
    return fill_inverses();
}

/* Semidirect product Z_m x|_r Z_k, element (a,b) = a*k+b, (a,b)(c,e) = (a + r^b c, b+e). */
static int set_semidirect(int m, int k, int r) {
    int N = m * k;
    static int RP[MAXG];
    if (N > MAXG || N < 1) return 0;
    G_N = N;
    RP[0] = 1 % m;
    for (int b = 1; b < k; b++) RP[b] = (int)((long)RP[b - 1] * r % m);
    for (int x = 0; x < N; x++) {
        int a = x / k, b = x % k;
        for (int y = 0; y < N; y++) {
            int c = y / k, e = y % k;
            MUL[x * N + y] = (int)(((long)a + (long)RP[b] * c) % m) * k + (b + e) % k;
        }
    }
    return fill_inverses();
}

/* Uniformly random semidirect product of some order N in [lo, hi]. Returns N or 0. */
static int pick_semidirect(int lo, int hi) {
    int N = lo + rndint(hi - lo + 1);
    long cnt = 0;
    int bm = 0, bk = 0, br = 0;
    for (int m = 1; m <= N; m++) {
        if (N % m) continue;
        int k = N / m;
        for (int r = 0; r < m; r++) {
            if (gcd_i(r, m) != 1) continue;
            if (powmod(r, k, m) != 1 % m) continue;
            cnt++;
            if (rndint((int)cnt) == 0) { bm = m; bk = k; br = r; }
        }
    }
    if (cnt == 0) return 0;
    if (!set_semidirect(bm, bk, br)) return 0;
    return N;
}

/* Random subgroup of PGL(2,q), q in {5,7,11,13}, generated by 2-3 random
 * projective maps. Acts on the q+1 points of the projective line. Returns order or 0. */
static int pick_pgl(int cap) {
    static const int QS[4] = {5, 7, 11, 13};
    int q = QS[rndint(4)];
    int P = q + 1;
    int ng = 2 + rndint(2);
    static unsigned char gens[3][MAXP];
    for (int g = 0; g < ng; g++) {
        int a, b, c, e;
        do {
            a = rndint(q); b = rndint(q); c = rndint(q); e = rndint(q);
        } while ((((long)a * e - (long)b * c) % q + q) % q == 0);
        /* point [x:1] maps to [ax+b : cx+e] */
        for (int x = 0; x < q; x++) {
            int X = (a * x + b) % q, Y = (c * x + e) % q;
            gens[g][x] = (unsigned char)(Y == 0 ? q : (X * minv(Y, q)) % q);
        }
        /* point [1:0] (index q) maps to [a : c] */
        gens[g][q] = (unsigned char)(c == 0 ? q : (a * minv(c, q)) % q);
    }
    int N = closure_gen(gens, ng, P, cap);
    if (N == 0) return 0;
    if (!build_mul(N, P)) return 0;
    return N;
}

/* ------------------------------------------------------------ Haar-type graph */

static int S[MAXD], IS[MAXD];

/* Neighbour i of vertex u in the bi-Cayley graph. */
static inline int nbr(int u, int i) {
    int N = G_N;
    if (u < N) return N + MUL[u * N + S[i]];
    return MUL[(u - N) * N + IS[i]];
}

static int VIS[MAXV], QB[MAXV], gstamp = 0;

/* Number of vertices within distance D of src. */
static int bfs_count(int src) {
    gstamp++;
    int head = 0, tail = 0;
    QB[tail++] = src;
    VIS[src] = gstamp;
    for (int lev = 0; lev < D && head < tail; lev++) {
        int end = tail;
        while (head < end) {
            int u = QB[head++];
            for (int i = 0; i < d; i++) {
                int v = nbr(u, i);
                if (VIS[v] != gstamp) {
                    VIS[v] = gstamp;
                    QB[tail++] = v;
                }
            }
        }
    }
    return tail;
}

/* Unreached (source, vertex) pairs for the two representatives a_e and b_e. */
static long cost_now(void) {
    int N = G_N;
    for (int i = 0; i < d; i++) IS[i] = G_INV[S[i]];
    return (2L * N - bfs_count(0)) + (2L * N - bfs_count(N));
}

static int in_S(int x) {
    for (int i = 0; i < d; i++)
        if (S[i] == x) return 1;
    return 0;
}

/* Simulated annealing over S for the current group. Returns 1 if cost 0 is reached. */
static int sa_group(double until) {
    int N = G_N;
    const int steps = 30000;
    while (now() < until) {
        for (int i = 0; i < d; i++) S[i] = -1;
        for (int i = 0; i < d; i++) {
            int x;
            do x = rndint(N); while (in_S(x));
            S[i] = x;
        }
        long c = cost_now();
        for (int s = 0; s < steps && c > 0; s++) {
            if ((s & 255) == 0 && now() > until) return 0;
            double T = 1.5 * (1.0 - (double)s / steps) + 0.05;
            int i = rndint(d);
            int x;
            do x = rndint(N); while (in_S(x));
            int old = S[i];
            S[i] = x;
            long c2 = cost_now();
            if (c2 <= c || rnd01() < exp((double)(c - c2) / T)) c = c2;
            else S[i] = old;
        }
        if (c == 0) return 1;
    }
    return 0;
}

/* Full check of the current (G, S): every vertex reaches all 2N vertices within D. */
static int full_ok(void) {
    int N = G_N, n = 2 * N;
    for (int i = 0; i < d; i++) IS[i] = G_INV[S[i]];
    for (int s = 0; s < n; s++)
        if (bfs_count(s) != n) return 0;
    return 1;
}

static void store_best(void) {
    int N = G_N, n = 2 * N, m = 0;
    for (int g = 0; g < N; g++)
        for (int i = 0; i < d; i++) {
            if (m >= MAXE) return;
            BE_U[m] = g;
            BE_V[m] = N + MUL[g * N + S[i]];
            m++;
        }
    best_n = n;
    best_m = m;
}

static void search(void) {
    int hi = (int)(moore / 2);
    if (hi > MAXG) hi = MAXG;
    while (now() < t_end) {
        int lo = best_n / 2 + 1;   /* need 2N > best_n */
        if (lo < d + 1) lo = d + 1;
        if (lo > hi) return;
        double rem = t_end - now();
        double slice = 0.15 * (t_end - t_start);
        if (slice > rem) slice = rem;
        if (slice < 0.05) return;
        int N;
        if (rndint(10) < 6) N = pick_pgl(hi);
        else N = pick_semidirect(lo, hi);
        if (N < lo) continue;
        if (sa_group(now() + slice) && full_ok()) store_best();
    }
}

/* ------------------------------------------------------------ main */

int main(int argc, char **argv) {
    if (argc < 5) {
        fprintf(stderr, "usage: %s d D seed time_limit\n", argv[0]);
        return 2;
    }
    d = atoi(argv[1]);
    D = atoi(argv[2]);
    long seed = atol(argv[3]);
    double limit = atof(argv[4]);
    if (d < 1 || d > MAXD || D < 2) {
        printf("0 0\n");
        return 0;
    }
    t_start = now();
    t_end = t_start + limit * 0.9 - 0.5;
    if (t_end < t_start) t_end = t_start;
    rng_state ^= (uint64_t)(seed + 1) * 0x9E3779B97F4A7C15ULL;
    if (!rng_state) rng_state = 1;
    for (int i = 0; i < 10; i++) rnd();
    moore = compute_moore();

    /* Fallback: K_{d,d}, valid for D >= 2. */
    best_n = 2 * d;
    best_m = 0;
    for (int a = 0; a < d; a++)
        for (int b = 0; b < d; b++) {
            BE_U[best_m] = a;
            BE_V[best_m] = d + b;
            best_m++;
        }

    if (best_n < moore) search();

    printf("%d %d\n", best_n, best_m);
    for (int i = 0; i < best_m; i++) printf("%d %d\n", BE_U[i], BE_V[i]);
    return 0;
}
'''


def _known_start(d, D):
    """Best directly constructible graph for (d, D), or None."""
    if D == 3 and lib.is_prime_power(d - 1):
        return lib.projective_plane_incidence(d - 1)   # Moore graph: optimal
    if D == 3 and d - 2 >= 3 and lib.is_prime_power(d - 2):
        return lib.araujo_lopez_graph(d - 2)           # record family 2(q^2+q+5)
    return None


def build(d, D, seed, time_limit):
    t0 = time.monotonic()
    if d < 1 or D < 1:
        return (1, [])
    if D == 1:
        return (2, [(0, 1)])

    best = lib.haar_graph(d, range(d))   # K_{d,d}: valid for D >= 2

    def consider(cand):
        nonlocal best
        if cand is not None and cand[0] > best[0] and lib.is_valid(cand[0], cand[1], d, D):
            best = cand

    start = _known_start(d, D)
    if start is not None:
        consider(start)

    if best[0] >= lib.moore_bound(d, D):
        return best

    budget = 0.85 * time_limit - (time.monotonic() - t0) - 2.0
    if budget < 1.0:
        return best

    try:
        text = lib.run_c(C_SOURCE, [d, D, seed, round(budget, 2)],
                         stdin_graph=None, timeout=budget + 10)
        consider(lib.parse_graph_text(text))
    except (RuntimeError, ValueError):
        pass

    if not lib.is_valid(best[0], best[1], d, D):
        best = lib.haar_graph(d, range(d))
    return best
