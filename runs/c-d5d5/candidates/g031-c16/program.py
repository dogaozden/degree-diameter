"""Bi-Cayley group search: a substantially different construction for the weak cases.

The parent's C voltage-lift engine is replaced. Python builds a bi-Cayley bipartite graph
over a finite permutation group G of order N. Left vertices are g in G and right vertices are
h in G. Each left g is joined to right g*s for s in a connection set S of d distinct
elements. Left multiplication is an automorphism, so the diameter is at most D iff a BFS
of depth D from the left identity and from the right identity reaches all 2N vertices.
That gives 2N vertices and degree d.

Groups come from direct products of small permutation groups (S4, A4, A5, S5, PGL(2,7))
with cyclic groups. A round-robin anneal over connection sets runs on each group with
doubling time slices, from the largest order down. The first success sets a new floor,
and only larger orders are tried after that. The start is K_{d,d}, or the known
construction for D = 3 or 4 when one exists. Every output is re-checked with lib.is_valid,
and any failure falls back to the start graph.
"""
import itertools
import math
import random
import time

import lib


# ------------------------------------------------------------ permutation groups

def _compose(x, y):
    """Return x o y as tuples, with (x o y)[i] = x[y[i]]."""
    return tuple(x[i] for i in y)


def _closure(gens, cap):
    """Return (elements, index) of the group generated by the permutations gens, or None if larger than cap."""
    n = len(gens[0])
    e = tuple(range(n))
    elems = [e]
    idx = {e: 0}
    i = 0
    while i < len(elems):
        x = elems[i]
        i += 1
        for g in gens:
            y = _compose(x, g)
            if y not in idx:
                if len(elems) >= cap:
                    return None
                idx[y] = len(elems)
                elems.append(y)
    return elems, idx


def _mult_table(elems, idx):
    """Return mul with mul[a][b] = index of elems[a] * elems[b]."""
    return [[idx[_compose(a, b)] for b in elems] for a in elems]


def _ext(gens, n0, k):
    """Direct product with a cyclic group Z_k acting on k fresh points after the first n0 points."""
    total = n0 + k
    out = [tuple(list(g) + list(range(n0, total))) for g in gens]
    if k > 1:
        cyc = list(range(total))
        for j in range(k):
            cyc[n0 + j] = n0 + (j + 1) % k
        out.append(tuple(cyc))
    return out


def _pgl27():
    """PGL(2,7) on the projective line 0..6 plus infinity (index 7)."""
    g1 = tuple([(x + 1) % 7 for x in range(7)] + [7])
    g2 = tuple([(3 * x) % 7 for x in range(7)] + [7])
    g3 = [0] * 8
    g3[0] = 7
    g3[7] = 0
    for x in range(1, 7):
        g3[x] = (-pow(x, 5, 7)) % 7
    return [g1, g2, tuple(g3)]


_S4 = [(1, 0, 2, 3), (1, 2, 3, 0)]
_A4 = [(1, 2, 0, 3), (1, 0, 3, 2)]
_A5 = [(1, 2, 0, 3, 4), (0, 1, 3, 4, 2)]
_S5 = [(1, 0, 2, 3, 4), (1, 2, 3, 4, 0)]

# (name, generators, number of base points, list of cyclic factor orders k)
_SPECS = [
    ("S4", _S4, 4, range(6, 15)),
    ("A5", _A5, 5, (3, 4, 5)),
    ("S5", _S5, 5, (2,)),
    ("A4", _A4, 4, (16, 20, 24, 28)),
    ("PGL27", _pgl27(), 8, (1,)),
]


# ------------------------------------------------------------ bi-Cayley search

def _cost(S, mul, inv, N, D):
    """Unreached (vertex, source) pairs from the two base vertices within depth D. Zero means valid."""
    Sinv = [inv[s] for s in S]
    adj = [[N + row[s] for s in S] for row in mul]          # left g -> right g*s
    adj += [[row[t] for t in Sinv] for row in mul]          # right h -> left h*s^-1
    n2 = 2 * N
    total = 0
    for src in (0, N):
        seen = bytearray(n2)
        seen[src] = 1
        frontier = [src]
        cnt = 1
        for _ in range(D):
            nxt = []
            for v in frontier:
                for u in adj[v]:
                    if not seen[u]:
                        seen[u] = 1
                        nxt.append(u)
            if not nxt:
                break
            cnt += len(nxt)
            frontier = nxt
        total += n2 - cnt
    return total


def _anneal(mul, inv, N, d, D, until, rng):
    """Anneal a connection set S of d distinct group elements; return S with zero cost, or None."""
    S = rng.sample(range(N), d)
    c = _cost(S, mul, inv, N, D)
    steps = 3000
    s = 0
    while c > 0:
        if time.monotonic() >= until:
            return None
        pos = rng.randrange(d)
        t = rng.randrange(N)
        if t in S:
            continue
        S2 = list(S)
        S2[pos] = t
        c2 = _cost(S2, mul, inv, N, D)
        T = 1.5 * (1.0 - s / steps) + 0.05
        if c2 <= c or rng.random() < math.exp(-(c2 - c) / T):
            S, c = S2, c2
        s += 1
        if s >= steps:
            s = 0
    return S


def _group_search(d, D, best_n, until, seed):
    """Return (n, edges) for the largest bi-Cayley graph found with n > best_n, or None."""
    rng = random.Random(seed * 7919 + 31 * d + D)
    moore = lib.moore_bound(d, D)
    cands = []
    for name, gens, n0, ks in _SPECS:
        for k in ks:
            cl = _closure(_ext(gens, n0, k), 400)
            if cl is None:
                continue
            elems, idx = cl
            N = len(elems)
            if N < d or 2 * N <= best_n or 2 * N > moore:
                continue
            cands.append((N, name, k, elems, idx))
    if not cands:
        return None
    cands.sort(key=lambda c: -c[0])
    slice_t = max(0.5, (until - time.monotonic()) / (3.0 * len(cands)))
    tables = {}
    best = None
    while time.monotonic() < until:
        if best is not None and cands[0][0] <= best[0]:
            break
        for N, name, k, elems, idx in cands:
            if best is not None and N <= best[0]:
                continue
            now = time.monotonic()
            if now >= until:
                break
            key = (name, k)
            if key not in tables:
                mul = _mult_table(elems, idx)
                inv = [row.index(0) for row in mul]
                tables[key] = (mul, inv)
            mul, inv = tables[key]
            S = _anneal(mul, inv, N, d, D, min(until, now + slice_t), rng)
            if S is not None:
                best = (N, S, mul)
        slice_t *= 2.0
    if best is None:
        return None
    N, S, mul = best
    edges = [(g, N + mul[g][s]) for g in range(N) for s in S]
    return 2 * N, edges


# ------------------------------------------------------------ known constructions

def _gq_w(q):
    """Incidence graph of points and lines of the generalized quadrangle W(q); diameter 4, degree q+1."""
    F = lib.GF(q)
    pts = [v for v in itertools.product(range(q), repeat=4)
           if any(v) and next(c for c in v if c) == 1]
    index = {v: i for i, v in enumerate(pts)}
    P = len(pts)

    def norm(v):
        c = next(x for x in v if x)
        inv = F.inv(c)
        return tuple(F.mul(inv, x) for x in v)

    def form(x, y):
        t = F.sub(F.mul(x[0], y[1]), F.mul(x[1], y[0]))
        return F.add(t, F.sub(F.mul(x[2], y[3]), F.mul(x[3], y[2])))

    covered = set()
    lines = []
    for i in range(P):
        x = pts[i]
        for j in range(i + 1, P):
            if (i, j) in covered:
                continue
            y = pts[j]
            if form(x, y) != 0:
                continue
            L = set()
            for a in range(q):
                for b in range(q):
                    if a == 0 and b == 0:
                        continue
                    v = tuple(F.add(F.mul(a, x[k]), F.mul(b, y[k])) for k in range(4))
                    if any(v):
                        L.add(index[norm(v)])
            L = sorted(L)
            lines.append(L)
            for p in L:
                for r in L:
                    if p < r:
                        covered.add((p, r))

    edges = []
    for j, L in enumerate(lines):
        for p in L:
            edges.append((p, P + j))
    return 2 * P, edges


def known_start(d, D):
    """Best known construction Python can build directly for (d, D), or None."""
    if D == 3 and lib.is_prime_power(d - 1):
        return lib.projective_plane_incidence(d - 1)   # Moore graph
    if D == 3 and d - 2 >= 3 and lib.is_prime_power(d - 2):
        return lib.araujo_lopez_graph(d - 2)
    if D == 4:
        for q in range(min(d - 1, 7), 1, -1):
            if lib.is_prime_power(q) and q + 1 <= d:
                return _gq_w(q)
    return None


# ------------------------------------------------------------ entry point

def build(d, D, seed, time_limit):
    t0 = time.monotonic()
    if d < 1 or D < 1:
        return 1, []
    if d == 1 or D == 1:
        return 2, [(0, 1)]

    best = lib.haar_graph(d, range(d))          # K_{d,d}: valid for D >= 2
    try:
        start = known_start(d, D)
    except (ValueError, RuntimeError):
        start = None
    if start is not None and start[0] > best[0] and lib.is_valid(start[0], start[1], d, D):
        best = start

    if best[0] >= lib.moore_bound(d, D):
        return best

    budget = 0.85 * time_limit - (time.monotonic() - t0) - 1.5
    if budget < 0.5:
        return best
    until = time.monotonic() + budget
    try:
        res = _group_search(d, D, best[0], until, seed)
    except Exception:
        res = None
    if res is not None:
        n, edges = res
        if n > best[0] and lib.is_valid(n, edges, d, D):
            best = (n, edges)
    return best
