"""Bold variant: Haar-type bipartite Cayley graphs over random finite permutation groups.

For a group G of order g and a d-subset S of G, the graph has vertices A_x and B_x (x in G),
with A_x adjacent to B_{xs} for s in S. This is d-regular, bipartite, and has 2g vertices.
Left multiplication is an automorphism that is transitive on each side, so the diameter is
<= D iff BFS of depth D from A_e and from B_e reaches everything. Two BFS runs per candidate.

Groups are sampled as closures of random permutation generators (cyclic, block products,
or random small sets), keeping only those with order in a range that can beat the current best.
Every result is re-checked with lib.is_valid. Without a valid improvement, the best known
construction (or K_{d,d}) is returned.
"""
import itertools
import random
import time

import lib


def _compose(p, q):
    """Permutation product (p o q)(i) = p[q[i]]."""
    return tuple(p[i] for i in q)


def _closure(gens, cap):
    """Return (elements, index) of the group generated by gens, or None if it has more than cap elements."""
    ident = tuple(range(len(gens[0])))
    elems = [ident]
    index = {ident: 0}
    frontier = [ident]
    while frontier:
        nxt = []
        for x in frontier:
            for g in gens:
                y = _compose(x, g)
                if y not in index:
                    if len(elems) >= cap:
                        return None
                    index[y] = len(elems)
                    elems.append(y)
                    nxt.append(y)
        frontier = nxt
    return elems, index


def _rand_perm(rng, size):
    p = list(range(size))
    rng.shuffle(p)
    return tuple(p)


def _random_group(rng, cap, min_order):
    """Sample a permutation group with order in [min_order, cap]; return (elems, index) or None."""
    for _ in range(60):
        n = rng.randint(4, 9)
        gens = []
        if rng.random() < 0.4:
            k = rng.randint(1, 3)
            gens = [_rand_perm(rng, n) for _ in range(k)]
        else:
            cuts = sorted(rng.sample(range(1, n), rng.randint(1, min(2, n - 1))))
            bounds = [0] + cuts + [n]
            for a, b in zip(bounds, bounds[1:]):
                size = b - a
                if size < 2:
                    continue
                prefix, suffix = list(range(a)), list(range(b, n))
                if rng.random() < 0.5:
                    cyc = [a + (x + 1) % size for x in range(size)]
                    gens.append(tuple(prefix + cyc + suffix))
                else:
                    for _ in range(rng.randint(1, 2)):
                        p = _rand_perm(rng, size)
                        gens.append(tuple(prefix + [a + x for x in p] + suffix))
        if not gens:
            continue
        res = _closure(gens, cap + 1)
        if res is None:
            continue
        elems, index = res
        if min_order <= len(elems) <= cap:
            return elems, index
    return None


def _reaches_all(src, adj, N, D):
    """True if BFS from src within D steps reaches all N vertices."""
    seen = [False] * N
    seen[src] = True
    frontier = [src]
    cnt = 1
    for _ in range(D):
        nxt = []
        for u in frontier:
            for v in adj[u]:
                if not seen[v]:
                    seen[v] = True
                    nxt.append(v)
        cnt += len(nxt)
        frontier = nxt
        if not frontier:
            break
    return cnt == N


def _group_haar_search(d, D, n_best, deadline, rng):
    """Search Haar-type Cayley bipartite graphs over random groups; return (n, edges) or None."""
    moore = lib.moore_bound(d, D)
    cap = min(moore // 2, 2000)
    best = None
    best_n = n_best
    while time.monotonic() < deadline:
        min_order = max(d, best_n // 2 + 1)
        if min_order > cap:
            break
        grp = _random_group(rng, cap, min_order)
        if grp is None:
            continue
        elems, index = grp
        G = len(elems)
        N = 2 * G
        cache = {}

        def right(s):
            if s not in cache:
                tab = [index[_compose(x, elems[s])] for x in elems]
                inv = [0] * G
                for i, j in enumerate(tab):
                    inv[j] = i
                cache[s] = (tab, inv)
            return cache[s]

        for _ in range(150):
            if time.monotonic() > deadline:
                break
            S = rng.sample(range(G), d)
            tabs = [right(s) for s in S]
            adjA = [[G + tab[i] for tab, _ in tabs] for i in range(G)]
            adjB = [[inv[j] for _, inv in tabs] for j in range(G)]
            adj = adjA + adjB
            if not (_reaches_all(0, adj, N, D) and _reaches_all(G, adj, N, D)):
                continue
            edges = [(i, G + tab[i]) for i in range(G) for tab, _ in tabs]
            if lib.is_valid(N, edges, d, D):
                best = (N, edges)
                best_n = N
                break
    return best


def _gq_w(q):
    """Incidence graph of points and lines of the generalized quadrangle W(q); diameter 4, degree q+1."""
    F = lib.GF(q)
    pts = [v for v in itertools.product(range(q), repeat=4)
           if any(v) and next(c for c in v if c) == 1]
    index = {v: i for i, v in enumerate(pts)}
    P = len(pts)

    def norm(v):
        c = next(x for x in v if x)
        inv = F.inv(c)
        return tuple(F.mul(inv, x) for x in v)

    def form(x, y):
        t = F.sub(F.mul(x[0], y[1]), F.mul(x[1], y[0]))
        return F.add(t, F.sub(F.mul(x[2], y[3]), F.mul(x[3], y[2])))

    covered = set()
    lines = []
    for i in range(P):
        x = pts[i]
        for j in range(i + 1, P):
            if (i, j) in covered:
                continue
            y = pts[j]
            if form(x, y) != 0:
                continue
            L = set()
            for a in range(q):
                for b in range(q):
                    if a == 0 and b == 0:
                        continue
                    v = tuple(F.add(F.mul(a, x[k]), F.mul(b, y[k])) for k in range(4))
                    if any(v):
                        L.add(index[norm(v)])
            L = sorted(L)
            lines.append(L)
            for p in L:
                for r in L:
                    if p < r:
                        covered.add((p, r))

    edges = []
    for j, L in enumerate(lines):
        for p in L:
            edges.append((p, P + j))
    return 2 * P, edges


def known_start(d, D):
    """Best known construction Python can build directly for (d, D), or None."""
    if D == 3 and lib.is_prime_power(d - 1):
        return lib.projective_plane_incidence(d - 1)   # Moore graph
    if D == 3 and d - 2 >= 3 and lib.is_prime_power(d - 2):
        return lib.araujo_lopez_graph(d - 2)
    if D == 4:
        for q in range(min(d - 1, 7), 1, -1):
            if lib.is_prime_power(q) and q + 1 <= d:
                return _gq_w(q)
    return None


def build(d, D, seed, time_limit):
    t0 = time.monotonic()
    if d < 1 or D < 1:
        return 1, []
    if d == 1 or D == 1:
        return 2, [(0, 1)]

    # Safe fallback chain: K_{d,d}, then the best known construction.
    best = lib.haar_graph(d, range(d))          # K_{d,d}: valid for D >= 2
    try:
        start = known_start(d, D)
    except (ValueError, RuntimeError):
        start = None
    if start is not None and start[0] > best[0] and lib.is_valid(start[0], start[1], d, D):
        best = start

    if best[0] >= lib.moore_bound(d, D):
        return best

    deadline = t0 + max(0.5, 0.8 * time_limit - 2.0)
    rng = random.Random(seed * 1000003 + d * 101 + D)
    try:
        cand = _group_haar_search(d, D, best[0], deadline, rng)
    except (ValueError, RuntimeError, IndexError, KeyError, MemoryError):
        cand = None
    if cand is not None and cand[0] > best[0] and lib.is_valid(cand[0], cand[1], d, D):
        best = cand
    return best
