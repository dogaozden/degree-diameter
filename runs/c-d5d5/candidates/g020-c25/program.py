GROUP_LO = 59          # smallest group order worth a table (kb = 3 needs about 59)
GROUP_HI = 340         # largest group order (kb = 1 gives 2*340 = 680 vertices)
TABLE_BUDGET = 600_000 # total multiplication-table entries sent to C
MAX_GROUPS = 48


# ------------------------------------------------------------ group tables

def _compose(x, y):
    """The permutation x after y, as tuples."""
    return tuple(x[i] for i in y)


def _closure(gens, cap):
    """Elements (identity first) and index dict of the generated group, or None if above cap."""
    k = len(gens[0])
    ident = tuple(range(k))
    elems, index = [ident], {ident: 0}
    frontier = [ident]
    while frontier:
        nxt = []
        for x in frontier:
            for g in gens:
                y = _compose(x, g)
                if y not in index:
                    if len(elems) >= cap:
                        return None
                    index[y] = len(elems)
                    elems.append(y)
                    nxt.append(y)
        frontier = nxt
    return elems, index


def _table(elems, index):
    return [[index[_compose(a, b)] for b in elems] for a in elems]


def _invariant(t):
    """Order, commutativity and element-order counts: a cheap isomorphism fingerprint."""
    o = len(t)
    abel = all(t[a][b] == t[b][a] for a in range(o) for b in range(a))
    counts = {}
    for a in range(o):
        p, m = a, 1
        while p != 0:
            p = t[p][a]
            m += 1
        counts[m] = counts.get(m, 0) + 1
    return o, abel, tuple(sorted(counts.items()))


def _semidirect_table(m, k, r):
    """Z_m x|_r Z_k with element a*k+b, (a,b)(c,e) = (a + r^b c, b + e); identity is index 0."""
    pw = [pow(r, b, m) for b in range(k)]
    o = m * k
    tab = []
    for x in range(o):
        a, b = divmod(x, k)
        row = []
        for y in range(o):
            c, e = divmod(y, k)
            row.append(((a + pw[b] * c) % m) * k + (b + e) % k)
        tab.append(row)
    return tab


def _perm(k, cycles):
    p = list(range(k))
    for cyc in cycles:
        for i, a in enumerate(cyc):
            p[a] = cyc[(i + 1) % len(cyc)]
    return tuple(p)


def _cycle(c):
    return tuple((i + 1) % c for i in range(c))


def _dprod(A, B):
    """Direct product of two permutation groups given as (k, gens), acting on disjoint point sets."""
    ka, ga = A
    kb, gb = B
    k = ka + kb
    return k, ([g + tuple(range(ka, k)) for g in ga] +
               [tuple(range(ka)) + tuple(ka + x for x in g) for g in gb])


def _pgl7(psl):
    """PGL(2,7) (or PSL(2,7) with psl=True) on the projective line 0..6, 7 = infinity."""
    t = tuple((i + 1) % 7 if i < 7 else 7 for i in range(8))
    m = tuple(((2 if psl else 3) * i) % 7 if i < 7 else 7 for i in range(8))
    inv = tuple(7 if i == 0 else (0 if i == 7 else (-pow(i, 5, 7)) % 7) for i in range(8))
    return 8, [t, m, inv]


def _base_specs():
    return {
        "A4": (4, [_perm(4, [(0, 1, 2)]), _perm(4, [(1, 2, 3)])]),
        "S3": (3, [_perm(3, [(0, 1, 2)]), _perm(3, [(0, 1)])]),
        "S4": (4, [_perm(4, [(0, 1, 2, 3)]), _perm(4, [(0, 1)])]),
        "A5": (5, [_perm(5, [(0, 1, 2, 3, 4)]), _perm(5, [(0, 1, 2)])]),
        "S5": (5, [_perm(5, [(0, 1, 2, 3, 4)]), _perm(5, [(0, 1)])]),
        "PSL27": _pgl7(True),
        "PGL27": _pgl7(False),
    }


def _perm_specs():
    """Named permutation groups in the window: bases, base x Z_c, and pairs of bases."""
    bases = {}
    for name, spec in _base_specs().items():
        cl = _closure(spec[1], GROUP_HI)
        if cl is not None:
            bases[name] = (spec, len(cl[0]))
    out = [(name, spec) for name, (spec, o) in bases.items()]
    for name, (spec, o) in bases.items():
        for c in range(2, GROUP_HI // o + 1):
            if o * c >= GROUP_LO:
                out.append((f"{name}xZ{c}", _dprod(spec, (c, [_cycle(c)]))))
    names = list(bases)
    for i, a in enumerate(names):
        for b in names[i + 1:]:
            out.append((f"{a}x{b}", _dprod(bases[a][0], bases[b][0])))
    return out


def _semi_params():
    """(m, k, r) for Z_m x|_r Z_k with orders in the window; r = 1 gives direct products."""
    out = []
    for o in range(GROUP_LO, GROUP_HI + 1):
        for k in range(1, o + 1):
            if o % k:
                continue
            m = o // k
            if m < 2:
                continue
            for r in range(1, m):
                if gcd(r, m) == 1 and pow(r, k, m) == 1 % m:
                    out.append((m, k, r))
    return out


def _chosen_groups():
    """Deterministic portfolio: mandatory PGL/PSL, then shuffled candidates within budget."""
    rng = random.Random(20240601)
    perm = _perm_specs()
    mandatory = [("perm", s) for s in perm if s[0] in ("PGL27", "PSL27")]
    rest = [("perm", s) for s in perm if s[0] not in ("PGL27", "PSL27")]
    rest += [("semi", p) for p in _semi_params()]
    rng.shuffle(rest)
    chosen, seen, used = [], set(), 0
    for kind, payload in mandatory + rest:
        if len(chosen) >= MAX_GROUPS:
            break
        if kind == "perm":
            gens = payload[1][1]
            cl = _closure(gens, GROUP_HI)
            if cl is None:
                continue
            o = len(cl[0])
            if o < GROUP_LO or used + o * o > TABLE_BUDGET:
                continue
            tab = _table(cl[0], cl[1])
            inv = _invariant(tab)
            if inv in seen:
                continue
            seen.add(inv)
        else:
            m, k, r = payload
            o = m * k
            if used + o * o > TABLE_BUDGET:
                continue
            tab = _semidirect_table(m, k, r)
        used += o * o
        chosen.append((o, tab))
    chosen.sort(key=lambda t: t[0])
    return chosen


def _groups_c_block(chosen):
    ords = [o for o, _ in chosen]
    offs, flat, off = [], [], 0
    for o, tab in chosen:
        offs.append(off)
        for row in tab:
            flat.extend(row)
        off += o * o
    ords_s = ", ".join(map(str, ords))
    offs_s = ", ".join(map(str, offs))
    flat_s = ",".join(map(str, flat))
    return (
        "/*@GROUPS_BEGIN@*/\n"
        f"#define NGRP {len(chosen)}\n"
        f"static const int GORD[NGRP] = {{{ords_s}}};\n"
        f"static const int GOFF[NGRP] = {{{offs_s}}};\n"
        f"static const unsigned short GTAB[{len(flat)}] = {{{flat_s}}};\n"
        "/*@GROUPS_END@*/"
    )


