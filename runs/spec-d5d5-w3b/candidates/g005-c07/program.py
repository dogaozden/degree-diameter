"""Bi-Cayley lifts over non-metacyclic groups (permutation families) for D >= 3.

Construction: vertices A_x and B_x for x in a finite group G of order N; A_x is joined to
B_{x*s} for each s in a connection set S of size d containing the identity (WLOG). The graph
has 2N vertices, is bipartite, and is d-regular. The diameter is checked by BFS from A_e and B_e,
which suffices by left-translation symmetry. Groups are either permutation groups (affine groups
AGL(1,q), AGammaL(1,8), PSL(2,7), A5/S5/S4/A4 times cyclic groups) or semidirect products Z_m x| Z_k.
A hill-climb over S looks for zero unreached pairs. A projective-plane incidence graph and K_{d,d}
serve as valid fallbacks.
"""
import math
import random
import time

import lib

BIG = 10 ** 9
MAX_GROUPS = 10      # groups tried per order N
CLIMB_ITERS = 1500   # hill-climb steps per restart
STALL_LIMIT = 300    # re-randomize after this many non-improving steps
WINDOW = 8           # candidate orders above the current lower bound
MAX_ORDER = 400      # largest permutation group considered
MAX_N = 700          # largest group order whose table we are willing to build
_TABLE_CACHE = {}
_FAMS = None         # list of (order, generators) for permutation families
_PERM_BY_ORDER = None


# ----------------------------------------------------------------------------
# Permutation groups
# ----------------------------------------------------------------------------

def _closure(gens):
    """Elements of the group generated by permutation tuples; None if larger than MAX_ORDER."""
    n = len(gens[0])
    ident = tuple(range(n))
    elems = [ident]
    index = {ident: 0}
    frontier = [ident]
    while frontier:
        nxt = []
        for x in frontier:
            for g in gens:
                y = tuple(g[j] for j in x)
                if y not in index:
                    if len(elems) >= MAX_ORDER:
                        return None
                    index[y] = len(elems)
                    elems.append(y)
                    nxt.append(y)
        frontier = nxt
    return elems, index


def _perm_table(gens):
    """Multiplication table T[x][g] = x*g and inverses for a permutation group (identity = 0)."""
    elems, index = _closure(gens)
    N = len(elems)
    T = []
    for a in elems:
        T.append([index[tuple(a[j] for j in b)] for b in elems])
    invs = [0] * N
    for g in range(N):
        row = T[g]
        for h in range(N):
            if row[h] == 0:
                invs[g] = h
                break
    return T, invs


def _dprod(A, B):
    """Direct product of two permutation groups on disjoint supports."""
    nA, gA = A
    nB, gB = B
    gens = [a + tuple(nA + i for i in range(nB)) for a in gA]
    gens += [tuple(range(nA)) + tuple(nA + j for j in b) for b in gB]
    return nA + nB, gens


def _cycle(k):
    return k, [tuple((i + 1) % k for i in range(k))]


def _affine(q, frob=False):
    """AGL(1,q) acting on GF(q) (optionally with Frobenius, giving AGammaL(1,q) for q = 8)."""
    F = lib.GF(q)
    gens = []
    for i in range(F.k):
        c = F.p ** i
        gens.append(tuple(F.add(x, c) for x in range(q)))
    g = F.primitive_element()
    gens.append(tuple(F.mul(g, x) for x in range(q)))
    if frob:
        gens.append(tuple(F.mul(x, x) for x in range(q)))
    return q, gens


def _families():
    """Build the permutation-group families once and index them by actual order."""
    global _FAMS, _PERM_BY_ORDER
    if _FAMS is not None:
        return
    raw = []
    for q in (9, 11, 13, 16, 17):
        raw.append(_affine(q))
    raw.append(_affine(8, True))
    raw.append((8, [
        tuple([(x + 1) % 7 for x in range(7)] + [7]),
        tuple([(2 * x) % 7 for x in range(7)] + [7]),
        tuple([7] + [(-pow(x, 5, 7)) % 7 for x in range(1, 7)] + [0]),
    ]))
    A5 = (5, [(1, 2, 0, 3, 4), (1, 2, 3, 4, 0)])
    S5 = (5, [(1, 0, 2, 3, 4), (1, 2, 3, 4, 0)])
    S4 = (4, [(1, 0, 2, 3), (1, 2, 3, 0)])
    A4 = (4, [(1, 2, 0, 3), (1, 0, 3, 2)])
    raw += [_dprod(A5, _cycle(2)), _dprod(A5, _cycle(3)), _dprod(A5, _cycle(4)),
            _dprod(S5, _cycle(2)), S5, A5]
    for k in range(3, 15):
        raw.append(_dprod(S4, _cycle(k)))
    for k in range(2, 11):
        raw.append(_dprod(A4, _cycle(k)))

    _FAMS = []
    _PERM_BY_ORDER = {}
    for n, gens in raw:
        res = _closure(gens)
        if res is None:
            continue
        order = len(res[0])
        if order < 2:
            continue
        idx = len(_FAMS)
        _FAMS.append((order, gens))
        _PERM_BY_ORDER.setdefault(order, []).append(idx)


def _groups(N):
    """Semidirect parameters (m, k, r) with m*k = N, giving Z_m x|_r Z_k."""
    out = []
    for k in range(1, N + 1):
        if N % k:
            continue
        m = N // k
        for r in range(m):
            if math.gcd(r, m) == 1 and pow(r, k, m) == 1 % m:
                out.append((m, k, r))
    return out


def _options(N):
    opts = [('p', i) for i in _PERM_BY_ORDER.get(N, [])]
    opts += [('s', m, k, r) for (m, k, r) in _groups(N)]
    return opts


def _table(opt):
    hit = _TABLE_CACHE.get(opt)
    if hit is not None:
        return hit
    if opt[0] == 'p':
        T, invs = _perm_table(_FAMS[opt[1]][1])
    else:
        _, m, k, r = opt
        order, mul, inv = lib.semidirect_group(m, k, r)
        T = [[mul(x, g) for g in range(order)] for x in range(order)]
        invs = [inv(g) for g in range(order)]
    if len(_TABLE_CACHE) >= 40:
        _TABLE_CACHE.clear()
    _TABLE_CACHE[opt] = (T, invs)
    return T, invs


# ----------------------------------------------------------------------------
# Bi-Cayley connection-set search
# ----------------------------------------------------------------------------

def _unreached(N, T, invs, S, D, limit=BIG):
    """Pairs (source, vertex) not within distance D, for sources A_0 and B_0; early exit above limit."""
    Sinv = [invs[g] for g in S]
    total = 0
    for src in (0, N):
        seen = bytearray(2 * N)
        seen[src] = 1
        count = 1
        frontier = [src]
        for _ in range(D):
            nxt = []
            for u in frontier:
                if u < N:
                    row = T[u]
                    for g in S:
                        v = N + row[g]
                        if not seen[v]:
                            seen[v] = 1
                            nxt.append(v)
                else:
                    row = T[u - N]
                    for h in Sinv:
                        v = row[h]
                        if not seen[v]:
                            seen[v] = 1
                            nxt.append(v)
            count += len(nxt)
            frontier = nxt
            if not frontier:
                break
        total += 2 * N - count
        if total > limit:
            return total
    return total


def _climb(N, T, invs, d, D, rng, iters, deadline):
    """Hill-climb S (identity fixed as one element) to zero unreached pairs."""
    def fresh():
        S = [0] + rng.sample(range(1, N), d - 1)
        return S, _unreached(N, T, invs, S, D)

    S, cur = fresh()
    stall = 0
    for _ in range(iters):
        if cur == 0 or time.monotonic() > deadline:
            break
        i = rng.randrange(1, d)
        c = rng.randrange(1, N)
        if c in S:
            continue
        S2 = S[:]
        S2[i] = c
        v = _unreached(N, T, invs, S2, D, limit=cur)
        if v < cur:
            stall = 0
        else:
            stall += 1
        if v <= cur:
            S, cur = S2, v
        if stall > STALL_LIMIT:
            S, cur = fresh()
            stall = 0
    return S if cur == 0 else None


def _search(N, d, D, rng, deadline):
    opts = _options(N)
    rng.shuffle(opts)
    for opt in opts[:MAX_GROUPS]:
        if time.monotonic() > deadline:
            break
        T, invs = _table(opt)
        S = _climb(N, T, invs, d, D, rng, CLIMB_ITERS, deadline)
        if S is not None:
            return T, S
    return None


# ----------------------------------------------------------------------------
# Structured baseline: projective plane incidence graph (diameter 3).
# ----------------------------------------------------------------------------

def _best_pg(d):
    for q in range(d - 1, 1, -1):
        if lib.is_prime_power(q):
            return lib.projective_plane_incidence(q)
    return None


# ----------------------------------------------------------------------------
# Main entry point.
# ----------------------------------------------------------------------------

def build(d, D, seed, time_limit):
    start = time.monotonic()
    budget = max(0.5, min(0.85 * time_limit, time_limit - 4.0))
    deadline = start + budget
    rng = random.Random(seed)

    if d < 1 or D < 1:
        return 1, []
    if D == 1:
        return 2, [(0, 1)]

    # Safe fallback: K_{d,d} has diameter 2 and is valid for every D >= 2.
    best = lib.haar_graph(d, range(d))
    if D == 2:
        return best

    moore = lib._moore_bound(d, D)

    def consider(n, e):
        nonlocal best
        if n > best[0] and lib.is_valid(n, e, d, D):
            best = (n, e)

    if D >= 3:
        pg = _best_pg(d)
        if pg is not None:
            consider(pg[0], pg[1])

    if d < 2 or best[0] >= moore:
        return best

    _families()

    while best[0] < moore and time.monotonic() < deadline:
        lo = best[0] // 2 + 1
        if lo > moore // 2 or lo > MAX_N:
            break
        hi = min(lo + WINDOW, moore // 2 + 1, MAX_N + 1)
        N = rng.randrange(lo, hi)
        res = _search(N, d, D, rng, deadline)
        if res is not None:
            T, S = res
            edges = [(x, N + T[x][g]) for x in range(N) for g in S]
            consider(2 * N, edges)

    if not lib.is_valid(best[0], best[1], d, D):
        best = lib.haar_graph(d, range(d))
    return best
