def build(d, D, seed, time_limit):
    start = time.monotonic()
    rng = random.Random(seed)

    if d < 1 or D < 1:
        return 1, []
    if D == 1:
        return 2, [(0, 1)]

    # Safe fallback: K_{d,d} has diameter 2, valid for D >= 2.
    best = lib.haar_graph(d, range(d))

    def consider(n, e):
        nonlocal best
        if n > best[0] and lib.is_valid(n, e, d, D):
            best = (n, e)

    bases = []
    if D == 3:
        bases = [b for b in _best_pg(d, 2)]
    elif D >= 4:
        qs = [q for q in range(min(d - 1, 9), 1, -1) if lib.is_prime_power(q)][:2]
        for q in qs:
            if time.monotonic() >= start + 0.2 * time_limit:
                break
            bases.append(_gq_w(q))

    for b in bases:
        consider(b[0], b[1])

    moore = lib._moore_bound(d, D)
    if best[0] >= moore:
        return best

    # Phase 1 (D >= 4): bi-Cayley lift search over small non-abelian groups.
    if D >= 4 and d >= 3:
        _lift_search(d, D, rng, start + 0.55 * time_limit, consider)

    # Phase 1b: parent's growth on the generalized-quadrangle bases and the current best.
    expand_frac = 0.4 if D == 3 else 0.7
    expand_deadline = start + expand_frac * time_limit
    rot = 0
    while bases and time.monotonic() < expand_deadline:
        if best[0] > 0 and rng.random() < 0.3:
            src = best
        else:
            src = bases[rot % len(bases)]
            rot += 1
        n2, e2 = _expand(src[0], src[1], d, D, expand_deadline, rng)
        consider(n2, e2)

    # Phase 2: iterated local search on the best graph found.
    search_deadline = start + 0.88 * time_limit
    if time.monotonic() < search_deadline and best[0] >= 2:
        holder = [best]
        _ils(best[0], best[1], d, D, search_deadline, rng, holder)
        if holder[0][0] > best[0] and lib.is_valid(holder[0][0], holder[0][1], d, D):
            best = holder[0]

    return best
