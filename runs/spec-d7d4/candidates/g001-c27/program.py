# Helpers: projective plane and generalized quadrangle bases.
# ----------------------------------------------------------------------------

def _best_pg(d):
    """Incidence graph of PG(2, q) for the largest prime power q with q + 1 <= d."""
    for q in range(d - 1, 1, -1):
        if lib.is_prime_power(q):
            return lib.projective_plane_incidence(q)
    return None


def _gq_w(q):
    """Incidence graph of points and lines of the generalized quadrangle W(q); diameter 4."""
    F = lib.GF(q)
    pts = [v for v in itertools.product(range(q), repeat=4)
           if any(v) and next(c for c in v if c) == 1]
    index = {v: i for i, v in enumerate(pts)}
    P = len(pts)

    def norm(v):
        c = next(x for x in v if x)
        inv = F.inv(c)
        return tuple(F.mul(inv, x) for x in v)

    def form(x, y):
        t = F.sub(F.mul(x[0], y[1]), F.mul(x[1], y[0]))
        return F.add(t, F.sub(F.mul(x[2], y[3]), F.mul(x[3], y[2])))

    covered = set()
    lines = []
    for i in range(P):
        x = pts[i]
        for j in range(i + 1, P):
            if (i, j) in covered:
                continue
            y = pts[j]
            if form(x, y) != 0:
                continue
            L = set()
            for a in range(q):
                for b in range(q):
                    if a == 0 and b == 0:
                        continue
                    v = tuple(F.add(F.mul(a, x[k]), F.mul(b, y[k])) for k in range(4))
                    if any(v):
                        L.add(index[norm(v)])
            L = sorted(L)
            lines.append(L)
            for p in L:
                for r in L:
                    if p < r:
                        covered.add((p, r))

    edges = []
    for j, L in enumerate(lines):
        for p in L:
            edges.append((p, P + j))
    return 2 * P, edges


def _best_gq(d):
    """W(q) for the largest prime power q with q + 1 <= d, restricted to small q for speed."""
    for q in range(min(d - 1, 9), 1, -1):
        if lib.is_prime_power(q):
            return _gq_w(q)
    return None


# ----------------------------------------------------------------------------
# NEW: degree-preserving growth of a regular bipartite graph plus
# annealing on bad pairs (diameter repair by double-edge swaps).
#
# Start from W(q) completed to a d-regular bipartite graph. Each growth step
# adds one vertex x on side 0 and one vertex y on side 1: choose a matching
# (a_i, b_i), i = 1..d, and replace each edge a_i-b_i by a_i-y and x-b_i.
# Every degree stays exactly d. Then double-edge swaps (preserving degrees and
# bipartiteness) are annealed to drive the count of pairs at distance > D to 0.
# The bad-pair count is computed with a numpy matrix power of (I + A).
# ----------------------------------------------------------------------------

def _adj_sets(n, edges):
    adj = [set() for _ in range(n)]
    for u, v in edges:
        adj[u].add(v)
        adj[v].add(u)
    return adj


def _complete_regular(n, edges, d, rng, tries=40):
    """Randomly add edges between deficient opposite-side vertices until d-regular; None on failure."""
    base = _adj_sets(n, edges)
    color = _bipartition(n, [sorted(s) for s in base])
    for _ in range(tries):
        cur = [set(s) for s in base]
        ok = True
        while True:
            defi = [v for v in range(n) if len(cur[v]) < d]
            if not defi:
                break
            a = rng.choice(defi)
            cands = [b for b in defi if color[b] != color[a] and b not in cur[a]]
            if not cands:
                ok = False
                break
            b = rng.choice(cands)
            cur[a].add(b)
            cur[b].add(a)
        if ok:
            return cur, color
    return None


def _mat(n, edges):
    A = np.zeros((n, n), dtype=np.float32)
    for u, v in edges:
        A[u, v] = 1.0
        A[v, u] = 1.0
    return A


def _mat_side0_edges(A, color):
    rows, cols = np.nonzero(A)
    return [(int(u), int(v)) for u, v in zip(rows, cols) if color[u] == 0]


def _mat_all_edges(A):
    rows, cols = np.nonzero(np.triu(A, 1))
    return [(int(u), int(v)) for u, v in zip(rows, cols)]


def _bad_mat(A, D):
    """Number of unordered vertex pairs at distance > D (uses entries of (I + A)^D)."""
    n = A.shape[0]
    M = A + np.eye(n, dtype=np.float32)
    R = M
    for _ in range(D - 1):
        R = R @ M
    return (n * n - int(np.count_nonzero(R > 0))) // 2


def _insert_mat(A, color, d, rng):
    """Return a new matrix with two extra vertices (side 0 and side 1), degrees preserved; None on failure.

    Appends to `color` only on success.
    """
    n = A.shape[0]
    E = _mat_side0_edges(A, color)
    pick = None
    for _ in range(300):
        rng.shuffle(E)
        used_a, used_b, cand = set(), set(), []
        for a, b in E:
            if a in used_a or b in used_b:
                continue
            cand.append((a, b))
            used_a.add(a)
            used_b.add(b)
            if len(cand) == d:
                break
        if len(cand) == d:
            pick = cand
            break
    if pick is None:
        return None
    x, y = n, n + 1
    B = np.zeros((n + 2, n + 2), dtype=np.float32)
    B[:n, :n] = A
    for a, b in pick:
        B[a, b] = B[b, a] = 0.0
        B[a, y] = B[y, a] = 1.0
        B[b, x] = B[x, b] = 1.0
    color.append(0)
    color.append(1)
    return B


def _anneal_mat(A, color, D, rng, deadline, max_iters):
    """Double-edge swaps (degree and bipartition preserving) annealing the bad-pair count to 0."""
    cur = _bad_mat(A, D)
    if cur == 0:
        return True
    E = _mat_side0_edges(A, color)
    if len(E) < 2:
        return False
    T = 0.6
    for it in range(max_iters):
        if cur == 0:
            break
        if (it & 31) == 0 and time.monotonic() > deadline:
            break
        i = rng.randrange(len(E))
        j = rng.randrange(len(E))
        if i == j:
            continue
        a, b = E[i]
        c, e = E[j]
        if a == c or b == e or A[a, e] or A[c, b]:
            continue
        A[a, b] = A[b, a] = 0.0
        A[c, e] = A[e, c] = 0.0
        A[a, e] = A[e, a] = 1.0
        A[c, b] = A[b, c] = 1.0
        new = _bad_mat(A, D)
        if new <= cur or rng.random() < math.exp(-(new - cur) / T):
            cur = new
            E[i] = (a, e)
            E[j] = (c, b)
        else:
            A[a, e] = A[e, a] = 0.0
            A[c, b] = A[b, c] = 0.0
            A[a, b] = A[b, a] = 1.0
            A[c, e] = A[e, c] = 1.0
        T = max(0.25, T * 0.9995)
    return cur == 0


def _search_gq_regular(d, D, deadline, rng):
    """Grow a regular bipartite base by pair insertions, repairing diameter by annealing."""
    base = _best_gq(d)
    if base is None:
        return None
    n, e0 = base
    comp = _complete_regular(n, e0, d, rng)
    if comp is None:
        return None
    adj_sets, color = comp
    edges = [(a, b) for a in range(n) if color[a] == 0 for b in adj_sets[a]]
    A = _mat(n, edges)
    best = None
    if _bad_mat(A, D) == 0:
        best = (n, edges)
    while time.monotonic() < deadline:
        ok = False
        for _ in range(4):
            col_snap = list(color)
            A2 = _insert_mat(A, color, d, rng)
            if A2 is None:
                continue
            left = deadline - time.monotonic()
            if left <= 0:
                break
            slice_end = time.monotonic() + min(left, 6.0)
            if _anneal_mat(A2, color, D, rng, slice_end, 20000):
                A = A2
                ok = True
                break
            color[:] = col_snap
        if not ok:
            break
        best = (A.shape[0], _mat_all_edges(A))
    return best


