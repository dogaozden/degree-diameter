# ----------------------------------------------------------------------------
# Engine B: voltage annealing of bi-Cayley lifts with K base vertices per side.
#
# Usage: prog d D K m k2 r seed slice_seconds
# ----------------------------------------------------------------------------

C_SOURCE = r"""
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>
#include <math.h>
#include <time.h>

#define PEN 1000
#define BIGCOST (1 << 30)
#define STAG 8000

static int DEG, DIAM, K, MM, K2, G, N, NE;
static int *POWR;
static int *dI, *dJ, *dS, *perm, *adj, *cnt, *fr, *nx;
static int *bestS, *bestJ;
static uint32_t *vis;
static uint32_t stamp = 0;
static uint64_t rs = 88172645463325252ULL;

static inline uint64_t rnd64(void) {
    rs ^= rs << 13; rs ^= rs >> 7; rs ^= rs << 17;
    return rs;
}
static inline int rndint(int n) { return (int)(rnd64() % (uint64_t)n); }
static inline double rnd01(void) { return (double)(rnd64() >> 11) * (1.0 / 9007199254740992.0); }

static double elapsed(clock_t t0) {
    return (double)(clock() - t0) / (double)CLOCKS_PER_SEC;
}

static int gcd_int(int a, int b) {
    while (b) { int t = a % b; a = b; b = t; }
    return a;
}

static int gmul(int x, int y) {
    int a = x / K2, b = x % K2, c = y / K2, dd = y % K2;
    long long t = (a + (long long)POWR[b] * c) % MM;
    return (int)(t * K2 + (b + dd) % K2);
}

static void set_perm(int e) {
    int s = dS[e];
    int *pm = perm + (size_t)e * G;
    for (int g = 0; g < G; g++) pm[g] = gmul(g, s);
}

static int cost_fn(void) {
    int dup = 0;
    for (int e1 = 0; e1 < NE; e1++)
        for (int e2 = e1 + 1; e2 < NE; e2++)
            if (dI[e1] == dI[e2] && dJ[e1] == dJ[e2] && dS[e1] == dS[e2]) dup++;

    memset(cnt, 0, sizeof(int) * (size_t)N);
    for (int e = 0; e < NE; e++) {
        int ba = dI[e] * G, bb = (K + dJ[e]) * G;
        const int *pm = perm + (size_t)e * G;
        for (int g = 0; g < G; g++) {
            int a = ba + g, b = bb + pm[g];
            adj[(size_t)a * DEG + cnt[a]++] = b;
            adj[(size_t)b * DEG + cnt[b]++] = a;
        }
    }

    int total = 0;
    for (int ri = 0; ri < 2 * K; ri++) {
        int src = ri * G;
        if (stamp == 0xFFFFFFFFu) {
            memset(vis, 0, sizeof(uint32_t) * (size_t)N);
            stamp = 0;
        }
        stamp++;
        vis[src] = stamp;
        int *cur = fr, *nxt = nx;
        int fn = 1, reached = 1;
        cur[0] = src;
        for (int lv = 0; lv < DIAM && fn > 0; lv++) {
            int nn = 0;
            for (int q = 0; q < fn; q++) {
                int u = cur[q];
                const int *au = adj + (size_t)u * DEG;
                for (int t = 0; t < DEG; t++) {
                    int v = au[t];
                    if (vis[v] != stamp) {
                        vis[v] = stamp;
                        nxt[nn++] = v;
                    }
                }
            }
            reached += nn;
            int *tmp = cur; cur = nxt; nxt = tmp;
            fn = nn;
        }
        total += N - reached;
    }
    return total + PEN * dup;
}

static void save_best(void) {
    memcpy(bestS, dS, sizeof(int) * (size_t)NE);
    memcpy(bestJ, dJ, sizeof(int) * (size_t)NE);
}

int main(int argc, char **argv) {
    if (argc < 9) {
        fprintf(stderr, "usage: prog d D K m k2 r seed slice\n");
        return 1;
    }
    DEG = atoi(argv[1]);
    DIAM = atoi(argv[2]);
    K = atoi(argv[3]);
    MM = atoi(argv[4]);
    K2 = atoi(argv[5]);
    int r = atoi(argv[6]);
    uint64_t seed = strtoull(argv[7], NULL, 10);
    double slice = atof(argv[8]);

    if (DEG < 1 || DIAM < 1 || K < 1 || MM < 1 || K2 < 1 || K2 > 4096) {
        printf("0 0\n");
        return 0;
    }
    if (gcd_int(r, MM) != 1) { printf("0 0\n"); return 0; }
    POWR = malloc(sizeof(int) * (size_t)K2);
    if (!POWR) { printf("0 0\n"); return 0; }
    POWR[0] = 1 % MM;
    for (int b = 1; b < K2; b++) POWR[b] = (int)((long long)POWR[b - 1] * r % MM);
    if (((long long)POWR[K2 - 1] * r) % MM != 1 % MM) { printf("0 0\n"); return 0; }

    G = MM * K2;
    N = 2 * K * G;
    NE = DEG * K;

    rs = seed * 0x9E3779B97F4A7C15ULL ^ 0x1234567ULL;
    if (rs == 0) rs = 1;

    dI = malloc(sizeof(int) * NE);
    dJ = malloc(sizeof(int) * NE);
    dS = malloc(sizeof(int) * NE);
    bestS = malloc(sizeof(int) * NE);
    bestJ = malloc(sizeof(int) * NE);
    perm = malloc(sizeof(int) * (size_t)NE * G);
    adj = malloc(sizeof(int) * (size_t)N * DEG);
    cnt = malloc(sizeof(int) * N);
    fr = malloc(sizeof(int) * N);
    nx = malloc(sizeof(int) * N);
    vis = calloc(N, sizeof(uint32_t));
    int *p = malloc(sizeof(int) * K);
    if (!dI || !dJ || !dS || !bestS || !bestJ || !perm || !adj || !cnt || !fr || !nx || !vis || !p) {
        printf("0 0\n");
        return 0;
    }

    clock_t t0 = clock();
    int found = 0;
    int bestCost = BIGCOST;
    const int RL = 60000;

    while (!found && elapsed(t0) < slice) {
        double T0;
        if (bestCost >= BIGCOST || rnd01() < 0.25) {
            for (int l = 0; l < DEG; l++) {
                for (int i = 0; i < K; i++) p[i] = i;
                for (int i = K - 1; i > 0; i--) {
                    int j = rndint(i + 1);
                    int t = p[i]; p[i] = p[j]; p[j] = t;
                }
                for (int i = 0; i < K; i++) {
                    dI[l * K + i] = i;
                    dJ[l * K + i] = p[i];
                }
            }
            for (int e = 0; e < NE; e++) {
                dS[e] = rndint(G);
                set_perm(e);
            }
            T0 = 2.0;
        } else {
            memcpy(dJ, bestJ, sizeof(int) * (size_t)NE);
            memcpy(dS, bestS, sizeof(int) * (size_t)NE);
            int kick = NE / 8 + 1;
            for (int q = 0; q < kick; q++) dS[rndint(NE)] = rndint(G);
            for (int e = 0; e < NE; e++) set_perm(e);
            T0 = 0.8;
        }
        int cur = cost_fn();
        if (cur < bestCost) { bestCost = cur; save_best(); }
        if (cur == 0) { found = 1; break; }

        int runBest = cur;
        int since = 0;
        for (int it = 0; it < RL; it++) {
            if ((it & 255) == 0 && elapsed(t0) >= slice) break;
            double T = T0 * (1.0 - (double)it / RL) + 0.05;
            if (K > 1 && rnd01() < 0.3) {
                int l = rndint(DEG);
                int i1 = rndint(K);
                int i2 = rndint(K - 1);
                if (i2 >= i1) i2++;
                int e1 = l * K + i1, e2 = l * K + i2;
                int t = dJ[e1]; dJ[e1] = dJ[e2]; dJ[e2] = t;
                int nc = cost_fn();
                if (nc <= cur || rnd01() < exp(-(double)(nc - cur) / T)) {
                    cur = nc;
                } else {
                    t = dJ[e1]; dJ[e1] = dJ[e2]; dJ[e2] = t;
                }
            } else {
                int e = rndint(NE);
                int old = dS[e];
                int ns = rndint(G);
                if (ns == old) continue;
                dS[e] = ns;
                set_perm(e);
                int nc = cost_fn();
                if (nc <= cur || rnd01() < exp(-(double)(nc - cur) / T)) {
                    cur = nc;
                } else {
                    dS[e] = old;
                    set_perm(e);
                }
            }
            if (cur < bestCost) { bestCost = cur; save_best(); }
            if (cur < runBest) { runBest = cur; since = 0; }
            else if (++since > STAG) break;
            if (cur == 0) { found = 1; break; }
        }
    }

    if (found) {
        printf("%d %d\n", N, NE * G);
        for (int e = 0; e < NE; e++) {
            for (int g = 0; g < G; g++) {
                printf("%d %d\n", dI[e] * G + g, (K + dJ[e]) * G + perm[(size_t)e * G + g]);
            }
        }
    } else {
        printf("0 0\n");
    }
    fflush(stdout);
    return 0;
}
"""


# ----------------------------------------------------------------------------
# Engine G (new, different construction): general bipartite simulated
# annealing over edge switches, no group structure.
#
# The graph is a DEG-regular bipartite graph with H + H vertices (A = 0..H-1,
# B = H..2H-1). A move picks edges (a1,b1), (a2,b2) and replaces them with
# (a1,b2), (a2,b1). This keeps every degree equal to DEG and the graph simple
# and bipartite. Cost = number of ordered vertex pairs at distance > DIAM,
# computed with bitset ball expansion. Zero cost means a valid graph.
#
# Usage: prog DEG DIAM H seed slice_seconds
# Prints "N M" and the edges on success, or "0 0".
# ----------------------------------------------------------------------------

GEN_SOURCE = r"""
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>
#include <math.h>
#include <time.h>

static int H, DEG, DIAM, N, W;
static int *nb;
static unsigned char *mat;
static uint64_t *R1, *R2;
static uint64_t rs = 88172645463325252ULL;

static inline uint64_t rnd64(void) {
    rs ^= rs << 13; rs ^= rs >> 7; rs ^= rs << 17;
    return rs;
}
static inline int rndint(int n) { return (int)(rnd64() % (uint64_t)n); }
static inline double rnd01(void) { return (double)(rnd64() >> 11) * (1.0 / 9007199254740992.0); }

static double now_s(void) { return (double)clock() / CLOCKS_PER_SEC; }

static int popc(uint64_t x) {
    x = x - ((x >> 1) & 0x5555555555555555ULL);
    x = (x & 0x3333333333333333ULL) + ((x >> 2) & 0x3333333333333333ULL);
    x = (x + (x >> 4)) & 0x0F0F0F0F0F0F0F0FULL;
    return (int)((x * 0x0101010101010101ULL) >> 56);
}

/* Ordered pairs (u,v) with dist(u,v) > DIAM. Zero iff the graph is good. */
static long cost_fn(void) {
    uint64_t *cur = R1, *nxt = R2;
    memset(cur, 0, sizeof(uint64_t) * (size_t)N * W);
    for (int v = 0; v < N; v++)
        cur[(size_t)v * W + (v >> 6)] |= 1ULL << (v & 63);
    for (int lv = 0; lv < DIAM; lv++) {
        for (int v = 0; v < N; v++) {
            uint64_t *dst = nxt + (size_t)v * W;
            const uint64_t *src = cur + (size_t)v * W;
            memcpy(dst, src, sizeof(uint64_t) * (size_t)W);
            const int *row = nb + (size_t)v * DEG;
            for (int k = 0; k < DEG; k++) {
                const uint64_t *s = cur + (size_t)row[k] * W;
                for (int w = 0; w < W; w++) dst[w] |= s[w];
            }
        }
        uint64_t *t = cur; cur = nxt; nxt = t;
    }
    long reached = 0;
    size_t total = (size_t)N * W;
    for (size_t i = 0; i < total; i++) reached += popc(cur[i]);
    return (long)N * N - reached;
}

/* Replace (a1,b1),(a2,b2) by (a1,b2),(a2,b1). Applying it twice restores the graph. */
static void do_switch(int a1, int k1, int a2, int k2) {
    int b1 = nb[(size_t)a1 * DEG + k1];
    int b2 = nb[(size_t)a2 * DEG + k2];
    nb[(size_t)a1 * DEG + k1] = b2;
    nb[(size_t)a2 * DEG + k2] = b1;
    for (int j = 0; j < DEG; j++)
        if (nb[(size_t)b1 * DEG + j] == a1) { nb[(size_t)b1 * DEG + j] = a2; break; }
    for (int j = 0; j < DEG; j++)
        if (nb[(size_t)b2 * DEG + j] == a2) { nb[(size_t)b2 * DEG + j] = a1; break; }
    mat[(size_t)a1 * N + b1] = 0; mat[(size_t)b1 * N + a1] = 0;
    mat[(size_t)a2 * N + b2] = 0; mat[(size_t)b2 * N + a2] = 0;
    mat[(size_t)a1 * N + b2] = 1; mat[(size_t)b2 * N + a1] = 1;
    mat[(size_t)a2 * N + b1] = 1; mat[(size_t)b1 * N + a2] = 1;
}

/* Random simple DEG-regular bipartite graph by sequential greedy with restarts. */
static int build_init(void) {
    int *bdeg = malloc(sizeof(int) * (size_t)H);
    int *cand = malloc(sizeof(int) * (size_t)H);
    if (!bdeg || !cand) { free(bdeg); free(cand); return 0; }
    int done = 0;
    for (int tr = 0; tr < 300 && !done; tr++) {
        memset(bdeg, 0, sizeof(int) * (size_t)H);
        memset(mat, 0, (size_t)N * N);
        int ok = 1;
        for (int a = 0; a < H && ok; a++) {
            for (int k = 0; k < DEG; k++) {
                int nc = 0;
                for (int b = 0; b < H; b++)
                    if (bdeg[b] < DEG && !mat[(size_t)a * N + H + b]) cand[nc++] = b;
                if (nc == 0) { ok = 0; break; }
                int b = cand[rndint(nc)];
                int bid = H + b;
                bdeg[b]++;
                nb[(size_t)a * DEG + k] = bid;
                nb[(size_t)bid * DEG + (bdeg[b] - 1)] = a;
                mat[(size_t)a * N + bid] = 1;
                mat[(size_t)bid * N + a] = 1;
            }
        }
        if (ok) done = 1;
    }
    free(bdeg);
    free(cand);
    return done;
}

int main(int argc, char **argv) {
    if (argc < 6) { printf("0 0\n"); return 0; }
    DEG = atoi(argv[1]);
    DIAM = atoi(argv[2]);
    H = atoi(argv[3]);
    uint64_t seed = strtoull(argv[4], NULL, 10);
    double slice = atof(argv[5]);

    if (DEG < 2 || DIAM < 1 || H <= DEG || H > 1200) { printf("0 0\n"); return 0; }
    N = 2 * H;
    W = (N + 63) / 64;

    rs = seed * 0x9E3779B97F4A7C15ULL ^ 0x5DEECE66DULL;
    if (rs == 0) rs = 1;

    nb = malloc(sizeof(int) * (size_t)N * DEG);
    mat = calloc((size_t)N * N, 1);
    R1 = malloc(sizeof(uint64_t) * (size_t)N * W);
    R2 = malloc(sizeof(uint64_t) * (size_t)N * W);
    if (!nb || !mat || !R1 || !R2) { printf("0 0\n"); return 0; }

    if (!build_init()) { printf("0 0\n"); return 0; }

    double start = now_s();
    long cur = cost_fn();
    int found = (cur == 0);
    const int RL = 40000;
    long it = 0;

    while (!found) {
        if ((it & 15) == 0 && now_s() - start > slice) break;
        double T = 1.5 * (1.0 - (double)(it % RL) / RL) + 0.05;
        it++;
        int a1 = rndint(H);
        int a2 = rndint(H - 1);
        if (a2 >= a1) a2++;
        int k1 = rndint(DEG), k2 = rndint(DEG);
        int b1 = nb[(size_t)a1 * DEG + k1];
        int b2 = nb[(size_t)a2 * DEG + k2];
        if (mat[(size_t)a1 * N + b2] || mat[(size_t)a2 * N + b1]) continue;
        do_switch(a1, k1, a2, k2);
        long nc = cost_fn();
        if (nc <= cur || rnd01() < exp(-(double)(nc - cur) / T)) {
            cur = nc;
            if (cur == 0) found = 1;
        } else {
            do_switch(a1, k1, a2, k2);
        }
    }

    if (found) {
        printf("%d %d\n", N, H * DEG);
        for (int a = 0; a < H; a++)
            for (int k = 0; k < DEG; k++)
                printf("%d %d\n", a, nb[(size_t)a * DEG + k]);
    } else {
        printf("0 0\n");
    }
    fflush(stdout);
    return 0;
}
"""


