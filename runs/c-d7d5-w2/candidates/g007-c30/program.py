def _anneal_general(d, D, h, seed, slice_s):
    """Run the general edge-switch annealer on a 2h-vertex graph; returns (n, edges) or (0, [])."""
    out = lib.run_c(
        GEN_SOURCE,
        [d, D, h, seed, f"{slice_s:.2f}"],
        timeout=slice_s + 10.0,
    )
    return lib.parse_graph_text(out)


def build(d, D, seed, time_limit):
    start = time.monotonic()
    budget = max(1.0, min(0.85 * time_limit, time_limit - 5.0))
    deadline = start + budget
    search_deadline = start + 0.9 * budget
    span = search_deadline - start
    rng = random.Random(seed)

    if d < 1 or D < 1:
        return 1, []
    if D == 1:
        return 2, [(0, 1)]

    # Safe fallback: K_{d,d} has diameter 2.
    best = lib.haar_graph(d, range(d))

    def consider(n, e):
        nonlocal best
        if n > best[0] and lib.is_valid(n, e, d, D):
            best = (n, e)

    if D >= 3:
        pg = _best_pg(d)
        if pg is not None:
            consider(pg[0], pg[1])
            if D == 3 and lib.is_prime_power(d - 1):
                return best

    if D >= 4 and time.monotonic() < deadline:
        gq = _best_gq(d)
        if gq is not None:
            consider(gq[0], gq[1])
            if D == 4 and d - 1 <= 9 and lib.is_prime_power(d - 1):
                return best

    # Phase B: voltage lift annealing (baseline), first quarter of the search time.
    phaseB_end = start + 0.25 * span
    while True:
        remaining = phaseB_end - time.monotonic()
        if remaining < 1.0:
            break
        slice_s = min(remaining, 12.0)
        k = rng.choice([1, 1, 2, 2, 3])
        base = best[0] // (2 * k)
        target = base + 1 + rng.randrange(0, max(2, base // 10 + 1))
        grp = _sample_group(target, rng)
        if grp is None:
            continue
        m, k2, r = grp
        try:
            out = lib.run_c(
                C_SOURCE,
                [d, D, k, m, k2, r, rng.randrange(1, 10 ** 9), f"{slice_s:.2f}"],
                timeout=slice_s + 10.0,
            )
        except RuntimeError:
            break
        try:
            n, e = lib.parse_graph_text(out)
        except ValueError:
            continue
        consider(n, e)

    # Phase G (bold, different construction): general bipartite annealing over
    # edge switches, aiming at 2h vertices with h just above half the current best.
    # Runs for most of the remaining search time.
    if d >= 3 and D >= 2:
        fails = 0
        while True:
            remaining = search_deadline - time.monotonic()
            if remaining < 2.0:
                break
            h = best[0] // 2 + 1
            if h > 1200 or h <= d:
                break
            slice_s = min(remaining, 12.0)
            try:
                n, e = _anneal_general(d, D, h, rng.randrange(1, 10 ** 9), slice_s)
            except (RuntimeError, ValueError):
                break
            if n == 0:
                fails += 1
                if fails >= 5:
                    break
                continue
            consider(n, e)

    # Phase A: remaining search slot for the voltage lift engine.
    phaseA_end = search_deadline
    while True:
        remaining = phaseA_end - time.monotonic()
        if remaining < 1.0:
            break
        slice_s = min(remaining, 8.0)
        k = rng.choice([1, 2])
        base = best[0] // (2 * k)
        target = base + 1 + rng.randrange(0, max(2, base // 10 + 1))
        grp = _sample_group(target, rng)
        if grp is None:
            continue
        m, k2, r = grp
        try:
            out = lib.run_c(
                C_SOURCE,
                [d, D, k, m, k2, r, rng.randrange(1, 10 ** 9), f"{slice_s:.2f}"],
                timeout=slice_s + 10.0,
            )
        except RuntimeError:
            break
        try:
            n, e = lib.parse_graph_text(out)
        except ValueError:
            continue
        consider(n, e)

    if not lib.is_valid(best[0], best[1], d, D):
        best = lib.haar_graph(d, range(d))

    # Spare-degree extension with the remaining time.
    try:
        n2, e2 = _extend_spare(best[0], best[1], d, D, deadline)
        if n2 > best[0] and lib.is_valid(n2, e2, d, D):
            best = (n2, e2)
    except Exception:
        pass

    if not lib.is_valid(best[0], best[1], d, D):
        best = lib.haar_graph(d, range(d))
    return best
