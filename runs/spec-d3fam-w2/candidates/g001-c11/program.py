import math
import random
import time

import lib


# ----------------------------------------------------------------------------
# Baseline constructions (diameter 3, degree <= d).
# ----------------------------------------------------------------------------

def _best_pg(d):
    """Incidence graph of PG(2, q) for the largest prime power q with q + 1 <= d."""
    for q in range(d - 1, 1, -1):
        if lib.is_prime_power(q):
            return lib.projective_plane_incidence(q)
    return None


# ----------------------------------------------------------------------------
# Haar graphs H(Z_m, S) with |S| = d and S - S = Z_m (a "difference cover").
# Such a graph is bipartite, d-regular, of order 2m, and has diameter <= 3.
#
# New idea: MULTIPLIER-INVARIANT difference covers. Pick a unit u of Z_m with
# small multiplicative order k, and split the nonzero residues into orbits
# {x * u^j}. Build S as {0} together with a union of whole orbits. Searching
# over unions of orbits (instead of over all d-subsets) shrinks the search
# space by about a factor k and makes large m reachable by annealing. Orbit
# swaps keep |S| = d when the swapped orbits have equal size.
# ----------------------------------------------------------------------------

def _cover_cost(S, m):
    """Number of nonzero residues of Z_m that are NOT differences of S."""
    diffs = set()
    for a in S:
        for b in S:
            if a != b:
                diffs.add((a - b) % m)
    return (m - 1) - len(diffs)


def _unit_orbits(m, u):
    """Orbits of nonzero residues under multiplication by the group generated by unit u."""
    H = []
    x = 1
    while True:
        H.append(x)
        x = x * u % m
        if x == 1:
            break
    seen = [False] * m
    seen[0] = True
    orbits = []
    for x in range(1, m):
        if seen[x]:
            continue
        orb = sorted({x * h % m for h in H} - {0})
        for y in orb:
            seen[y] = True
        if orb:
            orbits.append(orb)
    return orbits


def _random_unit(m, rng, max_order):
    """Random unit u of Z_m with multiplicative order in [2, max_order], or None."""
    for _ in range(300):
        u = rng.randrange(2, m)
        if math.gcd(u, m) != 1:
            continue
        k, x = 1, u
        while x != 1 and k <= max_order:
            x = x * u % m
            k += 1
        if x == 1 and 2 <= k <= max_order:
            return u
    return None


def _pick_orbits(orbits, need, rng):
    """Random set of orbit indices whose sizes sum exactly to need, or None."""
    for _ in range(300):
        idx = list(range(len(orbits)))
        rng.shuffle(idx)
        chosen, tot = [], 0
        for i in idx:
            s = len(orbits[i])
            if tot + s <= need:
                chosen.append(i)
                tot += s
                if tot == need:
                    return chosen
    return None


def _orbit_anneal(d, m, orbits, rng, deadline):
    """Anneal over unions of orbits (plus 0) of total size d to cover Z_m by differences."""
    chosen = _pick_orbits(orbits, d - 1, rng)
    if chosen is None:
        return None
    in_set = set(chosen)
    by_size = {}
    for i, o in enumerate(orbits):
        by_size.setdefault(len(o), []).append(i)

    def build_S(ch):
        S = [0]
        for i in ch:
            S.extend(orbits[i])
        return S

    S = build_S(chosen)
    cost = _cover_cost(S, m)
    if cost == 0:
        return S
    start = time.monotonic()
    span = max(1e-6, deadline - start)
    frac = 0.0
    it = 0
    while cost > 0:
        it += 1
        if (it & 63) == 0:
            now = time.monotonic()
            if now >= deadline:
                return None
            frac = (now - start) / span
        T = 0.8 * (0.1 ** frac)
        pos = rng.randrange(len(chosen))
        old = chosen[pos]
        cands = by_size[len(orbits[old])]
        new = cands[rng.randrange(len(cands))]
        if new in in_set:
            continue
        chosen[pos] = new
        S2 = build_S(chosen)
        c2 = _cover_cost(S2, m)
        delta = c2 - cost
        if delta <= 0 or rng.random() < math.exp(-delta / T):
            in_set.discard(old)
            in_set.add(new)
            cost = c2
            S = S2
        else:
            chosen[pos] = old
    return S


def _find_difference_cover(d, m, rng, deadline):
    """Try random multipliers u (restarting annealing each time) until a cover of Z_m of size d is found."""
    while time.monotonic() < deadline:
        u = _random_unit(m, rng, max(2, d))
        if u is None:
            continue
        orbits = _unit_orbits(m, u)
        attempt_end = min(deadline, time.monotonic() + 1.5)
        S = _orbit_anneal(d, m, orbits, rng, attempt_end)
        if S is not None:
            return S
    return None


def build(d, D, seed, time_limit):
    start = time.monotonic()
    deadline = start + 0.8 * time_limit
    rng = random.Random(seed)

    if d < 1 or D < 1:
        return 1, []
    if D == 1:
        return 2, [(0, 1)]

    # Safe fallback: K_{d,d} has diameter 2, valid for D >= 2.
    best = lib.haar_graph(d, range(d))

    def consider(n, e):
        nonlocal best
        if n > best[0] and lib.is_valid(n, e, d, D):
            best = (n, e)

    if D >= 3 and d >= 3:
        # Known record-type constructions.
        if d - 2 >= 3 and lib.is_prime_power(d - 2):
            try:
                n_a, e_a = lib.araujo_lopez_graph(d - 2)
                consider(n_a, e_a)
            except Exception:
                pass
        pg = _best_pg(d)
        if pg is not None:
            consider(pg[0], pg[1])

        # New search: multiplier-invariant difference covers -> Haar graphs of order 2m.
        # Only m with 2m > current best can improve; go upward from there.
        lo = best[0] // 2 + 1
        hi = d * (d - 1) + 1  # Moore-type limit for diameter-3 Haar graphs
        m = lo
        while m <= hi and time.monotonic() < deadline:
            now = time.monotonic()
            budget_end = now + 0.6 * (deadline - now)
            S = _find_difference_cover(d, m, rng, budget_end)
            if S is None:
                break
            n, e = lib.haar_graph(m, S)
            consider(n, e)
            m += 1

    if not lib.is_valid(best[0], best[1], d, D):
        best = lib.haar_graph(d, range(d))
    return best
