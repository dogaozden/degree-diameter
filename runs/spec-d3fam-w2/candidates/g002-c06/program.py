# Arc-extended projective plane graphs (diameter 3).
# ----------------------------------------------------------------------------

def _pg_data(q):
    """Return (m, edges, point_lines, line_points, index, pts) for PG(2, q)."""
    pts = lib.projective_points(q)
    n2, edges = lib.projective_plane_incidence(q)
    m = n2 // 2
    point_lines = [[] for _ in range(m)]
    line_points = [[] for _ in range(m)]
    for u, v in edges:
        point_lines[u].append(v - m)
        line_points[v - m].append(u)
    index = {p: i for i, p in enumerate(pts)}
    return m, edges, point_lines, line_points, index, pts


def _loads_ok(S, s, m, point_lines, line_points):
    cl = [0] * m
    cp = [0] * m
    for P in S:
        for L in point_lines[P]:
            cl[L] += 1
        for Q in line_points[P]:
            cp[Q] += 1
    return max(cl, default=0) <= s and max(cp, default=0) <= s


def _greedy_arc(m, s, point_lines, line_points, rng, trials, deadline):
    best = []
    order = list(range(m))
    for _ in range(trials):
        if time.monotonic() > deadline:
            break
        rng.shuffle(order)
        cl = [0] * m
        cp = [0] * m
        S = []
        for P in order:
            if all(cl[L] < s for L in point_lines[P]) and all(cp[Q] < s for Q in line_points[P]):
                S.append(P)
                for L in point_lines[P]:
                    cl[L] += 1
                for Q in line_points[P]:
                    cp[Q] += 1
        if len(S) > len(best):
            best = S
    return best


def _local_improve(m, s, point_lines, line_points, S, rng, deadline, iters):
    cl = [0] * m
    cp = [0] * m
    inS = [False] * m

    def add(P):
        inS[P] = True
        for L in point_lines[P]:
            cl[L] += 1
        for Q in line_points[P]:
            cp[Q] += 1

    def rem(P):
        inS[P] = False
        for L in point_lines[P]:
            cl[L] -= 1
        for Q in line_points[P]:
            cp[Q] -= 1

    def fits(P):
        return (all(cl[L] < s for L in point_lines[P])
                and all(cp[Q] < s for Q in line_points[P]))

    cur = list(S)
    for P in cur:
        add(P)
    best = list(cur)
    for it in range(iters):
        if (it & 63) == 0 and time.monotonic() > deadline:
            break
        P = rng.randrange(m)
        if inS[P]:
            continue
        if fits(P):
            add(P)
            cur.append(P)
            if len(cur) > len(best):
                best = list(cur)
            continue
        if not cur:
            continue
        idx = rng.randrange(len(cur))
        R = cur[idx]
        rem(R)
        if fits(P):
            add(P)
            cur[idx] = P
        else:
            add(R)
    return best


def _conic_set(q, index, F):
    S = [index[(1, t, F.mul(t, t))] for t in range(q)]
    S.append(index[(0, 0, 1)])
    if q % 2 == 0:
        S.append(index[(0, 1, 0)])
    return S


def _arc_graph(m, edges, point_lines, line_points, S):
    k = len(S)
    n = 2 * m + 2 * k
    E = list(edges)
    for t, P in enumerate(S):
        x = 2 * m + t
        for L in point_lines[P]:
            E.append((x, m + L))
    for t, j in enumerate(S):
        b = 2 * m + k + t
        for Q in line_points[j]:
            E.append((Q, b))
    return n, E


def _arc_extensions(d, deadline, rng):
    out = []
    for q in range(2, min(d - 1, 23) + 1):
        if not lib.is_prime_power(q):
            continue
        if time.monotonic() > deadline:
            break
        s = d - q - 1
        m, edges, point_lines, line_points, index, pts = _pg_data(q)
        cands = []
        if s >= 1:
            g = _greedy_arc(m, s, point_lines, line_points, rng, 40, deadline)
            g = _local_improve(m, s, point_lines, line_points, g, rng, deadline, 3000)
            cands.append(g)
        if s >= 2:
            F = lib.GF(q)
            cs = _conic_set(q, index, F)
            if _loads_ok(cs, s, m, point_lines, line_points):
                cands.append(cs)
        S = max(cands, key=len, default=[])
        if not S or not _loads_ok(S, s, m, point_lines, line_points):
            continue
        out.append(_arc_graph(m, edges, point_lines, line_points, S))
    return out


# ----------------------------------------------------------------------------
# Matching-rewire growth for diameter 3.
# Free a matching R of d edges (u on side 0, v on side 1). Add x on side 0
# joined to all v's and y on side 1 joined to all u's. Degrees stay <= d.
# Anneal the matching so the rewired graph has diameter <= D.
# ----------------------------------------------------------------------------

def _bipartition(n, adj):
    color = [-1] * n
    for s in range(n):
        if color[s] != -1:
            continue
        color[s] = 0
        stack = [s]
        while stack:
            u = stack.pop()
            for v in adj[u]:
                if color[v] == -1:
                    color[v] = 1 - color[u]
                    stack.append(v)
    return color


def _random_matching(Eo, d, rng):
    pool = list(Eo)
    rng.shuffle(pool)
    used = set()
    R = []
    for u, v in pool:
        if u in used or v in used:
            continue
        R.append((u, v))
        used.add(u)
        used.add(v)
        if len(R) == d:
            return R
    return None


def _rewire_build(n, Eo, R):
    Rkeys = {(min(u, v), max(u, v)) for u, v in R}
    out = [e for e in Eo if (min(e[0], e[1]), max(e[0], e[1])) not in Rkeys]
    x, y = n, n + 1
    for u, v in R:
        out.append((x, v))
        out.append((u, y))
    return n + 2, out


def _pair_search(n, E, d, D, deadline, rng):
    adj = [[] for _ in range(n)]
    for u, v in E:
        adj[u].append(v)
        adj[v].append(u)
    col = _bipartition(n, adj)
    if any(col[u] == col[v] for u, v in E):
        return None
    Eo = [(u, v) if col[u] == 0 else (v, u) for u, v in E]
    if len(Eo) < d:
        return None
    R = _random_matching(Eo, d, rng)
    if R is None:
        return None

    def cost(RR):
        nn, ee = _rewire_build(n, Eo, RR)
        return lib.bad_pairs(nn, ee, D)

    c = cost(R)
    t_start = time.monotonic()
    span = max(1e-6, deadline - t_start)
    while time.monotonic() < deadline:
        if c == 0:
            return _rewire_build(n, Eo, R)
        frac = (time.monotonic() - t_start) / span
        T = 1.0 * (0.05 ** frac)
        i = rng.randrange(d)
        cand = Eo[rng.randrange(len(Eo))]
        used = set()
        for j, (a, b) in enumerate(R):
            if j != i:
                used.add(a)
                used.add(b)
        if cand[0] in used or cand[1] in used:
            continue
        newR = list(R)
        newR[i] = cand
        c2 = cost(newR)
        if c2 <= c or rng.random() < math.exp(-(c2 - c) / T):
            R, c = newR, c2
    if c == 0:
        return _rewire_build(n, Eo, R)
    return None


def _pair_grow(n, E, d, D, deadline, rng):
    cur_n, cur_e = n, list(E)
    while time.monotonic() < deadline:
        res = _pair_search(cur_n, cur_e, d, D, deadline, rng)
        if res is None:
            break
        cur_n, cur_e = res
    return cur_n, cur_e


# ----------------------------------------------------------------------------
# Driver
# ----------------------------------------------------------------------------

def build(d, D, seed, time_limit):
    start = time.monotonic()
    deadline = start + max(1.0, 0.8 * time_limit - 2.0)
    total = deadline - start
    rng = random.Random(seed)

    base_n, base_e = _fallback(d, D)
    if not lib.is_valid(base_n, base_e, d, D):
        return 1, []

    # Moore-extremal or non-diameter-3 cases: the fallback is the answer here.
    if D != 3 or d < 3 or lib.is_prime_power(d - 1):
        return base_n, base_e

    best = (base_n, base_e)

    def consider(n, e):
        nonlocal best
        if n > best[0] and lib.is_valid(n, e, d, D):
            best = (n, e)

    # Phase 1: arc-extended projective planes (cheap; may raise the starting point).
    for n_c, e_c in _arc_extensions(d, start + 0.12 * total,
                                    random.Random(seed * 7919 + d)):
        consider(n_c, e_c)

    # Phase 2: difference-cover lifts over cyclic and semidirect groups.
    gn, ge = _group_search(d, best[0], rng, start + 0.6 * total)
    if gn is not None:
        consider(gn, ge)

    # Phase 3: rewire growth from the best graph found so far.
    n3, e3 = _pair_grow(best[0], best[1], d, D, deadline, random.Random(seed + 101))
    consider(n3, e3)

    if not lib.is_valid(best[0], best[1], d, D):
        return base_n, base_e
    return best
