import itertools
import math
import random
import time

import lib

ITERS = 800            # annealing steps per restart
RESTARTS = 3           # fresh random connection sets per group
TOP_SLACK = 8          # search orders lo .. lo + TOP_SLACK
PERM_PROB = 0.5        # chance to draw a random permutation group instead of a semidirect product
MAX_PERM_TRIES = 150   # random generator pairs tried per draw


# ----------------------------------------------------------------------------
# Baseline families (fast, always validated before use).
# ----------------------------------------------------------------------------

def _best_pg(d):
    """Incidence graph of PG(2, q) for the largest prime power q with q + 1 <= d."""
    for q in range(d - 1, 1, -1):
        if lib.is_prime_power(q):
            return lib.projective_plane_incidence(q)
    return None


def _gq_w(q):
    """Incidence graph of points and lines of the generalized quadrangle W(q); diameter 4."""
    F = lib.GF(q)
    pts = [v for v in itertools.product(range(q), repeat=4)
           if any(v) and next(c for c in v if c) == 1]
    index = {v: i for i, v in enumerate(pts)}
    P = len(pts)

    def norm(v):
        c = next(x for x in v if x)
        inv = F.inv(c)
        return tuple(F.mul(inv, x) for x in v)

    def form(x, y):
        t = F.sub(F.mul(x[0], y[1]), F.mul(x[1], y[0]))
        return F.add(t, F.sub(F.mul(x[2], y[3]), F.mul(x[3], y[2])))

    covered = set()
    lines = []
    for i in range(P):
        x = pts[i]
        for j in range(i + 1, P):
            if (i, j) in covered:
                continue
            y = pts[j]
            if form(x, y) != 0:
                continue
            L = set()
            for a in range(q):
                for b in range(q):
                    if a == 0 and b == 0:
                        continue
                    v = tuple(F.add(F.mul(a, x[k]), F.mul(b, y[k])) for k in range(4))
                    if any(v):
                        L.add(index[norm(v)])
            L = sorted(L)
            lines.append(L)
            for p in L:
                for r in L:
                    if p < r:
                        covered.add((p, r))

    edges = []
    for j, L in enumerate(lines):
        for p in L:
            edges.append((p, P + j))
    return 2 * P, edges


def _best_gq(d):
    """W(q) for the largest prime power q with q + 1 <= d, restricted to small q for speed."""
    for q in range(min(d - 1, 5), 1, -1):
        if lib.is_prime_power(q):
            return _gq_w(q)
    return None


# ----------------------------------------------------------------------------
# Group sources for bi-Cayley graphs.
#
# A group is returned as (N, T, invs): T[x][g] = x*g as indices 0..N-1, invs[g] = g^-1,
# and element 0 is the identity.
#
# NEW HELPER: random permutation groups. Two random permutations with biased cycle
# types generate a group by closure, which is aborted as soon as it exceeds the
# allowed order. This reaches non-metacyclic groups (e.g. PSL(2,7) has order 168)
# that the semidirect family Z_m x| Z_k cannot produce.
# ----------------------------------------------------------------------------

def _groups(N):
    """Return semidirect parameters (m, k, r) with m*k = N, giving Z_m x|_r Z_k."""
    out = []
    for k in range(1, N + 1):
        if N % k:
            continue
        m = N // k
        for r in range(m):
            if math.gcd(r, m) == 1 and pow(r, k, m) == 1 % m:
                out.append((m, k, r))
    return out


def _random_semidirect(lo, top, rng):
    """Random semidirect product Z_m x|_r Z_k with order in [lo, top], or None."""
    Ns = list(range(lo, top + 1))
    rng.shuffle(Ns)
    for N in Ns:
        params = _groups(N)
        if not params:
            continue
        m, k, r = rng.choice(params)
        _, mul, inv = lib.semidirect_group(m, k, r)
        T = [[mul(x, g) for g in range(N)] for x in range(N)]
        invs = [inv(g) for g in range(N)]
        return N, T, invs
    return None


def _random_perm(n, rng):
    """Random permutation of range(n) whose cycle lengths are biased toward small values."""
    pts = list(range(n))
    rng.shuffle(pts)
    parts = []
    left = n
    while left > 0:
        c = min(rng.choice([2, 2, 3, 3, 4, 5, 6, 7]), left)
        parts.append(c)
        left -= c
    p = list(range(n))
    pos = 0
    for c in parts:
        cyc = pts[pos:pos + c]
        pos += c
        for i in range(c):
            p[cyc[i]] = cyc[(i + 1) % c]
    return tuple(p)


def _perm_group(gens, lo, top):
    """Group generated by permutation tuples gens, if its order is in [lo, top]; else None."""
    n = len(gens[0])
    ident = tuple(range(n))
    elems = [ident]
    index = {ident: 0}
    i = 0
    while i < len(elems):
        x = elems[i]
        i += 1
        for g in gens:
            y = tuple(g[t] for t in x)
            if y not in index:
                if len(elems) >= top:
                    return None
                index[y] = len(elems)
                elems.append(y)
    N = len(elems)
    if N < lo:
        return None
    mul = [[0] * N for _ in range(N)]
    for a in range(N):
        ea = elems[a]
        row = mul[a]
        for b in range(N):
            eb = elems[b]
            row[b] = index[tuple(ea[t] for t in eb)]
    invs = [mul[a].index(0) for a in range(N)]
    return N, mul, invs


def _random_perm_group(lo, top, rng, tries):
    """Try random 2-generator permutation groups until one has order in [lo, top]."""
    for _ in range(tries):
        n = rng.randint(5, 10)
        gens = [_random_perm(n, rng) for _ in range(2)]
        if all(g == tuple(range(n)) for g in gens):
            continue
        got = _perm_group(gens, lo, top)
        if got is not None:
            return got
    return None


# ----------------------------------------------------------------------------
# Bi-Cayley search. Vertices A_x and B_y (x, y in G); edge A_x -- B_{x s}, s in S, |S| = d.
# Identity is WLOG in S. Distances from A_0 and B_0 decide the diameter.
# ----------------------------------------------------------------------------

def _unreached(N, T, invs, S, D):
    """Count (source, vertex) pairs not within distance D, for sources A_0 and B_0."""
    Sinv = [invs[g] for g in S]
    total = 0
    for src in (0, N):
        seen = bytearray(2 * N)
        seen[src] = 1
        count = 1
        frontier = [src]
        for _ in range(D):
            nxt = []
            for u in frontier:
                if u < N:
                    row = T[u]
                    for g in S:
                        v = N + row[g]
                        if not seen[v]:
                            seen[v] = 1
                            nxt.append(v)
                else:
                    row = T[u - N]
                    for h in Sinv:
                        v = row[h]
                        if not seen[v]:
                            seen[v] = 1
                            nxt.append(v)
            count += len(nxt)
            frontier = nxt
            if not frontier:
                break
        total += 2 * N - count
    return total


def _anneal(N, T, invs, d, D, rng, iters, deadline):
    """Simulated annealing over S = {0, s_1, ..., s_{d-1}} to zero unreached pairs."""
    S = [0] + rng.sample(range(1, N), d - 1)
    cur = _unreached(N, T, invs, S, D)
    for it in range(iters):
        if cur == 0:
            return S
        if time.monotonic() > deadline:
            break
        temp = max(0.05, 2.0 * (1.0 - it / iters))
        i = rng.randrange(1, d)
        c = rng.randrange(1, N)
        if c in S:
            continue
        S2 = S[:]
        S2[i] = c
        v = _unreached(N, T, invs, S2, D)
        if v <= cur or rng.random() < math.exp(-(v - cur) / temp):
            S, cur = S2, v
    return S if cur == 0 else None


def build(d, D, seed, time_limit):
    start = time.monotonic()
    deadline = start + 0.85 * time_limit
    rng = random.Random(seed)

    if d < 1 or D < 1:
        return 1, []

    best = (1, [])

    def consider(n, e):
        nonlocal best
        if n > best[0] and lib.is_valid(n, e, d, D):
            best = (n, e)

    # Record-matching case: incidence graph of PG(2, d-1).
    if D == 3 and lib.is_prime_power(d - 1):
        n, e = lib.projective_plane_incidence(d - 1)
        consider(n, e)
        return best

    if D >= 2:
        consider(*lib.haar_graph(d, range(d)))
    if D >= 3:
        pg = _best_pg(d)
        if pg is not None:
            consider(pg[0], pg[1])
    if D >= 4 and time.monotonic() < deadline:
        gq = _best_gq(d)
        if gq is not None:
            consider(gq[0], gq[1])

    if d < 2 or D < 2:
        return best

    Nmax = lib._moore_bound(d, D) // 2   # bi-Cayley graph has 2N vertices

    # Driver: search group orders N just above the current best (2N > best vertex count).
    fails = 0
    while time.monotonic() < deadline and fails < 200:
        lo = max(d + 1, best[0] // 2 + 1)
        top = min(Nmax, lo + TOP_SLACK)
        if lo > top:
            break

        grp = None
        if rng.random() < PERM_PROB:
            grp = _random_perm_group(lo, top, rng, MAX_PERM_TRIES)
        if grp is None:
            grp = _random_semidirect(lo, top, rng)
        if grp is None:
            fails += 1
            continue

        N, T, invs = grp
        S = None
        for _ in range(RESTARTS):
            if time.monotonic() > deadline:
                break
            S = _anneal(N, T, invs, d, D, rng, ITERS, deadline)
            if S is not None:
                break

        if S is not None:
            edges = [(x, N + T[x][g]) for x in range(N) for g in S]
            consider(2 * N, edges)
            fails = 0
        else:
            fails += 1

    if not lib.is_valid(best[0], best[1], d, D):
        return 1, []
    return best
