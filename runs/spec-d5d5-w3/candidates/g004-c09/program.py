import itertools
import math
import random
import time

import numpy as np

import lib


# ----------------------------------------------------------------------------
# Safe structured baselines.
# ----------------------------------------------------------------------------

def _gq_w(q):
    """Incidence graph of points and lines of the generalized quadrangle W(q); diameter 4."""
    F = lib.GF(q)
    pts = [v for v in itertools.product(range(q), repeat=4)
           if any(v) and next(c for c in v if c) == 1]
    index = {v: i for i, v in enumerate(pts)}
    P = len(pts)

    def norm(v):
        c = next(x for x in v if x)
        inv = F.inv(c)
        return tuple(F.mul(inv, x) for x in v)

    def form(x, y):
        t = F.sub(F.mul(x[0], y[1]), F.mul(x[1], y[0]))
        return F.add(t, F.sub(F.mul(x[2], y[3]), F.mul(x[3], y[2])))

    covered = set()
    lines = []
    for i in range(P):
        x = pts[i]
        for j in range(i + 1, P):
            if (i, j) in covered:
                continue
            y = pts[j]
            if form(x, y) != 0:
                continue
            L = set()
            for a in range(q):
                for b in range(q):
                    if a == 0 and b == 0:
                        continue
                    v = tuple(F.add(F.mul(a, x[k]), F.mul(b, y[k])) for k in range(4))
                    if any(v):
                        L.add(index[norm(v)])
            L = sorted(L)
            lines.append(L)
            for p in L:
                for r in L:
                    if p < r:
                        covered.add((p, r))

    edges = []
    for j, L in enumerate(lines):
        for p in L:
            edges.append((p, P + j))
    return 2 * P, edges


# ----------------------------------------------------------------------------
# New construction: bi-Cayley graphs over non-metacyclic finite groups.
#
# Vertices A_x and B_y for x, y in G. Edge A_x ~ B_{x*g} for g in S, |S| = d.
# Left translation by h is an automorphism, so only distances from A_e and B_e
# matter. Groups tried: SL(2,p), PGL(2,p), PSL(2,p) (as permutation-free matrix
# closures) and semidirect products Z_m x| Z_k as a fallback.
# ----------------------------------------------------------------------------

def _primes(limit):
    sieve = [True] * (limit + 1)
    out = []
    for i in range(2, limit + 1):
        if sieve[i]:
            out.append(i)
            for j in range(i * i, limit + 1, i):
                sieve[j] = False
    return out


def _prim_root(p):
    fac = [q for q in range(2, p) if (p - 1) % q == 0 and all(q % r for r in range(2, int(q ** 0.5) + 1))]
    for g in range(2, p):
        if all(pow(g, (p - 1) // q, p) != 1 for q in fac):
            return g
    return None


def _closure(gens, mul, ident, cap):
    """All elements of the group generated by gens, identity at index 0; None if more than cap."""
    elems = [ident]
    idx = {ident: 0}
    frontier = [ident]
    while frontier:
        nxt = []
        for x in frontier:
            for g in gens:
                y = mul(x, g)
                if y not in idx:
                    idx[y] = len(elems)
                    elems.append(y)
                    nxt.append(y)
                    if len(elems) > cap:
                        return None
        frontier = nxt
    return elems, idx


def _table(N, f):
    """Right-multiplication table: R[g][x] = index of x*g; Rinv[g] = R[g^{-1}]."""
    R = np.empty((N, N), dtype=np.int64)
    for g in range(N):
        R[g] = [f(x, g) for x in range(N)]
    inv_idx = np.argmax(R == 0, axis=1)
    Rinv = R[inv_idx]
    return (N, R, Rinv)


def _mk_matrix(p, kind, cap):
    def mm(A, B):
        a, b, c, d_ = A
        e, f, g, h = B
        return ((a * e + b * g) % p, (a * f + b * h) % p,
                (c * e + d_ * g) % p, (c * f + d_ * h) % p)

    def nrm(M):
        c = next(x for x in M if x)
        inv = pow(c, p - 2, p)
        return tuple(x * inv % p for x in M)

    base = [(1, 1, 0, 1), (1, 0, 1, 1)]
    if kind == 'SL':
        mul = mm
        gens = base
    else:
        mul = lambda A, B: nrm(mm(A, B))
        gens = [nrm(g) for g in base]
        if kind == 'PGL':
            gens.append(nrm((_prim_root(p), 0, 0, 1)))
    res = _closure(gens, mul, (1, 0, 0, 1), cap)
    if res is None:
        return None
    elems, idx = res
    N = len(elems)
    return _table(N, lambda x, g: idx[mul(elems[x], elems[g])])


def _groups(N):
    """Semidirect parameters (m, k, r) with m*k = N, giving Z_m x|_r Z_k."""
    out = []
    for k in range(1, N + 1):
        if N % k:
            continue
        m = N // k
        for r in range(m):
            if math.gcd(r, m) == 1 and pow(r, k, m) == 1 % m:
                out.append((m, k, r))
    return out


def _mk_semi(m, k, r):
    try:
        N, mul, _inv = lib.semidirect_group(m, k, r)
    except ValueError:
        return None
    return _table(N, mul)


def _cost(N, R, Rinv, S, D):
    """Number of (source, vertex) pairs at distance > D, sources A_e and B_e."""
    total = 0
    for src in (0, N):
        F = np.zeros(2 * N, dtype=bool)
        F[src] = True
        V = F.copy()
        for _ in range(D):
            nxt = np.zeros(2 * N, dtype=bool)
            FA = F[:N]
            FB = F[N:]
            for g in S:
                nxt[N + R[g]] |= FA      # A_x -> B_{x g}
                nxt[Rinv[g]] |= FB       # B_y -> A_{y g^{-1}}
            nxt &= ~V
            V |= nxt
            F = nxt
            if not F.any():
                break
        total += 2 * N - int(V.sum())
    return total


def _anneal(G, d, D, rng, end):
    """Anneal a connection set S (identity included) until diameter <= D or time end."""
    N, R, Rinv = G
    if N - 1 < d - 1 or d < 2:
        return None
    S = [0] + rng.sample(range(1, N), d - 1)
    cur = _cost(N, R, Rinv, S, D)
    t0 = time.monotonic()
    span = max(1e-3, end - t0)
    while cur > 0:
        now = time.monotonic()
        if now >= end:
            break
        temp = max(0.2, 4.0 * (1.0 - (now - t0) / span))
        i = rng.randrange(1, d)
        c = rng.randrange(1, N)
        if c in S:
            continue
        S2 = S[:]
        S2[i] = c
        v = _cost(N, R, Rinv, S2, D)
        if v <= cur or rng.random() < math.exp(-(v - cur) / temp):
            S, cur = S2, v
    return S if cur == 0 else None


def _edges(N, R, S):
    E = []
    for g in S:
        col = R[g]
        for x in range(N):
            E.append((x, N + int(col[x])))
    return E


# ----------------------------------------------------------------------------
# Main entry point.
# ----------------------------------------------------------------------------

def build(d, D, seed, time_limit):
    start = time.monotonic()
    budget = max(0.2, min(0.8 * time_limit, time_limit - 5.0))
    deadline = start + budget
    rng = random.Random(seed)

    if d < 1 or D < 1:
        return 1, []
    if D == 1:
        return 2, [(0, 1)]

    # K_{d,d}: diameter 2, always valid. Safe fallback.
    best_n, best_e = lib.haar_graph(d, range(d))
    if D == 2:
        return best_n, best_e

    def consider(n, e):
        nonlocal best_n, best_e
        if n > best_n and lib.is_valid(n, e, d, D):
            best_n, best_e = n, e
            return True
        return False

    moore = lib.moore_bound(d, D)

    # Projective plane incidence graph: diameter 3, degree d when d-1 is a prime power.
    if D >= 3 and d - 1 >= 2 and lib.is_prime_power(d - 1):
        n, e = lib.projective_plane_incidence(d - 1)
        consider(n, e)
        if best_n >= moore:
            return best_n, best_e

    # Generalized quadrangle W(q), diameter 4, degree q+1.
    if D >= 4 and d - 1 >= 2 and d - 1 <= 5 and lib.is_prime_power(d - 1):
        try:
            n, e = _gq_w(d - 1)
            consider(n, e)
        except Exception:
            pass

    # Main search: bi-Cayley graphs over groups of order N in (best/2, moore/2].
    if D >= 3 and d >= 2:
        Nmax = moore // 2
        Nlo = max(d + 1, best_n // 2 + 1)
        if Nlo <= Nmax:
            cands = []
            for p in _primes(40):
                if p < 3:
                    continue
                for kind in ('SL', 'PGL', 'PSL'):
                    N = p * (p * p - 1) if kind != 'PSL' else p * (p * p - 1) // 2
                    if Nlo <= N <= Nmax:
                        cands.append({'N': N, 'make': (lambda p=p, kind=kind: _mk_matrix(p, kind, Nmax)),
                                      'G': None})
            semi = []
            for N in range(Nlo, Nmax + 1):
                for m, k, r in _groups(N):
                    semi.append((N, m, k, r))
            rng.shuffle(semi)
            semi = semi[:40]
            semi.sort()
            for N, m, k, r in semi:
                cands.append({'N': N, 'make': (lambda m=m, k=k, r=r: _mk_semi(m, k, r)), 'G': None})

            pending = cands
            slice_len = 1.0
            while time.monotonic() < deadline and pending:
                pending = [c for c in pending if 2 * c['N'] > best_n and not c.get('dead')]
                if not pending:
                    break
                for c in pending:
                    now = time.monotonic()
                    if now >= deadline:
                        break
                    if c['G'] is None:
                        c['G'] = c['make']()
                        if c['G'] is None:
                            c['dead'] = True
                            continue
                    S = _anneal(c['G'], d, D, rng, min(deadline, now + slice_len))
                    if S is not None:
                        N, R, _ = c['G']
                        if not consider(2 * N, _edges(N, R, S)):
                            c['dead'] = True
                slice_len = min(slice_len * 2.0, 20.0)

    if not lib.is_valid(best_n, best_e, d, D):
        best_n, best_e = lib.haar_graph(d, range(d))
    return best_n, best_e
