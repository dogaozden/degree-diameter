# Driver.
# ----------------------------------------------------------------------------

def _search(d, D, seed, start, deadline, rng, consider, st, T):
    bases = _best_pg(d, 2) if D == 3 else _gq_bases(d, 2)
    for b in bases:
        consider(b[0], b[1])
    if not bases:
        return

    # Phase A: twin packing and cover growth from the bases and the best graph.
    exp_end = min(deadline, start + 0.30 * T)
    rot = 0
    while time.monotonic() < exp_end:
        if rng.random() < 0.3:
            src = st["best"]
        else:
            src = bases[rot % len(bases)]
            rot += 1
        slice_end = min(exp_end, time.monotonic() + 0.1 * T)
        n2, e2 = _expand(src[0], src[1], d, D, slice_end, rng)
        consider(n2, e2)

    # Phase B: small Haar search for diameter <= 4.
    if D <= 4:
        hend = min(deadline, start + 0.36 * T)
        m, miss = d + 1, 0
        while time.monotonic() < hend and miss < 4:
            S = _search_haar(d, D, m, rng, hend, 120)
            if S is not None:
                n, e = lib.haar_graph(m, S)
                consider(n, e)
                miss = 0
            else:
                miss += 1
            m += 1

    # Phase C: voltage-lift annealing over semidirect products.
    if D >= 4:
        vend = min(deadline, start + 0.42 * T)
        ks = [1, 2, 2, 3, 4] if D >= 5 else [1, 1, 2, 3]
        while time.monotonic() < vend:
            k = rng.choice(ks)
            base = st["best"][0] // (2 * k)
            G = max(2, base + 1 + rng.randrange(0, max(3, base // 8 + 1)))
            g = _sample_group(G, rng)
            if g is None:
                continue
            order, mul = g
            res = _anneal(d, D, k, order, mul, rng, vend, 1200)
            if res is not None:
                consider(res[0], res[1])

    # Phase D: switch-annealed growth from the best graph.
    gend = min(deadline, start + 0.6 * T)
    if st["best"][0] >= 2 and time.monotonic() < gend:
        gn, ge = _grow_switch(st["best"][0], st["best"][1], d, D, gend, rng)
        consider(gn, ge)

    # Phase E: iterated local search, restarted in chunks from the best graph.
    chunk = max(3.0, 0.15 * T)
    while time.monotonic() < deadline - 0.5 and st["best"][0] >= 2:
        cend = min(deadline, time.monotonic() + chunk)
        holder = [st["best"]]
        _ils(st["best"][0], st["best"][1], d, D, cend, rng, holder)
        if holder[0][0] > st["best"][0]:
            consider(holder[0][0], holder[0][1])


def build(d, D, seed, time_limit):
    start = time.monotonic()
    deadline = start + 0.85 * time_limit
    rng = random.Random(seed)

    if d < 1 or D < 1:
        return 1, []
    if D == 1:
        return 2, [(0, 1)]
    if D == 2:
        return lib.haar_graph(d, range(d))  # K_{d,d} has the Moore order for D = 2
    if d == 2:
        n = 2 * D
        return n, [(i, (i + 1) % n) for i in range(n)]  # even cycle C_{2D}

    st = {"best": lib.haar_graph(d, range(d))}  # K_{d,d}: valid fallback

    def consider(n, e):
        if n > st["best"][0] and lib.is_valid(n, e, d, D):
            st["best"] = (n, e)

    if st["best"][0] >= lib._moore_bound(d, D):
        return st["best"]

    try:
        _search(d, D, seed, start, deadline, rng, consider, st, time_limit)
    except Exception:
        pass

    n, e = st["best"]
    if not lib.is_valid(n, e, d, D):
        return lib.haar_graph(d, range(d))
    return n, e
