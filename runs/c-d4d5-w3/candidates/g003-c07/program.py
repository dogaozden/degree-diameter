"""Combined program, bold variant: besides the algebraic starts (PG(2,q), W(q), Araujo-Pardo-Lopez,
K_{d,d}), Python now searches Haar graphs H(G, S) over non-cyclic groups G, built as direct products
of small cyclic, dihedral, affine, S4 and A4 factors. A Haar graph on 2|G| vertices is d-regular and
bipartite, and its diameter can be checked from two BFS runs, one from each side's identity. The
largest valid Haar graph, or the best algebraic start if none beats it, becomes the start for the
unchanged C engine (voltage lifts plus grow-by-two annealing). Every candidate is checked with
lib.is_valid, so the algebraic fallback is always kept."""
