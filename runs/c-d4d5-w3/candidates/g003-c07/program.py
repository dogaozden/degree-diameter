def _gq_w(q):
    """Incidence graph of points and lines of W(q): degree q+1, diameter 4."""
    F = lib.GF(q)
    pts = [v for v in itertools.product(range(q), repeat=4)
           if any(v) and next(c for c in v if c) == 1]
    index = {v: i for i, v in enumerate(pts)}
    P = len(pts)

    def norm(v):
        c = next(x for x in v if x)
        inv = F.inv(c)
        return tuple(F.mul(inv, x) for x in v)

    def form(x, y):
        t = F.sub(F.mul(x[0], y[1]), F.mul(x[1], y[0]))
        return F.add(t, F.sub(F.mul(x[2], y[3]), F.mul(x[3], y[2])))

    covered = set()
    lines = []
    for i in range(P):
        x = pts[i]
        for j in range(i + 1, P):
            if (i, j) in covered:
                continue
            y = pts[j]
            if form(x, y) != 0:
                continue
            L = set()
            for a in range(q):
                for b in range(q):
                    if a == 0 and b == 0:
                        continue
                    v = tuple(F.add(F.mul(a, x[k]), F.mul(b, y[k])) for k in range(4))
                    if any(v):
                        L.add(index[norm(v)])
            L = sorted(L)
            lines.append(L)
            for p in L:
                for r in L:
                    if p < r:
                        covered.add((p, r))

    edges = []
    for j, L in enumerate(lines):
        for p in L:
            edges.append((p, P + j))
    return 2 * P, edges


def _largest_prime_power_le(x):
    for q in range(x, 1, -1):
        if lib.is_prime_power(q):
            return q
    return None


def known_starts(d, D):
    """Algebraic candidates valid for diameter D (may be empty)."""
    out = []
    if D >= 3 and d - 1 >= 2 and lib.is_prime_power(d - 1):
        out.append(lib.projective_plane_incidence(d - 1))
    if D == 3 and d - 2 >= 3 and lib.is_prime_power(d - 2):
        out.append(lib.araujo_lopez_graph(d - 2))
    if D >= 4:
        q = _largest_prime_power_le(min(d - 1, 9))
        if q is not None and q >= 2:
            out.append(_gq_w(q))
    return out


# ---------------------------------------------------------------- Haar graphs over groups
# A group is (order, mul): mul[a][b] is the index of a*b, identity index 0.

def _closure(gens, k, cap=10 ** 6):
    """Group generated by permutations gens (tuples of length k), as (order, mul), or None if > cap."""
    ident = tuple(range(k))
    elems = [ident]
    seen = {ident: 0}
    i = 0
    while i < len(elems):
        x = elems[i]
        i += 1
        for g in gens:
            y = tuple(x[t] for t in g)
            if y not in seen:
                if len(elems) >= cap:
                    return None
                seen[y] = len(elems)
                elems.append(y)
    N = len(elems)
    table = [[0] * N for _ in range(N)]
    for a in range(N):
        ea = elems[a]
        row = table[a]
        for b in range(N):
            eb = elems[b]
            row[b] = seen[tuple(ea[t] for t in eb)]
    return N, table


def _cyc_table(n):
    return n, [[(a + b) % n for b in range(n)] for a in range(n)]


def _dih_table(n):
    """Dihedral group of order 2n; element f*n + a stands for s^f r^a with s r s = r^-1."""
    N = 2 * n
    table = [[0] * N for _ in range(N)]
    for f in range(2):
        for a in range(n):
            row = table[f * n + a]
            for g in range(2):
                for b in range(n):
                    r_b = b if f == 0 else (-b) % n
                    row[g * n + (a + r_b) % n] = ((f + g) % 2) * n + (a + r_b) % n
    return N, table


def _direct(G, H):
    n1, t1 = G
    n2, t2 = H
    N = n1 * n2
    table = [[0] * N for _ in range(N)]
    for i in range(n1):
        for j in range(n2):
            row = table[i * n2 + j]
            for k in range(n1):
                a = t1[i][k] * n2
                for l in range(n2):
                    row[k * n2 + l] = a + t2[j][l]
    return N, table


def _build(desc):
    kind = desc[0]
    if kind == "cyc":
        return _cyc_table(desc[1])
    if kind == "dih":
        return _dih_table(desc[1])
    if kind == "agl":
        q = desc[1]
        a = next(a for a in range(2, q) if all(pow(a, k, q) != 1 for k in range(1, q - 1)))
        t = tuple((i + 1) % q for i in range(q))
        m = tuple((a * i) % q for i in range(q))
        return _closure([t, m], q)
    if kind == "S4":
        return _closure([(1, 0, 2, 3), (1, 2, 3, 0)], 4)
    if kind == "A4":
        return _closure([(1, 2, 0, 3), (0, 2, 3, 1)], 4)
    if kind == "prod":
        return _direct(_build(desc[1]), _build(desc[2]))
    return None


def _descs(lo, hi):
    """(descriptor, order) for groups of order in [lo, hi]: simple groups and direct products of two."""
    singles = []
    for n in range(2, hi + 1):
        singles.append((("cyc", n), n))
    for n in range(3, hi // 2 + 1):
        singles.append((("dih", n), 2 * n))
    for q in (5, 7, 11):
        if q * (q - 1) <= hi:
            singles.append((("agl", q), q * (q - 1)))
    if 24 <= hi:
        singles.append((("S4",), 24))
    if 12 <= hi:
        singles.append((("A4",), 12))
    out = [(dsc, o) for dsc, o in singles if lo <= o <= hi]
    for i in range(len(singles)):
        da, oa = singles[i]
        for j in range(i, len(singles)):
            db, ob = singles[j]
            o = oa * ob
            if lo <= o <= hi:
                out.append((("prod", da, db), o))
    return out


def _haar_ok(N, mul, S, D):
    """Haar graph: A-vertex x adjacent to B-vertex x*s for s in S. Left multiplication is an
    automorphism, so diameter <= D iff BFS from A_e and from B_e reach everything within D."""
    V = 2 * N
    adj = [[] for _ in range(V)]
    for x in range(N):
        row = mul[x]
        ax = adj[x]
        for s in S:
            y = N + row[s]
            ax.append(y)
            adj[y].append(x)
    for src in (0, N):
        dist = [-1] * V
        dist[src] = 0
        q = [src]
        for v in q:
            dv = dist[v]
            if dv >= D:
                continue
            for u in adj[v]:
                if dist[u] < 0:
                    dist[u] = dv + 1
                    q.append(u)
        if len(q) < V:
            return False
    return True


def _haar_search(d, D, best_n, deadline, rng):
    """Largest valid Haar graph (n, edges) with n > best_n found before the deadline, or None."""
    moore = lib.moore_bound(d, D)
    hi = moore // 2
    lo = max(d, best_n // 2 + 1)
    if hi < lo:
        return None
    cands = _descs(lo, hi)
    rng.shuffle(cands)
    cands.sort(key=lambda t: -t[1])  # largest orders first; a success ends the smaller ones
    best = None
    for dsc, order in cands:
        if time.monotonic() > deadline:
            break
        if best is not None and order < best[0] // 2:
            break
        grp = _build(dsc)
        if grp is None:
            continue
        N, mul = grp
        if N < d:
            continue
        for _ in range(300):
            if time.monotonic() > deadline:
                break
            S = rng.sample(range(N), d)
            if _haar_ok(N, mul, S, D):
                edges = [(x, N + mul[x][s]) for x in range(N) for s in S]
                if lib.is_valid(2 * N, edges, d, D) and (best is None or 2 * N > best[0]):
                    best = (2 * N, edges)
                break
    return best


def build(d, D, seed, time_limit):
    t0 = time.monotonic()
    if d < 1 or D < 1:
        return 1, []
    if d == 1 or D == 1:
        return 2, [(0, 1)]
    if d == 2:
        L = 2 * D
        return L, [(i, (i + 1) % L) for i in range(L)]

    best = lib.haar_graph(d, range(d))  # K_{d,d}: always valid for D >= 2
    for cand in known_starts(d, D):
        n, e = cand
        if n > best[0] and lib.is_valid(n, e, d, D):
            best = (n, e)

    if d > 31 or best[0] >= lib.moore_bound(d, D):
        return best

    # Bold step: try Haar graphs over non-cyclic groups before the C search.
    if D >= 2 and d >= 3:
        haar_time = min(0.2 * time_limit, 12.0)
        try:
            rng = random.Random(seed * 1000003 + d * 101 + D)
            found = _haar_search(d, D, best[0], t0 + haar_time, rng)
            if found is not None and found[0] > best[0] and lib.is_valid(found[0], found[1], d, D):
                best = found
        except Exception:
            pass

    budget = 0.9 * time_limit - (time.monotonic() - t0) - 1.5
    if budget <= 0.2:
        return best
    try:
        text = lib.run_c(C_SOURCE, [d, D, seed, budget],
                         stdin_graph=best, timeout=budget + 4)
        out = lib.parse_graph_text(text)
        if out[0] > best[0] and lib.is_valid(out[0], out[1], d, D):
            best = out
    except Exception:
        pass
    return best
