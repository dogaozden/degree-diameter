def _gq_w(q):
    """Incidence graph of points and lines of the generalized quadrangle W(q); diameter 4, degree q+1."""
    F = lib.GF(q)
    pts = [v for v in itertools.product(range(q), repeat=4)
           if any(v) and next(c for c in v if c) == 1]
    index = {v: i for i, v in enumerate(pts)}
    P = len(pts)

    def norm(v):
        c = next(x for x in v if x)
        inv = F.inv(c)
        return tuple(F.mul(inv, x) for x in v)

    def form(x, y):
        t = F.sub(F.mul(x[0], y[1]), F.mul(x[1], y[0]))
        return F.add(t, F.sub(F.mul(x[2], y[3]), F.mul(x[3], y[2])))

    covered = set()
    lines = []
    for i in range(P):
        x = pts[i]
        for j in range(i + 1, P):
            if (i, j) in covered:
                continue
            y = pts[j]
            if form(x, y) != 0:
                continue
            L = set()
            for a in range(q):
                for b in range(q):
                    if a == 0 and b == 0:
                        continue
                    v = tuple(F.add(F.mul(a, x[k]), F.mul(b, y[k])) for k in range(4))
                    if any(v):
                        L.add(index[norm(v)])
            L = sorted(L)
            lines.append(L)
            for p in L:
                for r in L:
                    if p < r:
                        covered.add((p, r))

    edges = []
    for j, L in enumerate(lines):
        for p in L:
            edges.append((p, P + j))
    return 2 * P, edges


def known_start(d, D):
    """Best known construction Python can build directly for (d, D), or None."""
    if D == 3 and lib.is_prime_power(d - 1):
        return lib.projective_plane_incidence(d - 1)   # Moore graph
    if D == 3 and d - 2 >= 3 and lib.is_prime_power(d - 2):
        return lib.araujo_lopez_graph(d - 2)
    if D == 4:
        for q in range(min(d - 1, 7), 1, -1):
            if lib.is_prime_power(q) and q + 1 <= d:
                return _gq_w(q)
    return None


def _frobenius(F, h):
    """Group E x| H, E = (GF(q), +), H = subgroup of GF(q)* of order h, product (u,a)(v,b) = (u + a v, ab).

    Returns (order, flat table) with entry x*N + y = index of the product of elements x and y.
    """
    q = F.q
    g = F.primitive_element()
    step = (q - 1) // h
    H = np.array([F.pow(g, step * i) for i in range(h)], dtype=np.int64)
    N = q * h
    U = np.repeat(np.arange(q, dtype=np.int64), h)   # u-part of element i
    A = np.tile(H, q)                                 # a-part of element i
    au = F.mul_table[A[:, None], U[None, :]]          # a_i * u_j
    W = F.add_table[U[:, None], au]                   # u_i + a_i * u_j
    C = F.mul_table[A[:, None], A[None, :]]           # a_i * a_j
    pos = np.full(q * q, -1, dtype=np.int64)
    pos[U * q + A] = np.arange(N, dtype=np.int64)
    table = pos[W * q + C]
    if (table < 0).any():
        raise ValueError("Frobenius table is not closed")
    return N, table.ravel().tolist()


def _group_tables(lo, hi, seed, cap_entries=1_200_000):
    """Frobenius groups with order in [lo, hi], in random order, until the entry budget is used."""
    rng = random.Random(seed)
    cands = []
    for q in range(2, hi + 1):
        if not lib.is_prime_power(q):
            continue
        for h in range(1, q):
            if (q - 1) % h:
                continue
            if lo <= q * h <= hi:
                cands.append((q, h))
    rng.shuffle(cands)
    cache = {}
    out = []
    total = 0
    for q, h in cands:
        if total + (q * h) ** 2 > cap_entries:
            continue
        if q not in cache:
            cache[q] = lib.GF(q)
        N, table = _frobenius(cache[q], h)
        out.append((N, table))
        total += N * N
    return out


def _stream(start, groups):
    """Flat stream: [start_n, start_m, edges..., NGRP, (G, table)...], sent as pairs with a "0 M" header."""
    n, edges = start
    flat = [int(n), len(edges)]
    for u, v in edges:
        flat.append(int(u))
        flat.append(int(v))
    flat.append(len(groups))
    for N, table in groups:
        flat.append(int(N))
        flat.extend(table)
    if len(flat) % 2:
        flat.append(0)
    pairs = list(zip(flat[0::2], flat[1::2]))
    return (0, pairs)


def build(d, D, seed, time_limit):
    t0 = time.monotonic()
    if d < 1 or D < 1:
        return 1, []
    if d == 1 or D == 1:
        return 2, [(0, 1)]

    best = lib.haar_graph(d, range(d))          # K_{d,d}: valid for D >= 2
    try:
        start = known_start(d, D)
    except (ValueError, RuntimeError):
        start = None
    if start is not None and start[0] > best[0] and lib.is_valid(start[0], start[1], d, D):
        best = start

    moore = lib.moore_bound(d, D)
    if best[0] >= moore:
        return best

    # Use most of the limit; keep a margin for compilation and process startup.
    budget = 0.95 * time_limit - (time.monotonic() - t0) - 1.5
    if budget < 0.5:
        return best
    try:
        hi = min(moore // 2, 340)
        groups = _group_tables(8, hi, seed)
        stream = _stream(best, groups)
        text = lib.run_c(C_SOURCE, [d, D, seed, round(budget, 2)],
                         stdin_graph=stream, timeout=budget + 2.5)
        n, edges = lib.parse_graph_text(text)
        if n > best[0] and lib.is_valid(n, edges, d, D):
            best = (n, edges)
    except (RuntimeError, ValueError, OSError, MemoryError):
        pass
    if not lib.is_valid(best[0], best[1], d, D):
        best = lib.haar_graph(d, range(d))
    return best
