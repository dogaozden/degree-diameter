"""Diameter-3 bipartite search: deletion-repair from PG(2,d) plus arc-extension starts and a C engine.

Starts:
  * Arc-extended PG(2,q) incidence graphs for prime powers q < d (the previous best family).
  * NEW bold start for prime-power d: the incidence graph of PG(2,d) with a perfect matching of
    incidences removed. This is d-regular on 2(d^2+d+1) vertices but generally has diameter 4, so the
    C engine first repairs it: it repeatedly deletes the vertex involved in the most too-far pairs.
    Once every pair is within distance D, it augments with the same safe rule as before.

The C engine: (1) repairs any start whose diameter exceeds D by greedy vertex deletion, then
(2) repeatedly adds one vertex on a random side, joined to a set T of spare vertices on the other side
chosen by greedy set cover. A new vertex is accepted only if every existing vertex lies within
distance D-1 of T, so the new vertex is within distance D of everything and existing distances never
grow. Python re-checks every result with lib.is_valid and falls back to the best valid start,
so the returned graph is never worse than the best valid start that was built.
"""
import itertools
import random
import sys
import time

import lib

C_SOURCE = r"""
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>
#include <time.h>

#define MAXN 2048
#define WORDS (MAXN / 64)
#define MAXDEG 64

static int N, Dd, Dist, W;
static int deg[MAXN];
static int adj[MAXN][MAXDEG];
static int side[MAXN];
static uint64_t ball[MAXN][WORDS];
static uint64_t tmpb[WORDS];
static int badv[MAXN];
static int mark[MAXN], lev[MAXN], bq[MAXN];
static int stamp = 0;
static uint64_t rs = 88172645463325252ULL;

static uint64_t rnd(void) {
    rs ^= rs << 13;
    rs ^= rs >> 7;
    rs ^= rs << 17;
    return rs;
}

static int rndint(int k) { return (int)(rnd() % (uint64_t)k); }

static double elapsed(void) { return (double)clock() / (double)CLOCKS_PER_SEC; }

static int popc(uint64_t x) {
    x = x - ((x >> 1) & 0x5555555555555555ULL);
    x = (x & 0x3333333333333333ULL) + ((x >> 2) & 0x3333333333333333ULL);
    x = (x + (x >> 4)) & 0x0f0f0f0f0f0f0f0fULL;
    return (int)((x * 0x0101010101010101ULL) >> 56);
}

/* Bitset of all vertices within distance r of src. */
static void ball_of(int src, int r, uint64_t *bits) {
    int head = 0, t = 0;
    stamp++;
    for (int i = 0; i < W; i++) bits[i] = 0;
    bq[t++] = src;
    mark[src] = stamp;
    lev[src] = 0;
    while (head < t) {
        int u = bq[head++];
        bits[u >> 6] |= 1ULL << (u & 63);
        if (lev[u] >= r) continue;
        for (int k = 0; k < deg[u]; k++) {
            int v = adj[u][k];
            if (mark[v] != stamp) {
                mark[v] = stamp;
                lev[v] = lev[u] + 1;
                bq[t++] = v;
            }
        }
    }
}

static void recompute_balls(void) {
    W = (N + 63) / 64;
    for (int v = 0; v < N; v++) ball_of(v, Dist - 1, ball[v]);
}

/* Fills badv[v] = number of vertices NOT within distance Dist of v. Returns the sum (ordered pairs). */
static int badcount(void) {
    int total = 0;
    W = (N + 63) / 64;
    for (int v = 0; v < N; v++) {
        ball_of(v, Dist, tmpb);
        int c = 0;
        for (int i = 0; i < W; i++) c += popc(tmpb[i]);
        badv[v] = N - c;
        total += badv[v];
    }
    return total;
}

/* Delete vertex v by moving the last vertex into its slot. */
static void remove_vertex(int v) {
    for (int k = 0; k < deg[v]; k++) {
        int u = adj[v][k];
        for (int j = 0; j < deg[u]; j++) {
            if (adj[u][j] == v) {
                adj[u][j] = adj[u][deg[u] - 1];
                deg[u]--;
                break;
            }
        }
    }
    int last = N - 1;
    if (v != last) {
        for (int k = 0; k < deg[last]; k++) {
            int u = adj[last][k];
            for (int j = 0; j < deg[u]; j++) {
                if (adj[u][j] == last) {
                    adj[u][j] = v;
                    break;
                }
            }
        }
        deg[v] = deg[last];
        for (int k = 0; k < deg[last]; k++) adj[v][k] = adj[last][k];
        side[v] = side[last];
    }
    deg[last] = 0;
    N--;
    W = (N + 63) / 64;
}

/* Try to add one new vertex on side X. Returns 1 if the graph grew. */
static int try_add(int X) {
    uint64_t U[WORDS];
    int sel[MAXN];
    int T[MAXDEG];
    int nt = 0;
    if (N + 1 >= MAXN) return 0;
    W = (N + 63) / 64;
    for (int i = 0; i < W; i++) U[i] = ~0ULL;
    if (N & 63) U[W - 1] = (1ULL << (N & 63)) - 1ULL;
    memset(sel, 0, sizeof(sel));
    while (nt < Dd) {
        int best = -1;
        long bestsc = -1;
        for (int v = 0; v < N; v++) {
            if (side[v] == X || deg[v] >= Dd || sel[v]) continue;
            int g = 0;
            for (int i = 0; i < W; i++) g += popc(ball[v][i] & U[i]);
            if (g <= 0) continue;
            long sc = (long)g * 8 + rndint(8);
            if (sc > bestsc) {
                bestsc = sc;
                best = v;
            }
        }
        if (best < 0) break;
        sel[best] = 1;
        T[nt++] = best;
        for (int i = 0; i < W; i++) U[i] &= ~ball[best][i];
    }
    for (int i = 0; i < W; i++)
        if (U[i]) return 0;
    if (nt == 0) return 0;
    int x = N;
    side[x] = X;
    deg[x] = nt;
    for (int k = 0; k < nt; k++) {
        int t = T[k];
        adj[x][k] = t;
        adj[t][deg[t]++] = x;
    }
    N++;
    recompute_balls();
    return 1;
}

int main(int argc, char **argv) {
    if (argc < 5) return 1;
    Dd = atoi(argv[1]);
    if (Dd > MAXDEG) Dd = MAXDEG;
    Dist = atoi(argv[2]);
    unsigned long seed = strtoul(argv[3], NULL, 10);
    double budget = atof(argv[4]);
    rs ^= (uint64_t)seed * 0x9E3779B97F4A7C15ULL + 12345ULL;
    if (rs == 0) rs = 1;

    int n = 0, m = 0;
    if (scanf("%d %d", &n, &m) != 2) n = 0;
    if (n <= 0 || n > MAXN - 2 || Dist < 2) {
        printf("0 0\n");
        return 0;
    }
    N = n;
    for (int i = 0; i < m; i++) {
        int u, v;
        if (scanf("%d %d", &u, &v) != 2) break;
        if (u < 0 || u >= N || v < 0 || v >= N || u == v) continue;
        if (deg[u] >= MAXDEG || deg[v] >= MAXDEG) continue;
        adj[u][deg[u]++] = v;
        adj[v][deg[v]++] = u;
    }

    /* Bipartition by BFS colouring (the input must be bipartite). */
    for (int v = 0; v < N; v++) side[v] = -1;
    for (int s = 0; s < N; s++) {
        if (side[s] >= 0) continue;
        side[s] = 0;
        int head = 0, t = 0;
        bq[t++] = s;
        while (head < t) {
            int u = bq[head++];
            for (int k = 0; k < deg[u]; k++) {
                int v = adj[u][k];
                if (side[v] < 0) {
                    side[v] = 1 - side[u];
                    bq[t++] = v;
                }
            }
        }
    }

    double t_end = elapsed() + budget;
    double t_rep = elapsed() + 0.6 * budget;

    /* Phase 1: repair. Delete the vertex with the most too-far pairs until diameter <= Dist. */
    int total = badcount();
    while (total > 0 && N > 2 && elapsed() < t_rep) {
        long bestsc = -1;
        int bv = 0;
        for (int v = 0; v < N; v++) {
            long sc = (long)badv[v] * 1024 + rndint(1024);
            if (sc > bestsc) {
                bestsc = sc;
                bv = v;
            }
        }
        remove_vertex(bv);
        total = badcount();
    }

    /* Phase 2: augment only a valid graph. */
    if (total == 0) {
        recompute_balls();
        int fails = 0;
        while (elapsed() < t_end && N < MAXN - 2 && fails < 4000) {
            int X = rndint(2);
            if (try_add(X)) fails = 0;
            else fails++;
        }
    }

    int M = 0;
    for (int v = 0; v < N; v++)
        for (int k = 0; k < deg[v]; k++)
            if (adj[v][k] > v) M++;
    printf("%d %d\n", N, M);
    for (int v = 0; v < N; v++)
        for (int k = 0; k < deg[v]; k++)
            if (adj[v][k] > v) printf("%d %d\n", v, adj[v][k]);
    return 0;
}
"""


# ----------------------------------------------------------------------------
# Arc-extended projective plane incidence graphs (diameter 3), as before.
# ----------------------------------------------------------------------------

def _pg_data(q):
    """Return (m, edges, point_lines, line_points, index, pts) for PG(2, q)."""
    pts = lib.projective_points(q)
    n2, edges = lib.projective_plane_incidence(q)
    m = n2 // 2
    point_lines = [[] for _ in range(m)]
    line_points = [[] for _ in range(m)]
    for u, v in edges:
        point_lines[u].append(v - m)
        line_points[v - m].append(u)
    index = {p: i for i, p in enumerate(pts)}
    return m, edges, point_lines, line_points, index, pts


def _loads_ok(S, s, m, point_lines, line_points):
    """True if every line holds <= s points of S and every point lies on <= s lines indexed by S."""
    cl = [0] * m
    cp = [0] * m
    for P in S:
        for L in point_lines[P]:
            cl[L] += 1
        for Q in line_points[P]:
            cp[Q] += 1
    return max(cl, default=0) <= s and max(cp, default=0) <= s


def _greedy_arc(m, s, point_lines, line_points, rng, trials, deadline):
    """Randomized greedy choice of S with all loads <= s; returns the largest found."""
    best = []
    order = list(range(m))
    for _ in range(trials):
        if time.monotonic() > deadline:
            break
        rng.shuffle(order)
        cl = [0] * m
        cp = [0] * m
        S = []
        for P in order:
            if all(cl[L] < s for L in point_lines[P]) and all(cp[Q] < s for Q in line_points[P]):
                S.append(P)
                for L in point_lines[P]:
                    cl[L] += 1
                for Q in line_points[P]:
                    cp[Q] += 1
        if len(S) > len(best):
            best = S
    return best


def _conic_set(q, index, F):
    """Conic (plus nucleus for even q) as a point-index set: an arc with no three collinear."""
    S = [index[(1, t, F.mul(t, t))] for t in range(q)]
    S.append(index[(0, 0, 1)])
    if q % 2 == 0:
        S.append(index[(0, 1, 0)])
    return S


def _arc_graph(m, edges, point_lines, line_points, S):
    """Old PG incidence plus a new A and a new B vertex per element of S."""
    k = len(S)
    n = 2 * m + 2 * k
    E = list(edges)
    for t, P in enumerate(S):
        x = 2 * m + t
        for L in point_lines[P]:
            E.append((x, m + L))
    for t, j in enumerate(S):
        b = 2 * m + k + t
        for Q in line_points[j]:
            E.append((Q, b))
    return n, E


def _arc_extensions(d, deadline, rng):
    """Return (n, edges) candidates for each prime power q with q + 1 <= d."""
    out = []
    for q in range(2, min(d - 1, 23) + 1):
        if not lib.is_prime_power(q):
            continue
        if time.monotonic() > deadline:
            break
        s = d - q - 1
        m, edges, pl, lp, index, _pts = _pg_data(q)
        cands = [[]]
        if s >= 1:
            cands.append(_greedy_arc(m, s, pl, lp, rng, 40, deadline))
        if s >= 2:
            cs = _conic_set(q, index, lib.GF(q))
            if _loads_ok(cs, s, m, pl, lp):
                cands.append(cs)
        S = max(cands, key=len)
        if not _loads_ok(S, s, m, pl, lp):
            continue
        out.append(_arc_graph(m, edges, pl, lp, S))
    return out


# ----------------------------------------------------------------------------
# NEW bold start: PG(2,q) incidence minus a perfect matching of incidences.
# Gives a q-regular bipartite graph on 2(q^2+q+1) vertices (q = d). Its diameter is
# typically larger than 3, so the C engine's repair phase deletes the worst vertices.
# ----------------------------------------------------------------------------

def _matching_pg(q):
    """PG(2,q) incidence minus a perfect matching: (q+1)-regular -> q-regular. None if no matching."""
    sys.setrecursionlimit(max(sys.getrecursionlimit(), 10000))
    n2, edges = lib.projective_plane_incidence(q)
    m = n2 // 2
    lines_of = [[] for _ in range(m)]
    for u, v in edges:
        lines_of[u].append(v - m)
    owner = [-1] * m  # line index -> matched point

    def augment(p, seen):
        for L in lines_of[p]:
            if L in seen:
                continue
            seen.add(L)
            if owner[L] == -1 or augment(owner[L], seen):
                owner[L] = p
                return True
        return False

    for p in range(m):
        if not augment(p, set()):
            return None
    removed = {(owner[L], m + L) for L in range(m)}
    kept = [(u, v) for u, v in edges if (u, v) not in removed]
    return n2, kept


# ----------------------------------------------------------------------------
# Generalized quadrangle W(q) incidence graph (diameter 4), used for D >= 4.
# ----------------------------------------------------------------------------

def _gq_w(q):
    """Incidence graph of points and lines of the generalized quadrangle W(q)."""
    F = lib.GF(q)
    pts = [v for v in itertools.product(range(q), repeat=4)
           if any(v) and next(c for c in v if c) == 1]
    index = {v: i for i, v in enumerate(pts)}
    P = len(pts)

    def norm(v):
        c = next(x for x in v if x)
        inv = F.inv(c)
        return tuple(F.mul(inv, x) for x in v)

    def form(x, y):
        t = F.sub(F.mul(x[0], y[1]), F.mul(x[1], y[0]))
        return F.add(t, F.sub(F.mul(x[2], y[3]), F.mul(x[3], y[2])))

    covered = set()
    lines = []
    for i in range(P):
        x = pts[i]
        for j in range(i + 1, P):
            if (i, j) in covered:
                continue
            y = pts[j]
            if form(x, y) != 0:
                continue
            L = set()
            for a in range(q):
                for b in range(q):
                    if a == 0 and b == 0:
                        continue
                    v = tuple(F.add(F.mul(a, x[k]), F.mul(b, y[k])) for k in range(4))
                    if any(v):
                        L.add(index[norm(v)])
            L = sorted(L)
            lines.append(L)
            for p in L:
                for r in L:
                    if p < r:
                        covered.add((p, r))

    edges = []
    for j, L in enumerate(lines):
        for p in L:
            edges.append((p, P + j))
    return 2 * P, edges


def _best_gq(d):
    """W(q) for the largest prime power q with q + 1 <= d, restricted to small q for speed."""
    for q in range(min(d - 1, 9), 1, -1):
        if lib.is_prime_power(q):
            return _gq_w(q)
    return None


# ----------------------------------------------------------------------------
# C driver.
# ----------------------------------------------------------------------------

def _augment(n0, e0, d, D, seed, budget, timeout):
    """Run the C engine from the start graph (n0, e0) and parse its output."""
    text = lib.run_c(C_SOURCE, [d, D, seed, f"{budget:.2f}"],
                     stdin_graph=(n0, e0), timeout=timeout)
    return lib.parse_graph_text(text)


def build(d, D, seed, time_limit):
    """Return the best valid (n, edges) found within about 80% of time_limit."""
    t0 = time.monotonic()
    hard_end = t0 + 0.80 * time_limit
    if d < 1 or D < 1:
        return 1, []
    if D == 1:
        return 2, [(0, 1)]
    rng = random.Random(seed * 7919 + d)

    # Safe fallback: K_{d,d} has diameter 2, so it is valid for every D >= 2.
    fallback = lib.haar_graph(d, range(d))

    starts = []
    if D >= 3:
        starts.extend(_arc_extensions(d, t0 + 0.20 * time_limit, rng))
    if D >= 4 and time.monotonic() < t0 + 0.25 * time_limit:
        gq = _best_gq(d)
        if gq is not None:
            starts.append(gq)
    starts = [g for g in starts if lib.is_valid(g[0], g[1], d, D)]
    starts.sort(key=lambda g: -g[0])
    if lib.is_valid(fallback[0], fallback[1], d, D):
        starts.append(fallback)
    if not starts:
        return 1, []
    best = max(starts, key=lambda g: g[0])

    # Jobs: the bold deletion-repair start first (if available), then the best valid starts.
    jobs = []
    if D >= 3 and lib.is_prime_power(d) and time.monotonic() < t0 + 0.30 * time_limit:
        try:
            mg = _matching_pg(d)
        except Exception:
            mg = None
        if mg is not None:
            jobs.append(mg)
    jobs.extend(starts[:2])

    for idx, src in enumerate(jobs):
        remaining = hard_end - time.monotonic()
        if remaining < 2.0:
            break
        share = remaining / (len(jobs) - idx)
        try:
            n1, e1 = _augment(src[0], src[1], d, D, seed * 31 + idx,
                              max(0.3, share - 1.0), share + 3.0)
        except Exception:
            continue
        if n1 > best[0] and lib.is_valid(n1, e1, d, D):
            best = (n1, e1)

    # Spend any leftover time augmenting the current best valid graph.
    remaining = hard_end - time.monotonic()
    if remaining >= 2.0:
        try:
            n1, e1 = _augment(best[0], best[1], d, D, seed * 31 + 99,
                              max(0.3, remaining - 1.0), remaining + 3.0)
            if n1 > best[0] and lib.is_valid(n1, e1, d, D):
                best = (n1, e1)
        except Exception:
            pass

    if not lib.is_valid(best[0], best[1], d, D):
        best = fallback
    return best
