def build(d, D, seed, time_limit):
    t0 = time.monotonic()
    if d < 1 or D < 1:
        return 1, []
    if D == 1:
        return 2, [(0, 1)]

    fallback = lib.haar_graph(d, range(d))   # K_{d,d}: diameter 2, valid for D >= 2
    if not lib.is_valid(fallback[0], fallback[1], d, D):
        fallback = (1, [])
    best = fallback

    rng = random.Random(seed * 7919 + d * 131 + D)
    try:
        cands = _starts(d, D, rng, t0 + 0.2 * time_limit)
    except Exception:
        cands = []
    for g in cands:
        try:
            if g[0] > best[0] and lib.is_valid(g[0], g[1], d, D):
                best = g
        except Exception:
            pass

    elapsed = time.monotonic() - t0
    budget = 0.86 * time_limit - elapsed - 3.0
    if best[0] >= lib.moore_bound(d, D):
        budget = min(budget, 0.5)
    if budget >= 0.5:
        timeout = max(1.0, 0.97 * time_limit - (time.monotonic() - t0))
        try:
            text = lib.run_c(C_SOURCE, [d, D, seed, f"{budget:.2f}"],
                             stdin_graph=best, timeout=timeout)
            n1, e1 = lib.parse_graph_text(text)
            if n1 > best[0] and lib.is_valid(n1, e1, d, D):
                best = (n1, e1)
        except Exception:
            pass

    if not lib.is_valid(best[0], best[1], d, D):
        best = fallback
    return best
