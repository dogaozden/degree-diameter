"""Diameter-D bipartite search: structured starts (projective planes, conic twin blow-ups,
arc extensions, Araujo-Pardo-Lopez graphs, generalized quadrangles) plus a C engine that
alternates two moves: (1) add one vertex on a random side, joined to a set of spare
vertices that covers everything within distance D-1 (distances to old pairs never grow),
and (2) grow by two vertices with degree-preserving edge swaps annealed until no pair is
too far apart. Group-voltage lifts run as a short side search. Python validates everything.
"""
