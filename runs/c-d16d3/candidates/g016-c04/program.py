"""Diameter-3 bipartite search: structured starts (arc-extended PG(2,q), conic twin blow-up,
Moore graphs, generalized quadrangles for D >= 4) followed by a C engine that adds vertices
(set-cover augmentation) and anneals degree-preserving swaps (grow-by-two), with a small
voltage-lift search when the start is weak. Python re-checks everything with lib.is_valid.
"""
