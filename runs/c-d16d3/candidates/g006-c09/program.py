# ----------------------------------------------------------------------------
# Arc-extended projective plane incidence graphs (diameter 3).
#
# Start from the incidence graph of PG(2, q) (points 0..m-1, lines m..2m-1).
# Each old vertex has degree q+1, so spare capacity s = d - q - 1. A point set S
# with every line holding <= s points of S (and every point on <= s lines of S)
# lets each P in S get a new A-vertex joined to the lines through P, and each
# j in S get a new B-vertex joined to the points on line j.
# ----------------------------------------------------------------------------

def _pg_data(q):
    """Return (m, edges, point_lines, line_points, index, pts) for PG(2, q)."""
    pts = lib.projective_points(q)
    n2, edges = lib.projective_plane_incidence(q)
    m = n2 // 2
    point_lines = [[] for _ in range(m)]
    line_points = [[] for _ in range(m)]
    for u, v in edges:
        point_lines[u].append(v - m)
        line_points[v - m].append(u)
    index = {p: i for i, p in enumerate(pts)}
    return m, edges, point_lines, line_points, index, pts


def _loads_ok(S, s, m, point_lines, line_points):
    """True if every line holds <= s points of S and every point lies on <= s lines indexed by S."""
    cl = [0] * m
    cp = [0] * m
    for P in S:
        for L in point_lines[P]:
            cl[L] += 1
        for Q in line_points[P]:
            cp[Q] += 1
    return max(cl, default=0) <= s and max(cp, default=0) <= s


def _greedy_arc(m, s, point_lines, line_points, rng, trials, deadline):
    """Randomized greedy choice of S with all loads <= s; returns the largest found."""
    best = []
    order = list(range(m))
    for _ in range(trials):
        if time.monotonic() > deadline:
            break
        rng.shuffle(order)
        cl = [0] * m
        cp = [0] * m
        S = []
        for P in order:
            if all(cl[L] < s for L in point_lines[P]) and all(cp[Q] < s for Q in line_points[P]):
                S.append(P)
                for L in point_lines[P]:
                    cl[L] += 1
                for Q in line_points[P]:
                    cp[Q] += 1
        if len(S) > len(best):
            best = S
    return best


def _conic_set(q, index, F):
    """Conic (plus nucleus for even q) as a point-index set: an arc with no three collinear."""
    S = [index[(1, t, F.mul(t, t))] for t in range(q)]
    S.append(index[(0, 0, 1)])
    if q % 2 == 0:
        S.append(index[(0, 1, 0)])
    return S


def _arc_graph(m, edges, point_lines, line_points, S):
    """Old PG incidence plus a new A-vertex (pencil at P) and a new B-vertex (line j) per element of S.

    Layout: points 0..m-1 and A-vertices 2m..2m+k-1 are one side; lines m..2m-1 and B-vertices after are the other.
    """
    k = len(S)
    n = 2 * m + 2 * k
    E = list(edges)
    for t, P in enumerate(S):
        x = 2 * m + t
        for L in point_lines[P]:
            E.append((x, m + L))
    for t, j in enumerate(S):
        b = 2 * m + k + t
        for Q in line_points[j]:
            E.append((Q, b))
    return n, E


def _arc_extensions(d, deadline, rng):
    """Return (n, edges) candidates for each prime power q with q + 1 <= d."""
    out = []
    for q in range(2, min(d - 1, 23) + 1):
        if not lib.is_prime_power(q):
            continue
        if time.monotonic() > deadline:
            break
        s = d - q - 1
        m, edges, point_lines, line_points, index, pts = _pg_data(q)
        cands = []
        if s >= 1:
            cands.append(_greedy_arc(m, s, point_lines, line_points, rng, 40, deadline))
        if s >= 2:
            F = lib.GF(q)
            cs = _conic_set(q, index, F)
            if _loads_ok(cs, s, m, point_lines, line_points):
                cands.append(cs)
        S = max(cands, key=len, default=[])
        if not _loads_ok(S, s, m, point_lines, line_points):
            continue
        n_c, e_c = _arc_graph(m, edges, point_lines, line_points, S)
        out.append((n_c, e_c))
    return out


# ----------------------------------------------------------------------------
# NEW (high-risk): graph repair annealing that grows a valid D=3 graph.
#
# Starting from a valid bipartite graph, add one vertex on each side (no edges),
# then anneal over degree-preserving 2-switches, edge additions and deletions,
# minimising the number of ordered vertex pairs at distance > 3. Each success
# adds another pair of vertices. Every bipartition edge stays across sides, and
# degrees never exceed d, so only the diameter needs checking (done by is_valid).
# ----------------------------------------------------------------------------

def _side_colors(n, edges):
    """Return a proper 2-colouring (list of 0/1) of the bipartite graph."""
    adj = [[] for _ in range(n)]
    for u, v in edges:
        adj[u].append(v)
        adj[v].append(u)
    col = [-1] * n
    for s in range(n):
        if col[s] != -1:
            continue
        col[s] = 0
        stack = [s]
        while stack:
            u = stack.pop()
            for v in adj[u]:
                if col[v] == -1:
                    col[v] = 1 - col[u]
                    stack.append(v)
    return col


def _bad_pairs_adj(adj, n):
    """Ordered count of vertex pairs at distance > 3 (unreachable counts as bad)."""
    reach = [1 << v for v in range(n)]
    for _ in range(3):
        new = []
        for v in range(n):
            r = reach[v]
            for u in adj[v]:
                r |= reach[u]
            new.append(r)
        reach = new
    return sum(n - r.bit_count() for r in reach)


def _anneal_repair(n, edges, col, d, deadline, rng):
    """Anneal toward a diameter-3 graph on n vertices; return its edge list or None."""
    adj = [set() for _ in range(n)]
    for u, v in edges:
        adj[u].add(v)
        adj[v].add(u)
    side = ([i for i in range(n) if col[i] == 0], [i for i in range(n) if col[i] == 1])
    cost = _bad_pairs_adj(adj, n)
    t0 = time.monotonic()
    span = max(1e-3, deadline - t0)
    while cost > 0:
        now = time.monotonic()
        if now >= deadline:
            return None
        T = 0.8 * (1.0 - (now - t0) / span) + 0.03
        r = rng.random()
        if r < 0.35:
            # Add an edge between two vertices with spare degree.
            u = rng.randrange(n)
            if len(adj[u]) >= d:
                continue
            v = rng.choice(side[1 - col[u]])
            if v in adj[u] or len(adj[v]) >= d:
                continue
            adj[u].add(v)
            adj[v].add(u)
            c2 = _bad_pairs_adj(adj, n)
            if c2 <= cost or rng.random() < math.exp(-(c2 - cost) / T):
                cost = c2
            else:
                adj[u].discard(v)
                adj[v].discard(u)
        elif r < 0.95:
            # 2-switch on one side: u-w, v-x  ->  u-x, v-w (degrees unchanged).
            pool = side[rng.randrange(2)]
            u = rng.choice(pool)
            v = rng.choice(pool)
            if u == v or not adj[u] or not adj[v]:
                continue
            w = rng.choice(tuple(adj[u]))
            x = rng.choice(tuple(adj[v]))
            if x in adj[u] or w in adj[v]:
                continue
            adj[u].discard(w)
            adj[w].discard(u)
            adj[v].discard(x)
            adj[x].discard(v)
            adj[u].add(x)
            adj[x].add(u)
            adj[v].add(w)
            adj[w].add(v)
            c2 = _bad_pairs_adj(adj, n)
            if c2 <= cost or rng.random() < math.exp(-(c2 - cost) / T):
                cost = c2
            else:
                adj[u].discard(x)
                adj[x].discard(u)
                adj[v].discard(w)
                adj[w].discard(v)
                adj[u].add(w)
                adj[w].add(u)
                adj[v].add(x)
                adj[x].add(v)
        else:
            # Delete a random edge (frees degree for later additions).
            u = rng.randrange(n)
            if not adj[u]:
                continue
            w = rng.choice(tuple(adj[u]))
            adj[u].discard(w)
            adj[w].discard(u)
            c2 = _bad_pairs_adj(adj, n)
            if c2 <= cost or rng.random() < math.exp(-(c2 - cost) / T):
                cost = c2
            else:
                adj[u].add(w)
                adj[w].add(u)
    return [(u, v) for u in range(n) for v in adj[u] if u < v]


def _grow_repair(n, edges, d, deadline, rng):
    """Repeatedly add a vertex pair and anneal; return the largest valid (n, edges) reached, or None."""
    col = _side_colors(n, edges)
    cur_n, cur_e = n, list(edges)
    best = None
    while time.monotonic() < deadline:
        nn = cur_n + 2
        ncol = col + [0, 1]
        res = _anneal_repair(nn, cur_e, ncol, d, deadline, rng)
        if res is None:
            break
        cur_n, cur_e, col = nn, res, ncol
        best = (cur_n, cur_e)
    return best


