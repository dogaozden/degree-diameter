import itertools
import math
import random
import time

import lib


# ----------------------------------------------------------------------------
# Main changes from the parent:
#
# 1. Twin-cloning growth (new operator). Cloning a vertex v (adding x with
#    N(x) = N(v)) keeps the graph bipartite, keeps distances between old
#    vertices unchanged, and gives dist(x, v) = 2 and dist(x, y) <= dist(v, y).
#    So diameter <= D is preserved. A clone is allowed only if every neighbour
#    of v has spare degree. Cloning is run greedily with random restarts on
#    several bases: arc-extended PG(2,q), plain PG(2,q) incidence graphs, and
#    the Araujo-Pardo-Lopez graphs.
# 2. Random restarts of the voltage annealing are kept for D >= 4 only.
# 3. Every candidate is checked with lib.is_valid before it can replace the
#    best graph. The fallback is K_{d,d}, which is valid for D >= 2.
#
# Limitation: within the PG(2,13) blow-up family, the weight argument gives
# at most 14 extra copies per side, so 394 is the ceiling of that family. Beating
# the record needs a different base graph, which this program does not find.
# ----------------------------------------------------------------------------


def _pg_data(q):
    """Return (m, edges, point_lines, line_points, index, pts) for PG(2, q)."""
    pts = lib.projective_points(q)
    n2, edges = lib.projective_plane_incidence(q)
    m = n2 // 2
    point_lines = [[] for _ in range(m)]
    line_points = [[] for _ in range(m)]
    for u, v in edges:
        point_lines[u].append(v - m)
        line_points[v - m].append(u)
    index = {p: i for i, p in enumerate(pts)}
    return m, edges, point_lines, line_points, index, pts


def _loads_ok(S, s, m, point_lines, line_points):
    """True if every line holds <= s points of S and every point lies on <= s lines indexed by S."""
    cl = [0] * m
    cp = [0] * m
    for P in S:
        for L in point_lines[P]:
            cl[L] += 1
        for Q in line_points[P]:
            cp[Q] += 1
    return max(cl, default=0) <= s and max(cp, default=0) <= s


def _greedy_arc(m, s, point_lines, line_points, rng, trials, deadline):
    """Randomized greedy choice of S with all loads <= s; returns the largest found."""
    best = []
    order = list(range(m))
    for _ in range(trials):
        if time.monotonic() > deadline:
            break
        rng.shuffle(order)
        cl = [0] * m
        cp = [0] * m
        S = []
        for P in order:
            if all(cl[L] < s for L in point_lines[P]) and all(cp[Q] < s for Q in line_points[P]):
                S.append(P)
                for L in point_lines[P]:
                    cl[L] += 1
                for Q in line_points[P]:
                    cp[Q] += 1
        if len(S) > len(best):
            best = S
    return best


def _conic_set(q, index, F):
    """Conic (plus nucleus for even q) as a point-index set: an arc with no three collinear."""
    S = [index[(1, t, F.mul(t, t))] for t in range(q)]
    S.append(index[(0, 0, 1)])
    if q % 2 == 0:
        S.append(index[(0, 1, 0)])
    return S


def _arc_graph(m, edges, point_lines, line_points, S):
    """Old PG incidence plus a new A and a new B vertex for each element of S."""
    k = len(S)
    n = 2 * m + 2 * k
    E = list(edges)
    for t, P in enumerate(S):
        x = 2 * m + t
        for L in point_lines[P]:
            E.append((x, m + L))
    for t, j in enumerate(S):
        b = 2 * m + k + t
        for Q in line_points[j]:
            E.append((Q, b))
    return n, E


def _arc_extensions(d, deadline, rng):
    """Return candidate bases for each prime power q with q + 1 <= d: plain PG and arc-extended."""
    out = []
    for q in range(2, min(d - 1, 23) + 1):
        if not lib.is_prime_power(q):
            continue
        if time.monotonic() > deadline:
            break
        s = d - q - 1
        m, edges, point_lines, line_points, index, pts = _pg_data(q)
        out.append((2 * m, list(edges)))
        if s >= 1:
            cands = [_greedy_arc(m, s, point_lines, line_points, rng, 40, deadline)]
            if s >= 2:
                cs = _conic_set(q, index, lib.GF(q))
                if _loads_ok(cs, s, m, point_lines, line_points):
                    cands.append(cs)
            S = max(cands, key=len, default=[])
            if S and _loads_ok(S, s, m, point_lines, line_points):
                out.append(_arc_graph(m, edges, point_lines, line_points, S))
    return out


def _clone_grow(n, edges, d, rng, deadline):
    """Greedy randomized twin-cloning. Returns (n, edges) with more vertices, diameter unchanged."""
    adj = [set() for _ in range(n)]
    for u, v in edges:
        adj[u].add(v)
        adj[v].add(u)
    deg = [len(a) for a in adj]
    E = [tuple(e) for e in edges]
    while time.monotonic() < deadline:
        cands = [v for v in range(n) if adj[v] and all(deg[u] < d for u in adj[v])]
        if not cands:
            break
        v = rng.choice(cands)
        x = n
        n += 1
        adj.append(set(adj[v]))
        deg.append(deg[v])
        for u in adj[v]:
            adj[u].add(x)
            deg[u] += 1
            E.append((u, x))
    return n, E


# ----------------------------------------------------------------------------
# Generalized quadrangle baseline (D = 4).
# ----------------------------------------------------------------------------

def _gq_w(q):
    """Incidence graph of points and lines of the generalized quadrangle W(q); diameter 4."""
    F = lib.GF(q)
    pts = [v for v in itertools.product(range(q), repeat=4)
           if any(v) and next(c for c in v if c) == 1]
    index = {v: i for i, v in enumerate(pts)}
    P = len(pts)

    def norm(v):
        c = next(x for x in v if x)
        inv = F.inv(c)
        return tuple(F.mul(inv, x) for x in v)

    def form(x, y):
        t = F.sub(F.mul(x[0], y[1]), F.mul(x[1], y[0]))
        return F.add(t, F.sub(F.mul(x[2], y[3]), F.mul(x[3], y[2])))

    covered = set()
    lines = []
    for i in range(P):
        x = pts[i]
        for j in range(i + 1, P):
            if (i, j) in covered:
                continue
            y = pts[j]
            if form(x, y) != 0:
                continue
            L = set()
            for a in range(q):
                for b in range(q):
                    if a == 0 and b == 0:
                        continue
                    v = tuple(F.add(F.mul(a, x[k]), F.mul(b, y[k])) for k in range(4))
                    if any(v):
                        L.add(index[norm(v)])
            L = sorted(L)
            lines.append(L)
            for p in L:
                for r in L:
                    if p < r:
                        covered.add((p, r))

    edges = []
    for j, L in enumerate(lines):
        for p in L:
            edges.append((p, P + j))
    return 2 * P, edges


def _best_gq(d):
    """W(q) for the largest prime power q with q + 1 <= d, restricted to small q for speed."""
    for q in range(min(d - 1, 9), 1, -1):
        if lib.is_prime_power(q):
            return _gq_w(q)
    return None


