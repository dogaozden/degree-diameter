# Cost = number of unordered pairs at distance > D. Moves keep max degree <= d
# and bipartiteness. Whenever the cost reaches 0 the engine saves the graph and
# appends one isolated vertex, so it grows the order while staying valid.
# ----------------------------------------------------------------------------

