import itertools
import math
import random
import time

import lib


# ----------------------------------------------------------------------------
# New construction for D = 3: multiplier-invariant difference covers.
#
# The Haar graph H(m, S) has parts A = Z_m and B = Z_m with a_i ~ b_{i+s}
# for s in S. It has diameter 3 exactly when S - S = Z_m (a difference cover).
# Plain annealing over S is slow for m near the Moore cap k(k-1)+1.
#
# New idea: restrict S to a union of orbits of a multiplicative subgroup H of
# Z_m^*. If S is H-invariant, so is S - S, so a cover only has to hit each
# H-orbit of nonzero residues. The search then runs over subsets of orbits
# (about m/|H| units), which is far smaller than over subsets of Z_m.
# Subgroups H = <g> are sampled from random units g. The trivial group gives
# the plain search as a special case.
# ----------------------------------------------------------------------------

def _subgroup(g, m):
    """Return the list of elements of the cyclic group generated by unit g in Z_m."""
    H = [1 % m]
    x = g % m
    while x != 1 % m and len(H) <= m:
        H.append(x)
        x = (x * g) % m
    return H


def _orbits(m, H):
    """Partition Z_m into orbits under multiplication by the group H."""
    seen = [False] * m
    orbs = []
    for x in range(m):
        if seen[x]:
            continue
        orb = sorted({(h * x) % m for h in H})
        for y in orb:
            seen[y] = True
        orbs.append(orb)
    return orbs


def _uncovered(m, S):
    """Number of nonzero residues not of the form a - b with a != b in S."""
    cov = set()
    for a in S:
        for b in S:
            if a != b:
                cov.add((a - b) % m)
    return (m - 1) - len(cov)


def _anneal_orbits(m, k, orbs, rng, iters, T0):
    """Anneal over subsets of orbits with total size <= k; return S with full cover, or None."""
    no = len(orbs)
    sizes = [len(o) for o in orbs]

    def make(sel):
        return [x for i in sel for x in orbs[i]]

    order = list(range(no))
    rng.shuffle(order)
    sel, tot = set(), 0
    for i in order:
        if tot + sizes[i] <= k:
            sel.add(i)
            tot += sizes[i]
    cur = _uncovered(m, make(sel))
    if cur == 0:
        return make(sel)
    for it in range(iters):
        T = T0 * (1.0 - it / iters) + 0.05
        r = rng.random()
        new = set(sel)
        ntot = tot
        if r < 0.4 and sel:
            i = rng.choice(tuple(sel))
            j = rng.randrange(no)
            if j in sel or tot - sizes[i] + sizes[j] > k:
                continue
            new.discard(i)
            new.add(j)
            ntot = tot - sizes[i] + sizes[j]
        elif r < 0.7:
            j = rng.randrange(no)
            if j in sel or tot + sizes[j] > k:
                continue
            new.add(j)
            ntot = tot + sizes[j]
        else:
            if not sel:
                continue
            i = rng.choice(tuple(sel))
            new.discard(i)
            ntot = tot - sizes[i]
        val = _uncovered(m, make(new))
        if val <= cur or rng.random() < math.exp(-(val - cur) / T):
            sel, tot, cur = new, ntot, val
            if cur == 0:
                return make(sel)
    return None


def _try_m(m, k, rng, end):
    """Search for a cover S of Z_m with |S| <= k, mixing orbit-invariant and plain searches."""
    trivial = [[x] for x in range(m)]
    tries = 0
    while time.monotonic() < end:
        tries += 1
        if tries % 4 == 0:
            orbs = trivial
        else:
            g = rng.randrange(2, m)
            if math.gcd(g, m) != 1:
                continue
            H = _subgroup(g, m)
            if len(H) < 2 or len(H) > k:
                continue
            orbs = _orbits(m, H)
        S = _anneal_orbits(m, k, orbs, rng, 1500, 0.8)
        if S is not None:
            return S
    return None


def _haar_cover(k, rng, deadline):
    """Scan m downward from the Moore cap k(k-1)+1; return (m, S) for the largest m found."""
    mmax = k * (k - 1) + 1
    mlow = max(k + 1, (mmax * 3) // 5)
    ms = list(range(mmax, mlow - 1, -1))
    for idx, m in enumerate(ms):
        now = time.monotonic()
        if now >= deadline:
            break
        share = (deadline - now) / (len(ms) - idx)
        S = _try_m(m, k, rng, now + max(0.15, share))
        if S is not None:
            return m, S
    return None


# ----------------------------------------------------------------------------
# Generalized quadrangle baseline (D = 4)
# ----------------------------------------------------------------------------

def _gq_w(q):
    """Incidence graph of points and lines of the generalized quadrangle W(q); diameter 4."""
    F = lib.GF(q)
    pts = [v for v in itertools.product(range(q), repeat=4)
           if any(v) and next(c for c in v if c) == 1]
    index = {v: i for i, v in enumerate(pts)}
    P = len(pts)

    def norm(v):
        c = next(x for x in v if x)
        inv = F.inv(c)
        return tuple(F.mul(inv, x) for x in v)

    def form(x, y):
        t = F.sub(F.mul(x[0], y[1]), F.mul(x[1], y[0]))
        return F.add(t, F.sub(F.mul(x[2], y[3]), F.mul(x[3], y[2])))

    covered = set()
    lines = []
    for i in range(P):
        x = pts[i]
        for j in range(i + 1, P):
            if (i, j) in covered:
                continue
            y = pts[j]
            if form(x, y) != 0:
                continue
            L = set()
            for a in range(q):
                for b in range(q):
                    if a == 0 and b == 0:
                        continue
                    v = tuple(F.add(F.mul(a, x[k]), F.mul(b, y[k])) for k in range(4))
                    if any(v):
                        L.add(index[norm(v)])
            L = sorted(L)
            lines.append(L)
            for p in L:
                for r in L:
                    if p < r:
                        covered.add((p, r))

    edges = []
    for j, L in enumerate(lines):
        for p in L:
            edges.append((p, P + j))
    return 2 * P, edges


def _best_gq(d):
    for q in range(min(d - 1, 9), 1, -1):
        if lib.is_prime_power(q):
            return _gq_w(q)
    return None


# ----------------------------------------------------------------------------
# Entry point
# ----------------------------------------------------------------------------

def build(d, D, seed, time_limit):
    start = time.monotonic()
    budget = min(0.75 * float(time_limit), 42.0)
    deadline = start + budget
    rng = random.Random(seed * 1000003 + 17 * d + D)

    if d < 1 or D < 1:
        return 1, []
    if D == 1:
        return 2, [(0, 1)]

    # Safe fallback: K_{d,d} has diameter 2.
    best_n, best_E = lib.haar_graph(d, range(d))

    def consider(n, E):
        nonlocal best_n, best_E
        if n > best_n and lib.is_valid(n, E, d, D):
            best_n, best_E = n, list(E)

    if D == 3 and d >= 2:
        res = _haar_cover(d, rng, start + 0.9 * budget)
        if res is not None:
            m, S = res
            n, E = lib.haar_graph(m, S)
            consider(n, E)

    if D >= 4 and time.monotonic() < deadline:
        gq = _best_gq(d)
        if gq is not None:
            consider(gq[0], gq[1])

    if not lib.is_valid(best_n, best_E, d, D):
        best_n, best_E = lib.haar_graph(d, range(d))
    return best_n, list(best_E)
