# ----------------------------------------------------------------------------
# Projective-plane base and its decoupled arc extensions (diameter 3).
#
# Earlier versions reused one set S as both the point set and the line set of
# the extension, so a single S had to satisfy two load limits at once. Here two
# independent sets are chosen:
#   S1 (points): every line holds <= s points of S1; each gets a new A-vertex
#                joined to the q+1 lines through it.
#   S2 (lines):  every point lies on <= s lines of S2; each gets a new B-vertex
#                joined to the q+1 points on it.
# The two constraints do not interact, so the search for each set is an
# independent max-load-set problem with the same local-search routine.
# Sides: A-vertices sit with the points (side 0), B-vertices with the lines
# (side 1), so the graph stays bipartite. Diameter 3 is checked by lib.is_valid.
# ----------------------------------------------------------------------------

def _best_pg(d):
    """Incidence graph of PG(2, q) for the largest prime power q with q + 1 <= d."""
    for q in range(d - 1, 1, -1):
        if lib.is_prime_power(q):
            return lib.projective_plane_incidence(q)
    return None


def _pg_data(q):
    """Return (m, edges, point_lines, line_points, index, pts) for PG(2, q)."""
    pts = lib.projective_points(q)
    n2, edges = lib.projective_plane_incidence(q)
    m = n2 // 2
    point_lines = [[] for _ in range(m)]
    line_points = [[] for _ in range(m)]
    for u, v in edges:
        point_lines[u].append(v - m)
        line_points[v - m].append(u)
    index = {p: i for i, p in enumerate(pts)}
    return m, edges, point_lines, line_points, index, pts


def _load_ok(X, s, incid, nother):
    """True if every y is hit by at most s elements of X, where incid[x] lists the y's of x."""
    load = [0] * nother
    for x in X:
        for y in incid[x]:
            load[y] += 1
    return max(load, default=0) <= s


def _conic_set(q, index, F):
    """Conic (plus nucleus for even q): an arc with no three collinear, as point indices."""
    S = [index[(1, t, F.mul(t, t))] for t in range(q)]
    S.append(index[(0, 0, 1)])
    if q % 2 == 0:
        S.append(index[(0, 1, 0)])
    return S


def _max_load_set(s, incid, nother, m, rng, deadline, init):
    """Iterated local search for a large X in range(m) with every y hit by <= s elements.

    incid[x] lists the y-indices that x loads. A random outside x is inserted if
    feasible. Otherwise the members that load a saturated y touching x are removed
    (all contributors to a saturated y are blockers, so removing them makes x
    feasible), and x is inserted when there are at most 2 such blockers; the
    2-blocker swap is taken only occasionally. Returns the largest feasible set seen.
    """
    load = [0] * nother
    inS = [False] * m
    S = []

    def add(x):
        inS[x] = True
        S.append(x)
        for y in incid[x]:
            load[y] += 1

    def remove(x):
        inS[x] = False
        S.remove(x)
        for y in incid[x]:
            load[y] -= 1

    def blockers(x):
        sat = {y for y in incid[x] if load[y] >= s}
        if not sat:
            return []
        return [r for r in S if any(y in sat for y in incid[r])]

    for x in init:
        if not inS[x] and all(load[y] < s for y in incid[x]):
            add(x)
    best = list(S)
    it = 0
    while True:
        it += 1
        if (it & 255) == 0 and time.monotonic() > deadline:
            break
        x = rng.randrange(m)
        if inS[x]:
            continue
        B = blockers(x)
        if not B:
            add(x)
        elif len(B) == 1 or (len(B) == 2 and rng.random() < 0.1):
            for r in B:
                remove(r)
            add(x)
        else:
            continue
        if len(S) > len(best):
            best = list(S)
    return best


def _arc_graph2(m, edges, point_lines, line_points, S1, S2):
    """PG incidence plus an A-vertex per point of S1 and a B-vertex per line of S2."""
    k1 = len(S1)
    n = 2 * m + k1 + len(S2)
    E = list(edges)
    for t, P in enumerate(S1):
        x = 2 * m + t
        for L in point_lines[P]:
            E.append((x, m + L))
    for t, L in enumerate(S2):
        b = 2 * m + k1 + t
        for Q in line_points[L]:
            E.append((Q, b))
    return n, E


def _arc_extensions2(d, deadline, rng, threshold):
    """Return (n, edges) candidates from decoupled arc extensions for prime powers q with q + 1 <= d.

    Each q with spare s = d - q - 1 >= 1 gets its time share split between S1 and S2.
    A q is skipped when the counting bound 2m + 2*s*m/(q+1) cannot beat `threshold`.
    """
    qs = []
    for q in range(2, min(d - 1, 23) + 1):
        if not lib.is_prime_power(q):
            continue
        s = d - q - 1
        if s < 1:
            continue
        m = q * q + q + 1
        kmax = s * m // (q + 1)
        if 2 * m + 2 * kmax <= threshold:
            continue
        qs.append((q, s))

    out = []
    for idx, (q, s) in enumerate(qs):
        now = time.monotonic()
        if now > deadline:
            break
        share = (deadline - now) / (len(qs) - idx)
        m, edges, point_lines, line_points, index, pts = _pg_data(q)
        init1, init2 = [], []
        if s >= 2:
            cs = _conic_set(q, index, lib.GF(q))
            if _load_ok(cs, s, point_lines, m):
                init1 = cs
            if _load_ok(cs, s, line_points, m):
                init2 = cs
        S1 = _max_load_set(s, point_lines, m, m, rng, now + 0.5 * share, init1)
        S2 = _max_load_set(s, line_points, m, m, rng, now + share, init2)
        if not S1 and not S2:
            continue
        if not (_load_ok(S1, s, point_lines, m) and _load_ok(S2, s, line_points, m)):
            continue
        out.append(_arc_graph2(m, edges, point_lines, line_points, S1, S2))
    return out


# ----------------------------------------------------------------------------
# Cover-based vertex extension (diameter-preserving growth).
# ----------------------------------------------------------------------------

def _balls_radius(n, adj, r):
    """Bitmask per vertex of all vertices within distance r."""
    ball = [1 << v for v in range(n)]
    for _ in range(r):
        new = []
        for v in range(n):
            x = ball[v]
            for u in adj[v]:
                x |= ball[u]
            new.append(x)
        ball = new
    return ball


def _bipartition(n, adj):
    """Two-colouring of a bipartite graph given by adjacency lists."""
    color = [-1] * n
    for s in range(n):
        if color[s] != -1:
            continue
        color[s] = 0
        stack = [s]
        while stack:
            u = stack.pop()
            for v in adj[u]:
                if color[v] == -1:
                    color[v] = 1 - color[u]
                    stack.append(v)
    return color


def _greedy_cover(cands, ball, full, d, rng, randomize):
    """Greedy set cover of `full` by at most d candidate vertices; None if it fails."""
    pool = list(cands)
    if randomize:
        rng.shuffle(pool)
    covered = 0
    chosen = []
    while covered != full and len(chosen) < d and pool:
        gains = [(ball[s] & ~covered).bit_count() for s in pool]
        best_g = max(gains, default=0)
        if best_g == 0:
            break
        thr = best_g
        if randomize and rng.random() < 0.5:
            thr = best_g - 1
        opts = [i for i, g in enumerate(gains) if g >= thr and g > 0]
        i = rng.choice(opts) if randomize else opts[0]
        s = pool.pop(i)
        chosen.append(s)
        covered |= ball[s]
    return chosen if covered == full else None


def _extend_cover(n, edges, d, D, deadline, rng):
    """Greedily add vertices whose neighbourhoods cover all vertices within D-1 of the graph."""
    if D < 2:
        return n, edges
    edges = list(edges)
    adj = [[] for _ in range(n)]
    for u, v in edges:
        adj[u].append(v)
        adj[v].append(u)
    deg = [len(a) for a in adj]
    color = _bipartition(n, adj)

    while time.monotonic() < deadline:
        ball = _balls_radius(n, adj, D - 1)
        full = (1 << n) - 1
        added = False
        for c in (0, 1):
            cands = [s for s in range(n) if color[s] == c and deg[s] < d]
            if not cands:
                continue
            chosen = None
            for attempt in range(200):
                if time.monotonic() >= deadline:
                    break
                chosen = _greedy_cover(cands, ball, full, d, rng, attempt > 0)
                if chosen:
                    break
            if chosen:
                v = n
                n += 1
                color.append(1 - c)
                adj.append([])
                deg.append(0)
                for s in chosen:
                    edges.append((s, v))
                    adj[s].append(v)
                    adj[v].append(s)
                    deg[s] += 1
                    deg[v] += 1
                added = True
                break
        if not added:
            break
    return n, edges


def _saturate_edges(n, edges, d, rng):
    """Greedily join deficient opposite-side vertices in random order."""
    edges = list(edges)
    adj = [[] for _ in range(n)]
    existing = set()
    for u, v in edges:
        adj[u].append(v)
        adj[v].append(u)
        existing.add((min(u, v), max(u, v)))
    deg = [len(a) for a in adj]
    color = _bipartition(n, adj)
    left = [v for v in range(n) if color[v] == 0 and deg[v] < d]
    right = [v for v in range(n) if color[v] == 1 and deg[v] < d]
    pairs = [(a, b) for a in left for b in right
             if (min(a, b), max(a, b)) not in existing]
    rng.shuffle(pairs)
    for a, b in pairs:
        if deg[a] < d and deg[b] < d:
            edges.append((a, b))
            deg[a] += 1
            deg[b] += 1
    return edges


def _grow(n, edges, d, D, deadline, rng):
    """Extend by cover vertices first, then saturate edges with the leftover spare degree."""
    cur_n, cur_e = n, list(edges)
    for _ in range(8):
        if time.monotonic() >= deadline:
            break
        n2, e2 = _extend_cover(cur_n, cur_e, d, D, deadline, rng)
        grew = n2 != cur_n
        cur_n = n2
        cur_e = _saturate_edges(cur_n, e2, d, rng)
        if not grew:
            break
    return cur_n, cur_e


