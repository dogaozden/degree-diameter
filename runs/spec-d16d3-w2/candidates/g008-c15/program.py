# build
# ----------------------------------------------------------------------------

def build(d, D, seed, time_limit):
    start = time.monotonic()
    deadline = start + 0.82 * time_limit
    rng = random.Random(seed)

    if d < 1 or D < 1:
        return 1, []
    if D == 1:
        return 2, [(0, 1)]

    # Fallback: K_{d,d} has diameter 2, valid for D >= 2.
    best = lib.haar_graph(d, range(d))
    best_n = best[0]
    moore = lib.moore_bound(d, D)

    def consider(n, e):
        nonlocal best, best_n
        if n > best_n and lib.is_valid(n, e, d, D):
            best = (n, e)
            best_n = n

    if D >= 3:
        pg = _best_pg(d)
        if pg is not None:
            consider(pg[0], pg[1])
            n2, e2 = _grow(pg[0], pg[1], d, D, time.monotonic() + 0.03 * time_limit, rng)
            consider(n2, e2)

    arcs = []
    if D >= 3 and best_n < moore:
        arcs = _arc_extensions(d, start + 0.3 * time_limit,
                               random.Random(seed * 7919 + d), best_n)
        arcs.sort(key=lambda t: -t[0])
        for n_c, e_c, m, pl, lp in arcs[:3]:
            consider(n_c, e_c)
            n2, e2 = _grow(n_c, e_c, d, D, time.monotonic() + 0.02 * time_limit, rng)
            consider(n2, e2)

    if D == 3 and arcs and best_n < moore:
        n_c, e_c, m, pl, lp = arcs[0]
        if lib.is_valid(n_c, e_c, d, D):
            E = _local_search(e_c, n_c, m, pl, lp, d, D,
                              start + 0.72 * time_limit, random.Random(seed * 31 + 7))
            if E:
                n, EE = lib.relabel(E)
                consider(n, EE)
                n2, e2 = _grow(n, EE, d, D, start + 0.78 * time_limit, rng)
                consider(n2, e2)

    if D >= 4 and best_n < moore and time.monotonic() < deadline:
        gq = _best_gq(d)
        if gq is not None:
            consider(gq[0], gq[1])
            n2, e2 = _grow(gq[0], gq[1], d, D, start + 0.4 * time_limit, rng)
            consider(n2, e2)

    # Annealed voltage lifts for leftover time (any D), skipped once the Moore bound is met.
    if not (D == 3 and arcs):
        ks = [1, 2, 2, 3, 4] if D >= 5 else [1, 1, 2, 3]
        while time.monotonic() < deadline and best_n < moore:
            k = rng.choice(ks)
            base = best_n // (2 * k)
            G = max(2, base + 1 + rng.randrange(0, max(3, base // 8 + 1)))
            g = _sample_group(G, rng)
            if g is None:
                continue
            order, mul = g
            res = _anneal(d, D, k, order, mul, rng, deadline, iters=400)
            if res is not None:
                consider(res[0], res[1])

    if not lib.is_valid(best[0], best[1], d, D):
        best = lib.haar_graph(d, range(d))
    return best
