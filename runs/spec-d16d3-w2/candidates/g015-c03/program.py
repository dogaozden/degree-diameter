def _moore(d, D):
    """Upper bound on the order of a bipartite graph with max degree d and diameter D."""
    if D == 0 or d == 0:
        return 1
    if d == 1:
        return min(2, D + 1)
    if d == 2:
        return 2 * D
    return 2 * sum((d - 1) ** i for i in range(D))


def _pg_incidence(q):
    """Return (m, edges, point_lines, line_points) for PG(2, q); points 0..m-1, lines indexed 0..m-1."""
    n2, edges = lib.projective_plane_incidence(q)
    m = n2 // 2
    point_lines = [[] for _ in range(m)]
    line_points = [[] for _ in range(m)]
    for u, v in edges:
        point_lines[u].append(v - m)
        line_points[v - m].append(u)
    return m, edges, point_lines, line_points


def _loads_ok(S, s, m, point_lines, line_points):
    """True if every line holds <= s points of S and every point lies on <= s lines indexed by S."""
    cl = [0] * m
    cp = [0] * m
    for P in S:
        for L in point_lines[P]:
            cl[L] += 1
        for Q in line_points[P]:
            cp[Q] += 1
    return max(cl, default=0) <= s and max(cp, default=0) <= s


def _greedy_arc(m, s, point_lines, line_points, rng, trials, deadline):
    """Randomized greedy set S with all loads <= s; returns the largest found."""
    best = []
    order = list(range(m))
    for _ in range(trials):
        if time.monotonic() > deadline:
            break
        rng.shuffle(order)
        cl = [0] * m
        cp = [0] * m
        S = []
        for P in order:
            if all(cl[L] < s for L in point_lines[P]) and all(cp[Q] < s for Q in line_points[P]):
                S.append(P)
                for L in point_lines[P]:
                    cl[L] += 1
                for Q in line_points[P]:
                    cp[Q] += 1
        if len(S) > len(best):
            best = S
    return best


def _conic_set(q, index):
    """Conic (plus nucleus for even q): an arc with no three collinear."""
    F = lib.GF(q)
    S = [index[(1, t, F.mul(t, t))] for t in range(q)]
    S.append(index[(0, 0, 1)])
    if q % 2 == 0:
        S.append(index[(0, 1, 0)])
    return S


def _arc_graph(m, edges, point_lines, line_points, S):
    """Incidence graph of PG(2,q) plus, per element of S, an A-vertex (on lines through it)
    and a B-vertex (joined to points of the line). Returns (n, edges, side)."""
    k = len(S)
    n = 2 * m + 2 * k
    E = list(edges)
    for t, P in enumerate(S):
        a = 2 * m + t
        for L in point_lines[P]:
            E.append((a, m + L))
    for t, j in enumerate(S):
        b = 2 * m + k + t
        for Q in line_points[j]:
            E.append((Q, b))
    side = [0] * m + [1] * m + [0] * k + [1] * k
    return n, E, side


def _arc_candidates(d, deadline, rng):
    """For each prime power q with q + 1 <= d, build the best arc-extended PG(2,q) graph."""
    out = []
    for q in range(2, min(d - 1, 23) + 1):
        if not lib.is_prime_power(q):
            continue
        if time.monotonic() > deadline:
            break
        s = d - q - 1
        m, edges, point_lines, line_points = _pg_incidence(q)
        pts = lib.projective_points(q)
        index = {p: i for i, p in enumerate(pts)}
        cands = [[]]
        if s >= 1:
            cands.append(_greedy_arc(m, s, point_lines, line_points, rng, 60, deadline))
        if s >= 2:
            cs = _conic_set(q, index)
            if _loads_ok(cs, s, m, point_lines, line_points):
                cands.append(cs)
        S = max(cands, key=len)
        if not _loads_ok(S, s, m, point_lines, line_points):
            continue
        out.append(_arc_graph(m, edges, point_lines, line_points, S))
    return out


# ----------------------------------------------------------------------------
# Bipartite repair annealing.
#
# Start from a valid arc-extended graph, append two new vertices (one on each
# side), and anneal over bipartite edge sets to drive the number of pairs at
# distance > 3 to zero.
#
# Change in this version: moves are GUIDED by a randomly chosen bad pair (u, w).
#   * opposite sides: add edge u-w if both have spare degree, otherwise a
#     2-opt swap that inserts u-w directly while keeping all degrees fixed;
#   * same side: attach one endpoint to a neighbour of the other, so they
#     gain a common neighbour (distance 2).
# Unguided random moves are used as a fallback. Edges only join the two sides,
# so the graph stays bipartite throughout.
# ----------------------------------------------------------------------------

def _to_adj(n, edges):
    adj = [set() for _ in range(n)]
    for u, v in edges:
        adj[u].add(v)
        adj[v].add(u)
    return adj


def _reach(n, adj, D):
    """Bitmask per vertex of all vertices within distance D."""
    reach = [1 << v for v in range(n)]
    for _ in range(D):
        nxt = []
        for v in range(n):
            r = reach[v]
            for u in adj[v]:
                r |= reach[u]
            nxt.append(r)
        reach = nxt
    return reach


def _cost(n, reach):
    """Unordered pairs at distance > D, given the reach masks."""
    return sum(n - r.bit_count() for r in reach) // 2


def _pick_bad(n, reach, rng):
    """Return a random bad pair (u, w) with dist(u, w) > D, or None."""
    bad = [v for v in range(n) if reach[v].bit_count() < n]
    if not bad:
        return None
    u = rng.choice(bad)
    missing = [w for w in range(n) if not (reach[u] >> w) & 1]
    return u, rng.choice(missing)


def _apply(adj, ops):
    for op, x, y in ops:
        if op == 'a':
            adj[x].add(y)
            adj[y].add(x)
        else:
            adj[x].discard(y)
            adj[y].discard(x)


def _propose(adj, side0, side1, d, rng):
    """Unguided random move: list of ops ('a' add / 'd' delete) keeping max degree <= d, or None."""
    r = rng.random()
    if r < 0.6:
        x1 = rng.choice(side0)
        x2 = rng.choice(side0)
        if x1 == x2 or not adj[x1] or not adj[x2]:
            return None
        y1 = rng.choice(list(adj[x1]))
        y2 = rng.choice(list(adj[x2]))
        if y1 == y2 or y2 in adj[x1] or y1 in adj[x2]:
            return None
        return [('d', x1, y1), ('d', x2, y2), ('a', x1, y2), ('a', x2, y1)]
    if r < 0.8:
        x = rng.choice(side0)
        y = rng.choice(side1)
        if y in adj[x] or len(adj[x]) >= d or len(adj[y]) >= d:
            return None
        return [('a', x, y)]
    x1 = rng.choice(side0)
    if not adj[x1]:
        return None
    y1 = rng.choice(list(adj[x1]))
    if rng.random() < 0.5:
        y2 = rng.choice(side1)
        if y2 == y1 or y2 in adj[x1] or len(adj[y2]) >= d:
            return None
        return [('d', x1, y1), ('a', x1, y2)]
    x2 = rng.choice(side0)
    if x2 == x1 or y1 in adj[x2] or len(adj[x2]) >= d:
        return None
    return [('d', x1, y1), ('a', x2, y1)]


def _guided(adj, u, w, side, d, rng):
    """Move aimed at making the bad pair (u, w) close. Returns ops or None."""
    if side[u] != side[w]:
        x, y = (u, w) if side[u] == 0 else (w, u)
        if len(adj[x]) < d and len(adj[y]) < d:
            return [('a', x, y)]
        if not adj[x] or not adj[y]:
            return None
        # 2-opt: remove x-y0 and x0-y, add x-y and x0-y0; all degrees unchanged.
        y0 = rng.choice(list(adj[x]))
        x0 = rng.choice(list(adj[y]))
        if y0 == y or x0 == x or y0 in adj[x0]:
            return None
        return [('d', x, y0), ('d', x0, y), ('a', x, y), ('a', x0, y0)]
    # Same side: give u and w a common neighbour y.
    if not adj[u] and not adj[w]:
        return None
    if adj[u] and (not adj[w] or rng.random() < 0.5):
        a, b = u, w
    else:
        a, b = w, u
    y = rng.choice(list(adj[a]))
    if y in adj[b] or len(adj[y]) >= d:
        return None
    if len(adj[b]) < d:
        return [('a', b, y)]
    z = rng.choice(list(adj[b]))
    return [('d', b, z), ('a', b, y)]


def _repair(n, adj, side, d, D, rng, deadline):
    """Anneal until no pair is at distance > D. Returns True on success (adj updated in place)."""
    side0 = [v for v in range(n) if side[v] == 0]
    side1 = [v for v in range(n) if side[v] == 1]
    reach = _reach(n, adj, D)
    cost = _cost(n, reach)
    T = 1.0
    while cost > 0:
        if time.monotonic() > deadline:
            return False
        T = max(0.05, T * 0.9995)
        pair = _pick_bad(n, reach, rng)
        ops = None
        if pair is not None and rng.random() < 0.8:
            ops = _guided(adj, pair[0], pair[1], side, d, rng)
        if ops is None:
            ops = _propose(adj, side0, side1, d, rng)
        if ops is None:
            continue
        _apply(adj, ops)
        new_reach = _reach(n, adj, D)
        c2 = _cost(n, new_reach)
        if c2 <= cost or rng.random() < math.exp(-(c2 - cost) / T):
            cost = c2
            reach = new_reach
        else:
            undo = [('d' if op == 'a' else 'a', x, y) for op, x, y in reversed(ops)]
            _apply(adj, undo)
    return True


