def build(d, D, seed, time_limit):
    t0 = time.monotonic()
    budget = max(1.0, min(0.85 * time_limit, time_limit - 8.0))
    deadline = t0 + budget
    mis_deadline = t0 + 0.5 * budget
    rng = random.Random(seed)
    nprng = np.random.default_rng(abs(int(seed)) % (2 ** 32))

    if d < 1 or D < 1:
        return 1, []
    if D == 1:
        return 2, [(0, 1)]

    # Safe fallback: K_{d,d}, valid for D >= 2.
    best = lib.haar_graph(d, range(d))

    def consider(n, edges):
        nonlocal best
        if n > best[0] and lib.is_valid(n, edges, d, D):
            best = (n, edges)

    if D == 2:
        return best

    # Projective plane incidence graph: degree d, diameter 3.
    if D >= 3 and lib.is_prime_power(d - 1):
        try:
            consider(*lib.projective_plane_incidence(d - 1))
        except Exception:
            pass

    # Generalized quadrangle W(d-1): degree d, diameter 4.
    if D >= 4 and lib.is_prime_power(d - 1) and 2 <= d - 1 <= 11:
        try:
            consider(*_gq_incidence(d - 1))
        except Exception:
            pass

    # Twin blow-up of a degree-(d-1) base: W(d-2) for D >= 4, PG(2, d-2) for D = 3.
    q = d - 2
    if D >= 3 and 2 <= q <= 11 and lib.is_prime_power(q):
        try:
            if D >= 4:
                n0, e0 = _gq_incidence(q)
            else:
                n0, e0 = lib.projective_plane_incidence(q)
            res = _blowup(n0, e0, d, mis_deadline, rng, nprng)
            if res is not None:
                consider(res[0], res[1])
        except Exception:
            pass

    # Spend the remaining budget extending the best graph with spare degree.
    if D >= 3:
        try:
            n2, e2 = _extend(best[0], list(best[1]), d, D - 1, deadline, rng)
            consider(n2, e2)
        except Exception:
            pass

    if not lib.is_valid(best[0], best[1], d, D):
        return lib.haar_graph(d, range(d))
    return best
