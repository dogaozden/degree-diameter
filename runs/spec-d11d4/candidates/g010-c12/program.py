def build(d, D, seed, time_limit):
    t0 = time.monotonic()
    budget = max(1.0, min(0.8 * time_limit, time_limit - 10.0))
    rng = random.Random(seed)
    nprng = np.random.default_rng(abs(int(seed)) % (2 ** 32))

    if d < 1 or D < 1:
        return 1, []
    if D == 1:
        return 2, [(0, 1)]

    best = lib.haar_graph(d, range(d))

    def consider(n, e):
        nonlocal best
        if n > best[0] and lib.is_valid(n, e, d, D):
            best = (n, e)

    if D == 2:
        return best

    # D = 3 (or any D): projective plane incidence, degree d.
    if D >= 3:
        try:
            pg = _pg(d)
            if pg is not None:
                consider(pg[0], pg[1])
        except Exception:
            pass

    q = d - 2
    if D >= 4 and 2 <= q <= 11 and lib.is_prime_power(q):
        # Route A: twin blow-up of W(q) (degree q+1 = d-1), then greedy extension.
        try:
            n0, e0 = _gq(q)
            consider(n0, e0)
            res = _blowup(n0, e0, d, t0 + 0.35 * budget, rng, nprng)
            if res is not None:
                consider(res[0], res[1])
                n1, e1 = _extend(res[0], res[1], d, t0 + 0.6 * budget, rng)
                consider(n1, e1)
        except Exception:
            pass

        # Route B: twin graph on W(q) (degree q+2 = d), then greedy extension.
        try:
            n2, e2 = _twin_graph(q, t0 + 0.7 * budget, rng, nprng)
            consider(n2, e2)
            n3, e3 = _extend(n2, e2, d, t0 + budget, rng)
            consider(n3, e3)
        except Exception:
            pass

    if not lib.is_valid(best[0], best[1], d, D):
        return lib.haar_graph(d, range(d))
    return best
