def build(d, D, seed, time_limit):
    start = time.monotonic()
    blow_deadline = start + max(0.5, 0.55 * time_limit - 2.0)
    grow_deadline = start + max(0.8, 0.8 * time_limit - 4.0)
    rng = random.Random(seed)
    nprng = np.random.default_rng(abs(int(seed)) % (2 ** 32))

    if d < 1 or D < 1:
        return 1, []
    if D == 1:
        return 2, [(0, 1)]

    # Safe fallback: K_{d,d} has diameter 2.
    best = lib.haar_graph(d, range(d))
    best_n = best[0]

    def consider(n, e):
        nonlocal best, best_n
        if n > best_n and lib.is_valid(n, e, d, D):
            best = (n, e)
            best_n = n

    if D == 2:
        return best

    pg = _pg(d)
    if pg is not None:
        consider(pg[0], pg[1])

    # Blow-up route: base of degree exactly d-1 with q = d-2 a prime power.
    q = d - 2
    if 2 <= q <= 11 and lib.is_prime_power(q) and time.monotonic() < blow_deadline - 2.0:
        if D >= 4:
            n0, e0 = _gq(q)
        elif D == 3:
            n0, e0 = lib.projective_plane_incidence(q)
        else:
            n0, e0 = 0, []
        if n0 > 0:
            consider(n0, e0)
            try:
                res = _blowup(n0, e0, d, blow_deadline, rng, nprng)
            except Exception:
                res = None
            if res is not None:
                consider(res[0], res[1])

    # New stage: grow the best valid graph by ball-cover augmentation.
    if time.monotonic() < grow_deadline:
        try:
            n1, e1 = _grow(best[0], best[1], d, D, grow_deadline, rng)
            consider(n1, e1)
        except Exception:
            pass

    if not lib.is_valid(best[0], best[1], d, D):
        best = lib.haar_graph(d, range(d))
    return best
