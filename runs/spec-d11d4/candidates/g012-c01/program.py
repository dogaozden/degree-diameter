# Twin blow-up with a distance-2-free vertex set, searched side by side.
# ----------------------------------------------------------------------------

def _independent_set(N, nb, rng, nprng, deadline):
    """Iterated local search for a large set of vertices with no conflicting pair."""
    nbn = [np.asarray(x, dtype=np.int64) for x in nb]
    cnt = np.zeros(N, dtype=np.int64)     # number of chosen conflict-neighbours
    inS = np.zeros(N, dtype=bool)
    tabu = np.zeros(N, dtype=np.int64)
    S = []
    conf = 0
    best = []
    best_size = 0
    it = 0
    last_best_it = 0

    def add(v):
        nonlocal conf
        conf += int(cnt[v])
        cnt[nbn[v]] += 1
        inS[v] = True
        S.append(v)

    def remove(u):
        nonlocal conf
        conf -= int(cnt[u])
        cnt[nbn[u]] -= 1
        inS[u] = False
        S.remove(u)

    def pick():
        score = cnt + nprng.random(N)     # random tie-breaking
        score[inS] = np.inf
        score[tabu > it] = np.inf
        return int(np.argmin(score))

    if N == 0:
        return []

    while True:
        it += 1
        if (it & 63) == 0 and time.monotonic() >= deadline:
            break
        if conf == 0:
            if len(S) > best_size:
                best = list(S)
                best_size = len(S)
                last_best_it = it
            add(pick())
        else:
            conflicting = [u for u in S if cnt[u] > 0]
            u = conflicting[rng.randrange(len(conflicting))]
            remove(u)
            tabu[u] = it + 5 + rng.randrange(8)
            add(pick())
        if S and it - last_best_it > 15000:
            u = S[rng.randrange(len(S))]
            remove(u)
            tabu[u] = it + 5
            last_best_it = it
    if conf == 0 and len(S) > best_size:
        best = list(S)
    return best


def _side_search(V, cs, rng, nprng, deadline):
    """Large conflict-free subset of one side V, using local conflict lists cs."""
    idx = {v: i for i, v in enumerate(V)}
    nb_local = [[idx[w] for w in cs[v] if w in idx] for v in V]
    res = _independent_set(len(V), nb_local, rng, nprng, deadline)
    return [V[i] for i in res]


def _two_colour(n, edges):
    """Return a 0/1 colouring of a bipartite graph (vertices in each component start at 0)."""
    adj = [[] for _ in range(n)]
    for u, v in edges:
        adj[u].append(v)
        adj[v].append(u)
    color = [-1] * n
    for s in range(n):
        if color[s] != -1:
            continue
        color[s] = 0
        stack = [s]
        while stack:
            x = stack.pop()
            for y in adj[x]:
                if color[y] == -1:
                    color[y] = 1 - color[x]
                    stack.append(y)
    return color


def _blow(n0, edges0, S):
    """Blow up each vertex of S into two twin copies (same neighbourhood)."""
    extra = {}
    for v in S:
        extra[v] = n0 + len(extra)
    copies = [[v] + ([extra[v]] if v in extra else []) for v in range(n0)]
    edges = []
    for u, v in edges0:
        for a in copies[u]:
            for b in copies[v]:
                edges.append((a, b))
    return n0 + len(extra), edges


def _blowup(n0, edges0, d, deadline, rng, nprng):
    """Twin blow-up of a base graph of degree d-1, searching each side separately."""
    adj = [[] for _ in range(n0)]
    for u, v in edges0:
        adj[u].append(v)
        adj[v].append(u)
    if any(len(a) != d - 1 for a in adj):
        return None
    cs = [set() for _ in range(n0)]
    for w in range(n0):
        a = adj[w]
        for i in range(len(a)):
            for j in range(i + 1, len(a)):
                x, y = a[i], a[j]
                cs[x].add(y)
                cs[y].add(x)
    if n0 <= 60:
        deadline = min(deadline, time.monotonic() + 2.0)
    color = _two_colour(n0, edges0)
    sides = [[v for v in range(n0) if color[v] == c] for c in (0, 1)]

    now = time.monotonic()
    total = max(0.0, deadline - now)
    S = []
    S += _side_search(sides[0], cs, rng, nprng, now + 0.5 * total)
    S += _side_search(sides[1], cs, rng, nprng, deadline)
    return _blow(n0, edges0, S)


# ----------------------------------------------------------------------------
# NEW: ball-cover vertex augmentation.
#
# Adding a vertex w never increases any existing distance, so an existing
# valid graph stays valid once w is attached, provided w itself reaches every
# vertex within D steps. Attaching w to a set T of opposite-side vertices with
# spare degree gives dist(w, x) <= D iff some t in T has dist(t, x) <= D-1.
#
# So each attempt is a max-coverage problem over radius-(D-1) balls, solved
# greedily with random tie-breaking. Balls are kept as bitmasks; they may be
# stale (they only under-estimate true balls, so a cover found with them is
# still a real cover). New vertices are not in the stale masks, so each
# candidate is confirmed with one exact BFS from w before it is committed.
# ----------------------------------------------------------------------------

def _balls_mask(adj, R):
    """Bitmask per vertex of all vertices within distance R."""
    n = len(adj)
    reach = [1 << v for v in range(n)]
    for _ in range(R):
        new = []
        for v in range(n):
            r = reach[v]
            for u in adj[v]:
                r |= reach[u]
            new.append(r)
        reach = new
    return reach


def _reach_all(adj, src, D):
    """True if a BFS from src within D steps reaches every vertex."""
    n = len(adj)
    seen = bytearray(n)
    seen[src] = 1
    frontier = [src]
    cnt = 1
    for _ in range(D):
        nxt = []
        for u in frontier:
            for v in adj[u]:
                if not seen[v]:
                    seen[v] = 1
                    nxt.append(v)
        cnt += len(nxt)
        frontier = nxt
        if not frontier:
            break
    return cnt == n


def _grow(n0, edges0, d, D, deadline, rng):
    """Greedily attach new vertices, each to a ball-covering set of spare-degree vertices."""
    if D < 2 or n0 == 0:
        return n0, edges0
    adj = [[] for _ in range(n0)]
    for u, v in edges0:
        adj[u].append(v)
        adj[v].append(u)
    color = _two_colour(n0, edges0)
    state = {"balls": None, "stale_n": 0}

    def refresh():
        state["balls"] = _balls_mask(adj, D - 1)
        state["stale_n"] = len(adj)

    refresh()
    since = 0
    fails = 0
    while time.monotonic() < deadline and fails < 20000:
        if since >= 8:
            refresh()
            since = 0
        balls = state["balls"]
        stale_n = state["stale_n"]
        full = (1 << stale_n) - 1
        c = rng.randrange(2)
        opp = 1 - c
        pool = [t for t in range(stale_n)
                if color[t] == opp and len(adj[t]) < d and balls[t]]
        rng.shuffle(pool)
        covered = 0
        T = []
        while covered != full and len(T) < d and pool:
            bi = -1
            bg = 0
            for i, t in enumerate(pool):
                g = (balls[t] & ~covered).bit_count()
                if g > bg:
                    bg = g
                    bi = i
            if bi < 0:
                break
            t = pool.pop(bi)
            T.append(t)
            covered |= balls[t]
        if covered != full or not T:
            fails += 1
            continue
        w = len(adj)
        adj.append(list(T))
        for t in T:
            adj[t].append(w)
        if _reach_all(adj, w, D):
            color.append(c)
            since += 1
            fails = 0
        else:
            adj.pop()
            for t in T:
                adj[t].pop()
            fails += 1

    n = len(adj)
    edges = [(u, v) for u in range(n) for v in adj[u] if u < v]
    return n, edges


