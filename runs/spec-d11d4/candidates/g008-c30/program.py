def _pg(d):
    """Incidence graph of PG(2, q) for the largest prime power q <= d - 1, or None."""
    for q in range(d - 1, 1, -1):
        if lib.is_prime_power(q):
            return lib.projective_plane_incidence(q)
    return None


def _gq_struct(q):
    """Build the symplectic generalized quadrangle W(q) as point-line incidence data.

    Returns (F, pts, index, norm, M, P, lines): points are indexed 0..P-1 and
    lines are given as sorted lists of point indices.
    """
    F = lib.GF(q)
    A = F.add_table.tolist()
    M = F.mul_table.tolist()
    NEG = [F.neg(a) for a in range(q)]
    INV = [0] + [F.inv(a) for a in range(1, q)]
    pts = [v for v in itertools.product(range(q), repeat=4)
           if any(v) and next(c for c in v if c) == 1]
    P = len(pts)
    index = {v: i for i, v in enumerate(pts)}

    def norm(v):
        c = next(x for x in v if x)
        ic = INV[c]
        return tuple(M[ic][x] for x in v)

    covered = [bytearray(P) for _ in range(P)]
    lines = []
    for i in range(P):
        x = pts[i]
        ci = covered[i]
        for j in range(i + 1, P):
            if ci[j]:
                continue
            y = pts[j]
            # Symplectic form x0*y1 - x1*y0 + x2*y3 - x3*y2.
            t = A[M[x[0]][y[1]]][NEG[M[x[1]][y[0]]]]
            s = A[M[x[2]][y[3]]][NEG[M[x[3]][y[2]]]]
            if A[t][s] != 0:
                continue
            L = set()
            for a in range(q):
                ax = [M[a][x[k]] for k in range(4)]
                for b in range(q):
                    if a == 0 and b == 0:
                        continue
                    v = tuple(A[ax[k]][M[b][y[k]]] for k in range(4))
                    if any(v):
                        L.add(index[norm(v)])
            L = sorted(L)
            lines.append(L)
            for p in L:
                cp = covered[p]
                for r in L:
                    cp[r] = 1
    return F, pts, index, norm, M, P, lines


def _gq_context(q):
    """Context dict for W(q): vertices 0..P-1 are points, P..N-1 are lines."""
    F, pts, index, norm, M, P, lines = _gq_struct(q)
    line_map = {frozenset(L): j for j, L in enumerate(lines)}
    edges = [(p, P + j) for j, L in enumerate(lines) for p in L]
    return {"q": q, "F": F, "pts": pts, "index": index, "norm": norm, "M": M,
            "P": P, "N": P + len(lines), "lines": lines, "line_map": line_map,
            "edges": edges}


def _gq(q):
    ctx = _gq_context(q)
    return ctx["N"], ctx["edges"]


# ----------------------------------------------------------------------------
# NEW: torus symmetry of W(q).
#
# diag(a, a^-1, b, b^-1) preserves the symplectic form, so it is an automorphism
# of W(q). It permutes the points and the lines. A blow-up set can be chosen as
# a union of orbits of a subgroup of this torus, which shrinks the search space.
# Orbits that are internally conflicting are discarded. The orbit-level problem
# is a weighted independent set, solved by tabu local search.
# ----------------------------------------------------------------------------

def _torus_perm(ctx, a, b):
    """Permutation of all vertices induced by diag(a, a^-1, b, b^-1), or None."""
    F = ctx["F"]
    M = ctx["M"]
    norm = ctx["norm"]
    pts = ctx["pts"]
    index = ctx["index"]
    P = ctx["P"]
    ai = F.inv(a)
    bi = F.inv(b)
    pp = [index[norm((M[a][x[0]], M[ai][x[1]], M[b][x[2]], M[bi][x[3]]))]
          for x in pts]
    lm = ctx["line_map"]
    lp = []
    for L in ctx["lines"]:
        j = lm.get(frozenset(pp[p] for p in L))
        if j is None:
            return None
        lp.append(P + j)
    return pp + lp


def _side_orbits(side, perms):
    """Orbits of the group generated by perms, restricted to one side."""
    seen = set()
    orbits = []
    for v in side:
        if v in seen:
            continue
        seen.add(v)
        orb = [v]
        stack = [v]
        while stack:
            x = stack.pop()
            for pm in perms:
                y = pm[x]
                if y not in seen:
                    seen.add(y)
                    orb.append(y)
                    stack.append(y)
        orbits.append(orb)
    return orbits


def _orbit_search(w, adj, rng, nprng, deadline):
    """Weighted tabu local search for a heavy independent set of orbits.

    w[k] is the weight of orbit k and adj[k] lists its conflicting orbits.
    Returns a list of chosen orbit indices (the best found).
    """
    K = len(w)
    if K == 0:
        return []
    warr = np.asarray(w, dtype=np.float64)
    inS = np.zeros(K, dtype=bool)
    cnt = np.zeros(K, dtype=np.int64)
    cw = np.zeros(K, dtype=np.float64)
    tabu = np.zeros(K, dtype=np.int64)
    S = set()

    def add(k):
        inS[k] = True
        S.add(k)
        wk = w[k]
        for j in adj[k]:
            cnt[j] += 1
            cw[j] += wk

    def rem(k):
        inS[k] = False
        S.discard(k)
        wk = w[k]
        for j in adj[k]:
            cnt[j] -= 1
            cw[j] -= wk

    total = 0.0
    best = []
    best_w = 0.0
    last_imp = 0
    it = 0
    while True:
        it += 1
        if len(S) == K:
            break
        if (it & 15) == 0 and time.monotonic() >= deadline:
            break
        if S and it - last_imp > 4000:
            # Kick: drop a random quarter of the current solution.
            drop = rng.sample(sorted(S), max(1, len(S) // 4))
            for j in drop:
                rem(j)
                total -= w[j]
                tabu[j] = it + 4 + rng.randrange(8)
            last_imp = it
        free = (~inS) & (cnt == 0) & (tabu <= it)
        if free.any():
            idx = np.flatnonzero(free)
            k = int(idx[int(np.argmax(warr[idx] + nprng.random(len(idx)) * 0.5))])
            add(k)
            total += w[k]
        else:
            ok = (~inS) & (tabu <= it)
            if not ok.any():
                tabu[:] = 0
                continue
            idx = np.flatnonzero(ok)
            sc = warr[idx] - cw[idx] + nprng.random(len(idx)) * 2.0
            k = int(idx[int(np.argmax(sc))])
            for j in adj[k]:
                if inS[j]:
                    rem(j)
                    total -= w[j]
                    tabu[j] = it + 3 + rng.randrange(6)
            add(k)
            total += w[k]
        if total > best_w + 1e-9:
            best_w = total
            best = sorted(S)
            last_imp = it
    return best


def _solve_side(side, conf, trials, rng, nprng, deadline):
    """Best conflict-free subset of one side, over several symmetry groups.

    trials is a list of permutation lists; an empty list means the trivial group.
    Each trial gets an equal slice of the remaining time.
    """
    best = []
    span = deadline - time.monotonic()
    if span <= 0:
        return best
    slot = span / len(trials)
    for perms in trials:
        now = time.monotonic()
        if now >= deadline:
            break
        end = min(deadline, now + slot)
        orbs = _side_orbits(side, perms)
        adm = []
        for orb in orbs:
            s = set(orb)
            if all(not (conf[u] & s) for u in orb):
                adm.append(orb)
        oid = {}
        for k, orb in enumerate(adm):
            for u in orb:
                oid[u] = k
        adj = []
        for k, orb in enumerate(adm):
            nb = set()
            for u in orb:
                for x in conf[u]:
                    j = oid.get(x)
                    if j is not None and j != k:
                        nb.add(j)
            adj.append(sorted(nb))
        w = [len(o) for o in adm]
        chosen = _orbit_search(w, adj, rng, nprng, end)
        res = [u for k in chosen for u in adm[k]]
        if len(res) > len(best):
            best = res
    return best


def _blowup_gq(ctx, deadline, rng, nprng):
    """Twin blow-up of W(q) (degree q+1 = d-1), with symmetry-orbit search per side."""
    N, P, q = ctx["N"], ctx["P"], ctx["q"]
    edges = ctx["edges"]
    nbrs = [[] for _ in range(N)]
    for u, v in edges:
        nbrs[u].append(v)
        nbrs[v].append(u)
    # Same-side conflicts: two vertices sharing a neighbour may not both be blown up.
    conf = [set() for _ in range(N)]
    for x in range(N):
        nb = nbrs[x]
        for i in range(len(nb)):
            for j in range(i + 1, len(nb)):
                conf[nb[i]].add(nb[j])
                conf[nb[j]].add(nb[i])

    F = ctx["F"]
    g0 = F.primitive_element()
    trials = [[]]  # trivial group first
    attempts = 0
    while len(trials) < 7 and attempts < 300:
        attempts += 1
        perms = []
        for _ in range(rng.choice((1, 2))):
            i = rng.randrange(q - 1)
            j = rng.randrange(q - 1)
            if i == 0 and j == 0:
                continue
            pm = _torus_perm(ctx, F.pow(g0, i), F.pow(g0, j))
            if pm is not None:
                perms.append(pm)
        if perms:
            trials.append(perms)

    now = time.monotonic()
    mid = now + 0.5 * max(0.0, deadline - now)
    S = _solve_side(list(range(P)), conf, trials, rng, nprng, mid)
    S += _solve_side(list(range(P, N)), conf, trials, rng, nprng, deadline)
    return _blow(N, edges, S)


