# Twin blow-up (unchanged core): blow up a distance-2-free set S of base
# vertices of degree d-1 into twin pairs.
# ----------------------------------------------------------------------------

def _independent_set(N, nb, rng, nprng, deadline):
    """Iterated local search for a large set of vertices with no conflicting pair."""
    nbn = [np.asarray(x, dtype=np.int64) for x in nb]
    cnt = np.zeros(N, dtype=np.int64)
    inS = np.zeros(N, dtype=bool)
    tabu = np.zeros(N, dtype=np.int64)
    S = []
    conf = 0
    best = []
    best_size = 0
    it = 0
    last_best_it = 0

    def add(v):
        nonlocal conf
        conf += int(cnt[v])
        cnt[nbn[v]] += 1
        inS[v] = True
        S.append(v)

    def remove(u):
        nonlocal conf
        conf -= int(cnt[u])
        cnt[nbn[u]] -= 1
        inS[u] = False
        S.remove(u)

    def pick():
        score = cnt + nprng.random(N)
        score[inS] = np.inf
        score[tabu > it] = np.inf
        return int(np.argmin(score))

    while True:
        it += 1
        if (it & 63) == 0 and time.monotonic() >= deadline:
            break
        if conf == 0:
            if len(S) > best_size:
                best = list(S)
                best_size = len(S)
                last_best_it = it
            add(pick())
        else:
            conflicting = [u for u in S if cnt[u] > 0]
            u = conflicting[rng.randrange(len(conflicting))]
            remove(u)
            tabu[u] = it + 5 + rng.randrange(8)
            add(pick())
        if S and it - last_best_it > 15000:
            u = S[rng.randrange(len(S))]
            remove(u)
            tabu[u] = it + 5
            last_best_it = it
    if conf == 0 and len(S) > best_size:
        best = list(S)
    return best


def _blow(n0, edges0, S):
    """Blow up each vertex of S into two twin copies (same neighbourhood)."""
    extra = {}
    for v in S:
        extra[v] = n0 + len(extra)
    copies = [[v] + ([extra[v]] if v in extra else []) for v in range(n0)]
    edges = []
    for u, v in edges0:
        for a in copies[u]:
            for b in copies[v]:
                edges.append((a, b))
    return n0 + len(extra), edges


def _blowup(n0, edges0, d, deadline, rng, nprng):
    """Twin blow-up of a base graph of degree d-1 by a large distance-2-free set."""
    adj = [[] for _ in range(n0)]
    for u, v in edges0:
        adj[u].append(v)
        adj[v].append(u)
    if any(len(a) != d - 1 for a in adj):
        return None
    cs = [set() for _ in range(n0)]
    for w in range(n0):
        a = adj[w]
        for i in range(len(a)):
            for j in range(i + 1, len(a)):
                x, y = a[i], a[j]
                cs[x].add(y)
                cs[y].add(x)
    nb = [sorted(s) for s in cs]
    if n0 <= 60:
        deadline = min(deadline, time.monotonic() + 2.0)
    S = _independent_set(n0, nb, rng, nprng, deadline)
    return _blow(n0, edges0, S)


# ----------------------------------------------------------------------------
# NEW (bold, untested against scorer): vertex augmentation on spare degree.
#
# After a blow-up, some vertices have degree < d. A new vertex x can be
# attached to d spare vertices on one side. Adding edges never increases
# distances, so the diameter can only improve, but x itself must still reach
# everything within D. Every candidate is verified with lib.is_valid, so a
# failed attempt is simply undone and the graph stays valid.
# ----------------------------------------------------------------------------

def _two_colour(n, edges):
    """BFS 2-colouring; isolated vertices get colour 0."""
    adj = [[] for _ in range(n)]
    for u, v in edges:
        adj[u].append(v)
        adj[v].append(u)
    color = [-1] * n
    for s in range(n):
        if color[s] != -1:
            continue
        color[s] = 0
        stack = [s]
        while stack:
            u = stack.pop()
            for v in adj[u]:
                if color[v] == -1:
                    color[v] = 1 - color[u]
                    stack.append(v)
    return [max(c, 0) for c in color]


def _augment(n, edges, d, D, deadline, rng):
    """Greedily add vertices attached to d spare vertices of one side, keeping validity."""
    edges = list(edges)
    if n >= lib._moore_bound(d, D):
        return n, edges
    while time.monotonic() < deadline:
        color = _two_colour(n, edges)
        deg = [0] * n
        for u, v in edges:
            deg[u] += 1
            deg[v] += 1
        spare = [[v for v in range(n) if deg[v] < d and color[v] == c] for c in (0, 1)]
        sides = [c for c in (0, 1) if len(spare[c]) >= d]
        if not sides:
            break
        c = rng.choice(sides)
        nbrs = rng.sample(spare[c], d)
        new = n
        added = [(new, u) for u in nbrs]
        edges.extend(added)
        if lib.is_valid(n + 1, edges, d, D):
            n += 1
        else:
            del edges[len(edges) - d:]
            # Keep trying other random choices until the deadline.
    return n, edges


