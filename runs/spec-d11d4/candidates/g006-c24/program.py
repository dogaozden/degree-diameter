def build(d, D, seed, time_limit):
    t0 = time.monotonic()
    budget = max(1.0, min(0.8 * time_limit, time_limit - 10.0))
    deadline = t0 + budget
    rng = random.Random(seed)
    nprng = np.random.default_rng(abs(int(seed)) % (2 ** 32))

    if d < 1 or D < 1:
        return 1, []
    if D == 1:
        return 2, [(0, 1)]

    # Safe fallback: K_{d,d}, valid for D >= 2.
    best = lib.haar_graph(d, range(d))

    def consider(n, e):
        nonlocal best
        if n > best[0] and lib.is_valid(n, e, d, D):
            best = (n, e)

    if D == 2:
        return best

    if D >= 3:
        pg = _pg(d)
        if pg is not None:
            consider(pg[0], pg[1])

    # Target route: W(q) with q = d-2, degree d-1, diameter 4.
    # Blow up a distance-2-free set, then extend greedily using spare slots.
    q = d - 2
    if D >= 4 and 2 <= q <= 11 and lib.is_prime_power(q):
        try:
            n0, e0 = _gq_incidence(q)
            consider(n0, e0)

            now = time.monotonic()
            blow_deadline = now + 0.45 * max(0.0, deadline - now)
            S = _find_blowup_set(n0, e0, d, blow_deadline, rng, nprng)
            if S is not None:
                n1, e1 = _blow(n0, e0, S)
                consider(n1, e1)
                if lib.is_valid(n1, e1, d, D):
                    n2, e2 = _extend(n1, e1, d, deadline, rng)
                    consider(n2, e2)
        except Exception:
            pass

    if not lib.is_valid(best[0], best[1], d, D):
        best = lib.haar_graph(d, range(d))
    return best
