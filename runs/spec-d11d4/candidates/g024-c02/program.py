import itertools
import random
import time

import lib


# ----------------------------------------------------------------------------
# Generalized quadrangle W(q) as a point/line list (table-based, pure Python).
# ----------------------------------------------------------------------------

def _gq_w(q):
    """Return (P, lines): points of W(q) indexed 0..P-1 and each totally isotropic line as a sorted point list."""
    F = lib.GF(q)
    mul = F.mul_table.tolist()
    add = F.add_table.tolist()
    neg = [next(b for b in range(q) if add[a][b] == 0) for a in range(q)]
    inv = [0] * q
    for a in range(1, q):
        inv[a] = next(b for b in range(1, q) if mul[a][b] == 1)
    pts = [v for v in itertools.product(range(q), repeat=4)
           if any(v) and next(c for c in v if c) == 1]
    index = {v: i for i, v in enumerate(pts)}
    P = len(pts)

    def norm(v):
        c = next(x for x in v if x)
        ic = inv[c]
        return tuple(mul[ic][x] for x in v)

    def form(x, y):
        t = add[mul[x[0]][y[1]]][neg[mul[x[1]][y[0]]]]
        u = add[mul[x[2]][y[3]]][neg[mul[x[3]][y[2]]]]
        return add[t][u]

    covered = set()
    lines = []
    for i in range(P):
        x = pts[i]
        for j in range(i + 1, P):
            if (i * P + j) in covered:
                continue
            y = pts[j]
            if form(x, y):
                continue
            Lset = set()
            for a in range(q):
                for b in range(q):
                    if a == 0 and b == 0:
                        continue
                    v = tuple(add[mul[a][x[k]]][mul[b][y[k]]] for k in range(4))
                    if any(v):
                        Lset.add(index[norm(v)])
            Ls = sorted(Lset)
            lines.append(Ls)
            for p in Ls:
                for r in Ls:
                    if p < r:
                        covered.add(p * P + r)
    return P, lines


def _gq_incidence(q):
    """Incidence graph of W(q): (n, edges), points 0..P-1, lines P..P+L-1; degree q+1, diameter 4."""
    P, lines = _gq_w(q)
    L = len(lines)
    return P + L, [(p, P + j) for j, Ls in enumerate(lines) for p in Ls]


# ----------------------------------------------------------------------------
# Maximum independent set by k-fixed tabu search (pure Python).
# ----------------------------------------------------------------------------

def _mis(n, adj, deadline, rng):
    """Return a large independent set of the graph (n vertices, adj neighbour lists) found before deadline."""
    inS = [False] * n
    c = [0] * n
    S = []

    def add(v):
        inS[v] = True
        S.append(v)
        for w in adj[v]:
            c[w] += 1

    def remove(u):
        inS[u] = False
        S.remove(u)
        for w in adj[u]:
            c[w] -= 1

    order = list(range(n))
    rng.shuffle(order)
    for v in order:
        if c[v] == 0:
            add(v)
    best = list(S)
    tab_add = [0] * n
    tab_rem = [0] * n
    it = 0
    stuck = 0
    while time.monotonic() < deadline:
        it += 1
        cost = sum(c[v] for v in S)
        if cost == 0:
            if len(S) > len(best):
                best = list(S)
                stuck = 0
            cands = [v for v in range(n) if not inS[v] and tab_add[v] <= it] \
                or [v for v in range(n) if not inS[v]]
            if not cands:
                break
            mn = min(c[v] for v in cands)
            add(rng.choice([v for v in cands if c[v] == mn]))
            continue
        stuck += 1
        if stuck > 3000:
            for v in list(S):
                remove(v)
            for v in best:
                add(v)
            stuck = 0
            continue
        ok = [u for u in S if tab_rem[u] <= it] or list(S)
        mx = max(c[u] for u in ok)
        u = rng.choice([x for x in ok if c[x] == mx])
        remove(u)
        tab_add[u] = it + rng.randint(5, 15)
        cands = [v for v in range(n) if not inS[v] and tab_add[v] <= it] \
            or [v for v in range(n) if not inS[v]]
        mn = min(c[v] for v in cands)
        v = rng.choice([x for x in cands if c[x] == mn])
        add(v)
        tab_rem[v] = it + rng.randint(5, 15)
    return best


# ----------------------------------------------------------------------------
# Twin construction on W(q), degree q+2 (for d = q+2, D = 4).
# ----------------------------------------------------------------------------

def _twin_graph(q, deadline, rng):
    P, lines = _gq_w(q)
    L = len(lines)
    pl = [[] for _ in range(P)]
    for j, Ls in enumerate(lines):
        for p in Ls:
            pl[p].append(j)
    padj = [set() for _ in range(P)]
    for Ls in lines:
        for p in Ls:
            for r in Ls:
                if p != r:
                    padj[p].add(r)
    ladj = [set() for _ in range(L)]
    for p in range(P):
        for a in pl[p]:
            for b in pl[p]:
                if a != b:
                    ladj[a].add(b)

    now = time.monotonic()
    mid = now + (deadline - now) / 2.0
    I = _mis(P, [sorted(s) for s in padj], mid, rng)
    J = _mis(L, [sorted(s) for s in ladj], deadline, rng)

    edges = [(p, P + j) for j, Ls in enumerate(lines) for p in Ls]
    n = P + L
    for p in I:
        for j in pl[p]:
            edges.append((n, P + j))
        n += 1
    for j in J:
        for p in lines[j]:
            edges.append((p, n))
        n += 1
    return n, edges


# ----------------------------------------------------------------------------
# Set-cover vertex extension for diameter 4 (all-alive graph representation).
# ----------------------------------------------------------------------------

NOISE = 0.25
TRIES = 25
KICK_ACCEPT_WORSE = 0.05


def _balls(n, adj, r):
    """Per-vertex bitmask of all vertices within distance r."""
    reach = [1 << v for v in range(n)]
    for _ in range(r):
        new = []
        for v in range(n):
            x = reach[v]
            for u in adj[v]:
                x |= reach[u]
            new.append(x)
        reach = new
    return reach


def _pick(pool, reach, unc, rng):
    """Next cover vertex: best gain, or a random useful one with probability NOISE."""
    if rng.random() < NOISE:
        useful = [v for v in pool if reach[v] & unc]
        if useful:
            return rng.choice(useful)
        return -1
    best, bv = 0, -1
    for v in pool:
        g = (reach[v] & unc).bit_count()
        if g > best:
            best, bv = g, v
    return bv


def _grow(adj, color, d, deadline, rng):
    """Append vertices in place while the diameter-4 invariant and max degree d are kept.

    A new vertex x joins a set S of same-colour spare vertices whose radius-3 balls
    cover every existing vertex. Reach is recomputed after every addition so the
    cover check stays exact.
    """
    while time.monotonic() < deadline:
        n = len(adj)
        spare = [v for v in range(n) if len(adj[v]) < d]
        if not spare:
            return
        reach = _balls(n, adj, 3)
        full = (1 << n) - 1
        found = None
        for _ in range(TRIES):
            s0 = rng.choice(spare)
            pool = [v for v in spare if color[v] == color[s0] and v != s0]
            S = [s0]
            unc = full & ~reach[s0]
            while unc and len(S) < d and pool:
                bv = _pick(pool, reach, unc, rng)
                if bv < 0:
                    break
                S.append(bv)
                unc &= ~reach[bv]
                pool.remove(bv)
            if not unc:
                found = (S, s0)
                break
        if found is None:
            return
        S, s0 = found
        x = n
        for s in S:
            adj[s].append(x)
        adj.append(list(S))
        color.append(1 - color[s0])


def _remove(adj, color, rem):
    """Return a compacted copy of the graph with vertices in rem deleted (indices shift, order kept)."""
    rs = set(rem)
    keep = [v for v in range(len(adj)) if v not in rs]
    idx = {v: i for i, v in enumerate(keep)}
    nadj = [[idx[w] for w in adj[v] if w not in rs] for v in keep]
    ncol = [color[v] for v in keep]
    return nadj, ncol


def _ils(adj, color, nb, d, deadline, rng):
    """Iterated local search: remove a few extension vertices, check diameter, regrow.

    Vertices 0..nb-1 (the twin core) are never removed. Returns the best (adj, color) found.
    """
    _grow(adj, color, d, deadline, rng)
    cur_adj, cur_col = adj, color
    best_adj = [list(a) for a in cur_adj]
    best_col = list(cur_col)
    best_n = len(cur_adj)
    while time.monotonic() < deadline:
        ext = list(range(nb, len(cur_adj)))
        if not ext:
            break
        k = rng.randint(1, min(4, len(ext)))
        rem = rng.sample(ext, k)
        radj, rcol = _remove(cur_adj, cur_col, rem)
        n = len(radj)
        full = (1 << n) - 1
        r4 = _balls(n, radj, 4)
        if any(x != full for x in r4):
            continue
        _grow(radj, rcol, d, deadline, rng)
        if len(radj) >= len(cur_adj) or rng.random() < KICK_ACCEPT_WORSE:
            cur_adj, cur_col = radj, rcol
        if len(cur_adj) > best_n:
            best_n = len(cur_adj)
            best_adj = [list(a) for a in cur_adj]
            best_col = list(cur_col)
    return best_adj, best_col


def _two_color(adj):
    """Proper 2-colouring of a bipartite adjacency list; raises if not bipartite."""
    n = len(adj)
    color = [-1] * n
    for s in range(n):
        if color[s] != -1:
            continue
        color[s] = 0
        stack = [s]
        while stack:
            u = stack.pop()
            for w in adj[u]:
                if color[w] == -1:
                    color[w] = 1 - color[u]
                    stack.append(w)
                elif color[w] == color[u]:
                    raise ValueError("not bipartite")
    return color


