def build(d, D, seed, time_limit):
    t0 = time.monotonic()
    budget = max(1.0, min(0.8 * time_limit, time_limit - 10.0))
    deadline = t0 + budget
    rng = random.Random(seed)
    nprng = np.random.default_rng(abs(int(seed)) % (2 ** 32))

    if d < 1 or D < 1:
        return 1, []
    if D == 1:
        return 2, [(0, 1)]

    # Safe fallback: K_{d,d}, valid for D >= 2.
    best = lib.haar_graph(d, range(d))

    def consider(n, e):
        nonlocal best
        if n > best[0] and lib.is_valid(n, e, d, D):
            best = (n, e)

    if D == 2:
        return best

    if D == 3:
        try:
            pg = _pg(d)
            if pg is not None:
                consider(*pg)
        except Exception:
            pass

    if D >= 4 and lib.is_prime_power(d - 1) and 2 <= d - 1 <= 11:
        try:
            consider(*_gq_incidence(d - 1))
        except Exception:
            pass

    # Blow-up route on base of degree d-1 (q = d-2 prime power).
    q = d - 2
    if D >= 3 and 2 <= q <= 11 and lib.is_prime_power(q):
        try:
            if D == 3:
                n0, e0 = lib.projective_plane_incidence(q)
            else:
                n0, e0 = _gq_incidence(q)
            consider(n0, e0)
            blow_deadline = t0 + 0.85 * budget
            res = _blowup(n0, e0, d, blow_deadline, rng, nprng)
            if res is not None:
                consider(res[0], res[1])
                if time.monotonic() < deadline - 2.0:
                    n3, e3 = _extend(res[0], res[1], d, deadline, rng)
                    consider(n3, e3)
        except Exception:
            pass

    if not lib.is_valid(best[0], best[1], d, D):
        return lib.haar_graph(d, range(d))
    return best
