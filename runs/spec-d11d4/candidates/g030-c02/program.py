import itertools
import random
import time

import lib


# ----------------------------------------------------------------------------
# Generalized quadrangle W(q) as a point/line list (table-based, pure Python).
# ----------------------------------------------------------------------------

def _gq_w(q):
    """Return (P, lines): points of W(q) indexed 0..P-1 and each totally isotropic line as a sorted point list."""
    F = lib.GF(q)
    mul = F.mul_table.tolist()
    add = F.add_table.tolist()
    neg = [next(b for b in range(q) if add[a][b] == 0) for a in range(q)]
    inv = [0] * q
    for a in range(1, q):
        inv[a] = next(b for b in range(1, q) if mul[a][b] == 1)
    pts = [v for v in itertools.product(range(q), repeat=4)
           if any(v) and next(c for c in v if c) == 1]
    index = {v: i for i, v in enumerate(pts)}
    P = len(pts)

    def norm(v):
        c = next(x for x in v if x)
        ic = inv[c]
        return tuple(mul[ic][x] for x in v)

    def form(x, y):
        t = add[mul[x[0]][y[1]]][neg[mul[x[1]][y[0]]]]
        u = add[mul[x[2]][y[3]]][neg[mul[x[3]][y[2]]]]
        return add[t][u]

    covered = set()
    lines = []
    for i in range(P):
        x = pts[i]
        for j in range(i + 1, P):
            if (i * P + j) in covered:
                continue
            y = pts[j]
            if form(x, y):
                continue
            Lset = set()
            for a in range(q):
                for b in range(q):
                    if a == 0 and b == 0:
                        continue
                    v = tuple(add[mul[a][x[k]]][mul[b][y[k]]] for k in range(4))
                    if any(v):
                        Lset.add(index[norm(v)])
            Ls = sorted(Lset)
            lines.append(Ls)
            for p in Ls:
                for r in Ls:
                    if p < r:
                        covered.add(p * P + r)
    return P, lines


def _gq_incidence(q):
    """Incidence graph of W(q): (n, edges), points 0..P-1, lines P..P+L-1; degree q+1, diameter 4."""
    P, lines = _gq_w(q)
    L = len(lines)
    return P + L, [(p, P + j) for j, Ls in enumerate(lines) for p in Ls]


# ----------------------------------------------------------------------------
# Maximum independent set by k-fixed tabu search (pure Python).
# ----------------------------------------------------------------------------

def _mis(n, adj, deadline, rng):
    """Return a large independent set of the graph (n vertices, adj neighbour lists) found before deadline."""
    inS = [False] * n
    c = [0] * n
    S = []

    def add(v):
        inS[v] = True
        S.append(v)
        for w in adj[v]:
            c[w] += 1

    def remove(u):
        inS[u] = False
        S.remove(u)
        for w in adj[u]:
            c[w] -= 1

    order = list(range(n))
    rng.shuffle(order)
    for v in order:
        if c[v] == 0:
            add(v)
    best = list(S)
    tab_add = [0] * n
    tab_rem = [0] * n
    it = 0
    stuck = 0
    while time.monotonic() < deadline:
        it += 1
        cost = sum(c[v] for v in S)
        if cost == 0:
            if len(S) > len(best):
                best = list(S)
                stuck = 0
            cands = [v for v in range(n) if not inS[v] and tab_add[v] <= it] \
                or [v for v in range(n) if not inS[v]]
            if not cands:
                break
            mn = min(c[v] for v in cands)
            add(rng.choice([v for v in cands if c[v] == mn]))
            continue
        stuck += 1
        if stuck > 3000:
            for v in list(S):
                remove(v)
            for v in best:
                add(v)
            stuck = 0
            continue
        ok = [u for u in S if tab_rem[u] <= it] or list(S)
        mx = max(c[u] for u in ok)
        u = rng.choice([x for x in ok if c[x] == mx])
        remove(u)
        tab_add[u] = it + rng.randint(5, 15)
        cands = [v for v in range(n) if not inS[v] and tab_add[v] <= it] \
            or [v for v in range(n) if not inS[v]]
        mn = min(c[v] for v in cands)
        v = rng.choice([x for x in cands if c[x] == mn])
        add(v)
        tab_rem[v] = it + rng.randint(5, 15)
    return best


# ----------------------------------------------------------------------------
# Twin construction on W(q), degree q+2 (for d = q+2, D = 4).
# ----------------------------------------------------------------------------

def _twin_graph(q, deadline, rng):
    P, lines = _gq_w(q)
    L = len(lines)
    pl = [[] for _ in range(P)]
    for j, Ls in enumerate(lines):
        for p in Ls:
            pl[p].append(j)
    padj = [set() for _ in range(P)]
    for Ls in lines:
        for p in Ls:
            for r in Ls:
                if p != r:
                    padj[p].add(r)
    ladj = [set() for _ in range(L)]
    for p in range(P):
        for a in pl[p]:
            for b in pl[p]:
                if a != b:
                    ladj[a].add(b)

    now = time.monotonic()
    mid = now + (deadline - now) / 2.0
    I = _mis(P, [sorted(s) for s in padj], mid, rng)
    J = _mis(L, [sorted(s) for s in ladj], deadline, rng)

    edges = [(p, P + j) for j, Ls in enumerate(lines) for p in Ls]
    n = P + L
    for p in I:
        for j in pl[p]:
            edges.append((n, P + j))
        n += 1
    for j in J:
        for p in lines[j]:
            edges.append((p, n))
        n += 1
    return n, edges


# ----------------------------------------------------------------------------
# Ball bitmasks and greedy set-cover extension (for radius D-1 covers).
# ----------------------------------------------------------------------------

NOISE = 0.25


def _ball3(n, adj):
    """Return per-vertex bitmasks of all vertices within distance 3."""
    reach = [1 << v for v in range(n)]
    for _ in range(3):
        new = []
        for v in range(n):
            r = reach[v]
            for u in adj[v]:
                r |= reach[u]
            new.append(r)
        reach = new
    return reach


def _pick(pool, reach, unc, rng):
    """Choose the next cover vertex from pool: best gain, or a random useful one with prob NOISE."""
    if rng.random() < NOISE:
        useful = [v for v in pool if reach[v] & unc]
        if useful:
            return rng.choice(useful)
        return -1
    best, bv = 0, -1
    for v in pool:
        g = (reach[v] & unc).bit_count()
        if g > best:
            best, bv = g, v
    return bv


def _extend(n, edges, d, deadline, rng, max_fails=3000):
    """Greedily add vertices while keeping max degree d and diameter 4; return (n, edges)."""
    edges = list(edges)
    adj = [[] for _ in range(n)]
    for u, v in edges:
        adj[u].append(v)
        adj[v].append(u)
    color = [-1] * n
    for s in range(n):
        if color[s] != -1:
            continue
        color[s] = 0
        stack = [s]
        while stack:
            u = stack.pop()
            for w in adj[u]:
                if color[w] == -1:
                    color[w] = 1 - color[u]
                    stack.append(w)

    fails = 0
    while time.monotonic() < deadline:
        reach = _ball3(n, adj)
        full = (1 << n) - 1
        grown = False
        while time.monotonic() < deadline:
            spare = [v for v in range(n) if len(adj[v]) < d]
            if not spare:
                return n, edges
            if fails >= max_fails:
                return n, edges
            s0 = rng.choice(spare)
            pool = [v for v in spare if color[v] == color[s0] and v != s0]
            S = [s0]
            unc = full & ~reach[s0]
            while unc and len(S) < d and pool:
                bv = _pick(pool, reach, unc, rng)
                if bv < 0:
                    break
                S.append(bv)
                unc &= ~reach[bv]
                pool.remove(bv)
            if unc:
                fails += 1
                continue
            x = n
            n += 1
            for s in S:
                edges.append((s, x))
                adj[s].append(x)
            adj.append(list(S))
            color.append(1 - color[s0])
            fails = 0
            grown = True
            break
        if not grown:
            break
    return n, edges


# ----------------------------------------------------------------------------
# NEW: remove-and-refill plateau search with exact diameter verification.
#
# A mutable graph keeps adjacency as sets and an "active" flag per index.
# A move picks a random active vertex v, detaches it, and checks that the
# remaining graph still has diameter <= D. Then it greedily refills the freed
# degree slots with new vertices (each joined to a set S whose radius-(D-1)
# balls cover every active vertex), recomputing balls after each addition so
# coverage always uses exact distances. The move is kept when at least one
# vertex was added (net change >= 0, so plateaus are explored). Otherwise
# or on any failed check, the change is undone. Removed indices are recycled
# through a free list, which keeps bitmask widths bounded.
# ----------------------------------------------------------------------------

class _G:
    def __init__(self, n, edges):
        self.N = n
        self.adj = [set() for _ in range(n)]
        for u, v in edges:
            self.adj[u].add(v)
            self.adj[v].add(u)
        self.active = [True] * n
        self.free = []
        self.color = [-1] * n
        for s in range(n):
            if self.color[s] != -1:
                continue
            self.color[s] = 0
            stack = [s]
            while stack:
                u = stack.pop()
                for w in self.adj[u]:
                    if self.color[w] == -1:
                        self.color[w] = 1 - self.color[u]
                        stack.append(w)

    def amask(self):
        m = 0
        for v in range(self.N):
            if self.active[v]:
                m |= 1 << v
        return m

    def new_vertex(self, S, col):
        if self.free:
            x = self.free.pop()
            self.adj[x] = set(S)
            self.active[x] = True
            self.color[x] = col
        else:
            x = self.N
            self.N += 1
            self.adj.append(set(S))
            self.active.append(True)
            self.color.append(col)
        for s in S:
            self.adj[s].add(x)
        return x

    def detach(self, v):
        S = list(self.adj[v])
        for s in S:
            self.adj[s].discard(v)
        self.adj[v] = set()
        self.active[v] = False
        return S

    def attach(self, v, S):
        self.adj[v] = set(S)
        self.active[v] = True
        for s in S:
            self.adj[s].add(v)


def _reach(g, r):
    """Per-vertex bitmask of active vertices within distance r (inactive entries are 0)."""
    N, adj, active = g.N, g.adj, g.active
    reach = [(1 << v) if active[v] else 0 for v in range(N)]
    for _ in range(r):
        new = [0] * N
        for v in range(N):
            if active[v]:
                x = reach[v]
                for u in adj[v]:
                    x |= reach[u]
                new[v] = x
        reach = new
    return reach


def _diam_ok(g, D):
    m = g.amask()
    reach = _reach(g, D)
    return all(reach[v] == m for v in range(g.N) if g.active[v])


def _refill(g, d, D, rng, deadline, tries=8):
    """Greedily add vertices into spare degree; return the list of (index, S) added."""
    added = []
    fails = 0
    reach = _reach(g, D - 1)
    m = g.amask()
    while fails < tries and time.monotonic() < deadline:
        spare = [v for v in range(g.N) if g.active[v] and len(g.adj[v]) < d]
        if not spare:
            break
        s0 = rng.choice(spare)
        pool = [v for v in spare if v != s0 and g.color[v] == g.color[s0]]
        S = [s0]
        unc = m & ~reach[s0]
        while unc and len(S) < d and pool:
            bv = _pick(pool, reach, unc, rng)
            if bv < 0:
                break
            S.append(bv)
            unc &= ~reach[bv]
            pool.remove(bv)
        if unc:
            fails += 1
            continue
        y = g.new_vertex(S, 1 - g.color[s0])
        added.append((y, S))
        reach = _reach(g, D - 1)
        m = g.amask()
        fails = 0
    return added


def _snap(g):
    act = [v for v in range(g.N) if g.active[v]]
    idx = {v: i for i, v in enumerate(act)}
    edges = [(idx[u], idx[w]) for u in act for w in g.adj[u] if u < w]
    return len(act), edges


def _improve(n, edges, d, D, rng, deadline):
    """Remove-and-refill plateau search; return the best (n, edges) seen."""
    g = _G(n, edges)
    cur = sum(g.active)
    best_n, best_snap = cur, _snap(g)
    while time.monotonic() < deadline:
        while True:
            v = rng.randrange(g.N)
            if g.active[v]:
                break
        S = g.detach(v)
        if not _diam_ok(g, D):
            g.attach(v, S)
            continue
        added = _refill(g, d, D, rng, deadline)
        if not added:
            g.attach(v, S)
            continue
        if not _diam_ok(g, D):
            for y, _ in reversed(added):
                g.detach(y)
                g.free.append(y)
            g.attach(v, S)
            continue
        g.free.append(v)
        cur += len(added) - 1
        if cur > best_n:
            best_n = cur
            best_snap = _snap(g)
    return best_snap


