def build(d, D, seed, time_limit):
    t0 = time.monotonic()
    budget = max(0.5, 0.8 * time_limit - 4.0)
    deadline = t0 + budget
    rng = random.Random(seed)
    nprng = np.random.default_rng(abs(int(seed)) % (2 ** 32))

    if d < 1 or D < 1:
        return 1, []
    if D == 1:
        return 2, [(0, 1)]

    # Safe fallback: K_{d,d}, diameter 2.
    best = lib.haar_graph(d, range(d))

    def consider(n, edges):
        nonlocal best
        if n > best[0] and lib.is_valid(n, edges, d, D):
            best = (n, edges)

    if D == 2:
        return best

    # Projective plane PG(2, d-1): degree d, diameter 3.
    if lib.is_prime_power(d - 1):
        try:
            consider(*lib.projective_plane_incidence(d - 1))
        except Exception:
            pass

    # Generalized quadrangle W(d-1): degree d, diameter 4.
    if D >= 4 and lib.is_prime_power(d - 1) and 2 <= d - 1 <= 11:
        try:
            _, n1, e1 = _gq(d - 1)
            consider(n1, e1)
        except Exception:
            pass

    # Blow-up route: base of degree exactly d-1 with q = d-2 a prime power.
    # Blow up a conflict-free set of vertices, then extend with spare degree.
    q = d - 2
    if 2 <= q <= 11 and lib.is_prime_power(q):
        try:
            if D == 3:
                n0, e0 = lib.projective_plane_incidence(q)
            elif D >= 4:
                _, n0, e0 = _gq(q)
            else:
                n0, e0 = 0, []
            if n0 > 0:
                consider(n0, e0)
                blow_deadline = t0 + 0.6 * budget if D >= 4 else deadline
                cur = (n0, e0)
                res = _blowup(n0, e0, d, blow_deadline, rng, nprng)
                if res is not None:
                    consider(res[0], res[1])
                    cur = res
                if D >= 4:
                    n3, e3 = _extend(cur[0], cur[1], d, deadline, rng)
                    consider(n3, e3)
        except Exception:
            pass

    if not lib.is_valid(best[0], best[1], d, D):
        return lib.haar_graph(d, range(d))
    return best
