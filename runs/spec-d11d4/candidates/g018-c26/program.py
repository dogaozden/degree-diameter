# NEW IDEA: exact slack filling by ball cover.
#
# A new vertex x on side c can be attached to a set Y of opposite-side vertices
# that have spare degree. For x to be within distance D of every old vertex w,
# it suffices that some y in Y has dist(y, w) <= D-1 (the path from x to w
# leaves x through some neighbour, and the rest of the path avoids x). Adding x
# never lengthens any old shortest path, so old pairs stay within D. Hence:
#     x can be attached to Y  iff  union over y in Y of Ball_{D-1}(y) = V.
# Y is found greedily as a set cover of the vertex set by radius-(D-1) balls
# (bitmasks), with |Y| <= d. Every accepted step is exact, so the result stays
# valid by construction, and it is still checked with lib.is_valid at the end.
# ----------------------------------------------------------------------------

def _ball_masks(n, adj, R):
    """Bitmask of all vertices within distance R of each vertex."""
    reach = [1 << v for v in range(n)]
    for _ in range(R):
        new = []
        for v in range(n):
            r = reach[v]
            for u in adj[v]:
                r |= reach[u]
            new.append(r)
        reach = new
    return reach


def _augment(n, edges, d, D, deadline):
    """Greedily add new vertices whose neighbourhoods are covering sets of spare-degree vertices."""
    if D < 2:
        return n, edges
    adj = [[] for _ in range(n)]
    for u, v in edges:
        adj[u].append(v)
        adj[v].append(u)
    if any(len(a) > d for a in adj):
        return n, edges
    color = [-1] * n
    color[0] = 0
    stack = [0]
    while stack:
        u = stack.pop()
        for v in adj[u]:
            if color[v] == -1:
                color[v] = 1 - color[u]
                stack.append(v)
    if any(c == -1 for c in color):
        return n, edges
    R = D - 1
    while time.monotonic() < deadline:
        cur = len(adj)
        full = (1 << cur) - 1
        balls = _ball_masks(cur, adj, R)
        placed = False
        for c in (0, 1):
            cands = [y for y in range(cur) if color[y] == 1 - c and len(adj[y]) < d]
            if not cands:
                continue
            U = full
            chosen = []
            while U and len(chosen) < d:
                best_y = -1
                best_g = 0
                for y in cands:
                    g = (balls[y] & U).bit_count()
                    if g > best_g:
                        best_g = g
                        best_y = y
                if best_y < 0:
                    break
                chosen.append(best_y)
                U &= ~balls[best_y]
            if U == 0 and chosen:
                x = cur
                adj.append([])
                color.append(c)
                for y in chosen:
                    adj[y].append(x)
                    adj[x].append(y)
                placed = True
                break
        if not placed:
            break
    out = [(u, v) for u in range(len(adj)) for v in adj[u] if u < v]
    return len(adj), out


