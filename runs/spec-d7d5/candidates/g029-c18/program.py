def build(d, D, seed, time_limit):
    start = time.monotonic()
    budget = max(1.0, min(0.85 * time_limit, time_limit - 7.0))
    deadline = start + budget

    if d < 1 or D < 1:
        return 1, []
    if D == 1:
        return 2, [(0, 1)]

    rng = random.Random(seed)

    # Safe fallback: K_{d,d} has diameter 2.
    best = lib.haar_graph(d, range(d))
    best_n = best[0]

    def consider(n, e):
        nonlocal best, best_n
        if n > best_n and lib.is_valid(n, e, d, D):
            best = (n, e)
            best_n = n

    # Exact projective-plane construction for D >= 3.
    if D >= 3:
        for q in range(d - 1, 1, -1):
            if lib.is_prime_power(q):
                n, e = lib.projective_plane_incidence(q)
                consider(n, e)
                if D == 3 and q == d - 1:
                    return best
                break

    # Main search: nonabelian group lifts (new family) plus semidirect lifts.
    cache = {}

    def group(spec):
        if spec not in cache:
            cache[spec] = _build_spec(spec)
        return cache[spec]

    slots = _configs(d, D) + [None]  # None = semidirect slot
    idx = 0
    while time.monotonic() < deadline:
        slot = slots[idx % len(slots)]
        idx += 1
        slice_end = min(deadline, time.monotonic() + _SLICE)

        if slot is None:
            kk = rng.choice((1, 2, 3, 4))
            target = best_n // (2 * kk) + 1 + rng.randrange(3)
            s = _sample_semi(target, rng)
            if s is None:
                continue
            m, k2, r = s
            G, Rcol, Rinv = _tables(_semi_M(m, k2, r))
        else:
            spec, kk, tot = slot
            if tot <= best_n:
                continue
            g = group(spec)
            if g is None:
                continue
            G, Rcol, Rinv = g
            if 2 * kk * G <= best_n:
                continue

        while time.monotonic() < slice_end:
            res = _search(d, D, kk, G, Rcol, Rinv, rng, slice_end, 4000, 1200)
            if res is not None:
                consider(res[0], res[1])
                break

    if not lib.is_valid(best[0], best[1], d, D):
        return lib.haar_graph(d, range(d))
    return best
