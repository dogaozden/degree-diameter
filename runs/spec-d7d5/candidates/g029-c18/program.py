import math
import random
import time
from math import factorial, gcd

import numpy as np

import lib


# ----------------------------------------------------------------------------
# Safe baseline: projective plane incidence graphs (exact for D = 3).
# ----------------------------------------------------------------------------

_PENALTY = 1000
_KMAX = 10
_SLICE = 3.0
_POP = np.zeros(1 << (2 * _KMAX), dtype=np.int64)
_ar = np.arange(1 << (2 * _KMAX), dtype=np.int64)
for _b in range(2 * _KMAX):
    _POP += (_ar >> _b) & 1
del _ar, _b


# ----------------------------------------------------------------------------
# Group tables. Every group is given as a multiplication table M (M[g, h] = g*h,
# identity = index 0). Tables come from permutation groups (PSL/PGL(2,p), S_n,
# A_n) or from semidirect products Z_m x| Z_k2.
# ----------------------------------------------------------------------------

def _prime_factors(n):
    f = set()
    x = n
    p = 2
    while p * p <= x:
        while x % p == 0:
            f.add(p)
            x //= p
        p += 1
    if x > 1:
        f.add(x)
    return f


def _prim_root(p):
    fs = _prime_factors(p - 1)
    for g in range(2, p):
        if all(pow(g, (p - 1) // f, p) != 1 for f in fs):
            return g
    return 1


def _pgl_gens(p, proj):
    """Generators of PSL(2,p) (proj=False) or PGL(2,p) acting on p+1 points; infinity = p."""
    g = _prim_root(p)
    c = g if proj else g * g % p
    T = tuple([(x + 1) % p for x in range(p)] + [p])
    Mu = tuple([(c * x) % p for x in range(p)] + [p])
    Sg = tuple([p] + [(-pow(x, p - 2, p)) % p for x in range(1, p)] + [0])
    return [T, Mu, Sg], p + 1


def _closure(gens, n, limit):
    """Elements of the permutation group generated by gens (tuples), or None if above limit."""
    idt = tuple(range(n))
    seen = {idt: 0}
    elems = [idt]
    i = 0
    while i < len(elems):
        g = elems[i]
        i += 1
        for s in gens:
            h = tuple(g[s[x]] for x in range(n))
            if h not in seen:
                if len(elems) >= limit:
                    return None
                seen[h] = len(elems)
                elems.append(h)
    return elems


def _mult_table(elems):
    P = np.array(elems, dtype=np.int64)
    N, n = P.shape
    w = np.array([n ** i for i in range(n)], dtype=np.int64)
    keys = P @ w
    order = np.argsort(keys)
    sk = keys[order]
    M = np.empty((N, N), dtype=np.int64)
    for g in range(N):
        C = P[g][P]              # row h: (g o h)
        pos = np.searchsorted(sk, C @ w)
        M[g] = order[pos]
    return M


def _semi_M(m, k2, r):
    """Multiplication table of Z_m x| Z_k2: (a,b)(c,e) = (a + r^b c, b + e), element a*k2 + b."""
    G = m * k2
    x = np.arange(G, dtype=np.int64)
    a = x // k2
    b = x % k2
    pw = np.array([pow(r, t, m) for t in range(k2)], dtype=np.int64)
    return ((a[:, None] + pw[b][:, None] * a[None, :]) % m) * k2 + (b[:, None] + b[None, :]) % k2


def _tables(M):
    """Return (G, Rcol, Rinv): Rcol[s][g] = g*s and Rinv[s][g] = g*s^-1."""
    G = M.shape[0]
    Rcol = np.ascontiguousarray(M.T)
    inv = np.argmax(M == 0, axis=1)
    Rinv = np.ascontiguousarray(Rcol[inv])
    return G, Rcol, Rinv


def _order(spec):
    kind, p = spec
    if kind == "psl":
        return p * (p * p - 1) // 2
    if kind == "pgl":
        return p * (p * p - 1)
    if kind == "sym":
        return factorial(p)
    return factorial(p) // 2  # alt


def _build_spec(spec):
    kind, p = spec
    if kind in ("psl", "pgl"):
        gens, npts = _pgl_gens(p, kind == "pgl")
    elif kind == "sym":
        npts = p
        gens = [tuple([1, 0] + list(range(2, p))), tuple((x + 1) % p for x in range(p))]
    else:
        npts = p
        three = tuple([1, 2, 0] + list(range(3, p)))
        if p % 2 == 1:
            cyc = tuple((x + 1) % p for x in range(p))
        else:
            cyc = tuple([0] + [x + 1 if x < p - 1 else 1 for x in range(1, p)])
        gens = [three, cyc]
    elems = _closure(gens, npts, 1600)
    if elems is None:
        return None
    return _tables(_mult_table(elems))


_SPECS = [("alt", 5), ("psl", 7), ("pgl", 7), ("alt", 6), ("sym", 6),
          ("psl", 11), ("pgl", 11), ("psl", 13)]


def _configs(d, D):
    """(spec, k, total) for group lifts whose order lies in the useful band of the Moore bound."""
    moore = lib._moore_bound(d, D)
    lo, hi = 0.35 * moore, 0.55 * moore
    out = []
    for spec in _SPECS:
        G = _order(spec)
        for k in range(1, _KMAX + 1):
            tot = 2 * k * G
            if lo <= tot <= hi:
                out.append((spec, k, tot))
    out.sort(key=lambda t: t[2])
    return out


def _sample_semi(target, rng):
    for _ in range(100):
        k2 = rng.choice([1, 1, 2, 2, 3, 4, 5, 6, 8, 9, 10, 12])
        m = max(2, -(-target // k2))
        if k2 == 1:
            return m, 1, 1
        r = None
        for _ in range(60):
            c = rng.randrange(2, m) if m > 2 else 1
            if gcd(c, m) == 1 and pow(c, k2, m) == 1 % m:
                r = c
                break
        if r is not None:
            return m, k2, r
    return None


# ----------------------------------------------------------------------------
# Bi-Cayley lift over a general group G with k base vertices per side.
# A_{i,g} = i*G + g, B_{j,h} = (k+j)*G + h. In layer l, A_i is joined to
# B_{pi_l(i)} with voltage s: A_{i,g} ~ B_{j, g*s}. Each layer is a perfect
# matching between blocks, so the lift is d-regular bipartite.
# Validity uses left-multiplication symmetry: reach bitmask over block reps.
# ----------------------------------------------------------------------------

def _set_pair(nbr, k, G, Rcol, Rinv, l, i, j, s):
    nbr[l, i * G:(i + 1) * G] = (k + j) * G + Rcol[s]
    nbr[l, (k + j) * G:(k + j + 1) * G] = i * G + Rinv[s]


def _reach(k, G, D, nb, d):
    N = nb.shape[1]
    reach = np.zeros(N, dtype=np.int64)
    for b in range(2 * k):
        reach[b * G] = 1 << b
    for _ in range(D):
        new = reach.copy()
        for l in range(d):
            new |= reach[nb[l]]
        if np.array_equal(new, reach):
            break
        reach = new
    return reach


def _search(d, D, k, G, Rcol, Rinv, rng, deadline, iters, patience):
    """Simulated annealing over voltages and layer permutations. Returns (n, edges) or None."""
    N = 2 * k * G
    full = (1 << (2 * k)) - 1
    tot_pairs = 2 * k * N
    pi = [rng.sample(range(k), k) for _ in range(d)]
    S = [[rng.randrange(G) for _ in range(k)] for _ in range(d)]
    nbr = np.empty((d, N), dtype=np.int64)
    for l in range(d):
        for i in range(k):
            _set_pair(nbr, k, G, Rcol, Rinv, l, i, pi[l][i], S[l][i])

    def dup():
        keys = [(i, pi[l][i], S[l][i]) for l in range(d) for i in range(k)]
        return len(keys) - len(set(keys))

    def evaluate():
        r = _reach(k, G, D, nbr, d)
        return tot_pairs - int(_POP[r].sum()) + _PENALTY * dup(), r

    cost, reach = evaluate()
    c0 = float(max(cost, 1))
    best_cost = cost
    last = 0
    for t in range(iters):
        if cost == 0 or time.monotonic() > deadline:
            break
        if t - last > patience:
            break
        temp = max(0.5, 0.01 * c0 * (1.0 - t / iters))

        if k >= 2 and rng.random() < 0.25:
            # Layer-swap move: exchange the B-targets of two A-blocks in one layer.
            l = rng.randrange(d)
            i1, i2 = rng.sample(range(k), 2)
            pl = pi[l]
            pl[i1], pl[i2] = pl[i2], pl[i1]
            _set_pair(nbr, k, G, Rcol, Rinv, l, i1, pl[i1], S[l][i1])
            _set_pair(nbr, k, G, Rcol, Rinv, l, i2, pl[i2], S[l][i2])
            c2, r2 = evaluate()
            if c2 <= cost or rng.random() < math.exp(-(c2 - cost) / temp):
                cost, reach = c2, r2
                if cost < best_cost:
                    best_cost, last = cost, t
            else:
                pl[i1], pl[i2] = pl[i2], pl[i1]
                _set_pair(nbr, k, G, Rcol, Rinv, l, i1, pl[i1], S[l][i1])
                _set_pair(nbr, k, G, Rcol, Rinv, l, i2, pl[i2], S[l][i2])
            continue

        # Voltage move, defect-targeted with probability 0.4.
        bad = np.flatnonzero(reach != full) if rng.random() < 0.4 else None
        if bad is not None and bad.size:
            u = int(bad[rng.randrange(bad.size)])
            blk = u // G
            l = rng.randrange(d)
            if blk < k:
                i = blk
            else:
                i = pi[l].index(blk - k)
        else:
            l = rng.randrange(d)
            i = rng.randrange(k)
        old = S[l][i]
        new = rng.randrange(G)
        if new == old:
            continue
        S[l][i] = new
        _set_pair(nbr, k, G, Rcol, Rinv, l, i, pi[l][i], new)
        c2, r2 = evaluate()
        if c2 <= cost or rng.random() < math.exp(-(c2 - cost) / temp):
            cost, reach = c2, r2
            if cost < best_cost:
                best_cost, last = cost, t
        else:
            S[l][i] = old
            _set_pair(nbr, k, G, Rcol, Rinv, l, i, pi[l][i], old)

    if cost != 0:
        return None
    edges = []
    for u in range(k * G):
        for v in nbr[:, u]:
            edges.append((u, int(v)))
    return N, edges


