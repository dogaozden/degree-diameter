import itertools
import math
import random
import time

import lib

MAX_GROUPS_PER_ATTEMPT = 12   # semidirect groups tried per order N within one attempt
ITERS_SEMI = 600              # annealing steps per (group, connection set) try
ITERS_EXPLICIT = 1500         # annealing steps per restart for explicit groups
T_HOT = 1.5                   # initial annealing temperature (unreached-pair units)
T_COLD = 0.15                 # final annealing temperature


# ----------------------------------------------------------------------------
# Baseline families (fast, validated before use).
# ----------------------------------------------------------------------------

def _best_pg(d):
    """Incidence graph of PG(2, q) for the largest prime power q with q + 1 <= d."""
    for q in range(d - 1, 1, -1):
        if lib.is_prime_power(q):
            return lib.projective_plane_incidence(q)
    return None


def _gq_w(q):
    """Incidence graph of points and lines of the generalized quadrangle W(q); diameter 4."""
    F = lib.GF(q)
    pts = [v for v in itertools.product(range(q), repeat=4)
           if any(v) and next(c for c in v if c) == 1]
    index = {v: i for i, v in enumerate(pts)}
    P = len(pts)

    def norm(v):
        c = next(x for x in v if x)
        inv = F.inv(c)
        return tuple(F.mul(inv, x) for x in v)

    def form(x, y):
        t = F.sub(F.mul(x[0], y[1]), F.mul(x[1], y[0]))
        return F.add(t, F.sub(F.mul(x[2], y[3]), F.mul(x[3], y[2])))

    covered = set()
    lines = []
    for i in range(P):
        x = pts[i]
        for j in range(i + 1, P):
            if (i, j) in covered:
                continue
            y = pts[j]
            if form(x, y) != 0:
                continue
            L = set()
            for a in range(q):
                for b in range(q):
                    if a == 0 and b == 0:
                        continue
                    v = tuple(F.add(F.mul(a, x[k]), F.mul(b, y[k])) for k in range(4))
                    if any(v):
                        L.add(index[norm(v)])
            L = sorted(L)
            lines.append(L)
            for p in L:
                for r in L:
                    if p < r:
                        covered.add((p, r))

    edges = []
    for j, L in enumerate(lines):
        for p in L:
            edges.append((p, P + j))
    return 2 * P, edges


def _best_gq(d):
    """W(q) for the largest prime power q with q + 1 <= d, restricted to small q for speed."""
    for q in range(min(d - 1, 5), 1, -1):
        if lib.is_prime_power(q):
            return _gq_w(q)
    return None


# ----------------------------------------------------------------------------
# Group tables. A group is a triple (N, T, invs): T[x][g] = x*g with identity 0,
# invs[g] = g^{-1}. Left multiplication is an automorphism of every bi-Cayley graph.
# ----------------------------------------------------------------------------

def _tables_from_perms(elems, index):
    """Multiplication table of a permutation group, where x*g = x composed with g."""
    N = len(elems)
    T = [[index[tuple(x[i] for i in g)] for g in elems] for x in elems]
    invs = [0] * N
    for a in range(N):
        row = T[a]
        for b in range(N):
            if row[b] == 0:
                invs[a] = b
                break
    return N, T, invs


def _closure_group(gens):
    """Group generated by permutation tuples gens, built by closure from the identity."""
    k = len(gens[0])
    ident = tuple(range(k))
    elems = [ident]
    index = {ident: 0}
    frontier = [ident]
    while frontier:
        nxt = []
        for x in frontier:
            for g in gens:
                y = tuple(x[i] for i in g)
                if y not in index:
                    index[y] = len(elems)
                    elems.append(y)
                    nxt.append(y)
        frontier = nxt
    return _tables_from_perms(elems, index)


def _pgl_gens(q, squares):
    """Generators of PGL(2, q), or PSL(2, q) when squares is True, acting on the projective line 0..q."""
    F = lib.GF(q)
    g = F.primitive_element()
    s = F.mul(g, g) if squares else g

    def mob(a, b, c, e):
        perm = []
        for t in range(q + 1):
            if t == q:
                img = q if c == 0 else F.mul(a, F.inv(c))
            else:
                num = F.add(F.mul(a, t), b)
                den = F.add(F.mul(c, t), e)
                img = q if den == 0 else F.mul(num, F.inv(den))
            perm.append(img)
        return tuple(perm)

    return [mob(1, 1, 0, 1), mob(s, 0, 0, 1), mob(0, F.neg(1), 1, 0)]


def _pgl(q, squares):
    return lambda: _closure_group(_pgl_gens(q, squares))


def _cyc_tables(k):
    T = [[(a + b) % k for b in range(k)] for a in range(k)]
    invs = [(-a) % k for a in range(k)]
    return k, T, invs


def _cyc(k):
    return lambda: _cyc_tables(k)


def _direct(G1, G2):
    """Direct product of two group tables; element (a, b) is coded as a*N2 + b."""
    N1, T1, I1 = G1
    N2, T2, I2 = G2
    N = N1 * N2
    T = [[0] * N for _ in range(N)]
    for a in range(N1):
        for b in range(N2):
            row = T[a * N2 + b]
            for c in range(N1):
                t1 = T1[a][c] * N2
                t2row = T2[b]
                base = c * N2
                for d2 in range(N2):
                    row[base + d2] = t1 + t2row[d2]
    invs = [I1[a] * N2 + I2[b] for a in range(N1) for b in range(N2)]
    return N, T, invs


def _dir(f1, f2):
    return lambda: _direct(f1(), f2())


def _semi_tables(m, k, r):
    N, mul, inv = lib.semidirect_group(m, k, r)
    T = [[mul(x, g) for g in range(N)] for x in range(N)]
    invs = [inv(g) for g in range(N)]
    return N, T, invs


def _explicit_groups():
    """Non-abelian and direct-product groups tried first: (expected order, factory, weight)."""
    pgl5 = _pgl(5, False)
    psl5 = _pgl(5, True)
    pgl7 = _pgl(7, False)
    psl7 = _pgl(7, True)
    return [
        (336, pgl7, 4),                    # PGL(2,7): the main hope to beat 336
        (336, _dir(psl7, _cyc(2)), 2),
        (300, _dir(psl5, _cyc(5)), 1),
        (240, _dir(pgl5, _cyc(2)), 1),
        (240, _dir(psl5, _cyc(4)), 1),
        (180, _dir(psl5, _cyc(3)), 1),
        (168, psl7, 1),
        (120, pgl5, 1),
        (120, _dir(psl5, _cyc(2)), 1),
        (60, psl5, 1),
    ]


# ----------------------------------------------------------------------------
# Bi-Cayley search: vertices A_x, B_y (x, y in G), edges A_x -- B_{x s} for s in S.
# Identity is WLOG in S. Sources A_0 and B_0 decide the diameter.
# ----------------------------------------------------------------------------

def _groups(N):
    """Semidirect parameters (m, k, r) with m*k = N, giving Z_m x|_r Z_k."""
    out = []
    for k in range(1, N + 1):
        if N % k:
            continue
        m = N // k
        for r in range(m):
            if math.gcd(r, m) == 1 and pow(r, k, m) == 1 % m:
                out.append((m, k, r))
    return out


def _unreached(N, T, invs, S, D):
    """Count (source, vertex) pairs not within distance D, for sources A_0 and B_0."""
    Sinv = [invs[g] for g in S]
    total = 0
    for src in (0, N):
        seen = bytearray(2 * N)
        seen[src] = 1
        count = 1
        frontier = [src]
        for _ in range(D):
            nxt = []
            for u in frontier:
                if u < N:
                    row = T[u]
                    for g in S:
                        v = N + row[g]
                        if not seen[v]:
                            seen[v] = 1
                            nxt.append(v)
                else:
                    row = T[u - N]
                    for h in Sinv:
                        v = row[h]
                        if not seen[v]:
                            seen[v] = 1
                            nxt.append(v)
            count += len(nxt)
            frontier = nxt
            if not frontier:
                break
        total += 2 * N - count
    return total


def _anneal(N, T, invs, d, D, rng, iters, deadline):
    """Simulated annealing over S = {0, s_1, ..., s_{d-1}} to zero unreached pairs."""
    S = [0] + rng.sample(range(1, N), d - 1)
    cur = _unreached(N, T, invs, S, D)
    for it in range(iters):
        if cur == 0:
            return S
        if time.monotonic() > deadline:
            break
        temp = T_HOT * (T_COLD / T_HOT) ** (it / iters)
        i = rng.randrange(1, d)
        c = rng.randrange(1, N)
        if c in S:
            continue
        S2 = S[:]
        S2[i] = c
        v = _unreached(N, T, invs, S2, D)
        if v <= cur or rng.random() < math.exp(-(v - cur) / temp):
            S, cur = S2, v
    if cur == 0:
        return S
    return None


def _search_group(N, T, invs, d, D, rng, iters, deadline):
    """Repeated annealing restarts on one fixed group until success or deadline."""
    while time.monotonic() < deadline:
        S = _anneal(N, T, invs, d, D, rng, iters, deadline)
        if S is not None:
            return S
    return None


def _attempt_semi(N, d, D, rng, deadline):
    """Try semidirect groups of order N until one yields a valid connection set."""
    groups = _groups(N)
    rng.shuffle(groups)
    for m, k, r in groups[:MAX_GROUPS_PER_ATTEMPT]:
        if time.monotonic() > deadline:
            return None
        N2, T, invs = _semi_tables(m, k, r)
        S = _anneal(N2, T, invs, d, D, rng, ITERS_SEMI, deadline)
        if S is not None:
            return T, S
    return None


def build(d, D, seed, time_limit):
    start = time.monotonic()
    span = min(0.85 * time_limit, time_limit - 7.0)
    deadline = start + span
    rng = random.Random(seed)

    if d < 1 or D < 1:
        return 1, []

    best = (1, [])
    best_n = 1

    def consider(n, e):
        nonlocal best, best_n
        if n > best_n and lib.is_valid(n, e, d, D):
            best = (n, e)
            best_n = n

    # Record-matching case: incidence graph of PG(2, d-1).
    if D == 3 and lib.is_prime_power(d - 1):
        n, e = lib.projective_plane_incidence(d - 1)
        consider(n, e)
        return best

    if D >= 2:
        consider(*lib.haar_graph(d, range(d)))
    if D >= 3:
        pg = _best_pg(d)
        if pg is not None:
            consider(pg[0], pg[1])
    if D >= 4 and time.monotonic() < deadline:
        gq = _best_gq(d)
        if gq is not None:
            consider(gq[0], gq[1])

    if d < 2 or D < 2:
        return best

    Nmax = lib._moore_bound(d, D) // 2   # bi-Cayley graph has 2N vertices
    lo = max(d + 1, best_n // 2 + 1)
    if lo > Nmax:
        return best

    # Phase A: explicit non-abelian and direct-product groups, weighted budgets.
    phaseA_deadline = start + 0.5 * span
    entries = [(N, f, w) for (N, f, w) in _explicit_groups() if lo <= N <= Nmax]
    entries.sort(key=lambda t: -t[0])
    while entries and time.monotonic() < phaseA_deadline:
        wsum = sum(w for _, _, w in entries)
        N, f, w = entries.pop(0)
        now = time.monotonic()
        att = (phaseA_deadline - now) * w / wsum
        Nreal, T, invs = f()
        if Nreal != N:
            continue
        S = _search_group(N, T, invs, d, D, rng, ITERS_EXPLICIT, now + att)
        if S is not None:
            consider(2 * N, [(x, N + T[x][g]) for x in range(N) for g in S])
            break

    # Phase B: semidirect cyclic-plus-action groups, descending order, doubling budget.
    cands = set(range(max(d + 1, best_n // 2 + 1), Nmax + 1))
    budget = 0.3
    while time.monotonic() < deadline and cands:
        cands = {N for N in cands if 2 * N > best_n}
        if not cands:
            break
        success = False
        for N in sorted(cands, reverse=True):
            now = time.monotonic()
            if now >= deadline:
                break
            res = _attempt_semi(N, d, D, rng, min(deadline, now + budget))
            if res is None:
                continue
            T, S = res
            consider(2 * N, [(x, N + T[x][g]) for x in range(N) for g in S])
            cands = {M for M in cands if M > N}
            success = True
            break
        if not success:
            budget *= 2

    if not lib.is_valid(best[0], best[1], d, D):
        return 1, []
    return best
