import itertools
import math
import random
import time

import lib


# ----------------------------------------------------------------------------
# Safe fallback families (used only as the starting incumbent).
# ----------------------------------------------------------------------------

def _moore(d, D):
    """Moore-type ceiling for bipartite graphs with max degree d and diameter D."""
    if D == 0 or d == 0:
        return 1
    if d == 1:
        return min(2, D + 1)
    if d == 2:
        return 2 * D
    return 2 * sum((d - 1) ** i for i in range(D))


def _best_pg(d):
    """Incidence graph of PG(2, q) for the largest prime power q with q + 1 <= d."""
    for q in range(d - 1, 1, -1):
        if lib.is_prime_power(q):
            return lib.projective_plane_incidence(q)
    return None


def _gq_w(q):
    """Incidence graph of points and lines of the generalized quadrangle W(q); diameter 4."""
    F = lib.GF(q)
    pts = [v for v in itertools.product(range(q), repeat=4)
           if any(v) and next(c for c in v if c) == 1]
    index = {v: i for i, v in enumerate(pts)}
    P = len(pts)

    def norm(v):
        c = next(x for x in v if x)
        inv = F.inv(c)
        return tuple(F.mul(inv, x) for x in v)

    def form(x, y):
        t = F.sub(F.mul(x[0], y[1]), F.mul(x[1], y[0]))
        return F.add(t, F.sub(F.mul(x[2], y[3]), F.mul(x[3], y[2])))

    covered = set()
    lines = []
    for i in range(P):
        x = pts[i]
        for j in range(i + 1, P):
            if (i, j) in covered:
                continue
            y = pts[j]
            if form(x, y) != 0:
                continue
            L = set()
            for a in range(q):
                for b in range(q):
                    if a == 0 and b == 0:
                        continue
                    v = tuple(F.add(F.mul(a, x[k]), F.mul(b, y[k])) for k in range(4))
                    if any(v):
                        L.add(index[norm(v)])
            L = sorted(L)
            lines.append(L)
            for p in L:
                for r in L:
                    if p < r:
                        covered.add((p, r))

    edges = []
    for j, L in enumerate(lines):
        for p in L:
            edges.append((p, P + j))
    return 2 * P, edges


def _best_gq(d):
    for q in range(min(d - 1, 9), 1, -1):
        if lib.is_prime_power(q):
            return _gq_w(q)
    return None


# ----------------------------------------------------------------------------
# Group pool. A group is a tuple (order, mul, inv) with identity coded as 0.
# Non-metacyclic groups come from permutation closures (PSL(2,7), PGL(2,7),
# A5, S4, A4) and from direct products with cyclic or metacyclic groups.
# ----------------------------------------------------------------------------

def _closure_group(gens):
    """Group generated by permutation tuples `gens`; element 0 is the identity."""
    n = len(gens[0])
    ident = tuple(range(n))
    els = [ident]
    idx = {ident: 0}
    frontier = [ident]
    while frontier:
        nxt = []
        for p in frontier:
            for g in gens:
                r = tuple(p[g[i]] for i in range(n))
                if r not in idx:
                    if len(els) > 400:
                        return None
                    idx[r] = len(els)
                    els.append(r)
                    nxt.append(r)
        frontier = nxt

    def mul(x, y):
        a = els[x]
        b = els[y]
        return idx[tuple(a[b[i]] for i in range(n))]

    def inv(x):
        a = els[x]
        q = [0] * n
        for i, ai in enumerate(a):
            q[ai] = i
        return idx[tuple(q)]

    return (len(els), mul, inv)


def _psl_gens():
    t = tuple((x + 1) % 7 for x in range(7)) + (7,)
    s = [0] * 8
    s[0] = 7
    s[7] = 0
    for x in range(1, 7):
        s[x] = (-pow(x, 5, 7)) % 7  # -1/x, since x^5 = x^{-1} in GF(7)
    return t, tuple(s)


_BASE_GENS = {
    "A5": [(1, 2, 0, 3, 4), (1, 2, 3, 4, 0)],
    "S4": [(1, 0, 2, 3), (1, 2, 3, 0)],
    "A4": [(1, 2, 0, 3), (1, 0, 3, 2)],
    "PSL27": list(_psl_gens()),
    "PGL27": list(_psl_gens()) + [tuple((3 * x) % 7 for x in range(7)) + (7,)],
}
_base_cache = {}


def _base_group(name):
    if name not in _base_cache:
        try:
            _base_cache[name] = _closure_group(_BASE_GENS[name])
        except Exception:
            _base_cache[name] = None
    return _base_cache[name]


def _prod(G1, G2):
    """Direct product; element (x1, x2) is coded x1*N2 + x2."""
    N1, m1, i1 = G1
    N2, m2, i2 = G2

    def mul(x, y):
        x1, x2 = divmod(x, N2)
        y1, y2 = divmod(y, N2)
        return m1(x1, y1) * N2 + m2(x2, y2)

    def inv(x):
        x1, x2 = divmod(x, N2)
        return i1(x1) * N2 + i2(x2)

    return (N1 * N2, mul, inv)


_BASE_NAMES = ("PGL27", "PSL27", "A5", "S4", "A4")


def _candidates(N, rng):
    out = [lib.cyclic_group(N)]
    for k2 in range(2, N + 1):
        if N % k2:
            continue
        m = N // k2
        if m < 2:
            continue
        rs = [r for r in range(1, m)
              if math.gcd(r, m) == 1 and pow(r, k2, m) == 1 % m]
        if not rs:
            continue
        rng.shuffle(rs)
        for r in rs[:3]:
            out.append(lib.semidirect_group(m, k2, r))
    for name in _BASE_NAMES:
        B = _base_group(name)
        if B is None:
            continue
        b = B[0]
        if N == b:
            out.append(B)
        elif N % b == 0 and N // b >= 2:
            out.append(_prod(B, lib.cyclic_group(N // b)))
    if len(out) > 40:
        out = rng.sample(out, 40)
    return out


# ----------------------------------------------------------------------------
# Bi-Cayley search: vertices a_g = g and b_g = N + g; darts s in S join
# a_g to b_{g s}. Left multiplication is an automorphism, so the diameter is
# at most D iff BFS from a_e and from b_e reaches everything within D.
# ----------------------------------------------------------------------------

_OFFSETS = [0, 0, 0, 1, 1, 2, 3]
_SLICE = 2.5


def _search(d, D, grp, end, rng):
    N, mul, inv = grp
    if N < d:
        return None
    pcache = {}

    def perm(s):
        p = pcache.get(s)
        if p is None:
            p = [mul(g, s) for g in range(N)]
            pcache[s] = p
        return p

    def unreached(Pf, Pb, src):
        seen = bytearray(2 * N)
        seen[src] = 1
        frontier = [src]
        cnt = 1
        for _ in range(D):
            nxt = []
            for u in frontier:
                if u < N:
                    for P in Pf:
                        v = N + P[u]
                        if not seen[v]:
                            seen[v] = 1
                            nxt.append(v)
                else:
                    h = u - N
                    for Q in Pb:
                        v = Q[h]
                        if not seen[v]:
                            seen[v] = 1
                            nxt.append(v)
            if not nxt:
                break
            cnt += len(nxt)
            frontier = nxt
        return 2 * N - cnt

    def cost(S):
        Pf = [perm(s) for s in S]
        Pb = [perm(inv(s)) for s in S]
        return unreached(Pf, Pb, 0) + unreached(Pf, Pb, N)

    S = rng.sample(range(N), d)
    cur = cost(S)
    if cur == 0:
        return S
    T = 1.0
    best_c = cur
    stall = 0
    it = 0
    while True:
        it += 1
        if (it & 31) == 0 and time.monotonic() > end:
            return None
        t = rng.randrange(d)
        x = rng.randrange(N)
        if x in S:
            continue
        newS = S[:]
        newS[t] = x
        c = cost(newS)
        if c <= cur or rng.random() < math.exp(-(c - cur) / T):
            S = newS
            cur = c
            if cur == 0:
                return S
            if cur < best_c:
                best_c = cur
                stall = 0
                continue
        stall += 1
        if stall > 3000:
            S = rng.sample(range(N), d)
            cur = cost(S)
            best_c = cur
            stall = 0
            if cur == 0:
                return S


def _edges(grp, S):
    N, mul, _ = grp
    E = []
    for s in S:
        for g in range(N):
            E.append((g, N + mul(g, s)))
    return 2 * N, E


# ----------------------------------------------------------------------------

def build(d, D, seed, time_limit):
    start = time.monotonic()
    budget = max(0.5, min(0.85 * time_limit, time_limit - 3.0))
    deadline = start + budget
    rng = random.Random(seed)

    if d < 1 or D < 1:
        return 1, []
    if D == 1:
        return 2, [(0, 1)]

    # Safe fallback: K_{d,d}, valid for D >= 2.
    best = lib.haar_graph(d, range(d))
    best_n = best[0]

    def consider(n, e):
        nonlocal best, best_n
        if n > best_n and lib.is_valid(n, e, d, D):
            best = (n, e)
            best_n = n

    try:
        if D >= 3:
            pg = _best_pg(d)
            if pg is not None:
                consider(pg[0], pg[1])
        if D >= 4:
            gq = _best_gq(d)
            if gq is not None:
                consider(gq[0], gq[1])
    except Exception:
        pass

    Nmax = _moore(d, D) // 2
    try:
        cache = {}

        def cands(N):
            if N not in cache:
                cache[N] = _candidates(N, rng)
            return cache[N]

        while time.monotonic() < deadline and best_n // 2 < Nmax:
            N = min(Nmax, best_n // 2 + 1 + rng.choice(_OFFSETS))
            groups = cands(N)
            if not groups:
                continue
            grp = rng.choice(groups)
            end = min(deadline, time.monotonic() + _SLICE)
            S = _search(d, D, grp, end, rng)
            if S is not None:
                n, e = _edges(grp, S)
                consider(n, e)
    except Exception:
        pass

    if not lib.is_valid(best[0], best[1], d, D):
        best = lib.haar_graph(d, range(d))
    return best
