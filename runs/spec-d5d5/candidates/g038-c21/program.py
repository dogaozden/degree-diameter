import itertools
import math
import random
import time

import lib

ITERS = 1500                  # annealing steps per (group, connection set) try
T_HOT = 1.5                   # initial annealing temperature (in unreached-pair units)
T_COLD = 0.15                 # final annealing temperature
BUDGET0 = 0.4                 # seconds per group in the first search round
MAX_CLOSURE = 400             # reject matrix groups larger than this


# ----------------------------------------------------------------------------
# Baseline families (fast, validated by lib.is_valid before use).
# ----------------------------------------------------------------------------

def _best_pg(d):
    """Incidence graph of PG(2, q) for the largest prime power q with q + 1 <= d."""
    for q in range(d - 1, 1, -1):
        if lib.is_prime_power(q):
            return lib.projective_plane_incidence(q)
    return None


def _gq_w(q):
    """Incidence graph of points and lines of the generalized quadrangle W(q); diameter 4."""
    F = lib.GF(q)
    pts = [v for v in itertools.product(range(q), repeat=4)
           if any(v) and next(c for c in v if c) == 1]
    index = {v: i for i, v in enumerate(pts)}
    P = len(pts)

    def norm(v):
        c = next(x for x in v if x)
        inv = F.inv(c)
        return tuple(F.mul(inv, x) for x in v)

    def form(x, y):
        t = F.sub(F.mul(x[0], y[1]), F.mul(x[1], y[0]))
        return F.add(t, F.sub(F.mul(x[2], y[3]), F.mul(x[3], y[2])))

    covered = set()
    lines = []
    for i in range(P):
        x = pts[i]
        for j in range(i + 1, P):
            if (i, j) in covered:
                continue
            y = pts[j]
            if form(x, y) != 0:
                continue
            L = set()
            for a in range(q):
                for b in range(q):
                    if a == 0 and b == 0:
                        continue
                    v = tuple(F.add(F.mul(a, x[k]), F.mul(b, y[k])) for k in range(4))
                    if any(v):
                        L.add(index[norm(v)])
            L = sorted(L)
            lines.append(L)
            for p in L:
                for r in L:
                    if p < r:
                        covered.add((p, r))

    edges = []
    for j, L in enumerate(lines):
        for p in L:
            edges.append((p, P + j))
    return 2 * P, edges


def _best_gq(d):
    """W(q) for the largest prime power q with q + 1 <= d, restricted to small q for speed."""
    for q in range(min(d - 1, 5), 1, -1):
        if lib.is_prime_power(q):
            return _gq_w(q)
    return None


# ----------------------------------------------------------------------------
# NEW ROUTINE: group tables from matrix-group closure.
#
# The parent only used metacyclic groups Z_m x| Z_k. Here a group is given by
# generator matrices over GF(p) (optionally taken projectively, i.e. modulo
# scalars). Closure under right multiplication by the generators enumerates the
# group, and we turn it into a multiplication table T[x][g] = index(x*g) with
# identity at index 0. Such groups (PSL(2,7) of order 168, PGL(2,7) of order 336,
# SL(2,5), PGL(2,5), ...) are non-metacyclic and are absent from the parent's
# search space. Direct products with Z_k extend the list.
# ----------------------------------------------------------------------------

def _closure(gens, mul, ident, norm, limit):
    """Enumerate the group generated by gens (elements are hashable, already normalised)."""
    elems = [ident]
    index = {ident: 0}
    frontier = [ident]
    while frontier:
        nxt = []
        for x in frontier:
            for g in gens:
                y = norm(mul(x, g))
                if y not in index:
                    if len(elems) >= limit:
                        return None
                    index[y] = len(elems)
                    elems.append(y)
                    nxt.append(y)
        frontier = nxt
    return elems, index


def _matrix_setup(p, gens_raw, projective):
    """Return (order, table_builder) for the group generated by 2x2 matrices over GF(p)."""
    def mul(A, B):
        return ((A[0] * B[0] + A[1] * B[2]) % p, (A[0] * B[1] + A[1] * B[3]) % p,
                (A[2] * B[0] + A[3] * B[2]) % p, (A[2] * B[1] + A[3] * B[3]) % p)

    if projective:
        def norm(M):
            c = next(x for x in M if x)
            inv = pow(c, p - 2, p)
            return tuple((x * inv) % p for x in M)
    else:
        def norm(M):
            return M

    ident = norm((1, 0, 0, 1))
    gens = [norm(tuple(x % p for x in g)) for g in gens_raw]
    cl = _closure(gens, mul, ident, norm, MAX_CLOSURE)
    if cl is None:
        return None
    elems, index = cl

    def table():
        N = len(elems)
        T = [[index[norm(mul(elems[x], elems[g]))] for g in range(N)] for x in range(N)]
        invs = [T[g].index(0) for g in range(N)]   # g^{-1} is the y with g*y = identity
        return N, T, invs

    return len(elems), table


def _times_cyclic(N, T, invs, k):
    """Direct product G x Z_k; element (x, c) is coded x*k + c, identity is 0."""
    M = N * k
    TT = [[0] * M for _ in range(M)]
    for x in range(N):
        for c in range(k):
            row = TT[x * k + c]
            for y in range(N):
                base = T[x][y] * k
                for e in range(k):
                    row[y * k + e] = base + (c + e) % k
    inv2 = [invs[x] * k + (-c) % k for x in range(N) for c in range(k)]
    return M, TT, inv2


def _make_semidirect(m, k, r):
    order, mul, inv = lib.semidirect_group(m, k, r)
    T = [[mul(x, g) for g in range(order)] for x in range(order)]
    invs = [inv(g) for g in range(order)]
    return order, T, invs


def _groups(N):
    """Return semidirect parameters (m, k, r) with m*k = N, giving Z_m x|_r Z_k."""
    out = []
    for k in range(1, N + 1):
        if N % k:
            continue
        m = N // k
        for r in range(m):
            if math.gcd(r, m) == 1 and pow(r, k, m) == 1 % m:
                out.append((m, k, r))
    return out


# Non-metacyclic base groups: (name, prime p, generators, projective?)
EXC_BASES = [
    ("PSL27", 7, [(1, 1, 0, 1), (0, 1, 6, 0), (1, 0, 1, 1)], True),
    ("PGL27", 7, [(1, 1, 0, 1), (3, 0, 0, 1), (0, 1, 1, 0)], True),
    ("SL25", 5, [(1, 1, 0, 1), (0, 4, 1, 0)], False),
    ("PSL25", 5, [(1, 1, 0, 1), (0, 1, 4, 0), (1, 0, 1, 1)], True),
    ("PGL25", 5, [(1, 1, 0, 1), (2, 0, 0, 1), (0, 1, 1, 0)], True),
]

_CACHE = {}


def _cached(key, fn):
    """Small cache so that large multiplication tables do not exhaust memory."""
    if key not in _CACHE:
        if len(_CACHE) > 24:
            _CACHE.clear()
        _CACHE[key] = fn()
    return _CACHE[key]


def _items(lo, hi):
    """Candidate groups with order in [lo, hi], as (order, maker) pairs; maker -> (N, T, invs).

    Exceptional (matrix-closure) groups come first, then semidirect products.
    Within each part, larger orders come first.
    """
    exc = []
    for name, p, gens, proj in EXC_BASES:
        setup = _matrix_setup(p, gens, proj)
        if setup is None:
            continue
        order, table = setup
        if order > hi:
            continue
        if lo <= order:
            exc.append((order, lambda name=name, table=table: _cached(("base", name), table)))
        for k in range(2, hi // order + 1):
            N2 = order * k
            if lo <= N2 <= hi:
                exc.append((N2, lambda name=name, k=k, table=table:
                            _cached(("prod", name, k),
                                    lambda: _times_cyclic(*_cached(("base", name), table), k))))
    exc.sort(key=lambda it: -it[0])

    sd = []
    for N in range(lo, hi + 1):
        for (m, k, r) in _groups(N):
            sd.append((N, lambda m=m, k=k, r=r:
                       _cached(("sd", m, k, r), lambda: _make_semidirect(m, k, r))))
    sd.sort(key=lambda it: -it[0])
    return exc + sd


# ----------------------------------------------------------------------------
# Bi-Cayley search over any finite group G of order N (given as a table).
#
# Vertices A_x and B_y (x, y in G). Edge A_x -- B_{x s} for s in S, |S| = d.
# Left multiplication is an automorphism, so eccentricities from A_0 and B_0
# decide the diameter. Identity is WLOG in S.
# ----------------------------------------------------------------------------

def _unreached(N, T, invs, S, D):
    """Count (source, vertex) pairs not within distance D, for sources A_0 and B_0."""
    Sinv = [invs[g] for g in S]
    total = 0
    for src in (0, N):
        seen = bytearray(2 * N)
        seen[src] = 1
        count = 1
        frontier = [src]
        for _ in range(D):
            nxt = []
            for u in frontier:
                if u < N:
                    row = T[u]
                    for g in S:
                        v = N + row[g]
                        if not seen[v]:
                            seen[v] = 1
                            nxt.append(v)
                else:
                    row = T[u - N]
                    for h in Sinv:
                        v = row[h]
                        if not seen[v]:
                            seen[v] = 1
                            nxt.append(v)
            count += len(nxt)
            frontier = nxt
            if not frontier:
                break
        total += 2 * N - count
    return total


def _anneal(N, T, invs, d, D, rng, iters, deadline):
    """Simulated annealing over S = {0, s_1, ..., s_{d-1}} to zero unreached pairs."""
    S = [0] + rng.sample(range(1, N), d - 1)
    cur = _unreached(N, T, invs, S, D)
    for it in range(iters):
        if cur == 0:
            return S
        if time.monotonic() > deadline:
            break
        temp = T_HOT * (T_COLD / T_HOT) ** (it / iters)
        i = rng.randrange(1, d)
        c = rng.randrange(1, N)
        if c in S:
            continue
        S2 = S[:]
        S2[i] = c
        v = _unreached(N, T, invs, S2, D)
        if v <= cur or rng.random() < math.exp(-(v - cur) / temp):
            S, cur = S2, v
    return S if cur == 0 else None


def _search(d, D, rng, deadline, consider):
    """Round-robin annealing over candidate groups, only keeping orders above the last success."""
    Nmax = lib._moore_bound(d, D) // 2
    if Nmax <= d:
        return
    items = _items(d + 1, Nmax)
    floor = d
    budget = BUDGET0
    while time.monotonic() < deadline:
        live = [it for it in items if it[0] > floor]
        if not live:
            return
        success = False
        for N_expected, make in live:
            now = time.monotonic()
            if now >= deadline:
                return
            try:
                N, T, invs = make()
            except Exception:
                continue
            if N != N_expected:
                continue
            S = _anneal(N, T, invs, d, D, rng, ITERS, min(deadline, now + budget))
            if S is not None:
                edges = [(x, N + T[x][g]) for x in range(N) for g in S]
                consider(2 * N, edges)
                floor = N
                success = True
                break
        if not success:
            budget *= 2


def build(d, D, seed, time_limit):
    start = time.monotonic()
    deadline = start + 0.8 * time_limit
    rng = random.Random(seed)

    if d < 1 or D < 1:
        return 1, []

    best = (1, [])
    best_n = 1

    def consider(n, e):
        nonlocal best, best_n
        if n > best_n and lib.is_valid(n, e, d, D):
            best = (n, e)
            best_n = n

    # Record-matching case: incidence graph of PG(2, d-1).
    if D == 3 and lib.is_prime_power(d - 1):
        n, e = lib.projective_plane_incidence(d - 1)
        consider(n, e)
        return best

    if D >= 2:
        consider(*lib.haar_graph(d, range(d)))
    if D >= 3:
        pg = _best_pg(d)
        if pg is not None:
            consider(pg[0], pg[1])
    if D >= 4 and time.monotonic() < deadline:
        gq = _best_gq(d)
        if gq is not None:
            consider(gq[0], gq[1])

    if d < 2 or D < 2:
        return best

    if time.monotonic() < deadline:
        _search(d, D, rng, deadline, consider)

    if not lib.is_valid(best[0], best[1], d, D):
        return 1, []
    return best
