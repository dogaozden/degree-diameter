import itertools
import math
import random
import time

import numpy as np

import lib

ITERS = 500                       # annealing steps per (group, connection set) try
PER_TRY = 3.0                     # seconds per group before moving on
MATRIX_PRIMES = (2, 3, 5, 7)
MATRIX_DIMS = (2, 3)
GENS_RANGE = (2, 3)
MATRIX_PROB = 0.7                 # chance of sampling a matrix group rather than a semidirect product


# ----------------------------------------------------------------------------
# Safe baseline families (unchanged from the parent; always checked by lib.is_valid).
# ----------------------------------------------------------------------------

def _best_pg(d):
    """Incidence graph of PG(2, q) for the largest prime power q with q + 1 <= d."""
    for q in range(d - 1, 1, -1):
        if lib.is_prime_power(q):
            return lib.projective_plane_incidence(q)
    return None


def _gq_w(q):
    """Incidence graph of points and lines of the generalized quadrangle W(q); diameter 4."""
    F = lib.GF(q)
    pts = [v for v in itertools.product(range(q), repeat=4)
           if any(v) and next(c for c in v if c) == 1]
    index = {v: i for i, v in enumerate(pts)}
    P = len(pts)

    def norm(v):
        c = next(x for x in v if x)
        inv = F.inv(c)
        return tuple(F.mul(inv, x) for x in v)

    def form(x, y):
        t = F.sub(F.mul(x[0], y[1]), F.mul(x[1], y[0]))
        return F.add(t, F.sub(F.mul(x[2], y[3]), F.mul(x[3], y[2])))

    covered = set()
    lines = []
    for i in range(P):
        x = pts[i]
        for j in range(i + 1, P):
            if (i, j) in covered:
                continue
            y = pts[j]
            if form(x, y) != 0:
                continue
            L = set()
            for a in range(q):
                for b in range(q):
                    if a == 0 and b == 0:
                        continue
                    v = tuple(F.add(F.mul(a, x[k]), F.mul(b, y[k])) for k in range(4))
                    if any(v):
                        L.add(index[norm(v)])
            L = sorted(L)
            lines.append(L)
            for p in L:
                for r in L:
                    if p < r:
                        covered.add((p, r))

    edges = []
    for j, L in enumerate(lines):
        for p in L:
            edges.append((p, P + j))
    return 2 * P, edges


def _best_gq(d):
    """W(q) for the largest prime power q with q + 1 <= d, restricted to small q for speed."""
    for q in range(min(d - 1, 5), 1, -1):
        if lib.is_prime_power(q):
            return _gq_w(q)
    return None


# ----------------------------------------------------------------------------
# New family: bi-Cayley graphs over NON-metacyclic finite matrix groups.
#
# A group G is generated by random small matrices over GF(p) (k = 2 or 3),
# so it can be PSL(2,7), SL(2,5), GL(3,2), ... which semidirect products miss.
# Vertices A_x, B_y (x, y in G); edge A_x -- B_{x s} for s in S, |S| = d.
# ----------------------------------------------------------------------------

def _ident(k):
    return tuple(1 if i % (k + 1) == 0 else 0 for i in range(k * k))


def _mat_mul(x, y, k, p):
    out = []
    for i in range(k):
        for j in range(k):
            s = 0
            for l in range(k):
                s += x[i * k + l] * y[l * k + j]
            out.append(s % p)
    return tuple(out)


def _closure(gens, k, p, cap):
    """Elements generated by gens (identity first); None if more than cap elements."""
    I = _ident(k)
    elems = [I]
    seen = {I: 0}
    frontier = [I]
    while frontier:
        nxt = []
        for x in frontier:
            for g in gens:
                y = _mat_mul(x, g, k, p)
                if y not in seen:
                    if len(elems) >= cap:
                        return None
                    seen[y] = len(elems)
                    elems.append(y)
                    nxt.append(y)
        frontier = nxt
    return elems


def _table(elems, k, p):
    """Multiplication table T[x][g] = index of x*g, and inverse list; None if not a group."""
    N = len(elems)
    E = np.array(elems, dtype=np.int64).reshape(N, k, k)
    prod = np.einsum('xij,yjl->xyil', E, E) % p
    w = (p ** np.arange(k * k)).astype(np.int64)
    pk = prod.reshape(N, N, k * k) @ w
    ek = E.reshape(N, k * k) @ w
    order = np.argsort(ek)
    sk = ek[order]
    pos = np.clip(np.searchsorted(sk, pk), 0, N - 1)
    if not np.array_equal(sk[pos], pk):
        return None
    T = order[pos]
    ident_mask = (T == 0)            # identity is index 0
    if not ident_mask.any(axis=1).all():
        return None                  # some element is not invertible
    invs = np.argmax(ident_mask, axis=1)
    return T.tolist(), invs.tolist()


def _random_matrix_group(Nmax, rng):
    k = rng.choice(MATRIX_DIMS)
    p = rng.choice(MATRIX_PRIMES)
    ng = rng.choice(GENS_RANGE)
    gens = [tuple(rng.randrange(p) for _ in range(k * k)) for _ in range(ng)]
    elems = _closure(gens, k, p, Nmax + 1)
    if elems is None or len(elems) < 2:
        return None
    tab = _table(elems, k, p)
    if tab is None:
        return None
    T, invs = tab
    return len(elems), T, invs


# ----------------------------------------------------------------------------
# Parent's metacyclic semidirect products, kept as a second family.
# ----------------------------------------------------------------------------

def _groups(N):
    """Return semidirect parameters (m, k, r) with m*k = N, giving Z_m x|_r Z_k."""
    out = []
    for k in range(1, N + 1):
        if N % k:
            continue
        m = N // k
        for r in range(m):
            if math.gcd(r, m) == 1 and pow(r, k, m) == 1 % m:
                out.append((m, k, r))
    return out


def _semidirect_group(Nlo, Nhi, rng):
    if Nhi < Nlo:
        return None
    N = rng.randint(Nlo, Nhi)
    cands = _groups(N)
    if not cands:
        return None
    m, k, r = rng.choice(cands)
    _, mul, inv = lib.semidirect_group(m, k, r)
    T = [[mul(x, g) for g in range(N)] for x in range(N)]
    invs = [inv(g) for g in range(N)]
    return N, T, invs


# ----------------------------------------------------------------------------
# Connection-set search (shared by both families).
# ----------------------------------------------------------------------------

def _unreached(N, T, invs, S, D):
    """Count (source, vertex) pairs not within distance D, for sources A_0 and B_0."""
    Sinv = [invs[g] for g in S]
    total = 0
    for src in (0, N):
        seen = bytearray(2 * N)
        seen[src] = 1
        count = 1
        frontier = [src]
        for _ in range(D):
            nxt = []
            for u in frontier:
                if u < N:
                    row = T[u]
                    for g in S:
                        v = N + row[g]
                        if not seen[v]:
                            seen[v] = 1
                            nxt.append(v)
                else:
                    row = T[u - N]
                    for h in Sinv:
                        v = row[h]
                        if not seen[v]:
                            seen[v] = 1
                            nxt.append(v)
            count += len(nxt)
            frontier = nxt
            if not frontier:
                break
        total += 2 * N - count
    return total


def _anneal(N, T, invs, d, D, rng, iters, deadline):
    """Simulated annealing over S = {0, s_1, ..., s_{d-1}} to zero unreached pairs."""
    S = [0] + rng.sample(range(1, N), d - 1)
    cur = _unreached(N, T, invs, S, D)
    for it in range(iters):
        if cur == 0:
            return S
        if time.monotonic() > deadline:
            break
        temp = max(0.05, 2.0 * (1.0 - it / iters))
        i = rng.randrange(1, d)
        c = rng.randrange(1, N)
        if c in S:
            continue
        S2 = S[:]
        S2[i] = c
        v = _unreached(N, T, invs, S2, D)
        if v <= cur or rng.random() < math.exp(-(v - cur) / temp):
            S, cur = S2, v
    return S if cur == 0 else None


def _search(d, D, rng, deadline, consider):
    """Repeatedly sample groups, keep only orders larger than the best found so far."""
    Nmax = lib._moore_bound(d, D) // 2   # bi-Cayley graph has 2N vertices
    best_N = d
    while time.monotonic() < deadline:
        if rng.random() < MATRIX_PROB:
            grp = _random_matrix_group(Nmax, rng)
        else:
            grp = _semidirect_group(max(d + 1, best_N + 1), Nmax, rng)
        if grp is None:
            continue
        N, T, invs = grp
        if N <= d or N <= best_N:
            continue
        try_deadline = min(deadline, time.monotonic() + PER_TRY)
        S = _anneal(N, T, invs, d, D, rng, ITERS, try_deadline)
        if S is None:
            continue
        edges = [(x, N + T[x][g]) for x in range(N) for g in S]
        consider(2 * N, edges)
        best_N = N


def build(d, D, seed, time_limit):
    start = time.monotonic()
    deadline = start + 0.8 * time_limit
    rng = random.Random(seed)

    if d < 1 or D < 1:
        return 1, []

    best = (1, [])

    def consider(n, e):
        nonlocal best
        if n > best[0] and lib.is_valid(n, e, d, D):
            best = (n, e)

    # Record-matching case: incidence graph of PG(2, d-1).
    if D == 3 and lib.is_prime_power(d - 1):
        n, e = lib.projective_plane_incidence(d - 1)
        consider(n, e)
        return best

    if D >= 2:
        consider(*lib.haar_graph(d, range(d)))
    if D >= 3:
        pg = _best_pg(d)
        if pg is not None:
            consider(pg[0], pg[1])
    if D >= 4 and time.monotonic() < deadline:
        gq = _best_gq(d)
        if gq is not None:
            consider(gq[0], gq[1])

    if d >= 2 and D >= 2 and time.monotonic() < deadline:
        _search(d, D, rng, deadline, consider)

    return best
