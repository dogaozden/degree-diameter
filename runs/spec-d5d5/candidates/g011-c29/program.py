# ----------------------------------------------------------------------------
# Constants.
# ----------------------------------------------------------------------------

MAX_CLOSURE = 400     # give up on a group whose closure exceeds this order
CLIMB_BASE = 40       # hill-climb steps in the first round-robin round
ANNEAL_BASE = 60      # annealing steps in the first multi-base round
_BIG = 10 ** 9


# ----------------------------------------------------------------------------
# Structured baselines (kept from the parent): PG(2,q) for D = 3 and the
# generalized quadrangle W(q) for D >= 4.
# ----------------------------------------------------------------------------

def _best_pg(d):
    """Incidence graph of PG(2, q) for the largest prime power q with q + 1 <= d."""
    for q in range(d - 1, 1, -1):
        if lib.is_prime_power(q):
            return lib.projective_plane_incidence(q)
    return None


def _gq_w(q):
    """Incidence graph of points and lines of the generalized quadrangle W(q); diameter 4."""
    F = lib.GF(q)
    pts = [v for v in itertools.product(range(q), repeat=4)
           if any(v) and next(c for c in v if c) == 1]
    index = {v: i for i, v in enumerate(pts)}
    P = len(pts)

    def norm(v):
        c = next(x for x in v if x)
        inv = F.inv(c)
        return tuple(F.mul(inv, x) for x in v)

    def form(x, y):
        t = F.sub(F.mul(x[0], y[1]), F.mul(x[1], y[0]))
        return F.add(t, F.sub(F.mul(x[2], y[3]), F.mul(x[3], y[2])))

    covered = set()
    lines = []
    for i in range(P):
        x = pts[i]
        for j in range(i + 1, P):
            if (i, j) in covered:
                continue
            y = pts[j]
            if form(x, y) != 0:
                continue
            L = set()
            for a in range(q):
                for b in range(q):
                    if a == 0 and b == 0:
                        continue
                    v = tuple(F.add(F.mul(a, x[k]), F.mul(b, y[k])) for k in range(4))
                    if any(v):
                        L.add(index[norm(v)])
            L = sorted(L)
            lines.append(L)
            for p in L:
                for r in L:
                    if p < r:
                        covered.add((p, r))

    edges = []
    for j, L in enumerate(lines):
        for p in L:
            edges.append((p, P + j))
    return 2 * P, edges


def _best_gq(d):
    """W(q) for the largest prime power q with q + 1 <= d, capped at q = 7 for speed."""
    for q in range(min(d - 1, 7), 1, -1):
        if lib.is_prime_power(q):
            return _gq_w(q)
    return None


# ----------------------------------------------------------------------------
# NEW: generic finite-group machinery. Groups are given by an identity, a
# multiplication on hashable elements and generators. Closure enumerates the
# group, and the multiplication table is indexed with identity = 0, so that
# any finite group (not only metacyclic ones) can drive a voltage lift.
# Direct products with cyclic groups give non-metacyclic groups such as
# A5 x Z_m, S4 x Z_m, GL(2,3) x Z_m, SL(2,5) x Z_m and SL(2,7), which the
# semidirect-product family cannot express.
# ----------------------------------------------------------------------------

def _closure(identity, gens, mul, cap):
    """Enumerate the group generated by gens, or return None if it exceeds cap."""
    elems = [identity]
    index = {identity: 0}
    i = 0
    while i < len(elems):
        x = elems[i]
        i += 1
        for g in gens:
            y = mul(x, g)
            if y not in index:
                if len(elems) >= cap:
                    return None
                index[y] = len(elems)
                elems.append(y)
    return elems, index


def _from_spec(spec):
    """Multiplication table (G, T, inv) of a group spec, with identity index 0; None if too big."""
    identity, mul, gens = spec
    res = _closure(identity, gens, mul, MAX_CLOSURE)
    if res is None:
        return None
    elems, index = res
    T = [[index[mul(a, b)] for b in elems] for a in elems]
    inv = [row.index(0) for row in T]
    return len(elems), T, inv


def _perm_spec(n, alt):
    """Symmetric group S_n, or alternating group A_n when alt is True."""
    ident = tuple(range(n))

    def mul(p, q):
        return tuple(p[x] for x in q)

    if alt:
        gens = []
        for i in range(n - 2):
            p = list(range(n))
            p[i] = i + 1
            p[i + 1] = i + 2
            p[i + 2] = i
            gens.append(tuple(p))
    else:
        t = list(range(n))
        t[0], t[1] = 1, 0
        gens = [tuple(t), tuple((x + 1) % n for x in range(n))]
    return ident, mul, gens


def _mat_mul(p):
    """Multiplication of 2x2 matrices (a,b,c,d) over Z_p."""
    def mul(x, y):
        a, b, c, d = x
        e, f, g, h = y
        return ((a * e + b * g) % p, (a * f + b * h) % p,
                (c * e + d * g) % p, (c * f + d * h) % p)
    return mul


def _sl_spec(p):
    """SL(2,p) generated by the elementary matrix and the order-4 element."""
    return (1, 0, 0, 1), _mat_mul(p), [(1, 1, 0, 1), (0, p - 1, 1, 0)]


def _gl23_spec():
    """GL(2,3) generated by two SL(2,3) generators and diag(2,1)."""
    return (1, 0, 0, 1), _mat_mul(3), [(1, 1, 0, 1), (0, 2, 1, 0), (2, 0, 0, 1)]


def _psl27_spec():
    """PSL(2,7) = SL(2,7)/{+-I}, with elements represented by the smaller of M and -M."""
    p = 7
    base = _mat_mul(p)

    def canon(z):
        nz = tuple((-t) % p for t in z)
        return min(z, nz)

    def mul(x, y):
        return canon(base(x, y))

    gens = [canon((1, 1, 0, 1)), canon((0, p - 1, 1, 0))]
    return canon((1, 0, 0, 1)), mul, gens


def _z_spec(m):
    """Cyclic group Z_m."""
    return 0, (lambda a, b: (a + b) % m), [1]


def _prod_spec(A, B):
    """Direct product of two group specs; elements are pairs."""
    ia, ma, ga = A
    ib, mb, gb = B

    def mul(x, y):
        return (ma(x[0], y[0]), mb(x[1], y[1]))

    gens = [(g, ib) for g in ga] + [(ia, g) for g in gb]
    return (ia, ib), mul, gens


def _meta_spec(m, k, r):
    """Metacyclic group Z_m x|_r Z_k from lib.semidirect_group, with elements coded as ints."""
    order, mul, _ = lib.semidirect_group(m, k, r)
    return 0, mul, [k, 1]          # code k = (1, 0) and code 1 = (0, 1) generate


def _S(n):
    return _perm_spec(n, False)


def _A(n):
    return _perm_spec(n, True)


