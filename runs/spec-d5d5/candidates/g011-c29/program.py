def _make_cand(G, thunk):
    """Lazily-built candidate: estimated order G and a builder for its table."""
    return {"G": G, "make": (lambda: _from_spec(thunk()))}


def _groups(N):
    """Semidirect parameters (m, k, r) with m*k = N, giving Z_m x|_r Z_k."""
    out = []
    for k in range(1, N + 1):
        if N % k:
            continue
        m = N // k
        for r in range(m):
            if math.gcd(r, m) == 1 and pow(r, k, m) == 1 % m:
                out.append((m, k, r))
    return out


def _meta_cands(rng):
    """One random non-abelian metacyclic group for each order in a fallback band."""
    out = []
    for N in (112, 120, 128, 144, 150, 160, 168):
        gs = [g for g in _groups(N) if g[1] >= 2 and g[0] >= 2]
        if gs:
            m, k, r = rng.choice(gs)
            out.append(_make_cand(N, lambda m=m, k=k, r=r: _meta_spec(m, k, r)))
    return out


def _tab_for(c):
    """Table of a candidate, built on first use; marks the candidate dead if it fails."""
    if "tab" not in c:
        try:
            c["tab"] = c["make"]()
        except Exception:
            c["tab"] = None
        if c["tab"] is None:
            c["dead"] = True
    return c.get("tab")


# ----------------------------------------------------------------------------
# Bi-Cayley hill climb over a general group table.
# Graph: A_x ~ B_{x s} for s in S. Left multiplication is an automorphism,
# so eccentricities from A_e and B_e decide diameter.
# ----------------------------------------------------------------------------

def _unr(G, T, inv, S, D):
    """Count vertex pairs (source, target) not within distance D from A_e and B_e."""
    Sinv = [inv[s] for s in S]
    total = 0
    for src in (0, G):
        seen = bytearray(2 * G)
        seen[src] = 1
        count = 1
        frontier = [src]
        for _ in range(D):
            nxt = []
            for u in frontier:
                if u < G:
                    row = T[u]
                    for s in S:
                        v = G + row[s]
                        if not seen[v]:
                            seen[v] = 1
                            nxt.append(v)
                else:
                    row = T[u - G]
                    for h in Sinv:
                        v = row[h]
                        if not seen[v]:
                            seen[v] = 1
                            nxt.append(v)
            count += len(nxt)
            frontier = nxt
            if not frontier:
                break
        total += 2 * G - count
    return total


def _climb(G, T, inv, d, D, rng, iters, deadline):
    """Hill-climb a connection set S (identity fixed WLOG) to zero unreached pairs."""
    S = [0] + rng.sample(range(1, G), d - 1)
    cur = _unr(G, T, inv, S, D)
    for _ in range(iters):
        if cur == 0 or time.monotonic() > deadline:
            break
        i = rng.randrange(1, d)
        c = rng.randrange(1, G)
        if c in S:
            continue
        S2 = S[:]
        S2[i] = c
        v = _unr(G, T, inv, S2, D)
        if v <= cur:
            S, cur = S2, v
    return S if cur == 0 else None


def _run_k1(cands, d, D, rng, deadline, B, consider, moore):
    """Round-robin bi-Cayley climbs over the candidate groups, doubling effort per round."""
    r = 0
    while time.monotonic() < deadline:
        live = [c for c in cands if not c.get("dead") and B["n"] < 2 * c["G"] <= moore]
        if not live:
            return
        iters = CLIMB_BASE * (1 << min(r, 6))
        for c in live:
            if time.monotonic() >= deadline:
                return
            tab = _tab_for(c)
            if tab is None:
                continue
            G, T, inv = tab
            if 2 * G <= B["n"] or 2 * G > moore or G - 1 < d - 1:
                continue
            S = _climb(G, T, inv, d, D, rng, iters, deadline)
            if S is not None:
                consider(2 * G, [(x, G + T[x][s]) for x in range(G) for s in S])
        r += 1


# ----------------------------------------------------------------------------
# Multi-base lifts over a general group table, annealed.
# Dart (i, j, s): A_{i,g} ~ B_{j, g s}. Each layer is a permutation of the
# k sources onto the k targets, so every vertex has degree d.
# ----------------------------------------------------------------------------

def _cost_t(k, G, D, darts, pms):
    """Number of (representative, vertex) pairs not reached within D. Zero means valid."""
    if len({(i, j, s) for i, j, s in darts}) < len(darts):
        return _BIG
    N = 2 * k * G
    adj = [[] for _ in range(N)]
    for (i, j, _s), pm in zip(darts, pms):
        ba = i * G
        bb = (k + j) * G
        for g in range(G):
            a = ba + g
            b = bb + pm[g]
            adj[a].append(b)
            adj[b].append(a)
    reps = [i * G for i in range(k)] + [(k + j) * G for j in range(k)]
    total = 0
    for src in reps:
        seen = bytearray(N)
        seen[src] = 1
        frontier = [src]
        count = 1
        for _ in range(D):
            nxt = []
            for u in frontier:
                for v in adj[u]:
                    if not seen[v]:
                        seen[v] = 1
                        nxt.append(v)
            count += len(nxt)
            frontier = nxt
            if not frontier:
                break
        total += N - count
    return total


def _edges_t(k, G, darts, pms):
    E = set()
    for (i, j, _s), pm in zip(darts, pms):
        for g in range(G):
            E.add((i * G + g, (k + j) * G + pm[g]))
    return 2 * k * G, sorted(E)


def _anneal_t(d, D, k, G, T, rng, deadline, iters):
    """Simulated annealing over voltages and per-layer target assignments."""
    darts = []
    for _ in range(d):
        p = rng.sample(range(k), k)
        for i in range(k):
            darts.append([i, p[i], rng.randrange(G)])
    pms = [[T[g][s] for g in range(G)] for _, _, s in darts]
    cost = _cost_t(k, G, D, darts, pms)

    T0 = max(1.0, 0.05 * cost) if cost < _BIG else 1.0
    T_end = 0.5
    decay = (T_end / T0) ** (1.0 / max(1, iters)) if T0 > T_end else 1.0
    temp = T0

    for _ in range(iters):
        if cost == 0 or time.monotonic() > deadline:
            break
        temp = max(T_end, temp * decay)
        if k == 1 or rng.random() < 0.7:
            idx = rng.randrange(len(darts))
            old_s = darts[idx][2]
            new_s = rng.randrange(G)
            if new_s == old_s:
                continue
            old_pm = pms[idx]
            darts[idx][2] = new_s
            pms[idx] = [T[g][new_s] for g in range(G)]
            c2 = _cost_t(k, G, D, darts, pms)
            if c2 <= cost or rng.random() < math.exp(-(c2 - cost) / temp):
                cost = c2
            else:
                darts[idx][2] = old_s
                pms[idx] = old_pm
        else:
            L = rng.randrange(d)
            a, b = rng.sample(range(k), 2)
            ia, ib = L * k + a, L * k + b
            darts[ia][1], darts[ib][1] = darts[ib][1], darts[ia][1]
            c2 = _cost_t(k, G, D, darts, pms)
            if c2 <= cost or rng.random() < math.exp(-(c2 - cost) / temp):
                cost = c2
            else:
                darts[ia][1], darts[ib][1] = darts[ib][1], darts[ia][1]

    if cost == 0:
        return _edges_t(k, G, darts, pms)
    return None


def _run_k2(cands, d, D, rng, deadline, B, consider, moore):
    """Round-robin two-base annealed lifts over the candidate groups."""
    r = 0
    while time.monotonic() < deadline:
        live = [c for c in cands if not c.get("dead") and B["n"] < 4 * c["G"] <= moore]
        if not live:
            return
        iters = ANNEAL_BASE * (1 << min(r, 5))
        for c in live:
            if time.monotonic() >= deadline:
                return
            tab = _tab_for(c)
            if tab is None:
                continue
            G, T, _ = tab
            if 4 * G <= B["n"] or 4 * G > moore:
                continue
            res = _anneal_t(d, D, 2, G, T, rng, deadline, iters)
            if res is not None:
                consider(res[0], res[1])
        r += 1


# ----------------------------------------------------------------------------
# Main entry point.
# ----------------------------------------------------------------------------

def build(d, D, seed, time_limit):
    start = time.monotonic()
    budget = max(0.5, min(0.85 * time_limit, time_limit - 3.0))
    deadline = start + budget
    rng = random.Random(seed)

    if d < 1 or D < 1:
        return 1, []
    if D == 1:
        return 2, [(0, 1)]

    # Safe fallback: K_{d,d} has diameter 2.
    base = lib.haar_graph(d, range(d))
    if D == 2:
        return base

    moore = lib._moore_bound(d, D)
    B = {"n": base[0], "e": base[1]}

    def consider(n, e):
        if n > B["n"] and lib.is_valid(n, e, d, D):
            B["n"], B["e"] = n, e

    if D == 3:
        pg = _best_pg(d)
        if pg is not None:
            consider(pg[0], pg[1])
    if D >= 4:
        gq = _best_gq(d)
        if gq is not None:
            consider(gq[0], gq[1])

    if d >= 2 and B["n"] < moore:
        k1 = [_make_cand(CATALOG[nm][0], CATALOG[nm][1]) for nm in K1_NAMES]
        k1 += _meta_cands(rng)
        k2 = [_make_cand(CATALOG[nm][0], CATALOG[nm][1]) for nm in K2_NAMES]

        # Single-base non-metacyclic and metacyclic lifts get the first 60% of the budget.
        _run_k1(k1, d, D, rng, start + 0.6 * budget, B, consider, moore)
        # Two-base annealed lifts over the remaining time.
        _run_k2(k2, d, D, rng, deadline, B, consider, moore)

    if not lib.is_valid(B["n"], B["e"], d, D):
        return base
    return B["n"], B["e"]
