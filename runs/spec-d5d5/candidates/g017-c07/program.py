import itertools
import math
import random
import time

import lib

T_HOT = 4.0        # initial annealing temperature (unreached-pair units, summed over sources)
T_COLD = 0.2       # final annealing temperature
SLICE = 3.0        # seconds per anneal attempt on one (base shape, group) pair
PRIMES = (3, 5, 7, 11)


# ----------------------------------------------------------------------------
# Safe baseline families (always validated before being returned).
# ----------------------------------------------------------------------------

def _best_pg(d):
    """Incidence graph of PG(2, q) for the largest prime power q with q + 1 <= d."""
    for q in range(d - 1, 1, -1):
        if lib.is_prime_power(q):
            return lib.projective_plane_incidence(q)
    return None


# ----------------------------------------------------------------------------
# Finite groups as multiplication tables. Identity is always index 0.
# ----------------------------------------------------------------------------

def _table(N, mul):
    """Return (N, T, inv) with T[x][y] = x*y and inv[x] the inverse of x."""
    T = [[mul(x, y) for y in range(N)] for x in range(N)]
    inv = [row.index(0) for row in T]
    return N, T, inv


def _groups(N):
    """Semidirect parameters (m, k, r) with m*k = N, giving Z_m x|_r Z_k."""
    out = []
    for k in range(1, N + 1):
        if N % k:
            continue
        m = N // k
        for r in range(m):
            if math.gcd(r, m) == 1 and pow(r, k, m) == 1 % m:
                out.append((m, k, r))
    return out


def _mm(x, y, p):
    """Multiply 2x2 matrices (as 4-tuples) over GF(p)."""
    a, b, c, d = x
    e, f, g, h = y
    return ((a * e + b * g) % p, (a * f + b * h) % p,
            (c * e + d * g) % p, (c * f + d * h) % p)


def _matrix_closure(p, rng, cap):
    """Subgroup of GL(2, p) generated by two random elements; None if larger than cap."""
    def rand_gl():
        while True:
            m = (rng.randrange(p), rng.randrange(p), rng.randrange(p), rng.randrange(p))
            if (m[0] * m[3] - m[1] * m[2]) % p:
                return m
    gens = [rand_gl(), rand_gl()]
    ident = (1, 0, 0, 1)
    elems = [ident]
    seen = {ident}
    i = 0
    while i < len(elems):
        x = elems[i]
        i += 1
        for g in gens:
            y = _mm(x, g, p)
            if y not in seen:
                seen.add(y)
                elems.append(y)
                if len(elems) > cap:
                    return None
    return elems, p


def _random_group(lo, hi, rng):
    """Return (N, T, inv) for a random group with lo <= N <= hi, or None."""
    for _ in range(60):
        r = rng.random()
        if r < 0.4:
            p = rng.choice(PRIMES)
            res = _matrix_closure(p, rng, hi)
            if res is None:
                continue
            elems, p = res
            if len(elems) < lo:
                continue
            idx = {e: i for i, e in enumerate(elems)}
            T = [[idx[_mm(x, y, p)] for y in elems] for x in elems]
            inv = [row.index(0) for row in T]
            return len(elems), T, inv
        elif r < 0.7:
            N = rng.randint(lo, hi)
            cand = _groups(N)
            if not cand:
                continue
            order, mul, _ = lib.semidirect_group(*rng.choice(cand))
            return _table(order, mul)
        else:
            N1 = rng.randint(2, 12)
            lo2 = max(2, -(-lo // N1))
            hi2 = hi // N1
            if lo2 > hi2:
                continue
            N2 = rng.randint(lo2, hi2)
            c1, c2 = _groups(N1), _groups(N2)
            if not c1 or not c2:
                continue
            o1, m1, _ = lib.semidirect_group(*rng.choice(c1))
            o2, m2, _ = lib.semidirect_group(*rng.choice(c2))

            def mul(x, y, o2=o2, m1=m1, m2=m2):
                x1, x2 = divmod(x, o2)
                y1, y2 = divmod(y, o2)
                return m1(x1, y1) * o2 + m2(x2, y2)

            return _table(o1 * o2, mul)
    return None


# ----------------------------------------------------------------------------
# Generalized voltage lifts: base graph with `a` A-vertices and `a` B-vertices,
# and d layers. Layer t joins A_i to B_{sig_t(i)} with voltage g_t, so the
# lift has vertices A_{i,x}, B_{j,x} (x in G) and edges A_{i,x} -- B_{j, x*g_t}.
# Every vertex has degree d (before deduplication), and the graph is bipartite.
# Vertex ids: A_{i,x} -> i*N + x, B_{j,x} -> (a+j)*N + x.
# ----------------------------------------------------------------------------

def _sinv(p):
    q = [0] * len(p)
    for i, v in enumerate(p):
        q[v] = i
    return q


def _cost(a, N, T, d, D, sig, siginv, g, ginv):
    """Total number of (source, vertex) pairs not within distance D over all 2a sources."""
    V = 2 * a * N
    aN = a * N
    total = 0
    sources = [i * N for i in range(a)] + [(a + j) * N for j in range(a)]
    rd = range(d)
    for src in sources:
        seen = bytearray(V)
        seen[src] = 1
        count = 1
        frontier = [src]
        for _ in range(D):
            nxt = []
            for u in frontier:
                if u < aN:
                    i, x = divmod(u, N)
                    row = T[x]
                    for t in rd:
                        v = (a + sig[t][i]) * N + row[g[t]]
                        if not seen[v]:
                            seen[v] = 1
                            nxt.append(v)
                else:
                    j, y = divmod(u - aN, N)
                    row = T[y]
                    for t in rd:
                        v = siginv[t][j] * N + row[ginv[t]]
                        if not seen[v]:
                            seen[v] = 1
                            nxt.append(v)
            count += len(nxt)
            if not nxt:
                break
            frontier = nxt
        total += V - count
    return total


def _anneal(a, N, T, inv, d, D, rng, deadline):
    """Anneal layer permutations and voltages until the lift has diameter <= D, or deadline."""
    sig = [rng.sample(range(a), a) for _ in range(d)]
    siginv = [_sinv(p) for p in sig]
    g = [rng.randrange(N) for _ in range(d)]
    ginv = [inv[x] for x in g]
    cur = _cost(a, N, T, d, D, sig, siginv, g, ginv)
    t0 = time.monotonic()
    span = max(1e-6, deadline - t0)
    while cur > 0:
        now = time.monotonic()
        if now >= deadline:
            return None
        frac = min(1.0, (now - t0) / span)
        temp = T_HOT * (T_COLD / T_HOT) ** frac
        t = rng.randrange(d)
        if a > 1 and rng.random() < 0.3:
            old_s, old_si = sig[t], siginv[t]
            p = rng.sample(range(a), a)
            sig[t], siginv[t] = p, _sinv(p)
            nv = _cost(a, N, T, d, D, sig, siginv, g, ginv)
            if nv <= cur or rng.random() < math.exp(-(nv - cur) / temp):
                cur = nv
            else:
                sig[t], siginv[t] = old_s, old_si
        else:
            old_g, old_gi = g[t], ginv[t]
            ng = rng.randrange(N)
            g[t], ginv[t] = ng, inv[ng]
            nv = _cost(a, N, T, d, D, sig, siginv, g, ginv)
            if nv <= cur or rng.random() < math.exp(-(nv - cur) / temp):
                cur = nv
            else:
                g[t], ginv[t] = old_g, old_gi
    return sig, g


def _edges(a, N, T, d, sig, g):
    """Edge list of the lift (deduplicated)."""
    s = set()
    for t in range(d):
        for i in range(a):
            j = sig[t][i]
            for x in range(N):
                s.add((i * N + x, (a + j) * N + T[x][g[t]]))
    return list(s)


def build(d, D, seed, time_limit):
    start = time.monotonic()
    deadline = start + max(1.0, 0.8 * time_limit - 1.5)
    rng = random.Random(seed)

    if d < 1 or D < 1:
        return 1, []

    best = [1, []]

    def consider(n, e):
        if n > best[0] and lib.is_valid(n, e, d, D):
            best[0] = n
            best[1] = e

    # Exact record family for D = 3.
    if D == 3 and d >= 2 and lib.is_prime_power(d - 1):
        n, e = lib.projective_plane_incidence(d - 1)
        consider(n, e)
        return best[0], best[1]

    if D >= 2 and d >= 2:
        consider(*lib.haar_graph(d, range(d)))
    if D >= 3:
        pg = _best_pg(d)
        if pg is not None:
            consider(pg[0], pg[1])

    if d < 2 or D < 2:
        return best[0], best[1]

    moore = lib._moore_bound(d, D)
    choices = [1, 2, 2, 3, 3, 4]

    while time.monotonic() < deadline:
        cur_n = best[0]
        a = rng.choice(choices)
        lo = cur_n // (2 * a) + 1
        hi = moore // (2 * a)
        if lo > hi or lo < 2:
            if all(cur_n // (2 * x) + 1 > moore // (2 * x) for x in choices):
                break
            continue
        grp = _random_group(lo, hi, rng)
        if grp is None:
            continue
        N, T, inv = grp
        if N < lo or N > hi:
            continue
        attempt_deadline = min(deadline, time.monotonic() + SLICE)
        res = _anneal(a, N, T, inv, d, D, rng, attempt_deadline)
        if res is not None:
            sig, g = res
            consider(2 * a * N, _edges(a, N, T, d, sig, g))

    if not lib.is_valid(best[0], best[1], d, D):
        return 1, []
    return best[0], best[1]
