import itertools
import math
import random
import time

import lib

ITERS = 6000          # annealing steps per attempt
SEMI_LIMIT = 60       # semidirect-product candidates kept in the pool
CACHE_LIMIT = 6       # group multiplication tables kept in memory


# ----------------------------------------------------------------------------
# Baseline families (fast, always valid when they pass lib.is_valid).
# ----------------------------------------------------------------------------

def _best_pg(d):
    """Incidence graph of PG(2, q) for the largest prime power q with q + 1 <= d."""
    for q in range(d - 1, 1, -1):
        if lib.is_prime_power(q):
            return lib.projective_plane_incidence(q)
    return None


def _gq_w(q):
    """Incidence graph of points and lines of the generalized quadrangle W(q); diameter 4."""
    F = lib.GF(q)
    pts = [v for v in itertools.product(range(q), repeat=4)
           if any(v) and next(c for c in v if c) == 1]
    index = {v: i for i, v in enumerate(pts)}
    P = len(pts)

    def norm(v):
        c = next(x for x in v if x)
        inv = F.inv(c)
        return tuple(F.mul(inv, x) for x in v)

    def form(x, y):
        t = F.sub(F.mul(x[0], y[1]), F.mul(x[1], y[0]))
        return F.add(t, F.sub(F.mul(x[2], y[3]), F.mul(x[3], y[2])))

    covered = set()
    lines = []
    for i in range(P):
        x = pts[i]
        for j in range(i + 1, P):
            if (i, j) in covered:
                continue
            y = pts[j]
            if form(x, y) != 0:
                continue
            L = set()
            for a in range(q):
                for b in range(q):
                    if a == 0 and b == 0:
                        continue
                    v = tuple(F.add(F.mul(a, x[k]), F.mul(b, y[k])) for k in range(4))
                    if any(v):
                        L.add(index[norm(v)])
            L = sorted(L)
            lines.append(L)
            for p in L:
                for r in L:
                    if p < r:
                        covered.add((p, r))

    edges = []
    for j, L in enumerate(lines):
        for p in L:
            edges.append((p, P + j))
    return 2 * P, edges


def _best_gq(d):
    """W(q) for the largest prime power q with q + 1 <= d, restricted to small q for speed."""
    for q in range(min(d - 1, 5), 1, -1):
        if lib.is_prime_power(q):
            return _gq_w(q)
    return None


# ----------------------------------------------------------------------------
# Permutation groups. Each group is a list of generators acting on n points.
# Elements are enumerated by closure, so non-abelian groups are available:
# PSL(2,7), PGL(2,7), A5, S5, S4, AGL(1,p), and direct products with cyclic groups.
# ----------------------------------------------------------------------------

def _perm_mul(a, b):
    """(a*b)(i) = a[b[i]]."""
    return tuple(a[i] for i in b)


def _perm_inv(g):
    inv = [0] * len(g)
    for i, x in enumerate(g):
        inv[x] = i
    return tuple(inv)


def _closure(gens, npts, cap):
    """Enumerate the group generated by gens. Identity is element 0. None if more than cap-1 elements."""
    ident = tuple(range(npts))
    elems = [ident]
    index = {ident: 0}
    frontier = [ident]
    while frontier:
        nxt = []
        for e in frontier:
            for g in gens:
                h = _perm_mul(e, g)
                if h not in index:
                    if len(elems) >= cap:
                        return None
                    index[h] = len(elems)
                    elems.append(h)
                    nxt.append(h)
        frontier = nxt
    return elems, index


def _cycle(n, cyc):
    p = list(range(n))
    L = len(cyc)
    for i in range(L):
        p[cyc[i]] = cyc[(i + 1) % L]
    return tuple(p)


def _cyc(k):
    if k < 2:
        return (k, [])
    return (k, [_cycle(k, list(range(k)))])


def _sym(n):
    return (n, [_cycle(n, [0, 1]), _cycle(n, list(range(n)))])


def _alt5():
    return (5, [_cycle(5, [0, 1, 2]), _cycle(5, [2, 3, 4])])


def _dprod(A, B):
    """Direct product of two permutation groups acting on disjoint point sets."""
    na, ga = A
    nb, gb = B
    gens = [tuple(g) + tuple(range(na, na + nb)) for g in ga]
    gens += [tuple(range(na)) + tuple(na + x for x in g) for g in gb]
    return (na + nb, gens)


def _primroot(p):
    fac = []
    m = p - 1
    q = 2
    while q * q <= m:
        if m % q == 0:
            fac.append(q)
            while m % q == 0:
                m //= q
        q += 1
    if m > 1:
        fac.append(m)
    for g in range(2, p):
        if all(pow(g, (p - 1) // f, p) != 1 for f in fac):
            return g
    return 1


def _agl1(p):
    """Affine group x -> a x + b over GF(p), order p(p-1)."""
    g = _primroot(p)
    t = tuple((x + 1) % p for x in range(p))
    m = tuple((g * x) % p for x in range(p))
    return (p, [t, m])


def _psl2(p, pgl=False):
    """PSL(2,p) (or PGL(2,p)) acting on the projective line; point p is infinity."""
    INF = p
    t = tuple([(x + 1) % p for x in range(p)] + [INF])
    s = []
    for x in range(p + 1):
        if x == INF:
            s.append(0)
        elif x == 0:
            s.append(INF)
        else:
            s.append((-pow(x, p - 2, p)) % p)
    gens = [t, tuple(s)]
    if pgl:
        n = next(a for a in range(2, p) if pow(a, (p - 1) // 2, p) == p - 1)
        gens.append(tuple([(n * x) % p for x in range(p)] + [INF]))
    return (p + 1, gens)


def _families():
    return [
        lambda: _agl1(17),                                   # 272
        lambda: _psl2(7),                                    # 168
        lambda: _psl2(7, True),                              # 336
        lambda: _dprod(_psl2(7), _cyc(2)),                   # 336
        lambda: _dprod(_agl1(13), _cyc(2)),                  # 312
        lambda: _dprod(_agl1(11), _cyc(2)),                  # 220
        lambda: _dprod(_agl1(11), _cyc(3)),                  # 330
        lambda: _dprod(_agl1(7), _cyc(5)),                   # 210
        lambda: _dprod(_agl1(7), _cyc(6)),                   # 252
        lambda: _dprod(_agl1(7), _cyc(7)),                   # 294
        lambda: _dprod(_agl1(7), _cyc(8)),                   # 336
        lambda: _dprod(_alt5(), _cyc(3)),                    # 180
        lambda: _dprod(_alt5(), _cyc(4)),                    # 240
        lambda: _dprod(_alt5(), _cyc(5)),                    # 300
        lambda: _dprod(_alt5(), _dprod(_cyc(2), _cyc(2))),   # 240
        lambda: _dprod(_sym(5), _cyc(2)),                    # 240
        lambda: _dprod(_sym(4), _cyc(7)),                    # 168
        lambda: _dprod(_sym(4), _cyc(8)),                    # 192
        lambda: _dprod(_sym(4), _cyc(10)),                   # 240
        lambda: _dprod(_sym(4), _cyc(12)),                   # 288
        lambda: _dprod(_sym(4), _cyc(13)),                   # 312
        lambda: _dprod(_sym(4), _dprod(_sym(3), _cyc(2))),   # 288
        lambda: _dprod(_sym(3), _dprod(_sym(3), _sym(3))),   # 216
        lambda: _dprod(_sym(4), _sym(3)),                    # 144
        lambda: _dprod(_psl2(5), _cyc(4)),                   # 240
    ]


def _groups(N):
    """Semidirect parameters (m, k, r) with m*k = N, giving Z_m x|_r Z_k."""
    out = []
    for k in range(1, N + 1):
        if N % k:
            continue
        m = N // k
        for r in range(m):
            if math.gcd(r, m) == 1 and pow(r, k, m) == 1 % m:
                out.append((m, k, r))
    return out


def _make_pool(lo, hi, rng):
    """Candidate groups with lo <= order <= hi, sorted by order ascending."""
    pool = []
    for make in _families():
        try:
            npts, gens = make()
            cl = _closure(gens, npts, hi + 1)
        except Exception:
            continue
        if cl is None:
            continue
        elems, index = cl
        N = len(elems)
        if lo <= N <= hi:
            pool.append((N, ('perm', elems, index)))
    semis = []
    for N in range(lo, hi + 1):
        for (m, k, r) in _groups(N):
            semis.append((N, ('semi', m, k, r)))
    rng.shuffle(semis)
    pool.extend(semis[:SEMI_LIMIT])
    pool.sort(key=lambda e: e[0])
    return pool


def _tables(N, spec):
    """Return (T, invs): T[x][g] = index of x*g, invs[g] = index of g^-1. Identity is index 0."""
    if spec[0] == 'perm':
        elems, index = spec[1], spec[2]
        T = [[index[_perm_mul(x, g)] for g in elems] for x in elems]
        invs = [index[_perm_inv(g)] for g in elems]
    else:
        _, m, k, r = spec
        _, mul, inv = lib.semidirect_group(m, k, r)
        T = [[mul(x, g) for g in range(N)] for x in range(N)]
        invs = [inv(g) for g in range(N)]
    return T, invs


# ----------------------------------------------------------------------------
# Bi-Cayley search. Vertices A_x and B_y (x, y in G), edge A_x -- B_{x s} for s in S.
# Left multiplication is an automorphism, so the diameter is decided by the
# eccentricities of A_0 and B_0. Identity is WLOG in S.
# ----------------------------------------------------------------------------

def _unreached(N, T, invs, S, D):
    """Count (source, vertex) pairs not within distance D, for sources A_0 and B_0."""
    Sinv = [invs[g] for g in S]
    total = 0
    for src in (0, N):
        seen = bytearray(2 * N)
        seen[src] = 1
        count = 1
        frontier = [src]
        for _ in range(D):
            nxt = []
            for u in frontier:
                if u < N:
                    row = T[u]
                    for g in S:
                        v = N + row[g]
                        if not seen[v]:
                            seen[v] = 1
                            nxt.append(v)
                else:
                    row = T[u - N]
                    for h in Sinv:
                        v = row[h]
                        if not seen[v]:
                            seen[v] = 1
                            nxt.append(v)
            count += len(nxt)
            frontier = nxt
            if not frontier:
                break
        total += 2 * N - count
    return total


def _anneal(N, T, invs, d, D, rng, iters, deadline):
    """Simulated annealing over S = {0, s_1, ..., s_{d-1}} to drive unreached pairs to zero."""
    S = [0] + rng.sample(range(1, N), d - 1)
    cur = _unreached(N, T, invs, S, D)
    for it in range(iters):
        if cur == 0:
            return S
        if time.monotonic() > deadline:
            break
        temp = max(0.3, 3.0 * (1.0 - it / iters))
        i = rng.randrange(1, d)
        c = rng.randrange(1, N)
        if c in S:
            continue
        S2 = S[:]
        S2[i] = c
        v = _unreached(N, T, invs, S2, D)
        if v <= cur or rng.random() < math.exp(-(v - cur) / temp):
            S, cur = S2, v
    return S if cur == 0 else None


