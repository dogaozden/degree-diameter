def build(d, D, seed, time_limit):
    start = time.monotonic()
    deadline = start + max(1.0, min(0.8 * time_limit, time_limit - 3.0))
    rng = random.Random(seed)

    if d < 1 or D < 1:
        return 1, []

    best = (1, [])
    best_n = 1

    def consider(n, e):
        nonlocal best, best_n
        if n > best_n and lib.is_valid(n, e, d, D):
            best = (n, e)
            best_n = n

    # Record-matching case: incidence graph of PG(2, d-1).
    if D == 3 and lib.is_prime_power(d - 1):
        n, e = lib.projective_plane_incidence(d - 1)
        consider(n, e)
        return best

    # Safe baselines.
    try:
        if D >= 2:
            consider(*lib.haar_graph(d, range(d)))
        if D >= 3:
            pg = _best_pg(d)
            if pg is not None:
                consider(pg[0], pg[1])
        if D >= 4 and time.monotonic() < deadline:
            gq = _best_gq(d)
            if gq is not None:
                consider(gq[0], gq[1])
    except Exception:
        pass

    if d < 2 or D < 2:
        return best if lib.is_valid(best[0], best[1], d, D) else (1, [])

    # Bold search: bi-Cayley graphs over non-abelian permutation groups,
    # plus semidirect products. Order ladder: each success raises the floor.
    try:
        Nmax = lib._moore_bound(d, D) // 2
        lo = max(d + 1, best_n // 2 + 1)
        hi = Nmax
        if lo <= hi:
            pool = _make_pool(lo, hi, rng)
            cache = {}
            floor = best_n // 2
            budget = 0.5
            while time.monotonic() < deadline:
                pool = [e for e in pool if e[0] > floor]
                if not pool:
                    break
                success = False
                for entry in pool:
                    now = time.monotonic()
                    if now >= deadline:
                        break
                    N, spec = entry
                    key = id(spec)
                    if key not in cache:
                        if len(cache) >= CACHE_LIMIT:
                            cache.clear()
                        cache[key] = _tables(N, spec)
                    T, invs = cache[key]
                    S = _anneal(N, T, invs, d, D, rng, ITERS,
                                min(deadline, now + budget))
                    if S is not None:
                        edges = [(x, N + T[x][g]) for x in range(N) for g in S]
                        consider(2 * N, edges)
                        floor = max(floor, N)
                        success = True
                        break
                if not success:
                    budget *= 1.5
    except Exception:
        pass

    if not lib.is_valid(best[0], best[1], d, D):
        return 1, []
    return best
