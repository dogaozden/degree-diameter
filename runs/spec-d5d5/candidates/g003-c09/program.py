import itertools
import math
import random
import time

import lib


# ----------------------------------------------------------------------------
# Structured baselines (safe fallbacks), kept from the parent.
# ----------------------------------------------------------------------------

def _moore(d, D):
    """Moore-type bound for bipartite graphs with max degree d and diameter D."""
    if D == 0 or d == 0:
        return 1
    if d == 1:
        return min(2, D + 1)
    if d == 2:
        return 2 * D
    return 2 * sum((d - 1) ** i for i in range(D))


def _best_pg(d):
    """Incidence graph of PG(2, q) for the largest prime power q with q + 1 <= d."""
    for q in range(d - 1, 1, -1):
        if lib.is_prime_power(q):
            return lib.projective_plane_incidence(q)
    return None


def _gq_w(q):
    """Incidence graph of points and lines of the generalized quadrangle W(q); diameter 4."""
    F = lib.GF(q)
    pts = [v for v in itertools.product(range(q), repeat=4)
           if any(v) and next(c for c in v if c) == 1]
    index = {v: i for i, v in enumerate(pts)}
    P = len(pts)

    def norm(v):
        c = next(x for x in v if x)
        inv = F.inv(c)
        return tuple(F.mul(inv, x) for x in v)

    def form(x, y):
        t = F.sub(F.mul(x[0], y[1]), F.mul(x[1], y[0]))
        return F.add(t, F.sub(F.mul(x[2], y[3]), F.mul(x[3], y[2])))

    covered = set()
    lines = []
    for i in range(P):
        x = pts[i]
        for j in range(i + 1, P):
            if (i, j) in covered:
                continue
            y = pts[j]
            if form(x, y) != 0:
                continue
            L = set()
            for a in range(q):
                for b in range(q):
                    if a == 0 and b == 0:
                        continue
                    v = tuple(F.add(F.mul(a, x[k]), F.mul(b, y[k])) for k in range(4))
                    if any(v):
                        L.add(index[norm(v)])
            L = sorted(L)
            lines.append(L)
            for p in L:
                for r in L:
                    if p < r:
                        covered.add((p, r))

    edges = []
    for j, L in enumerate(lines):
        for p in L:
            edges.append((p, P + j))
    return 2 * P, edges


def _best_gq(d):
    """W(q) for the largest prime power q with q + 1 <= d, restricted to small q for speed."""
    for q in range(min(d - 1, 9), 1, -1):
        if lib.is_prime_power(q):
            return _gq_w(q)
    return None


# ----------------------------------------------------------------------------
# NEW helper 1: permutation groups from generators (closure + multiplication
# table). Lets us use non-cyclic, non-metabelian groups such as PSL(2,7) of
# order 168 and PGL(2,7) of order 336, acting on the projective line PG(1,7).
# ----------------------------------------------------------------------------

def _pgl_gens(scale):
    """Generators of PGL(2,7) (scale=3, nonsquare) or PSL(2,7) (scale=2, square)
    acting on PG(1,7) = {0..6, 7(=infinity)}: x+1, scale*x, -1/x."""
    shift = tuple((v + 1) % 7 if v < 7 else 7 for v in range(8))
    scl = tuple((scale * v) % 7 if v < 7 else 7 for v in range(8))
    inv = tuple(7 if v == 0 else (0 if v == 7 else (-pow(v, 5, 7)) % 7) for v in range(8))
    return [shift, scl, inv]


def _perm_group(gens, cap=400):
    """Return (order, table) for the permutation group generated by gens, identity = index 0,
    table[x][y] = index of elems[x] o elems[y]. Returns None if the group exceeds cap."""
    n = len(gens[0])
    ident = tuple(range(n))
    elems = [ident]
    index = {ident: 0}
    frontier = [ident]
    while frontier:
        nxt = []
        for x in frontier:
            for g in gens:
                y = tuple(g[v] for v in x)
                if y not in index:
                    if len(elems) >= cap:
                        return None
                    index[y] = len(elems)
                    elems.append(y)
                    nxt.append(y)
        frontier = nxt
    table = [[index[tuple(a[v] for v in b)] for b in elems] for a in elems]
    return len(elems), table


def _group_table(order, mul):
    return [[mul(x, y) for y in range(order)] for x in range(order)]


def _random_group(G, rng):
    """Random group of order G: semidirect Z_m x| Z_k2 (possibly direct) with random action r."""
    opts = [k2 for k2 in range(1, 13) if G % k2 == 0 and G // k2 >= 2]
    if not opts:
        return None
    k2 = rng.choice(opts)
    m = G // k2
    rs = [1] + [r for r in range(2, m) if math.gcd(r, m) == 1 and pow(r, k2, m) == 1 % m]
    r = rng.choice(rs)
    order, mul, _ = lib.semidirect_group(m, k2, r)
    return order, _group_table(order, mul)


# ----------------------------------------------------------------------------
# NEW helper 2: fast cost for group-lifted bipartite graphs. Vertex-transitivity
# within each base fiber (left translation by the group) means BFS from one
# representative per fiber (2k BFS runs) decides the diameter exactly.
# Cost = total number of (representative, vertex) pairs at distance > D.
# ----------------------------------------------------------------------------

def _cost(k, G, T, darts, D):
    N = 2 * k * G
    adj = [[] for _ in range(N)]
    for i, j, s in darts:
        base_a = i * G
        base_b = (k + j) * G
        for x in range(G):
            a = base_a + x
            b = base_b + T[x][s]
            adj[a].append(b)
            adj[b].append(a)
    total = 0
    for src in [i * G for i in range(k)] + [(k + j) * G for j in range(k)]:
        seen = bytearray(N)
        seen[src] = 1
        frontier = [src]
        cnt = 1
        for _ in range(D):
            nxt = []
            for u in frontier:
                for v in adj[u]:
                    if not seen[v]:
                        seen[v] = 1
                        nxt.append(v)
            if not nxt:
                break
            cnt += len(nxt)
            frontier = nxt
        total += N - cnt
    return total


def _apply(darts, S, changes):
    for idx, _ in changes:
        S.discard(darts[idx])
    for idx, t in changes:
        darts[idx] = t
        S.add(t)


def _group_sa(d, D, k, G, T, rng, deadline):
    """Anneal voltage darts (i, j, s) of a degree-d bi-Cayley lift until diameter <= D.
    Each base vertex has d darts (layers are permutations). Returns darts or None."""
    darts = []
    for _ in range(d):
        p = list(range(k))
        rng.shuffle(p)
        for i in range(k):
            darts.append((i, p[i], rng.randrange(G)))
    S = set(darts)
    if len(S) < len(darts):
        return None
    cur = _cost(k, G, T, darts, D)
    t0 = time.monotonic()
    span = max(1e-3, deadline - t0)
    m = len(darts)
    while cur > 0:
        now = time.monotonic()
        if now >= deadline:
            return None
        temp = 2.0 * (1.0 - (now - t0) / span) + 0.05
        if k > 1 and rng.random() < 0.3:
            # swap target base vertices of two darts (keeps all degrees)
            a, b = rng.sample(range(m), 2)
            ia, ja, sa = darts[a]
            ib, jb, sb = darts[b]
            if ja == jb:
                continue
            na = (ia, jb, sa)
            nb = (ib, ja, sb)
            if na in S or nb in S:
                continue
            changes = ((a, na), (b, nb))
        else:
            a = rng.randrange(m)
            ia, ja, sa = darts[a]
            ns = rng.randrange(G)
            if ns == sa:
                continue
            na = (ia, ja, ns)
            if na in S:
                continue
            changes = ((a, na),)
        olds = tuple((idx, darts[idx]) for idx, _ in changes)
        _apply(darts, S, changes)
        new = _cost(k, G, T, darts, D)
        delta = new - cur
        if delta <= 0 or rng.random() < math.exp(-delta / temp):
            cur = new
        else:
            _apply(darts, S, olds)
    return darts


# ----------------------------------------------------------------------------
# Entry point.
# ----------------------------------------------------------------------------

def build(d, D, seed, time_limit):
    start = time.monotonic()
    budget = max(1.0, min(0.85 * time_limit, time_limit - 4.0))
    deadline = start + budget
    rng = random.Random(seed)

    if d < 1 or D < 1:
        return 1, []
    if D == 1 or d == 1:
        return 2, [(0, 1)]

    # Safe fallback: K_{d,d} has diameter 2.
    best = lib.haar_graph(d, range(d))
    best_n = best[0]
    moore = _moore(d, D)

    def consider(n, e):
        nonlocal best, best_n
        if n > best_n and lib.is_valid(n, e, d, D):
            best = (n, e)
            best_n = n

    if d == 2:
        n = 2 * D  # the cycle C_{2D} is optimal here
        consider(n, [(i, (i + 1) % n) for i in range(n)])
        return best

    if D == 2 or best_n >= moore:
        return best

    if D >= 3:
        pg = _best_pg(d)
        if pg is not None:
            consider(pg[0], pg[1])
    if D >= 4:
        gq = _best_gq(d)
        if gq is not None:
            consider(gq[0], gq[1])
    if best_n >= moore:
        return best

    def try_group(order, T, k, sub_deadline):
        """Run group SA until found or sub_deadline; consider the lift if found."""
        try:
            while time.monotonic() < sub_deadline:
                darts = _group_sa(d, D, k, order, T, rng, sub_deadline)
                if darts is not None:
                    n, e = lib.group_lift(
                        2 * k,
                        [(i, k + j, s) for i, j, s in darts],
                        order,
                        lambda x, y: T[x][y],
                    )
                    consider(n, e)
                    return True
        except Exception:
            pass
        return False

    # Stage 1: exceptional non-abelian groups from PGL(2,7) and PSL(2,7) (k = 1).
    # PGL(2,7) would give 672 vertices; PSL(2,7) gives 336 (the record order).
    if D >= 3:
        for scale, share in ((3, 0.4), (2, 0.2)):
            if time.monotonic() >= deadline:
                break
            pg_group = _perm_group(_pgl_gens(scale))
            if pg_group is None:
                continue
            order, T = pg_group
            if 2 * order > moore or 2 * order <= best_n:
                continue
            sub = min(deadline, time.monotonic() + share * budget)
            try_group(order, T, 1, sub)

    # Stage 2: random groups of orders just above the current best, k base vertices.
    while time.monotonic() < deadline - 0.5:
        k = rng.choice([1, 1, 2, 2, 3])
        maxG = min(340, moore // (2 * k))
        lo = best_n // (2 * k) + 1
        if lo > maxG:
            continue
        G = min(maxG, lo + rng.randrange(0, max(2, lo // 5 + 1)))
        grp = _random_group(G, rng)
        if grp is None:
            continue
        order, T = grp
        sub = min(deadline, time.monotonic() + max(3.0, 0.2 * budget))
        try_group(order, T, k, sub)

    if not lib.is_valid(best[0], best[1], d, D):
        best = lib.haar_graph(d, range(d))
    return best
