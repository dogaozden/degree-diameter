import math
import random
import time

import lib


# ----------------------------------------------------------------------------
# Bi-Cayley graphs over finite groups.
#
# Vertices A_x and B_y for x, y in G, with A_x ~ B_{x*s} for s in S (|S| = d).
# Left translation is an automorphism, so the graph is valid (diameter <= D)
# iff every vertex is within distance D of A_0 and of B_0.
#
# Groups are non-abelian permutation groups (A5 x Z_k, S5 x Z_2, PSL(2,7),
# PGL(2,7), PSL(2,7) x Z_2) plus metacyclic semidirect products. Each group is
# searched with simulated annealing over S. Any found graph is checked with
# lib.is_valid before it is accepted.
# ----------------------------------------------------------------------------

ANNEAL_ITERS = 3000
SLICE_SECONDS = 6.0
PERM_PROB = 0.65


# ----------------------------------------------------------------------------
# Permutation groups.
# ----------------------------------------------------------------------------

def _prim_root(q):
    """Smallest primitive root modulo prime q."""
    for g in range(2, q):
        x, k = g, 1
        while x != 1:
            x = x * g % q
            k += 1
        if k == q - 1:
            return g
    raise ValueError("no primitive root")


def _mob_gens(q, square):
    """Generators of PSL(2,q) (square=True) or PGL(2,q) (square=False) acting on PG(1,q).

    Points are 0..q-1 plus infinity = q.
    """
    g = _prim_root(q)
    c = g * g % q if square else g
    t = tuple((x + 1) % q if x < q else q for x in range(q + 1))
    s = tuple(q if x == 0 else (0 if x == q else (-pow(x, q - 2, q)) % q)
              for x in range(q + 1))
    m = tuple((c * x) % q if x < q else q for x in range(q + 1))
    return [t, s, m], q + 1


def _with_cyclic(gens, npts, k):
    """Direct product with Z_k, realised as a k-cycle on k new points."""
    total = npts + k
    out = [tuple(list(g) + list(range(len(g), total))) for g in gens]
    if k > 1:
        cyc = list(range(total))
        for i in range(k):
            cyc[npts + i] = npts + (i + 1) % k
        out.append(tuple(cyc))
    return out, total


_A5 = [(1, 2, 0, 3, 4), (1, 2, 3, 4, 0)]
_S5 = [(1, 0, 2, 3, 4), (1, 2, 3, 4, 0)]

# (name, expected order, builder returning (generators, number of points))
_SPECS = [
    ("A5xZ3", 180, lambda: _with_cyclic(_A5, 5, 3)),
    ("A5xZ4", 240, lambda: _with_cyclic(_A5, 5, 4)),
    ("A5xZ5", 300, lambda: _with_cyclic(_A5, 5, 5)),
    ("S5xZ2", 240, lambda: _with_cyclic(_S5, 5, 2)),
    ("PSL27", 168, lambda: _mob_gens(7, True)),
    ("PSL27xZ2", 336, lambda: _with_cyclic(*_mob_gens(7, True), 2)),
    ("PGL27", 336, lambda: _mob_gens(7, False)),
    ("A5xZ2", 120, lambda: _with_cyclic(_A5, 5, 2)),
    ("S5", 120, lambda: (_S5, 5)),
]

_PERM_CACHE = {}


def _closure(gens, npts, cap=400):
    """Element list (identity first) and index dict of the group generated by gens."""
    ident = tuple(range(npts))
    elems = [ident]
    index = {ident: 0}
    i = 0
    while i < len(elems):
        e = elems[i]
        i += 1
        for g in gens:
            p = tuple(g[y] for y in e)
            if p not in index:
                if len(elems) >= cap:
                    return None
                index[p] = len(elems)
                elems.append(p)
    return elems, index


def _perm_table(spec):
    """(N, M, inv) multiplication table of a permutation group, cached. Identity is index 0."""
    name, _, make = spec
    if name in _PERM_CACHE:
        return _PERM_CACHE[name]
    gens, npts = make()
    tab = None
    res = _closure([tuple(g) for g in gens], npts)
    if res is not None:
        elems, index = res
        N = len(elems)
        M = []
        inv = [0] * N
        for i, ei in enumerate(elems):
            row = [0] * N
            for j, ej in enumerate(elems):
                k = index[tuple(ei[y] for y in ej)]
                row[j] = k
                if k == 0:
                    inv[i] = j
            M.append(row)
        tab = (N, M, inv)
    _PERM_CACHE[name] = tab
    return tab


def _metacyclic_table(limit, moore, rng):
    """Random metacyclic semidirect product of a random order just above limit."""
    lo = limit + 1
    hi = min(moore // 2, lo + max(6, lo // 10))
    if lo > hi:
        return None
    N = rng.randint(lo, hi)
    opts = []
    for k in range(1, N + 1):
        if N % k:
            continue
        m = N // k
        for r in range(m):
            if math.gcd(r, m) == 1 and pow(r, k, m) == 1 % m:
                opts.append((m, k, r))
    if not opts:
        return None
    m, k, r = rng.choice(opts)
    order, mul, inv = lib.semidirect_group(m, k, r)
    M = [[mul(x, y) for y in range(order)] for x in range(order)]
    iv = [inv(x) for x in range(order)]
    return order, M, iv


# ----------------------------------------------------------------------------
# Annealing over the connection set S.
# ----------------------------------------------------------------------------

def _unreached(N, M, inv, S, D):
    """Number of (source, vertex) pairs with source in {A_0, B_0} not within distance D."""
    Sinv = [inv[s] for s in S]
    N2 = 2 * N
    total = 0
    for src in (0, N):
        seen = bytearray(N2)
        seen[src] = 1
        count = 1
        frontier = [src]
        for _ in range(D):
            nxt = []
            for u in frontier:
                if u < N:
                    row = M[u]
                    for s in S:
                        v = N + row[s]
                        if not seen[v]:
                            seen[v] = 1
                            nxt.append(v)
                else:
                    row = M[u - N]
                    for h in Sinv:
                        v = row[h]
                        if not seen[v]:
                            seen[v] = 1
                            nxt.append(v)
            if not nxt:
                break
            count += len(nxt)
            frontier = nxt
        total += N2 - count
    return total


def _anneal(N, M, inv, d, D, rng, deadline, iters):
    """Simulated annealing over S (identity fixed in S). Returns valid S or None."""
    S = [0] + rng.sample(range(1, N), d - 1)
    cur = _unreached(N, M, inv, S, D)
    if cur == 0:
        return S
    best_S, best_v = S, cur
    T0 = 2.0 + 0.05 * cur
    for step in range(iters):
        if (step & 15) == 0 and time.monotonic() > deadline:
            break
        temp = T0 * (1.0 - step / iters) + 0.15
        i = rng.randrange(1, d)
        c = rng.randrange(1, N)
        if c in S:
            continue
        S2 = S[:]
        S2[i] = c
        v = _unreached(N, M, inv, S2, D)
        delta = v - cur
        if delta <= 0 or rng.random() < math.exp(-delta / temp):
            S, cur = S2, v
            if cur < best_v:
                best_v, best_S = cur, S
                if cur == 0:
                    return S
    return best_S if best_v == 0 else None


# ----------------------------------------------------------------------------
# Main entry point.
# ----------------------------------------------------------------------------

def build(d, D, seed, time_limit):
    start = time.monotonic()
    budget = max(0.5, min(0.85 * time_limit, time_limit - 3.0))
    deadline = start + budget
    rng = random.Random(seed)

    if d < 1 or D < 1:
        return 1, []
    if d == 1 or D == 1:
        return 2, [(0, 1)]

    # Safe fallback: K_{d,d}, diameter 2.
    best = lib.haar_graph(d, range(d))
    if D == 2:
        return best

    moore = lib._moore_bound(d, D)

    def consider(n, e):
        nonlocal best
        if n > best[0] and lib.is_valid(n, e, d, D):
            best = (n, e)

    # D = 3 with d - 1 a prime power: projective plane incidence graph (Moore-optimal).
    if D == 3 and d >= 3 and lib.is_prime_power(d - 1):
        n, e = lib.projective_plane_incidence(d - 1)
        consider(n, e)

    half = moore // 2
    while best[0] < moore and time.monotonic() < deadline:
        limit = best[0] // 2  # a bi-Cayley graph on group order N gives 2N vertices
        if limit + 1 > half:
            break
        slice_end = min(deadline, time.monotonic() + SLICE_SECONDS)

        tab = None
        if rng.random() < PERM_PROB:
            elig = [s for s in _SPECS if limit < s[1] <= half and s[1] >= d]
            if elig:
                tab = _perm_table(rng.choice(elig))
        if tab is None:
            tab = _metacyclic_table(limit, moore, rng)
        if tab is None:
            break

        N, M, inv = tab
        if N < d or N <= limit or 2 * N > moore:
            continue

        S = _anneal(N, M, inv, d, D, rng, slice_end, ANNEAL_ITERS)
        if S is not None:
            edges = [(x, N + M[x][s]) for x in range(N) for s in S]
            consider(2 * N, edges)

    if not lib.is_valid(best[0], best[1], d, D):
        best = lib.haar_graph(d, range(d))
    return best
