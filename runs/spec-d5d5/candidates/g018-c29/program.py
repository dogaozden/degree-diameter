import math
import random
import time

import lib


# ----------------------------------------------------------------------------
# Structured baseline for D = 3: incidence graph of PG(2, q).
# ----------------------------------------------------------------------------

def _best_pg(d):
    """Incidence graph of PG(2, q) for the largest prime power q with q + 1 <= d."""
    for q in range(d - 1, 1, -1):
        if lib.is_prime_power(q):
            return lib.projective_plane_incidence(q)
    return None


# ----------------------------------------------------------------------------
# Non-metacyclic group catalogue. Each group is a permutation group given by
# generators; the closure yields its elements and an index map. Direct products
# with cyclic / small groups are formed by placing factors on disjoint supports.
# ----------------------------------------------------------------------------

MAX_ORDER = 400          # closure bails out beyond this size
CLIMB_ITERS = 300        # hill-climb steps per attempt


def _closure(gens):
    """Return (elements, index) of the group generated by permutation tuples, identity first."""
    n = len(gens[0])
    ident = tuple(range(n))
    elems = [ident]
    index = {ident: 0}
    frontier = [ident]
    while frontier:
        nxt = []
        for x in frontier:
            for g in gens:
                y = tuple(g[i] for i in x)          # g o x
                if y not in index:
                    if len(elems) >= MAX_ORDER:
                        return None
                    index[y] = len(elems)
                    elems.append(y)
                    nxt.append(y)
        frontier = nxt
    return elems, index


def _embed(gens, offset, total):
    out = []
    for g in gens:
        p = list(range(total))
        for i, v in enumerate(g):
            p[offset + i] = offset + v
        out.append(tuple(p))
    return out


def _product(parts):
    """Direct product of permutation parts, each given as (size, gens) on disjoint supports."""
    total = sum(k for k, _ in parts)
    out = []
    off = 0
    for k, gens in parts:
        out += _embed(gens, off, total)
        off += k
    return out


def _cyc(k):
    return (k, [tuple((i + 1) % k for i in range(k))])


def _vec_part(p, mats, trans=(), zero=False):
    """Linear (or affine) maps of F_p^2 acting on nonzero vectors (or all vectors if zero=True)."""
    pts = [(x, y) for x in range(p) for y in range(p) if zero or (x, y) != (0, 0)]
    idx = {v: i for i, v in enumerate(pts)}
    gens = []
    for a, b, c, dd in mats:
        gens.append(tuple(idx[((a * x + b * y) % p, (c * x + dd * y) % p)] for x, y in pts))
    for u, v in trans:
        gens.append(tuple(idx[((x + u) % p, (y + v) % p)] for x, y in pts))
    return len(pts), gens


def _field_part(q, frob):
    """AGL(1,q) (or AGammaL(1,q) when frob) acting on GF(q), q a power of 2."""
    F = lib.GF(q)
    gens = []
    e = 1
    while e < q:
        gens.append(tuple(F.add(x, e) for x in range(q)))
        e <<= 1
    prim = F.primitive_element()
    gens.append(tuple(F.mul(prim, x) for x in range(q)))
    if frob:
        gens.append(tuple(F.mul(x, x) for x in range(q)))
    return q, gens


def _specs():
    A5 = (5, [(1, 2, 0, 3, 4), (1, 2, 3, 4, 0)])
    S5 = (5, [(1, 0, 2, 3, 4), (1, 2, 3, 4, 0)])
    A4 = (4, [(1, 2, 0, 3), (1, 0, 3, 2)])
    S4 = (4, [(1, 0, 2, 3), (1, 2, 3, 0)])
    PSL27 = (7, [(1, 2, 3, 4, 5, 6, 0), (0, 2, 4, 6, 1, 3, 5)])
    SL23 = _vec_part(3, [(1, 1, 0, 1), (0, 2, 1, 0)])
    GL23 = _vec_part(3, [(1, 1, 0, 1), (0, 2, 1, 0), (2, 0, 0, 1)])
    SL25 = _vec_part(5, [(1, 1, 0, 1), (0, 4, 1, 0)])
    ASL23 = _vec_part(3, [(1, 1, 0, 1), (0, 2, 1, 0)], trans=[(1, 0), (0, 1)], zero=True)
    return [
        [A5, _cyc(3)], [A5, _cyc(4)], [A5, _cyc(5)], [S5, _cyc(2)],
        [S4, _cyc(8)], [S4, _cyc(10)], [S4, _cyc(12)], [S4, _cyc(14)],
        [A4, _cyc(15)], [A4, _cyc(20)], [A4, _cyc(25)], [A4, _cyc(28)],
        [PSL27], [PSL27, _cyc(2)],
        [SL23, _cyc(8)], [SL23, _cyc(10)], [SL23, _cyc(12)], [SL23, _cyc(14)],
        [GL23, _cyc(4)], [GL23, _cyc(5)], [GL23, _cyc(6)], [GL23, _cyc(7)],
        [SL25, _cyc(2)], [SL25], [ASL23],
        [_field_part(16, False)], [_field_part(8, True)],
    ]


def _build_catalog(hi):
    """Closures of catalogue groups with order <= hi, sorted by order: list of (N, elems, index)."""
    cat = []
    for spec in _specs():
        cl = _closure(_product(spec))
        if cl is None:
            continue
        elems, index = cl
        N = len(elems)
        if 2 <= N <= hi:
            cat.append((N, elems, index))
    cat.sort(key=lambda t: t[0])
    return cat


def _perm_tables(elems, index):
    """Multiplication table T[a][b] = a*b (composition) and inverses; identity has index 0."""
    T = [[index[tuple(a[i] for i in b)] for b in elems] for a in elems]
    invs = [row.index(0) for row in T]
    return T, invs


# ----------------------------------------------------------------------------
# Metacyclic semidirect products Z_m x| Z_k (secondary job family).
# ----------------------------------------------------------------------------

def _meta_groups(N):
    out = []
    for k in range(2, N + 1):
        if N % k:
            continue
        m = N // k
        for r in range(m):
            if math.gcd(r, m) == 1 and pow(r, k, m) == 1 % m:
                out.append((m, k, r))
    return out


def _meta_tables(m, k, r):
    order, mul, inv = lib.semidirect_group(m, k, r)
    T = [[mul(x, g) for g in range(order)] for x in range(order)]
    invs = [inv(g) for g in range(order)]
    return T, invs


# ----------------------------------------------------------------------------
# Bi-Cayley lift search: A_x ~ B_{x g} for g in S, |S| = d, on a group of order N.
# The lift has 2N vertices. Left translation is an automorphism, so the
# eccentricities of A_0 and B_0 determine the diameter.
# ----------------------------------------------------------------------------

def _unreached(N, T, invs, S, D):
    """Count vertex pairs (source, target) not within distance D, from A_0 and B_0."""
    Sinv = [invs[g] for g in S]
    total = 0
    for src in (0, N):
        seen = bytearray(2 * N)
        seen[src] = 1
        count = 1
        frontier = [src]
        for _ in range(D):
            nxt = []
            for u in frontier:
                if u < N:
                    row = T[u]
                    for g in S:
                        v = N + row[g]
                        if not seen[v]:
                            seen[v] = 1
                            nxt.append(v)
                else:
                    row = T[u - N]
                    for h in Sinv:
                        v = row[h]
                        if not seen[v]:
                            seen[v] = 1
                            nxt.append(v)
            count += len(nxt)
            frontier = nxt
            if not frontier:
                break
        total += 2 * N - count
    return total


def _climb(N, T, invs, d, D, rng, iters, deadline):
    """Hill-climb a connection set S (identity fixed as one dart) to zero unreached pairs."""
    S = [0] + rng.sample(range(1, N), d - 1)
    cur = _unreached(N, T, invs, S, D)
    for _ in range(iters):
        if cur == 0 or time.monotonic() > deadline:
            break
        i = rng.randrange(1, d)
        c = rng.randrange(1, N)
        if c in S:
            continue
        S2 = S[:]
        S2[i] = c
        v = _unreached(N, T, invs, S2, D)
        if v <= cur:
            S, cur = S2, v
    return S if cur == 0 else None


# ----------------------------------------------------------------------------
# Main entry point.
# ----------------------------------------------------------------------------

def build(d, D, seed, time_limit):
    start = time.monotonic()
    budget = max(0.5, min(0.8 * time_limit, time_limit - 5.0))
    deadline = start + budget
    rng = random.Random(seed)

    if d < 1 or D < 1:
        return 1, []
    if D == 1:
        return 2, [(0, 1)]

    # Safe fallback: K_{d,d} has diameter 2 and meets the Moore bound for D = 2.
    best = lib.haar_graph(d, range(d))
    if D == 2 or d < 2:
        return best

    moore = lib._moore_bound(d, D)

    def consider(n, e):
        nonlocal best
        if n > best[0] and lib.is_valid(n, e, d, D):
            best = (n, e)

    if D == 3:
        pg = _best_pg(d)
        if pg is not None:
            consider(pg[0], pg[1])

    if best[0] < moore:
        try:
            hi = moore // 2          # bi-Cayley order N must satisfy 2N <= moore
            catalog = _build_catalog(hi)
            jobs = [(N, ('perm', i)) for i, (N, _, _) in enumerate(catalog) if N >= d]
            for N in range(max(2, d), hi + 1):
                for m, k, r in _meta_groups(N)[:2]:
                    jobs.append((N, ('meta', m, k, r)))

            cache = {}

            def tables_for(key):
                if key[0] == 'perm':
                    _, elems, index = catalog[key[1]]
                    return _perm_tables(elems, index)
                return _meta_tables(key[1], key[2], key[3])

            while time.monotonic() < deadline and best[0] < moore:
                lo = best[0] // 2 + 1
                if lo > hi:
                    break
                active = [j for j in jobs if j[0] >= lo]
                if not active:
                    break
                improved = False
                for N, key in active:
                    if time.monotonic() > deadline:
                        break
                    if key not in cache:
                        cache[key] = tables_for(key)
                    T, invs = cache[key]
                    S = _climb(N, T, invs, d, D, rng, CLIMB_ITERS, deadline)
                    if S is not None:
                        edges = [(x, N + T[x][g]) for x in range(N) for g in S]
                        before = best[0]
                        consider(2 * N, edges)
                        if best[0] > before:
                            improved = True
                            break
                if not improved and time.monotonic() > deadline:
                    break
        except Exception:
            pass

    if not lib.is_valid(best[0], best[1], d, D):
        best = lib.haar_graph(d, range(d))
    return best
