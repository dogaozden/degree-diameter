"""Bi-Cayley lifts over a catalogue of NON-cyclic groups.

New in this version: a lazily built catalogue of permutation groups
(S4, A4, S5, A5, PSL(2,7), PGL(2,7), AGL(1,p)) and their direct products
with small cyclic groups. Each group G of order N gives a bipartite graph
on 2N vertices, A_x ~ B_{xg} for g in S, with |S| = d. Connection sets
are found by hill-climbing on the number of pairs not within distance D.
The target order is swept upward from the current best.
"""
import bisect
import random
import time

import lib

SLICE = 3.5          # seconds spent on one group before moving on
STALL_LIMIT = 250    # random restarts after this many non-improving moves
MAX_CYC = 400        # largest cyclic factor used in products
PROD_CACHE_LIMIT = 24

_BASE = {}           # name -> (order, R, inv); R[x][g] = x*g, identity index 0
_PROD_CACHE = {}


def _cyc_perm(n, cyc):
    """Permutation of range(n) that cycles the given points."""
    p = list(range(n))
    for i, c in enumerate(cyc):
        p[c] = cyc[(i + 1) % len(cyc)]
    return tuple(p)


def _perm_group(gens, limit=400):
    """Permutation group generated by gens, as (order, R), or None if larger than limit."""
    n = len(gens[0])
    idt = tuple(range(n))
    elems = [idt]
    index = {idt: 0}
    i = 0
    while i < len(elems):
        e = elems[i]
        i += 1
        for s in gens:
            f = tuple(e[k] for k in s)
            if f not in index:
                if len(elems) >= limit:
                    return None
                index[f] = len(elems)
                elems.append(f)
    R = [[index[tuple(x[k] for k in g)] for g in elems] for x in elems]
    return len(elems), R


def _inverse_list(N, R):
    """inv[x] is the index of x^-1."""
    inv = [0] * N
    for x in range(N):
        row = R[x]
        for g in range(N):
            if row[g] == 0:
                inv[x] = g
                break
    return inv


def _base_groups():
    """Build the non-cyclic base groups used as factors."""
    specs = {}
    specs["S4"] = [_cyc_perm(4, (0, 1)), _cyc_perm(4, (0, 1, 2, 3))]
    specs["A4"] = [_cyc_perm(4, (0, 1, 2)), _cyc_perm(4, (1, 2, 3))]
    specs["S5"] = [_cyc_perm(5, (0, 1)), _cyc_perm(5, (0, 1, 2, 3, 4))]
    specs["A5"] = [_cyc_perm(5, (0, 1, 2)), _cyc_perm(5, (1, 2, 3)), _cyc_perm(5, (2, 3, 4))]
    # Projective line over F_7: points 0..6 and infinity = 7.
    t = tuple([(x + 1) % 7 for x in range(7)] + [7])
    m3 = tuple([(3 * x) % 7 for x in range(7)] + [7])
    dbl = tuple([(2 * x) % 7 for x in range(7)] + [7])
    neg_inv = tuple([7] + [(-pow(x, 5, 7)) % 7 for x in range(1, 7)] + [0])
    specs["PSL27"] = [t, dbl, neg_inv]
    specs["PGL27"] = [t, m3, neg_inv]
    # Affine groups AGL(1,p) on Z_p.
    for p in (7, 11, 13, 17):
        a = next(a for a in range(2, p) if len({pow(a, k, p) for k in range(1, p)}) == p - 1)
        specs["AGL%d" % p] = [tuple((x + 1) % p for x in range(p)),
                              tuple((a * x) % p for x in range(p))]
    out = {}
    for name, gens in specs.items():
        res = _perm_group(gens, 400)
        if res is None:
            continue
        N, R = res
        out[name] = (N, R, _inverse_list(N, R))
    return out


def _product(A, B):
    """Direct product of two groups given as (N, R, inv)."""
    NA, RA, _ = A
    NB, RB, _ = B
    N = NA * NB
    R = []
    for x in range(N):
        xa, xb = divmod(x, NB)
        ra, rb = RA[xa], RB[xb]
        R.append([ra[g // NB] * NB + rb[g % NB] for g in range(N)])
    return N, R, _inverse_list(N, R)


def _get(key):
    """Return (N, R, inv) for a recipe key: ('b', name), ('c', m) or ('p', keyA, keyB)."""
    if key[0] == 'b':
        return _BASE[key[1]]
    if key[0] == 'c':
        m = key[1]
        R = [[(x + g) % m for g in range(m)] for x in range(m)]
        return m, R, [(-x) % m for x in range(m)]
    hit = _PROD_CACHE.get(key)
    if hit is None:
        if len(_PROD_CACHE) >= PROD_CACHE_LIMIT:
            _PROD_CACHE.clear()
        hit = _product(_get(key[1]), _get(key[2]))
        _PROD_CACHE[key] = hit
    return hit


def _recipes(hi):
    """Sorted (order, key) list of candidate groups with order <= hi."""
    bases = [(v[0], ('b', k)) for k, v in _BASE.items()]
    recs = [(o, k) for o, k in bases if o <= hi]
    for o, kb in bases:
        for m in range(2, min(hi // o, MAX_CYC) + 1):
            recs.append((o * m, ('p', kb, ('c', m))))
    for i, (oa, ka) in enumerate(bases):
        for ob, kb in bases[i:]:
            if oa * ob <= hi:
                recs.append((oa * ob, ('p', ka, kb)))
    recs.sort(key=lambda t: t[0])
    return recs


def _unreached(N, R, inv, S, D):
    """Pairs not within distance D, counted from A_0 and B_0.

    Left translation is an automorphism, so these two eccentricities suffice.
    """
    Sinv = [inv[g] for g in S]
    total = 0
    for src in (0, N):
        seen = bytearray(2 * N)
        seen[src] = 1
        count = 1
        frontier = [src]
        for _ in range(D):
            nxt = []
            for u in frontier:
                if u < N:
                    row = R[u]
                    for g in S:
                        v = N + row[g]
                        if not seen[v]:
                            seen[v] = 1
                            nxt.append(v)
                else:
                    row = R[u - N]
                    for h in Sinv:
                        v = row[h]
                        if not seen[v]:
                            seen[v] = 1
                            nxt.append(v)
            count += len(nxt)
            frontier = nxt
            if not frontier:
                break
        total += 2 * N - count
    return total


def _climb(N, R, inv, d, D, rng, deadline):
    """Find S = {0, s_1..s_{d-1}} (identity WLOG) with zero unreached pairs, or None."""
    while time.monotonic() < deadline:
        S = [0] + rng.sample(range(1, N), d - 1)
        cur = _unreached(N, R, inv, S, D)
        stall = 0
        while cur and stall < STALL_LIMIT and time.monotonic() < deadline:
            i = rng.randrange(1, d)
            c = rng.randrange(1, N)
            if c in S:
                continue
            S2 = S[:]
            S2[i] = c
            v = _unreached(N, R, inv, S2, D)
            stall = 0 if v < cur else stall + 1
            if v <= cur:
                S, cur = S2, v
        if cur == 0:
            return S
    return None


def build(d, D, seed, time_limit):
    start = time.monotonic()
    budget = max(0.5, min(0.85 * time_limit, time_limit - 3.0))
    deadline = start + budget
    rng = random.Random(seed)

    if d < 1 or D < 1:
        return 1, []
    if D == 1:
        return 2, [(0, 1)]

    # K_{d,d} has diameter 2 and is the safe fallback.
    best = lib.haar_graph(d, range(d))
    if D == 2:
        return best

    moore = lib._moore_bound(d, D)

    def consider(n, e):
        nonlocal best
        if n > best[0] and lib.is_valid(n, e, d, D):
            best = (n, e)

    if D == 3:
        for q in range(d - 1, 1, -1):
            if lib.is_prime_power(q):
                n2, e2 = lib.projective_plane_incidence(q)
                consider(n2, e2)
                break

    if best[0] >= moore or time.monotonic() >= deadline:
        return best

    if not _BASE:
        _BASE.update(_base_groups())

    hi = moore // 2
    recs = _recipes(hi)
    orders = [o for o, _ in recs]

    while time.monotonic() < deadline:
        # Bi-Cayley graph on 2N vertices must beat the current best.
        lo = best[0] // 2 + 1
        a = bisect.bisect_left(orders, lo)
        b = bisect.bisect_right(orders, hi)
        if a >= b:
            break
        # Bias toward orders just above the current best.
        idx = a + int((b - a) * rng.random() ** 2)
        _, key = recs[idx]
        N, R, inv = _get(key)
        if N < d or N < lo:
            continue
        end = min(deadline, time.monotonic() + SLICE)
        S = _climb(N, R, inv, d, D, rng, end)
        if S is not None:
            edges = [(x, N + R[x][g]) for x in range(N) for g in S]
            consider(2 * N, edges)

    if not lib.is_valid(best[0], best[1], d, D):
        best = lib.haar_graph(d, range(d))
    return best
