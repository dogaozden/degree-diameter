# ----------------------------------------------------------------------------
# Helper (new): bitset rotation BFS for cyclic Bi-Cayley graphs.
#
# Graph on A_x, B_x (x in Z_N) with A_x ~ B_{x+s} for s in S. A subset of one
# side is a bitmask over Z_N, and translating it by s is a cyclic rotation of
# the mask. One BFS layer then costs O(|S|) big-int operations instead of
# O(N*|S|) Python operations, so the annealer can afford far more steps.
# Translations are automorphisms, so eccentricities of A_0 and B_0 decide
# validity.
# ----------------------------------------------------------------------------

def _rot(X, s, N, full):
    """Cyclically shift the N-bit mask X so that position i moves to (i+s) mod N."""
    if s == 0:
        return X
    return ((X << s) | (X >> (N - s))) & full


def _cyc_unreached(N, S, D, full):
    """Number of (source, vertex) pairs at distance > D, for sources A_0 and B_0."""
    negS = [(-s) % N for s in S]
    total = 0
    for side in (0, 1):
        FA = 1 if side == 0 else 0
        FB = 1 - FA
        RA, RB = FA, FB
        for _ in range(D):
            if not FA and not FB:
                break
            nb = 0
            if FA:
                for s in S:
                    nb |= _rot(FA, s, N, full)
                nb &= ~RB & full
            na = 0
            if FB:
                for t in negS:
                    na |= _rot(FB, t, N, full)
                na &= ~RA & full
            RB |= nb
            RA |= na
            FA, FB = na, nb
        total += 2 * N - RA.bit_count() - RB.bit_count()
    return total


def _cyc_anneal(N, d, D, rng, iters, deadline):
    """Anneal a connection set S of size d in Z_N (0 in S WLOG). Returns S if valid, else None."""
    full = (1 << N) - 1
    S = [0] + rng.sample(range(1, N), d - 1)
    cur = _cyc_unreached(N, S, D, full)
    best_S, best_v = list(S), cur
    T0 = 2.0 + 0.1 * cur
    for step in range(iters):
        if best_v == 0:
            break
        if (step & 255) == 0 and time.monotonic() > deadline:
            break
        temp = T0 * (1.0 - step / iters) + 0.15
        i = rng.randrange(1, d)
        c = rng.randrange(1, N)
        if c in S:
            continue
        S2 = S[:]
        S2[i] = c
        v = _cyc_unreached(N, S2, D, full)
        delta = v - cur
        if delta <= 0 or rng.random() < math.exp(-delta / temp):
            S, cur = S2, v
            if cur < best_v:
                best_S, best_v = list(S), cur
    return best_S if best_v == 0 else None


