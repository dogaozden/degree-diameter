"""Bold variant for D >= 3: bi-Cayley lifts over NON-METABELIAN groups.

The parent only searched semidirect products Z_m x| Z_k, which are metabelian.
This version adds permutation groups (A4, S4, A5, S5, PSL(2,7), PGL(2,7)) and
their direct products with cyclic groups Z_k. Orders from 169 up to moore//2
become reachable, so the search can target bi-Cayley graphs with order above the
record 168. Each bi-Cayley graph has 2N vertices, with A_x ~ B_{x g} for g in S.

Safety: K_{d,d} is the starting fallback, and every candidate passes lib.is_valid
before it replaces the best graph. Search exceptions are caught.

Status: not executed in this session. The construction is checked only by the
validity guards, so it may return a smaller graph than the parent's 336 if the
new groups do not yield a valid lift in time.
"""
import math
import random
import time

import lib

MAX_ORDER = 341              # bi-Cayley order cap: 2N <= Moore bound for (5, 5)
CLIMB_ITERS = 450            # hill-climb steps per candidate group
MAX_GROUPS_PER_ORDER = 3     # candidate groups tried per order N
_CACHE_LIMIT = 24
_TABLE_CACHE = {}

_BASE_ORDER = {'A4': 12, 'S4': 24, 'A5': 60, 'S5': 120, 'PSL7': 168, 'PGL7': 336}


# ----------------------------------------------------------------------------
# D = 3 baseline: projective plane incidence graph (optimal when d - 1 is a prime power).
# ----------------------------------------------------------------------------

def _best_pg(d):
    for q in range(d - 1, 1, -1):
        if lib.is_prime_power(q):
            return lib.projective_plane_incidence(q)
    return None


# ----------------------------------------------------------------------------
# Group tables.
# ----------------------------------------------------------------------------

def _cache_put(key, val):
    if len(_TABLE_CACHE) >= _CACHE_LIMIT:
        _TABLE_CACHE.clear()
    _TABLE_CACHE[key] = val


def _finish(N, T):
    """Attach inverse table; identity is index 0 in every table built here."""
    invs = [row.index(0) for row in T]   # T[g][h] == 0 means h = g^-1
    return (N, T, invs)


def _groups_semi(N):
    """Semidirect parameters (m, k, r) with m*k = N, giving Z_m x|_r Z_k."""
    out = []
    for k2 in range(1, N + 1):
        if N % k2:
            continue
        m = N // k2
        for r in range(m):
            if math.gcd(r, m) == 1 and pow(r, k2, m) == 1 % m:
                out.append((m, k2, r))
    return out


def _psl_gens(p, pgl):
    """Generators of PSL(2,p) (or PGL(2,p)) acting on the projective line {0..p-1, p=inf}."""
    inf = p
    T = tuple([(i + 1) % p for i in range(p)] + [inf])
    S = [0] * (p + 1)
    S[inf] = 0
    S[0] = inf
    for x in range(1, p):
        S[x] = (-pow(x, p - 2, p)) % p
    gens = [T, tuple(S)]
    if pgl:
        a = next(a for a in range(2, p) if pow(a, (p - 1) // 2, p) == p - 1)
        gens.append(tuple([(a * i) % p for i in range(p)] + [inf]))
    return gens


def _base_gens(name):
    if name == 'A4':
        return [(1, 2, 0, 3), (1, 0, 3, 2)]
    if name == 'S4':
        return [(1, 2, 3, 0), (1, 0, 2, 3)]
    if name == 'A5':
        return _psl_gens(5, False)
    if name == 'S5':
        return [(1, 2, 3, 4, 0), (1, 0, 2, 3, 4)]
    if name == 'PSL7':
        return _psl_gens(7, False)
    if name == 'PGL7':
        return _psl_gens(7, True)
    return None


def _perm_table(gens):
    """Multiplication table of the permutation group generated by gens (identity at index 0)."""
    n = len(gens[0])
    idp = tuple(range(n))
    elems = [idp]
    index = {idp: 0}
    frontier = [idp]
    while frontier:
        nxt = []
        for x in frontier:
            for s in gens:
                y = tuple(s[i] for i in x)
                if y not in index:
                    if len(elems) >= MAX_ORDER:
                        return None
                    index[y] = len(elems)
                    elems.append(y)
                    nxt.append(y)
        frontier = nxt
    N = len(elems)
    T = [[index[tuple(a[b[i]] for i in range(n))] for b in elems] for a in elems]
    return N, T


def _base_table(name):
    key = ('base', name)
    if key in _TABLE_CACHE:
        return _TABLE_CACHE[key]
    res = _perm_table(_base_gens(name))
    val = None
    if res is not None and res[0] == _BASE_ORDER[name]:
        val = _finish(res[0], res[1])
    _cache_put(key, val)
    return val


def _product_table(TB, NB, k):
    """Direct product of a base group (table TB, order NB) with Z_k; index = g*k + c."""
    N = NB * k
    T = [[0] * N for _ in range(N)]
    for x in range(N):
        gx, cx = divmod(x, k)
        row = T[x]
        for y in range(N):
            gy, cy = divmod(y, k)
            row[y] = TB[gx][gy] * k + (cx + cy) % k
    return T


def _group_table(spec):
    """Cached (N, T, invs) for a group spec, or None if unavailable."""
    if spec in _TABLE_CACHE:
        return _TABLE_CACHE[spec]
    if spec[0] == 'semi':
        _, m, k2, r = spec
        order, mul, _inv = lib.semidirect_group(m, k2, r)
        T = [[mul(x, y) for y in range(order)] for x in range(order)]
        val = _finish(order, T)
    else:
        _, name, k = spec
        base = _base_table(name)
        if base is None:
            val = None
        else:
            NB, TB, _ = base
            T = TB if k == 1 else _product_table(TB, NB, k)
            val = _finish(NB * k, T)
    _cache_put(spec, val)
    return val


def _specs_for(N, rng):
    specs = [('semi', m, k2, r) for (m, k2, r) in _groups_semi(N)]
    for name, NB in _BASE_ORDER.items():
        if N % NB == 0:
            specs.append(('prod', name, N // NB))
    rng.shuffle(specs)
    return specs


# ----------------------------------------------------------------------------
# Bi-Cayley hill climb.
# A_x ~ B_{x g} for g in S, with 1 in S WLOG. Left translation is an automorphism,
# so eccentricities from A_0 and B_0 decide diameter <= D.
# ----------------------------------------------------------------------------

def _unreached(N, T, invs, S, D):
    Sinv = [invs[g] for g in S]
    total = 0
    for src in (0, N):
        seen = bytearray(2 * N)
        seen[src] = 1
        count = 1
        frontier = [src]
        for _ in range(D):
            nxt = []
            for u in frontier:
                if u < N:
                    row = T[u]
                    for g in S:
                        v = N + row[g]
                        if not seen[v]:
                            seen[v] = 1
                            nxt.append(v)
                else:
                    row = T[u - N]
                    for h in Sinv:
                        v = row[h]
                        if not seen[v]:
                            seen[v] = 1
                            nxt.append(v)
            count += len(nxt)
            frontier = nxt
            if not frontier:
                break
        total += 2 * N - count
    return total


def _climb(N, T, invs, d, D, rng, iters, deadline):
    S = [0] + rng.sample(range(1, N), d - 1)
    cur = _unreached(N, T, invs, S, D)
    for _ in range(iters):
        if cur == 0 or time.monotonic() > deadline:
            break
        i = rng.randrange(1, d)
        c = rng.randrange(1, N)
        if c in S:
            continue
        S2 = S[:]
        S2[i] = c
        v = _unreached(N, T, invs, S2, D)
        if v <= cur:
            S, cur = S2, v
    return S if cur == 0 else None


def _sweep(d, D, rng, deadline, hi, cur_best, consider):
    """Sweep bi-Cayley orders N upward from the smallest one that beats cur_best."""
    N = max(d, cur_best // 2 + 1)
    while time.monotonic() < deadline and N <= hi:
        found = None
        tried = 0
        for spec in _specs_for(N, rng):
            if time.monotonic() >= deadline or tried >= MAX_GROUPS_PER_ORDER:
                break
            tab = _group_table(spec)
            if tab is None:
                continue
            gN, T, invs = tab
            if gN != N or gN < d:
                continue
            tried += 1
            S = _climb(N, T, invs, d, D, rng, CLIMB_ITERS, deadline)
            if S is not None:
                found = (T, S)
                break
        if found is not None:
            T, S = found
            edges = [(x, N + T[x][g]) for x in range(N) for g in S]
            cur_best = consider(2 * N, edges)
        N = max(N + 1, cur_best // 2 + 1)


# ----------------------------------------------------------------------------
# Main entry point.
# ----------------------------------------------------------------------------

def build(d, D, seed, time_limit):
    start = time.monotonic()
    budget = max(0.5, min(0.85 * time_limit, time_limit - 3.0))
    deadline = start + budget
    rng = random.Random(seed)

    if d < 1 or D < 1:
        return 1, []
    if D == 1:
        return 2, [(0, 1)]

    # Safe fallback: K_{d,d}, diameter 2.
    best = lib.haar_graph(d, range(d))
    if D == 2 or d < 2:
        return best

    moore = lib._moore_bound(d, D)

    def consider(n, e):
        nonlocal best
        if n > best[0] and lib.is_valid(n, e, d, D):
            best = (n, e)
        return best[0]

    if D == 3:
        pg = _best_pg(d)
        if pg is not None:
            consider(pg[0], pg[1])

    if best[0] < moore:
        try:
            _sweep(d, D, rng, deadline, moore // 2, best[0], consider)
        except Exception:
            pass

    if not lib.is_valid(best[0], best[1], d, D):
        best = lib.haar_graph(d, range(d))
    return best
