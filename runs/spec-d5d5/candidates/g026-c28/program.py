import math
import random
import time

import lib

# Bi-Cayley lifts B(G, S) over non-abelian and direct-product groups.
# Vertices: A_x = x and B_y = N + y for x, y in G. Edges: A_x ~ B_{x s} for s in S.
# Left multiplication is an automorphism, so only the eccentricities of A_e and B_e matter.

MAX_GROUPS = 4        # group candidates tried per order N
CLIMB_ITERS = 250     # hill-climb steps per candidate
SPREAD = 14           # orders tried in [lo, lo + SPREAD)
BASE_SIZES = (('S4', 24), ('A4', 12), ('A5', 60), ('S5', 120), ('PSL27', 168), ('PGL27', 336))

_BASE_CACHE = {}
_TABLE_CACHE = {}


def _cyclic_table(n):
    return n, [[(x + y) % n for y in range(n)] for x in range(n)]


def _dihedral_table(n):
    """Dihedral group of order 2n; index s*n + a encodes r^a f^s."""
    N = 2 * n
    T = [[0] * N for _ in range(N)]
    for x in range(N):
        s, a = divmod(x, n)
        row = T[x]
        for y in range(N):
            t, b = divmod(y, n)
            c = (a + b) % n if s == 0 else (a - b) % n
            row[y] = ((s + t) % 2) * n + c
    return N, T


def _perm_table(gens, cap):
    """Multiplication table of the permutation group generated by gens (identity is index 0)."""
    n = len(gens[0])
    e = tuple(range(n))
    elems = [e]
    idx = {e: 0}
    i = 0
    while i < len(elems):
        g = elems[i]
        i += 1
        for s in gens:
            h = tuple(s[x] for x in g)
            if h not in idx:
                if len(elems) >= cap:
                    return None
                idx[h] = len(elems)
                elems.append(h)
    N = len(elems)
    T = [[idx[tuple(p[x] for x in q)] for q in elems] for p in elems]
    return N, T


def _base_group(name):
    hit = _BASE_CACHE.get(name)
    if hit is not None:
        return hit
    if name == 'S4':
        res = _perm_table([(1, 0, 2, 3), (1, 2, 3, 0)], 64)
    elif name == 'A4':
        res = _perm_table([(1, 2, 0, 3), (1, 0, 3, 2)], 64)
    elif name == 'A5':
        res = _perm_table([(1, 2, 3, 4, 0), (1, 2, 0, 3, 4)], 128)
    elif name == 'S5':
        res = _perm_table([(1, 2, 3, 4, 0), (1, 0, 2, 3, 4)], 128)
    else:
        # PSL(2,7) and PGL(2,7) acting on the projective line over GF(7); point 7 is infinity.
        translate = tuple((i + 1) % 7 if i < 7 else 7 for i in range(8))
        mobius = tuple((7 if i == 0 else (-pow(i, 5, 7)) % 7) if i < 7 else 0 for i in range(8))
        gens = [translate, mobius]
        if name == 'PGL27':
            gens.append(tuple((3 * i) % 7 if i < 7 else 7 for i in range(8)))
        res = _perm_table(gens, 400)
    _BASE_CACHE[name] = res
    return res


def _product(A, B):
    NA, TA = A
    NB, TB = B
    N = NA * NB
    T = []
    for x in range(N):
        i, j = divmod(x, NB)
        ra = TA[i]
        rb = TB[j]
        row = [0] * N
        for y in range(N):
            k, l = divmod(y, NB)
            row[y] = ra[k] * NB + rb[l]
        T.append(row)
    return N, T


def _materialize(spec):
    hit = _TABLE_CACHE.get(spec)
    if hit is not None:
        return hit
    kind = spec[0]
    if kind == 'cyc':
        res = _cyclic_table(spec[1])
    elif kind == 'dih':
        res = _dihedral_table(spec[1])
    elif kind == 'base':
        res = _base_group(spec[1])
    elif kind == 'prod':
        res = _product(_base_group(spec[1]), _cyclic_table(spec[2]))
    else:  # 'semi'
        _, m, k, r = spec
        order, mul, _inv = lib.semidirect_group(m, k, r)
        T = [[mul(x, y) for y in range(order)] for x in range(order)]
        res = (order, T)
    if len(_TABLE_CACHE) >= 40:
        _TABLE_CACHE.clear()
    _TABLE_CACHE[spec] = res
    return res


def _semi_specs(N):
    out = []
    for k in range(2, N + 1):
        if N % k:
            continue
        m = N // k
        if m < 2:
            continue
        for r in range(1, m):
            if math.gcd(r, m) == 1 and pow(r, k, m) == 1 % m:
                out.append(('semi', m, k, r))
    return out


def _candidate_specs(N, rng):
    specs = []
    semi = _semi_specs(N)
    rng.shuffle(semi)
    specs.extend(semi[:4])
    for name, size in BASE_SIZES:
        if N % size == 0:
            k = N // size
            specs.append(('base', name) if k == 1 else ('prod', name, k))
    if N % 2 == 0 and N // 2 >= 3:
        specs.append(('dih', N // 2))
    specs.append(('cyc', N))
    rng.shuffle(specs)
    return specs


def _invs(T):
    return [row.index(0) for row in T]


def _unreached(N, T, invs, S, D):
    """Number of (source, vertex) pairs at distance > D, for sources A_e and B_e."""
    Sinv = [invs[g] for g in S]
    total = 0
    for src in (0, N):
        seen = bytearray(2 * N)
        seen[src] = 1
        count = 1
        frontier = [src]
        for _ in range(D):
            nxt = []
            for u in frontier:
                if u < N:
                    row = T[u]
                    for g in S:
                        v = N + row[g]
                        if not seen[v]:
                            seen[v] = 1
                            nxt.append(v)
                else:
                    row = T[u - N]
                    for h in Sinv:
                        v = row[h]
                        if not seen[v]:
                            seen[v] = 1
                            nxt.append(v)
            count += len(nxt)
            frontier = nxt
            if not frontier:
                break
        total += 2 * N - count
    return total


def _climb(N, T, invs, d, D, rng, iters, deadline):
    if N < d:
        return None
    S = [0] + rng.sample(range(1, N), d - 1)   # identity WLOG
    cur = _unreached(N, T, invs, S, D)
    for _ in range(iters):
        if cur == 0 or time.monotonic() > deadline:
            break
        i = rng.randrange(1, d)
        c = rng.randrange(1, N)
        if c in S:
            continue
        S2 = S[:]
        S2[i] = c
        v = _unreached(N, T, invs, S2, D)
        if v <= cur:
            S, cur = S2, v
    return S if cur == 0 else None


def _edges_from(N, T, S):
    return [(x, N + T[x][g]) for x in range(N) for g in S]


def build(d, D, seed, time_limit):
    start = time.monotonic()
    budget = max(0.5, min(0.8 * time_limit, time_limit - 5.0))
    deadline = start + budget
    rng = random.Random(seed)

    if d < 1 or D < 1:
        return 1, []
    if d == 1 or D == 1:
        return 2, [(0, 1)]

    fallback = lib.haar_graph(d, range(d))   # K_{d,d}, diameter 2
    if D == 2:
        return fallback

    if D == 3 and lib.is_prime_power(d - 1):
        n, e = lib.projective_plane_incidence(d - 1)   # Moore-optimal for D = 3
        if lib.is_valid(n, e, d, D):
            return n, e

    moore = lib._moore_bound(d, D)
    best = fallback
    hi = moore // 2

    while time.monotonic() < deadline:
        best_n = best[0]
        if best_n >= moore:
            break
        lo = max(best_n // 2 + 1, d)
        if lo > hi:
            break
        N = min(hi, lo + min(rng.randrange(SPREAD), rng.randrange(SPREAD)))
        found = None
        for spec in _candidate_specs(N, rng)[:MAX_GROUPS]:
            if time.monotonic() > deadline:
                break
            order, T = _materialize(spec)
            if order != N:
                continue
            invs = _invs(T)
            S = _climb(N, T, invs, d, D, rng, CLIMB_ITERS, deadline)
            if S is not None:
                found = (N, T, S)
                break
        if found is not None:
            N_, T, S = found
            cand_n = 2 * N_
            if cand_n > best[0]:
                edges = _edges_from(N_, T, S)
                if lib.is_valid(cand_n, edges, d, D):
                    best = (cand_n, edges)

    if not lib.is_valid(best[0], best[1], d, D):
        best = fallback
    return best
