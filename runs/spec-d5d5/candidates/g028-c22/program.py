import itertools
import math
import random
import time

import lib

ITERS = 500          # annealing steps per (group, attempt)
MAX_CANDS = 60       # cap on candidate groups kept
MAX_CACHE = 24       # cap on cached multiplication tables


# ----------------------------------------------------------------------------
# Baseline families (fast, always valid when they pass lib.is_valid).
# ----------------------------------------------------------------------------

def _best_pg(d):
    """Incidence graph of PG(2, q) for the largest prime power q with q + 1 <= d."""
    for q in range(d - 1, 1, -1):
        if lib.is_prime_power(q):
            return lib.projective_plane_incidence(q)
    return None


def _gq_w(q):
    """Incidence graph of points and lines of the generalized quadrangle W(q); diameter 4."""
    F = lib.GF(q)
    pts = [v for v in itertools.product(range(q), repeat=4)
           if any(v) and next(c for c in v if c) == 1]
    index = {v: i for i, v in enumerate(pts)}
    P = len(pts)

    def norm(v):
        c = next(x for x in v if x)
        inv = F.inv(c)
        return tuple(F.mul(inv, x) for x in v)

    def form(x, y):
        t = F.sub(F.mul(x[0], y[1]), F.mul(x[1], y[0]))
        return F.add(t, F.sub(F.mul(x[2], y[3]), F.mul(x[3], y[2])))

    covered = set()
    lines = []
    for i in range(P):
        x = pts[i]
        for j in range(i + 1, P):
            if (i, j) in covered:
                continue
            y = pts[j]
            if form(x, y) != 0:
                continue
            L = set()
            for a in range(q):
                for b in range(q):
                    if a == 0 and b == 0:
                        continue
                    v = tuple(F.add(F.mul(a, x[k]), F.mul(b, y[k])) for k in range(4))
                    if any(v):
                        L.add(index[norm(v)])
            L = sorted(L)
            lines.append(L)
            for p in L:
                for r in L:
                    if p < r:
                        covered.add((p, r))

    edges = []
    for j, L in enumerate(lines):
        for p in L:
            edges.append((p, P + j))
    return 2 * P, edges


def _best_gq(d):
    """W(q) for the largest prime power q with q + 1 <= d, restricted to small q for speed."""
    for q in range(min(d - 1, 5), 1, -1):
        if lib.is_prime_power(q):
            return _gq_w(q)
    return None


# ----------------------------------------------------------------------------
# Group machinery. Groups are given either as permutation groups (closure of
# generators, identity at index 0) or as semidirect products Z_m x| Z_k.
# ----------------------------------------------------------------------------

def _pmul(x, g):
    """Composition x after g, as tuples: (x o g)(i) = x[g[i]]."""
    return tuple(x[i] for i in g)


def _closure(gens, cap):
    """Elements of the group generated by permutation tuples gens (identity first), or None if > cap."""
    if not gens:
        return None
    k = len(gens[0])
    ident = tuple(range(k))
    elems = [ident]
    seen = {ident}
    i = 0
    while i < len(elems):
        x = elems[i]
        i += 1
        for g in gens:
            y = _pmul(x, g)
            if y not in seen:
                seen.add(y)
                elems.append(y)
                if len(elems) > cap:
                    return None
    return elems


def _table(elems):
    """Multiplication table T[x][g] = index(x*g) and inverse list for a permutation group."""
    idx = {e: i for i, e in enumerate(elems)}
    T = [[idx[_pmul(x, g)] for g in elems] for x in elems]
    invs = [row.index(0) for row in T]
    return T, invs


def _groups(N):
    """Return semidirect parameters (m, k, r) with m*k = N, giving Z_m x|_r Z_k."""
    out = []
    for k in range(1, N + 1):
        if N % k:
            continue
        m = N // k
        for r in range(m):
            if math.gcd(r, m) == 1 and pow(r, k, m) == 1 % m:
                out.append((m, k, r))
    return out


def _sd_table(m, k, r):
    N, mul, inv = lib.semidirect_group(m, k, r)
    T = [[mul(x, g) for g in range(N)] for x in range(N)]
    invs = [inv(g) for g in range(N)]
    return T, invs


def _primroot(p):
    for g in range(2, p):
        x, e = g, 1
        while x != 1:
            x = x * g % p
            e += 1
        if e == p - 1:
            return g
    return 1


def _pair(gA, dA, gB, dB):
    """Generators of the direct product acting on the disjoint union of supports."""
    g = [tuple(list(p) + list(range(dA, dA + dB))) for p in gA]
    g += [tuple(list(range(dA)) + [dA + x for x in p]) for p in gB]
    return g, dA + dB


def _base_groups():
    """Small permutation groups as (degree, generators)."""
    base = []
    for a in range(2, 13):                       # cyclic
        base.append((a, [tuple((i + 1) % a for i in range(a))]))
    for m in range(3, 9):                        # dihedral, order 2m
        base.append((m, [tuple((i + 1) % m for i in range(m)),
                         tuple((-i) % m for i in range(m))]))
    base.append((4, [(1, 0, 2, 3), (1, 2, 3, 0)]))                 # S4
    base.append((5, [(1, 0, 2, 3, 4), (1, 2, 3, 4, 0)]))           # S5
    base.append((4, [(1, 2, 0, 3), (1, 0, 3, 2)]))                 # A4
    base.append((5, [(1, 2, 3, 4, 0), (1, 2, 0, 3, 4)]))           # A5

    # GL(3,2) acting on the 8 vectors of F_2^3.
    def e_op(v):
        return v ^ ((v >> 1) & 1)

    def p_op(v):
        b0, b1, b2 = v & 1, (v >> 1) & 1, (v >> 2) & 1
        return b1 | (b2 << 1) | (b0 << 2)

    base.append((8, [tuple(e_op(v) for v in range(8)), tuple(p_op(v) for v in range(8))]))

    # PGL(2,7) acting on PG(1,7) = {0..6, 7 = infinity}.
    t = tuple([(i + 1) % 7 for i in range(7)] + [7])
    mu = tuple([(3 * i) % 7 for i in range(7)] + [7])
    inv_ = (7, 1, 4, 5, 2, 3, 6, 0)
    base.append((8, [t, mu, inv_]))

    for p in (5, 7, 11, 13):                     # affine groups AGL(1,p)
        g = _primroot(p)
        base.append((p, [tuple((i + 1) % p for i in range(p)),
                         tuple((g * i) % p for i in range(p))]))
    return base


def _candidates(lo, hi, rng):
    """Candidate groups with orders in [lo, hi] as (N, maker) pairs, largest first."""
    cands = []   # (N, elems or None, payload)

    base_ok = []  # (order, gens, deg) for groups of order <= hi
    for deg, gens in _base_groups():
        elems = _closure(gens, hi)
        if elems is None:
            continue
        N = len(elems)
        base_ok.append((N, gens, deg))
        if lo <= N <= hi:
            cands.append((N, elems))

    for (oA, gA, dA), (oB, gB, dB) in itertools.combinations(base_ok, 2):
        if lo <= oA * oB <= hi:
            g, dg = _pair(gA, dA, gB, dB)
            elems = _closure(g, hi)
            if elems is not None and len(elems) == oA * oB:
                cands.append((oA * oB, elems))

    ms = [m for m in range(3, hi // 2 + 1) if lo <= 2 * m <= hi]
    for m in rng.sample(ms, min(8, len(ms))):
        gens = [tuple((i + 1) % m for i in range(m)), tuple((-i) % m for i in range(m))]
        elems = _closure(gens, hi)
        if elems is not None:
            cands.append((len(elems), elems))

    sd = []
    for N in rng.sample(range(lo, hi + 1), min(10, hi - lo + 1)):
        gs = _groups(N)
        if gs:
            sd.append((N, rng.choice(gs)))
    if lo <= 168 <= hi:
        gs = _groups(168)
        if gs:
            sd.append((168, rng.choice(gs)))

    out = []
    for N, elems in cands:
        out.append((N, (lambda e=elems: _table(e))))
    for N, (m, k, r) in sd:
        out.append((N, (lambda m=m, k=k, r=r: _sd_table(m, k, r))))

    rng.shuffle(out)
    out.sort(key=lambda c: -c[0])
    return out[:MAX_CANDS]


def _unreached(N, T, invs, S, D):
    """Count (source, vertex) pairs not within distance D, for sources A_0 and B_0."""
    Sinv = [invs[g] for g in S]
    total = 0
    for src in (0, N):
        seen = bytearray(2 * N)
        seen[src] = 1
        count = 1
        frontier = [src]
        for _ in range(D):
            nxt = []
            for u in frontier:
                if u < N:
                    row = T[u]
                    for g in S:
                        v = N + row[g]
                        if not seen[v]:
                            seen[v] = 1
                            nxt.append(v)
                else:
                    row = T[u - N]
                    for h in Sinv:
                        v = row[h]
                        if not seen[v]:
                            seen[v] = 1
                            nxt.append(v)
            count += len(nxt)
            frontier = nxt
            if not frontier:
                break
        total += 2 * N - count
    return total


def _anneal(N, T, invs, d, D, rng, iters, deadline):
    """Simulated annealing over S = {0, s_1, ..., s_{d-1}} to zero unreached pairs."""
    if d - 1 > N - 1:
        return None
    S = [0] + rng.sample(range(1, N), d - 1)
    cur = _unreached(N, T, invs, S, D)
    for it in range(iters):
        if cur == 0:
            return S
        if time.monotonic() > deadline:
            break
        temp = max(0.05, 2.0 * (1.0 - it / iters))
        i = rng.randrange(1, d)
        c = rng.randrange(1, N)
        if c in S:
            continue
        S2 = S[:]
        S2[i] = c
        v = _unreached(N, T, invs, S2, D)
        if v <= cur or rng.random() < math.exp(-(v - cur) / temp):
            S, cur = S2, v
    return S if cur == 0 else None


def build(d, D, seed, time_limit):
    start = time.monotonic()
    deadline = start + max(0.5, min(0.8 * time_limit, time_limit - 4.0))
    rng = random.Random(seed)

    if d < 1 or D < 1:
        return 1, []

    best = (1, [])

    def consider(n, e):
        nonlocal best
        if n > best[0] and lib.is_valid(n, e, d, D):
            best = (n, e)

    # Record-matching case: incidence graph of PG(2, d-1).
    if D == 3 and lib.is_prime_power(d - 1):
        n, e = lib.projective_plane_incidence(d - 1)
        consider(n, e)
        return best

    # Safe baselines.
    if D >= 2:
        consider(*lib.haar_graph(d, range(d)))
    if D >= 3:
        pg = _best_pg(d)
        if pg is not None:
            consider(pg[0], pg[1])
    if D >= 4 and time.monotonic() < deadline:
        gq = _best_gq(d)
        if gq is not None:
            consider(gq[0], gq[1])

    if d < 2 or D < 2:
        return best

    # Bi-Cayley search over a broad family of groups (permutation groups,
    # direct products, dihedral, affine, GL(3,2), PGL(2,7), semidirect products).
    # Graph: A_x -- B_{x s} for s in S, |S| = d, on 2N vertices.
    Nmax = lib._moore_bound(d, D) // 2
    lo = d + 1
    if Nmax < lo:
        return best

    cands = _candidates(lo, Nmax, rng)
    cache = {}
    done = set()
    budget = 1.0

    while time.monotonic() < deadline and cands:
        for ci, (N, maker) in enumerate(cands):
            if time.monotonic() >= deadline:
                break
            if ci in done or 2 * N <= best[0]:
                continue
            if ci not in cache:
                if len(cache) >= MAX_CACHE:
                    cache.clear()
                cache[ci] = maker()
            T, invs = cache[ci]
            att = min(deadline, time.monotonic() + budget)
            S = _anneal(N, T, invs, d, D, rng, ITERS, att)
            if S is not None:
                done.add(ci)
                consider(2 * N, [(x, N + T[x][g]) for x in range(N) for g in S])

        budget *= 1.7
        if all(ci in done or 2 * N <= best[0] for ci, (N, _) in enumerate(cands)):
            break

    if not lib.is_valid(best[0], best[1], d, D):
        return 1, []
    return best
