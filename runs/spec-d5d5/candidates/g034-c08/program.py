# ----------------------------------------------------------------------------
# NEW IN THIS VERSION: bi-Cayley lifts over permutation groups.
#
# The parent only lifts over metacyclic groups Z_m x|_r Z_k. Many record-size
# lifts need non-metacyclic groups (e.g. PSL(2,7) of order 168, the record
# group for d=5, D=5). Here a group is given by permutation generators, its
# elements are enumerated by BFS closure (identity gets index 0), and
# multiplication/inverse tables are built from that. Direct products of small
# factors are generated by concatenating generators on disjoint point sets;
# their order is the product of the factor orders, so candidates are cheap to
# list. The annealed bi-Cayley search (_climb) then runs over these groups too.
# ----------------------------------------------------------------------------

def _closure(gens, cap):
    """Enumerate the group generated by permutation tuples; identity is index 0. None if above cap."""
    n = len(gens[0])
    ident = tuple(range(n))
    elems = [ident]
    index = {ident: 0}
    frontier = [ident]
    while frontier:
        nxt = []
        for x in frontier:
            for g in gens:
                y = tuple(x[j] for j in g)  # x composed with g
                if y not in index:
                    if len(elems) >= cap:
                        return None
                    index[y] = len(elems)
                    elems.append(y)
                    nxt.append(y)
        frontier = nxt
    return elems, index


def _cyc(m):
    return tuple((i + 1) % m for i in range(m))


def _refl(m):
    return tuple((-i) % m for i in range(m))


def _transp(n):
    return tuple([1, 0] + list(range(2, n)))


def _dp(A, B):
    """Generators of the direct product, acting on disjoint point sets."""
    n1 = len(A[0])
    n2 = len(B[0])
    out = []
    for a in A:
        out.append(tuple(a) + tuple(range(n1, n1 + n2)))
    for b in B:
        out.append(tuple(range(n1)) + tuple(n1 + x for x in b))
    return out


def _prim_root(p):
    for g in range(2, p):
        if len({pow(g, k, p) for k in range(1, p)}) == p - 1:
            return g
    return 1


def _psl_gens(p, pgl):
    """Generators of PSL(2,p) (or PGL(2,p) if pgl) on the projective line {0..p-1, p=inf}."""
    INF = p
    g = _prim_root(p)
    s = g if pgl else (g * g) % p
    gA = tuple((t + 1) % p if t < p else INF for t in range(p + 1))
    gM = tuple((s * t) % p if t < p else INF for t in range(p + 1))
    gI = tuple(0 if t == INF else (INF if t == 0 else (-pow(t, p - 2, p)) % p)
               for t in range(p + 1))
    return [gA, gM, gI]


def _agl_gens(p):
    g = _prim_root(p)
    return [tuple((t + 1) % p for t in range(p)), tuple((g * t) % p for t in range(p))]


_CANDS = None
_PERM_CACHE = {}


def _group_candidates():
    """Permutation-group candidates (order, name, gens) with orders in [20, 340], sorted by order."""
    global _CANDS
    if _CANDS is not None:
        return _CANDS
    base = []

    def add(name, gens):
        cl = _closure(gens, 400)
        if cl is not None and len(cl[0]) >= 2:
            base.append((len(cl[0]), name, gens))

    for m in range(2, 21):
        add("Z%d" % m, [_cyc(m)])
    for m in range(3, 13):
        add("D%d" % m, [_cyc(m), _refl(m)])
    add("S3", [_cyc(3), _transp(3)])
    add("S4", [_cyc(4), _transp(4)])
    add("S5", [_cyc(5), _transp(5)])
    add("PSL25", _psl_gens(5, False))
    add("PGL25", _psl_gens(5, True))
    add("PSL27", _psl_gens(7, False))
    add("PGL27", _psl_gens(7, True))
    for p in (5, 7, 11, 13):
        add("AGL1_%d" % p, _agl_gens(p))

    cands = [(N, name, gens) for N, name, gens in base if 20 <= N <= 340]
    for i in range(len(base)):
        for j in range(i + 1, len(base)):
            Ni, ni, gi = base[i]
            Nj, nj, gj = base[j]
            N = Ni * Nj
            if 20 <= N <= 340:
                cands.append((N, ni + "x" + nj, _dp(gi, gj)))
    cands.sort(key=lambda c: c[0])
    _CANDS = cands
    return _CANDS


def _perm_tables(name, gens):
    """(N, T, invs) for a permutation group, with T[x][g] = x*g and invs[g] = g^-1."""
    hit = _PERM_CACHE.get(name)
    if hit is not None:
        return hit
    elems, index = _closure(gens, 400)
    N = len(elems)
    T = [[index[tuple(x[j] for j in h)] for h in elems] for x in elems]
    invs = []
    for g in elems:
        inv = [0] * len(g)
        for i, j in enumerate(g):
            inv[j] = i
        invs.append(index[tuple(inv)])
    val = (N, T, invs)
    if len(_PERM_CACHE) >= 40:
        _PERM_CACHE.clear()
    _PERM_CACHE[name] = val
    return val


