import itertools
import math
import random
import time

import lib

ITERS = 300             # annealing steps per restart
MAX_SEMI = 60           # cap on semidirect-product candidates
START_BUDGET = 0.25     # seconds per candidate in the first pass


# ----------------------------------------------------------------------------
# Baseline families (fast, always valid when they pass lib.is_valid).
# ----------------------------------------------------------------------------

def _best_pg(d):
    """Incidence graph of PG(2, q) for the largest prime power q with q + 1 <= d."""
    for q in range(d - 1, 1, -1):
        if lib.is_prime_power(q):
            return lib.projective_plane_incidence(q)
    return None


def _gq_w(q):
    """Incidence graph of points and lines of the generalized quadrangle W(q); diameter 4."""
    F = lib.GF(q)
    pts = [v for v in itertools.product(range(q), repeat=4)
           if any(v) and next(c for c in v if c) == 1]
    index = {v: i for i, v in enumerate(pts)}
    P = len(pts)

    def norm(v):
        c = next(x for x in v if x)
        inv = F.inv(c)
        return tuple(F.mul(inv, x) for x in v)

    def form(x, y):
        t = F.sub(F.mul(x[0], y[1]), F.mul(x[1], y[0]))
        return F.add(t, F.sub(F.mul(x[2], y[3]), F.mul(x[3], y[2])))

    covered = set()
    lines = []
    for i in range(P):
        x = pts[i]
        for j in range(i + 1, P):
            if (i, j) in covered:
                continue
            y = pts[j]
            if form(x, y) != 0:
                continue
            L = set()
            for a in range(q):
                for b in range(q):
                    if a == 0 and b == 0:
                        continue
                    v = tuple(F.add(F.mul(a, x[k]), F.mul(b, y[k])) for k in range(4))
                    if any(v):
                        L.add(index[norm(v)])
            L = sorted(L)
            lines.append(L)
            for p in L:
                for r in L:
                    if p < r:
                        covered.add((p, r))

    edges = []
    for j, L in enumerate(lines):
        for p in L:
            edges.append((p, P + j))
    return 2 * P, edges


def _best_gq(d):
    """W(q) for the largest prime power q with q + 1 <= d, restricted to small q for speed."""
    for q in range(min(d - 1, 5), 1, -1):
        if lib.is_prime_power(q):
            return _gq_w(q)
    return None


# ----------------------------------------------------------------------------
# NEW: permutation-group library for bi-Cayley lifts.
#
# Semidirect products of cyclic groups (used by the parent) miss many groups
# of the right order. Record graphs for d=5, D=5 are lifts of order 168, and
# the groups below cover that range and beyond: GL(3,2), PGL(2,7), S4 x Z_k,
# A5 x Z_k, S5 x Z2, S3^3. Each group is given by permutation generators and
# its elements are generated by closure.
# ----------------------------------------------------------------------------

def _cycle(total, pts):
    """Permutation of range(total) that cycles the points in pts."""
    p = list(range(total))
    for a, b in zip(pts, pts[1:] + pts[:1]):
        p[a] = b
    return tuple(p)


def _perm_closure(gens, cap):
    """All elements of the permutation group generated by gens (sorted, identity first), or None if > cap."""
    n = len(gens[0])
    ident = tuple(range(n))
    seen = {ident}
    frontier = [ident]
    while frontier:
        nxt = []
        for x in frontier:
            for g in gens:
                y = tuple(x[i] for i in g)
                if y not in seen:
                    if len(seen) >= cap:
                        return None
                    seen.add(y)
                    nxt.append(y)
        frontier = nxt
    return sorted(seen)


def _product(A, B):
    """Direct product of two (gens, npts) groups acting on disjoint point sets."""
    (G, nG), (H, nH) = A, B
    gens = [g + tuple(range(nG, nG + nH)) for g in G]
    gens += [tuple(range(nG)) + tuple(nG + x for x in h) for h in H]
    return gens, nG + nH


def _sym(n):
    return [_cycle(n, list(range(n))), _cycle(n, [0, 1])], n


def _alt5():
    return [_cycle(5, [0, 1, 2]), _cycle(5, [0, 1, 2, 3, 4])], 5


def _cyclic(k):
    return [_cycle(k, list(range(k)))], k


def _gl32():
    """GL(3,2) acting on the 7 nonzero vectors of GF(2)^3."""
    def elem(i, j):
        def f(v):
            b = [(v >> t) & 1 for t in range(3)]
            b[i] ^= b[j]
            return b[0] | (b[1] << 1) | (b[2] << 2)
        return tuple(f(v) - 1 for v in range(1, 8))
    return [elem(0, 1), elem(1, 0), elem(1, 2), elem(2, 1)], 7


def _pgl27():
    """PGL(2,7) acting on the projective line 0..6 plus infinity (= 7)."""
    INF = 7

    def tab(f):
        return tuple(f(x) for x in range(8))

    shift = tab(lambda x: INF if x == INF else (x + 1) % 7)
    scale = tab(lambda x: INF if x == INF else (3 * x) % 7)

    def finv(x):
        if x == INF:
            return 0
        if x == 0:
            return INF
        return pow(x, 5, 7)

    return [shift, scale, tab(finv)], 8


def _table_from_perms(elems):
    """Multiplication table, element 0 = identity, and inverse indices for a perm group."""
    idx = {e: i for i, e in enumerate(elems)}
    T = [[idx[tuple(x[i] for i in g)] for g in elems] for x in elems]
    invs = []
    npts = len(elems[0])
    for g in elems:
        ip = [0] * npts
        for i, v in enumerate(g):
            ip[v] = i
        invs.append(idx[tuple(ip)])
    return T, invs


# ----------------------------------------------------------------------------
# Bi-Cayley search. Vertices A_x and B_y (x, y in G). Edge A_x -- B_{x s} for
# s in S, |S| = d. Identity WLOG in S. Diameter is checked from A_0 and B_0.
# ----------------------------------------------------------------------------

def _groups(N):
    """Semidirect parameters (m, k, r) with m*k = N, giving Z_m x|_r Z_k."""
    out = []
    for k in range(1, N + 1):
        if N % k:
            continue
        m = N // k
        for r in range(m):
            if math.gcd(r, m) == 1 and pow(r, k, m) == 1 % m:
                out.append((m, k, r))
    return out


def _unreached(N, T, invs, S, D):
    """Count (source, vertex) pairs not within distance D, for sources A_0 and B_0."""
    Sinv = [invs[g] for g in S]
    total = 0
    for src in (0, N):
        seen = bytearray(2 * N)
        seen[src] = 1
        count = 1
        frontier = [src]
        for _ in range(D):
            nxt = []
            for u in frontier:
                if u < N:
                    row = T[u]
                    for g in S:
                        v = N + row[g]
                        if not seen[v]:
                            seen[v] = 1
                            nxt.append(v)
                else:
                    row = T[u - N]
                    for h in Sinv:
                        v = row[h]
                        if not seen[v]:
                            seen[v] = 1
                            nxt.append(v)
            count += len(nxt)
            frontier = nxt
            if not frontier:
                break
        total += 2 * N - count
    return total


def _anneal(N, T, invs, d, D, rng, iters, deadline):
    """Simulated annealing over S = {0, s_1, ..., s_{d-1}} to zero unreached pairs."""
    S = [0] + rng.sample(range(1, N), d - 1)
    cur = _unreached(N, T, invs, S, D)
    for it in range(iters):
        if cur == 0:
            return S
        if time.monotonic() > deadline:
            break
        temp = max(0.05, 2.0 * (1.0 - it / iters))
        i = rng.randrange(1, d)
        c = rng.randrange(1, N)
        if c in S:
            continue
        S2 = S[:]
        S2[i] = c
        v = _unreached(N, T, invs, S2, D)
        if v <= cur or rng.random() < math.exp(-(v - cur) / temp):
            S, cur = S2, v
    return S if cur == 0 else None


def _candidate_specs(d, Nmax, rng):
    """Candidate groups (N, kind, payload) with d+1 <= N <= Nmax, sorted by N."""
    specs = []
    gl = _gl32()
    sym3, sym4, sym5, alt5 = _sym(3), _sym(4), _sym(5), _alt5()
    perm_gens = [gl, _pgl27(), _product(gl, _cyclic(2)), _product(sym5, _cyclic(2)),
                 _product(_product(sym3, sym3), sym3), _product(sym4, sym3)]
    perm_gens += [_product(alt5, _cyclic(k)) for k in range(2, 6)]
    perm_gens += [_product(sym4, _cyclic(k)) for k in range(2, 16)]
    for gens, npts in perm_gens:
        elems = _perm_closure(gens, Nmax)
        if elems is not None and d + 1 <= len(elems) <= Nmax:
            specs.append((len(elems), "perm", elems))
    semi = []
    for N in range(d + 1, Nmax + 1):
        for m, k, r in _groups(N):
            semi.append((N, "semi", (m, k, r)))
    rng.shuffle(semi)
    specs += semi[:MAX_SEMI]
    specs.sort(key=lambda t: t[0])
    return specs


def _table(entry):
    """Return (T, invs) for a candidate group entry."""
    N, kind, payload = entry
    if kind == "perm":
        return _table_from_perms(payload)
    m, k, r = payload
    order, mul, inv = lib.semidirect_group(m, k, r)
    T = [[mul(x, g) for g in range(N)] for x in range(N)]
    invs = [inv(g) for g in range(N)]
    return T, invs


def build(d, D, seed, time_limit):
    start = time.monotonic()
    deadline = start + 0.8 * time_limit
    rng = random.Random(seed)

    if d < 1 or D < 1:
        return 1, []

    best = (1, [])
    best_n = 1

    def consider(n, e):
        nonlocal best, best_n
        if n > best_n and lib.is_valid(n, e, d, D):
            best = (n, e)
            best_n = n

    # Record-matching case: incidence graph of PG(2, d-1).
    if D == 3 and lib.is_prime_power(d - 1):
        n, e = lib.projective_plane_incidence(d - 1)
        consider(n, e)
        return best

    if D >= 2:
        consider(*lib.haar_graph(d, range(d)))
    if D >= 3:
        pg = _best_pg(d)
        if pg is not None:
            consider(pg[0], pg[1])
    if D >= 4 and time.monotonic() < deadline:
        gq = _best_gq(d)
        if gq is not None:
            consider(gq[0], gq[1])

    if d < 2 or D < 2:
        return best

    Nmax = lib._moore_bound(d, D) // 2   # bi-Cayley graph has 2N vertices
    specs = _candidate_specs(d, Nmax, rng)

    # Ladder search: climb N upward; each success raises the floor.
    floor = best_n // 2
    cache = {}
    cands = [(i, e) for i, e in enumerate(specs) if e[0] > floor]
    budget = START_BUDGET

    while time.monotonic() < deadline and cands:
        any_success = False
        for i, entry in list(cands):
            now = time.monotonic()
            if now >= deadline:
                break
            N = entry[0]
            if N <= floor:
                continue
            if i not in cache:
                cache[i] = _table(entry)
            T, invs = cache[i]
            att_deadline = min(deadline, now + budget)
            S = None
            while time.monotonic() < att_deadline:
                S = _anneal(N, T, invs, d, D, rng, ITERS, att_deadline)
                if S is not None:
                    break
            if S is None:
                continue
            edges = [(x, N + T[x][g]) for x in range(N) for g in S]
            if lib.is_valid(2 * N, edges, d, D):
                any_success = True
                if 2 * N > best_n:
                    best = (2 * N, edges)
                    best_n = 2 * N
                floor = max(floor, N)
                cands = [(j, e) for j, e in cands if e[0] > floor]
        if not any_success:
            budget *= 2

    if not lib.is_valid(best[0], best[1], d, D):
        return 1, []
    return best
