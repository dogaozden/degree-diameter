import itertools
import math
import random
import time
from array import array

import lib

ITERS = 2000        # annealing steps per try
MAX_GROUPS = 12     # metacyclic groups tried per order in the fallback search


# ----------------------------------------------------------------------------
# Baseline families (fast, always valid when they pass lib.is_valid).
# ----------------------------------------------------------------------------

def _best_pg(d):
    """Incidence graph of PG(2, q) for the largest prime power q with q + 1 <= d."""
    for q in range(d - 1, 1, -1):
        if lib.is_prime_power(q):
            return lib.projective_plane_incidence(q)
    return None


def _gq_w(q):
    """Incidence graph of points and lines of the generalized quadrangle W(q); diameter 4."""
    F = lib.GF(q)
    pts = [v for v in itertools.product(range(q), repeat=4)
           if any(v) and next(c for c in v if c) == 1]
    index = {v: i for i, v in enumerate(pts)}
    P = len(pts)

    def norm(v):
        c = next(x for x in v if x)
        inv = F.inv(c)
        return tuple(F.mul(inv, x) for x in v)

    def form(x, y):
        t = F.sub(F.mul(x[0], y[1]), F.mul(x[1], y[0]))
        return F.add(t, F.sub(F.mul(x[2], y[3]), F.mul(x[3], y[2])))

    covered = set()
    lines = []
    for i in range(P):
        x = pts[i]
        for j in range(i + 1, P):
            if (i, j) in covered:
                continue
            y = pts[j]
            if form(x, y) != 0:
                continue
            L = set()
            for a in range(q):
                for b in range(q):
                    if a == 0 and b == 0:
                        continue
                    v = tuple(F.add(F.mul(a, x[k]), F.mul(b, y[k])) for k in range(4))
                    if any(v):
                        L.add(index[norm(v)])
            L = sorted(L)
            lines.append(L)
            for p in L:
                for r in L:
                    if p < r:
                        covered.add((p, r))

    edges = []
    for j, L in enumerate(lines):
        for p in L:
            edges.append((p, P + j))
    return 2 * P, edges


def _best_gq(d):
    """W(q) for the largest prime power q with q + 1 <= d, restricted to small q for speed."""
    for q in range(min(d - 1, 5), 1, -1):
        if lib.is_prime_power(q):
            return _gq_w(q)
    return None


# ----------------------------------------------------------------------------
# NEW IDEA: bi-Cayley graphs over PERMUTATION groups.
#
# The parent only used metacyclic groups Z_m x| Z_k. Many record-sized
# groups are not metacyclic, e.g. PSL(2,7) (order 168, the record's half)
# and PGL(2,7) (order 336). We realise such groups as permutation groups
# by closing a few generators under composition, then use the group's
# multiplication table as the base of a bi-Cayley graph:
#     A_x -- B_{x s},  s in S,  |S| = d.
# Left multiplication is an automorphism, so the same two-source BFS
# (from A_0 and B_0) decides the diameter.
#
# Families: PSL(2,p) = <x+1, -1/x>, PGL(2,p) adds x -> g x (g a primitive
# root), and AGL(1,p) = <x+1, g x> acting on p points.
# ----------------------------------------------------------------------------

def _prim_root(p):
    """Smallest primitive root modulo the prime p."""
    for g in range(2, p):
        if len({pow(g, e, p) for e in range(p - 1)}) == p - 1:
            return g
    return 1


def _perm_tables(gens, order):
    """Multiplication and inverse tables of the permutation group generated by gens.

    Returns (T, invs) with identity index 0, or None if the closure has a size other than order.
    T[x][g] is the index of elems[x] o elems[g]; rows are compact arrays.
    """
    n = len(gens[0])
    ident = tuple(range(n))
    elems = [ident]
    index = {ident: 0}
    frontier = [ident]
    while frontier:
        nxt = []
        for x in frontier:
            for g in gens:
                y = tuple(g[i] for i in x)
                if y not in index:
                    if len(elems) >= order:
                        return None
                    index[y] = len(elems)
                    elems.append(y)
                    nxt.append(y)
        frontier = nxt
    if len(elems) != order:
        return None
    rng_n = range(n)
    T = []
    for ex in elems:
        T.append(array('H', [index[tuple(ex[e[i]] for i in rng_n)] for e in elems]))
    invs = [int(T[g].index(0)) for g in range(order)]
    return T, invs


def _perm_specs(lo, hi):
    """Permutation-group specs (order, generators) with lo <= order <= hi."""
    raw = []
    for p in (5, 7, 11, 13):
        g = _prim_root(p)
        shift = tuple([(x + 1) % p for x in range(p)] + [p])
        inv = tuple([p] + [(-pow(x, p - 2, p)) % p for x in range(1, p)] + [0])
        scale = tuple([(g * x) % p for x in range(p)] + [p])
        raw.append((p * (p * p - 1) // 2, [shift, inv]))         # PSL(2, p)
        raw.append((p * (p * p - 1), [shift, inv, scale]))       # PGL(2, p)
    for p in (5, 7, 11, 13, 17, 19):
        g = _prim_root(p)
        shift = tuple((x + 1) % p for x in range(p))
        scale = tuple((g * x) % p for x in range(p))
        raw.append((p * (p - 1), [shift, scale]))                # AGL(1, p)
    return [{"N": N, "gens": gens, "tab": None, "dead": False}
            for N, gens in raw if lo <= N <= hi]


# ----------------------------------------------------------------------------
# Metacyclic fallback (parent's family): Z_m x|_r Z_k of order N.
# ----------------------------------------------------------------------------

def _groups(N):
    """Return semidirect parameters (m, k, r) with m*k = N, giving Z_m x|_r Z_k."""
    out = []
    for k in range(1, N + 1):
        if N % k:
            continue
        m = N // k
        for r in range(m):
            if math.gcd(r, m) == 1 and pow(r, k, m) == 1 % m:
                out.append((m, k, r))
    return out


def _meta_tables(m, k, r, N):
    """Multiplication and inverse tables of Z_m x|_r Z_k (identity index 0)."""
    _, mul, inv = lib.semidirect_group(m, k, r)
    T = [array('H', [mul(x, g) for g in range(N)]) for x in range(N)]
    invs = [inv(g) for g in range(N)]
    return T, invs


# ----------------------------------------------------------------------------
# Bi-Cayley evaluation and annealing (shared by all families).
# ----------------------------------------------------------------------------

def _unreached(N, T, invs, S, D):
    """Count (source, vertex) pairs not within distance D, for sources A_0 and B_0."""
    Sinv = [invs[g] for g in S]
    total = 0
    for src in (0, N):
        seen = bytearray(2 * N)
        seen[src] = 1
        count = 1
        frontier = [src]
        for _ in range(D):
            nxt = []
            for u in frontier:
                if u < N:
                    row = T[u]
                    for g in S:
                        v = N + row[g]
                        if not seen[v]:
                            seen[v] = 1
                            nxt.append(v)
                else:
                    row = T[u - N]
                    for h in Sinv:
                        v = row[h]
                        if not seen[v]:
                            seen[v] = 1
                            nxt.append(v)
            count += len(nxt)
            frontier = nxt
            if not frontier:
                break
        total += 2 * N - count
    return total


def _anneal(N, T, invs, d, D, rng, iters, deadline):
    """Simulated annealing over S = {0, s_1, ..., s_{d-1}} to zero unreached pairs."""
    S = [0] + rng.sample(range(1, N), d - 1)
    cur = _unreached(N, T, invs, S, D)
    for it in range(iters):
        if cur == 0:
            return S
        if time.monotonic() > deadline:
            break
        temp = max(0.05, 2.0 * (1.0 - it / iters))
        i = rng.randrange(1, d)
        c = rng.randrange(1, N)
        if c in S:
            continue
        S2 = S[:]
        S2[i] = c
        v = _unreached(N, T, invs, S2, D)
        if v <= cur or rng.random() < math.exp(-(v - cur) / temp):
            S, cur = S2, v
    return S if cur == 0 else None


def _try(N, T, invs, d, D, rng, until):
    """Repeated annealing restarts on one group until success or the time is up."""
    while time.monotonic() < until:
        S = _anneal(N, T, invs, d, D, rng, ITERS, until)
        if S is not None:
            return S
    return None


def _perm_search(specs, d, D, rng, deadline, consider):
    """Search permutation-group families, largest order first, with doubling budgets."""
    budget = 2.5
    found = 0
    while time.monotonic() < deadline:
        live = [s for s in specs if not s["dead"] and s["N"] > found]
        if not live:
            return
        success = False
        for s in sorted(live, key=lambda s: -s["N"]):
            now = time.monotonic()
            if now >= deadline:
                return
            if s["tab"] is None:
                s["tab"] = _perm_tables(s["gens"], s["N"])
                if s["tab"] is None:
                    s["dead"] = True
                    continue
            T, invs = s["tab"]
            N = s["N"]
            S = _try(N, T, invs, d, D, rng, min(deadline, now + budget))
            if S is not None:
                consider(2 * N, [(x, N + T[x][g]) for x in range(N) for g in S])
                found = N
                success = True
                break
        if not success:
            budget *= 2


def _meta_attempt(N, d, D, rng, until):
    """Try up to MAX_GROUPS metacyclic groups of order N, one anneal each."""
    groups = _groups(N)
    rng.shuffle(groups)
    for m, k, r in groups[:MAX_GROUPS]:
        if time.monotonic() > until:
            return None
        T, invs = _meta_tables(m, k, r, N)
        S = _anneal(N, T, invs, d, D, rng, ITERS, until)
        if S is not None:
            return T, S
    return None


def _meta_search(d, D, rng, deadline, lo, hi, consider):
    """Fallback search over metacyclic groups, descending order with doubling budgets."""
    cands = set(range(lo, hi + 1))
    budget = 0.4
    while time.monotonic() < deadline and cands:
        success = False
        for N in sorted(cands, reverse=True):
            now = time.monotonic()
            if now >= deadline:
                break
            res = _meta_attempt(N, d, D, rng, min(deadline, now + budget))
            if res is None:
                continue
            T, S = res
            consider(2 * N, [(x, N + T[x][g]) for x in range(N) for g in S])
            cands = {M for M in cands if M > N}
            success = True
            break
        if not success:
            budget *= 2


# ----------------------------------------------------------------------------
# Entry point.
# ----------------------------------------------------------------------------

def build(d, D, seed, time_limit):
    start = time.monotonic()
    deadline = start + 0.8 * time_limit
    rng = random.Random(seed)

    if d < 1 or D < 1:
        return 1, []

    best = (1, [])
    best_n = 1

    def consider(n, e):
        nonlocal best, best_n
        if n > best_n and lib.is_valid(n, e, d, D):
            best = (n, e)
            best_n = n

    # Record-matching case: incidence graph of PG(2, d-1).
    if D == 3 and lib.is_prime_power(d - 1):
        n, e = lib.projective_plane_incidence(d - 1)
        consider(n, e)
        return best

    if D >= 2:
        consider(*lib.haar_graph(d, range(d)))
    if D >= 3:
        pg = _best_pg(d)
        if pg is not None:
            consider(pg[0], pg[1])
    if D >= 4 and time.monotonic() < deadline:
        gq = _best_gq(d)
        if gq is not None:
            consider(gq[0], gq[1])

    if d < 2 or D < 2:
        return best

    Nmax = lib._moore_bound(d, D) // 2   # bi-Cayley graph has 2N vertices
    top = min(Nmax, Nmax // 2 + 3)

    # Phase 1: permutation-group bi-Cayley graphs (PGL/PSL/AGL), largest first.
    perm_end = start + 0.55 * (deadline - start)
    specs = _perm_specs(max(d + 1, best_n // 2 + 1), Nmax)
    _perm_search(specs, d, D, rng, perm_end, consider)

    # Phase 2: metacyclic fallback for the remaining time, above the current best.
    lo = max(d + 1, best_n // 2 + 1)
    _meta_search(d, D, rng, deadline, lo, top, consider)

    if not lib.is_valid(best[0], best[1], d, D):
        return 1, []
    return best
