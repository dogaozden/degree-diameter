# ----------------------------------------------------------------------------
# C engine 1: cyclic Haar-graph annealer (new in this version).
#
# Haar graph H(Z_m, S): a_i ~ b_{i+s} for s in S, |S| = d. Translations act
# transitively on each side, so every pair of vertices is equivalent to a pair
# involving a_0 or b_0. The number of ordered bad pairs is therefore
#     m * (unreached(a_0) + unreached(b_0)),
# and only two BFS runs are needed per move. The search keeps 0 in S (a
# translation of S gives an isomorphic graph) and anneals the other d-1 residues
# to minimise the unreached count. It bisects on m to find the largest order
# that still has a valid S.
# ----------------------------------------------------------------------------

C_HAAR_SOURCE = r"""
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>
#include <math.h>
#include <time.h>

typedef uint64_t u64;
#define MAXD 64

static u64 rs = 88172645463325252ULL;
static u64 rnd(void) { rs ^= rs << 13; rs ^= rs >> 7; rs ^= rs << 17; return rs; }
static int rint_(int n) { return (int)(rnd() % (u64)n); }
static double rdbl(void) { return (double)(rnd() >> 11) * (1.0 / 9007199254740992.0); }

static int d_, D_, M, Mcap;
static int S[MAXD], bestS[MAXD], bestM = 0;
static int *stamp, *fa, *fb;
static int curstamp = 0;
static double limit_s;
static clock_t c0;

static double elapsed(void) { return (double)(clock() - c0) / CLOCKS_PER_SEC; }

/* Number of vertices within distance D_ of src (src included). Vertices:
   a_i = i (0..M-1), b_j = M + j. a_i ~ b_{i+s}, b_j ~ a_{j-s}. */
static int reached(int src) {
    int *frontier = fa, *nxt = fb;
    int cntv = 1, nf = 1;
    curstamp++;
    frontier[0] = src;
    stamp[src] = curstamp;
    for (int lev = 0; lev < D_ && nf > 0; lev++) {
        int nn = 0;
        for (int k = 0; k < nf; k++) {
            int v = frontier[k];
            if (v < M) {
                for (int t = 0; t < d_; t++) {
                    int u = v + S[t];
                    if (u >= M) u -= M;
                    u += M;
                    if (stamp[u] != curstamp) { stamp[u] = curstamp; nxt[nn++] = u; }
                }
            } else {
                int j = v - M;
                for (int t = 0; t < d_; t++) {
                    int u = j - S[t];
                    if (u < 0) u += M;
                    if (stamp[u] != curstamp) { stamp[u] = curstamp; nxt[nn++] = u; }
                }
            }
        }
        cntv += nn;
        int *tmp = frontier; frontier = nxt; nxt = tmp;
        nf = nn;
    }
    return cntv;
}

static long long cost_of(void) {
    int ra = reached(0);
    int rb = reached(M);
    return (long long)(2 * M - ra) + (long long)(2 * M - rb);
}

/* Random residue not equal to S[t] for t < n, t != idx. */
static int fresh_excl(int idx, int n) {
    for (;;) {
        int r = rint_(M), ok = 1;
        for (int t = 0; t < n; t++) {
            if (t != idx && S[t] == r) { ok = 0; break; }
        }
        if (ok) return r;
    }
}

static int anneal(long long iters) {
    const double T0 = 2.0, T1 = 0.05;
    S[0] = 0;
    for (int t = 1; t < d_; t++) S[t] = fresh_excl(-1, t);
    long long cost = cost_of();
    for (long long it = 0; it < iters && cost > 0; it++) {
        if ((it & 255) == 0 && elapsed() > limit_s) break;
        double fr = (double)it / (double)iters;
        double T = T0 * pow(T1 / T0, fr);
        int t = 1 + rint_(d_ - 1);
        int old = S[t];
        S[t] = fresh_excl(t, d_);
        long long nc = cost_of();
        long long delta = nc - cost;
        if (delta <= 0 || rdbl() < exp(-(double)delta / T)) {
            cost = nc;
        } else {
            S[t] = old;
        }
    }
    return cost == 0;
}

int main(int argc, char **argv) {
    if (argc < 7) { printf("0 0\n"); return 0; }
    d_ = atoi(argv[1]);
    D_ = atoi(argv[2]);
    rs ^= (u64)strtoull(argv[3], NULL, 10) * 0x9E3779B97F4A7C15ULL;
    if (!rs) rs = 1;
    limit_s = atof(argv[4]);
    int mstart = atoi(argv[5]);
    Mcap = atoi(argv[6]);
    if (d_ < 2 || d_ > MAXD || D_ < 1 || mstart < 1 || Mcap < d_ + 1) {
        printf("0 0\n");
        return 0;
    }
    size_t cells = 2 * (size_t)Mcap + 4;
    stamp = calloc(cells, sizeof(int));
    fa = malloc(sizeof(int) * cells);
    fb = malloc(sizeof(int) * cells);
    if (!stamp || !fa || !fb) { printf("0 0\n"); return 0; }

    c0 = clock();
    int lo = 0, hi = 0, m = mstart, retries = 0;
    long long iters = 20000;
    while (elapsed() < limit_s) {
        if (m > Mcap) m = Mcap;
        if (m < d_ + 1) break;
        M = m;
        int ok = anneal(iters);
        if (ok) {
            lo = m;
            bestM = m;
            memcpy(bestS, S, sizeof(int) * d_);
            if (hi && m >= hi) hi = 0;
        } else {
            if (!hi || m < hi) hi = m;
        }
        if (lo == 0) {
            m = m - (m / 16 > 1 ? m / 16 : 1);
        } else if (lo >= Mcap) {
            break;
        } else if (hi == 0) {
            m = lo + (lo / 16 > 1 ? lo / 16 : 1);
        } else if (hi - lo > 1) {
            m = (lo + hi) / 2;
        } else {
            if (++retries > 3) break;
            iters *= 2;
            m = hi;
        }
    }

    if (bestM == 0) { printf("0 0\n"); return 0; }
    int n = 2 * bestM, E = bestM * d_;
    printf("%d %d\n", n, E);
    for (int i = 0; i < bestM; i++) {
        for (int t = 0; t < d_; t++) {
            int j = (i + bestS[t]) % bestM;
            printf("%d %d\n", i, bestM + j);
        }
    }
    return 0;
}
"""


# ----------------------------------------------------------------------------
# C engine 2: bipartite edge-toggle annealer with vertex growth.
#
# The state is a bipartite graph with max degree d. A move toggles one
# cross-side pair (a, b): if a or b is full, one of its edges is dropped
# first. The cost is the number of ordered vertex pairs at distance > D,
# computed with bitset ball expansion. Whenever the cost reaches zero, the
# current valid graph is saved and two isolated vertices (one per side) are
# added, so the search keeps growing the graph while time remains.
# ----------------------------------------------------------------------------

C_SOURCE = r"""
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>
#include <math.h>
#include <time.h>

typedef uint64_t u64;

static u64 rs = 88172645463325252ULL;
static u64 rnd(void) { rs ^= rs << 13; rs ^= rs >> 7; rs ^= rs << 17; return rs; }
static int rint_(int n) { return (int)(rnd() % (u64)n); }
static double rdbl(void) { return (double)(rnd() >> 11) * (1.0 / 9007199254740992.0); }

static int d_, D_, cap_n, cap_w, N, W;
static int *deg, *adj, *side, *bestEu, *bestEv;
static u64 *bufA, *bufB;
static int best_n = 0, best_m = 0;

static int isadj(int a, int b) {
    for (int i = 0; i < deg[a]; i++) if (adj[a * d_ + i] == b) return 1;
    return 0;
}
static void delE1(int a, int b) {
    for (int i = 0; i < deg[a]; i++) {
        if (adj[a * d_ + i] == b) {
            adj[a * d_ + i] = adj[a * d_ + deg[a] - 1];
            deg[a]--;
            return;
        }
    }
}
static void addE(int a, int b) {
    adj[a * d_ + deg[a]++] = b;
    adj[b * d_ + deg[b]++] = a;
}
static void delE(int a, int b) { delE1(a, b); delE1(b, a); }

/* Ordered pairs (u, v) with distance > D_. Zero means the graph is valid. */
static long long bad_pairs(void) {
    u64 *cur = bufA, *alt = bufB;
    W = (N + 63) / 64;
    memset(cur, 0, sizeof(u64) * (size_t)N * (size_t)cap_w);
    for (int v = 0; v < N; v++) cur[(size_t)v * cap_w + (v >> 6)] |= 1ULL << (v & 63);
    for (int it = 0; it < D_; it++) {
        int changed = 0;
        for (int v = 0; v < N; v++) {
            u64 *x = alt + (size_t)v * cap_w;
            u64 *r = cur + (size_t)v * cap_w;
            for (int w = 0; w < W; w++) x[w] = r[w];
            for (int i = 0; i < deg[v]; i++) {
                u64 *q = cur + (size_t)adj[v * d_ + i] * cap_w;
                for (int w = 0; w < W; w++) x[w] |= q[w];
            }
            for (int w = 0; w < W; w++) if (x[w] != r[w]) changed = 1;
        }
        u64 *t = cur; cur = alt; alt = t;
        if (!changed) break;
    }
    long long cnt = 0;
    for (int v = 0; v < N; v++) {
        u64 *r = cur + (size_t)v * cap_w;
        for (int w = 0; w < W; w++) cnt += __builtin_popcountll(r[w]);
    }
    return (long long)N * N - cnt;
}

static void save_best(void) {
    int m = 0;
    for (int v = 0; v < N; v++) {
        for (int i = 0; i < deg[v]; i++) {
            int u = adj[v * d_ + i];
            if (u > v) { bestEu[m] = v; bestEv[m] = u; m++; }
        }
    }
    best_n = N;
    best_m = m;
}

static void grow_pair(void) {
    side[N] = 0; deg[N] = 0;
    side[N + 1] = 1; deg[N + 1] = 0;
    N += 2;
}

int main(int argc, char **argv) {
    if (argc < 5) return 1;
    d_ = atoi(argv[1]);
    D_ = atoi(argv[2]);
    rs ^= (u64)strtoull(argv[3], NULL, 10) * 0x9E3779B97F4A7C15ULL;
    if (!rs) rs = 1;
    double limit = atof(argv[4]);
    int grow_max = argc > 5 ? atoi(argv[5]) : 60;

    int n0 = 0, m0 = 0;
    if (scanf("%d %d", &n0, &m0) != 2) { n0 = 0; m0 = 0; }
    if (d_ < 1 || D_ < 1 || n0 < 2 || n0 > 1000000 || grow_max < 0) {
        printf("0 0\n");
        return 0;
    }
    cap_n = n0 + 2 * grow_max + 2;
    cap_w = (cap_n + 63) / 64;
    deg = calloc(cap_n, sizeof(int));
    side = malloc(sizeof(int) * (size_t)cap_n);
    adj = malloc(sizeof(int) * (size_t)cap_n * d_);
    bestEu = malloc(sizeof(int) * (size_t)cap_n * d_);
    bestEv = malloc(sizeof(int) * (size_t)cap_n * d_);
    bufA = malloc(sizeof(u64) * (size_t)cap_n * cap_w);
    bufB = malloc(sizeof(u64) * (size_t)cap_n * cap_w);
    if (!deg || !side || !adj || !bestEu || !bestEv || !bufA || !bufB) {
        printf("0 0\n");
        return 0;
    }

    N = n0;
    for (int i = 0; i < m0; i++) {
        int u, v;
        if (scanf("%d %d", &u, &v) != 2) break;
        if (u < 0 || v < 0 || u >= N || v >= N || u == v) continue;
        if (deg[u] >= d_ || deg[v] >= d_ || isadj(u, v)) continue;
        addE(u, v);
    }

    /* Bipartition by BFS; isolated vertices take the side of their root. */
    for (int v = 0; v < N; v++) side[v] = -1;
    int *q = malloc(sizeof(int) * (size_t)cap_n);
    for (int s = 0; s < N; s++) {
        if (side[s] != -1) continue;
        side[s] = 0;
        int h = 0, t = 0;
        q[t++] = s;
        while (h < t) {
            int v = q[h++];
            for (int i = 0; i < deg[v]; i++) {
                int u = adj[v * d_ + i];
                if (side[u] == -1) { side[u] = 1 - side[v]; q[t++] = u; }
            }
        }
    }
    free(q);

    const double T0 = 30.0, T1 = 0.3;
    clock_t c0 = clock();
    long long cost = bad_pairs();
    if (cost == 0 && N > best_n) {
        save_best();
        if (N + 2 <= cap_n) { grow_pair(); cost = bad_pairs(); }
    }

    while (1) {
        double el = (double)(clock() - c0) / CLOCKS_PER_SEC;
        if (el >= limit) break;
        double frac = el / limit;
        double T = T0 * pow(T1 / T0, frac);

        int a = -1, b = -1;
        for (int t = 0; t < 50; t++) {
            int x = rint_(N), y = rint_(N);
            if (x == y || side[x] == side[y] || isadj(x, y)) continue;
            a = x; b = y;
            break;
        }
        if (a < 0) continue;

        int xa = -1, xb = -1;
        if (deg[a] == d_) { xa = adj[a * d_ + rint_(deg[a])]; delE(a, xa); }
        if (deg[b] == d_) { xb = adj[b * d_ + rint_(deg[b])]; delE(b, xb); }
        addE(a, b);

        long long nc = bad_pairs();
        long long delta = nc - cost;
        if (delta <= 0 || rdbl() < exp(-(double)delta / T)) {
            cost = nc;
            if (cost == 0 && N > best_n) {
                save_best();
                if (N + 2 <= cap_n) { grow_pair(); cost = bad_pairs(); }
            }
        } else {
            delE(a, b);
            if (xa >= 0) addE(a, xa);
            if (xb >= 0) addE(b, xb);
        }
    }

    if (best_n == 0) {
        printf("0 0\n");
        return 0;
    }
    printf("%d %d\n", best_n, best_m);
    for (int i = 0; i < best_m; i++) printf("%d %d\n", bestEu[i], bestEv[i]);
    return 0;
}
"""


