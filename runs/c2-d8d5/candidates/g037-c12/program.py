class _Best:
    """Holds the current best valid graph; consider() only accepts larger valid graphs."""

    def __init__(self, graph, d, D):
        self.graph = graph
        self.d = d
        self.D = D

    def best_n(self):
        return self.graph[0]

    def __call__(self, n, e):
        """Return the new graph if it is a larger valid graph, else None."""
        if n > self.graph[0] and lib.is_valid(n, e, self.d, self.D):
            self.graph = (n, e)
            return self.graph
        return None


def build(d, D, seed, time_limit):
    t0 = time.monotonic()
    usable = max(1.0, 0.85 * time_limit - 2.0)
    end = t0 + usable
    rng = random.Random(seed)

    if d < 1 or D < 1:
        return 1, []
    if D == 1:
        return 2, [(0, 1)]

    # Safe fallback: K_{d,d} has diameter 2.
    holder = _Best(lib.haar_graph(d, range(d)), d, D)

    # Exact constructions.
    if D >= 3:
        pg = _best_pg(d)
        if pg is not None:
            holder(pg[0], pg[1])
            if D == 3 and lib.is_prime_power(d - 1):
                return holder.graph
    if D == 3 and d - 2 >= 3 and lib.is_prime_power(d - 2):
        try:
            ar = lib.araujo_lopez_graph(d - 2)
            holder(ar[0], ar[1])
        except (ValueError, RuntimeError):
            pass
    if D == 4 and time.monotonic() < end:
        gq = _best_gq(d)
        if gq is not None:
            holder(gq[0], gq[1])
            if d - 1 <= 9 and lib.is_prime_power(d - 1):
                return holder.graph

    if D >= 2:
        # Phase 1 (Python): coordinate descent over voltages of semidirect lifts.
        try:
            _descent_phase(d, D, rng, t0 + usable * 0.8, holder)
        except Exception:
            pass

        # Phase 2 (C): lift + grow-by-two from the best graph so far.
        c_budget = end - time.monotonic() - 0.5
        if c_budget > 1.0:
            try:
                bn, be = holder.graph
                text = lib.run_c(C_SOURCE, [d, D, seed, round(c_budget, 2)],
                                 stdin_graph=(bn, be), timeout=c_budget + 8)
                out = lib.parse_graph_text(text)
                holder(out[0], out[1])
            except (RuntimeError, ValueError):
                pass

    best = holder.graph
    if not lib.is_valid(best[0], best[1], d, D):
        best = lib.haar_graph(d, range(d))
    return best
