"""Bipartite degree-diameter search.

Phase A (C): Haar graphs A_g ~ B_{g s} (s in S, |S| = d) over semidirect groups
Z_M x| Z_K of order N. The diameter condition reduces to covering the group by
products of <= D/2 elements of T0 = S S^-1 (and similar sets), which is a fast
simulated-annealing objective over S. Output has 2N vertices.
Phase B (Python): bi-Cayley lift search seeded from the best graph.
Phase C (C): lift + grow-by-two repair from the best graph.
"""
