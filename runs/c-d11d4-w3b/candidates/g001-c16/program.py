"""Program: Generalized-quadrangle start plus spare-slot growth for D = 4, lifts as the fallback.

For D = 4 the Python side builds the incidence graph of the generalized quadrangle W(q),
with q the largest prime power with q + 1 <= d. It is bipartite, diameter 4, and (q+1)-regular,
so for d > q + 1 every vertex has spare degree. The C engine then grows the graph by two
vertices at a time: each new point and line joins the spare slots of the old graph, the
remaining spare slots are filled with edges between far-apart pairs, and degree-preserving
edge swaps anneal away the remaining bad pairs. Where no start exists, the voltage-lift
search from the starter runs as before.
"""
import itertools
