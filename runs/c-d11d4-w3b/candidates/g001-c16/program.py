def _largest_prime_power_at_most(m):
    """Largest prime power q with 2 <= q <= m, or None."""
    for q in range(m, 1, -1):
        if lib.is_prime_power(q):
            return q
    return None


def gq_incidence(q):
    """Incidence graph of the generalized quadrangle W(q), q a prime power.

    Points: projective points of PG(3, q). Lines: totally isotropic lines of the symplectic
    form x0*y1 - x1*y0 + x2*y3 - x3*y2. Order 2(q+1)(q^2+1), degree q+1, diameter 4.
    Returns (n, edges), or None if the line count is off.
    """
    F = lib.GF(q)
    M = F.mul_table.tolist()
    A = F.add_table.tolist()
    NG = [F.neg(a) for a in range(q)]
    INV = [0] + [F.inv(a) for a in range(1, q)]

    def norm(v):
        for c in v:
            if c:
                i = INV[c]
                return tuple(M[i][x] for x in v)
        return None

    pts = sorted({norm(v) for v in itertools.product(range(q), repeat=4) if any(v)})
    index = {p: i for i, p in enumerate(pts)}

    def form(x, y):
        s = A[M[x[0]][y[1]]][NG[M[x[1]][y[0]]]]
        t = A[M[x[2]][y[3]]][NG[M[x[3]][y[2]]]]
        return A[s][t]

    lines = set()
    for i, p in enumerate(pts):
        for j in range(i + 1, len(pts)):
            r = pts[j]
            if form(p, r) != 0:
                continue
            line = {i, j}
            for t in range(1, q):
                v = tuple(A[p[k]][M[t][r[k]]] for k in range(4))
                line.add(index[norm(v)])
            lines.add(frozenset(line))
    lines = sorted(lines, key=sorted)
    if len(lines) != (q + 1) * (q * q + 1):
        return None
    m = len(pts)
    edges = [(pi, m + li) for li, L in enumerate(lines) for pi in L]
    return 2 * m, edges


def known_start(d, D):
    """Best graph Python can build directly for (d, D), or None."""
    if D == 3 and lib.is_prime_power(d - 1):
        return lib.projective_plane_incidence(d - 1)   # Moore graph: optimal
    if D == 3 and d - 2 >= 3 and lib.is_prime_power(d - 2):
        return lib.araujo_lopez_graph(d - 2)           # record graphs of order 2(q^2+q+5)
    if D == 4 and d >= 3:
        q = _largest_prime_power_at_most(d - 1)
        if q is not None:
            g = gq_incidence(q)
            if g is not None and lib.is_valid(g[0], g[1], d, 4):
                return g
    return None


def build(d, D, seed, time_limit):
    t0 = time.monotonic()
    start = known_start(d, D)
    best = start if start is not None else lib.haar_graph(d, range(d))   # K_{d,d}: always valid
    budget = 0.85 * time_limit - (time.monotonic() - t0) - 1.0
    if best[0] >= lib.moore_bound(d, D):
        budget = min(budget, 0.5)   # nothing beats a Moore graph; just exercise the C engine
    if budget > 0.2:
        text = lib.run_c(C_SOURCE, [d, D, seed, budget], stdin_graph=start, timeout=budget + 5)
        out = lib.parse_graph_text(text)
        if out[0] > best[0] and lib.is_valid(*out, d, D):
            best = out
    return best
