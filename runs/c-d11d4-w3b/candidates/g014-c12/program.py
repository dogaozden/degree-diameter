def _sample_group(G, rng):
    """Return (order, mul) for a random semidirect product Z_m x| Z_k2 of order G, or None."""
    for _ in range(60):
        k2 = rng.randint(1, 12)
        if G % k2:
            continue
        m = G // k2
        if m < 2:
            continue
        if k2 == 1:
            r = 1
        else:
            cands = [r for r in rng.sample(range(1, m), min(m - 1, 40))
                     if math.gcd(r, m) == 1 and pow(r, k2, m) == 1 % m]
            if not cands:
                continue
            r = rng.choice(cands)
        try:
            order, mul, _ = lib.semidirect_group(m, k2, r)
        except ValueError:
            continue
        return order, mul
    return None


def _group_search(d, D, k, G, rng, iters, deadline):
    """Hill-climb dart voltages in a group of order about G over a random d-regular base."""
    g = _sample_group(G, rng)
    if g is None:
        return None
    order, mul = g
    perms = [rng.sample(range(k), k) for _ in range(d)]
    darts = [[i, k + p[i], rng.randrange(order)] for p in perms for i in range(k)]

    def evaluate():
        n, e = lib.group_lift(2 * k, [tuple(x) for x in darts], order, mul)
        return n, e, lib.bad_pairs(n, e, D)

    n, e, c = evaluate()
    for _ in range(iters):
        if c == 0 or time.monotonic() > deadline:
            break
        if order < 2:
            break
        j = rng.randrange(len(darts))
        old = darts[j][2]
        darts[j][2] = (old + rng.randrange(1, order)) % order
        n2, e2, c2 = evaluate()
        if c2 <= c:
            n, e, c = n2, e2, c2
        else:
            darts[j][2] = old
    if c == 0:
        return n, e
    return None


def _search_lift(d, D, k, m, rng, iters, deadline):
    """Hill-climb Z_m voltages on a random d-regular bipartite base with k+k vertices."""
    perms = [rng.sample(range(k), k) for _ in range(d)]
    darts = [[i, k + p[i], rng.randrange(m)] for p in perms for i in range(k)]

    def evaluate():
        n, e = lib.voltage_lift(2 * k, [tuple(x) for x in darts], m)
        return n, e, lib.bad_pairs(n, e, D)

    n, e, c = evaluate()
    for _ in range(iters):
        if c == 0:
            break
        if time.monotonic() > deadline:
            break
        touched = [rng.randrange(len(darts))]
        if rng.random() < 0.2:
            touched.append(rng.randrange(len(darts)))
        olds = [(j, darts[j][2]) for j in touched]
        for j in touched:
            if m > 1:
                darts[j][2] = (darts[j][2] + rng.randrange(1, m)) % m
        n2, e2, c2 = evaluate()
        if c2 <= c:
            n, e, c = n2, e2, c2
        else:
            for j, old in olds:
                darts[j][2] = old
    if c == 0:
        return n, e
    return None


def _lift_phase(d, D, deadline, rng, bestobj):
    """Secondary search: group lifts and cyclic lifts, offered to bestobj as they succeed."""
    ladder = {k: 2 for k in range(1, 7)}
    while time.monotonic() < deadline:
        if rng.random() < 0.3:
            k = rng.choice([1, 2, 3, 4])
            G = max(bestobj.n // (2 * k) + 1, 2)
            res = _group_search(d, D, k, G, rng, 150, deadline)
            if res is not None:
                bestobj.offer(*res)
        else:
            k = rng.choice(range(1, 7))
            m = max(ladder[k], bestobj.n // (2 * k) + 1, 2)
            res = _search_lift(d, D, k, m, rng, 250, deadline)
            if res is not None:
                bestobj.offer(*res)
                ladder[k] = m + 1
            else:
                ladder[k] = m


def _run_c(d, D, seed, graph, budget, stall=1500):
    """Run the C annealer from `graph` for `budget` seconds; return the parsed (n, edges)."""
    out = lib.run_c(C_SOURCE, [d, D, seed, f"{budget:.2f}", stall],
                    stdin_graph=graph, timeout=budget + 4.0)
    return lib.parse_graph_text(out)


def build(d, D, seed, time_limit):
    start = time.monotonic()
    tl = float(time_limit)
    rng = random.Random(seed)

    def at(frac):
        return start + frac * tl

    # Trivial cases.
    if d >= 1 and D == 1:
        return 2, [(0, 1)]
    if d < 1 or D < 1:
        return 1, []

    # Calibration: D = 3 with d - 1 a prime power is the Moore-optimal incidence graph.
    if D == 3 and d >= 3 and lib.is_prime_power(d - 1):
        n0, e0 = lib.projective_plane_incidence(d - 1)
        if lib.is_valid(n0, e0, d, D):
            return n0, e0

    # Safe fallback: K_{d,d}, valid for D >= 2.
    fallback = lib.haar_graph(d, range(d))
    bestobj = _Best(fallback[0], fallback[1], d, D)

    # Phase 1 (to 8%): quick structured starts.
    if D >= 4:
        gq = _best_gq(d)
        if gq is not None:
            bestobj.offer(gq[0], gq[1])
            n1, e1 = _twin_grow(gq[0], gq[1], d, rng, at(0.08))
            e1 = _saturate_edges(n1, e1, d, rng)
            bestobj.offer(n1, e1)
    elif D == 3:
        pg = _best_pg(d)
        if pg is not None:
            pn, pe = pg
            bestobj.offer(pn, pe)
            bestobj.offer(pn, _saturate_edges(pn, pe, d, rng))

    # Phase 2 (8% to 40%): bi-Cayley graphs over semidirect groups of order near the target.
    # The order 2G must beat the current best; start near 0.775 of the Moore half-order.
    if D >= 2 and d >= 3:
        moore = lib.moore_bound(d, D)
        G0 = max(bestobj.n // 2 + 1, int(0.775 * moore / 2))
        _bicayley_phase(d, D, G0, at(0.40), rng, bestobj)

    # Phase 3 (40% to 55%): lift searches as secondary fallback.
    _lift_phase(d, D, at(0.55), rng, bestobj)

    # Phase 4 (55% to end): C annealing from the best valid graph found so far.
    if d >= 3 and D >= 2:
        end = at(0.92) - 1.5
        remaining = end - time.monotonic()
        if remaining >= 2.0:
            try:
                n2, e2 = _run_c(d, D, seed, (bestobj.n, bestobj.e), remaining)
                bestobj.offer(n2, e2)
            except Exception:
                pass

    if not lib.is_valid(bestobj.n, bestobj.e, d, D):
        return lib.haar_graph(d, range(d))
    return bestobj.n, bestobj.e
