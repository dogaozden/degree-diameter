# Bi-Cayley graphs over Z_m x| Z_k (the new construction for diameter-limited cases).
# ----------------------------------------------------------------------------

def _group_options(G, rng):
    """Candidate (m, k, r) with Z_m x|_r Z_k of order G, shuffled."""
    opts = []
    for k in range(1, 13):
        if G % k:
            continue
        m = G // k
        if m < 2:
            continue
        if k == 1:
            opts.append((m, 1, 1))
            continue
        rs = [r for r in range(1, m) if math.gcd(r, m) == 1 and pow(r, k, m) == 1 % m]
        rng.shuffle(rs)
        opts += [(m, k, r) for r in rs[:2]]
    rng.shuffle(opts)
    return opts


def _bc_run(m, k, r, d, D, seed, budget):
    """Run the C hill-climb for connection set S (|S| = d) in the given group; return S or None."""
    out = lib.run_c(BC_SOURCE, [m, k, r, d, D, seed, f"{budget:.2f}"],
                    timeout=budget + 5.0)
    toks = out.split()
    if len(toks) < 1 + d or toks[0] != "OK":
        return None
    return [int(x) for x in toks[1:1 + d]]


def _bicayley_graph(m, k, r, S):
    """Bi-Cayley graph: a_g ~ b_{g s} for s in S; order 2|G|, degree |S|."""
    G, mul, _ = lib.semidirect_group(m, k, r)
    edges = [(g, G + mul(g, s)) for g in range(G) for s in S]
    return 2 * G, edges


def _bicayley_phase(d, D, G0, deadline, rng, bestobj):
    """Try group orders G = G0, G0+1, ... ; each success is offered as a graph of order 2G."""
    G = G0
    stop = G0 + 25
    while G < stop and time.monotonic() < deadline:
        for m, k, r in _group_options(G, rng)[:2]:
            left = deadline - time.monotonic()
            if left < 0.2:
                return
            try:
                S = _bc_run(m, k, r, d, D, rng.randrange(1 << 30), min(left, 0.6))
            except Exception:
                S = None
            if S is not None:
                n, e = _bicayley_graph(m, k, r, S)
                bestobj.offer(n, e)
                break
        G += 1


