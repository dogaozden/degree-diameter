"""Starter program: Python builds the best known start graph, the C engine searches from it.

New in this version: the Cayley-lift search can grow N in larger steps (cap 256, was 64),
and it gets a larger share of the time budget (up to 80% of the search window), since the
Cayley phase is the one that scales to the large orders needed for d=4, D=9.

The Cayley-lift search (C, function cayley_search) uses a bipartite graph with parts A = G
and B = G over a group G, joined by a_x ~ b_{x s} for s in a set S of d distinct group
elements. It is d-regular and has an automorphism group transitive on each side, so its
diameter is the larger of two BFS eccentricities, from a_e and from b_e. Each check costs
O(N d) instead of the bitset all-pairs test. The search hill-climbs on S inside a random
group of order N, and raises N whenever it succeeds.
"""
