import math
import random
import time

import lib


_BIG = 10 ** 9


# ----------------------------------------------------------------------------
# Baseline constructions (safe fallbacks for diameter 3).
# ----------------------------------------------------------------------------

def _best_pg(d):
    """Incidence graph of PG(2, q) for the largest prime power q with q + 1 <= d."""
    for q in range(d - 1, 1, -1):
        if lib.is_prime_power(q):
            return lib.projective_plane_incidence(q)
    return None


def _araujo(d):
    """Araujo-Pardo & Lopez record graph for degree d when q = d-2 is a prime power >= 3."""
    q = d - 2
    if q >= 3 and lib.is_prime_power(q):
        try:
            return lib.araujo_lopez_graph(q)
        except Exception:
            return None
    return None


# ----------------------------------------------------------------------------
# Group pool: cyclic groups, semidirect products Z_m x| Z_k, and random
# permutation groups (generated by 1-3 random permutations of 4..7 points).
# Each group is a multiplication table M with identity at index 0.
# ----------------------------------------------------------------------------

def _table_from_mul(G, mul):
    return [[mul(a, b) for b in range(G)] for a in range(G)]


def _perm_compose(p, q):
    return tuple(p[x] for x in q)


def _perm_group(gens, cap):
    """Closure of the permutation group generated by gens; None if its order exceeds cap."""
    n = len(gens[0])
    ident = tuple(range(n))
    elems = [ident]
    index = {ident: 0}
    frontier = [ident]
    while frontier:
        new = []
        for x in frontier:
            for g in gens:
                y = _perm_compose(g, x)
                if y not in index:
                    if len(elems) >= cap:
                        return None
                    index[y] = len(elems)
                    elems.append(y)
                    new.append(y)
        frontier = new
    G = len(elems)
    table = [[index[_perm_compose(elems[a], elems[b])] for b in range(G)]
             for a in range(G)]
    return G, table


def _build_pool(max_order, t_end, rng):
    """Map order -> list of thunks producing multiplication tables, for orders 2..max_order."""
    pool = {}
    for G in range(2, max_order + 1):
        lst = pool.setdefault(G, [])
        lst.append(lambda G=G: _table_from_mul(G, lambda x, y: (x + y) % G))
        for k2 in range(2, G + 1):
            if G % k2:
                continue
            m = G // k2
            if m < 2:
                continue
            rs = range(1, m) if m <= 200 else rng.sample(range(1, m), 200)
            found = 0
            for r in rs:
                if found >= 2:
                    break
                if math.gcd(r, m) != 1 or pow(r, k2, m) != 1 % m:
                    continue
                found += 1
                order, mul, _ = lib.semidirect_group(m, k2, r)
                lst.append(lambda o=order, f=mul: _table_from_mul(o, f))

    count = 0
    while time.monotonic() < t_end and count < 4000:
        count += 1
        n = rng.randint(4, 7)
        gens = []
        for _ in range(rng.randint(1, 3)):
            p = list(range(n))
            rng.shuffle(p)
            gens.append(tuple(p))
        res = _perm_group(gens, max_order)
        if res is None:
            continue
        G, table = res
        if G >= 2 and len(pool[G]) < 80:
            pool[G].append(lambda t=table: t)
    return pool


# ----------------------------------------------------------------------------
# Bi-Cayley voltage lifts over a finite group G with table M.
#
# Vertices: A_i,g = i*G + g  and  B_j,h = (k+j)*G + h.
# Dart (i, j, s) joins A_i,g to B_j,(g*s) for every g. Left multiplication
# is an automorphism, so distances are measured from one representative
# per layer.
# ----------------------------------------------------------------------------

def _right_perm(M, G, s):
    return [M[g][s] for g in range(G)]


def _cost(k, G, D, darts, perms):
    """Number of (representative, vertex) pairs not reached within distance D. Zero means valid."""
    if len({(i, j, s) for i, j, s in darts}) < len(darts):
        return _BIG
    N = 2 * k * G
    adj = [[] for _ in range(N)]
    for (i, j, _s), pm in zip(darts, perms):
        base_a = i * G
        base_b = (k + j) * G
        for g in range(G):
            a = base_a + g
            b = base_b + pm[g]
            adj[a].append(b)
            adj[b].append(a)
    reps = [i * G for i in range(k)] + [(k + j) * G for j in range(k)]
    total = 0
    for src in reps:
        seen = [False] * N
        seen[src] = True
        frontier = [src]
        count = 1
        for _ in range(D):
            nxt = []
            for u in frontier:
                for v in adj[u]:
                    if not seen[v]:
                        seen[v] = True
                        nxt.append(v)
            count += len(nxt)
            frontier = nxt
            if not frontier:
                break
        total += N - count
    return total


def _edges(k, G, darts, perms):
    E = set()
    for (i, j, _s), pm in zip(darts, perms):
        for g in range(G):
            E.add((i * G + g, (k + j) * G + pm[g]))
    return 2 * k * G, sorted(E)


def _anneal(d, D, k, G, M, rng, deadline, iters):
    """Simulated annealing over voltages and per-layer B-assignments."""
    darts = []
    for _ in range(d):
        p = rng.sample(range(k), k)
        for i in range(k):
            darts.append([i, p[i], rng.randrange(G)])
    perms = [_right_perm(M, G, s) for _, _, s in darts]
    cost = _cost(k, G, D, darts, perms)

    if cost < _BIG:
        T0 = max(1.0, 0.05 * cost)
    else:
        T0 = 1.0
    T_end = 0.5
    decay = (T_end / T0) ** (1.0 / max(1, iters)) if T0 > T_end else 1.0
    T = T0

    for _ in range(iters):
        if cost == 0 or time.monotonic() > deadline:
            break
        T = max(T_end, T * decay)

        if rng.random() < 0.7 or k == 1:
            idx = rng.randrange(len(darts))
            old_s = darts[idx][2]
            new_s = rng.randrange(G)
            if new_s == old_s:
                continue
            old_perm = perms[idx]
            darts[idx][2] = new_s
            perms[idx] = _right_perm(M, G, new_s)
            c2 = _cost(k, G, D, darts, perms)
            delta = c2 - cost
            if delta <= 0 or rng.random() < math.exp(-min(700.0, delta / T)):
                cost = c2
            else:
                darts[idx][2] = old_s
                perms[idx] = old_perm
        else:
            L = rng.randrange(d)
            a, b = rng.sample(range(k), 2)
            ia, ib = L * k + a, L * k + b
            darts[ia][1], darts[ib][1] = darts[ib][1], darts[ia][1]
            c2 = _cost(k, G, D, darts, perms)
            delta = c2 - cost
            if delta <= 0 or rng.random() < math.exp(-min(700.0, delta / T)):
                cost = c2
            else:
                darts[ia][1], darts[ib][1] = darts[ib][1], darts[ia][1]

    if cost == 0:
        return _edges(k, G, darts, perms)
    return None


# ----------------------------------------------------------------------------
# Main entry point.
# ----------------------------------------------------------------------------

def build(d, D, seed, time_limit):
    start = time.monotonic()
    deadline = start + 0.8 * time_limit
    rng = random.Random(seed)

    if d < 1 or D < 1:
        return 1, []
    if D == 1:
        return 2, [(0, 1)]

    # Safe fallback: K_{d,d} has diameter 2, valid for D >= 2.
    best = lib.haar_graph(d, range(d))
    best_n = best[0]
    cap = lib.moore_bound(d, D)

    def consider(n, e):
        nonlocal best, best_n
        if n > best_n and lib.is_valid(n, e, d, D):
            best = (n, e)
            best_n = n

    try:
        if D >= 3:
            ap = _araujo(d)
            if ap is not None:
                consider(ap[0], ap[1])
            pg = _best_pg(d)
            if pg is not None:
                consider(pg[0], pg[1])

        # Already at the Moore bound: nothing larger is possible.
        if D >= 3 and best_n < cap:
            max_order = min(cap // 2, 400)
            pool = _build_pool(max_order, start + min(3.0, 0.05 * time_limit), rng)
            ks = [1, 1, 2, 2, 3, 3, 4, 5, 6, 8]

            while time.monotonic() < deadline and best_n < cap:
                ks_ok = []
                for k in ks:
                    lo = max(2, best_n // (2 * k) + 1)
                    hi = min(cap // (2 * k), max_order)
                    if lo <= hi:
                        ks_ok.append(k)
                if not ks_ok:
                    break
                k = rng.choice(ks_ok)
                lo = max(2, best_n // (2 * k) + 1)
                hi = min(cap // (2 * k), max_order)
                G = lo + rng.randrange(0, 4)
                if G > hi:
                    G = lo
                M = rng.choice(pool[G])()
                iters = 1500 if k <= 4 else 800
                res = _anneal(d, D, k, G, M, rng, deadline, iters)
                if res is not None:
                    consider(res[0], res[1])
    except Exception:
        pass

    try:
        valid = lib.is_valid(best[0], best[1], d, D)
    except Exception:
        valid = False
    if not valid:
        best = lib.haar_graph(d, range(d))
    return best
