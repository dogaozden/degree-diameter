def build(d, D, seed, time_limit):
    start = time.monotonic()
    rng = random.Random(seed)

    if d < 1 or D < 1:
        return 1, []
    if D == 1:
        return 2, [(0, 1)]

    # Safe fallback: K_{d,d} has diameter 2, valid for D >= 2.
    best = lib.haar_graph(d, range(d))
    best_n = best[0]
    cap = lib.moore_bound(d, D)

    def consider(n, e):
        nonlocal best, best_n
        if n > best_n and lib.is_valid(n, e, d, D):
            best = (n, e)
            best_n = n

    if D >= 3:
        pg = _best_pg(d)
        if pg is not None:
            consider(pg[0], pg[1])
            n2, e2 = _grow(pg[0], pg[1], d, D, start + 0.12 * time_limit, rng)
            consider(n2, e2)

    if D >= 4 and best_n < cap:
        gq = _best_gq(d)
        if gq is not None:
            consider(gq[0], gq[1])
            n2, e2 = _grow(gq[0], gq[1], d, D, start + 0.2 * time_limit, rng)
            consider(n2, e2)

    # Phase 1: annealed bi-Cayley voltage lifts, each extended by cover growth.
    v_deadline = start + 0.5 * time_limit
    if D >= 5:
        ks = [1, 1, 2, 2, 3, 4]
        iters_v = 1500
    else:
        ks = [1, 1, 2, 3]
        iters_v = 400
    while time.monotonic() < v_deadline and best_n < cap:
        k = rng.choice(ks)
        base = best_n // (2 * k)
        if D >= 5:
            G = max(2, base + 1 + rng.randrange(0, 3))
        else:
            G = max(2, base + 1 + rng.randrange(0, max(3, base // 8 + 1)))
        g = _sample_group(G, rng)
        if g is None:
            continue
        order, mul = g
        res = _anneal(d, D, k, order, mul, rng, v_deadline, iters_v)
        if res is not None:
            consider(res[0], res[1])
            gn, ge = _grow(res[0], res[1], d, D, v_deadline, rng)
            consider(gn, ge)

    # Phase 2: double-edge-swap repair growth from the best valid graph.
    if D >= 3 and best_n < cap:
        _, E0 = _orient(best_n, best[1])
        E0 = _saturate_pairs(best_n, E0, d, rng)
        r_n, r_E = _repair_search(d, D, best_n, E0, rng,
                                  start + 0.88 * time_limit, 800)
        consider(r_n, [(int(a), int(b)) for a, b in r_E])

    if not lib.is_valid(best[0], best[1], d, D):
        best = lib.haar_graph(d, range(d))
    return best
