# NEW: bipartite double-edge-swap repair growth.
#
# A graph is kept as a list E of (a, b) pairs with a on side 0 and b on side 1.
#  * _grow_pair adds one side-0 vertex x and one side-1 vertex y, each of degree
#    d, without changing any old degree: pick d edges (a_i, b_i) forming a
#    matching, replace each by (a_i, y) and add (x, b_i).
#  * _anneal_bip then performs degree-preserving double-edge swaps
#    (a1,b1),(a2,b2) -> (a1,b2),(a2,b1) under annealing, minimising the number
#    of ordered vertex pairs farther apart than D, until that number is zero.
# Each accepted size gives a valid graph two vertices larger.
# ----------------------------------------------------------------------------

def _orient(n, edges):
    """Return (color, E) with E the edges oriented as (side-0 vertex, side-1 vertex)."""
    adj = [[] for _ in range(n)]
    for u, v in edges:
        adj[u].append(v)
        adj[v].append(u)
    color = _bipartition(n, adj)
    E = [(u, v) if color[u] == 0 else (v, u) for u, v in edges]
    return color, E


def _saturate_pairs(n, E, d, rng):
    """Add edges between deficient opposite-side vertices. Only adds edges, so validity is kept."""
    deg = [0] * n
    S = set(E)
    for a, b in E:
        deg[a] += 1
        deg[b] += 1
    left = sorted({a for a, _ in E if deg[a] < d})
    right = sorted({b for _, b in E if deg[b] < d})
    pairs = [(a, b) for a in left for b in right if (a, b) not in S]
    rng.shuffle(pairs)
    out = list(E)
    for a, b in pairs:
        if deg[a] < d and deg[b] < d:
            out.append((a, b))
            deg[a] += 1
            deg[b] += 1
    return out


def _bad_count(n, E, D):
    """Ordered number of vertex pairs at distance more than D (unreachable included). Zero iff valid."""
    adj = [[] for _ in range(n)]
    for a, b in E:
        adj[a].append(b)
        adj[b].append(a)
    reach = [1 << v for v in range(n)]
    for _ in range(D):
        new = [0] * n
        for v in range(n):
            r = reach[v]
            for u in adj[v]:
                r |= reach[u]
            new[v] = r
        reach = new
    return sum(n - r.bit_count() for r in reach)


def _grow_pair(n, E, d, rng):
    """Add x (side 0, id n) and y (side 1, id n+1), each of degree d, keeping old degrees fixed."""
    idx = list(range(len(E)))
    rng.shuffle(idx)
    used_a, used_b = set(), set()
    picked = []
    for i in idx:
        a, b = E[i]
        if a in used_a or b in used_b:
            continue
        used_a.add(a)
        used_b.add(b)
        picked.append(i)
        if len(picked) == d:
            break
    if len(picked) < d:
        return None
    x, y = n, n + 1
    newE = list(E)
    for i in picked:
        a, b = E[i]
        newE[i] = (a, y)
        newE.append((x, b))
    return n + 2, newE


def _anneal_bip(n, E, D, rng, iters, deadline):
    """Degree-preserving double-edge-swap annealing on E (mutated in place).

    Returns (success, E). On success E has zero bad pairs.
    """
    S = set(E)
    m = len(E)
    cost = _bad_count(n, E, D)
    T0, T1 = 1.5, 0.15
    for it in range(iters):
        if cost == 0:
            break
        if (it & 15) == 0 and time.monotonic() > deadline:
            break
        T = T0 * (T1 / T0) ** (it / iters)
        i = rng.randrange(m)
        j = rng.randrange(m)
        if i == j:
            continue
        a1, b1 = E[i]
        a2, b2 = E[j]
        if a1 == a2 or b1 == b2:
            continue
        e1 = (a1, b2)
        e2 = (a2, b1)
        if e1 in S or e2 in S:
            continue
        E[i] = e1
        E[j] = e2
        c2 = _bad_count(n, E, D)
        if c2 <= cost or rng.random() < math.exp((cost - c2) / T):
            S.discard((a1, b1))
            S.discard((a2, b2))
            S.add(e1)
            S.add(e2)
            cost = c2
        else:
            E[i] = (a1, b1)
            E[j] = (a2, b2)
    return cost == 0, E


def _repair_search(d, D, n, E, rng, deadline, iters):
    """Repeatedly grow by two vertices and repair with swaps; returns the largest valid (n, E)."""
    cap = lib.moore_bound(d, D)
    best_n, best_E = n, list(E)
    fails = 0
    while time.monotonic() < deadline and best_n + 2 <= cap:
        g = _grow_pair(best_n, best_E, d, rng)
        if g is None:
            break
        n2, E2 = g
        budget = min(4 * iters, iters + 150 * fails)
        ok, res = _anneal_bip(n2, list(E2), D, rng, budget, deadline)
        if ok:
            best_n, best_E = n2, list(res)
            fails = 0
        else:
            fails += 1
    return best_n, best_E


