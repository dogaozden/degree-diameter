# ----------------------------------------------------------------------------
# Safe baseline families (valid for every case, used as fallbacks).
# ----------------------------------------------------------------------------

def _best_pg(d):
    """Incidence graph of PG(2, q) for the largest prime power q with q + 1 <= d."""
    for q in range(d - 1, 1, -1):
        if lib.is_prime_power(q):
            return lib.projective_plane_incidence(q)
    return None


def _araujo(d):
    """Araujo-Pardo & Lopez graph for degree d = q + 2 with q a prime power >= 3; diameter 3."""
    q = d - 2
    if q >= 3 and lib.is_prime_power(q):
        return lib.araujo_lopez_graph(q)
    return None


def _gq_w(q):
    """Incidence graph of points and lines of the generalized quadrangle W(q); diameter 4."""
    F = lib.GF(q)
    pts = [v for v in itertools.product(range(q), repeat=4)
           if any(v) and next(c for c in v if c) == 1]
    index = {v: i for i, v in enumerate(pts)}
    P = len(pts)

    def norm(v):
        c = next(x for x in v if x)
        inv = F.inv(c)
        return tuple(F.mul(inv, x) for x in v)

    def form(x, y):
        t = F.sub(F.mul(x[0], y[1]), F.mul(x[1], y[0]))
        return F.add(t, F.sub(F.mul(x[2], y[3]), F.mul(x[3], y[2])))

    covered = set()
    lines = []
    for i in range(P):
        x = pts[i]
        for j in range(i + 1, P):
            if (i, j) in covered:
                continue
            y = pts[j]
            if form(x, y) != 0:
                continue
            L = set()
            for a in range(q):
                for b in range(q):
                    if a == 0 and b == 0:
                        continue
                    v = tuple(F.add(F.mul(a, x[k]), F.mul(b, y[k])) for k in range(4))
                    if any(v):
                        L.add(index[norm(v)])
            L = sorted(L)
            lines.append(L)
            for p in L:
                for r in L:
                    if p < r:
                        covered.add((p, r))

    edges = []
    for j, L in enumerate(lines):
        for p in L:
            edges.append((p, P + j))
    return 2 * P, edges


def _best_gq(d):
    """W(q) for the largest prime power q with q + 1 <= d, restricted to small q for speed."""
    for q in range(min(d - 1, 5), 1, -1):
        if lib.is_prime_power(q):
            return _gq_w(q)
    return None


# ----------------------------------------------------------------------------
# Permutation groups (new construction): PSL/PGL(2,q), S_n, A_n.
# ----------------------------------------------------------------------------

def _cycle(seq, n):
    """Permutation of range(n) cycling the points in seq."""
    p = list(range(n))
    for i, x in enumerate(seq):
        p[x] = seq[(i + 1) % len(seq)]
    return p


def _sym_gens(n):
    """Generators of S_n: a transposition and an n-cycle."""
    t = list(range(n))
    t[0], t[1] = 1, 0
    return [t, _cycle(list(range(n)), n)]


def _alt_gens(n):
    """Generators of A_n (n = 5, 6): a 3-cycle and an (n-1 or n)-cycle of odd length."""
    seq = list(range(n)) if n % 2 else list(range(1, n))
    return [_cycle([0, 1, 2], n), _cycle(seq, n)]


def _mobius_gens(q, psl):
    """Generators of PGL(2, q) (or PSL(2, q) for odd q) acting on the q + 1 points of the projective line.

    Points 0..q-1 are field elements and q is infinity. Translations, a multiplier, and inversion
    (or x -> -1/x for PSL) generate the group. The closure computed in C is what is actually used,
    so any mismatch only changes the order, and the result is checked anyway.
    """
    F = lib.GF(q)
    INF = q
    g = F.primitive_element()
    a = F.mul(g, g) if psl else g

    def inv_map(x):
        if x == INF:
            return 0
        if x == 0:
            return INF
        y = F.inv(x)
        return F.neg(y) if psl else y

    gens = [[INF if x == INF else F.add(x, b) for x in range(q + 1)] for b in range(1, q)]
    gens.append([INF if x == INF else F.mul(a, x) for x in range(q + 1)])
    gens.append([inv_map(x) for x in range(q + 1)])
    return gens


def _group_candidates(best_n, moore):
    """Return (n, name, K, npts, gens) for every group/K whose lift order 2*K*|G| is in (best_n, moore]."""
    groups = [
        ("S5", 5, _sym_gens(5), 120),
        ("A5", 5, _alt_gens(5), 60),
        ("S6", 6, _sym_gens(6), 720),
        ("A6", 6, _alt_gens(6), 360),
    ]
    for q in (7, 8, 9):
        if lib.is_prime_power(q):
            groups.append((f"PGL2_{q}", q + 1, _mobius_gens(q, False), q * (q * q - 1)))
    for q in (7, 11):
        groups.append((f"PSL2_{q}", q + 1, _mobius_gens(q, True), q * (q * q - 1) // 2))
    cands = []
    for name, npts, gens, order in groups:
        for K in (1, 2, 3):
            n = 2 * K * order
            if best_n < n <= moore:
                cands.append((n, name, K, npts, gens))
    cands.sort(key=lambda c: (c[0], c[1], c[2]))
    return cands


# ----------------------------------------------------------------------------
# Driver: baselines, then the C search in two modes within the time budget.
# ----------------------------------------------------------------------------

def build(d, D, seed, time_limit):
    start = time.monotonic()
    end = start + 0.9 * time_limit - 1.0

    if d < 1 or D < 1:
        return 1, []
    if D == 1:
        return 2, [(0, 1)]

    # Safe fallback: K_{d,d} has diameter 2, so it is valid for D >= 2.
    best = lib.haar_graph(d, range(d))
    best_n = best[0]

    def consider(n, e):
        nonlocal best, best_n
        if n > best_n and lib.is_valid(n, e, d, D):
            best = (n, e)
            best_n = n

    if D >= 3:
        for builder in (_best_pg, _araujo):
            try:
                g = builder(d)
                if g is not None:
                    consider(g[0], g[1])
            except Exception:
                pass

    if D >= 4 and time.monotonic() - start < 0.2 * time_limit:
        try:
            gq = _best_gq(d)
            if gq is not None:
                consider(gq[0], gq[1])
        except Exception:
            pass

    moore = lib.moore_bound(d, D)
    if best_n >= moore:
        return best

    def run(args, stdin_graph, slice_s):
        now = time.monotonic()
        budget = min(slice_s + 2.0, time_limit - (now - start) - 1.0)
        if budget < 1.0:
            return None
        try:
            out = lib.run_c(C_SOURCE, [str(a) for a in args],
                            stdin_graph=stdin_graph, timeout=budget)
            return lib.parse_graph_text(out)
        except Exception:
            return None

    cands = _group_candidates(best_n, moore)

    # Stage 1: semidirect-product lifts (mode 0) get a share of the budget.
    rem = end - time.monotonic()
    if rem >= 1.5:
        share = 0.35 * rem if cands else rem
        res = run([d, D, seed, f"{share:.2f}", best_n, 0, 0, 0, 0], None, share)
        if res is not None:
            consider(*res)

    # Stage 2: permutation-group lifts (mode 1), smallest first. Each run stops early on success,
    # so unused time flows to the later, larger candidates.
    for i, (n_c, name, K, npts, gens) in enumerate(cands):
        if n_c <= best_n:
            continue
        rem = end - time.monotonic()
        if rem < 1.5:
            break
        left = sum(1 for c in cands[i:] if c[0] > best_n)
        share = min(rem, max(1.0, rem / max(1, left)))
        flat = [x for g in gens for x in g]
        if len(flat) % 2:
            flat.append(0)
        pairs = [(flat[j], flat[j + 1]) for j in range(0, len(flat), 2)]
        res = run([d, D, seed, f"{share:.2f}", best_n, 1, K, npts, len(gens)],
                  (0, pairs), share)
        if res is not None:
            consider(*res)

    if not lib.is_valid(best[0], best[1], d, D):
        best = lib.haar_graph(d, range(d))
    return best
