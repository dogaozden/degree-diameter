# ----------------------------------------------------------------------------
# Driver: baselines, then the Haar-type Cayley search, then the parent lift search.
# ----------------------------------------------------------------------------

def build(d, D, seed, time_limit):
    start = time.monotonic()
    if d < 1 or D < 1:
        return 1, []
    if D == 1:
        return 2, [(0, 1)]

    # Safe fallback: K_{d,d} has diameter 2, so it is valid for D >= 2.
    best = lib.haar_graph(d, range(d))
    best_n = best[0]

    def consider(n, e):
        nonlocal best, best_n
        if n > best_n and lib.is_valid(n, e, d, D):
            best = (n, e)
            best_n = n

    if D >= 3:
        for builder in (_best_pg, _araujo):
            try:
                g = builder(d)
                if g is not None:
                    consider(g[0], g[1])
            except Exception:
                pass

    if D >= 4 and time.monotonic() - start < 0.3 * time_limit:
        gq = _best_gq(d)
        if gq is not None:
            consider(gq[0], gq[1])

    if best_n >= lib.moore_bound(d, D):
        return best

    # Total C budget: keep a margin for cached compiles, parsing and validation.
    elapsed = time.monotonic() - start
    remaining = 0.85 * time_limit - elapsed - 2.0

    # Bold family first: Haar-type bipartite Cayley graphs over semidirect products.
    # Its output order is 2N, so the minimum group order is best_n // 2 + 1.
    if remaining >= 2.0:
        t_h = 0.6 * remaining
        hard = max(1.0, min(t_h + 4.0, time_limit - (time.monotonic() - start) - 1.0))
        try:
            out = lib.run_c(C_HAAR, [d, D, seed, f"{t_h:.2f}", best_n // 2 + 1],
                            timeout=hard)
            n, e = lib.parse_graph_text(out)
            consider(n, e)
        except Exception:
            pass

    # Parent voltage-lift search with the remaining budget; it only emits larger graphs.
    elapsed = time.monotonic() - start
    rem2 = 0.85 * time_limit - elapsed - 1.5
    if rem2 >= 1.0:
        hard = max(1.0, min(rem2 + 3.0, time_limit - elapsed - 1.5))
        try:
            out = lib.run_c(C_SOURCE, [d, D, seed, f"{rem2:.2f}", best_n],
                            timeout=hard)
            n, e = lib.parse_graph_text(out)
            consider(n, e)
        except Exception:
            pass

    if not lib.is_valid(best[0], best[1], d, D):
        best = lib.haar_graph(d, range(d))
    return best
