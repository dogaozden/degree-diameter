"""Bi-Cayley search for d-regular bipartite graphs with diameter D.

The main change from the parent: phase 1 is an exhaustive search over one-vertex-per-side
bi-Cayley lifts. For each order N it tries every semidirect product Z_m x| Z_k of order N
(r^k = 1 mod m, gcd(r, m) = 1), and every set of d distinct voltages containing the identity.
Left translation of the group is an automorphism, so the diameter check only needs BFS from
two representatives. The first voltage can be fixed to the identity by relabelling the
B-fibre, so the search is exact over the family. Phase 2 is the parent's annealed lift search
over p <= 4 fibres. Phase 3 grows the best graph by two vertices with annealed swaps. Python
always keeps a valid fallback (K_{d,d}, PG(2,q), Araujo-Pardo-Lopez, or W(q)).
"""
import itertools
