"""Bi-Cayley search first, then the lift and growth engine.

Stage 0: algebraic starts (K_{d,d}, PG(2,q), Araujo-Pardo-Lopez, GQ W(q)), each checked with lib.is_valid.
Stage 1 (new construction): bi-Cayley graphs. Vertices A_g and B_g for g in a group G of order N,
with A_g ~ B_{g s} for s in a d-element set S. Left multiplication is an automorphism, so the
diameter test needs only two BFS runs (from A_e and B_e). Groups range over the semidirect products
Z_m x|_r Z_k. S is found by hill-climbing and the order N is pushed upward.
Stage 2: the lift/growth engine from the parent, started from the best graph so far.
Every stage's output is accepted only if it is larger and passes lib.is_valid.
"""
