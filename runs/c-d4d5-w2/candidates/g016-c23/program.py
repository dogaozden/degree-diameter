def _gq_w(q):
    """Incidence graph of points and lines of W(q): degree q+1, diameter 4."""
    F = lib.GF(q)
    pts = [v for v in itertools.product(range(q), repeat=4)
           if any(v) and next(c for c in v if c) == 1]
    index = {v: i for i, v in enumerate(pts)}
    P = len(pts)

    def norm(v):
        c = next(x for x in v if x)
        inv = F.inv(c)
        return tuple(F.mul(inv, x) for x in v)

    def form(x, y):
        t = F.sub(F.mul(x[0], y[1]), F.mul(x[1], y[0]))
        return F.add(t, F.sub(F.mul(x[2], y[3]), F.mul(x[3], y[2])))

    covered = set()
    lines = []
    for i in range(P):
        x = pts[i]
        for j in range(i + 1, P):
            if (i, j) in covered:
                continue
            y = pts[j]
            if form(x, y) != 0:
                continue
            L = set()
            for a in range(q):
                for b in range(q):
                    if a == 0 and b == 0:
                        continue
                    v = tuple(F.add(F.mul(a, x[k]), F.mul(b, y[k])) for k in range(4))
                    if any(v):
                        L.add(index[norm(v)])
            L = sorted(L)
            lines.append(L)
            for p in L:
                for r in L:
                    if p < r:
                        covered.add((p, r))

    edges = []
    for j, L in enumerate(lines):
        for p in L:
            edges.append((p, P + j))
    return 2 * P, edges


def _largest_prime_power_le(x):
    for q in range(x, 1, -1):
        if lib.is_prime_power(q):
            return q
    return None


def known_starts(d, D):
    """Algebraic candidates valid for diameter D (may be empty)."""
    out = []
    if D >= 3 and d - 1 >= 2 and lib.is_prime_power(d - 1):
        out.append(lib.projective_plane_incidence(d - 1))
    if D == 3 and d - 2 >= 3 and lib.is_prime_power(d - 2):
        out.append(lib.araujo_lopez_graph(d - 2))
    if D >= 4:
        q = _largest_prime_power_le(min(d - 1, 9))
        if q is not None and q >= 2:
            out.append(_gq_w(q))
    return out


def _run_engine(source, args, stdin_graph, timeout):
    """Run one C engine; return the parsed graph or None on any failure."""
    try:
        text = lib.run_c(source, args, stdin_graph=stdin_graph, timeout=timeout)
        return lib.parse_graph_text(text)
    except Exception:
        return None


def _accept(cur, cand, d, D):
    """Keep cand only if it is valid and strictly larger than cur."""
    if cand is None:
        return cur
    n, e = cand
    if n > cur[0] and lib.is_valid(n, e, d, D):
        return (n, e)
    return cur


def build(d, D, seed, time_limit):
    t0 = time.monotonic()
    deadline = t0 + 0.8 * time_limit
    if d < 1 or D < 1:
        return 1, []
    if d == 1 or D == 1:
        return 2, [(0, 1)]
    if d == 2:
        L = 2 * D
        return L, [(i, (i + 1) % L) for i in range(L)]

    best = lib.haar_graph(d, range(d))  # K_{d,d}: valid for D >= 2
    for cand in known_starts(d, D):
        best = _accept(best, cand, d, D)

    if d > 31 or best[0] >= lib.moore_bound(d, D):
        return best

    # Stage 1: bi-Cayley search over semidirect products, started just above the current best.
    if 3 <= d <= 12 and D >= 2:
        budget1 = 0.35 * (deadline - time.monotonic())
        if budget1 > 1.5:
            nstart = max(d + 1, best[0] // 2 + 1)
            cand = _run_engine(C_BICAYLEY, [d, D, seed, f"{budget1:.2f}", nstart],
                               None, budget1 + 4.5)
            best = _accept(best, cand, d, D)

    # Stage 2: lift and growth engine from the best graph so far.
    budget2 = deadline - time.monotonic() - 0.8
    if budget2 > 1.0:
        cand = _run_engine(C_SOURCE, [d, D, seed, f"{budget2:.2f}"],
                           best, budget2 + 4.5)
        best = _accept(best, cand, d, D)

    return best
