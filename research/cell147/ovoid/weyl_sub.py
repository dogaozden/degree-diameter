#!/usr/bin/env python3
"""Reflection subgroups of W(E7) (mod 11, standard coordinates) and their orbit-union partial ovoids (orbclq).
usage: weyl_sub.py OUTDIR [--minrank 3] [--t 20]"""
import sys, os, itertools, subprocess, json, argparse
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ovlib as L
from weyl import E7, reflections
ap = argparse.ArgumentParser(); ap.add_argument('outdir'); ap.add_argument('--minrank', type=int, default=3)
ap.add_argument('--t', type=float, default=20); ap.add_argument('--only', default='')
a = ap.parse_args()
q = 11
os.makedirs(os.path.join(a.outdir, 'gens'), exist_ok=True)
A = E7; n = 7
def dot(u, v): return sum(u[i] * A[i][j] * v[j] for i in range(n) for j in range(n))
# all roots in simple-root coordinates
simple = [tuple(int(i == j) for j in range(n)) for i in range(n)]
roots = set(simple); frontier = list(simple)
while frontier:
    nf = []
    for r in frontier:
        for i in range(n):
            c = dot(r, simple[i])
            s = tuple(r[k] - c * (k == i) for k in range(n))
            if s not in roots: roots.add(s); nf.append(s)
    frontier = nf
roots = sorted(roots); pos = [r for r in roots if all(x >= 0 for x in r)]
assert len(roots) == 126, len(roots)
theta = max(pos, key=sum)
def refl_mat(r):
    # s_r(c) = c - (c . r) r, in root coordinates (integer matrix)
    M = [[int(i == j) for j in range(n)] for i in range(n)]
    Ar = [sum(A[i][j] * r[j] for j in range(n)) for i in range(n)]   # (c . r) = sum_i c_i (A r)_i
    for i in range(n):
        for j in range(n):
            M[i][j] -= r[i] * Ar[j]
    return [[x % q for x in row] for row in M]
_, P = L.conjugate_to_standard(reflections(E7, q), E7, q)
Pi = L.mat_inv(P, q)
def to_std(M): return L.mat_mul(L.mat_mul(P, M, q), Pi, q)
def name_of(rs):
    return '_'.join(''.join(map(str, r)).replace('-', 'm') for r in rs)
groups = []
# parabolic subgroups: subsets of simple roots
for k in range(a.minrank, 7):
    for J in itertools.combinations(range(7), k):
        groups.append(('par' + ''.join(map(str, J)), [simple[j] for j in J]))
# maximal-rank and other subsystems: simple roots minus some, plus -theta (extended diagram)
for k in range(a.minrank - 1, 7):
    for J in itertools.combinations(range(7), k):
        groups.append(('ext' + ''.join(map(str, J)), [simple[j] for j in J] + [tuple(-x for x in theta)]))
if a.only: groups = [g for g in groups if g[0] in a.only.split(',')]
runlog = os.path.join(a.outdir, 'runs.jsonl'); done = set()
if os.path.exists(runlog):
    for line in open(runlog): done.add(json.loads(line)['name'])
ORB = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'orbclq')
best = 0
for name, rs in groups:
    if name in done: continue
    mats = [to_std(refl_mat(r)) for r in rs]
    G = L.std_gram(q); assert all(L.is_isometry(M, G, q) for M in mats)
    gp = os.path.join(a.outdir, 'gens', name + '.txt')
    L.write_gens(gp, mats, f'reflection subgroup of W(E7) mod 11 generated by roots {rs} (simple-root coordinates, Bourbaki order)')
    outp = os.path.join(a.outdir, 'set_' + name + '.txt')
    r = subprocess.run([ORB, gp, '-t', str(a.t), '-x', '3000', '-o', outp], capture_output=True, text=True)
    res = {}
    for line in r.stdout.splitlines():
        if line.startswith('RESULT'):
            for kv in line.split()[1:]:
                kk, v = kv.split('='); res[kk] = float(v) if '.' in v else int(v)
    hist = [l for l in r.stderr.splitlines() if l.startswith('orbit sizes')]
    rec = dict(name=name, roots=rs, **res, hist=hist[0][:300] if hist else '')
    open(runlog, 'a').write(json.dumps(rec) + '\n')
    b = res.get('best', 0); best = max(best, b)
    if b <= 756 and os.path.exists(outp): os.remove(outp)
    print(name, 'K=', res.get('good'), 'best=', b, 'exact=', res.get('exact'), '| sweep best', best, flush=True)
