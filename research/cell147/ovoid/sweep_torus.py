#!/usr/bin/env python3
"""Sweep the cyclic (optionally bicyclic) subgroups of one maximal torus type of SO(7,q) with orbclq.
usage: sweep_torus.py TYPES OUTDIR [--lo 6] [--hi 80] [--t 20] [--bicyclic] [--seed 1]
TYPES e.g. E,H,H,L.  Writes OUTDIR/gens/<name>.txt, OUTDIR/runs.jsonl (one line per group), keeps the best set.
Symmetries used to skip duplicates: e_i -> -e_i in each block, permutations of blocks of the same kind."""
import sys, os, json, math, itertools, subprocess, argparse, time
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ovlib as L

ap = argparse.ArgumentParser()
ap.add_argument('types'); ap.add_argument('outdir')
ap.add_argument('--lo', type=int, default=6); ap.add_argument('--hi', type=int, default=80)
ap.add_argument('--t', type=float, default=20); ap.add_argument('--bicyclic', action='store_true')
ap.add_argument('--seed', type=int, default=1); ap.add_argument('--q', type=int, default=11)
ap.add_argument('--maxgroups', type=int, default=100000)
a = ap.parse_args()
q = a.q
types = a.types.split(',')
gens, orders, P = L.torus(types, q)
os.makedirs(os.path.join(a.outdir, 'gens'), exist_ok=True)
ORB = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'orbclq')

def lcm(x, y): return x * y // math.gcd(x, y)
def order_of(e): 
    o = 1
    for ei, oi in zip(e, orders): o = lcm(o, oi // math.gcd(ei, oi))
    return o
def subgroup(es):
    # all elements generated by exponent vectors es
    S = {tuple([0] * len(orders))}; frontier = list(S)
    while frontier:
        nf = []
        for x in frontier:
            for e in es:
                y = tuple((xi + ei) % oi for xi, ei, oi in zip(x, e, orders))
                if y not in S: S.add(y); nf.append(y)
        frontier = nf
    return frozenset(S)
def canon(S):
    # canonical form under block negations and permutations of equal kinds
    best = None
    idx = list(range(len(types)))
    perms = [p for p in itertools.permutations(idx) if all(types[p[i]] == types[i] for i in idx)]
    for p in perms:
        for signs in itertools.product((1, -1), repeat=len(types)):
            T = sorted(tuple((signs[i] * x[p[i]]) % orders[i] for i in idx) for x in S)
            T = tuple(T)
            if best is None or T < best: best = T
    return best

seen = set(); groups = []
elems = list(itertools.product(*[range(o) for o in orders]))
for e in elems:
    o = order_of(e)
    if not (a.lo <= o <= a.hi): continue
    S = subgroup([e])
    c = canon(S)
    if c in seen: continue
    seen.add(c); groups.append(([e], o))
if a.bicyclic:
    cyc = [g for g in groups]
    small = [e for e in elems if 2 <= order_of(e) <= a.hi]
    for (g, o) in cyc:
        for e2 in small:
            S = subgroup([g[0], e2])
            if not (a.lo <= len(S) <= a.hi) or len(S) == o: continue
            c = canon(S)
            if c in seen: continue
            seen.add(c); groups.append(([g[0], e2], len(S)))
groups.sort(key=lambda x: -x[1])
print(f'{a.types}: torus orders {orders}, {len(groups)} subgroups with order in [{a.lo},{a.hi}]', flush=True)
runlog = os.path.join(a.outdir, 'runs.jsonl')
done = set()
if os.path.exists(runlog):
    for line in open(runlog):
        try: done.add(json.loads(line)['name'])
        except Exception: pass
best = 0
for gi, (es, o) in enumerate(groups[:a.maxgroups]):
    name = a.types.replace(',', '') + '_' + '_'.join('-'.join(map(str, e)) for e in es)
    if name in done: continue
    mats = [L.elem(gens, e, q) for e in es]
    gpath = os.path.join(a.outdir, 'gens', name + '.txt')
    L.write_gens(gpath, mats, f'torus {a.types} orders {orders}; subgroup generated by exponent vectors {es}; order {o}')
    outp = os.path.join(a.outdir, 'set_' + name + '.txt')
    t0 = time.time()
    r = subprocess.run([ORB, gpath, '-q', str(q), '-t', str(a.t), '-s', str(a.seed), '-o', outp], capture_output=True, text=True)
    res = {}
    for line in r.stdout.splitlines():
        if line.startswith('RESULT'):
            for kv in line.split()[1:]:
                k, v = kv.split('='); res[k] = float(v) if '.' in v else int(v)
    rec = dict(name=name, types=a.types, exps=es, order=o, **res, wall=round(time.time() - t0, 1))
    with open(runlog, 'a') as f: f.write(json.dumps(rec) + '\n')
    b = res.get('best', 0)
    if b > best: best = b
    if b < 700 and os.path.exists(outp): os.remove(outp)
    print(f'[{gi+1}/{len(groups)}] {name} order {o} K={res.get("good")} best={b} (sweep best {best})', flush=True)
