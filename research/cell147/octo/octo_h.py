import numpy as np, itertools, sys
from octo import LINES, mult, is_alternative
q = 11; inv2 = 6
# E7 roots in frame coordinates (u0..u6 orthonormal): +-u_i and (+-u_a+-u_b+-u_c+-u_d)/2 over complements of lines
quads = [tuple(sorted(set(range(7)) - set(L))) for L in LINES]
roots = []
for i in range(7):
    for s in (1, -1):
        v = [0] * 7; v[i] = 2 * s; roots.append(tuple(v))           # stored doubled (integers)
for qd in quads:
    for signs in itertools.product((1, -1), repeat=4):
        v = [0] * 7
        for i, s in zip(qd, signs): v[i] = s
        roots.append(tuple(v))
assert len(roots) == 126
def refl(rd):
    # s_r(x) = x - 2 (x.r) r with r = rd/2 (norm 1): x - (x.rd) rd / 2
    rd = np.array(rd); M = np.eye(7, dtype=np.int64) * 1
    M = (np.eye(7, dtype=np.int64) - np.outer(rd, rd) * inv2) % q
    return M
def emb(M):  # 8x8 acting on O = <1> + V
    E = np.zeros((8, 8), dtype=np.int64); E[0, 0] = 1; E[1:, 1:] = M; return E
if __name__ == '__main__':
    d6 = [r for r in roots if r[0] == 0]
    print('D6 roots', len(d6))
    gens = [refl(r) for r in d6]
    # BFS closure of the group generated by the D6 reflections (mod 11)
    I = np.eye(7, dtype=np.int64)
    seen = {I.tobytes(): I}; frontier = [I]
    while frontier:
        nf = []
        for X in frontier:
            for g in gens[:]:
                Y = (X @ g) % q; k = Y.tobytes()
                if k not in seen: seen[k] = Y; nf.append(Y)
        frontier = nf
    G = list(seen.values()); print('|W(D6)| =', len(G))
    best = None
    for o in itertools.product((1, -1), repeat=7):
        T = mult(o)
        if not is_alternative(T): continue
        Tq = T % q
        H = []
        for M in G:
            E = emb(M)
            # w(e_i e_j) = w(e_i) w(e_j) for all basis pairs: E @ T[i,j,:] == prod(E[:,i], E[:,j])
            lhs = np.einsum('kl,ijl->ijk', E, Tq) % q                          # w applied to e_i e_j
            rhs = np.einsum('ai,bj,abk->ijk', E, E, Tq) % q                    # w(e_i) w(e_j)
            if np.array_equal(lhs, rhs): H.append(M)
        print('orientation', o, '|H| =', len(H))
        if best is None or len(H) > len(best[1]): best = (o, H)
    np.save('H_best.npy', np.array(best[1])); print('best orientation', best[0], 'order', len(best[1]))
    open('orient.txt', 'w').write(' '.join(map(str, best[0])) + '\n')
