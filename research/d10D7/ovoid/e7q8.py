        print('%-7s %s orbits %d selfcompat %d best union %d %s %s [%.0fs]' % (name, 'frob' if withF else '    ', len(sizes), len(S), bw,
              'exact' if ex else 'TL', sorted(w[cl].tolist())[-6:], time.time() - t0), flush=True)
