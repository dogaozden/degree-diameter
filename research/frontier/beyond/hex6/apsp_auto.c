/* apsp_auto: exact diameter of a graph using automorphisms that the checker verifies itself.
   Same checks as research/lifts/coordinator_check/apsp_mt.c (simple, max degree, bipartite, connected, exact diameter),
   but BFS runs only from one vertex per orbit of the group generated by the given permutations, after checking that each
   permutation is a bijection of 0..n-1 that maps every edge to an edge (a bijection mapping E into E maps E onto E, so it
   is an automorphism). Eccentricity is constant on orbits, so the largest eccentricity over the representatives is the
   diameter. Bit-parallel BFS, 64 sources per batch, T threads.
   AUT file: int32 k, int32 n, then k arrays of n int32 (the permutations).
   Usage: apsp_auto EDGES AUT d D [T]         (build: cc -O3 -pthread -o apsp_auto apsp_auto.c) */
#include <pthread.h>
#include <stdio.h>
#include <stdlib.h>
#include <stdint.h>
#include <string.h>
static long n, *st; static int *adj, *src; static long nsrc;
static long next_k = 0; static int diam = 0, bad = 0;
static pthread_mutex_t mu = PTHREAD_MUTEX_INITIALIZER;
static int cmpi(const void *a, const void *b) { int x = *(const int *)a, y = *(const int *)b; return x < y ? -1 : x > y; }
static int has_edge(long u, int v) {
    long lo = st[u], hi = st[u + 1] - 1;
    while (lo <= hi) { long m = (lo + hi) / 2; if (adj[m] == v) return 1; if (adj[m] < v) lo = m + 1; else hi = m - 1; }
    return 0;
}
static int *par;
static int find(int x) { while (par[x] != x) { par[x] = par[par[x]]; x = par[x]; } return x; }
static void *work(void *unused) {
    uint64_t *vis = malloc(n * 8), *fr = malloc(n * 8), *nx = malloc(n * 8); int my = 0;
    for (;;) {
        pthread_mutex_lock(&mu); long k0 = next_k; next_k += 64; int stop = bad; pthread_mutex_unlock(&mu);
        if (k0 >= nsrc || stop) break;
        memset(vis, 0, n * 8); memset(fr, 0, n * 8);
        int ns = (nsrc - k0 < 64) ? (int)(nsrc - k0) : 64; uint64_t full = ns == 64 ? ~0ULL : ((1ULL << ns) - 1);
        for (int k = 0; k < ns; k++) { vis[src[k0 + k]] |= 1ULL << k; fr[src[k0 + k]] |= 1ULL << k; }
        int lev = 0;
        for (;;) { int any = 0;
            for (long x = 0; x < n; x++) { uint64_t acc = 0; for (long i = st[x]; i < st[x + 1]; i++) acc |= fr[adj[i]];
                acc &= ~vis[x]; nx[x] = acc; if (acc) any = 1; }
            if (!any) break; lev++; for (long x = 0; x < n; x++) vis[x] |= nx[x]; uint64_t *t = fr; fr = nx; nx = t; }
        for (long x = 0; x < n; x++) if (vis[x] != full) { pthread_mutex_lock(&mu); bad = 1; pthread_mutex_unlock(&mu); break; }
        if (lev > my) my = lev;
    }
    pthread_mutex_lock(&mu); if (my > diam) diam = my; pthread_mutex_unlock(&mu);
    free(vis); free(fr); free(nx); return NULL;
}
int main(int c, char **v) {
    if (c < 5) { fprintf(stderr, "usage: apsp_auto EDGES AUT d D [T]\n"); return 2; }
    FILE *f = fopen(v[1], "r"); int d = atoi(v[3]), D = atoi(v[4]), T = c > 5 ? atoi(v[5]) : 1;
    long m = 0, cap = 1 << 20; if (fscanf(f, "%ld", &n) != 1) return 2;
    int *U = malloc(cap * 4), *W = malloc(cap * 4); long a, b;
    while (fscanf(f, "%ld %ld", &a, &b) == 2) { if (m == cap) { cap *= 2; U = realloc(U, cap * 4); W = realloc(W, cap * 4); }
        if (a < 0 || b < 0 || a >= n || b >= n || a == b) { printf("RESULT INVALID bad edge %ld\n", m); return 1; } U[m] = a; W[m] = b; m++; }
    fclose(f);
    long *deg = calloc(n + 1, 8); for (long i = 0; i < m; i++) { deg[U[i]]++; deg[W[i]]++; }
    st = malloc((n + 1) * 8); st[0] = 0; for (long i = 0; i < n; i++) st[i + 1] = st[i] + deg[i];
    adj = malloc(2 * m * 4); long *pos = calloc(n, 8);
    for (long i = 0; i < m; i++) { adj[st[U[i]] + pos[U[i]]++] = W[i]; adj[st[W[i]] + pos[W[i]]++] = U[i]; }
    long maxd = 0, mind = n;
    for (long x = 0; x < n; x++) { qsort(adj + st[x], st[x + 1] - st[x], 4, cmpi);
        long k = deg[x]; if (k > maxd) maxd = k; if (k < mind) mind = k;
        for (long i = st[x] + 1; i < st[x + 1]; i++) if (adj[i] == adj[i - 1]) { printf("RESULT INVALID repeated edge at %ld\n", x); return 1; } }
    int *col = malloc(n * 4); for (long i = 0; i < n; i++) col[i] = -1;
    int *qq = malloc(n * 4); long h = 0, t = 0; col[0] = 0; qq[t++] = 0; int bip = 1;
    while (h < t) { long x = qq[h++]; for (long i = st[x]; i < st[x + 1]; i++) { int y = adj[i];
        if (col[y] < 0) { col[y] = 1 - col[x]; qq[t++] = y; } else if (col[y] == col[x]) bip = 0; } }
    if (t != n) { printf("RESULT INVALID disconnected (%ld of %ld)\n", t, n); return 1; }
    /* automorphisms */
    FILE *g = fopen(v[2], "rb"); int hk[2]; if (fread(hk, 4, 2, g) != 2 || hk[1] != n) { printf("RESULT INVALID aut file header\n"); return 1; }
    int *perm = malloc(n * 4), *seen = malloc(n * 4); par = malloc(n * 4); for (long i = 0; i < n; i++) par[i] = i;
    for (int k = 0; k < hk[0]; k++) {
        if (fread(perm, 4, n, g) != (size_t)n) { printf("RESULT INVALID aut file short\n"); return 1; }
        memset(seen, 0, n * 4);
        for (long i = 0; i < n; i++) { if (perm[i] < 0 || perm[i] >= n || seen[perm[i]]) { printf("RESULT INVALID permutation %d is not a bijection\n", k); return 1; } seen[perm[i]] = 1; }
        for (long i = 0; i < m; i++) if (!has_edge(perm[U[i]], perm[W[i]])) { printf("RESULT INVALID permutation %d maps edge %ld off the edge set\n", k, i); return 1; }
        for (long i = 0; i < n; i++) { int r1 = find(i), r2 = find(perm[i]); if (r1 != r2) par[r1] = r2; }
    }
    fclose(g);
    src = malloc(n * 4); nsrc = 0; for (long i = 0; i < n; i++) if (find(i) == i) src[nsrc++] = i;
    printf("n=%ld edges=%ld degree min=%ld max=%ld bipartite=%s automorphisms verified=%d orbits=%ld\n", n, m, mind, maxd, bip ? "yes" : "no", hk[0], nsrc);
    fflush(stdout);
    pthread_t th[64]; if (T > 64) T = 64;
    for (int i = 0; i < T; i++) pthread_create(&th[i], NULL, work, NULL);
    for (int i = 0; i < T; i++) pthread_join(th[i], NULL);
    if (bad) { printf("RESULT INVALID unreached\n"); return 1; }
    printf("diameter=%d (BFS from %ld orbit representatives)\n", diam, nsrc);
    if (bip && maxd <= d && diam <= D) printf("RESULT VALID d=%d D=%d n=%ld\n", d, D, n); else printf("RESULT INVALID\n");
    return 0;
}
