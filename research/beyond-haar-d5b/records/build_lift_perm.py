#!/usr/bin/env python3
"""GAP-free, table-free rebuild of a 2+2 lift from voltages given as permutations (file from perm_voltages.g).
The group is generated by the voltages (closure by BFS); products follow GAP: p*q = apply p, then q. Lift vertex
(v, h) for base vertex v in A0, A1, B0, B1 and group element h; a base edge a -> b of voltage g joins (a, h) and
(b, h*g). Base and voltage slots as in the solution line ("SOL x .. y .. .. z .. .. .. w .." for [[2,3],[3,2]],
"SOL g .. .. .. d .. .. .. c .." for [[1,4],[4,1]]; identity on the spanning-tree edges).
usage: build_lift_perm.py PERMFILE "SOL ..." OUT.edges"""
import re, sys
from collections import deque
perm = {}
deg = 0
for ln in open(sys.argv[1]):
    if ln.startswith('#') or ln.startswith('gens'): continue
    k, rest = ln.split(' ', 1); cyc = [list(map(int, c.split(','))) for c in re.findall(r'\(([^)]*)\)', rest)]
    perm[int(k)] = cyc; deg = max([deg] + [max(c) for c in cyc])
def topm(cyc):
    p = list(range(deg + 1))
    for c in cyc:
        for i, a in enumerate(c): p[a] = c[(i + 1) % len(c)]
    return tuple(p)
P = {k: topm(c) for k, c in perm.items()}; e = tuple(range(deg + 1)); P[0] = e
mul = lambda p, q: tuple(q[p[i]] for i in range(deg + 1))     # p then q
t = sys.argv[2].split()
if t[1] == 'x':
    x = int(t[2]); y1, y2 = int(t[4]), int(t[5]); z = [int(v) for v in t[7:10]]; w = int(t[11])
    base = [(0, 2, 0), (0, 2, x), (0, 3, 0), (0, 3, y1), (0, 3, y2)] + [(1, 2, g) for g in z] + [(1, 3, 0), (1, 3, w)]
else:
    i, j, k = t.index('g'), t.index('d'), t.index('c')
    g = [int(v) for v in t[i + 1:j]]; d = [int(v) for v in t[j + 1:k]]; c = int(t[k + 1])
    base = [(0, 2, 0)] + [(0, 3, v) for v in [0] + g] + [(1, 2, v) for v in [0] + d] + [(1, 3, c)]
gens = [P[g] for _, _, g in base if g != 0]
idx = {e: 0}; els = [e]; q = deque([e])
while q:
    h = q.popleft()
    for s in gens:
        hs = mul(h, s)
        if hs not in idx: idx[hs] = len(els); els.append(hs); q.append(hs)
m = len(els)
E = set()
for a, b, g in base:
    for h in els:
        E.add((a * m + idx[h], b * m + idx[mul(h, P[g])]))
assert len(E) == 10 * m, "multi-edge"
with open(sys.argv[3], 'w') as o:
    o.write(f"{4 * m}\n")
    for u, v in sorted(E): o.write(f"{u} {v}\n")
print(f"group order {m} (generated by the voltages), {4 * m} vertices, {len(E)} edges", file=sys.stderr)
