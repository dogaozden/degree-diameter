#!/usr/bin/env python3
"""coverage.py: coverage of the order-384 Haar search (job six-five-384).
Reads data/inv384.txt (all 20,169 ids), data/excluded.txt (exact filters) and logs/h384_<id>.log (exhaustive runs),
writes data/coverage384.txt (one line per id: id, method, result) and prints a markdown summary table.
A log counts as closed only if it has a DONE line covering all pair classes (pairs=0..P with P = pair classes).
usage: python3 src/coverage.py   (run from research/six-five-384)"""
import os, re, collections

ids = [int(l.split()[0]) for l in open("data/inv384.txt")]
inv = {int(l.split()[0]): dict(kv.split("=") for kv in l.split()[1:]) for l in open("data/inv384.txt")}
excl = {}
for l in open("data/excluded.txt"):
    t = l.split()
    excl[int(t[0])] = t[1]
rows, stats = [], collections.Counter()
valid_ids, aside_ids = [], []
for i in ids:
    if i in excl:
        method = "rank-filter" if excl[i].startswith("rank") else "quotient-filter"
        rows.append(f"{i} {method} {excl[i]}")
        stats[method] += 1
        continue
    p = f"logs/h384_{i}.log"
    if not os.path.exists(p):
        rows.append(f"{i} open -"); stats["open"] += 1; continue
    txt = open(p).read()
    head = re.search(r"pair classes=(\d+), doing (\d+)\.\.(\d+)", txt)
    done = re.search(r"DONE N=384 pairs=(\d+)\.\.(\d+) prefixes=(\d+) Acovered=(\d+) valid=(\d+)", txt)
    if not (head and done) or int(done.group(1)) != 0 or int(done.group(2)) != int(head.group(1)):
        rows.append(f"{i} open incomplete-log"); stats["open"] += 1; continue
    prog = re.search(r"\((haarex\d)\)", txt).group(1)
    acov, val = int(done.group(4)), int(done.group(5))
    if val: valid_ids.append(i)
    if acov: aside_ids.append(i)
    rows.append(f"{i} exhaustive-{prog} pairs={head.group(1)} prefixes={done.group(3)} Acovered={acov} valid={val}")
    stats["exhaustive"] += 1
with open("data/coverage384.txt", "w") as f:
    f.write("# id method result (job six-five-384; generated by src/coverage.py)\n")
    f.write("\n".join(rows) + "\n")
print("| method | groups |")
print("|---|---:|")
for k in ["rank-filter", "quotient-filter", "exhaustive", "open"]:
    print(f"| {k} | {stats[k]} |")
print(f"| total | {sum(stats.values())} |")
print(f"\ngroups with a side-A cover: {len(aside_ids)} {aside_ids[:50]}")
print(f"groups with a VALID set: {len(valid_ids)} {valid_ids}")
