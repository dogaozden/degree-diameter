#!/usr/bin/env python3
"""coverage_gen.py: coverage of the Haar search over orders 401-450 (job six-five-384).
Reads o401_450/filtered.txt (ABELIAN / RANK lines) and o401_450/logs/h<ORD>_<id>.log, with the number of groups of
each order from o401_450/nr_groups.txt ("ORD NR" lines). A log counts as closed only with a DONE line over all pair
classes. Writes o401_450/coverage.txt (one line per group) and prints a markdown table per order.
usage: python3 src/coverage_gen.py   (run from research/six-five-384)"""
import os, re, collections
nr = {int(a): int(b) for a, b in (l.split() for l in open("o401_450/nr_groups.txt"))}
filt = {}
for l in open("o401_450/filtered.txt"):
    t = l.split()
    filt[(int(t[1]), int(t[2]))] = t[0].lower() + ("" if t[0] == "ABELIAN" else t[3])
rows, per = [], collections.defaultdict(collections.Counter)
covers, valid = [], []
for o in sorted(nr):
    for i in range(1, nr[o] + 1):
        if (o, i) in filt:
            m = "abelian" if filt[(o, i)] == "abelian" else "rank-filter"
            rows.append(f"{o} {i} {m} {filt[(o, i)]}"); per[o][m] += 1; continue
        p = f"o401_450/logs/h{o}_{i}.log"
        if not os.path.exists(p):
            rows.append(f"{o} {i} open -"); per[o]["open"] += 1; continue
        txt = open(p).read()
        head = re.search(r"pair classes=(\d+), doing (\d+)\.\.(\d+)", txt)
        done = re.search(r"DONE N=(\d+) pairs=(\d+)\.\.(\d+) prefixes=(\d+) Acovered=(\d+) valid=(\d+)", txt)
        if not (head and done) or int(done.group(1)) != o or int(done.group(2)) != 0 or int(done.group(3)) != int(head.group(1)):
            rows.append(f"{o} {i} open incomplete-log"); per[o]["open"] += 1; continue
        a, v = int(done.group(5)), int(done.group(6))
        if a: covers.append(f"{o}_{i}")
        if v: valid.append(f"{o}_{i}")
        prog = re.search(r"\((haarex\d)\)", txt).group(1)
        rows.append(f"{o} {i} exhaustive-{prog} pairs={head.group(1)} prefixes={done.group(4)} Acovered={a} valid={v}")
        per[o]["exhaustive"] += 1
with open("o401_450/coverage.txt", "w") as f:
    f.write("# order id method result (job six-five-384; generated by src/coverage_gen.py)\n" + "\n".join(rows) + "\n")
print("| order | groups | abelian | rank filter | exhaustive | open |")
print("|---:|---:|---:|---:|---:|---:|")
tot = collections.Counter()
for o in sorted(nr):
    c = per[o]; tot.update(c); tot["groups"] += nr[o]
    print(f"| {o} | {nr[o]} | {c['abelian']} | {c['rank-filter']} | {c['exhaustive']} | {c['open']} |")
print(f"| all | {tot['groups']} | {tot['abelian']} | {tot['rank-filter']} | {tot['exhaustive']} | {tot['open']} |")
print(f"\ngroups with a side-A cover: {len(covers)} {covers[:40]}")
print(f"groups with a VALID set: {len(valid)} {valid}")
