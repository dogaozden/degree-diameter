#!/bin/bash
# Regenerate the STRUCTURE.md §4 records table (between the records_table marker and the next blank line).
HERE=$(cd "$(dirname "$0")" && pwd); F=$HERE/../STRUCTURE.md
python3 "$HERE/records_table.py" > "$F.tbl" || exit 1
python3 - "$F" "$F.tbl" <<'PY'
import sys
f, t = sys.argv[1], sys.argv[2]
s = open(f).read().split('\n'); tbl = open(t).read().rstrip('\n').split('\n')
i = s.index('<!-- generated by tools/records_table.py from runs/ -->') + 1
j = i
while j < len(s) and s[j].strip(): j += 1
open(f, 'w').write('\n'.join(s[:i] + tbl + s[j:]))
PY
rm -f "$F.tbl"
