"""Re-express a lift over G as a lift over a subgroup H (bigger base, smaller group), as a start for salift2-style
annealing (research/squads/d3D7-r1/c4/salift2.c).  H = the subgroup generated by the given element indices of G.
Usage: python3 requot.py BASE GROUPS id "v1 ... vE" "h1 h2 ..." OUTPREFIX
Writes OUTPREFIX.grp (H's multiplication table, gap_export format, identity 0) and OUTPREFIX.sol ("h 1 p'" then
"u v a" lines, whites u < p', blacks >= p').  Convention as liftx/salift: (u,g) ~ (v, g*a); H acts on the left, its
orbits are (u, H t_j) for right-coset representatives t_j; edge ((u,j),x) ~ ((v,k), x*b) where t_j*a = b*t_k."""
import sys

def read_group(path, gid):
    tok = open(path).read().split(); i = 0
    while i < len(tok):
        N, g = int(tok[i + 1]), int(tok[i + 2]); i += 4
        if g == gid:
            return N, [list(map(int, tok[i + r * N:i + (r + 1) * N])) for r in range(N)]
        i += N * N
    raise SystemExit("group not found")

def main():
    base, gfile, gid = sys.argv[1], sys.argv[2], int(sys.argv[3])
    volt = list(map(int, sys.argv[4].split())); gens = list(map(int, sys.argv[5].split())); out = sys.argv[6]
    b = open(base).read().split(); k, E = int(b[0]), int(b[1])
    edges = [(int(b[2 + 2 * e]), int(b[3 + 2 * e])) for e in range(E)]
    N, M = read_group(gfile, gid)
    H = [0]; seen = {0}; i = 0
    while i < len(H):
        for g in gens:
            y = M[H[i]][g]
            if y not in seen: seen.add(y); H.append(y)
        i += 1
    h = len(H); pos = {x: j for j, x in enumerate(H)}
    # right cosets H t
    reps, coset_of = [], {}
    for g in range(N):
        if g in coset_of: continue
        j = len(reps); reps.append(g)
        for x in H: coset_of[M[x][g]] = (j, x)          # element x*t_j
    r = len(reps); p = k // 2
    # new base vertex: whites (u, j) -> u*r + j for u < p, blacks -> p*r + (u-p)*r + j
    def nv(u, j):
        return u * r + j
    lines = []
    for (u, v), a in zip(edges, volt):
        for j, t in enumerate(reps):
            kk, bb = coset_of[M[t][a]]                  # t_j * a = bb * t_kk
            lines.append(f"{nv(u, j)} {nv(v, kk)} {pos[bb]}")
    inv_ok = all(M[x][y] in seen for x in H for y in H)
    assert inv_ok
    with open(out + ".grp", "w") as f:
        f.write(f"G {h} 1 sub{h}\n")
        for x in H:
            f.write(" ".join(str(pos[M[x][y]]) for y in H) + "\n")
    with open(out + ".sol", "w") as f:
        f.write(f"{h} 1 {p * r}\n" + "\n".join(lines) + "\n")
    print(f"H order {h}, index {r}, new base {p * r}+{p * r}, expected cost x{r} of the G-lift cost")

main()
