#!/usr/bin/env python3
"""Generate the Lean files for the (7,5) Haar record on 1312 vertices, G = C41 : C16 = <x, y | x^41 = y^16 = 1,
y x y^-1 = x^38> (SmallGroup(656,28)), S = {(0,0), (3,8), (18,8), (14,3), (1,5), (32,14), (1,2)} (elements x^i y^j
written (i,j)); edge list research/d75-raise/records/d7D5_n1312_haar_c41c16.edges.

Writes lean/BipartiteDD/Haar/D7D5C41C16/{Grp,Cert,Record1312}.lean, the same layout as the 1200 record
(lean/BipartiteDD/Haar/D7D5SL5, generated by gen_d7D5_1200.py). Before writing, the script checks that the Haar graph of
S on the numbering i*16 + j (side A) and 656 + i*16 + j (side B) is exactly the edge list (4,592 edges, 7-regular).
Each element g of G gets a quadruple of indices into S with
  g = a^-1 b c^-1 d   (cert1)    and    g = a b^-1 c d^-1   (cert2).
usage: python3 research/lean-haarD/gen_d7D5_1312.py"""
from itertools import product
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
EDGES = ROOT / "research/d75-raise/records/d7D5_n1312_haar_c41c16.edges"
OUT = ROOT / "lean/BipartiteDD/Haar/D7D5C41C16"
M, K, R = 41, 16, 38                      # x has order 41, y has order 16, y x y^-1 = x^R
S = [(0, 0), (3, 8), (18, 8), (14, 3), (1, 5), (32, 14), (1, 2)]
N = M * K                                 # |G| = 656
RP = [pow(R, j, M) for j in range(K)]     # r^j, the action of y^j on x

assert pow(R, K, M) == 1 and all(RP[(j + b) % K] == RP[j] * RP[b] % M for j in range(K) for b in range(K))


def mul(g, h):                            # (i, j)(a, b) = (i + r^j a, j + b)
    return ((g[0] + RP[g[1]] * h[0]) % M, (g[1] + h[1]) % K)


def inv(g):
    return (-(RP[(-g[1]) % K] * g[0]) % M, (-g[1]) % K)


def enc(g):                               # index on one side of the Haar graph
    return g[0] * K + g[1]


def grp_of(n):
    return (n // K, n % K)


elems = [(i, j) for i in range(M) for j in range(K)]
assert sorted(enc(g) for g in elems) == list(range(N))
assert all(grp_of(enc(g)) == g for g in elems)
assert all(mul(g, inv(g)) == (0, 0) and mul(inv(g), g) == (0, 0) for g in elems)
assert all(mul(mul(g, h), k) == mul(g, mul(h, k)) for g, h, k in product(elems[::37], elems[::41], elems[::23]))

# the Haar graph of S (vertex enc g on side A, N + enc h on side B, (g, A) ~ (s g, B)) against the edge file
lean_edges = sorted((enc(g), N + enc(mul(s, g))) for g in elems for s in S)
lines = EDGES.read_text().split()
assert lines[0] == str(2 * N)
file_edges = sorted((int(lines[k]), int(lines[k + 1])) for k in range(1, len(lines), 2))
assert len(lean_edges) == len(set(lean_edges)) == len(file_edges) == 7 * N, len(file_edges)
assert file_edges == lean_edges, "Haar graph of S differs from the edge file"
deg = Counter()
for a, b in file_edges:
    deg[a] += 1
    deg[b] += 1
assert set(deg.values()) == {7} and len(deg) == 2 * N


def find(word):
    tab = {}
    for w in product(range(7), repeat=4):
        g = word(*(S[i] for i in w))
        tab.setdefault(enc(g), w)
    assert len(tab) == N, len(tab)
    return [tab[n] for n in range(N)]


cert1 = find(lambda a, b, c, d: mul(mul(mul(inv(a), b), inv(c)), d))
cert2 = find(lambda a, b, c, d: mul(mul(mul(a, inv(b)), c), inv(d)))


def fmt_list(cert):
    items = ["(%d, %d, %d, %d)" % w for w in cert]
    rows = [", ".join(items[k:k + 6]) for k in range(0, len(items), 6)]
    return ",\n  ".join(rows)


def lean_elem(g):
    return "⟨%d, %d⟩" % g


S_LEAN = ", ".join(lean_elem(s) for s in S)

