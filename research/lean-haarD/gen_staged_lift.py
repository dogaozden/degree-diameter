#!/usr/bin/env python3
"""Staged Lean proof of a bipartite degree-diameter record whose one-shot kernel check runs out of memory
(the (3,12) 2368 lift: `decide +kernel` on `Fast.checkFast` grows past 12 GB, so each radius step is its own module).

Given a folder that already holds Graph.lean (the neighbour lists, from gen_lift_gaps.py), this script writes
  Levels.lean   the ball masks of radius 1 … D−1 (bit w of entry v is set iff dist(v, w) ≤ r), as hex literals,
                computed from the edge file here and checked against it,
  StageNN.lean  one per radius step r → r+1 (r = 0 … D−1): `Staged.stepOK K adjL (chainL n D levs r) (…(r+1)) = true`,
                by `decide +kernel`, one declaration per module,
  Check.lean    the local test `Staged.checkLocal K d adjL colL = true`,
  Record.lean   the theorem, via `Staged.check_of_chain` and `check_sound`.
The levels are data; nothing in them is trusted, because each stage checks one step of the ball recurrence.

usage: python3 research/lean-haarD/gen_staged_lift.py FOLDER THEOREM N DELTA D K EDGES
  e.g. python3 research/lean-haarD/gen_staged_lift.py D3D12N2368 nb_3_12_2368 2368 3 12 12 \
         research/squads/own-small/records/d3D12_n2368_meta37_8.edges"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_lift_gaps import neighbour_lists, read_edges, two_colour  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent.parent
OUT = ROOT / "lean/BipartiteDD/Haar"


def masks(n, adj, D):
    """levels[r-1] = the radius-r ball masks, for r = 1 … D−1."""
    cur = [1 << v for v in range(n)]
    levels = []
    for _ in range(1, D):
        cur = [cur[v] | _or(cur, adj[v]) for v in range(n)]
        levels.append(cur)
    return levels


def _or(cur, nbrs):
    out = 0
    for u in nbrs:
        out |= cur[u]
    return out


def hex_list(xs):
    return ",\n  ".join(hex(x) for x in xs)


def main(folder, theorem, n, d, D, K, edges):
    rec_dir = OUT / folder
    n2, E = read_edges(edges)
    assert n2 == n
    adj = neighbour_lists(n, E)
    col = two_colour(n, adj)
    levels = masks(n, adj, D)
    ns = f"BipartiteDD.Haar.{folder}"
    gen = f"/- Generated by research/lean-haarD/gen_staged_lift.py from {edges.relative_to(ROOT)}. Do not edit by hand. -/"

    # one file per radius keeps each module small; Levels.lean collects them
    for r, lvl in enumerate(levels, start=1):
        body = [gen, "import BipartiteDD.Staged", "", f"namespace {ns}", "", "set_option maxHeartbeats 0 in",
                "set_option maxRecDepth 100000 in",
                f"/-- The ball masks of radius {r} (bit `w` of entry `v` is set iff `dist v w ≤ {r}`). -/",
                f"def lev{r} : List ℕ := [" + ", ".join(hex(x) for x in lvl) + "]", "", f"end {ns}", ""]
        (rec_dir / f"Level{r:02d}.lean").write_text("\n".join(body))
    lv = [gen, *(f"import {ns}.Level{r:02d}" for r in range(1, D)), "", f"namespace {ns}", "",
          "/-- The radius-`r` masks at position `r - 1`, for `r = 1 … D - 1`. -/",
          "def levs : List (List ℕ) := [" + ", ".join(f"lev{r}" for r in range(1, D)) + "]", "",
          f"end {ns}", ""]
    (rec_dir / "Levels.lean").write_text("\n".join(lv))

    for r in range(D):
        stage = [
            gen,
            "import BipartiteDD.Staged",
            f"import {ns}.Graph",
            f"import {ns}.Levels",
            "",
            f"namespace {ns}",
            "",
            "open BipartiteDD.Staged",
            "",
            "set_option maxRecDepth 100000 in",
            f"/-- Radius step {r} → {r + 1} of the {n}-vertex graph. -/",
            f"theorem stage{r:02d} : stepOK {K} adjL (chainL {n} {D} levs {r}) (chainL {n} {D} levs {r + 1}) = true := by",
            "  decide +kernel",
            "",
            f"end {ns}",
            "",
        ]
        (rec_dir / f"Stage{r:02d}.lean").write_text("\n".join(stage))

    check = [
        gen,
        "import BipartiteDD.Staged",
        f"import {ns}.Graph",
        "",
        f"namespace {ns}",
        "",
        "open BipartiteDD.Staged",
        "",
        f"/-- The local test (degrees, symmetry, colouring) of the {n}-vertex graph. -/",
        f"theorem local_ok : checkLocal {K} {d} adjL colL = true := by",
        "  decide +kernel",
        "",
        f"end {ns}",
        "",
    ]
    (rec_dir / "Check.lean").write_text("\n".join(check))

    stage_imports = "\n".join(f"import {ns}.Stage{r:02d}" for r in range(D))
    stage_names = ", ".join(f"{ns}.stage{r:02d}" for r in range(D))
    alts = " | ".join(f"rfl" for _ in range(D))
    values = " ∨ ".join(f"r = {r}" for r in range(D))
    rec = [
        "import BipartiteDD.Basic",
        "import BipartiteDD.Fast",
        "import BipartiteDD.Staged",
        f"import {ns}.Graph",
        f"import {ns}.Levels",
        f"import {ns}.Check",
        stage_imports,
        "",
        "/-! The record, proved by the staged check: the ball masks of each radius are data (`Levels`), and each radius",
        "step is checked in its own module (`Stage00 … Stage" + f"{D - 1:02d}`), so the kernel never holds the whole",
        "computation (the one-shot `decide +kernel` of `Fast.checkFast` exceeds 12 GB here). The local test is `Check`. -/",
        "",
        "open BipartiteDD in",
        f"/-- A graph on {n} vertices, bipartite, of degree at most {d} and diameter at most {D}. -/",
        f"theorem {theorem} : ∃ G : SimpleGraph (Fin {n}), BipartiteDD.IsBipartiteDegDiam G {d} {D} :=",
        f"  ⟨_, BipartiteDD.check_sound {d} {D} {ns}.nbrs {ns}.color",
        f"    (BipartiteDD.Staged.check_of_chain {K} {d} {D} {ns}.adjL {ns}.colL",
        f"      (by decide) {ns}.levs (by decide) {ns}.local_ok",
        "      (by",
        "        intro r hr",
        f"        obtain {alts} : {values} := by omega",
        f"        exacts [{stage_names}]))⟩",
        "",
    ]
    (rec_dir / "Record.lean").write_text("\n".join(rec))
    print(f"{folder}: levels 1..{D - 1} written, {len(levels)} masks per level, local and {D} stages")


if __name__ == "__main__":
    folder, theorem, n, d, D, K = sys.argv[1], sys.argv[2], int(sys.argv[3]), int(sys.argv[4]), int(sys.argv[5]), int(sys.argv[6])
    main(folder, theorem, n, d, D, K, ROOT / sys.argv[7] if not Path(sys.argv[7]).is_absolute() else Path(sys.argv[7]))
