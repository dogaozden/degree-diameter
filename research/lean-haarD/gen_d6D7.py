#!/usr/bin/env python3
"""Covering certificates for the (6,7) Haar record: G = meta 279 15 7 = Z_279 x|_7 Z_15 (order 4185).

Numbering (must match lean/BipartiteDD/Haar/D6D7/Group.lean): as in research/frontier/haar_gen3.c, the element
(a, j) has index a*15 + j in [0, 4185), and (a, j)(b, l) = (a + 7^j b, j + l) mod (279, 15).

S is read from research/frontier/sols/d6D7_meta_279_15_7_1_s1.txt (six elements, degree 6).

Covering words. For every g in G there are two words of three pairs (digits d0..d5 in 0..5, indices into S):
  A-word: g = S[d0]^-1 S[d1] S[d2]^-1 S[d3] S[d4]^-1 S[d5]
  B-word: g = S[d0] S[d1]^-1 S[d2] S[d3]^-1 S[d4] S[d5]^-1
Six letters are D - 1 for D = 7, the odd case of Haar.lean's GraphD lemma with n = 3 (two pairs per side in
D = 5). The code is sum_k d_k 6^k < 6^6 = 46656 < 2^16. Entry n of the A (resp. B) table is the code of the A
(resp. B) word of the element with index n. Every word is re-checked by direct multiplication.

Usage: python3 gen_d6D7.py SOL.txt OUTDIR
writes OUTDIR/codes.json and OUTDIR/lean/Stage{00..04}.lean, OUTDIR/lean/Cover.lean.
The Lean files are copied to lean/BipartiteDD/Haar/D6D7/ by hand (the generator does not touch the repo).
"""
import itertools
import json
import os
import re
import sys

M = 279
K = 15
R = 7
N = M * K  # 4185
NS = 6
NPAIR = 3
STAGES = 5
STAGE = N // STAGES  # 837
BITS = 16
assert STAGE * STAGES == N
assert 6 ** (2 * NPAIR) < 2 ** BITS


def mul(x, y):
    a, j = x
    b, l = y
    return ((a + pow(R, j, M) * b) % M, (j + l) % K)


def inv(x):
    a, j = x
    l = (-j) % K
    return ((-pow(R, l, M) * a) % M, l)


def enc(x):
    return x[0] * K + x[1]


def dec(n):
    return (n // K, n % K)


def parse_sol(path):
    lines = [ln.strip() for ln in open(path) if ln.strip()]
    head = lines[0].split()
    assert head[:6] == ["6", "7", "meta", str(M), str(K), str(R)] and head[9] == str(N), head
    S = []
    for ln in lines[1:]:
        m = re.fullmatch(r"(\d+)\s+meta\(a=(\d+),j=(\d+)\)\s+z=0", ln)
        assert m, ln
        idx, a, j = map(int, m.groups())
        assert idx == a * K + j and 0 <= a < M and 0 <= j < K, ln
        S.append((a, j))
    assert len(S) == NS and len(set(S)) == NS, S
    return S


def check_group():
    for n in range(N):
        assert enc(dec(n)) == n
    # inverses and associativity on a sample of triples
    for a in range(0, M, 7):
        for j in range(K):
            x = (a, j)
            assert mul(x, inv(x)) == (0, 0) and mul(inv(x), x) == (0, 0), x
    for x in [(1, 2), (100, 14), (278, 3), (5, 0)]:
        for y in [(3, 7), (250, 1), (0, 13)]:
            for z in [(17, 9), (200, 5), (1, 0)]:
                assert mul(mul(x, y), z) == mul(x, mul(y, z))
    assert pow(R, K, M) == 1


def word_value(S, digs, side):
    el = (0, 0)
    for p in range(NPAIR):
        x, y = digs[2 * p], digs[2 * p + 1]
        if side == "A":
            el = mul(el, mul(inv(S[x]), S[y]))
        else:
            el = mul(el, mul(S[x], inv(S[y])))
    return el


def find_words(S):
    """For each index n, the A and B digit tuples (d0..d5) of a covering word."""
    results = {}
    for side in ("A", "B"):
        words = {}
        for digs in itertools.product(range(NS), repeat=2 * NPAIR):
            el = word_value(S, digs, side)
            words.setdefault(enc(el), digs)
        assert len(words) == N, (side, N - len(words))
        results[side] = [words[n] for n in range(N)]
    return results


def code_of(digs):
    return sum(d * 6 ** k for k, d in enumerate(digs))


def verify(S, digits):
    for side in ("A", "B"):
        for n in range(N):
            assert word_value(S, digits[side][n], side) == dec(n), (side, n)


LEAN_STAGE = """import BipartiteDD.Haar.D6D7.Check

/-! Covering certificates, stage {k} of {stages}: the indices `{lo} ≤ n < {hi}` of the (6,7) record on
`Z_279 ⋊ Z_15`. Generated by research/lean-haarD/gen_d6D7.py. Do not edit by hand.

`stageA{k}` (resp. `stageB{k}`) packs the base-6 codes of the A-words (resp. B-words) of the elements with indices
`{lo} ≤ n < {hi}`: the code of index `{lo} + i` is `codeAt stageA{k} i`, 16 bits each. -/

namespace BipartiteDD.Haar.D6D7

def stageA{k} : ℕ := {a}

def stageB{k} : ℕ := {b}

set_option maxRecDepth 100000 in
theorem certA{k} : chkA {lo} {len} stageA{k} = true := by decide +kernel

set_option maxRecDepth 100000 in
theorem certB{k} : chkB {lo} {len} stageB{k} = true := by decide +kernel

end BipartiteDD.Haar.D6D7
"""

COVER = """import BipartiteDD.Haar.D6D7.Check
{imports}

/-! Covering hypotheses of the (6,7) record: every element of `Z_279 ⋊ Z_15` is an A-word and a B-word in
the connection set `SS`, by the kernel-checked certificates of the stage modules. Generated by
research/lean-haarD/gen_d6D7.py. Do not edit by hand. -/

namespace BipartiteDD.Haar.D6D7

open BipartiteDD.Haar.Meta279

/-- Every index `n < 4185` has an A-code. -/
theorem exA (n : ℕ) (hn : n < 4185) : ∃ c, okA c n = true := by
  obtain ⟨k, hk⟩ : ∃ k, n / {stage} = k := ⟨_, rfl⟩
  have hk12 : k < {stages} := by omega
  rcases (show {ors} by omega) with {alts}
{casesA}

/-- Every index `n < 4185` has a B-code. -/
theorem exB (n : ℕ) (hn : n < 4185) : ∃ c, okB c n = true := by
  obtain ⟨k, hk⟩ : ∃ k, n / {stage} = k := ⟨_, rfl⟩
  have hk12 : k < {stages} := by omega
  rcases (show {ors} by omega) with {alts}
{casesB}

theorem cover1 : ∀ g : Grp, ∃ x1 ∈ SS, ∃ x2 ∈ SS, ∃ x3 ∈ SS, ∃ x4 ∈ SS, ∃ x5 ∈ SS, ∃ x6 ∈ SS,
    g = x1⁻¹ * x2 * x3⁻¹ * x4 * x5⁻¹ * x6 := by
  intro g
  obtain ⟨c, hc⟩ := exA (enc g) (enc_lt g)
  have h : grpOf (enc g) = wordA c := of_decide_eq_true hc
  rw [grpOf_enc] at h
  exact ⟨_, sel_mem _ (digit_lt c 0), _, sel_mem _ (digit_lt c 1), _, sel_mem _ (digit_lt c 2),
    _, sel_mem _ (digit_lt c 3), _, sel_mem _ (digit_lt c 4), _, sel_mem _ (digit_lt c 5), h⟩

theorem cover2 : ∀ g : Grp, ∃ x1 ∈ SS, ∃ x2 ∈ SS, ∃ x3 ∈ SS, ∃ x4 ∈ SS, ∃ x5 ∈ SS, ∃ x6 ∈ SS,
    g = x1 * x2⁻¹ * x3 * x4⁻¹ * x5 * x6⁻¹ := by
  intro g
  obtain ⟨c, hc⟩ := exB (enc g) (enc_lt g)
  have h : grpOf (enc g) = wordB c := of_decide_eq_true hc
  rw [grpOf_enc] at h
  exact ⟨_, sel_mem _ (digit_lt c 0), _, sel_mem _ (digit_lt c 1), _, sel_mem _ (digit_lt c 2),
    _, sel_mem _ (digit_lt c 3), _, sel_mem _ (digit_lt c 4), _, sel_mem _ (digit_lt c 5), h⟩

end BipartiteDD.Haar.D6D7
"""


def cover_text():
    imports = "\n".join("import BipartiteDD.Haar.D6D7.Stage%02d" % k for k in range(STAGES))
    cases = {}
    for side in ("A", "B"):
        lines = []
        for k in range(STAGES):
            lines.append("  · exact stageEx%s %d %d stage%s%02d cert%s%02d n (by omega) (by omega)"
                         % (side, k * STAGE, STAGE, side, k, side, k))
        cases[side] = "\n".join(lines)
    text = COVER
    text = text.replace("{imports}", imports)
    text = text.replace("{stage}", str(STAGE))
    text = text.replace("{stages}", str(STAGES))
    ors = " ∨ ".join("k = %d" % k for k in range(STAGES))
    alts = " | ".join("h%d" % k for k in range(STAGES))
    text = text.replace("{ors}", "(" + ors + ")").replace("{alts}", alts)
    text = text.replace("{casesA}", cases["A"])
    text = text.replace("{casesB}", cases["B"])
    return text


def pack(codes):
    v = 0
    for i, c in enumerate(codes):
        assert 0 <= c < 2 ** BITS
        v |= c << (BITS * i)
    return v


def emit_lean(digits, outdir):
    os.makedirs(outdir, exist_ok=True)
    for k in range(STAGES):
        lo = k * STAGE
        hi = lo + STAGE
        ca = [code_of(digits["A"][n]) for n in range(lo, hi)]
        cb = [code_of(digits["B"][n]) for n in range(lo, hi)]
        text = LEAN_STAGE.format(k="%02d" % k, stages=STAGES, lo=lo, hi=hi, len=STAGE,
                                 a="0x%x" % pack(ca), b="0x%x" % pack(cb))
        with open(os.path.join(outdir, "Stage%02d.lean" % k), "w") as f:
            f.write(text)
    with open(os.path.join(outdir, "Cover.lean"), "w") as f:
        f.write(cover_text())


def main():
    sol, outdir = sys.argv[1], sys.argv[2]
    S = parse_sol(sol)
    check_group()
    digits = find_words(S)
    verify(S, digits)
    os.makedirs(outdir, exist_ok=True)
    with open(os.path.join(outdir, "codes.json"), "w") as f:
        json.dump({"S": S, "A": digits["A"], "B": digits["B"]}, f)
    emit_lean(digits, os.path.join(outdir, "lean"))
    print("S =", S)
    print("verified A and B words for all", N, "elements")


if __name__ == "__main__":
    main()
