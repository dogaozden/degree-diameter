#!/usr/bin/env python3
"""Generate the Lean files for the (9,5) Haar record on 2928 vertices, G = C61 : C24 = <x, y | x^61 = y^24 = 1,
y x y^-1 = x^14> (y acts with order 6), S = {(0,0), (19,0), (42,12), (59,4), (35,20), (54,7), (30,5), (57,14), (56,10)}
(elements x^i y^j written (i,j)); edge list research/selfdual-d5/records/d9D5_n2928_haar_c61c24.edges.

Writes lean/BipartiteDD/Haar/D9D5C61C24/{Grp,Cert,Record2928}.lean and copies the edge list there, the same layout as the
(7,5) 1312 record (gen_d7D5_1312.py). Before writing, the script checks that the Haar graph of S on the numbering
i*24 + j (side A) and 1464 + i*24 + j (side B) is exactly the edge list (13,176 edges, 9-regular, 2,928 vertices).
Each element g of G gets a quadruple of indices into S with
  g = a^-1 b c^-1 d   (cert1)    and    g = a b^-1 c d^-1   (cert2).
usage: python3 research/lean-haarD/gen_d9D5_2928.py"""
import shutil
from itertools import product
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
EDGES = ROOT / "research/selfdual-d5/records/d9D5_n2928_haar_c61c24.edges"
OUT = ROOT / "lean/BipartiteDD/Haar/D9D5C61C24"
M, K, R = 61, 24, 14                      # x has order 61, y has order 24, y x y^-1 = x^R
S = [(0, 0), (19, 0), (42, 12), (59, 4), (35, 20), (54, 7), (30, 5), (57, 14), (56, 10)]
D = len(S)                                # the valency
N = M * K                                 # |G| = 1464
RP = [pow(R, j, M) for j in range(K)]     # r^j, the action of y^j on x

assert pow(R, K, M) == 1 and all(RP[(j + b) % K] == RP[j] * RP[b] % M for j in range(K) for b in range(K))


def mul(g, h):                            # (i, j)(a, b) = (i + r^j a, j + b)
    return ((g[0] + RP[g[1]] * h[0]) % M, (g[1] + h[1]) % K)


def inv(g):
    return (-(RP[(-g[1]) % K] * g[0]) % M, (-g[1]) % K)


def enc(g):                               # index on one side of the Haar graph
    return g[0] * K + g[1]


def grp_of(n):
    return (n // K, n % K)


elems = [(i, j) for i in range(M) for j in range(K)]
assert sorted(enc(g) for g in elems) == list(range(N))
assert all(grp_of(enc(g)) == g for g in elems)
assert all(mul(g, inv(g)) == (0, 0) and mul(inv(g), g) == (0, 0) for g in elems)
assert all(mul(mul(g, h), k) == mul(g, mul(h, k)) for g, h, k in product(elems[::37], elems[::41], elems[::23]))

# the Haar graph of S (vertex enc g on side A, N + enc h on side B, (g, A) ~ (s g, B)) against the edge file
lean_edges = sorted((enc(g), N + enc(mul(s, g))) for g in elems for s in S)
lines = EDGES.read_text().split()
assert lines[0] == str(2 * N)
file_edges = sorted((int(lines[k]), int(lines[k + 1])) for k in range(1, len(lines), 2))
assert len(lean_edges) == len(set(lean_edges)) == len(file_edges) == D * N, len(file_edges)
assert file_edges == lean_edges, "Haar graph of S differs from the edge file"
deg = Counter()
for a, b in file_edges:
    deg[a] += 1
    deg[b] += 1
assert set(deg.values()) == {D} and len(deg) == 2 * N


def find(word):
    tab = {}
    for w in product(range(D), repeat=4):
        g = word(*(S[i] for i in w))
        tab.setdefault(enc(g), w)
    assert len(tab) == N, len(tab)
    return [tab[n] for n in range(N)]


cert1 = find(lambda a, b, c, d: mul(mul(mul(inv(a), b), inv(c)), d))
cert2 = find(lambda a, b, c, d: mul(mul(mul(a, inv(b)), c), inv(d)))


def fmt_list(cert):
    items = ["(%d, %d, %d, %d)" % w for w in cert]
    rows = [", ".join(items[k:k + 6]) for k in range(0, len(items), 6)]
    return ",\n  ".join(rows)


def lean_elem(g):
    return "⟨%d, %d⟩" % g


S_LEAN = ", ".join(lean_elem(s) for s in S)
S_TEXT = ", ".join("(%d,%d)" % s for s in S)

