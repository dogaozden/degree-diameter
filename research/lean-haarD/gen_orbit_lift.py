#!/usr/bin/env python3
"""Lean folder for a fibre-transitive cyclic lift, by the orbit reduction (lean/BipartiteDD/Orbit.lean).

Input: an edge file (first line n, then one "u v" line per edge; .gz allowed) of a regular bipartite graph on
n = m * k vertices, in which the vertices m x, m x + 1, ..., m x + m - 1 form the fibre x, and the shift
tau(m x + h) = m x + (h + 1) mod m is an automorphism (the lifts of research/d10D7, with lift vertex (x, h) = m x + h).

What the script checks, independently of Lean, before writing anything:
  1. degrees all equal d, no repeated neighbour, the graph is bipartite, n = m k;
  2. tau preserves adjacency (every arc u-v maps to an arc tau(u)-tau(v));
  3. the radius-r masks over the k representatives m x (bit x of the mask of v at radius r: dist(m x, v) <= r)
     for r = 0 .. D; the radius-D masks are all full.
It then writes lean/BipartiteDD/Haar/<folder>/ with
  Graph.lean   neighbour lists and the colour classes (as Lean literals),
  Levels.lean  the masks of radii 1 .. D-1 (hex literals) and the list L,
  Local.lean   the local test (checkLocal), in two halves,
  Hom.lean     the shift check (homOK),
  Stage0..    one module per radius step (step K adj (L r) = L (r+1)),
  Record.lean  the theorem, from Orbit.lift_sound,
  Axioms.lean  #print axioms,
and copies the edge file into the folder. It then reads Graph.lean back and checks that its lists give exactly the
edge file, and that the levels read back equal the masks computed here.

usage: python3 research/lean-haarD/gen_orbit_lift.py EDGES M D FOLDER THEOREM [K]
  e.g. python3 research/lean-haarD/gen_orbit_lift.py research/d10D7/graphs/d12D5_n9840_gqdm_q9.edges.gz 6 5 D12D5GQ9Z6 nb_12_5_n9840
"""
import gzip
import re
import shutil
import sys
from collections import deque
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
OUT = ROOT / "lean/BipartiteDD/Haar"


def read_edges(path):
    text = gzip.open(path, "rt").read() if str(path).endswith(".gz") else Path(path).read_text()
    toks = text.split()
    n = int(toks[0])
    edges = [(int(toks[k]), int(toks[k + 1])) for k in range(1, len(toks), 2)]
    return n, edges


def neighbour_lists(n, edges):
    adj = [[] for _ in range(n)]
    for a, b in edges:
        adj[a].append(b)
        adj[b].append(a)
    return adj


def two_colour(n, adj):
    col = [None] * n
    col[0] = False
    queue = deque([0])
    while queue:
        u = queue.popleft()
        for w in adj[u]:
            if col[w] is None:
                col[w] = not col[u]
                queue.append(w)
            elif col[w] == col[u]:
                raise SystemExit("not bipartite")
    assert all(c is not None for c in col), "not connected"
    return col


def shift(m, v):
    return m * (v // m) + (v % m + 1) % m


def masks(n, m, k, adj, D):
    """levels[r][v]: bit x set iff dist(m x, v) <= r, for the representatives m x (x < k)."""
    levels = [[(1 << (v // m)) if v % m == 0 else 0 for v in range(n)]]
    for _ in range(D):
        cur = levels[-1]
        nxt = []
        for v in range(n):
            acc = cur[v]
            for u in adj[v]:
                acc |= cur[u]
            nxt.append(acc)
        levels.append(nxt)
    return levels


def lean_nat_list(xs):
    return "[" + ",\n  ".join(f"0x{x:x}" for x in xs) + "]"


def write_folder(folder, theorem, n, m, k, K, d, D, edges_path, adj, col, levels):
    fdir = OUT / folder
    fdir.mkdir(parents=True, exist_ok=True)
    ns = f"BipartiteDD.Haar.{folder}"
    gen = f"/- Generated by research/lean-haarD/gen_orbit_lift.py from {Path(edges_path).relative_to(ROOT)}. Do not edit by hand. -/"

    # Graph.lean
    rows = ["[" + ", ".join(str(w) for w in adj[u]) + "]" for u in range(n)]
    graph = [
        gen,
        f"namespace {ns}",
        "",
        "set_option maxRecDepth 1000000 in",
        "set_option maxHeartbeats 0 in",
        f"/-- Neighbour lists of the {n}-vertex graph, indexed by vertex number. -/",
        f"def adjL : List (List (Fin {n})) := [",
        ",\n".join("  " + r for r in rows),
        "]",
        "",
        "set_option maxRecDepth 100000 in",
        f"/-- The colour classes of the {n}-vertex graph (`true` on one side, `false` on the other). -/",
        "def colL : List Bool := [" + ", ".join("true" if c else "false" for c in col) + "]",
        "",
        f"end {ns}",
        "",
    ]
    (fdir / "Graph.lean").write_text("\n".join(graph))

    # Levels.lean: radii 1 .. D-1 as data, L 0 from the code, L D = replicate
    lev = [gen, "import BipartiteDD.Orbit", f"namespace {ns}", ""]
    for r in range(1, D):
        lev.append("set_option maxHeartbeats 0 in")
        lev.append("set_option maxRecDepth 1000000 in")
        lev.append(f"/-- The masks of radius {r} over the {k} representatives. -/")
        lev.append(f"def lev{r} : List ℕ := {lean_nat_list(levels[r])}")
        lev.append("")
    lev.append(f"/-- The list of masks at radius `r`: `L 0` from the code, `L {D}` the full masks. -/")
    lev.append("def L : ℕ → List ℕ")
    lev.append(f"  | 0 => BipartiteDD.Orbit.repLevel0 {m} {n}")
    for r in range(1, D):
        lev.append(f"  | {r} => lev{r}")
    lev.append(f"  | _ => List.replicate {n} (2 ^ {k} - 1)")
    lev.append("")
    lev.append(f"end {ns}")
    lev.append("")
    (fdir / "Levels.lean").write_text("\n".join(lev))

    # Local.lean: checkLocal, from four quarters (each quarter is one kernel check; the two halves
    # in one check peaked at 12.9 GB here), combined by Orbit.checkLocalRange_append
    q = n // 4
    assert n == 4 * q
    local = [
        gen,
        "import BipartiteDD.Orbit",
        f"import {ns}.Graph",
        "",
        f"namespace {ns}",
        "",
        "open BipartiteDD.Staged BipartiteDD.Orbit",
        "",
    ]
    for i in range(4):
        local += [
            "set_option maxRecDepth 100000 in",
            f"/-- The local test of vertices `{i * q} … {(i + 1) * q - 1}`. -/",
            f"theorem local_q{i} : checkLocalRange {K} {d} adjL colL {i * q} {q} = true := by",
            "  decide +kernel",
            "",
        ]
    local += [
        f"/-- The local test of vertices `0 … {2 * q - 1}`. -/",
        f"theorem local_lo : checkLocalRange {K} {d} adjL colL 0 {2 * q} = true :=",
        f"  checkLocalRange_join (lo2 := {q}) (tot := {2 * q}) (by decide) (by decide) local_q0 local_q1",
        "",
        f"/-- The local test of vertices `{2 * q} … {n - 1}`. -/",
        f"theorem local_hi : checkLocalRange {K} {d} adjL colL {2 * q} ({n} - {2 * q}) = true :=",
        f"  checkLocalRange_join (lo2 := {3 * q}) (tot := {n} - {2 * q}) (by decide) (by decide) local_q2 local_q3",
        "",
        f"/-- The local test of the {n}-vertex graph, from its two halves. -/",
        f"theorem local_ok : checkLocal {K} {d} adjL colL = true :=",
        f"  checkLocal_of_split (n := {n}) {2 * q} (by decide) local_lo local_hi",
        "",
        f"end {ns}",
        "",
    ]
    (fdir / "Local.lean").write_text("\n".join(local))

    # Hom.lean: the shift preserves adjacency, from eight pieces (one kernel check each; the whole
    # check in one kernel run was killed at 13 GB here), joined by Orbit.homOKRange_join
    c = n // 8
    assert n == 8 * c
    hom = [
        gen,
        "import BipartiteDD.Orbit",
        f"import {ns}.Graph",
        "",
        f"namespace {ns}",
        "",
        "open BipartiteDD.Orbit",
        "",
    ]
    for i in range(8):
        hom += [
            "set_option maxRecDepth 100000 in",
            f"/-- The shift check on the vertices `{i * c} … {(i + 1) * c - 1}`. -/",
            f"theorem hom_q{i} : homOKRange {m} {K} adjL {i * c} {c} = true := by",
            "  decide +kernel",
            "",
        ]
    prev = "hom_q0"
    for j in range(1, 8):
        hom += [
            f"/-- The shift check on the vertices `0 … {(j + 1) * c - 1}`. -/",
            f"theorem hom_p{j} : homOKRange {m} {K} adjL 0 {(j + 1) * c} = true :=",
            f"  homOKRange_join (lo2 := {j * c}) (tot := {(j + 1) * c}) (by decide) (by decide) {prev} hom_q{j}",
            "",
        ]
        prev = f"hom_p{j}"
    hom += [
        f"/-- The cyclic shift `h ↦ h + 1 (mod {m})` in each fibre is an automorphism of the graph. -/",
        f"theorem hom_ok : homOK {m} {K} adjL = true := by",
        "  unfold homOK",
        "  exact hom_p7",
        "",
        f"end {ns}",
        "",
    ]
    (fdir / "Hom.lean").write_text("\n".join(hom))

    # Stage files, one radius step each
    for r in range(D):
        st = [
            gen,
            "import BipartiteDD.Orbit",
            f"import {ns}.Graph",
            f"import {ns}.Levels",
            "",
            f"namespace {ns}",
            "",
            "open BipartiteDD.Fast",
            "",
            "set_option maxRecDepth 100000 in",
            f"/-- Radius step {r} → {r + 1} of the masks over the {k} representatives. -/",
            f"theorem stage{r} : step {K} (Tree.build [] {K} adjL) (L {r}) = L {r + 1} := by",
            "  decide +kernel",
            "",
            f"end {ns}",
            "",
        ]
        (fdir / f"Stage{r}.lean").write_text("\n".join(st))

    # Record.lean
    stage_imports = "\n".join(f"import {ns}.Stage{r}" for r in range(D))
    cases = " ∨ ".join(f"r = {r}" for r in range(D))
    rfls = " | ".join(["rfl"] * D)
    stages = ", ".join(f"stage{r}" for r in range(D))
    rec = [
        gen,
        "import BipartiteDD.Orbit",
        f"import {ns}.Graph",
        f"import {ns}.Levels",
        f"import {ns}.Local",
        f"import {ns}.Hom",
        stage_imports,
        "",
        f"namespace {ns}",
        "",
        "open BipartiteDD.Orbit",
        "",
        f"theorem hs : ∀ r < {D}, BipartiteDD.Fast.step {K} (BipartiteDD.Fast.Tree.build [] {K} adjL) (L r) = L (r + 1) := by",
        "  intro r hr",
        f"  obtain {rfls} : {cases} := by omega",
        f"  exacts [{stages}]",
        "",
        f"/-- The {n}-vertex graph (`k = {k}` representatives, `m = {m}`): bipartite, degree at most {d}, diameter at most {D}. -/",
        f"theorem {theorem} : ∃ G : SimpleGraph (Fin {n}), BipartiteDD.IsBipartiteDegDiam G {d} {D} :=",
        f"  lift_sound (n := {n}) (m := {m}) (k := {k}) (K := {K}) (d := {d}) (D := {D}) (by decide) (by decide)",
        "    (by decide) (by decide) adjL colL local_ok hom_ok L rfl hs rfl",
        "",
        f"end {ns}",
        "",
    ]
    (fdir / "Record.lean").write_text("\n".join(rec))
    # the axioms file
    (fdir / "Axioms.lean").write_text(f"import {ns}.Record\n\n#print axioms {ns}.{theorem}\n")
    shutil.copy(edges_path, fdir / Path(edges_path).name)


def read_back(folder, n, D, m, k, levels, edges):
    fdir = OUT / folder
    text = (fdir / "Graph.lean").read_text()
    adj_part = text.split("def adjL")[1].split("set_option maxRecDepth 100000 in")[0]
    rows = [[int(x) for x in re.findall(r"\d+", row)] for row in re.findall(r"\[[^\[\]]*\]", adj_part)]
    assert len(rows) == n, (len(rows), n)
    got = sorted({tuple(sorted((u, w))) for u in range(n) for w in rows[u]})
    want = sorted({tuple(sorted(e)) for e in edges})
    assert got == want, "Lean adjacency lists differ from the edge file"
    assert all(len(set(r)) == len(r) for r in rows)
    lev = (fdir / "Levels.lean").read_text()
    for r in range(1, D):
        block = lev.split(f"def lev{r} : List ℕ := [")[1].split("]")[0]
        vals = [int(x, 16) for x in re.findall(r"0x([0-9a-f]+)", block)]
        assert vals == levels[r], f"level {r} differs"
    print(f"read back OK: {n} vertices, {len(got)} edges equal the edge file; levels 1..{D - 1} equal the masks")


def main():
    edges_path, m, D, folder, theorem = str(Path(sys.argv[1]).resolve()), int(sys.argv[2]), int(sys.argv[3]), sys.argv[4], sys.argv[5]
    n, edges = read_edges(edges_path)
    k = n // m
    assert n == m * k
    adj = neighbour_lists(n, edges)
    degs = {len(a) for a in adj}
    assert len(degs) == 1, degs
    d = degs.pop()
    assert all(len(set(a)) == len(a) for a in adj), "repeated neighbour"
    col = two_colour(n, adj)
    # 2. the shift preserves adjacency
    arcs_ok = all(shift(m, u) in adj[shift(m, v)] for v in range(n) for u in adj[v])
    assert arcs_ok, "the shift is not an automorphism"
    # 3. masks over the representatives
    levels = masks(n, m, k, adj, D)
    assert all(x == (1 << k) - 1 for x in levels[D]), "radius-D masks not full"
    K = max(1, (n - 1).bit_length())  # 2 ^ K >= n
    print(f"n={n} m={m} k={k} d={d} D={D} K={K}; shift automorphism OK; radius-{D} masks full")
    for r in range(1, D + 1):
        print(f"  radius {r}: full vertices {sum(1 for x in levels[r] if x == (1 << k) - 1)} / {n}")
    if len(sys.argv) > 6:
        K = int(sys.argv[6])
    assert n <= 2 ** K
    write_folder(folder, theorem, n, m, k, K, d, D, edges_path, adj, col, levels)
    read_back(folder, n, D, m, k, levels, edges)


if __name__ == "__main__":
    main()
