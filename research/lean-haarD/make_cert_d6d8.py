"""Certificate generator for the Delta = 6, D = 8 record: Haar graph of SL(2,13) x Z_7 (N = 15288, 30576 vertices).

Reads research/frontier/sols/d6D8_sl_13_7_s1.txt. For every element g of G it finds shortest covering words for the three
covering conditions of lean/BipartiteDD/Haar/Diam8.lean (BFS over the walk graph, the same as build_haar2.py's
distances), checks each word by multiplying out in Python, and writes:
  lean/BipartiteDD/Haar/Cert30576Gens.lean   generators sS, the set SS, and the predicates okA, okB, okAB
  lean/BipartiteDD/Haar/Cert30576_<k>.lean   stage k: the entries n = 1024 k + i, i < 1024 (last stage shorter)
  lean/BipartiteDD/Haar/Record30576.lean     cover lemmas (dispatch over the stages), G30576 and nb_6_8

Element numbering: n = SL213.enc(a, b, c, d) * 7 + z, as in SL213Z7.lean.
Words, outermost factor first, padded with identity pairs (0, 0) at the front:
  A : g = a1⁻¹ b1 (a2⁻¹ b2) (a3⁻¹ b3) (a4⁻¹ b4)     cert (a1, b1, a2, b2, a3, b3, a4, b4)
  B : g = a1 b1⁻¹ (a2 b2⁻¹) (a3 b3⁻¹) (a4 b4⁻¹)     cert (a1, b1, a2, b2, a3, b3, a4, b4)
  AB: g = a1 b1⁻¹ (a2 b2⁻¹) (a3 b3⁻¹) s            cert (s, a1, b1, a2, b2, a3, b3)
Indices are positions in the generator list of the sol file.
"""
import os
import re

P = 13
Q = 7
NSL = 2184          # |SL(2,13)|
N = NSL * Q         # 15288
STAGE = 1024
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
SOL = os.path.join(ROOT, "research/frontier/sols/d6D8_sl_13_7_s1.txt")
OUT = os.path.join(ROOT, "lean/BipartiteDD/Haar")
HEADER = "/- Generated by research/lean-haarD/make_cert_d6d8.py. Do not edit by hand. -/\n"


def mul(g, h):
    a, b, c, d, z = g
    a2, b2, c2, d2, z2 = h
    return ((a * a2 + b * c2) % P, (a * b2 + b * d2) % P, (c * a2 + d * c2) % P,
            (c * b2 + d * d2) % P, (z + z2) % Q)


def inv(g):
    a, b, c, d, z = g
    return (d, (-b) % P, (-c) % P, a, (-z) % Q)


IDENT = (1, 0, 0, 1, 0)


def enc_sl(a, b, c, d):
    """Same numbering as SL213.enc."""
    if c == 0:
        return (a - 1) * P + b
    return 156 + ((c - 1) * P + a) * P + d


def index(g):
    a, b, c, d, z = g
    return enc_sl(a, b, c, d) * Q + z


def read_sol():
    lines = [ln for ln in open(SOL).read().split("\n") if ln.strip()]
    head = lines[0].split()
    assert head[:6] == ["6", "8", "sl", "13", "n", "7"] and head[6:8] == ["N", "15288"], head
    gens = []
    for ln in lines[1:7]:
        m = re.fullmatch(r"\s*\d+\s+mat\((\d+),(\d+),(\d+),(\d+)\)\s+z=(\d+)\s*", ln)
        assert m, ln
        a, b, c, d, z = (int(t) for t in m.groups())
        assert (a * d - b * c) % P == 1, ln
        gens.append((a, b, c, d, z))
    assert len(set(gens)) == 6
    return gens


def all_elements():
    els = []
    for a in range(P):
        for b in range(P):
            for c in range(P):
                for d in range(P):
                    if (a * d - b * c) % P == 1:
                        for z in range(Q):
                            els.append((a, b, c, d, z))
    assert len(els) == N
    assert len({index(g) for g in els}) == N
    return els


def bfs(pairs, combine, depth_max):
    """dep[g] = (pair, parent, depth) with g = combine(pair value, parent); dep[IDENT] = None."""
    dep = {IDENT: None}
    frontier = [IDENT]
    for level in range(1, depth_max + 1):
        nxt = []
        for h in frontier:
            for pr, u in pairs.items():
                g = combine(u, h)
                if g not in dep:
                    dep[g] = (pr, h, level)
                    nxt.append(g)
        frontier = nxt
    return dep


def word(dep, g, length):
    """Pairs of the shortest word for g, outermost first, padded with (0, 0) at the front to `length`."""
    pairs = []
    while dep[g] is not None:
        pr, parent, _ = dep[g]
        pairs.append(pr)
        g = parent
    assert len(pairs) <= length     # walking up the tree gives the outermost pair first
    return [(0, 0)] * (length - len(pairs)) + pairs


def lean_tuple(t):
    return "(" + ", ".join(str(x) for x in t) + ")"


def main():
    S = read_sol()
    elements = all_elements()
    pairs_A = {(i, j): mul(inv(S[i]), S[j]) for i in range(6) for j in range(6)}
    pairs_B = {(i, j): mul(S[i], inv(S[j])) for i in range(6) for j in range(6)}
    depA = bfs(pairs_A, mul, 4)
    depB = bfs(pairs_B, mul, 4)
    assert len(depA) == N, ("A covering incomplete", len(depA))
    assert len(depB) == N, ("B covering incomplete", len(depB))
    depB3 = {g: v for g, v in depB.items() if v is None or v[2] <= 3}

    certA = [None] * N
    certB = [None] * N
    certAB = [None] * N
    for g in elements:
        n = index(g)
        certA[n] = tuple(x for pr in word(depA, g, 4) for x in pr)
        certB[n] = tuple(x for pr in word(depB, g, 4) for x in pr)
    for x in elements:
        n = index(x)
        for s in range(6):
            W = mul(x, inv(S[s]))          # x = W s
            if W in depB3:
                certAB[n] = (s,) + tuple(t for pr in word(depB3, W, 3) for t in pr)
                break
        assert certAB[n] is not None, ("AB covering incomplete at", n)

    # independent check of every word by multiplying out (the Lean kernel check repeats it)
    def prod(seq):
        r = IDENT
        for g in seq:
            r = mul(r, g)
        return r
    for g in elements:
        n = index(g)
        c = certA[n]
        assert prod([mul(inv(S[c[2*k]]), S[c[2*k+1]]) for k in range(4)]) == g
        c = certB[n]
        assert prod([mul(S[c[2*k]], inv(S[c[2*k+1]])) for k in range(4)]) == g
        c = certAB[n]
        w = prod([mul(S[c[1+2*k]], inv(S[c[2+2*k]])) for k in range(3)])
        assert mul(w, S[c[0]]) == g

    write(S, certA, certB, certAB)


def write(S, certA, certB, certAB):
    gens_lean = ", ".join(f"(⟨{a}, {b}, {c}, {d}, by decide⟩, Multiplicative.ofAdd ({z} : ZMod 7))"
                          for (a, b, c, d, z) in S)
    gens = f"""{HEADER}import BipartiteDD.Haar.SL213Z7
import Mathlib.Data.Fin.VecNotation

/-! The generators `S` of the (6,8) record on 30576 vertices: the Haar graph of `SL(2, 13) × Z_7`, with the six
elements of `research/frontier/sols/d6D8_sl_13_7_s1.txt` in file order. The predicates `okA`, `okB`, `okAB` say that
the certificate entry for `grpOf7 n` is a covering word (see `Diam8.lean`). -/

namespace BipartiteDD.Haar.SL213Z7

open BipartiteDD.Haar

/-- The connection set `S` (`|S| = 6`). -/
def sS : Fin 6 → Gp :=
  ![{gens_lean}]

/-- `S` as a finset. -/
def SS : Finset Gp := Finset.univ.image sS

theorem card_SS : SS.card = 6 := by decide +kernel

theorem sS_mem (i : Fin 6) : sS i ∈ SS :=
  Finset.mem_image_of_mem sS (Finset.mem_univ i)

/-- The `A`-side word: `grpOf7 n = a₁⁻¹ b₁ (a₂⁻¹ b₂) (a₃⁻¹ b₃) (a₄⁻¹ b₄)`. -/
def okA (n : ℕ) : Fin 6 × Fin 6 × Fin 6 × Fin 6 × Fin 6 × Fin 6 × Fin 6 × Fin 6 → Bool
  | (a, b, c, d, e, f, p, q) =>
    decide (grpOf7 n = (sS a)⁻¹ * sS b * ((sS c)⁻¹ * sS d) * ((sS e)⁻¹ * sS f) * ((sS p)⁻¹ * sS q))

/-- The `B`-side word: `grpOf7 n = a₁ b₁⁻¹ (a₂ b₂⁻¹) (a₃ b₃⁻¹) (a₄ b₄⁻¹)`. -/
def okB (n : ℕ) : Fin 6 × Fin 6 × Fin 6 × Fin 6 × Fin 6 × Fin 6 × Fin 6 × Fin 6 → Bool
  | (a, b, c, d, e, f, p, q) =>
    decide (grpOf7 n = sS a * (sS b)⁻¹ * (sS c * (sS d)⁻¹) * (sS e * (sS f)⁻¹) * (sS p * (sS q)⁻¹))

/-- The mixed word: `grpOf7 n = a₁ b₁⁻¹ (a₂ b₂⁻¹) (a₃ b₃⁻¹) s`. -/
def okAB (n : ℕ) : Fin 6 × Fin 6 × Fin 6 × Fin 6 × Fin 6 × Fin 6 × Fin 6 → Bool
  | (s, a, b, c, d, e, f) =>
    decide (grpOf7 n = sS a * (sS b)⁻¹ * (sS c * (sS d)⁻¹) * (sS e * (sS f)⁻¹) * sS s)

end BipartiteDD.Haar.SL213Z7
"""
    open(os.path.join(OUT, "Cert30576Gens.lean"), "w").write(gens)

    stages = (N + STAGE - 1) // STAGE
    for k in range(stages):
        base = k * STAGE
        L = min(STAGE, N - base)
        body = ""
        for name, pred, cert, width, dflt in (
                ("certA", "okA", certA, 8, "(0, 0, 0, 0, 0, 0, 0, 0)"),
                ("certB", "okB", certB, 8, "(0, 0, 0, 0, 0, 0, 0, 0)"),
                ("certAB", "okAB", certAB, 7, "(0, 0, 0, 0, 0, 0, 0)")):
            entries = ",\n    ".join(lean_tuple(cert[base + i]) for i in range(L))
            tup = " × ".join(["Fin 6"] * width)
            body += (f"set_option maxRecDepth 100000 in\n"
                     f"/-- Entries `n = {base} + i`, `i < {L}`, of the `{pred}` certificate. -/\n"
                     f"def {name}_{k} : List ({tup}) := [\n    {entries}]\n\n"
                     f"set_option maxRecDepth 100000 in\n"
                     f"theorem {pred}_all_{k} :\n"
                     f"    (List.range {L}).all (fun i => {pred} ({base} + i) ({name}_{k}.getD i {dflt})) = true"
                     f" := by decide +kernel\n\n")
        src = (HEADER + f"import BipartiteDD.Haar.Cert30576Gens\n\n"
               f"/-! Certificate stage {k}: the entries `n` with `{base} ≤ n < {base + L}`. -/\n\n"
               "namespace BipartiteDD.Haar.SL213Z7\n\nopen BipartiteDD.Haar\n\n" + body +
               "end BipartiteDD.Haar.SL213Z7\n")
        open(os.path.join(OUT, f"Cert30576_{k}.lean"), "w").write(src)

    stages = (N + STAGE - 1) // STAGE
    imports = "\n".join(f"import BipartiteDD.Haar.Cert30576_{k}" for k in range(stages))
    rec = [HEADER.rstrip("\n"), "import BipartiteDD.Haar.Diam8", "import BipartiteDD.Haar.SL213Z7", imports,
           "import BipartiteDD.Haar.Cert30576Gens", "",
           "/-! The (6,8) record on 30576 vertices: the Haar graph of `SL(2, 13) × Z_7` with the connection set",
           "`SS` of `Cert30576Gens`. The covering hypotheses of `Haar.Diam8` are the stage certificates. -/", "",
           "namespace BipartiteDD.Haar.SL213Z7", "", "open BipartiteDD.Haar", ""]

    def cover(pred, width, name_final):
        disj = " ∨\n      ".join(
            (f"n < {min(STAGE, N)}" if k == 0 else
             f"({k * STAGE} ≤ n ∧ n < {k * STAGE + min(STAGE, N - k * STAGE)})")
            for k in range(stages))
        alts = " | ".join(f"h{k}" for k in range(stages))
        out = [f"theorem {pred}_cover (n : ℕ) (hn : n < {N}) : ∃ w, {pred} n w = true := by",
               f"  rcases (show {disj} by omega) with {alts}"]
        for k in range(stages):
            base = k * STAGE
            L = min(STAGE, N - base)
            cert = {"okA": "certA", "okB": "certB", "okAB": "certAB"}[pred]
            dflt = "(0, 0, 0, 0, 0, 0, 0, 0)" if width == 8 else "(0, 0, 0, 0, 0, 0, 0)"
            out.append(f"  · have h : {pred} ({base} + (n - {base})) ({cert}_{k}.getD (n - {base}) {dflt}) = true :=")
            out.append(f"      List.all_eq_true.mp {pred}_all_{k} (n - {base}) (List.mem_range.mpr (by omega))")
            out.append(f"    rw [show {base} + (n - {base}) = n by omega] at h")
            out.append("    exact ⟨_, h⟩")
        return out

    rec += cover("okA", 8, "coverA") + [""]
    rec += cover("okB", 8, "coverB") + [""]
    rec += cover("okAB", 7, "coverAB") + [""]
    rec += [
        "theorem coverA' (g : Gp) : ∃ a₁ ∈ SS, ∃ b₁ ∈ SS, ∃ a₂ ∈ SS, ∃ b₂ ∈ SS, ∃ a₃ ∈ SS, ∃ b₃ ∈ SS,",
        "    ∃ a₄ ∈ SS, ∃ b₄ ∈ SS, g = a₁⁻¹ * b₁ * (a₂⁻¹ * b₂) * (a₃⁻¹ * b₃) * (a₄⁻¹ * b₄) := by",
        "  obtain ⟨⟨a, b, c, d, e, f, p, q⟩, hw⟩ := okA_cover (enc7 g) (enc7_lt g)",
        "  simp only [okA, decide_eq_true_eq] at hw",
        "  rw [grpOf7_enc] at hw",
        "  exact ⟨sS a, sS_mem a, sS b, sS_mem b, sS c, sS_mem c, sS d, sS_mem d, sS e, sS_mem e,",
        "    sS f, sS_mem f, sS p, sS_mem p, sS q, sS_mem q, hw⟩", "",
        "theorem coverB' (g : Gp) : ∃ a₁ ∈ SS, ∃ b₁ ∈ SS, ∃ a₂ ∈ SS, ∃ b₂ ∈ SS, ∃ a₃ ∈ SS, ∃ b₃ ∈ SS,",
        "    ∃ a₄ ∈ SS, ∃ b₄ ∈ SS, g = a₁ * b₁⁻¹ * (a₂ * b₂⁻¹) * (a₃ * b₃⁻¹) * (a₄ * b₄⁻¹) := by",
        "  obtain ⟨⟨a, b, c, d, e, f, p, q⟩, hw⟩ := okB_cover (enc7 g) (enc7_lt g)",
        "  simp only [okB, decide_eq_true_eq] at hw",
        "  rw [grpOf7_enc] at hw",
        "  exact ⟨sS a, sS_mem a, sS b, sS_mem b, sS c, sS_mem c, sS d, sS_mem d, sS e, sS_mem e,",
        "    sS f, sS_mem f, sS p, sS_mem p, sS q, sS_mem q, hw⟩", "",
        "theorem coverAB' (x : Gp) : ∃ s ∈ SS, ∃ a₁ ∈ SS, ∃ b₁ ∈ SS, ∃ a₂ ∈ SS, ∃ b₂ ∈ SS, ∃ a₃ ∈ SS,",
        "    ∃ b₃ ∈ SS, x = a₁ * b₁⁻¹ * (a₂ * b₂⁻¹) * (a₃ * b₃⁻¹) * s := by",
        "  obtain ⟨⟨s, a, b, c, d, e, f⟩, hw⟩ := okAB_cover (enc7 x) (enc7_lt x)",
        "  simp only [okAB, decide_eq_true_eq] at hw",
        "  rw [grpOf7_enc] at hw",
        "  exact ⟨sS s, sS_mem s, sS a, sS_mem a, sS b, sS_mem b, sS c, sS_mem c, sS d, sS_mem d,",
        "    sS e, sS_mem e, sS f, sS_mem f, hw⟩", "",
        "/-- The `(6,8)` graph on `Fin 30576`: the Haar graph of `SS`. -/",
        "def G30576 : SimpleGraph (Fin 30576) := (haarGraph SS).comap equiv30576.symm", "",
        "theorem nb_6_8 : BipartiteDD.IsBipartiteDegDiam G30576 6 8 := by",
        "  have h := isBipartiteDegDiam8_of SS G30576 equiv30576",
        "    (fun x y => by simp [G30576, SimpleGraph.comap_adj]) coverA' coverB' coverAB'",
        "  rw [card_SS] at h",
        "  exact h", "",
        "theorem nb_6_8_exists : ∃ G : SimpleGraph (Fin 30576), BipartiteDD.IsBipartiteDegDiam G 6 8 :=",
        "  ⟨G30576, nb_6_8⟩", "",
        "end BipartiteDD.Haar.SL213Z7", ""]
    open(os.path.join(OUT, "Record30576.lean"), "w").write("\n".join(rec))
    print("wrote", stages, "stage modules; N =", N)


if __name__ == "__main__":
    main()
