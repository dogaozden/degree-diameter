#!/usr/bin/env python3
"""Generate the Lean neighbour tables for three regular voltage-lift records that have no Lean proof on master:
(3,10) 810, (3,11) 1344, (3,12) 2368 (gaps job, see research/lean-haarD/GAPS.md).

For each record this script
  1. reads the edge file (first line n, then one "u v" line per edge),
  2. checks it: every vertex has degree 3 with no repeated neighbour, the graph is bipartite, and every two vertices
     are within D steps (all-pairs BFS, independent of the lab's apsp.c),
  3. writes lean/BipartiteDD/Haar/<folder>/Graph.lean with the neighbour lists and the 2-colouring as Lean literals,
     and copies the edge file next to it,
  4. reads Graph.lean back and checks that its lists give exactly the edge file (same edges, same degrees).
The Record.lean files are written by hand from the same template (see write_record below); the kernel check is
`Fast.check_of_fast` with `decide +kernel`, as in D5New/Record384.lean.

usage: python3 research/lean-haarD/gen_lift_gaps.py
"""
import gzip
import re
import shutil
from collections import deque
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
REC = ROOT / "research/squads/own-small/records"
OUT = ROOT / "lean/BipartiteDD/Haar"

RECORDS = [
    # n, Delta, D, Fast depth K (2^K >= n), edge file, folder
    dict(n=810, d=3, D=10, K=10, folder="D3D10N810", edges=REC / "d3D10_n810_c3xheis27.edges"),
    dict(n=1344, d=3, D=11, K=11, folder="D3D11N1344", edges=REC / "d3D11_n1344_meta7_24.edges"),
    dict(n=2368, d=3, D=12, K=12, folder="D3D12N2368", edges=REC / "d3D12_n2368_meta37_8.edges"),
    dict(n=4800, d=10, D=5, K=13, folder="D10D5GQ7Z6", edges=ROOT / "research/d10D7/graphs/d10D5_n4800_gqdm_q7.edges.gz"),
    dict(n=7020, d=11, D=5, K=13, folder="D11D5GQ8Z6", edges=ROOT / "research/d10D7/graphs/d11D5_n7020_gqdm_q8.edges.gz"),
]


def read_edges(path):
    text = gzip.open(path, "rt").read() if path.suffix == ".gz" else path.read_text()
    toks = text.split()
    n = int(toks[0])
    edges = [(int(toks[k]), int(toks[k + 1])) for k in range(1, len(toks), 2)]
    return n, edges


def neighbour_lists(n, edges):
    adj = [[] for _ in range(n)]
    for a, b in edges:
        adj[a].append(b)
        adj[b].append(a)
    return adj


def two_colour(n, adj):
    col = [None] * n
    col[0] = False
    queue = deque([0])
    while queue:
        u = queue.popleft()
        for w in adj[u]:
            if col[w] is None:
                col[w] = not col[u]
                queue.append(w)
            elif col[w] == col[u]:
                raise SystemExit("not bipartite")
    assert all(c is not None for c in col), "not connected"
    return col


def bfs(adj, s):
    dist = [-1] * len(adj)
    dist[s] = 0
    queue = deque([s])
    while queue:
        u = queue.popleft()
        for w in adj[u]:
            if dist[w] < 0:
                dist[w] = dist[u] + 1
                queue.append(w)
    return dist


def within(n, adj, D):
    """Bitset check: every vertex reaches every vertex within D steps (bit w of ball[v] is set iff dist(v, w) ≤ r)."""
    ball = [1 << v for v in range(n)]
    for _ in range(D):
        nxt = []
        for v in range(n):
            m = ball[v]
            for u in adj[v]:
                m |= ball[u]
            nxt.append(m)
        ball = nxt
    return all(b == (1 << n) - 1 for b in ball)


def check_record(rec, n, edges, adj, col):
    assert n == rec["n"], (n, rec["n"])
    assert len(edges) == n * rec["d"] // 2, len(edges)
    for u in range(n):
        assert len(adj[u]) == rec["d"] and len(set(adj[u])) == rec["d"], (u, adj[u])
        assert all(col[u] != col[w] for w in adj[u])
    assert within(n, adj, rec["D"]), "diameter exceeds D"
    return rec["D"]


def write_graph(rec, n, adj, col, name):
    folder = OUT / rec["folder"]
    folder.mkdir(parents=True, exist_ok=True)
    src = f"/- Generated by research/lean-haarD/gen_lift_gaps.py from {rec['edges'].relative_to(ROOT)}. Do not edit by hand. -/\n"
    # the largest tables need unlimited heartbeats to elaborate (as in Graphs/G9592)
    heart = ["set_option maxHeartbeats 0 in"] if n >= 4000 else []
    body = [
        f"namespace BipartiteDD.Haar.{name}",
        "",
        "set_option maxRecDepth 100000 in",
        *heart,
        f"/-- Neighbour lists of the {n}-vertex graph, indexed by vertex number. -/",
        f"def adjL : List (List (Fin {n})) := [",
    ]
    lists = ["[" + ", ".join(str(w) for w in adj[u]) + "]" for u in range(n)]
    body += [",\n".join("  " + row for row in lists) + "\n]", ""]
    body += [
        "set_option maxRecDepth 100000 in",
        *heart,
        f"/-- The colour classes of the {n}-vertex graph (`true` on one side, `false` on the other). -/",
        "def colL : List Bool := [" + ", ".join("true" if c else "false" for c in col) + "]",
        "",
        f"def nbrs (v : Fin {n}) : List (Fin {n}) := adjL.getD v.val []",
        f"def color (v : Fin {n}) : Bool := colL.getD v.val false",
        "",
        f"end BipartiteDD.Haar.{name}",
        "",
    ]
    (folder / "Graph.lean").write_text(src + "\n".join(body))
    shutil.copy(rec["edges"], folder / rec["edges"].name)


def read_back(rec, n, path):
    text = path.read_text()
    adjL = text.split("def adjL")[1].split("def colL")[0]
    lists = [[int(x) for x in re.findall(r"\d+", row)] for row in re.findall(r"\[[^\[\]]*\]", adjL)]
    assert len(lists) == n, (len(lists), n)
    colL = text.split("def colL : List Bool := [")[1].split("]")[0]
    cols = [c.strip() == "true" for c in colL.split(",")]
    assert len(cols) == n
    edges = sorted({tuple(sorted((u, w))) for u in range(n) for w in lists[u]})
    return lists, cols, edges


def main():
    for rec in RECORDS:
        n, edges = read_edges(rec["edges"])
        adj = neighbour_lists(n, edges)
        col = two_colour(n, adj)
        diam = check_record(rec, n, edges, adj, col)
        write_graph(rec, n, adj, col, rec["folder"])
        lists, cols, lean_edges = read_back(rec, n, OUT / rec["folder"] / "Graph.lean")
        assert lean_edges == sorted({tuple(sorted(e)) for e in edges}), "Lean lists differ from the edge file"
        assert lists == adj and cols == col
        print(f"{rec['folder']}: n={n} d={rec['d']} diameter={diam} <= D={rec['D']}, Lean lists equal the edge file")


if __name__ == "__main__":
    main()
