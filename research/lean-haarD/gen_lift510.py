#!/usr/bin/env python3
"""Covering certificates for the (5,10) record: G = Z_1989 x|_461 Z_24 (order 47736), S from
research/lifts/sols/d5D10_n95472_haar_meta1989_24_461.txt (lines "e 0 1 = a,j").

Cover (one condition, even D = 10, see lean/BipartiteDD/Haar/Diam10.lean): every g in G is
  x1 (x2^-1) x3 (x4^-1) x5 (x6^-1) x7 (x8^-1) x9      with all xi in S.
Letters: digit d_p (0..4) of the code c = sum d_p 5^p selects s_{d_p}; odd positions p are inverted.
Group: (a,j)(b,l) = (a + r^j b mod m, j + l mod k), inverse (a,j)^-1 = (-r^-j a, -j), index n = a*k + j.
The Lean side (lean/BipartiteDD/Haar/LiftC/) uses the same formulas with ZMod arithmetic; every chosen code is
re-checked here by a scalar mirror of those formulas (gmul, ginv, wordOf_py).

Usage: python3 -I gen_lift510.py SOL.txt OUTDIR [STAGE]
Writes OUTDIR/Check.lean, OUTDIR/Stage00.lean ..., OUTDIR/Cover.lean (STAGE indices per stage, default 1326).
Stage files are checked by `decide +kernel` one at a time.
"""
import re
import sys

import numpy as np

BASE = 5
DIG = 9
CODE_BITS = 21  # 5^9 = 1953125 < 2^21
assert BASE ** DIG < 2 ** CODE_BITS


def parse_sol(path):
    lines = [ln.strip() for ln in open(path) if ln.strip()]
    grp = [ln for ln in lines if ln.startswith("group meta ")]
    assert len(grp) == 1, grp
    m, k, r = map(int, grp[0].split()[2:5])
    S = []
    for ln in lines:
        mm = re.fullmatch(r"e 0 1 = (\d+),(\d+)", ln)
        if mm:
            S.append((int(mm.group(1)), int(mm.group(2))))
    assert len(S) == 5 and len(set(S)) == 5, S
    assert pow(r, k, m) == 1
    return m, k, r, S


def gmul(p, q, m, k, r):  # Lean: mul p q = ⟨p.x + tw p.y * q.x, p.y + q.y⟩ with tw y = r ^ y.val
    return ((p[0] + pow(r, p[1], m) * q[0]) % m, (p[1] + q[1]) % k)


def ginv(p, m, k, r):  # Lean: inv p = ⟨-(tw (-p.y) * p.x), -p.y⟩
    return ((-(pow(r, (-p[1]) % k, m) * p[0])) % m, (-p[1]) % k)


def wordOf_py(xs, m, k, r):  # x1 * (x2⁻¹ * (x3 * ( ... (x8⁻¹ * x9)))), right-nested, 0-indexed xs[0..8]
    acc = xs[8]
    for i in range(7, -1, -1):
        v = xs[i] if i % 2 == 0 else ginv(xs[i], m, k, r)
        acc = gmul(v, acc, m, k, r)
    return acc


def main():
    sol, outdir = sys.argv[1], sys.argv[2]
    STAGE = int(sys.argv[3]) if len(sys.argv) > 3 else 1326
    m, k, r, S = parse_sol(sol)
    N = m * k
    assert N % STAGE == 0, (N, STAGE)
    NSTAGES = N // STAGE

    # all 5^9 codes at once: letter at position p is s_{d_p} (inverse for odd p), product left to right
    R = np.array([pow(r, j, m) for j in range(k)], dtype=np.int64)
    Rinv = np.array([pow(pow(r, j, m), -1, m) for j in range(k)], dtype=np.int64)
    SA = np.array([s[0] for s in S], dtype=np.int64)
    SJ = np.array([s[1] for s in S], dtype=np.int64)
    codes = np.arange(BASE ** DIG, dtype=np.int64)
    digs = [(codes // BASE ** p) % BASE for p in range(DIG)]

    def letter(p):
        a, j = SA[digs[p]], SJ[digs[p]]
        if p % 2 == 1:
            a, j = (-(Rinv[j] * a)) % m, (-j) % k
        return a, j

    a, j = letter(0)
    for p in range(1, DIG):
        b, l = letter(p)
        a, j = (a + R[j] * b) % m, (j + l) % k
    idx = a * k + j
    uniq, first = np.unique(idx, return_index=True)
    assert len(uniq) == N and np.array_equal(uniq, np.arange(N)), "cover fails: some element has no word"
    code_of = first.astype(np.int64)  # smallest code per element index

    # re-check every chosen code by the scalar mirror of the Lean definitions
    for n in range(N):
        c = int(code_of[n])
        xs = [S[c // BASE ** p % BASE] for p in range(DIG)]
        g = wordOf_py(xs, m, k, r)
        assert g[0] * k + g[1] == n, (n, c, g)
    print(f"cover OK: all {N} elements, {len(S)} generators, stages {NSTAGES} x {STAGE}")

    def sgrp(s):
        return f"⟨{s[0]}, {s[1]}⟩"

    sv = ", ".join(sgrp(s) for s in S)
    check = f"""import BipartiteDD.Haar.LiftC.Meta1989

/-! The kernel-checkable certificate of the (5,10) record on `Z_1989 ⋊ Z_24` (order 47736).

The connection set `S` is the five elements `sVec` of `research/lifts/sols/d5D10_n95472_haar_meta1989_24_461.txt`.
The code `c = Σ dₚ 5ᵖ` (nine digits) gives the word `x₁ x₂⁻¹ x₃ x₄⁻¹ x₅ x₆⁻¹ x₇ x₈⁻¹ x₉` with `xₚ = s_{{dₚ}}`;
`wordOf` is that product in any group. `okC c n` says that the word of `c` is the element with index `n`.
The stage tables are generated by research/lean-haarD/gen_lift510.py. Do not edit by hand. -/

namespace BipartiteDD.Haar.LiftC

open BipartiteDD.Haar.LiftC.Meta1989

/-- The nine-letter alternating word `x₁ x₂⁻¹ x₃ x₄⁻¹ x₅ x₆⁻¹ x₇ x₈⁻¹ x₉` in a group, right-nested. It is the
right-hand side of `CoverHyp`, so `wordOf` is the same term as the covering word in every group. -/
def wordOf {{G : Type*}} [Group G] (x₁ x₂ x₃ x₄ x₅ x₆ x₇ x₈ x₉ : G) : G :=
  x₁ * (x₂⁻¹ * (x₃ * (x₄⁻¹ * (x₅ * (x₆⁻¹ * (x₇ * (x₈⁻¹ * x₉)))))))

/-- The connection set, as elements `(x, y)` of `Z_1989 ⋊ Z_24`, in the order of the sol file. -/
def sVec : List Grp := [{sv}]

/-- The `j`-th element of `S`, for `j < 5`. -/
def sel (j : ℕ) : Grp := sVec.getD j 1

/-- `S` as a finset. -/
def SS : Finset Grp := sVec.toFinset

theorem card_SS : SS.card = 5 := by decide +kernel

theorem sel_mem_all : (List.range 5).all (fun j => decide (sel j ∈ SS)) = true := by
  decide +kernel

theorem sel_mem (j : ℕ) (hj : j < 5) : sel j ∈ SS := by
  have h := List.all_eq_true.mp sel_mem_all j (List.mem_range.mpr hj)
  simpa using h

/-- The digit `p` of the code `c`, in base 5. -/
def dig (c p : ℕ) : ℕ := c / 5 ^ p % 5

theorem dig_lt (c p : ℕ) : dig c p < 5 := Nat.mod_lt _ (by norm_num)

/-- The nine-letter word of the code `c`. -/
def wordG (c : ℕ) : Grp :=
  wordOf (sel (dig c 0)) (sel (dig c 1)) (sel (dig c 2)) (sel (dig c 3)) (sel (dig c 4)) (sel (dig c 5))
    (sel (dig c 6)) (sel (dig c 7)) (sel (dig c 8))

/-- The code `c` gives the element with index `n` of `Z_1989 ⋊ Z_24`. -/
def okC (c n : ℕ) : Bool := decide (grpOf n = wordG c)

/-- The code in position `i` of a stage table `C`: 21 bits each. -/
def codeAt (C i : ℕ) : ℕ := (C >>> ({CODE_BITS} * i)) % {2 ** CODE_BITS}

/-- `chkC base len C`: the codes of the stage table `C` certify the indices `base … base + len - 1`. -/
def chkC (base len C : ℕ) : Bool :=
  (List.range len).all (fun i => okC (codeAt C i) (base + i))

theorem okC_ex (base len C : ℕ) (h : chkC base len C = true) (n : ℕ) (hn : base ≤ n) (hn' : n < base + len) :
    ∃ c, okC c n = true := by
  refine ⟨codeAt C (n - base), ?_⟩
  have := List.all_eq_true.mp h (n - base) (List.mem_range.mpr (by omega))
  rwa [show base + (n - base) = n by omega] at this

theorem okC_spec {{c n : ℕ}} (h : okC c n = true) : grpOf n = wordG c :=
  of_decide_eq_true h

end BipartiteDD.Haar.LiftC
"""
    with open(f"{outdir}/Check.lean", "w") as f:
        f.write(check)

    stage_names = []
    for st in range(NSTAGES):
        lo, hi = st * STAGE, (st + 1) * STAGE
        C = 0
        for i in range(STAGE):
            C |= int(code_of[lo + i]) << (CODE_BITS * i)
        name = f"{st:02d}"
        stage_names.append(name)
        body = f"""import BipartiteDD.Haar.LiftC.Check

/-! Certificates for the (5,10) record, stage {name} of {NSTAGES - 1}: the indices `{lo} ≤ n < {hi}`.
Generated by research/lean-haarD/gen_lift510.py. Do not edit by hand. -/

namespace BipartiteDD.Haar.LiftC

def stageC{name} : ℕ := 0x{C:x}

set_option maxRecDepth 100000 in
theorem certC{name} : chkC {lo} {STAGE} stageC{name} = true := by decide +kernel

end BipartiteDD.Haar.LiftC
"""
        with open(f"{outdir}/Stage{name}.lean", "w") as f:
            f.write(body)

    imports = "\n".join(f"import BipartiteDD.Haar.LiftC.Stage{nm}" for nm in stage_names)
    disj = " ∨ ".join(f"n / {STAGE} = {st}" for st in range(NSTAGES))
    rcases_pat = " | ".join("h" for _ in range(NSTAGES))
    cases = "\n".join(
        f"  · exact okC_ex {st * STAGE} {STAGE} stageC{nm} certC{nm} n (by omega) (by omega)"
        for st, nm in enumerate(stage_names))
    cover = f"""import BipartiteDD.Haar.LiftC.Check
{imports}

/-! Every index `n < {N}` has a certificate code, by the stage checks. Generated by
research/lean-haarD/gen_lift510.py. Do not edit by hand. -/

namespace BipartiteDD.Haar.LiftC

theorem exC (n : ℕ) (hn : n < {N}) : ∃ c, okC c n = true := by
  have hk : n / {STAGE} < {NSTAGES} := by omega
  rcases (show {disj} by omega) with {rcases_pat}
{cases}

end BipartiteDD.Haar.LiftC
"""
    with open(f"{outdir}/Cover.lean", "w") as f:
        f.write(cover)
    print(f"wrote Check.lean, Stage00..Stage{NSTAGES - 1:02d}.lean, Cover.lean to {outdir}")


if __name__ == "__main__":
    main()
