#!/usr/bin/env python3
"""Generate the Lean covering certificates for the (4,7) Haar record on 864 vertices (gaps job, see GAPS.md).

G = Heis(F_9) x| C_16 (order 432), S = {(0,0,0,0), (0,2,0,9), (2,1,0,8), (1,2,2,14)} as (a, b, z, j) with v = a + b i,
exactly as research/theorems/smallfam/graphs/build_d4D7_n864.py. The Lean group in
lean/BipartiteDD/Haar/D4D7Heis9C16/Grp.lean is written with the same formulas; this script mirrors them.

It checks, in Python,
  1. the group axioms of the mirrored law (associativity on all triples of a sample, identity, left inverses on all
     432 elements),
  2. that the Haar graph of S under the numbering `enc` (A side 0..431, B side 432..863, (g,A) ~ (s g, B)) is exactly
     research/theorems/smallfam/graphs/d4D7_n864_heis9xC16.edges.gz,
  3. for every g, a six-letter A-word x1^-1 x2 x3^-1 x4 x5^-1 x6 and a six-letter B-word x1 x2^-1 x3 x4^-1 x5 x6^-1 in S,
and writes lean/BipartiteDD/Haar/D4D7Heis9C16/Cert.lean with the index tuples (into S, 0-based) of those words, one row
per element number n (the word for n equals grpOf n).

usage: python3 research/lean-haarD/gen_d4D7_n864.py"""
import gzip
import itertools
import random
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
EDGES = ROOT / "research/theorems/smallfam/graphs/d4D7_n864_heis9xC16.edges.gz"
OUT = ROOT / "lean/BipartiteDD/Haar/D4D7Heis9C16"
S = [(0, 0, 0, 0), (0, 2, 0, 9), (2, 1, 0, 8), (1, 2, 2, 14)]
N = 432


def mu(k):
    p, q = 1, 0
    for _ in range(k):
        p, q = (p - q) % 3, (p + q) % 3
    return p, q


def P(j):
    return mu(j % 16)[0]


def Q(j):
    return mu(j % 16)[1]


def Sg(j):
    return 1 if (j % 16) % 2 == 0 else 2


def mul(x, y):
    a, b, z, j = x
    c, d, w, l = y
    p, q, s = P(j), Q(j), Sg(j)
    wa = (p * c - q * d) % 3
    wb = (p * d + q * c) % 3
    return ((a + wa) % 3, (b + wb) % 3, (z + s * w + 2 * (a * wb - b * wa)) % 3, (j + l) % 16)


def inv(x):
    a, b, z, j = x
    nj = (-j) % 16
    p, q = P(nj), Q(nj)
    wa = (p * a - q * b) % 3
    wb = (p * b + q * a) % 3
    return ((-wa) % 3, (-wb) % 3, (-(Sg(j) * z)) % 3, nj)


ONE = (0, 0, 0, 0)
ELS = [(a, b, z, j) for a in range(3) for b in range(3) for z in range(3) for j in range(16)]


def enc(g):
    a, b, z, j = g
    return ((a * 3 + b) * 3 + z) * 16 + j


assert [enc(g) for g in ELS] == list(range(N))
assert all(mul(g, inv(g)) == ONE and mul(inv(g), g) == ONE for g in ELS), "inverse law"
assert all(mul(ONE, g) == g and mul(g, ONE) == g for g in ELS), "identity law"
rng = random.Random(1)
for _ in range(20000):
    x, y, w = rng.choice(ELS), rng.choice(ELS), rng.choice(ELS)
    assert mul(mul(x, y), w) == mul(x, mul(y, w)), "associativity"

toks = gzip.open(EDGES, "rt").read().split()
assert toks[0] == str(2 * N)
file_edges = sorted((int(toks[k]), int(toks[k + 1])) for k in range(1, len(toks), 2))
haar_edges = sorted({(enc(g), N + enc(mul(s, g))) for g in ELS for s in S})
assert len(haar_edges) == 4 * N
assert haar_edges == file_edges, "Haar graph of S differs from the edge file"
print(f"Haar graph of S equals {EDGES.name}: {len(file_edges)} edges")

# six-letter words over S, as index tuples
tuples = list(itertools.product(range(4), repeat=6))
word_a, word_b = {}, {}
for t in tuples:
    x = [S[i] for i in t]
    va = mul(mul(mul(mul(mul(inv(x[0]), x[1]), inv(x[2])), x[3]), inv(x[4])), x[5])
    vb = mul(mul(mul(mul(mul(x[0], inv(x[1])), x[2]), inv(x[3])), x[4]), inv(x[5]))
    word_a.setdefault(va, t)
    word_b.setdefault(vb, t)
assert len(word_a) == N and len(word_b) == N, (len(word_a), len(word_b))
cert_a = [word_a[g] for g in ELS]
cert_b = [word_b[g] for g in ELS]

# check each certificate on its element
for n, g in enumerate(ELS):
    for cert, word in ((cert_a[n], "A"), (cert_b[n], "B")):
        x = [S[i] for i in cert]
        if word == "A":
            v = mul(mul(mul(mul(mul(inv(x[0]), x[1]), inv(x[2])), x[3]), inv(x[4])), x[5])
        else:
            v = mul(mul(mul(mul(mul(x[0], inv(x[1])), x[2]), inv(x[3])), x[4]), inv(x[5]))
        assert v == g, (n, word)

def lean_rows(cert):
    rows = ["[" + ", ".join(str(i) for i in t) + "]" for t in cert]
    return ",\n  ".join(rows)


text = f"""/- Generated by research/lean-haarD/gen_d4D7_n864.py. Do not edit by hand. -/
namespace BipartiteDD.Haar.D4D7Heis9C16

/-- For each element number `n` (`0 … 431`, the numbering of `Grp.enc`), the six indices into `S` of its A-word
`x₁⁻¹ x₂ x₃⁻¹ x₄ x₅⁻¹ x₆`: `grpOf n = x₁⁻¹ x₂ x₃⁻¹ x₄ x₅⁻¹ x₆` with `xₖ = S[certA n k]`. -/
def certA : List (List (Fin 4)) := [
  {lean_rows(cert_a)}]

/-- For each element number `n`, the six indices of its B-word `x₁ x₂⁻¹ x₃ x₄⁻¹ x₅ x₆⁻¹`. -/
def certB : List (List (Fin 4)) := [
  {lean_rows(cert_b)}]

end BipartiteDD.Haar.D4D7Heis9C16
"""
(OUT / "Cert.lean").write_text(text)
shutil.copy(EDGES, OUT / EDGES.name)
print(f"wrote {OUT / 'Cert.lean'}: {len(cert_a)} A-rows, {len(cert_b)} B-rows")
