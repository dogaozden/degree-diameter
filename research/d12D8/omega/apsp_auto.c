/* apsp_mt.c with symmetry: the same checks (simple, max degree, bipartite, connected, exact diameter), but BFS only from
   one vertex per orbit of the group generated by the permutations in GENS, after checking that each of them is a
   bijection that maps every edge to an edge (so an automorphism: a bijection mapping E into E maps E onto E).
   Eccentricity is constant on orbits, so the largest eccentricity over the orbit representatives is the diameter.
   GENS: binary file of int32: g, n, then g permutations of [0,n) (perm[v] = image of v).
   Prints the diameter and one witness pair (source, vertex at the largest distance).
   Usage: apsp_auto EDGES GENS d D [T]       (build: cc -O2 -pthread -o apsp_auto apsp_auto.c) */
#include <pthread.h>
#include <stdio.h>
#include <stdlib.h>
#include <stdint.h>
#include <string.h>
static long n, *st, *adj, *src, nsrc;
static long next_k = 0; static int diam = 0, bad = 0; static long wit_s = -1, wit_t = -1;
static pthread_mutex_t mu = PTHREAD_MUTEX_INITIALIZER;
static int cmpl(const void *a, const void *b) { long x = *(const long *)a, y = *(const long *)b; return x < y ? -1 : x > y; }
static int has_edge(long u, long v) {
    long lo = st[u], hi = st[u + 1] - 1;
    while (lo <= hi) { long m = (lo + hi) / 2; if (adj[m] == v) return 1; if (adj[m] < v) lo = m + 1; else hi = m - 1; }
    return 0;
}
static long *uf; static long find(long x) { while (uf[x] != x) { uf[x] = uf[uf[x]]; x = uf[x]; } return x; }
static void *work(void *unused) {
    uint64_t *vis = malloc(n * 8), *fr = malloc(n * 8), *nx = malloc(n * 8);
    for (;;) {
        pthread_mutex_lock(&mu); long k0 = next_k; next_k += 64; int stop = bad; pthread_mutex_unlock(&mu);
        if (k0 >= nsrc || stop) break;
        memset(vis, 0, n * 8); memset(fr, 0, n * 8);
        int ns = (nsrc - k0 < 64) ? (int)(nsrc - k0) : 64; uint64_t full = ns == 64 ? ~0ULL : ((1ULL << ns) - 1);
        for (int k = 0; k < ns; k++) { vis[src[k0 + k]] |= 1ULL << k; fr[src[k0 + k]] |= 1ULL << k; }
        int lev = 0; long ws = -1, wt = -1;
        for (;;) { int any = 0;
            for (long x = 0; x < n; x++) { uint64_t acc = 0; for (long i = st[x]; i < st[x + 1]; i++) acc |= fr[adj[i]]; acc &= ~vis[x]; nx[x] = acc; if (acc) any = 1; }
            if (!any) break; lev++; for (long x = 0; x < n; x++) vis[x] |= nx[x];
            for (long x = 0; x < n; x++) if (nx[x]) { ws = src[k0 + __builtin_ctzll(nx[x])]; wt = x; break; }
            uint64_t *tmp = fr; fr = nx; nx = tmp; }
        for (long x = 0; x < n; x++) if (vis[x] != full) { pthread_mutex_lock(&mu); bad = 1; pthread_mutex_unlock(&mu); break; }
        pthread_mutex_lock(&mu); if (lev > diam) { diam = lev; wit_s = ws; wit_t = wt; } pthread_mutex_unlock(&mu);
    }
    free(vis); free(fr); free(nx); return NULL;
}
int main(int c, char **v) {
    FILE *f = fopen(v[1], "r"); int d = atoi(v[3]), D = atoi(v[4]), T = c > 5 ? atoi(v[5]) : 1; long m = 0, cap = 1 << 20;
    if (fscanf(f, "%ld", &n) != 1) return 2;
    long *U = malloc(cap * 8), *W = malloc(cap * 8); long a, b;
    while (fscanf(f, "%ld %ld", &a, &b) == 2) { if (m == cap) { cap *= 2; U = realloc(U, cap * 8); W = realloc(W, cap * 8); } U[m] = a; W[m] = b; m++; }
    fclose(f);
    long *deg = calloc(n + 1, 8);
    for (long i = 0; i < m; i++) { if (U[i] == W[i] || U[i] < 0 || W[i] < 0 || U[i] >= n || W[i] >= n) { printf("BAD edge %ld\n", i); return 1; } deg[U[i]]++; deg[W[i]]++; }
    st = calloc(n + 1, 8); for (long i = 0; i < n; i++) st[i + 1] = st[i] + deg[i];
    adj = malloc(2 * m * 8); long *pos = calloc(n, 8);
    for (long i = 0; i < m; i++) { adj[st[U[i]] + pos[U[i]]++] = W[i]; adj[st[W[i]] + pos[W[i]]++] = U[i]; }
    long maxd = 0, mind = n;
    for (long x = 0; x < n; x++) { qsort(adj + st[x], st[x + 1] - st[x], 8, cmpl); long k = deg[x]; if (k > maxd) maxd = k; if (k < mind) mind = k;
        for (long i = st[x]; i + 1 < st[x + 1]; i++) if (adj[i] == adj[i + 1]) { printf("RESULT INVALID repeated edge at %ld\n", x); return 1; } }
    int *col = malloc(n * sizeof(int)); for (long i = 0; i < n; i++) col[i] = -1;
    long *qq = malloc(n * 8); long h = 0, t = 0; col[0] = 0; qq[t++] = 0; int bip = 1;
    while (h < t) { long x = qq[h++]; for (long i = st[x]; i < st[x + 1]; i++) { long y = adj[i]; if (col[y] < 0) { col[y] = 1 - col[x]; qq[t++] = y; } else if (col[y] == col[x]) bip = 0; } }
    if (t != n) { printf("RESULT INVALID disconnected (%ld of %ld)\n", t, n); return 1; }
    /* generators */
    FILE *g = fopen(v[2], "rb"); int32_t hd[2]; if (fread(hd, 4, 2, g) != 2 || hd[1] != n) { printf("BAD generator file\n"); return 1; }
    uf = malloc(n * 8); for (long x = 0; x < n; x++) uf[x] = x;
    int32_t *p = malloc(n * 4); char *seen = malloc(n);
    for (int gi = 0; gi < hd[0]; gi++) {
        if ((long)fread(p, 4, n, g) != n) { printf("BAD generator file\n"); return 1; }
        memset(seen, 0, n); for (long x = 0; x < n; x++) { if (p[x] < 0 || p[x] >= n || seen[p[x]]) { printf("generator %d is not a bijection\n", gi); return 1; } seen[p[x]] = 1; }
        for (long x = 0; x < n; x++) for (long i = st[x]; i < st[x + 1]; i++) if (!has_edge(p[x], p[adj[i]])) { printf("generator %d is not an automorphism (edge %ld-%ld)\n", gi, x, adj[i]); return 1; }
        for (long x = 0; x < n; x++) { long r1 = find(x), r2 = find(p[x]); if (r1 != r2) uf[r1 < r2 ? r2 : r1] = r1 < r2 ? r1 : r2; }
        printf("generator %d: automorphism (checked on all %ld edges)\n", gi, m);
    }
    fclose(g);
    src = malloc(n * 8); nsrc = 0; for (long x = 0; x < n; x++) if (find(x) == x) src[nsrc++] = x;
    printf("orbits: %ld (BFS sources)\n", nsrc); fflush(stdout);
    pthread_t *th = malloc(T * sizeof(pthread_t));
    for (int i = 0; i < T; i++) pthread_create(&th[i], NULL, work, NULL);
    for (int i = 0; i < T; i++) pthread_join(th[i], NULL);
    if (bad) { printf("RESULT INVALID unreached\n"); return 1; }
    printf("n=%ld edges=%ld degree min=%ld max=%ld bipartite=%s diameter=%d\n", n, m, mind, maxd, bip ? "yes" : "no", diam);
    printf("witness: d(%ld, %ld) = %d\n", wit_s, wit_t, diam);
    if (bip && maxd <= d && diam <= D) printf("RESULT VALID d=%d D=%d n=%ld\n", d, D, n); else printf("RESULT INVALID\n");
    return 0;
}
