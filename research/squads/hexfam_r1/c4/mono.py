def perm_matrix(p):
    M = np.zeros((7, 7), dtype=np.int64)
    for i, j in enumerate(p): M[j, i] = 1      # e_i -> e_{p(i)}
    return M
def sign_matrix(signs):
    return np.diag(np.array(signs, dtype=np.int64))
def cyc(*cycle):
    p = list(range(7))
    for a, b in zip(cycle, cycle[1:] + cycle[:1]): p[a] = b
    return tuple(p)
def closure_perms(gens):
    """all permutations generated by gens (tuples of length 7)"""
    seen = {tuple(range(7))}; frontier = [tuple(range(7))]
    while frontier:
        new = []
        for x in frontier:
            for g in gens:
                y = tuple(g[x[i]] for i in range(7))
                if y not in seen: seen.add(y); new.append(y)
        frontier = new
    return seen
FANO = [{0,1,3},{1,2,4},{2,3,5},{3,4,6},{4,5,0},{5,6,1},{6,0,2}]
def fano_aut():
    auts = []
    for p in itertools.permutations(range(7)):
        if all(frozenset(p[x] for x in L) in set(frozenset(l) for l in FANO) for L in FANO): auts.append(p)
    return auts
def fano_gens():
    auts = fano_aut(); gens = []
    for a in auts:
        if len(closure_perms(gens)) == 168: break
        if a not in closure_perms(gens): gens.append(a)
    assert len(closure_perms(gens)) == 168, len(closure_perms(gens))
    return gens

ALLS = [1]*7
def signs_gens(even=False):
    if not even: return [sign_matrix([-1 if k == i else 1 for k in range(7)]) for i in range(7)]
    return [sign_matrix([-1 if k in (i, i + 1) else 1 for k in range(7)]) for i in range(6)]
T7 = (1, 0, 2, 3, 4, 5, 6)   # transposition (0 1)
C7 = cyc(0, 1, 2, 3, 4, 5, 6)
def mono_gens(name):
    """returns (Gram diag list, abstract generator matrices)"""
    I = [1] * 7
    perms = {
        'B7': [T7, C7], 'B7_7:3': [tuple((2 * i) % 7 for i in range(7)), C7],
        'B7_L3': None, 'B7_A7': None, 'D7': [T7, C7], 'B7_S6': [T7, cyc(0,1,2,3,4,5)],
        'B7_S5': [cyc(0,1,2,3,4), cyc(0,1)] ,
        'B7_S3S4': [cyc(0,1,2), cyc(0,1), cyc(3,4,5,6), cyc(3,4)],
        'B7_7': [C7], 'B7_(S4xS3)': [cyc(0,1,2,3), cyc(0,1), cyc(4,5,6), cyc(4,5)],
    }
    if name == 'B7_L3': gens_p = fano_gens()
    elif name == 'B7_A7': gens_p = [cyc(0,1,2), C7 if False else cyc(0,1,2,3,4,5,6)]  # placeholder replaced below
    if name == 'B7_L3':
        mats = [perm_matrix(p) for p in gens_p] + signs_gens(False); return I, mats
    if name == 'B7_A7':
        mats = [perm_matrix(cyc(0,1,2))] + [perm_matrix(cyc(0,1,2,3,4,5,6))] + signs_gens(False); return I, mats
    if name == 'B7_7:3':
        mats = [perm_matrix(p) for p in perms[name]] + signs_gens(False); return I, mats
    if name in ('B7', 'B7_S6', 'B7_S5', 'B7_S3S4', 'B7_7', 'B7_(S4xS3)'):
        mats = [perm_matrix(p) for p in perms[name]] + signs_gens(False)
        if name == 'B7_7': mats = [perm_matrix(C7)] + signs_gens(False)
        return I, mats
    if name == 'D7':
        mats = [perm_matrix(p) for p in perms[name]] + signs_gens(True); return I, mats
    if name == 'D7A7':  # even signs, A7 perms
        mats = [perm_matrix(cyc(0,1,2)), perm_matrix(C7)] + signs_gens(True); return I, mats
    if name == 'B7_only_signs':
        return I, signs_gens(False)
    if name == 'B7_sign_even':
        return I, signs_gens(True)
    if name.startswith('form'):  # form_a=(a0..a6)  permutations within equal-a classes
        raise ValueError
    raise ValueError(name)

def form_gens(avals):
    """signed permutations preserving sum a_i x_i^2: all sign changes + permutations within equal-a classes (transposition and cycles)."""
    mats = signs_gens(False)
    classes = {}
    for i, a in enumerate(avals): classes.setdefault(a, []).append(i)
    for cl in classes.values():
        if len(cl) >= 2:
            p = list(range(7))
            p[cl[0]], p[cl[1]] = p[cl[1]], p[cl[0]]
            mats.append(perm_matrix(tuple(p)))
            if len(cl) >= 3:
                p = list(range(7))
                for k, c in enumerate(cl): p[c] = cl[(k + 1) % len(cl)]
                mats.append(perm_matrix(tuple(p)))
    return mats

