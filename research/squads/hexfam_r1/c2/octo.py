"""Idea B: subgroups of the monomial group Gamma = 2^3:L3(2) (order 1344) acting on Q(6,q).
usage: python3 octo.py q [npairs]"""
import sys, random, pickle, time, numpy as np
sys.path.insert(0,'/home/user/degree-diameter/research/squads/hexfam_r1/c2')
from common import *
from mwc import max_weight_clique
q = int(sys.argv[1]); npairs = int(sys.argv[2]) if len(sys.argv) > 2 else 400
OUT = '/home/user/degree-diameter/research/squads/hexfam_r1/c2/'
t0 = time.time()
mons = monomial_phi_group()
G, conj = setup(q, mons)
key = lambda M: M.tobytes()
idx = {key(M): i for i, M in enumerate(mons)}
permcache = {}
def perm_of(i):
    if i not in permcache:
        permcache[i] = G.perm(conj(mons[i]))
    return permcache[i]
rng = random.Random(7)
# enumerate subgroups generated by pairs of elements (and cyclic ones)
def closure_idx(gi):
    gens = [mons[i] for i in gi]
    cl = closure(gens)
    return frozenset(idx[key(M)] for M in cl)
subs = {}
for i in range(len(mons)):
    S = closure_idx([i])
    subs.setdefault(S, [i])
for _ in range(npairs):
    a, b = rng.randrange(len(mons)), rng.randrange(len(mons))
    S = closure_idx([a, b])
    if S not in subs: subs[S] = [a, b]
print('distinct subgroups', len(subs), 'orders', sorted(set(len(S) for S in subs)), time.time()-t0, flush=True)
# candidate point-sets from orbits of each subgroup (dedupe)
cand = {}
nsub = 0
for S, gens in subs.items():
    if len(S) == 1: continue
    gi = gens
    # ensure gens generate S
    if len(closure_idx(gi)) != len(S): continue
    perms = [perm_of(i) for i in gi]
    lab = orbits(G.N, perms)
    cs = candidate_orbits(G, lab)
    for pts in cs:
        k = tuple(sorted(int(x) for x in pts))
        if k not in cand: cand[k] = len(S)
    nsub += 1
print('subgroups processed', nsub, 'distinct candidate orbits', len(cand), time.time()-t0, flush=True)
groups = [np.array(k) for k in cand.keys()]
# dedupe nested? keep all
w, adj = compat_graph(G, groups)
print('compat built', time.time()-t0, flush=True)
# greedy + exact
best = (0, [])
ok, val, verts = None, None, None
tl = 120.0
res_w, res_v, exact = max_weight_clique(w, adj, tlimit=tl)
print('MWC weight', res_w, 'exact', exact, 'num groups in clique', len(res_v), time.time()-t0, flush=True)
pts = np.concatenate([groups[v] for v in res_v]) if res_v else np.array([], dtype=np.int64)
ok, ext = G.check_opp(pts) if len(pts) else (True, 0)
print('check_opp', ok, 'ext', ext, 'size', len(pts), flush=True)
write_set(OUT + 'octo_q%d_%d.txt' % (q, len(pts)), pts)
np.save(OUT + 'octo_q%d_groups.npy' % q, np.array(groups, dtype=object), allow_pickle=True)
