def monomial_phi_group():
    """signed permutation matrices preserving the 3-form phi of the Fano plane (octonion imaginary part).
    Returns list of 7x7 int matrices (orthogonal wrt identity)."""
    lines = [(0,1,2),(0,3,4),(0,6,5),(1,3,5),(1,4,6),(2,3,6),(2,5,4)]
    phi = np.zeros((7,7,7), dtype=np.int64)
    for (i,j,k) in lines:
        for (a,b,c), s in [((i,j,k),1),((j,k,i),1),((k,i,j),1),((j,i,k),-1),((i,k,j),-1),((k,j,i),-1)]:
            phi[a,b,c] = s
    out = []
    for sig in itertools.permutations(range(7)):
        sig = list(sig)
        for eps in itertools.product([1,-1], repeat=7):
            ok = True
            # condition: phi[sig i, sig j, sig k] * eps_i eps_j eps_k == phi[i,j,k]
            for (i,j,k) in itertools.combinations(range(7),3):
                if phi[sig[i],sig[j],sig[k]] * eps[i]*eps[j]*eps[k] != phi[i,j,k]:
                    ok = False; break
            if ok:
                M = np.zeros((7,7), dtype=np.int64)
                for i in range(7): M[sig[i], i] = eps[i]   # column i = image of e_i
                out.append(M)
    return out

def closure(gens, cap=10**6):
    """all matrices of the group generated by gens (mod nothing: integer matrices, use mod q at call site)"""
    I = np.eye(7, dtype=np.int64)
    seen = {I.tobytes(): I}; frontier = [I]
    while frontier:
        nf = []
        for X in frontier:
            for g in gens:
                Y = X @ g
                key = Y.tobytes()
                if key not in seen:
                    seen[key] = Y; nf.append(Y)
                    if len(seen) > cap: return None
        frontier = nf
    return list(seen.values())

def setup(q, mats_std):
    """mats_std: group matrices in abstract coords (orthogonal wrt identity). Returns (G, perms-maker)."""
    from q6lib import Geo
    G = Geo(q)
    T = G.to_std(np.eye(7, dtype=np.int64))
    Ti = inv_mod(T, q)
    def conj(g): return (T @ (g % q) @ Ti) % q
    return G, conj

