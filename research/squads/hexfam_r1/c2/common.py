def candidate_orbits(G, lab):
    """orbits that are pairwise opposite (partial ovoids). returns list of point-id arrays"""
    cnt = np.bincount(lab)
    cands = []
    order = np.argsort(lab, kind='stable')
    starts = np.concatenate([[0], np.cumsum(cnt)])
    for o in range(len(cnt)):
        pts = order[starts[o]:starts[o+1]]
        if len(pts) > 1332: continue
        Bm = G.B(G.C[pts], G.C[pts]) != 0
        np.fill_diagonal(Bm, True)
        if Bm.all(): cands.append(pts)
    return cands

def compat_graph(G, groups):
    """groups: list of point-id arrays (each pairwise opposite). Returns weights and adjacency bitsets."""
    allp = np.concatenate(groups)
    lab = np.concatenate([[i]*len(g) for i, g in enumerate(groups)])
    O = G.B(G.C[allp], G.C[allp]) != 0
    m = len(groups)
    bad = np.zeros((m, m), dtype=bool)
    # incompatibility: any non-opposite pair across groups
    Z = ~O
    # accumulate: for each pair of groups, Z-submatrix any
    import numpy as _np
    starts = _np.concatenate([[0], _np.cumsum([len(g) for g in groups])])
    for a in range(m):
        ra = Z[starts[a]:starts[a+1]]
        colany = ra.any(axis=0)
        # group index of columns with colany
        idx = _np.nonzero(colany)[0]
        if len(idx):
            gl = lab[idx]
            bad[a, _np.unique(gl)] = True
    bad = bad | bad.T
    np.fill_diagonal(bad, True)
    adj = [0]*m
    for a in range(m):
        bits = 0
        for b in range(m):
            if not bad[a, b]: bits |= (1 << b)
        adj[a] = bits
    w = [len(g) for g in groups]
    return w, adj

