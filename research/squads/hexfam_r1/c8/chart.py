"""c8 wildcard: affine chart of H(q) opposite e4 (q prime).
Points opposite e4: x=(1,a,b,c,c^2-ae-bf,e,f); B(x,x') = Q(x-x'), Q(d)=d_c^2-d_a d_e-d_b d_f.
Sets A in GF(q)^5 with Q(a-a') != 0 for all pairs; full partial ovoid = {e4} U {chart points of A}.
Symmetry: affine similitudes x -> M x + t with Q(Mv)=mu Q(v). Orbits of cyclic groups; orbit-level clique."""
import numpy as np


class Chart:
    def __init__(self, q):
        self.q = q
        self.N5 = q ** 5
        idx = np.arange(self.N5, dtype=np.int64)
        P = np.zeros((self.N5, 5), dtype=np.int64)
        for k in range(5):
            P[:, 4 - k] = idx % q
            idx //= q
        self.P = P  # columns a,b,c,e,f
        self._iso = None

    def Q(self, V):
        q = self.q
        return (V[..., 2] * V[..., 2] - V[..., 0] * V[..., 3] - V[..., 1] * V[..., 4]) % q

    def Bp(self, u, v):
        # Q(u+v)-Q(u)-Q(v)
        return (2 * u[..., 2] * v[..., 2] - (u[..., 0] * v[..., 3] + v[..., 0] * u[..., 3])
                - (u[..., 1] * v[..., 4] + v[..., 1] * u[..., 4])) % self.q

    def iso_vectors(self):
        if self._iso is None:
            self._iso = self.P[self.Q(self.P) == 0]
        return self._iso

    def encode(self, V):
        q = self.q
        return ((((V[..., 0] * q + V[..., 1]) * q + V[..., 2]) * q + V[..., 3]) * q + V[..., 4])

    def apply(self, M, t, V):
        return (V @ np.asarray(M, dtype=np.int64).T + np.asarray(t, dtype=np.int64)) % self.q

    def reflect_matrix(self, w):
        q = self.q
        inv = pow(int(self.Q(w)), q - 2, q)
        cols = []
        for j in range(5):
            e = np.zeros(5, dtype=np.int64)
            e[j] = 1
            c = (self.Bp(e, w) * inv) % q
            cols.append((e - c * w) % q)
        return np.array(cols).T % q

    def random_orthogonal(self, rng, nref=6):
        q = self.q
        M = np.eye(5, dtype=np.int64)
        for _ in range(nref):
            while True:
                w = np.array([rng.randrange(q) for _ in range(5)], dtype=np.int64)
                if int(self.Q(w)) % q:
                    break
            M = (self.reflect_matrix(w) @ M) % q
        return M


def matpow_order(M, q, maxo=10000):
    I = np.eye(M.shape[0], dtype=np.int64)
    X = M.copy() % q
    k = 1
    while not (X == I).all():
        X = (X @ M) % q
        k += 1
        if k > maxo:
            return None
    return k


def cyc_orbits(ch, M, t, maxo=400):
    """orbits of cyclic group generated by g(x)=Mx+t (cycles of the permutation); orbit sizes; validity.
    Orbit valid iff Q(g^j x - x) != 0 for 1 <= j < orbit size (then all internal pairs are non-isotropic)."""
    q = ch.q
    N5 = ch.N5
    perm_l = ch.encode(ch.apply(M, t, ch.P)).tolist()
    lab = [-1] * N5
    sizes = []
    k = 0
    for s in range(N5):
        if lab[s] >= 0:
            continue
        x = s
        n = 0
        while lab[x] < 0:
            lab[x] = k
            n += 1
            x = perm_l[x]
        sizes.append(n)
        k += 1
    label = np.array(lab, dtype=np.int64)
    size = np.array(sizes, dtype=np.int64)
    psz = size[label]
    Y = ch.P.copy()
    bad = np.zeros(N5, dtype=bool)
    maxs = int(size.max())
    for j in range(1, min(maxs, maxo) + 1):
        Y = ch.apply(M, t, Y)
        bad |= (j < psz) & (ch.Q((Y - ch.P) % q) == 0)
    orb_valid = np.ones(k, dtype=bool)
    np.logical_and.at(orb_valid, label, ~bad)
    return label, size, orb_valid


def orbit_graph(ch, label, size, orb_valid):
    """compat adjacency among valid orbits. Orbits O1 (rep x) and O2 compatible iff Q(x-y)!=0 for all y in O2.
    Bad points for rep x are x + Iso, Iso = {d : Q(d)=0}."""
    q = ch.q
    vids = np.nonzero(orb_valid)[0]
    m = len(vids)
    pos = -np.ones(len(size), dtype=np.int64)
    pos[vids] = np.arange(m)
    order = np.argsort(label, kind='stable')
    starts = np.concatenate([[0], np.cumsum(size)[:-1]])
    rep = order[starts]
    iso = ch.iso_vectors()
    A = np.ones((m, m), dtype=bool)
    lab_valid = pos[label]
    CH = max(1, 300000 // len(iso))
    for c0 in range(0, m, CH):
        ii = np.arange(c0, min(m, c0 + CH))
        X = ch.P[rep[vids[ii]]]
        Y = (X[:, None, :] + iso[None, :, :]) % q
        L = lab_valid[ch.encode(Y)]
        r, cc = np.nonzero(L >= 0)
        A[ii[r], L[r, cc]] = False
    np.fill_diagonal(A, False)
    A = A & A.T
    return vids, A


def greedy_clique(w, A, rng, restarts=50):
    m = len(w)
    best = (0, None)
    for r in range(restarts):
        cand = np.ones(m, dtype=bool)
        cl = []
        tot = 0
        while cand.any():
            ids = np.nonzero(cand)[0]
            sc = w[ids] + rng.random(len(ids)) * (w[ids].max() * 0.5)
            v = ids[np.argmax(sc)]
            cl.append(v)
            tot += w[v]
            cand &= A[v]
            cand[v] = False
        if tot > best[0]:
            best = (tot, cl)
    return best
