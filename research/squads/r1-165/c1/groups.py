def selftest():
    # 1) the pipeline reproduces the known cost-0 controller of Z_7 x| Z_6 (m = 42)
    T = P('meta 7 6 2')
    assert axioms_ok(T) is None
    bc, ns, bS, sol = run_exh(T, 'selftest_meta762')
    print('selftest meta 7 6 2 (expect best_cost=0):', bc, ns, sol, flush=True)
    assert bc == 0
    # 2) classification on known groups
    checks = {'D8': (D8, False), 'Q8': (Q8, False), 'A4': (A4, True), 'C2^3': (prod(C2, C2, C2), True),
              'SL(2,3)': (SL23, True), 'C3xS3': (prod(C3, S3), False), 'S4': (S4, True),
              'Z3^2:C8=AGL(1,9)': (None, True)}
    for name, (T, want_nonmeta) in checks.items():
        if T is None:
            continue
        assert axioms_ok(T) is None, name
        got = classify(T)['meta']
        print(f'  classify {name:18s} metacyclic={got} (expected non-metacyclic={want_nonmeta})', flush=True)
        assert got == (not want_nonmeta), name
    print('selftest OK', flush=True)


