# ---------------------------------------------------------------- group-level tools
def elt_order(T, e, g):
    k, x = 1, g
    while x != e:
        x = int(T[x, g]); k += 1
    return k


def identity(T):
    m = len(T)
    return [i for i in range(m) if np.array_equal(T[i], np.arange(m))][0]


def axioms_ok(T):
    m = len(T); ar = np.arange(m)
    if not (np.sort(T, axis=1) == ar).all() or not (np.sort(T, axis=0) == ar[:, None]).all():
        return 'not a Latin square'
    ids = [i for i in range(m) if np.array_equal(T[i], ar) and np.array_equal(T[:, i], ar)]
    if len(ids) != 1:
        return 'identity'
    for i in range(m):                      # full associativity: T[T[i,j],k] == T[i,T[j,k]] for all j,k
        if not np.array_equal(T[T[i]], T[i][T]):
            return 'associativity'
    return None


def classify(T):
    """Signature for dedupe, and metacyclic flag (exists normal cyclic N with G/N cyclic)."""
    m = len(T)
    e = identity(T)
    inv = np.array([int(np.nonzero(T[i] == e)[0][0]) for i in range(m)])
    cyc = []
    for g in range(m):
        seq, x = [e], g
        while x != e:
            seq.append(x); x = int(T[x, g])
        cyc.append(np.array(sorted(seq)))
    orders = [len(c) for c in cyc]
    cent = [int(np.sum(T[g] == T[:, g])) for g in range(m)]
    sq = [int(np.sum(np.diag(T) == g)) for g in range(m)]
    sig = tuple(sorted(zip(orders, cent, sq)))
    subs = {}
    for g in range(m):
        subs.setdefault(tuple(cyc[g].tolist()), g)
    meta = False
    for key in subs:
        N = np.array(key)
        conj = T[T[:, N], inv[:, None]]          # entry [g,k] = g n_k g^-1
        if not np.isin(conj, N).all():
            continue
        for h in range(m):
            if len(np.unique(T[np.ix_(cyc[h], N)])) == m:   # <h>N = G
                meta = True
                break
        if meta:
            break
    return dict(sig=sig, meta=meta)


def run_exh(T, name):
    m = len(T)
    fn = f'{TBL}/{name}.txt'
    with open(fn, 'w') as f:
        f.write(f'{m}\n' + ' '.join(map(str, T.flatten().tolist())) + '\n')
    out = subprocess.run(['nice', '-n', '10', EXH, fn, '1'], capture_output=True, text=True,
                         timeout=900).stdout.strip().splitlines()
    last = out[-1]
    bc = int(last.split('best_cost=')[1].split()[0])
    ns = int(last.split('solutions=')[1].split()[0])
    bestS = last.split('bestS=')[1].strip()
    sol = out[0] if ns > 0 else ''
    return bc, ns, bestS, sol


class Run:
    def __init__(self):
        self.seen = set(); self.rows = []; self.k = 0
        self.stats = dict(generated=0, axiom_fail=0, metacyclic=0, dup=0, tested=0)

    def add(self, label, T):
        if T is None:
            return
        self.stats['generated'] += 1
        err = axioms_ok(T)
        if err:
            self.stats['axiom_fail'] += 1
            print(f'AXIOM FAIL {label}: {err}', flush=True)
            return
        info = classify(T)
        if info['meta']:
            self.stats['metacyclic'] += 1
            return
        if info['sig'] in self.seen:
            self.stats['dup'] += 1
            return
        self.seen.add(info['sig'])
        self.k += 1; self.stats['tested'] += 1
        name = f'm{len(T)}_{self.k:03d}'
        bc, ns, bS, sol = run_exh(T, name)
        self.rows.append((label, len(T), bc, ns, bS, sol, name))
        print(f'{label:34s} m={len(T)} best_cost={bc:3d} solutions={ns:4d} bestS={bS}', flush=True)


# ---------------------------------------------------------------- semidirect products A x| X
_GL, _POOL = {}, {}


def gl_elems(d, n):
    if (d, n) not in _GL:
        out = []
        for ent in itertools.product(range(n), repeat=d * d):
            M = np.array(ent, dtype=np.int64).reshape(d, d)
            det = int(round(np.linalg.det(M))) % n
            if math.gcd(det, n) == 1:
                out.append(M)
        _GL[(d, n)] = out
    return _GL[(d, n)]


def gl_pool(d, n, k):
    """Invertible d x d matrices mod n with M^k = I."""
    if (d, n, k) not in _POOL:
        I = np.eye(d, dtype=np.int64)
        res = []
        for M in gl_elems(d, n):
            Q = I.copy()
            for _ in range(k):
                Q = (Q @ M) % n
            if np.array_equal(Q, I):
                res.append(M)
        _POOL[(d, n, k)] = res
    return _POOL[(d, n, k)]


def closure_set(T, gens, e):
    H = {e}; q = [e]; k = 0
    while k < len(q):
        x = q[k]; k += 1
        for g in gens:
            y = int(T[x, g])
            if y not in H:
                H.add(y); q.append(y)
    return H


def find_gens(T, e):
    m = len(T); gens = []; H = {e}
    while len(H) < m:
        g = RNG.choice([x for x in range(m) if x not in H])
        gens.append(g); H = closure_set(T, gens, e)
    return gens


def try_hom(X, e, gens, imgs, d, n):
    phi = {e: np.eye(d, dtype=np.int64)}
    q = [e]; k = 0
    while k < len(q):
        x = q[k]; k += 1
        for g, Mg in zip(gens, imgs):
            y = int(X[x, g]); val = (phi[x] @ Mg) % n
            if y in phi:
                if not np.array_equal(phi[y], val):
                    return None
            else:
                phi[y] = val; q.append(y)
    return [phi[x] for x in range(len(X))]


def build_semi(d, n, X, phis):
    """(v,x)(w,y) = (v + phi(x) w, x y) on Z_n^d x X; element index v*|X| + x."""
    vecs = list(itertools.product(range(n), repeat=d))
    vidx = {v: i for i, v in enumerate(vecs)}
    V = np.array(vecs, dtype=np.int64).reshape(len(vecs), d)
    nA, mX = len(vecs), len(X)
    addA = np.empty((nA, nA), dtype=np.int64)
    for i in range(nA):
        S = (V[i][None, :] + V) % n
        addA[i] = [vidx[tuple(int(c) for c in s)] for s in S]
    act = np.empty((mX, nA), dtype=np.int64)
    for x in range(mX):
        W = (V @ phis[x].T) % n
        act[x] = [vidx[tuple(int(c) for c in w)] for w in W]
    m = nA * mX
    T = np.empty((m, m), dtype=np.int32)
    for v in range(nA):
        for x in range(mX):
            T[v * mX + x] = (addA[v][act[x]][:, None] * mX + X[x][None, :]).reshape(-1)
    return T


def semi(run, label, d, n, Xname, X, trials=300, want=40):
    e = identity(X)
    gens = find_gens(X, e)
    ords = [elt_order(X, e, g) for g in gens]
    pools = [gl_pool(d, n, o) for o in ords]
    if any(len(p) == 0 for p in pools):
        return
    made = 0
    for _ in range(trials):
        imgs = [RNG.choice(p) for p in pools]
        phis = try_hom(X, e, gens, imgs, d, n)
        if phis is None:
            continue
        run.add(f'{label}:{Xname}', build_semi(d, n, X, phis))
        made += 1
        if made >= want:
            break


