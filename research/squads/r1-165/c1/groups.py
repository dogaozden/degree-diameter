def P(spec):
    return ct.parse(spec)


def prod(*Ts):
    T = Ts[0]
    for U in Ts[1:]:
        T = ct.product(T, U)
    return T


def twisted(a, b, r, t=0):
    """Z_a . Z_b with a^x b^e: b a b^-1 = a^r, b^b = a^t (t central).  Split iff t = 0."""
    assert pow(r, b, a) == 1 % a and (r * t - t) % a == 0, (a, b, r, t)
    m = a * b
    T = np.empty((m, m), dtype=np.int32)
    for e in range(b):
        for x in range(a):
            i = e * a + x
            for f in range(b):
                s = e + f
                for y in range(a):
                    T[i, f * a + y] = (s % b) * a + (x + pow(r, e, a) * y + (t if s >= b else 0)) % a
    return T


def closure(gens, mul, ident, limit=130):
    """Multiplication table and element list of the group generated by gens (right-multiplication BFS)."""
    els, idx = [ident], {ident: 0}
    k = 0
    while k < len(els):
        x = els[k]; k += 1
        for g in gens:
            y = mul(x, g)
            if y not in idx:
                if len(els) >= limit:
                    return None, None
                idx[y] = len(els); els.append(y)
    m = len(els)
    T = np.empty((m, m), dtype=np.int32)
    for i, x in enumerate(els):
        for j, y in enumerate(els):
            T[i, j] = idx[mul(x, y)]
    return T, els


def mat_group(gens, n, limit=130):
    d = len(gens[0])
    def mul(x, y):
        A = np.array(x, dtype=np.int64).reshape(d, d); B = np.array(y, dtype=np.int64).reshape(d, d)
        return tuple(int(v) for v in ((A @ B) % n).flatten())
    gg = [tuple(int(v) % n for row in g for v in row) for g in gens]
    ident = tuple(int(v) for v in np.eye(d, dtype=np.int64).flatten())
    return closure(gg, mul, ident, limit)[0]


def perm_group(gens, limit=130):
    n = len(gens[0])
    mul = lambda p, q: tuple(p[k] for k in q)
    return closure([tuple(g) for g in gens], mul, tuple(range(n)), limit)[0]


