# ---------------------------------------------------------------- generic constructions
def table_from(gens, mul, ident):
    """Multiplication table of the group generated by gens (closure by right multiplication). Identity is index 0."""
    els = [ident]; idx = {ident: 0}; k = 0
    while k < len(els):
        g = els[k]; k += 1
        for s in gens:
            h = mul(g, s)
            if h not in idx:
                idx[h] = len(els); els.append(h)
    m = len(els)
    T = np.empty((m, m), dtype=np.int32)
    for i, g in enumerate(els):
        for j, h in enumerate(els):
            T[i, j] = idx[mul(g, h)]
    return T


def perm_mul(p, q):
    return tuple(p[x] for x in q)


def perm_table(gens):
    return table_from([tuple(g) for g in gens], perm_mul, tuple(range(len(gens[0]))))


def mat_table(gens, p):
    n = len(gens[0])
    I = tuple(tuple(int(i == j) for j in range(n)) for i in range(n))

    def mul(A, B):
        return tuple(tuple(sum(A[i][k] * B[k][j] for k in range(n)) % p for j in range(n)) for i in range(n))
    return table_from([tuple(map(tuple, g)) for g in gens], mul, I)


def affine(p, k, lin):
    """F_p^k x| <lin> as affine maps x -> A x (+ translations), acting on p^k points (faithful)."""
    pts = list(itertools.product(range(p), repeat=k))
    index = {v: i for i, v in enumerate(pts)}

    def amap(A, b):
        return tuple(index[tuple((sum(A[i][j] * v[j] for j in range(k)) + b[i]) % p for i in range(k))] for v in pts)
    I = [[int(i == j) for j in range(k)] for i in range(k)]
    gens = [amap(I, [int(t == i) for t in range(k)]) for i in range(k)]
    gens += [amap(A, [0] * k) for A in lin]
    return perm_table(gens)


def cyc(n):
    T = np.empty((n, n), dtype=np.int32)
    for i in range(n):
        T[i] = (i + np.arange(n)) % n
    return T


def dihedral(n):
    """D_n of order 2n (n >= 2)."""
    if n == 2:
        return ct.meta(2, 2, 1)
    return ct.meta(n, 2, n - 1)


def dicyc(n):
    """Dicyclic group Dic_n = Q_{4n} (order 4n), non-split metacyclic for n even, split for n odd."""
    m = 4 * n; T = np.empty((m, m), dtype=np.int32)
    for x1 in range(2 * n):
        for s1 in range(2):
            for x2 in range(2 * n):
                for s2 in range(2):
                    sign = 1 if s1 == 0 else -1
                    x = (x1 + sign * x2 + n * s1 * s2) % (2 * n)
                    T[2 * x1 + s1, 2 * x2 + s2] = 2 * x + (s1 + s2) % 2
    return T


def dprod(T1, T2):
    n1, n2 = len(T1), len(T2); m = n1 * n2
    T = np.empty((m, m), dtype=np.int32)
    ar = np.arange(m)
    for a1 in range(n1):
        for b1 in range(n2):
            T[a1 * n2 + b1] = T1[a1][ar // n2] * n2 + T2[b1][ar % n2]
    return T


def prod(*Ts):
    T = Ts[0]
    for U in Ts[1:]:
        T = dprod(T, U)
    return T


def pauli():
    """Pauli group <X, Z, iI> (order 16), exact Gaussian-integer 2x2 matrices."""
    def mul(A, B):
        out = []
        for i in range(2):
            for j in range(2):
                re = im = 0
                for k in range(2):
                    a, b = A[2 * i + k]; c, d = B[2 * k + j]
                    re += a * c - b * d; im += a * d + b * c
                out.append((re, im))
        return tuple(out)
    X = ((0, 0), (1, 0), (1, 0), (0, 0)); Z = ((1, 0), (0, 0), (0, 0), (-1, 0)); I = ((0, 1), (0, 0), (0, 0), (0, 1))
    one = ((1, 0), (0, 0), (0, 0), (1, 0))
    return table_from([X, Z, I], mul, one)


def binary_octahedral():
    """2O (order 48) as a subgroup of SL(2,7): unique involution and 8 elements of order 3."""
    p = 7
    def mul(A, B):
        a, b, c, d = A; e, f, g, h = B
        return ((a * e + b * g) % p, (a * f + b * h) % p, (c * e + d * g) % p, (c * f + d * h) % p)
    I = (1, 0, 0, 1)
    els = [(a, b, c, d) for a in range(p) for b in range(p) for c in range(p) for d in range(p)
           if (a * d - b * c) % p == 1]
    def order(x):
        k, y = 1, x
        while y != I:
            y = mul(y, x); k += 1
        return k
    for _ in range(4000):
        A, B = RNG.sample(els, 2)
        S = {I}; q = [I]; ok = True
        for x in q:
            for g in (A, B):
                y = mul(x, g)
                if y not in S:
                    S.add(y); q.append(y)
                    if len(S) > 48:
                        ok = False; break
            if not ok:
                break
        if not ok or len(S) != 48:
            continue
        ords = [order(x) for x in S]
        if ords.count(2) == 1 and ords.count(3) == 8:
            return table_from([A, B], mul, I)
    raise RuntimeError('no 2O found')


def semidirect(TN, TH, phis):
    """N x| H; phis[h] is the automorphism of N (index array) for h in H. (n1,h1)(n2,h2) = (n1 phi_h1(n2), h1 h2)."""
    nN, nH = len(TN), len(TH)
    T = np.empty((nN * nH, nN * nH), dtype=np.int32)
    ar = np.arange(nN)
    for n1 in range(nN):
        for h1 in range(nH):
            i = n1 * nH + h1
            pn = TN[n1][np.asarray(phis[h1], dtype=np.int64)]
            for h2 in range(nH):
                T[i, ar * nH + h2] = pn * nH + TH[h1][h2]
    return T


# ---------------------------------------------------------------- group-theory helpers
def ident_of(T):
    ar = np.arange(len(T))
    for i in range(len(T)):
        if np.array_equal(T[i], ar):
            return i
    raise ValueError('no identity')


def check_group(T):
    m = len(T); ar = np.arange(m); e = ident_of(T)
    assert all((T[x] == e).any() for x in range(m)), 'inverse missing'
    L = T[T[:, :, None], ar[None, None, :]]      # (a,b,c) -> T[T[a,b], c]
    R = T[ar[:, None, None], T[None, :, :]]      # (a,b,c) -> T[a, T[b,c]]
    assert np.array_equal(L, R), 'not associative'


def bfs_hom(TH, e, gens, imgs, mul_t, ident_t):
    """Extend generator images to a homomorphism from H (table TH) into a target with product mul_t, or None."""
    m = len(TH)
    val = [None] * m
    val[e] = ident_t
    q = [e]
    for x in q:
        vx = val[x]
        for g, im in zip(gens, imgs):
            y = int(TH[x, g]); c = mul_t(vx, im)
            if val[y] is None:
                val[y] = c; q.append(y)
            elif val[y] != c:
                return None
    if len(q) != m:
        return None
    return val


def minimal_gens(T, e):
    m = len(T); gens = []; H = {e}
    while len(H) < m:
        best = None
        for x in range(m):
            if x in H:
                continue
            S = {e}; q = [e]
            for z in q:
                for g in gens + [x]:
                    y = int(T[z, g])
                    if y not in S:
                        S.add(y); q.append(y)
            if best is None or len(S) > len(best[1]):
                best = (x, S)
                if len(S) == m:
                    break
        gens.append(best[0]); H = best[1]
    return gens


def automorphisms(T):
    key = T.tobytes()
    if key in _AUT:
        return _AUT[key]
    m = len(T); e = ident_of(T); gens = minimal_gens(T, e)
    mul = lambda a, b: int(T[a, b])
    out = []
    for imgs in itertools.product(range(m), repeat=len(gens)):
        val = bfs_hom(T, e, gens, imgs, mul, e)
        if val is not None and len(set(val)) == m:
            out.append(tuple(val))
    _AUT[key] = out
    return out


def semidirect_from(TN, TH, Hgens, Himgs):
    comp = lambda a, b: tuple(a[x] for x in b)
    val = bfs_hom(TH, ident_of(TH), Hgens, Himgs, comp, tuple(range(len(TN))))
    if val is None:
        return None
    return semidirect(TN, TH, np.array(val, dtype=np.int64))


def signature(T):
    m = len(T); e = ident_of(T)
    orders = []
    for x in range(m):
        k, y = 1, x
        while y != e:
            y = int(T[y, x]); k += 1
        orders.append(k)
    Z = int(np.sum(np.all(T == T.T, axis=1)))
    return (m, tuple(sorted(orders)), Z)


def family(name, TN, TH, cap=6, tries=400):
    """All (up to cap, deduplicated by signature) semidirect products N x| H, phi given by generator images of H."""
    auts = automorphisms(TN)
    eH = ident_of(TH); Hg = minimal_gens(TH, eH)
    comp = lambda a, b: tuple(a[x] for x in b)
    idN = tuple(range(len(TN)))
    out = []; sigs = set(); seen_phi = set()
    if len(Hg) == 1:
        cands = ((a,) for a in auts)
    else:
        cands = (tuple(RNG.choice(auts) for _ in Hg) for _ in range(tries))
    for imgs in cands:
        val = bfs_hom(TH, eH, Hg, imgs, comp, idN)
        if val is None:
            continue
        key = tuple(val)
        if key in seen_phi:
            continue
        seen_phi.add(key)
        T = semidirect(TN, TH, np.array(val, dtype=np.int64))
        s = signature(T)
        if s in sigs:
            continue
        sigs.add(s); out.append((f"{name}#{len(out)}", T))
        if len(out) >= cap:
            break
    return out


# ---------------------------------------------------------------- metacyclic classification
def powers_list(T, x, e):
    pw = [e]; y = x
    while y != e:
        pw.append(y); y = int(T[y, x])
    return pw


def mc_type(T):
    """'cyclic' | 'split' | 'nonsplit' (metacyclic, not a split Z_a x| Z_b) | 'NM' (non-metacyclic)."""
    m = len(T); e = ident_of(T)
    P = [powers_list(T, x, e) for x in range(m)]
    if any(len(p) == m for p in P):
        return 'cyclic'
    inv = [int(np.nonzero(T[g] == e)[0][0]) for g in range(m)]
    seen = set(); subs = []
    for x in range(m):
        S = frozenset(P[x])
        if len(S) == 1 or S in seen:
            continue
        seen.add(S); subs.append(S)
    meta = False; split = False
    for S in subs:
        n = len(S); q = m // n
        # normal iff conjugates of a generator lie in S (generator = any element with <x> = S)
        gen = next(x for x in S if len(P[x]) == n)
        if not all(int(T[T[g, gen], inv[g]]) in S for g in range(m)):
            continue
        for g in range(m):
            pg = P[g]; L = len(pg); k = None
            for j in range(1, L + 1):
                if pg[j % L] in S:
                    k = j; break
            if k == q:
                meta = True
                if L == q:
                    split = True
        if split:
            break
    if split:
        return 'split'
    if meta:
        return 'nonsplit'
    return 'NM'


