def classify_and_run(G, out_tsv):
    rows = []
    with open(out_tsv, 'w') as f:
        f.write('name\torder\tclass\tbest_cost\tsolutions\tbestS\tfirst_solution\n')
        for name, T in G:
            if T is None:
                row = (name, '', 'BUILD_ERR', '', '', '', ''); rows.append(row)
                f.write('\t'.join(map(str, row)) + '\n'); continue
            m = len(T)
            if not (73 <= m <= 108):
                continue
            try:
                check_group(T)
            except AssertionError as ex:
                row = (name, m, 'BAD_GROUP:' + str(ex), '', '', '', ''); rows.append(row)
                f.write('\t'.join(map(str, row)) + '\n'); continue
            cls = mc_type(T)
            bc, ns, bestS, sols, path = run_ctrl(T, name)
            row = (name, m, cls, bc, ns, bestS, sols[0] if sols else '')
            rows.append(row)
            f.write('\t'.join(map(str, row)) + '\n'); f.flush()
            print(*row, sep='\t', flush=True)
    return rows


