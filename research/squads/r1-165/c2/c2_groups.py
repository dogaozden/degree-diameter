def bd(*Ms):
    n = sum(len(M) for M in Ms)
    out = [[0] * n for _ in range(n)]; off = 0
    for M in Ms:
        k = len(M)
        for i in range(k):
            for j in range(k):
                out[off + i][off + j] = M[i][j]
        off += k
    return out


