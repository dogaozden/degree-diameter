q = 11; CAP = q ** 3 + 1
S756 = np.array(sorted(int(x) for x in open('/home/user/degree-diameter/research/d10D7/sets/P11_r6c7_756.txt').read().split()))

def orbit_graph(G, perms, tag):
    t0 = time.time()
    lab = orbit_labels(G.N, perms)
    members, counts = orbit_members(lab)
    C = G.C
    S = []
    for o, m in enumerate(members):
        if len(m) > CAP or len(m) == 0: continue
        r = m[0]
        ok = ((C[r] @ A7 @ C[m].T) % q) != 0
        ok[0] = True
        if ok.all(): S.append(o)
    n = len(S)
    info = dict(tag=tag, orbits=len(members), selfcompat=n)
    if n == 0:
        return info, None
    sizes = np.array([counts[o] for o in S])
    order = np.concatenate([members[o] for o in S])
    starts = np.concatenate([[0], np.cumsum(sizes)[:-1]])
    CS = C[order].astype(np.float64)
    RA = np.array([C[members[o][0]] for o in S], dtype=np.float64) @ A7.astype(np.float64)
    A = np.zeros((n, n), dtype=bool)
    blk = max(1, int(3e7 // max(1, len(order))))
    for b0 in range(0, n, blk):
        b1 = min(n, b0 + blk)
        M = np.mod(RA[b0:b1] @ CS.T, q) != 0
        A[b0:b1] = np.logical_and.reduceat(M, starts, axis=1)
    A = A & A.T
    np.fill_diagonal(A, False)
    iu = np.triu_indices(n, 1)
    conf = ~A[iu]
    ea = iu[0][conf]; eb = iu[1][conf]
    info.update(edges=int(len(ea)), density=round(float(conf.mean()), 3), secs=round(time.time() - t0, 1))
    # seed: S-orbits fully inside the 756 set
    mask = np.zeros(G.N, bool); mask[S756] = True
    seed = [i for i, o in enumerate(S) if mask[members[o]].all()]
    info['seed_orbits'] = len(seed); info['seed_weight'] = int(sizes[seed].sum()) if seed else 0
    return info, dict(S=np.array(S), sizes=sizes, order=order, starts=starts, ea=ea, eb=eb, seed=np.array(seed, dtype=np.int64))

def save(name, data):
    n = len(data['sizes']); m = len(data['ea'])
    with open('/home/user/degree-diameter/research/squads/hexfam_r2/c3/graphs/%s.bin' % name, 'wb') as f:
        np.array([n, m], dtype='<i4').tofile(f)
        data['sizes'].astype('<i8').tofile(f)
        np.stack([data['ea'], data['eb']], 1).astype('<i4').tofile(f)
    np.savez('/home/user/degree-diameter/research/squads/hexfam_r2/c3/graphs/%s.npz' % name, S=data['S'], sizes=data['sizes'],
             order=data['order'], starts=data['starts'], seed=data['seed'])

if __name__ == '__main__':
    name = sys.argv[1]; spec = sys.argv[2]
    G = Geo(q); simple, R = e7_roots(q)
    if spec in SUBS:
        ed, n = SUBS[spec]; B = subsystem(R, q, ed, n, seed=1, tries=300)
    elif spec.startswith('rand:'):
        # subgroup generated by K random reflections-products (words in the 126 roots' reflections)
        _, seed, k = spec.split(':'); rng = random.Random(int(seed))
        B = [R[rng.randrange(len(R))] for _ in range(int(k))]
    elif spec.startswith('gens:'):
        # explicit list of root indices (into R) given as comma list
        B = R[np.array([int(x) for x in spec[5:].split(',')])]
    if B is None: print(name, 'no subsystem'); sys.exit(0)
    perms = [G.perm(reflection_matrix(b, q)) for b in B]
    info, data = orbit_graph(G, perms, name)
    print(info, flush=True)
    if data is not None:
        save(name, data)
