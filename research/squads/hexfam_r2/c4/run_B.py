"""c4 direction B: subgroups of SL3(13) (as isometries of A7 via sl3) and diagonal/monomial subgroups of O7 (torus)
generated by random small-order elements; orbit unions -> exact clique / ILS. usage: run_B.py TL NTRIALS SEED"""
import sys, time, numpy as np
from hx import *
from q6lib import inv_mod
TL = float(sys.argv[1]); NT = int(sys.argv[2]); SEED = int(sys.argv[3])
rng = np.random.default_rng(SEED)
G = geo()
def sl3_iso(M3):
    T = np.zeros((7, 7), dtype=np.int64)
    T[np.ix_([0, 1, 2], [0, 1, 2])] = M3 % Q
    T[np.ix_([4, 5, 6], [4, 5, 6])] = inv_mod(M3 % Q, Q).T
    T[3, 3] = 1
    return T % Q
def E(i, j):
    M = np.eye(3, dtype=np.int64); M[i, j] = 1; return M
def rand_gl3():
    while True:
        M = rng.integers(0, Q, (3, 3))
        d = int(round(np.linalg.det(M))) % Q
        if d != 0:
            # make det 1 by scaling row 0 (det scale by c -> c*det, need c = det^-1)
            c = pow(d, Q - 2, Q); M[0] = (M[0] * c) % Q
            if int(round(np.linalg.det(M))) % Q == 1: return M
def mat_order(M, cap=50):
    P = np.eye(3, dtype=np.int64)
    for k in range(1, cap + 1):
        P = (P @ M) % Q
        if (P == np.eye(3, dtype=np.int64)).all(): return k
    return None
def rand_small_order_sl3():
    # conjugate of a diagonal / permutation / small matrix of small order
    cands = [np.array([[-1,0,0],[0,-1,0],[0,0,1]]), np.array([[0,1,0],[0,0,1],[1,0,0]]),
             np.array([[0,-1,0],[1,0,0],[0,0,1]]), np.array([[0,1,0],[-1,-1,0],[0,0,1]])]
    base = cands[rng.integers(len(cands))] % Q
    g = rand_gl3()
    gi = inv_mod(g, Q)
    return (g @ base @ gi) % Q
def torus_iso():
    # diag(a,b,c,1,1/a,1/b,1/c) with a,b,c random units; optionally with a swap of the two Lagrangians
    a, b, c = [int(x) for x in rng.integers(1, Q, 3)]
    d = [a, b, c, 1, pow(a, Q - 2, Q), pow(b, Q - 2, Q), pow(c, Q - 2, Q)]
    return np.diag(np.array(d, dtype=np.int64))
results = []
if SEED == 0 or True:
    pass
# fixed case: long-root transvections generate SL3(13)
long_gens = [sl3_iso(E(i, j)) for i in range(3) for j in range(3) if i != j]
trials = [('SL3_longroots', long_gens)]
for t in range(NT):
    kind = t % 3
    if kind == 0:
        gens = [sl3_iso(rand_small_order_sl3()), sl3_iso(rand_small_order_sl3())]
        name = 'SL3_rand2small_%d' % t
    elif kind == 1:
        gens = [sl3_iso(rand_gl3() if False else rand_small_order_sl3()), torus_iso()]
        name = 'SL3_small+torus_%d' % t
    else:
        gens = [torus_iso(), torus_iso()]
        name = 'torus2_%d' % t
    trials.append((name, gens))
best_all = 0
for name, gens in trials:
    t0 = time.time()
    # orbits of the group generated by gens (point perms)
    perms = [G.perm(M) for M in gens]
    w, pts, info = solve_orbits(name, perms, tl_exact=TL, tl_ils=TL, seed=SEED + 1, verbose=False)
    sc = score(write_set('tmpB_%s.txt' % name, pts)) if pts else 'none'
    print(name, {k: info[k] for k in ('orbits', 'selfcompat', 'best', 'method') if k in info}, 'SCORE', sc, '[%.0fs]' % (time.time() - t0), flush=True)
    if pts and w >= 700:
        write_set('B_%s_%d.txt' % (name, w), pts)
    best_all = max(best_all, w)
print('bestB', best_all, flush=True)
