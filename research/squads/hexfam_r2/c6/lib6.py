from q6lib import Geo
from scipy.sparse import coo_matrix
from scipy.sparse.csgraph import connected_components

G = Geo(8)
N = G.N
C6 = G.C[:, [0, 1, 2, 4, 5, 6]].astype(np.int64)
assert (G.normalize(C6) == C6).all()
W8 = 8 ** np.arange(6, dtype=np.int64)
CODE6 = (C6 * W8).sum(1)
SORT = np.argsort(CODE6)
SC = CODE6[SORT]
assert len(np.unique(SC)) == N
J = np.zeros((6, 6), dtype=np.int64)
for i in range(3):
    J[i, i + 3] = J[i + 3, i] = 1

def wform_gf2(a, b):
    """symplectic form on GF(2)^6 vectors (0/1 arrays)"""
    return int(np.asarray(a) @ J @ np.asarray(b)) % 2

def transvection(a):
    a = np.asarray(a, dtype=np.int64)
    M = (np.eye(6, dtype=np.int64) + np.outer(a, (J @ a) % 2)) % 2
    return M

def is_symp(M):
    return ((M.T @ J @ M - J) % 2 == 0).all()

def act_rows(M, ids):
    """image of points ids under GF(2)-matrix M (entries 0/1): returns point ids"""
    X = C6[np.asarray(ids)]
    Y = np.zeros_like(X)
    for i in range(6):
        acc = np.zeros(len(X), dtype=np.int64)
        for j in range(6):
            if M[i, j]:
                acc ^= X[:, j]
        Y[:, i] = acc
    Y = G.normalize(Y)
    code = (Y * W8).sum(1)
    pos = np.searchsorted(SC, code)
    pos = np.minimum(pos, N - 1)
    ids_out = SORT[pos]
    assert (CODE6[ids_out] == code).all(), 'image not a point'
    return ids_out

def perm_of(M):
    return act_rows(M, np.arange(N))

def frob_perm():
    """x -> x^2 coordinatewise (Frobenius of GF(8)), on points"""
    Y = G.MUL[C6, C6]  # square each coord
    Y = G.normalize(Y)
    code = (Y * W8).sum(1)
    pos = np.searchsorted(SC, code)
    ids_out = SORT[np.minimum(pos, N - 1)]
    assert (CODE6[ids_out] == code).all()
    return ids_out

def orbits_of(perms):
    """orbit labels (0..k-1) under the group generated by the given permutations"""
    rows, cols = [], []
    ar = np.arange(N)
    for p in perms:
        rows.append(ar); cols.append(p)
    rows = np.concatenate(rows); cols = np.concatenate(cols)
    A = coo_matrix((np.ones(len(rows), dtype=np.int8), (rows, cols)), shape=(N, N))
    k, lab = connected_components(A, directed=True, connection='weak')
    return k, lab

def Bvals(i, ids=None):
    """w(x_i, y) for y in ids (default all) as bool 'nonorth' mask"""
    X = C6[[i]]
    Y = C6 if ids is None else C6[np.asarray(ids)]
    out = np.zeros(len(Y), dtype=np.int64)
    for a in range(6):
        for b in range(6):
            if J[a, b]:
                out ^= G.MUL[X[0, a], Y[:, b]]
    return out != 0  # True = non-orthogonal

def nonorth_mask_all(i):
    return Bvals(i)

