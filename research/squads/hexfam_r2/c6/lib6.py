def orbit_graph(lab, k=None):
    """returns sizes, selfok (orbit internally pairwise non-orthogonal), adj (k x k bool, compatibility)"""
    lab = np.asarray(lab)
    if k is None: k = int(lab.max()) + 1
    sizes = np.bincount(lab, minlength=k)
    reps = np.full(k, -1, dtype=np.int64)
    order = np.argsort(lab, kind='stable')
    starts = np.concatenate([[0], np.cumsum(sizes)[:-1]])
    reps = order[starts]
    selfok = np.zeros(k, dtype=bool)
    adj = np.zeros((k, k), dtype=bool)
    for i in range(k):
        m = Bvals(reps[i])            # True = non-orthogonal
        orth = ~m
        orth[reps[i]] = False          # ignore self (w(x,x)=0 is orthogonal)
        cnt = np.bincount(lab[orth], minlength=k)
        selfok[i] = cnt[i] == 0
        adj[i] = cnt == 0
    adj &= adj.T
    adj[np.arange(k), np.arange(k)] = False
    return sizes, selfok, adj, reps

def quad_val(Qf, a):
    return Qf(np.asarray(a)) % 2

def Qplus(a):
    a = np.asarray(a); return (a[0] * a[3] + a[1] * a[4] + a[2] * a[5]) % 2

def Qminus(a):
    a = np.asarray(a); return (a[0] * a[3] + a[1] * a[4] + a[2] * a[2] + a[2] * a[5] + a[5] * a[5]) % 2

def orth_transvections(Qf):
    import itertools
    out = []
    for a in itertools.product([0, 1], repeat=6):
        if any(a) and Qf(a) == 1:
            out.append(transvection(a))
    return out

def perp_transvections(v):
    import itertools
    out = []
    for a in itertools.product([0, 1], repeat=6):
        if any(a) and wform_gf2(a, v) == 0:
            out.append(transvection(a))
    return out

def run_group(gens, label='H', exact_limit=400, cpsat_time=20, verbose=True):
    """gens: list of 6x6 GF(2) matrices. Returns dict with best set (point ids) and score info."""
    import time
    t0 = time.time()
    perms = [perm_of(M) for M in gens]
    k, lab = orbits_of(perms)
    sizes, selfok, adj, reps = orbit_graph(lab, k)
    cand = np.nonzero(selfok)[0]
    if verbose:
        print(label, 'orbits', k, 'selfok', len(cand), 'selfok sizes', sorted(sizes[cand].tolist())[-12:], 'time', round(time.time()-t0,1), flush=True)
    if len(cand) == 0:
        return dict(label=label, k=k, best=0, ids=[], sizes=sizes, selfok=selfok)
    w = sizes[cand].tolist()
    A = adj[np.ix_(cand, cand)]
    best, chosen = mwc_solve(w, A, cpsat_time)
    chosen_orbits = cand[chosen]
    ids = np.nonzero(np.isin(lab, chosen_orbits))[0]
    if verbose:
        print(label, 'best union', best, 'orbits used', len(chosen_orbits), 'time', round(time.time()-t0,1), flush=True)
    return dict(label=label, k=k, best=int(best), ids=ids, sizes=sizes, selfok=selfok, cand=cand, adj=adj, lab=lab, reps=reps)

def mwc_solve(w, A, tlimit=20):
    """max-weight clique on the graph with adjacency bool matrix A (compatibility). CP-SAT on non-edges."""
    from ortools.sat.python import cp_model
    n = len(w)
    m = cp_model.CpModel()
    x = [m.NewBoolVar('x%d' % i) for i in range(n)]
    nonedges = np.argwhere(np.triu(~A, 1))
    for i, j in nonedges:
        m.AddBoolOr([x[i].Not(), x[j].Not()])
    m.Maximize(sum(int(w[i]) * x[i] for i in range(n)))
    s = cp_model.CpSolver()
    s.parameters.max_time_in_seconds = tlimit
    s.parameters.num_workers = 1
    s.parameters.random_seed = 1
    st = s.Solve(m)
    chosen = [i for i in range(n) if s.Value(x[i])]
    return int(sum(w[i] for i in chosen)), chosen

def is_clique(A, chosen):
    c = np.asarray(chosen, dtype=np.int64)
    if len(c) <= 1: return True
    sub = A[np.ix_(c, c)].copy()
    np.fill_diagonal(sub, True)
    return bool(sub.all())

def greedy_clique(w, A, tlimit=10.0, seed=0, starts=None):
    """randomised greedy weighted clique with restarts; A bool compatibility matrix (diag False)."""
    import time
    rng = np.random.default_rng(seed)
    n = len(w); w = np.asarray(w, dtype=np.int64)
    best_w, best_set = -1, []
    t0 = time.time(); it = 0
    while True:
        it += 1
        noise = rng.random(n)
        if it == 1:
            score = w.astype(float)
        else:
            score = w * (1.0 + 0.5 * rng.random(n))
        order = np.argsort(-score)
        allowed = np.ones(n, dtype=bool)
        chosen = []; tot = 0
        for v in order:
            if allowed[v]:
                chosen.append(v); tot += w[v]
                allowed &= A[v]
                allowed[v] = False
        if tot > best_w:
            best_w, best_set = tot, chosen
        if time.time() - t0 > tlimit or (starts is not None and it >= starts):
            break
    return int(best_w), best_set

def mwc_any(w, A, tlimit=10.0, seed=0):
    n = len(w)
    if n <= 120:
        bw, ch = mwc_solve(w, A, tlimit)
        if is_clique(A, ch):
            return bw, ch
    return greedy_clique(w, A, tlimit=tlimit, seed=seed)
