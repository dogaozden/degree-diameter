# c3 round 4: groups H = <rot^a> x K on E (q = 11), H acting by isometries of V = {x4 = -x0} = A (+) V4.
# rot: a -> zeta a on A = (x0,x3) (GF(121) = GF(11)[i], zeta of norm 1, order 12); K: M -> X M Y^-1 on V4 (det X = det Y).
# Writes orbit-cycle permutation files (cycles = H-orbits) for orbitclique, and reports orbit statistics.
import numpy as np, sys, json, random
p = 11
D = '/home/user/degree-diameter/research/cell147/data/'
rows = np.loadtxt(D + 'E11.map', dtype=np.int64)
pid = rows[:, 0].copy(); sline = rows[:, 1].copy()
X7 = rows[:, 2:9] % p
N = X7.shape[0]
assert np.all(X7[:, 4] == (-X7[:, 0]) % p)
U = X7[:, [0, 1, 2, 3, 5, 6]].copy()
M = np.zeros((6, 6), dtype=np.int64)
M[0, 0] = -2 % p; M[1, 4] = M[4, 1] = 1; M[2, 5] = M[5, 2] = 1; M[3, 3] = -2 % p
INV = np.array([0] + [pow(a, p - 2, p) for a in range(1, p)], dtype=np.int64)
PW = np.array([p ** i for i in range(6)], dtype=np.int64)
IDX = np.full(p ** 6, -1, dtype=np.int64); IDX[U @ PW] = np.arange(N)
assert np.all(IDX[U @ PW] == np.arange(N))
V4I = [1, 2, 4, 5]

def normalize(A):
    A = A % p
    first = np.argmax(A != 0, axis=1)
    lead = A[np.arange(A.shape[0]), first]
    return (A * INV[lead][:, None]) % p

def perm_of(g):
    assert np.all((g.T @ M @ g) % p == M), "not an isometry"
    IM = normalize((U @ g.T) % p)
    perm = IDX[IM @ PW]
    assert np.all(perm >= 0), "image not on E"
    return perm

def mul12(a, b):
    return ((a[0] * b[0] - a[1] * b[1]) % p, (a[0] * b[1] + a[1] * b[0]) % p)

# zeta: norm-1 element of GF(121) of order 12
zeta = None
for c in range(p):
    for d in range(p):
        if (c * c + d * d) % p == 1:
            z = (c, d); pw = [(1, 0)]
            for k in range(1, 12): pw.append(mul12(pw[-1], z))
            if pw[6] != (1, 0) and pw[4] != (1, 0) and pw[11] == (c, (-d) % p) and pw[1] == z:
                zeta = (c, d, pw); break
    if zeta: break
ZP = zeta[2]  # ZP[k] = zeta^k

def rot_mat(k):
    c, d = ZP[k % 12]
    G = np.eye(6, dtype=np.int64)
    G[0, 0] = c; G[0, 3] = (-d) % p; G[3, 0] = d; G[3, 3] = c
    return G

def v4_to_M(v):
    x1, x2, x5, x6 = v
    return np.array([[x1, x2], [(-x6) % p, x5]], dtype=np.int64)

def M_to_v4(Mx):
    return np.array([Mx[0, 0], Mx[0, 1], Mx[1, 1], (-Mx[1, 0]) % p], dtype=np.int64)

def inv2(Y):
    det = int((Y[0, 0] * Y[1, 1] - Y[0, 1] * Y[1, 0]) % p)
    adj = np.array([[Y[1, 1], -Y[0, 1]], [-Y[1, 0], Y[0, 0]]], dtype=np.int64) % p
    return (adj * INV[det]) % p

def det2(Y): return int((Y[0, 0] * Y[1, 1] - Y[0, 1] * Y[1, 0]) % p)

def T_of(Xm, Ym):
    Yi = inv2(Ym)
    T = np.zeros((4, 4), dtype=np.int64)
    for j in range(4):
        e = np.zeros(4, dtype=np.int64); e[j] = 1
        T[:, j] = M_to_v4((Xm @ v4_to_M(e) @ Yi) % p)
    return T

def full_mat(T4):
    G = np.eye(6, dtype=np.int64)
    G[np.ix_(V4I, V4I)] = T4
    return G

def mat_order(T, cap=2000):
    A = np.eye(T.shape[0], dtype=np.int64)
    for k in range(1, cap + 1):
        A = (A @ T) % p
        if np.array_equal(A, np.eye(T.shape[0], dtype=np.int64)): return k
    return None

def sample_K(rng, count):
    out = []
    for _ in range(count):
        while True:
            Xm = rng.integers(0, p, (2, 2)).astype(np.int64)
            if det2(Xm) % p: break
        Ym = rng.integers(0, p, (2, 2)).astype(np.int64)
        while det2(Ym) == 0: Ym = rng.integers(0, p, (2, 2)).astype(np.int64)
        d0, d1 = det2(Xm), det2(Ym)
        Ym[:, 0] = (Ym[:, 0] * d0 * INV[d1]) % p          # force det Ym = det Xm
        assert det2(Ym) == d0
        T = T_of(Xm, Ym)
        out.append((Xm, Ym, T))
    return out

def orbits_of(gens):
    """orbit partition of E under the group generated by the permutations in gens (union-find)."""
    par = np.arange(N)
    def find(x):
        while par[x] != x:
            par[x] = par[par[x]]; x = par[x]
        return x
    for g in gens:
        for i in range(N):
            a, b = find(i), find(int(g[i]))
            if a != b: par[a] = b
    roots = np.array([find(i) for i in range(N)])
    return roots

def write_perm(roots, path):
    # perm[j] = next element of the orbit (cyclic); cycles of perm are the orbits
    perm = np.arange(N)
    order = np.argsort(roots, kind='stable')
    rs_sorted = roots[order]
    starts = np.flatnonzero(np.r_[True, rs_sorted[1:] != rs_sorted[:-1]])
    ends = np.r_[starts[1:], N]
    sizes = []
    for s, e in zip(starts, ends):
        el = order[s:e]
        perm[el] = np.roll(el, -1)
        sizes.append(e - s)
    with open(path, 'w') as f:
        f.write('\n'.join(map(str, perm.tolist())) + '\n')
    return sizes

def stats(sizes):
    from collections import Counter
    c = Counter(sizes)
    return {int(k): int(v) for k, v in sorted(c.items())}

