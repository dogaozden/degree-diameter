# independent group model: SL(2,8) x D_P, GF(8) = F2[x]/(x^3+x+1)
import sys, itertools, random
def gmul(a,b):
    r=0
    for i in range(3):
        if (b>>i)&1: r^=a<<i
    for i in (4,3):
        if (r>>i)&1: r^=0b1011<<(i-3)
    return r
F=[[gmul(a,b) for b in range(8)] for a in range(8)]
SL=[]
for a,b,c,d in itertools.product(range(8),repeat=4):
    if F[a][d]^F[b][c]==1: SL.append((a,b,c,d))
def mm(X,Y):
    a,b,c,d=X; e,f,g,h=Y
    return (F[a][e]^F[b][g], F[a][f]^F[b][h], F[c][e]^F[d][g], F[c][f]^F[d][h])
def dmul(x,y,P):
    a,j=x; b,k=y
    return ((a+b)%P if j==0 else (a-b)%P, (j+k)%2)
def gm(g,h,P): return (mm(g[0],h[0]), dmul(g[1],h[1],P))
def inv_sl(X):
    a,b,c,d=X; return (d,b,c,a)
def ginv(g,P):
    a,j=g[1]
    return (inv_sl(g[0]), ((-a)%P,0) if j==0 else (a,1))
if __name__=="__main__":
    print(len(SL))
    P=37
    # closure of group generated by a set
    def closure(gens,P,limit=10**6):
        e=((1,0,0,1),(0,0))
        seen={e}; frontier=[e]
        while frontier:
            nf=[]
            for x in frontier:
                for g in gens:
                    y=gm(x,g,P)
                    if y not in seen:
                        seen.add(y); nf.append(y)
                        if len(seen)>limit: return len(seen)
            frontier=nf
        return len(seen)
    # random element g, alpha = sigma x beta, U=10
    random.seed(1)
    for trial in range(5):
        M=random.choice(SL); a=random.randrange(P); j=random.randrange(2)
        g=(M,(a,j))
        sq=lambda X: tuple(F[x][x] for x in X)
        ga=(sq(M),((10*a)%P,j))
        ga2=(sq(ga[0]),((10*ga[1][0])%P,ga[1][1]))
        S=[((1,0,0,1),(0,0)), g, ga, ga2]
        Si=[ginv(s,P) for s in S]
        diffs=[gm(x,y,P) for x in Si for y in S]
        print("trial",trial,"closure of S^-1 S:",closure(list(set(diffs)),P), "closure of S:", closure(S,P))
