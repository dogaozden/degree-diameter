#!/usr/bin/env python3
"""c4: non-abelian extensions of torus subgroups of SO(7,11) by monomial normaliser elements.

Block coordinates for T = ovlib.torus(types) (types E,H,H,L or H,H,H,L). The normaliser of T modulo T is the group W0
generated by
  s_b  : swap e <-> f inside a hyperbolic block (inverts that block's torus),
  t_ij : transposition of two equal hyperbolic blocks,
  F_b  : Frobenius x -> x^q on an elliptic block (inverts its torus).
A group G = <H, w*t> (H = <torus elements>, w in W0, t in T) is built in block coordinates and conjugated to the
standard form by P (returned by ovlib.torus): M = P W P^-1 preserves std_gram. Each G goes to orbclq.

usage: normext.py [--types E,H,H,L] [--n 100] [--t 8] [--seed 1] [--tag a] [--control]
"""
import sys, os, json, time, argparse, subprocess, itertools, math, hashlib, random, shutil
import numpy as np

OV = '/home/user/degree-diameter/research/cell147/ovoid'
sys.path.insert(0, OV)
import ovlib as L

HERE = os.path.dirname(os.path.abspath(__file__))
ORB = os.path.join(OV, 'orbclq')
SETS = os.path.join(HERE, 'sets')
GENS = os.path.join(HERE, 'gens')
RUNS = os.path.join(HERE, 'runs.jsonl')
q = 11
I7 = np.eye(7, dtype=np.int64)


def mm(A, B):
    return (A @ B) % q


def key(M):
    return M.tobytes()


def closure(gens, limit):
    """all products of gens (finite group), or None if more than `limit` elements."""
    seen = {key(I7): I7}
    frontier = [I7]
    while frontier:
        nf = []
        for X in frontier:
            for g in gens:
                Y = mm(X, g)
                k = key(Y)
                if k not in seen:
                    if len(seen) >= limit:
                        return None
                    seen[k] = Y
                    nf.append(Y)
        frontier = nf
    return seen


class Torus:
    def __init__(self, types):
        self.types = types
        gens_std, self.orders, P = L.torus(types, q)
        blocks = [L.block(t, q) for t in types]
        self.dims = [len(b[0]) for b in blocks]
        self.offs = list(itertools.accumulate([0] + self.dims[:-1]))
        self.Gp = np.zeros((7, 7), dtype=np.int64)
        tg = []
        for (g, t, o), d, off in zip(blocks, self.dims, self.offs):
            for i in range(d):
                for j in range(d):
                    self.Gp[off + i, off + j] = g[i][j] % q
            T = I7.copy()
            for i in range(d):
                for j in range(d):
                    T[off + i, off + j] = t[i][j] % q
            tg.append(T)
        self.P = np.array(P, dtype=np.int64)
        self.Pi = np.array(L.mat_inv(P, q), dtype=np.int64)
        self.STD = np.array(L.std_gram(q), dtype=np.int64)
        self.pw = []
        for T, o in zip(tg, self.orders):
            lst = [I7.copy()]
            for _ in range(1, o):
                lst.append(mm(lst[-1], T))
            assert (mm(lst[-1], T) == I7).all()
            self.pw.append(lst)
        self.exps, self.elems = [], []
        for e in itertools.product(*[range(o) for o in self.orders]):
            M = I7.copy()
            for b, eb in enumerate(e):
                M = mm(M, self.pw[b][eb])
            self.exps.append(e)
            self.elems.append(M)
        self.index = {e: i for i, e in enumerate(self.exps)}
        # sanity: block torus conjugated by P equals ovlib's generators
        for i, T in enumerate(tg):
            M = mm(mm(self.P, T), self.Pi)
            assert (M == np.array(gens_std[i], dtype=np.int64)).all()
            assert ((T.T @ self.Gp @ T - self.Gp) % q == 0).all()
        self.Weyl = self._weyl()
        W = closure(list(self.Weyl.values()), limit=1000)
        self.Wlist = list(W.values())
        assert (self.Wlist[0] == I7).all()
        self.Winv = {}
        for w in self.Wlist:
            for v in self.Wlist:
                if (mm(w, v) == I7).all():
                    self.Winv[key(w)] = v
                    break
        self.Wnames = {key(w): i for i, w in enumerate(self.Wlist)}

    def _weyl(self):
        out = {}

        def perm(pairs):
            M = I7.copy()
            for a, b in pairs:
                M[[a, b]] = M[[b, a]]
            return M

        for b, t in enumerate(self.types):
            o = self.offs[b]
            if t == 'H':
                out['s%d' % b] = perm([(o, o + 1)])
            elif t == 'E':
                F = L.GF(q, 2)
                cols = [F.pow([int(i == j) for i in range(2)], q) for j in range(2)]
                M = I7.copy()
                for i in range(2):
                    for j in range(2):
                        M[o + i, o + j] = cols[j][i] % q
                out['F%d' % b] = M
        hb = [b for b, t in enumerate(self.types) if t == 'H']
        for i, j in itertools.combinations(hb, 2):
            out['t%d%d' % (i, j)] = perm([(self.offs[i] + k, self.offs[j] + k) for k in range(self.dims[i])])
        for name, M in out.items():
            assert ((M.T @ self.Gp @ M - self.Gp) % q == 0).all(), name
        return out

    def sub_exps(self, es):
        zero = tuple(0 for _ in self.orders)
        S = {zero}
        frontier = [zero]
        while frontier:
            nf = []
            for x in frontier:
                for e in es:
                    y = tuple((xi + ei) % oi for xi, ei, oi in zip(x, e, self.orders))
                    if y not in S:
                        S.add(y)
                        nf.append(y)
            frontier = nf
        return S

    def to_std(self, M):
        Ms = mm(mm(self.P, M), self.Pi)
        assert ((Ms.T @ self.STD @ Ms - self.STD) % q == 0).all()
        return Ms


def describe_w(T, w):
    return T.Wnames[key(w)]


def run_orbclq(gpath, outp, t, seed):
    r = subprocess.run([ORB, gpath, '-q', str(q), '-t', str(t), '-s', str(seed), '-o', outp],
                       capture_output=True, text=True, timeout=max(120, 6 * t + 120))
    res = {}
    for line in r.stdout.splitlines():
        if line.startswith('RESULT'):
            for kv in line.split()[1:]:
                if '=' in kv:
                    k, v = kv.split('=', 1)
                    try:
                        res[k] = float(v) if '.' in v else int(v)
                    except ValueError:
                        res[k] = v
    return res, r.returncode, r.stderr


def inv_jobs(T, rng, n, maxH):
    """groups G = H <| <nm>: nm = w t an involution of N(T) outside T, H = <h> a cyclic torus subgroup with nm h nm in H.
    |G| = 2|H|."""
    invs = []
    for w in T.Wlist[1:]:
        if not (mm(w, w) == I7).all():
            continue
        for ti, tm in enumerate(T.elems):
            nm = mm(w, tm)
            if (mm(nm, nm) == I7).all():
                invs.append((w, nm, ti))
    print(f'involutions w*t in N(T) outside T: {len(invs)}', flush=True)
    jobs, tries = [], 0
    while len(jobs) < n and tries < 200000:
        tries += 1
        w, nm, ti = invs[rng.randrange(len(invs))]
        ei = rng.randrange(1, len(T.exps))
        e = T.exps[ei]
        sz = len(T.sub_exps([e]))
        if not (3 <= sz <= maxH):
            continue
        hel = [T.elems[ei]]
        Hk = set(closure(hel, limit=2 * maxH + 2).keys())
        if not all(key(mm(mm(nm, h), nm)) in Hk for h in hel):
            continue
        jobs.append((f'inv{ti}_{ei}', hel, [nm], [list(e)], [T.Wnames[key(w)]], [list(T.exps[ti])]))
    print(f'inv jobs {len(jobs)} after {tries} tries', flush=True)
    return jobs


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--types', default='E,H,H,L')
    ap.add_argument('--n', type=int, default=50)
    ap.add_argument('--t', type=float, default=8)
    ap.add_argument('--seed', type=int, default=1)
    ap.add_argument('--tag', default='a')
    ap.add_argument('--control', action='store_true')
    ap.add_argument('--minsize', type=int, default=8)
    ap.add_argument('--maxsize', type=int, default=800)
    ap.add_argument('--keep', type=int, default=740)
    ap.add_argument('--maxH', type=int, default=60)
    ap.add_argument('--mode', default='norm')
    a = ap.parse_args()
    for d in (SETS, GENS):
        os.makedirs(d, exist_ok=True)
    types = a.types.split(',')
    T = Torus(types)
    print(f'torus {types} orders {T.orders} |T|={len(T.elems)} W0 order {len(T.Wlist)} weyl {list(T.Weyl)}', flush=True)
    rng = random.Random(a.seed)
    seen = set()
    done_names = set()
    if os.path.exists(RUNS):
        for line in open(RUNS):
            try:
                done_names.add(json.loads(line)['name'])
            except Exception:
                pass

    jobs = []
    if a.control:
        # torus-only control: the order-15 group of the 756 set, exponents (4,2,4,0) if the types match
        for es in ([(4, 2, 4, 0)],):
            jobs.append(('control', [T.elems[T.index[e]] for e in es], [], [list(e) for e in es], [], None))
    elif a.mode == 'inv':
        jobs = inv_jobs(T, rng, a.n, a.maxH)
    else:
        for trial in range(a.n):
            while True:
                k = 1 if rng.random() < 0.55 else 2
                es = [T.exps[rng.randrange(1, len(T.exps))] for _ in range(k)]
                Hs = T.sub_exps(es)
                if 3 <= len(Hs) <= a.maxH:
                    break
            hel = [T.elems[T.index[e]] for e in es]
            Hkeys = set(closure(hel, limit=2 * a.maxH + 2).keys())
            norm = [w for w in T.Wlist[1:]
                    if all(key(mm(mm(w, h), T.Winv[key(w)])) in Hkeys for h in hel)]
            nw = 1 if rng.random() < 0.6 else 2
            wt, wdesc, tdesc = [], [], []
            for _ in range(nw):
                pool = norm if (norm and rng.random() < 0.85) else T.Wlist[1:]
                w = rng.choice(pool)
                ti = rng.randrange(len(T.elems))
                wt.append(mm(w, T.elems[ti]))
                wdesc.append(describe_w(T, w))
                tdesc.append(list(T.exps[ti]))
            jobs.append((f'{a.tag}{a.seed}_{trial}', hel, wt, [list(e) for e in es], wdesc, tdesc))

    best_so_far = 0
    for name, hel, wt, hexps, wdesc, tdesc in jobs:
        gens_block = hel + wt
        G = closure(gens_block, limit=a.maxsize)
        if G is None or len(G) < a.minsize:
            continue
        dig = hashlib.sha1(b''.join(sorted(G.keys()))).hexdigest()[:16]
        if dig in seen:
            continue
        seen.add(dig)
        abelian = all((mm(x, y) == mm(y, x)).all() for x in gens_block for y in gens_block)
        proj = len(G) // 2 if key((-I7) % q) in G else len(G)
        gname = f'{name}_o{len(G)}'
        if gname in done_names:
            continue
        gens_std = [T.to_std(M) for M in gens_block]
        gpath = os.path.join(GENS, gname + '.txt')
        L.write_gens(gpath, [M.tolist() for M in gens_std],
                     f'c4 normext torus {types} H exps {hexps} Weyl {wdesc} t exps {tdesc} |G|={len(G)}')
        outp = os.path.join(SETS, gname + '.txt')
        t0 = time.time()
        res, rc, err = run_orbclq(gpath, outp, a.t, a.seed)
        wall = round(time.time() - t0, 1)
        best = int(res.get('best', 0))
        K = res.get('good', None)
        rec = dict(name=gname, types=types, H=hexps, weyl=wdesc, tdesc=tdesc, order=len(G), proj_order=proj,
                   abelian=abelian, K=K, best=best, exact=res.get('exact'), pairs_orthogonal=res.get('pairs_orthogonal'),
                   rc=rc, wall=wall)
        with open(RUNS, 'a') as f:
            f.write(json.dumps(rec) + '\n')
        print(f"{gname} |G|={len(G)} proj={proj} abel={int(abelian)} W={wdesc} K={K} best={best} "
              f"exact={res.get('exact')} orth={res.get('pairs_orthogonal')} rc={rc} wall={wall}", flush=True)
        if rc != 0 or best < a.keep:
            if os.path.exists(outp):
                os.remove(outp)
        best_so_far = max(best_so_far, best)
    print(f'chunk done, best in chunk {best_so_far}', flush=True)


if __name__ == '__main__':
    main()
