import sys, random, pickle, numpy as np
exec(open('frames2.py').read().split("t0=time.time()")[0])
import ovlib
fr0 = frames_exact(U_signed)                       # 1344 signed frames = 2^3.L3(2)
def tomod(Fc): return [[(Fc[c][r+1]*6)%11 for c in range(7)] for r in range(7)]
G = [tomod(F) for F in fr0]
print('signed frames', len(G), flush=True)
I3 = [[int(i==j) for j in range(7)] for i in range(7)]
# conjugate the whole group to the standard form of Q(6,11) (same P for all)
conj, P = ovlib.conjugate_to_standard(G, I3, 11)
std = ovlib.std_gram(11)
assert all(ovlib.is_isometry(M, std, 11) for M in conj)
print('all', len(conj), 'elements preserve Q(6,11)', flush=True)
Gm = [np.array(M, dtype=np.int64) for M in conj]
Ikey = np.eye(7, dtype=np.int64).tobytes()
def closure(gens, cap):
    seen = {Ikey: np.eye(7, dtype=np.int64)}; fr = [seen[Ikey]]
    while fr:
        nf = []
        for X in fr:
            for g in gens:
                Y = (X @ g) % 11; k = Y.tobytes()
                if k not in seen:
                    seen[k] = Y; nf.append(Y)
                    if len(seen) > cap: return None
        fr = nf
    return seen
rng = random.Random(11)
found = {}
for trial in range(4000):
    a, b = rng.choice(Gm), rng.choice(Gm)
    H = closure([a, b], 1400)
    if H is None or len(H) < 4: continue
    key = frozenset(H.keys())
    if key in found: continue
    found[key] = ([a, b], len(H))
orders = {}
for key, (gens, n) in found.items(): orders.setdefault(n, []).append(gens)
print('subgroup orders found (2-generated, random sampling):', {n: len(v) for n, v in sorted(orders.items())}, flush=True)
pickle.dump({'orders': {n: [[M.tolist() for M in g] for g in v] for n, v in orders.items()}, 'P': P}, open('subgroups_23.pkl', 'wb'))
# write the full group (generated by two random elements, must give 1344) and a few subgroups
def write(name, gens):
    ovlib.write_gens(f'gens/{name}.txt', [M.tolist() for M in gens], comment=name)
for n in sorted(orders):
    for k, g in enumerate(orders[n][:2]):
        write(f'ord{n}_{k}', g)
print('written', flush=True)
