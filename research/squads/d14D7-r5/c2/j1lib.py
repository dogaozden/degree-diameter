def normalizer_mask(ALL, x, normal_only_k1=False):
    """boolean mask over ALL of g with g x g^-1 in <x> (k1 only: centralizer)."""
    o = order_of(x)
    pw = [I7]
    for _ in range(1, o): pw.append(mm(pw[-1], x))
    gx = mm(ALL, x)
    mask = np.zeros(len(ALL), bool)
    ks = [1] if normal_only_k1 else range(o)
    for k in ks:
        xkg = mm(pw[k], ALL)
        mask |= np.all((gx == xkg).reshape(len(ALL), 49), axis=1)
    return mask

def set_normalizer_mask(ALL, Hkeys, Hgens):
    """g with g H g^-1 = H (H a group given by generators Hgens; Hkeys its dict of keys)."""
    mask = np.ones(len(ALL), bool)
    for p in Hgens:
        gp = mm(ALL, p)
        m = np.zeros(len(ALL), bool)
        for q_ in Hkeys.values():
            m |= np.all((gp == mm(q_, ALL)).reshape(len(ALL), 49), axis=1)
        mask &= m
    return mask

def small_gens(elems_dict, rng, maxg=4):
    """a generating set (few matrices) of the group given as dict key->matrix."""
    target = len(elems_dict)
    vals = list(elems_dict.values())
    gens = []
    cur = {key(I7): I7}
    tries = 0
    while len(cur) < target and tries < 10000:
        tries += 1
        g = vals[rng.randrange(len(vals))]
        if key(g) in cur: continue
        gens.append(g)
        cur = closure(gens)
        if len(gens) > maxg: return None
    return gens if len(cur) == target else None
