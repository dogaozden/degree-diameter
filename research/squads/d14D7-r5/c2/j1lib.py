I7 = np.eye(7, dtype=np.int64)

def key(M):
    return (np.asarray(M, dtype=np.int64) % Q).astype(np.uint8).tobytes()

def mm(A, B):
    return (A @ B) % Q

def order_of(M):
    X = M % Q; k = 1
    while not np.array_equal(X, I7):
        X = mm(X, M); k += 1
    return k

def closure(gens, cap=None):
    """dict key -> matrix of the group generated by gens (None if larger than cap)."""
    seen = {key(I7): I7}
    frontier = [I7]
    while frontier:
        nf = []
        for X in frontier:
            for g in gens:
                Y = mm(X, g)
                k = key(Y)
                if k not in seen:
                    seen[k] = Y; nf.append(Y)
                    if cap is not None and len(seen) > cap:
                        return None
        frontier = nf
    return seen

def enumerate_group(gens):
    seen = {key(I7)}
    layers = [I7[None].copy()]
    frontier = I7[None].copy()
    while len(frontier):
        cand = np.concatenate([mm(frontier, g) for g in gens])
        flat = cand.reshape(len(cand), 49).astype(np.uint8)
        keep = []
        for i in range(len(flat)):
            b = flat[i].tobytes()
            if b not in seen:
                seen.add(b); keep.append(i)
        frontier = cand[keep]
        if keep: layers.append(frontier)
    return np.concatenate(layers)

