"""PSU(3,3) as a permutation group on the 28 isotropic points of the Hermitian form sum x_i y_i^3 over GF(9),
generated by all unitary transvections x -> x + a h(x,v) v (v isotropic, a^3 = -a). Writes tabs/PSU3_3.bin."""
import sys, os, itertools, random
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, "/home/user/degree-diameter/research/squads/handsoff-49/tools")
import pgen, groups
q, MUL, ADD, INV, NEG = pgen.gf_tables(3, 2, [2, 0])
conj = lambda a: MUL[MUL[a][a]][a]
def h(x, y):
    s = 0
    for i in range(3):
        s = ADD[s][MUL[x[i]][conj(y[i])]]
    return s
def normalize(v):
    c = next(x for x in v if x)
    ic = INV[c]
    return tuple(MUL[ic][x] for x in v)
vecs = [v for v in itertools.product(range(q), repeat=3) if any(v)]
pts = sorted({normalize(v) for v in vecs if h(v, v) == 0})
print("isotropic points:", len(pts))
idx = {p: i for i, p in enumerate(pts)}
# unitarity test of a candidate transvection
def T(a, v, x):
    c = MUL[a][h(x, v)]
    return tuple(ADD[x[i]][MUL[c][v[i]]] for i in range(3))
gens = []
alphas = [a for a in range(1, q) if conj(a) == NEG[a]]
print("alphas with conj(a) = -a:", alphas)
for v in pts:
    for a in alphas:
        perm = []
        for p in pts:
            perm.append(idx[normalize(T(a, v, p))])
        gens.append(tuple(perm))
# sanity: all generators are permutations
assert all(len(set(g)) == len(pts) for g in gens)
T_tab = pgen.perm_table(gens)
N = len(T_tab)
print("order", N)
groups.write_bin(T_tab, os.path.join(HERE, "tabs", "PSU3_3.bin"))
