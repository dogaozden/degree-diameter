/* exh: exhaustive certification of Haar graphs H(G,S) of diameter D (D odd), |S| = 4, over a metacyclic group
 * G = Z_m x|_r Z_k (element a + m*j, product (a,j)(b,l) = (a + r^j b, j + l)) or a table group (tab FILE.bin).
 *
 * Graph: vertices (g,A) = g and (g,B) = N + g; edges (g,A) ~ (s g,B) for s in S (left multiplication, as flift).
 * Right translation is transitive on each side, so the diameter is decided by the two roots (e,A), (e,B).
 * Cost (haar_gen3 convention, D odd):  sum over the two roots u of #(vertices on the side of u not within D-1 of
 * the root).  Cost 0 iff diam <= D.  It is exact: cost(lim) returns a value > lim (a partial sum) when it exceeds lim.
 *
 * Symmetry used (both exact):
 *  (1) H(G,S) = H(G, d S c^-1) for all d, c in G (map (g,A) -> (c g, A), (g,B) -> (d c g... ), so S can be taken to
 *      contain e; this is the volt[0] = e normalisation.
 *  (2) H(G,S) = H(G, sigma(S)) for sigma in Aut(G).  The automorphisms used are generated by verified maps
 *      (a,j) -> (u a, j) (u a unit) and, when they are automorphisms, (a,j) -> (a + c S_j, j), S_j = sum_{i<j} r^i.
 *      x runs over one representative of every orbit on G \ {e}; y < z run over all remaining pairs.
 *      Every 4-set {e,x,y,z} (with e in S) is mapped to one with x a representative, so the search is exhaustive.
 *
 * Usage: exh meta M K R | exh tab FILE.bin ,  then:  LIMIT TAG MAXSEC [D]
 *   LIMIT: initial bound (only sets with cost <= LIMIT are recorded; the search is exact below it), TAG: name of files
 *   in ./state, ./hits, ./out, MAXSEC: wall seconds for this call (state is saved after every representative, so a
 *   call resumes where the last one stopped).  Prints "DONE" with the exact minimum when every representative is done.
 */
#include <stdio.h>
#include <stdlib.h>
#include <stdint.h>
#include <string.h>
#include <time.h>
#include <errno.h>

#define MAXR 4096
static int N, D = 9, nH, R;
static uint16_t *MT; static int *INV;
static int *POS;
static uint64_t HMASK;
static int16_t *RMAP; static int8_t *ROT;
static uint64_t *Fb, *NFb, *Vb;
static long long evals;
static char tag[256];
static int M_, K_, R_;

static inline int mul(int x, int y) { return MT[(size_t)x * N + y]; }
static double now(void) { struct timespec t; clock_gettime(CLOCK_MONOTONIC, &t); return t.tv_sec + 1e-9 * t.tv_nsec; }

static void load_meta(int mm, int kk, int rr) {
    M_ = mm; K_ = kk; R_ = rr;
    N = mm * kk; MT = malloc((size_t)N * N * 2);
    long *rp = malloc(kk * sizeof(long)); rp[0] = 1 % mm; for (int j = 1; j < kk; j++) rp[j] = rp[j - 1] * rr % mm;
    for (int j = 0; j < kk; j++) for (int a = 0; a < mm; a++) for (int l = 0; l < kk; l++) for (int bb = 0; bb < mm; bb++)
        MT[(size_t)(a + mm * j) * N + bb + mm * l] = (uint16_t)((a + rp[j] * bb) % mm + mm * ((j + l) % kk));
    free(rp);
}

static void load_tab(const char *p) {
    FILE *f = fopen(p, "rb"); int32_t n32;
    if (!f || fread(&n32, 4, 1, f) != 1) { fprintf(stderr, "cannot read %s\n", p); exit(2); }
    N = n32; MT = malloc((size_t)N * N * 2);
    if (fread(MT, 2, (size_t)N * N, f) != (size_t)N * N) { fprintf(stderr, "short table\n"); exit(2); }
    fclose(f);
}

static void setup_inv(void) {
    INV = malloc(N * sizeof(int));
    for (int g = 0; g < N; g++) { INV[g] = -1; for (int h = 0; h < N; h++) if (mul(g, h) == 0) { INV[g] = h; break; } if (INV[g] < 0) { fprintf(stderr, "no inverse\n"); exit(2); } }
    for (int g = 0; g < N; g++) if (mul(0, g) != g || mul(g, 0) != g) { fprintf(stderr, "identity must be index 0\n"); exit(2); }
}

/* coset structure (as flift): elements = rep_r * h^t, h of order nH <= 64, bit t of row r */
static void setup_cosets(void) {
    int best = 1, bh = 0;
    for (int g = 0; g < N; g++) { int x = g, o = 1; while (x != 0 && o <= N) { x = mul(x, g); o++; }
        for (int dv = 64; dv > best; dv--) if (o % dv == 0) { int e = o / dv, hh = 0; for (int u = 0; u < e; u++) hh = mul(hh, g); best = dv; bh = hh; break; } }
    nH = best; R = N / nH; if (R > MAXR) { fprintf(stderr, "too many rows %d\n", R); exit(2); }
    HMASK = nH == 64 ? ~0ULL : ((1ULL << nH) - 1);
    int *HP = malloc(nH * sizeof(int)); HP[0] = 0; for (int t = 1; t < nH; t++) HP[t] = mul(HP[t - 1], bh);
    POS = malloc(N * sizeof(int)); for (int g = 0; g < N; g++) POS[g] = -1;
    int *REP = malloc(R * sizeof(int));
    int r = 0; for (int g = 0; g < N; g++) if (POS[g] < 0) { REP[r] = g; for (int t = 0; t < nH; t++) POS[mul(g, HP[t])] = r * 64 + t; r++; }
    if (r != R) { fprintf(stderr, "coset error\n"); exit(2); }
    RMAP = malloc((size_t)N * R * 2); ROT = malloc((size_t)N * R);
    for (int g = 0; g < N; g++) for (int q = 0; q < R; q++) { int p = POS[mul(g, REP[q])]; RMAP[(size_t)g * R + q] = p >> 6; ROT[(size_t)g * R + q] = p & 63; }
    free(HP); free(REP);
}

static inline uint64_t rotl(uint64_t x, int s) { if (!s) return x; return ((x << s) | (x >> (nH - s))) & HMASK; }

/* the 4 voltages of the dipole: volt[0] = e (fixed), volt[1..3] = x, y, z; inv[i] = inverse */
static int volt[4], vinv[4];

/* cost with early exit above lim: root u in {0,1}, levels 1..D-1, own-side unreached count */
static long cost(long lim) {
    evals++;
    long c = 0;
    size_t BR = (size_t)2 * R;
    for (int u = 0; u < 2; u++) {
        memset(Fb, 0, BR * 8); memset(Vb, 0, BR * 8);
        int p0 = POS[0];
        Fb[(size_t)u * R + (p0 >> 6)] = 1ULL << (p0 & 63); Vb[(size_t)u * R + (p0 >> 6)] = Fb[(size_t)u * R + (p0 >> 6)];
        uint64_t *F = Fb, *NF = NFb, *V = Vb;
        for (int lev = 1; lev <= D - 1; lev++) {
            memset(NF, 0, BR * 8);
            /* side 0 -> side 1 with volt g, side 1 -> side 0 with volt g^-1 */
            for (int i = 0; i < 4; i++) {
                int g = volt[i];
                const uint64_t *F0 = F; uint64_t *N1 = NF + R;
                const int16_t *rm = RMAP + (size_t)g * R; const int8_t *ro = ROT + (size_t)g * R;
                for (int rr = 0; rr < R; rr++) if (F0[rr]) N1[rm[rr]] |= rotl(F0[rr], ro[rr]);
                int gi = vinv[i];
                const uint64_t *F1 = F + R; uint64_t *N0 = NF;
                const int16_t *rm2 = RMAP + (size_t)gi * R; const int8_t *ro2 = ROT + (size_t)gi * R;
                for (int rr = 0; rr < R; rr++) if (F1[rr]) N0[rm2[rr]] |= rotl(F1[rr], ro2[rr]);
            }
            for (size_t q = 0; q < BR; q++) { NF[q] &= ~V[q]; V[q] |= NF[q]; }
            uint64_t *t = F; F = NF; NF = t;
        }
        long reached = 0; for (int rr = 0; rr < R; rr++) reached += __builtin_popcountll(V[(size_t)u * R + rr]);
        c += (long)N - reached;
        if (c > lim) return c;
    }
    return c;
}

/* graph edges of H(G,S) for S = {e, x, y, z}: (g,A)=g ~ (s g,B)=N+s g */
static void write_edges(const char *path, const int *S) {
    FILE *f = fopen(path, "w"); if (!f) { perror(path); exit(2); }
    fprintf(f, "%d\n", 2 * N);
    for (int i = 0; i < 4; i++) for (int g = 0; g < N; g++) fprintf(f, "%d %d\n", g, N + mul(S[i], g));
    fclose(f);
}

/* automorphism candidates: maps as arrays of length N; generators kept if they are homomorphisms */
static int check_hom_gens(const int *phi, const int *gl, int ng) {
    /* phi(g h) = phi(g) phi(h) for g in gl (generators) and all h: suffices (induction on words) */
    for (int t = 0; t < ng; t++) { int g = gl[t]; for (int h = 0; h < N; h++) if (phi[mul(g, h)] != mul(phi[g], phi[h])) return 0; }
    return 1;
}
static int *uf; static int uf_find(int a) { while (uf[a] != a) { uf[a] = uf[uf[a]]; a = uf[a]; } return a; }
static void uf_union(int a, int b) { a = uf_find(a); b = uf_find(b); if (a != b) { if (a < b) uf[b] = a; else uf[a] = b; } }

static int gcd_i(int a, int b) { while (b) { int t = a % b; a = b; b = t; } return a; }

/* representatives of orbits on G \ {e} under the verified automorphisms (meta: units and translations) */

/* ---- automorphisms and orbit representatives (meta groups) ----
 * AUT: all maps phi_{u,c}(a + m j) = (u a + c S_j mod m) + m j with u a unit and c in Z_m that are homomorphisms
 * (checked on the generators (1,0), (0,1); this suffices).  They are automorphisms of Z_m x|_r Z_k.  Pairs (u,c)
 * form a group.  Orbits on G \ {e} give the representatives x; for x, the stabiliser G_x (maps fixing x) acts on
 * unordered pairs {y,z} and only the lexicographically least pair of each orbit is searched. */
static int *reps; static int nreps;
static int naut = 0, *au, *ac, *Sj;
static int build_aut_meta(void) {
    int m = M_, k = K_, r = R_;
    int gl[2] = { 1 % N, m % N };
    Sj = malloc(k * sizeof(int)); Sj[0] = 0; long rp = 1 % m;
    for (int j = 1; j < k; j++) { Sj[j] = (int)((Sj[j - 1] + rp) % m); rp = rp * r % m; }
    au = malloc(sizeof(int) * (size_t)m * m); ac = malloc(sizeof(int) * (size_t)m * m);
    int *phi = malloc(N * sizeof(int));
    for (int u = 1; u < m || (m == 1 && u == 1); u++) {
        if (gcd_i(u, m) != 1 && m > 1) continue;
        for (int c = 0; c < m; c++) {
            for (int j = 0; j < k; j++) for (int a = 0; a < m; a++) phi[a + m * j] = (int)(((long)u * a + (long)c * Sj[j]) % m) + m * j;
            if (!check_hom_gens(phi, gl, 2)) continue;
            au[naut] = u; ac[naut] = c; naut++;
        }
    }
    free(phi);
    int ntr = 0; for (int t = 0; t < naut; t++) if (au[t] == 1) ntr++;
    fprintf(stderr, "aut: |AUT| = %d verified (u,c) maps, of which %d are translations (u=1)\n", naut, ntr);
    return naut;
}
static inline int aut_apply(int t, int y) {
    int a = y % M_, j = y / M_;
    return (int)(((long)au[t] * a + (long)ac[t] * Sj[j]) % M_) + M_ * j;
}
static void build_reps_meta(void) {
    build_aut_meta();
    uf = malloc(N * sizeof(int)); for (int g = 0; g < N; g++) uf[g] = g;
    for (int t = 0; t < naut; t++) for (int g = 0; g < N; g++) uf_union(g, aut_apply(t, g));
    reps = malloc(N * sizeof(int)); nreps = 0;
    int *seen = calloc(N, sizeof(int));
    for (int g = 1; g < N; g++) { int root = uf_find(g); if (!seen[root]) { seen[root] = 1; reps[nreps++] = g; } }
    free(seen);
    /* sanity: identity class is {0} */
    for (int g = 1; g < N; g++) if (uf_find(g) == uf_find(0)) { fprintf(stderr, "identity not fixed?\n"); exit(2); }
}

/* generic (table) groups: no automorphisms, all elements are reps */
static void build_reps_all(void) {
    naut = 0;
    reps = malloc(N * sizeof(int)); nreps = 0; for (int g = 1; g < N; g++) reps[nreps++] = g;
}

/* stabiliser of x: list of permutations (as uint16 arrays of length N) of the automorphisms fixing x, identity excluded */
static uint16_t *Pm; static int nPm;
static void build_stab(int x) {
    nPm = 0;
    if (naut == 0) return;
    int cnt = 0; for (int t = 0; t < naut; t++) if (aut_apply(t, x) == x && !(au[t] == 1 && ac[t] == 0)) cnt++;
    free(Pm); Pm = malloc((size_t)(cnt > 0 ? cnt : 1) * N * 2);
    for (int t = 0; t < naut; t++) {
        if (!(aut_apply(t, x) == x && !(au[t] == 1 && ac[t] == 0))) continue;
        uint16_t *P = Pm + (size_t)nPm * N;
        for (int g = 0; g < N; g++) P[g] = (uint16_t)aut_apply(t, g);
        nPm++;
    }
}
/* is {y,z} (y<z) the least pair of its orbit under the stabiliser? */
static inline int canonical(int y, int z) {
    for (int t = 0; t < nPm; t++) {
        const uint16_t *P = Pm + (size_t)t * N;
        int p = P[y], q = P[z]; if (p > q) { int tmp = p; p = q; q = tmp; }
        if (p < y || (p == y && q < z)) return 0;
    }
    return 1;
}
int main(int argc, char **argv) {
    if (argc < 6) { fprintf(stderr, "usage: exh meta M K R LIMIT TAG MAXSEC [D] | exh tab FILE LIMIT TAG MAXSEC [D]\n"); return 2; }
    int a = 1, meta = 0;
    if (!strcmp(argv[a], "meta")) { meta = 1; int mm = atoi(argv[a + 1]), kk = atoi(argv[a + 2]), rr = atoi(argv[a + 3]); a += 4; load_meta(mm, kk, rr); }
    else { load_tab(argv[a + 1]); a += 2; }
    long LIMIT = atol(argv[a]); snprintf(tag, sizeof tag, "%s", argv[a + 1]); double MAXSEC = atof(argv[a + 2]);
    if (argc > a + 3) D = atoi(argv[a + 3]);
    setup_inv();
    setup_cosets();
    if (meta) build_reps_meta(); else build_reps_all();
    if (MAXSEC < 0) { printf("reps=%d aut=%d\n", nreps, naut); return 0; }
    Fb = malloc((size_t)2 * R * 8); NFb = malloc((size_t)2 * R * 8); Vb = malloc((size_t)2 * R * 8);

    /* state: next representative index, best cost, evals, seconds, done.  Bound starts at LIMIT. */
    char spath[600], hpath[600];
    snprintf(spath, sizeof spath, "state/%s.txt", tag);
    snprintf(hpath, sizeof hpath, "hits/%s.txt", tag);
    int start = 0, done = 0; long best = LIMIT; long long ev_prev = 0; double secs_prev = 0;
    FILE *sf = fopen(spath, "r");
    if (sf) {
        int nx, dn; long bb; long long ev; double sc;
        if (fscanf(sf, "next %d best %ld evals %lld secs %lf done %d", &nx, &bb, &ev, &sc, &dn) == 5) { start = nx; best = bb; ev_prev = ev; secs_prev = sc; done = dn; }
        fclose(sf);
    }
    if (done) { printf("ALREADY DONE tag=%s min=%ld\n", tag, best); return 0; }
    FILE *hf = fopen(hpath, "a");
    double t0 = now();
    printf("exh tag=%s N=%d nH=%d R=%d reps=%d start_rep=%d bound=%ld D=%d\n", tag, N, nH, R, nreps, start, best, D);
    fflush(stdout);
    int ri = start; int wr[5] = {0,0,0,0,0};
    for (; ri < nreps; ri++) {
        int x = reps[ri];
        long long ev0 = evals; long before = best; long long skipped = 0, canon = 0;
        build_stab(x);
        for (int y = 1; y < N; y++) {
            if (y == x) continue;
            for (int z = y + 1; z < N; z++) {
                if (z == x) continue;
                if (!canonical(y, z)) { skipped++; continue; }
                canon++;
                volt[0] = 0; volt[1] = x; volt[2] = y; volt[3] = z;
                for (int i = 0; i < 4; i++) vinv[i] = INV[volt[i]];
                long c = cost(best);
                if (c <= best) {
                    int S[4] = { 0, x, y, z };
                    if (hf && c <= 6) fprintf(hf, "%ld 0 %d %d %d\n", c, x, y, z);
                    if (c < best) { best = c; printf("IMPROVED rep=%d cost=%ld S={0,%d,%d,%d}\n", ri, c, x, y, z); fflush(stdout); }
                    if (c <= 4 && !wr[c]) {          /* one edge list per small cost value */
                        wr[c] = 1; char ep[600]; snprintf(ep, sizeof ep, "out/%s_c%ld.edges", tag, c);
                        write_edges(ep, S); printf("WROTE cost=%ld S={0,%d,%d,%d} %s\n", c, x, y, z, ep); fflush(stdout);
                    }
                }
            }
        }
        if (hf) fflush(hf);
        printf("rep %d/%d x=%d stab=%d best=%ld (was %ld) canon_pairs=%lld rep_evals=%lld total=%lld t=%.1f\n", ri + 1, nreps, x, nPm, best, before,
               canon, evals - ev0, evals, now() - t0); fflush(stdout);
        FILE *o = fopen(spath, "w");
        if (o) { fprintf(o, "next %d best %ld evals %lld secs %.1f done %d\n", ri + 1, best, ev_prev + evals, secs_prev + (now() - t0), ri + 1 == nreps); fclose(o); }
        if (now() - t0 > MAXSEC && ri + 1 < nreps) { ri++; break; }
    }
    if (hf) fclose(hf);
    if (ri >= nreps) printf("DONE tag=%s N=%d min=%ld (exact over all %d reps, evals=%lld)\n", tag, N, best, nreps, evals);
    else printf("PAUSED tag=%s next_rep=%d best=%ld evals=%lld\n", tag, ri, best, evals);
    fflush(stdout);
    return 0;
}
