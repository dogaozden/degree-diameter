/* exh: exhaustive certification of Haar graphs H(G,S) of diameter D (D odd), |S| = 4, over a metacyclic group
 * G = Z_m x|_r Z_k (element a + m*j, product (a,j)(b,l) = (a + r^j b, j + l)) or a table group (tab FILE.bin).
 *
 * Graph: vertices (g,A) = g and (g,B) = N + g; edges (g,A) ~ (s g,B) for s in S (left multiplication, as flift).
 * Right translation is transitive on each side, so the diameter is decided by the two roots (e,A), (e,B).
 * Cost (haar_gen3 convention, D odd):  sum over the two roots u of #(vertices on the side of u not within D-1 of
 * the root).  Cost 0 iff diam <= D.  It is exact: cost(lim) returns a value > lim (a partial sum) when it exceeds lim.
 *
 * Symmetry used (both exact):
 *  (1) H(G,S) = H(G, d S c^-1) for all d, c in G (map (g,A) -> (c g, A), (g,B) -> (d c g... ), so S can be taken to
 *      contain e; this is the volt[0] = e normalisation.
 *  (2) H(G,S) = H(G, sigma(S)) for sigma in Aut(G).  The automorphisms used are generated by verified maps
 *      (a,j) -> (u a, j) (u a unit) and, when they are automorphisms, (a,j) -> (a + c S_j, j), S_j = sum_{i<j} r^i.
 *      x runs over one representative of every orbit on G \ {e}; y < z run over all remaining pairs.
 *      Every 4-set {e,x,y,z} (with e in S) is mapped to one with x a representative, so the search is exhaustive.
 *
 * Usage: exh meta M K R | exh tab FILE.bin ,  then:  LIMIT TAG MAXSEC [D]
 *   LIMIT: initial bound (only sets with cost <= LIMIT are recorded; the search is exact below it), TAG: name of files
 *   in ./state, ./hits, ./out, MAXSEC: wall seconds for this call (state is saved after every representative, so a
 *   call resumes where the last one stopped).  Prints "DONE" with the exact minimum when every representative is done.
 */
#include <stdio.h>
#include <stdlib.h>
#include <stdint.h>
#include <string.h>
#include <time.h>
#include <errno.h>

#define MAXR 4096
static int N, D = 9, nH, R;
static uint16_t *MT; static int *INV;
static int *POS;
static uint64_t HMASK;
static int16_t *RMAP; static int8_t *ROT;
static uint64_t *Fb, *NFb, *Vb;
static long long evals;
static char tag[256];
static int M_, K_, R_;

static inline int mul(int x, int y) { return MT[(size_t)x * N + y]; }
static double now(void) { struct timespec t; clock_gettime(CLOCK_MONOTONIC, &t); return t.tv_sec + 1e-9 * t.tv_nsec; }

static void load_meta(int mm, int kk, int rr) {
    M_ = mm; K_ = kk; R_ = rr;
    N = mm * kk; MT = malloc((size_t)N * N * 2);
    long *rp = malloc(kk * sizeof(long)); rp[0] = 1 % mm; for (int j = 1; j < kk; j++) rp[j] = rp[j - 1] * rr % mm;
    for (int j = 0; j < kk; j++) for (int a = 0; a < mm; a++) for (int l = 0; l < kk; l++) for (int bb = 0; bb < mm; bb++)
        MT[(size_t)(a + mm * j) * N + bb + mm * l] = (uint16_t)((a + rp[j] * bb) % mm + mm * ((j + l) % kk));
    free(rp);
}

static void load_tab(const char *p) {
    FILE *f = fopen(p, "rb"); int32_t n32;
    if (!f || fread(&n32, 4, 1, f) != 1) { fprintf(stderr, "cannot read %s\n", p); exit(2); }
    N = n32; MT = malloc((size_t)N * N * 2);
    if (fread(MT, 2, (size_t)N * N, f) != (size_t)N * N) { fprintf(stderr, "short table\n"); exit(2); }
    fclose(f);
}

static void setup_inv(void) {
    INV = malloc(N * sizeof(int));
    for (int g = 0; g < N; g++) { INV[g] = -1; for (int h = 0; h < N; h++) if (mul(g, h) == 0) { INV[g] = h; break; } if (INV[g] < 0) { fprintf(stderr, "no inverse\n"); exit(2); } }
    for (int g = 0; g < N; g++) if (mul(0, g) != g || mul(g, 0) != g) { fprintf(stderr, "identity must be index 0\n"); exit(2); }
}

/* coset structure (as flift): elements = rep_r * h^t, h of order nH <= 64, bit t of row r */
static void setup_cosets(void) {
    int best = 1, bh = 0;
    for (int g = 0; g < N; g++) { int x = g, o = 1; while (x != 0 && o <= N) { x = mul(x, g); o++; }
        for (int dv = 64; dv > best; dv--) if (o % dv == 0) { int e = o / dv, hh = 0; for (int u = 0; u < e; u++) hh = mul(hh, g); best = dv; bh = hh; break; } }
    nH = best; R = N / nH; if (R > MAXR) { fprintf(stderr, "too many rows %d\n", R); exit(2); }
    HMASK = nH == 64 ? ~0ULL : ((1ULL << nH) - 1);
    int *HP = malloc(nH * sizeof(int)); HP[0] = 0; for (int t = 1; t < nH; t++) HP[t] = mul(HP[t - 1], bh);
    POS = malloc(N * sizeof(int)); for (int g = 0; g < N; g++) POS[g] = -1;
    int *REP = malloc(R * sizeof(int));
    int r = 0; for (int g = 0; g < N; g++) if (POS[g] < 0) { REP[r] = g; for (int t = 0; t < nH; t++) POS[mul(g, HP[t])] = r * 64 + t; r++; }
    if (r != R) { fprintf(stderr, "coset error\n"); exit(2); }
    RMAP = malloc((size_t)N * R * 2); ROT = malloc((size_t)N * R);
    for (int g = 0; g < N; g++) for (int q = 0; q < R; q++) { int p = POS[mul(g, REP[q])]; RMAP[(size_t)g * R + q] = p >> 6; ROT[(size_t)g * R + q] = p & 63; }
    free(HP); free(REP);
}

static inline uint64_t rotl(uint64_t x, int s) { if (!s) return x; return ((x << s) | (x >> (nH - s))) & HMASK; }

/* the 4 voltages of the dipole: volt[0] = e (fixed), volt[1..3] = x, y, z; inv[i] = inverse */
static int volt[4], vinv[4];

/* cost with early exit above lim: root u in {0,1}, levels 1..D-1, own-side unreached count */
static long cost(long lim) {
    evals++;
    long c = 0;
    size_t BR = (size_t)2 * R;
    for (int u = 0; u < 2; u++) {
        memset(Fb, 0, BR * 8); memset(Vb, 0, BR * 8);
        int p0 = POS[0];
        Fb[(size_t)u * R + (p0 >> 6)] = 1ULL << (p0 & 63); Vb[(size_t)u * R + (p0 >> 6)] = Fb[(size_t)u * R + (p0 >> 6)];
        uint64_t *F = Fb, *NF = NFb, *V = Vb;
        for (int lev = 1; lev <= D - 1; lev++) {
            memset(NF, 0, BR * 8);
            /* side 0 -> side 1 with volt g, side 1 -> side 0 with volt g^-1 */
            for (int i = 0; i < 4; i++) {
                int g = volt[i];
                const uint64_t *F0 = F; uint64_t *N1 = NF + R;
                const int16_t *rm = RMAP + (size_t)g * R; const int8_t *ro = ROT + (size_t)g * R;
                for (int rr = 0; rr < R; rr++) if (F0[rr]) N1[rm[rr]] |= rotl(F0[rr], ro[rr]);
                int gi = vinv[i];
                const uint64_t *F1 = F + R; uint64_t *N0 = NF;
                const int16_t *rm2 = RMAP + (size_t)gi * R; const int8_t *ro2 = ROT + (size_t)gi * R;
                for (int rr = 0; rr < R; rr++) if (F1[rr]) N0[rm2[rr]] |= rotl(F1[rr], ro2[rr]);
            }
            for (size_t q = 0; q < BR; q++) { NF[q] &= ~V[q]; V[q] |= NF[q]; }
            uint64_t *t = F; F = NF; NF = t;
        }
        long reached = 0; for (int rr = 0; rr < R; rr++) reached += __builtin_popcountll(V[(size_t)u * R + rr]);
        c += (long)N - reached;
        if (c > lim) return c;
    }
    return c;
}

/* graph edges of H(G,S) for S = {e, x, y, z}: (g,A)=g ~ (s g,B)=N+s g */
static void write_edges(const char *path, const int *S) {
    FILE *f = fopen(path, "w"); if (!f) { perror(path); exit(2); }
    fprintf(f, "%d\n", 2 * N);
    for (int i = 0; i < 4; i++) for (int g = 0; g < N; g++) fprintf(f, "%d %d\n", g, N + mul(S[i], g));
    fclose(f);
}

