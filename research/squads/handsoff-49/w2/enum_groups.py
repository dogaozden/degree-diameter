"""Enumerate metacyclic groups Z_m x|_r Z_k with m*k = N in [LO, HI], one r per cyclic subgroup <r> of units (r^k = 1).
Writes lines: N m k r  (r = smallest generator-representative of the subgroup, r != 1 unless ABELIAN=1)."""
import sys, math, os
LO, HI = int(sys.argv[1]), int(sys.argv[2])
INCL_ABELIAN = os.environ.get("ABELIAN", "0") == "1"
out = []
for N in range(LO, HI + 1):
    for m in range(1, N + 1):
        if N % m: continue
        k = N // m
        units = [u for u in range(1, m) if math.gcd(u, m) == 1] if m > 1 else [0]
        # cyclic subgroups of units with order dividing k
        seen = set()
        for r in units:
            if m == 1: continue
            if pow(r, k, m) != 1 % m: continue
            # subgroup generated by r
            sub = set(); x = 1 % m
            while True:
                sub.add(x); x = x * r % m
                if x == 1 % m: break
            key = frozenset(sub)
            if key in seen: continue
            seen.add(key)
            if r == 1 % m:
                if not INCL_ABELIAN: continue
            out.append((N, m, k, r))
        if INCL_ABELIAN and m > 1:
            pass
print(len(out), file=sys.stderr)
for t in out:
    print(*t)
