"""List metacyclic groups meta:m:k:r (Z_m x|_r Z_k, r^k = 1 mod m, one r per cyclic subgroup <r>, r != 1) of order N in [lo, hi].
Usage: python3 gen_meta.py lo hi  -> prints 'N meta:m:k:r'"""
import sys
from math import gcd
lo, hi = int(sys.argv[1]), int(sys.argv[2])
for N in range(lo, hi + 1):
    seen = set()
    for m in range(2, N + 1):
        if N % m: continue
        k = N // m
        if m < 3: continue
        units = [r for r in range(2, m) if gcd(r, m) == 1] if m > 2 else []
        subs = set()
        for r in units:
            if pow(r, k, m) != 1 % m or r == 1: continue
            # cyclic subgroup generated by r
            S = frozenset(pow(r, t, m) for t in range(k) if True) if False else None
            cyc = []
            x = 1
            while True:
                x = x * r % m
                cyc.append(x)
                if x == 1: break
            key = frozenset(cyc)
            if key in subs: continue
            subs.add(key)
            print(N, f"meta:{m}:{k}:{r}")
