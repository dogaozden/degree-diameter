#!/usr/bin/env python3
"""Classify the uncovered elements (holes) of an EVAL output of haar_big0 (SL(2,p) x Z_n, ORBIT k=3).

usage: holes.py EVALFILE p n
Parses lines 'uncovered <index> mat(a,b,c,d) z=Z [(B side)]'. Side A = first list (cost1), side B = second list.
"""
import sys, re, math
from collections import Counter

def load(fn):
    out = []
    for line in open(fn):
        m = re.match(r"uncovered (\d+) mat\((-?\d+),(-?\d+),(-?\d+),(-?\d+)\) z=(-?\d+)( \(B side\))?", line.strip())
        if m:
            idx = int(m.group(1)); a, b, c, d = (int(m.group(i)) for i in range(2, 6)); z = int(m.group(6))
            out.append(dict(idx=idx, M=(a, b, c, d), z=z, side='B' if m.group(7) else 'A'))
    return out

def mmul(x, y, p):
    a, b, c, d = x; e, f, g, h = y
    return ((a*e + b*g) % p, (a*f + b*h) % p, (c*e + d*g) % p, (c*f + d*h) % p)

def minv(x, p):
    a, b, c, d = x
    return (d % p, (-b) % p, (-c) % p, a % p)

def morder(x, p):
    I = (1, 0, 0, 1); y = x; k = 1
    while y != I:
        y = mmul(y, x, p); k += 1
        if k > 4 * p + 10: return -1
    return k

def ordn(z, n):
    return n // math.gcd(z, n) if n > 1 else 1

def run(fn, p, n):
    H = load(fn)
    # alpha: conjugation by g = [[0,-1],[1,-1]] (order 3); z -> r z with r of order 3 mod n, fewest fixed points
    g = (0, p - 1, 1, p - 1); gi = minv(g, p)
    best = None
    for r in range(2, n):
        if n > 1 and math.gcd(r, n) == 1 and pow(r, 3, n) == 1 % n:
            fx = math.gcd(r - 1, n)
            if best is None or fx < best[1]: best = (r, fx)
    AR = best[0] if best else 1
    if n == 1: AR = 1
    def alpha(x):
        M, z = x
        return (mmul(mmul(g, M, p), gi, p), (AR * z) % n if n > 1 else 0)
    holes = {(h['M'], h['z'], h['side']) for h in H}
    holes_any = {(h['M'], h['z']) for h in H}
    print(f"# file {fn}\n# p={p} n={n} alpha: z->{AR} z (fixed z: {math.gcd(AR-1, n) if n>1 else 1}), #holes listed={len(H)}")
    sideA = [h for h in H if h['side'] == 'A']; sideB = [h for h in H if h['side'] == 'B']
    print(f"# side A (cost1) {len(sideA)}, side B (H(G,S^-1)) {len(sideB)}")
    # invariance under alpha and inversion, per side
    for lab, L in (('A', sideA), ('B', sideB)):
        S = {(h['M'], h['z']) for h in L}
        na = sum(1 for (M, z) in S if alpha((M, z)) in S)
        ninv = sum(1 for (M, z) in S if (minv(M, p), (-z) % n if n > 1 else 0) in S)
        ninv_other = sum(1 for (M, z) in S if (minv(M, p), (-z) % n if n > 1 else 0) in ({(q['M'], q['z']) for q in (sideB if lab=='A' else sideA)}))
        print(f"# side {lab}: alpha-closed {na}/{len(S)}, inverse in same side {ninv}/{len(S)}, inverse in other side {ninv_other}")
    rows = []
    for h in H:
        M, z = h['M'], h['z']
        tr = (M[0] + M[3]) % p
        cen = (M[1] == 0 and M[2] == 0 and M[0] == M[3])
        sgn = ('+I' if M[0] == 1 else '-I') if cen else ''
        ordM = morder(M, p)
        ordG = ordM * ordn(z, n) // math.gcd(ordM, ordn(z, n)) if ordM > 0 else -1
        Mg = mmul(M, g, p) == mmul(g, M, p)
        zfix = (AR * z - z) % n == 0 if n > 1 else True
        fixed = Mg and zfix
        inv = (minv(M, p), (-z) % n if n > 1 else 0)
        rows.append(dict(side=h['side'], M=M, z=z, tr=tr, central=cen, sgn=sgn, ordM=ordM, ordG=ordG,
                         alphafix=fixed, commg=Mg, inv_present=any((q['M'], q['z']) == inv for q in H),
                         det=(M[0]*M[3]-M[1]*M[2]) % p))
    print("# per hole: side | M | z | tr | ordM | ordG | central | commutes_g | alpha-fixed | inverse listed")
    for r in rows:
        print(f"{r['side']} {str(r['M']):22s} z={r['z']:<4d} tr={r['tr']:<4d} ordM={r['ordM']:<4d} ordG={r['ordG']:<4d} "
              f"{r['sgn']:3s} commg={int(r['commg'])} afix={int(r['alphafix'])} inv_listed={int(r['inv_present'])} det={r['det']}")
    print("# summary")
    print(" central:", Counter((r['side'], r['sgn'], r['z'] == 0) for r in rows if r['central']))
    print(" alpha-fixed:", sum(r['alphafix'] for r in rows), " commuting with g:", sum(r['commg'] for r in rows),
          " z=0 holes:", sum(r['z'] == 0 for r in rows), " of", len(rows))
    print(" trace:", sorted(Counter(r['tr'] for r in rows).items()))
    print(" ordG:", sorted(Counter(r['ordG'] for r in rows).items()))
    print(" inverse listed:", sum(r['inv_present'] for r in rows), "of", len(rows))
    zs = sorted({r['z'] for r in rows if r['z'] != 0})
    print(" nonzero z values:", zs)
    # z classes modulo the group generated by r and -1
    if n > 1:
        orb = set(); cls = {}
        for z in range(1, n):
            if z in cls: continue
            o = set(); w = z
            for _ in range(3):
                for s in (w, (-w) % n): o.add(s)
                w = (AR * w) % n
            for s in o: cls[s] = min(o)
        print(" z-orbit reps (under <r,-1>) of holes:", Counter(cls.get(r['z'], 0) for r in rows if r['z'] != 0))
    return rows

if __name__ == '__main__':
    fn, p, n = sys.argv[1], int(sys.argv[2]), int(sys.argv[3])
    run(fn, p, n)
