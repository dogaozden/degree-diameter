def load_hex():
    q, lines, coord = hexlib.load(HEX)
    assert q == 9
    N = len(coord); lines = np.asarray(lines, dtype=np.int64)
    code = coord.astype(np.int64) @ (9 ** np.arange(7))
    assert (np.diff(code) > 0).all(), 'points not sorted by code'
    return lines, coord.astype(np.int64), code

def point_lines_of(lines, N):
    pl = np.full((N, 10), -1, np.int64); cnt = np.zeros(N, np.int64)
    for l in range(len(lines)):
        for p in lines[l]:
            pl[p, cnt[p]] = l; cnt[p] += 1
    assert (cnt == 10).all()
    return pl

def collinear_nbrs(lines, pl, N):
    """N x 90 array of the points collinear with each point (distinct from it)."""
    nb = lines[pl].reshape(N, 100)  # for each point: its 10 lines' points (incl. itself 10 times)
    out = np.empty((N, 90), np.int64)
    for p in range(N):
        row = nb[p]; row = row[row != p]
        out[p] = np.unique(row)
        assert len(out[p]) == 90, (p, len(out[p]))
    return out

def perm_from_coords(Y, code):
    """Y: N x 7 coordinate array (F_9 indices), returns the point index of each row (rows must be points)."""
    k = Y @ (9 ** np.arange(7)); j = np.searchsorted(code, k)
    assert (j < len(code)).all() and (code[np.minimum(j, len(code) - 1)] == k).all(), 'image not a point'
    return j

def frob_perm(coord, code):
    Y = FROB[coord]
    # normalise: first nonzero coordinate must be 1 (FROB fixes 1, so already normalised)
    first = np.argmax(Y != 0, axis=1)
    assert (Y[np.arange(len(Y)), first] == 1).all()
    return perm_from_coords(Y, code)

def alpha_perm(N):
    pt2line = np.loadtxt(os.path.join(Q9, 'dual_pt2line.txt'), dtype=np.int64, comments='#')
    line2pt = np.loadtxt(os.path.join(Q9, 'dual_line2pt.txt'), dtype=np.int64, comments='#')
    assert len(pt2line) == N and len(line2pt) == N
    return line2pt[pt2line]

def is_collineation(perm, lines):
    """perm maps points to points; True iff it maps every line onto a line (and is a bijection)."""
    if len(np.unique(perm)) != len(perm): return False
    key = {tuple(sorted(r)): i for i, r in enumerate(lines.tolist())}
    img = np.sort(perm[lines], axis=1)
    return all(tuple(r) in key for r in img.tolist())

def cycle_lengths(perm):
    N = len(perm); seen = np.zeros(N, bool); out = []
    for s in range(N):
        if seen[s]: continue
        c = 0; t = s
        while not seen[t]:
            seen[t] = True; t = perm[t]; c += 1
        out.append(c)
    return out

def orbits_of(gens, N):
    """orbits of the group generated by the permutations in gens (union-find). Returns orbit id per point, #orbits."""
    par = np.arange(N)
    def find(x):
        while par[x] != x:
            par[x] = par[par[x]]; x = par[x]
        return x
    for g in gens:
        for p in range(N):
            a, b = find(p), find(int(g[p]))
            if a != b: par[a] = b
    roots = np.array([find(p) for p in range(N)])
    uniq, oid = np.unique(roots, return_inverse=True)
    return oid, len(uniq)

def check_noncollinear(idx, pl, lines, N):
    """True iff no line contains two of the points in idx (and indices are distinct and in range)."""
    idx = np.asarray(list(idx), dtype=np.int64)
    if len(idx) == 0: return True
    if len(np.unique(idx)) != len(idx) or idx.min() < 0 or idx.max() >= N: return False
    mark = np.zeros(N, np.int64); mark[idx] = 1
    cnt = mark[lines].sum(axis=1)
    return bool((cnt <= 1).all())

def read_idx(path):
    out = []
    for line in open(path):
        s = line.strip()
        if not s or s.startswith('#'): continue
        out.append(int(s.split()[0]))
    return out
