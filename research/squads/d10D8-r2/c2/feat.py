#!/usr/bin/env python3
# Squad card r2-c2: cheap statistics of an orbit set S = {e} + 3 alpha-orbits in G = PSL(2,23) x Z97
# (alpha = conjugation by AQ=337, z -> 35 z) versus the z-independent duplicate rate of haar_zopt.
#
# PSL(2,23) is rebuilt exactly as build_matrix() in research/structured/haar_sym.c (G_PSL), so the element
# indices in the ZSET lines (printed by the patched haar_zopt_p) decode to the same 2x2 matrices (checked by
# validate()).  The exact duplicate count of the binding words (odd length <= 7) is reproduced with numpy
# (checked against the ZDUP line); partial counts over words of length <= 3 / <= 5 are the cheap statistics.
import os
import re
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
q, NZ, NQ, IDENT, AQ, AR = 23, 97, 6072, 253, 337, 35

# ---------------- PSL(2,23) as in haar_sym.c ----------------
inv23 = [0] + [pow(x, q - 2, q) for x in range(1, q)]


def neg(x):
    return (-x) % q


def mkey(a, b, c, d):
    if a:
        return ((a - 1) * q + b) * q + c
    return (q - 1) * q * q + (b - 1) * q + d


IDXK = {}
E = []
for t in range(q ** 3):
    a, b, c = t // (q * q), (t // q) % q, t % q
    if a:
        dd = inv23[a] * (1 + b * c) % q
    else:
        if b == 0:
            continue
        dd, c = c, neg(inv23[b])
    k = mkey(a, b, c, dd)
    if k in IDXK:
        continue
    E.append((a, b, c, dd))
    IDXK[k] = len(E) - 1
    IDXK[mkey(neg(a), neg(b), neg(c), neg(dd))] = len(E) - 1
assert len(E) == NQ and IDXK[mkey(1, 0, 0, 1)] == IDENT, (len(E), IDXK[mkey(1, 0, 0, 1)])


def mul(x, y):
    a1, b1, c1, d1 = E[x]
    a2, b2, c2, d2 = E[y]
    return IDXK[mkey((a1 * a2 + b1 * c2) % q, (a1 * b2 + b1 * d2) % q,
                     (c1 * a2 + d1 * c2) % q, (c1 * b2 + d1 * d2) % q)]


def inv(x):
    a, b, c, d = E[x]
    return IDXK[mkey(d, neg(b), neg(c), a)]


def order(x):
    o, y = 1, x
    while y != IDENT:
        y = mul(y, x)
        o += 1
    return o


def tr_cls(x):
    a, b, c, d = E[x]
    t = (a + d) % q
    return min(t, q - t)


def disc_class(x):  # Legendre symbol of tr^2 - 4: +1 split torus (order | 11), -1 non-split (order | 12), 0 unipotent/+-I
    a, b, c, d = E[x]
    v = ((a + d) ** 2 - 4) % q
    if v == 0:
        return 0
    return 1 if pow(v, (q - 1) // 2, q) == 1 else -1


EA = np.array(E, dtype=np.int64)
KEYIDX = np.full(q ** 3 + q ** 2, -1, dtype=np.int64)
for _k, _v in IDXK.items():
    KEYIDX[_k] = _v


def lmul_all(m):
    """index of M*E[x] for all x, M = E[m] (left multiplication)."""
    a1, b1, c1, d1 = E[m]
    a2, b2, c2, d2 = EA[:, 0], EA[:, 1], EA[:, 2], EA[:, 3]
    na = (a1 * a2 + b1 * c2) % q
    nb = (a1 * b2 + b1 * d2) % q
    nc = (c1 * a2 + d1 * c2) % q
    nd = (c1 * b2 + d1 * d2) % q
    key = np.where(na != 0, ((na - 1) * q + nb) * q + nc, (q - 1) * q * q + (nb - 1) * q + nd)
    return KEYIDX[key]


AQI = inv(AQ)


def aQ(x):
    return mul(mul(AQ, x), AQI)


def comm(x, y):
    return mul(mul(x, y), mul(inv(x), inv(y)))


def rmul_all(m):
    """index of E[x]*M for all x, M = E[m] (right multiplication)."""
    a2, b2, c2, d2 = E[m]
    a1, b1, c1, d1 = EA[:, 0], EA[:, 1], EA[:, 2], EA[:, 3]
    na = (a1 * a2 + b1 * c2) % q
    nb = (a1 * b2 + b1 * d2) % q
    nc = (c1 * a2 + d1 * c2) % q
    nd = (c1 * b2 + d1 * d2) % q
    key = np.where(na != 0, ((na - 1) * q + nb) * q + nc, (q - 1) * q * q + (nb - 1) * q + nd)
    return KEYIDX[key]


def closure_size(gens):
    """order of the subgroup of PSL(2,23) generated by gens (BFS by right multiplication)."""
    R = [rmul_all(g) for g in gens]
    seen = np.zeros(NQ, dtype=bool)
    seen[IDENT] = True
    frontier = np.array([IDENT], dtype=np.int64)
    while frontier.size:
        new = []
        for Rg in R:
            nxt = np.unique(Rg[frontier])
            nxt = nxt[~seen[nxt]]
            seen[nxt] = True
            new.append(nxt)
        frontier = np.unique(np.concatenate(new))
    return int(seen.sum())


# letter tables: letter u of S (u = 0 is e; u = 1+3j+i is alpha^i of orbit j)
LJ = [-1] + [(u - 1) // 3 for u in range(1, 10)]
LRP = [0] + [pow(AR, (u - 1) % 3, NZ) for u in range(1, 10)]


def tables(S):
    TF = np.zeros((10, NQ), dtype=np.int32)
    TI = np.zeros((10, NQ), dtype=np.int32)
    for u in range(10):
        a = S[u] // NZ
        TF[u] = lmul_all(a)
        TI[u] = lmul_all(inv(a))
    return TF, TI


def dp(TF, TI, L):
    """all non-backtracking words of length <= L (zdfs order): levels[t] = (Q, C, last) at depth t."""
    Q = np.array([IDENT], dtype=np.int32)
    C = np.zeros((3, 1), dtype=np.int32)
    LA = np.array([-1], dtype=np.int8)
    levels = [(Q, C, LA)]
    for t in range(L):
        Qs, Cs, Ls = [], [], []
        for u in range(10):
            m = LA != u
            Qu = Q[m]
            Cu = C[:, m].copy()
            if t % 2 == 0:
                Qn = TF[u][Qu]
                sg = 1
            else:
                Qn = TI[u][Qu]
                sg = -1
            j = LJ[u]
            if j >= 0:
                Cu[j] = (Cu[j] + sg * LRP[u]) % NZ
            Qs.append(Qn)
            Cs.append(Cu)
            Ls.append(np.full(Qn.shape[0], u, dtype=np.int8))
        Q = np.concatenate(Qs)
        C = np.concatenate(Cs, axis=1)
        LA = np.concatenate(Ls)
        levels.append((Q, C, LA))
    return levels


def dup_upto(levels, L):
    """(duplicates, words) over binding words (odd depth <= L): words minus distinct (Q, c)."""
    ks = []
    for t in range(1, L + 1, 2):
        Q, C, _ = levels[t]
        ks.append((((Q.astype(np.int64) * NZ + C[0]) * NZ + C[1]) * NZ + C[2]))
    k = np.concatenate(ks)
    return int(k.size - np.unique(k).size), int(k.size)


def closed(levels, t):
    """closed non-backtracking walks of length t from (e,A): (#Q=1, #Q=1 and zero Z-coefficient vector)."""
    Q, C, _ = levels[t]
    m = Q == IDENT
    return int(m.sum()), int((m & (C[0] == 0) & (C[1] == 0) & (C[2] == 0)).sum())


# ---------------- parsing of haar_zopt logs ----------------
def parse(path, tag):
    out = []
    cur = None
    with open(path) as f:
        for line in f:
            s = line.strip()
            m = re.match(r'ZSET rep (\d+) AQ (\d+) AR (\d+): (.*)$', s)
            if m:
                cur = dict(tag=f'{tag}:{m.group(1)}', AQ=int(m.group(2)), AR=int(m.group(3)),
                           S=[int(x) for x in m.group(4).split()])
                out.append(cur)
                continue
            m = re.match(r'ZDUP rep (\d+): words (\d+) distinct \(q,c\) (\d+) duplicate (\d+) \(([0-9.]+) %\)', s)
            if m and cur is not None:
                cur['words'] = int(m.group(2))
                cur['distinct'] = int(m.group(3))
                cur['dup'] = int(m.group(4))
                cur['dup_pct'] = float(m.group(5))
    return out


def validate(S):
    """orbit structure of S: S[1+3j+i] = alpha^i(S[1+3j]), alpha(q, z) = (AQ q AQ^-1, 35 z)."""
    if S[0] != IDENT * NZ:
        return False

    def al(x):
        return aQ(x // NZ) * NZ + (AR * (x % NZ)) % NZ
    for j in range(3):
        x0, x1, x2 = S[1 + 3 * j], S[2 + 3 * j], S[3 + 3 * j]
        if not (al(x0) == x1 and al(x1) == x2 and al(x2) == x0):
            return False
    return True


# ---------------- features ----------------
def set_features(S):
    f = {}
    L9 = [S[u] // NZ for u in range(1, 10)]     # 9 non-identity letters (Q-parts), orbit-major
    reps = [L9[0], L9[3], L9[6]]
    ords = [order(x) for x in reps]
    trs = [tr_cls(x) for x in reps]
    dcs = [disc_class(x) for x in reps]
    f['ord_sum'] = sum(ords)
    f['ord_prod'] = int(np.prod(ords))
    f['n_ord_2346'] = sum(o in (2, 3, 4, 6) for o in ords)
    f['n_invol'] = sum(o == 2 for o in ords)
    f['n_ord_36'] = sum(o in (3, 6) for o in ords)
    f['n_ord_big'] = sum(o in (11, 12, 23) for o in ords)
    f['tr_sum'] = sum(trs)
    f['n_tr0'] = sum(t == 0 for t in trs)
    f['n_nonsplit'] = sum(d == -1 for d in dcs)
    f['n_unipotent_pm'] = sum(d == 0 and t != 0 for d, t in zip(dcs, trs))
    cAQ = [order(comm(x, AQ)) for x in reps]
    f['commAQ_ord_sum'] = sum(cAQ)
    f['n_commAQ_le3'] = sum(o <= 3 for o in cAQ)
    f['n_commAQ_eq1'] = sum(o == 1 for o in cAQ)           # representative commutes with AQ
    # within-orbit products of the conjugates x, aQ(x), aQ^2(x)
    wp = []
    for x in reps:
        y1 = aQ(x)
        y2 = aQ(y1)
        for a, b in ((x, y1), (y1, y2), (y2, x)):
            wp.append(order(mul(a, b)))
            wp.append(order(mul(a, inv(b))))
    f['within_ord_sum'] = sum(wp)
    f['n_within_le3'] = sum(o <= 3 for o in wp)
    f['n_within_le4'] = sum(o <= 4 for o in wp)
    # all pairs among the 9 non-identity letters
    cm_all = cm_w = cm_x = dq = dprod = dquot = 0
    for u in range(9):
        for v in range(u + 1, 9):
            same_orbit = (u // 3) == (v // 3)
            x, y = L9[u], L9[v]
            if mul(x, y) == mul(y, x):
                cm_all += 1
                if same_orbit:
                    cm_w += 1
                else:
                    cm_x += 1
            if x == y:
                dq += 1
            if order(mul(x, y)) <= 3:
                dprod += 1
            if order(mul(x, inv(y))) <= 3:
                dquot += 1
    f['n_commute_pairs'] = cm_all
    f['n_commute_within'] = cm_w
    f['n_commute_cross'] = cm_x
    f['n_equal_letters'] = dq
    f['n_prod_ord_le3'] = dprod
    f['n_quot_ord_le3'] = dquot
    f['gen_size_letters'] = closure_size(L9)
    f['gen_size_reps'] = closure_size(reps)
    f['n_distinct_letters'] = len(set(L9))
    return f


def rankdata(x):
    x = np.asarray(x, dtype=float)
    order_ = np.argsort(x, kind='mergesort')
    ranks = np.empty(len(x))
    sx = x[order_]
    i = 0
    while i < len(x):
        j = i
        while j + 1 < len(x) and sx[j + 1] == sx[i]:
            j += 1
        ranks[order_[i:j + 1]] = (i + j) / 2 + 1
        i = j + 1
    return ranks


def spearman(x, y):
    rx, ry = rankdata(x), rankdata(y)
    if rx.std() == 0 or ry.std() == 0:
        return float('nan')
    return float(np.corrcoef(rx, ry)[0, 1])


def main():
    full_check = '--full' in sys.argv
    sets = []
    sets += parse(os.path.join(HERE, 'rand60.err'), 'r60')
    for s in (2, 3, 4, 5):
        sets += parse(os.path.join(HERE, f'run_s{s}.err'), f'ckpt{s}')
    assert len(sets) == 64, len(sets)
    rows = []
    for st in sets:
        S = st['S']
        assert len(S) == 10 and validate(S), st['tag']
        assert st['AQ'] == AQ and st['AR'] == AR
        TF, TI = tables(S)
        lv = dp(TF, TI, 6)
        dup3, w3 = dup_upto(lv, 3)
        dup5, w5 = dup_upto(lv, 5)
        r4q, r4z = closed(lv, 4)
        r6q, r6z = closed(lv, 6)
        row = dict(tag=st['tag'], dup_pct=st['dup_pct'], dup=st['dup'])
        row.update(dup3=dup3, dup5=dup5, R4_Q=r4q, R4_0=r4z, R6_Q=r6q, R6_0=r6z)
        if full_check and st['tag'] in ('ckpt3:0', 'r60:1'):
            lv7 = dp(TF, TI, 7)
            d7, w7 = dup_upto(lv7, 7)
            print(f'CHECK {st["tag"]}: dup7 {d7} of {w7} words (zopt: {st["dup"]} of {st["words"]} '
                  f'distinct {st["distinct"]}, {100.0 * st["dup"] / st["words"]:.2f} %)')
            row['dup7_check'] = d7
            del lv7
        row.update(set_features(S))
        rows.append(row)
    y = np.array([r['dup_pct'] for r in rows])
    ycheck = np.array([r['dup'] for r in rows])
    assert np.all(ycheck == np.array([r['dup'] for r in rows]))
    is_rand = np.array([r['tag'].startswith('r60') for r in rows])
    names = [k for k in rows[0] if k not in ('tag', 'dup_pct', 'dup', 'dup7_check')]
    print(f'sets {len(rows)} (random {is_rand.sum()}, checkpoints {(~is_rand).sum()}); '
          f'dup% min {y.min():.2f} median {np.median(y):.2f} max {y.max():.2f}')
    print('checkpoints dup%:', {r['tag']: r['dup_pct'] for r in rows if not r['tag'].startswith('r60')})
    res = []
    for k in names:
        x = np.array([r[k] for r in rows], dtype=float)
        rho = spearman(x, y)
        rho_r = spearman(x[is_rand], y[is_rand])
        res.append((k, rho, rho_r))
    res.sort(key=lambda t: -abs(t[1]) if not np.isnan(t[1]) else 0)
    print(f'{"feature":24s} {"rho(all 64)":>12s} {"rho(60 random)":>15s}')
    for k, rho, rho_r in res:
        print(f'{k:24s} {rho:12.3f} {rho_r:15.3f}')
    # table
    with open(os.path.join(HERE, 'features.tsv'), 'w') as fh:
        fh.write('\t'.join(['tag'] + list(rows[0].keys())[1:]) + '\n')
        for r in rows:
            fh.write('\t'.join(str(r[k]) for k in rows[0].keys()) + '\n')


if __name__ == '__main__':
    main()
