"""c5 (squad round 2): symmetric cliques in G = Cay(F_11^4, {v : D(v) non-square}), D(s,b,c,f) = s^2+3c^2+8bf.
Vertices v = (s,b,c,f) of F_11^4 (index = s*1331+b*121+c*11+f). Two vertices adjacent iff D(v-w) is a non-square.
H acts by affine maps v -> A v + t with A a similitude of D with SQUARE multiplier (automorphisms of G).
Orbits of H that are cliques are "good"; two good orbits are compatible iff every cross pair is adjacent,
which (H acting by automorphisms) reduces to checking one representative of one orbit against the other orbit."""
import numpy as np

q = 11
N = q ** 4
PW = np.array([1331, 121, 11, 1], dtype=np.int64)
_ids = np.arange(N, dtype=np.int64)
C = np.stack([(_ids // 1331) % 11, (_ids // 121) % 11, (_ids // 11) % 11, _ids % 11], axis=1)
M = np.array([[1, 0, 0, 0], [0, 0, 0, 4], [0, 0, 3, 0], [0, 4, 0, 0]], dtype=np.int64)
DV = np.einsum('ni,ij,nj->n', C, M, C) % q
SQ = {1, 3, 4, 5, 9}
SM = np.isin(DV, [2, 6, 7, 8, 10])           # adjacency to 0 (neighbours of 0, 6710 of them)
assert SM.sum() == 6710
I4 = np.eye(4, dtype=np.int64)


def idx(X):
    return (np.asarray(X) % q) @ PW


def adjrow(r):
    """bool array over all vertices: adjacency to vertex r in G."""
    return SM[idx(C - C[r])]


def is_similitude(A, mu=None):
    """A^T M A = mu M mod 11 (mu a square if None)."""
    P = (A.T @ M @ A) % q
    for m in ([mu] if mu is not None else sorted(SQ)):
        if np.array_equal(P, (m * M) % q):
            return m
    return None


def perm_affine(A, t=None):
    Y = C @ A.T
    if t is not None:
        Y = Y + t
    return idx(Y)


def reflection(w):
    """x -> x - 2 B(x,w)/B(w,w) w with B(x,y)=x^T M y (an isometry of D)."""
    w = np.asarray(w, dtype=np.int64)
    Mw = (M @ w) % q
    bw = int(w @ Mw) % q
    inv = pow(bw, q - 2, q)
    R = (I4 - 2 * inv * np.outer(w, Mw)) % q
    return R


def matpow_order(A, maxo=2000):
    P = A.copy() % q
    k = 1
    while not np.array_equal(P, I4):
        P = (P @ A) % q
        k += 1
        if k > maxo:
            return None
    return k


def orbit_labels(perms):
    """labels of the orbits of the group generated by the permutations (partition of vertices)."""
    lab = np.arange(N)
    while True:
        old = lab
        lab = lab.copy()
        for p in perms:
            lab = np.minimum(lab, lab[p])
            np.minimum.at(lab, p, lab)
        lab = lab[lab]
        if np.array_equal(lab, old):
            break
    _, oid = np.unique(lab, return_inverse=True)
    return oid


def weighted_greedy(Cm, w, rng, iters, noise=0.0):
    """randomized greedy max-weight clique on the boolean matrix Cm (n x n), weights w (n,)."""
    n = len(w)
    best, bestset = -1, None
    for _ in range(iters):
        cand = np.ones(n, dtype=bool)
        chosen = []
        tot = 0
        while cand.any():
            ci = np.nonzero(cand)[0]
            key = w[ci] * (1.0 + noise * rng.random(len(ci)))
            v = ci[np.argmax(key)]
            chosen.append(v)
            tot += w[v]
            cand &= Cm[v]
            cand[v] = False
        if tot > best:
            best, bestset = tot, chosen
    return best, bestset


def exact_max_weight_clique(Cm, w, time_nodes=2_000_000):
    """simple branch and bound (weights, bound = sum of candidate weights). Returns (weight, set, complete)."""
    n = len(w)
    order = np.argsort(-w)  # heavy first
    Cm = Cm[np.ix_(order, order)]
    w = w[order]
    best = [0, []]
    count = [0]
    complete = [True]

    def rec(cur, curw, cand):
        count[0] += 1
        if count[0] > time_nodes:
            complete[0] = False
            return
        if curw > best[0]:
            best[0] = curw
            best[1] = list(cur)
        if not cand:
            return
        cw = w[cand].sum()
        if curw + cw <= best[0]:
            return
        for k, v in enumerate(cand):
            rest = cand[k + 1:]
            if curw + w[cand[k:]].sum() <= best[0]:
                return
            newc = [u for u in rest if Cm[v, u]]
            cur.append(v)
            rec(cur, curw + w[v], newc)
            cur.pop()
            if not complete[0]:
                return

    rec([], 0, list(range(n)))
    return best[0], [int(order[i]) for i in best[1]], complete[0]
