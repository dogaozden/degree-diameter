#!/usr/bin/env python3
"""List conjugacy-class representatives of subgroups of a group given by a table file (m, then m x m table).
usage: subgroups.py GROUP [MINORD MAXORD]  -> prints: idx order ngens elements(comma list)"""
import sys
tok = open(sys.argv[1]).read().split(); m = int(tok[0])
mul = [list(map(int, tok[1 + i*m:1 + (i+1)*m])) for i in range(m)]
inv = [r.index(0) for r in mul]
lo = int(sys.argv[2]) if len(sys.argv) > 2 else 1
hi = int(sys.argv[3]) if len(sys.argv) > 3 else m
def closure(S, gens):
    H = set(S); frontier = list(H)
    while frontier:
        new = []
        for x in frontier:
            for g in gens:
                y = mul[x][g]
                if y not in H:
                    H.add(y); new.append(y)
        frontier = new
    return frozenset(H)
subs = {frozenset([0])}
bylevel = [frozenset([0])]
# all subgroups: close each known subgroup with each element
todo = [frozenset([0])]
seen = {frozenset([0])}
while todo:
    H = todo.pop()
    for g in range(m):
        if g in H: continue
        K = closure(H, [g] + list(H))  # generated by H and g
        if K not in seen:
            seen.add(K); todo.append(K)
print("total subgroups", len(seen), file=sys.stderr)
# conjugacy classes
def conj(H, g):
    return frozenset(mul[mul[g][h]][inv[g]] for h in H)
reps = []; done = set()
for H in sorted(seen, key=len):
    if H in done: continue
    cls = {conj(H, g) for g in range(m)}
    done |= cls
    if lo <= len(H) <= hi: reps.append(H)
for H in reps:
    # minimal generating count (greedy)
    gens = []; cur = frozenset([0])
    for h in sorted(H):
        if h not in cur:
            gens.append(h); cur = closure(cur, [h])
    print(len(H), len(gens), ",".join(map(str, sorted(H))))
