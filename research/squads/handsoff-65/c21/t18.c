/* t18.c: tabu search for bipartite graphs of type "1,k|1,k" (c18, card in cards.md).
 * Orbits: A0 = G (regular), A1 = G/H (|H| = k), B0 = G (regular), B1 = G/K (|K| = k); H, K cyclic of order k.
 * Blocks (double cosets, full size): A0-B0: n00 single elements s (x ~ xs); A0-B1: n01 left cosets gK (x ~ coset of xg);
 * A1-B0: n10 right cosets Hg (coset xH ~ x h g); A1-B1: n11 double cosets H g K (coset xH ~ coset of x h g, h in H).
 * Degrees: n00 + n01 = 6, k (n10 + n11) = 6, n00 + n10 = 6, k (n01 + n11) = 6 (only n11 = 0 or 1 with k=6 types).
 * Vertices: A0 x -> x; A1 coset c -> m + c; B0 y -> m + q + y; B1 coset c -> 2m + q + c; q = m / k.
 * G acts on the graph, so diameter <= 5 iff the four representatives (vertex 0 of each orbit) reach everything in <= 5.
 * cost = number of (representative, vertex) pairs at distance > 5 (same scale as mcos).
 * usage: t18 TABLE K N00,N01,N10,N11 SEED ITERS TENURE OUT [HGEN KGEN]
 *   TABLE: group table as for mcos. HGEN / KGEN: optional fixed generators of the hub subgroups (else random).
 *   Moves: change one element of S, G01, G10 or G11 to another element; change H or K to another cyclic subgroup of order k.
 *   Prints "best C step S" lines; writes OUT (edge list) when cost 0 (and at the end, the best found).
 */
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <time.h>

#define MAXM 1024
#define MAXV 2600
#define MAXSUB 2048
static int m, *T, inv_[MAXM], ord_[MAXM];
#define MUL(x, y) T[(x) * m + (y)]
static uint64_t rs = 88172645463325252ULL;
static uint64_t rnd(void) { rs ^= rs << 13; rs ^= rs >> 7; rs ^= rs << 17; return rs; }
static double now(void) { struct timespec t; clock_gettime(CLOCK_MONOTONIC, &t); return t.tv_sec + 1e-9 * t.tv_nsec; }

static int k, q, nsub;
static int subel[MAXSUB][8];                 /* elements of subgroup s (k of them) */
static int *cosl[MAXSUB];                    /* left coset index of z for subgroup s: cosl[s][z] */
static int *cosr_rep[MAXSUB];                /* representative element of each left coset */
static int nS[4] = {0, 0, 0, 0};            /* n00 n01 n10 n11 */
static int par[4][8];                        /* parameter slots: [block][i] */
static int hs = 0, ks = 0;                   /* current subgroups for H (A1) and K (B1) */
static int SAMPLE = 1 << 20, SUBS = 1 << 20; /* env SAMPLE / SUBS: random candidate values per element slot / subgroups per move (default all) */

/* inverse of a subgroup's cosets: cosets of left multiplication: zH = {z h} */
static void build_subgroup_cosets(int s) {
    int *c = malloc(sizeof(int) * m), nxt = 0;
    for (int z = 0; z < m; z++) c[z] = -1;
    cosr_rep[s] = malloc(sizeof(int) * (m / k));
    for (int z = 0; z < m; z++) if (c[z] < 0) {
        int id = nxt++; cosr_rep[s][id] = z;
        for (int i = 0; i < k; i++) c[MUL(z, subel[s][i])] = id;
    }
    cosl[s] = c;
}
/* closure of {0, x, y} under right multiplication by x and y: the subgroup <x,y> if it has at most lim elements */
static int closure2(int x, int y, int *out, int lim) {
    int els[64], n = 1, gens[2] = {x, y};
    els[0] = 0;
    for (int i = 0; i < n; i++) for (int g = 0; g < 2; g++) {
        int z = MUL(els[i], gens[g]), f = 0;
        for (int j = 0; j < n && !f; j++) if (els[j] == z) f = 1;
        if (!f) { if (n >= lim) return lim + 1; els[n++] = z; }
    }
    memcpy(out, els, sizeof(int) * n);
    return n;
}
static int subgroup_eq(const int *a, const int *b, int k_) {
    for (int i = 0; i < k_; i++) { int f = 0; for (int j = 0; j < k_; j++) if (a[i] == b[j]) f = 1; if (!f) return 0; }
    return 1;
}
static int enum_subgroups(void) {
    /* all subgroups of order k generated by two elements (cyclic and non-cyclic, e.g. S3 for k = 6);
       env CYCLIC=1 restricts to cyclic subgroups */
    int n = 0;
    if (!getenv("CYCLIC")) {
        static int tmp[64];
        for (int x = 0; x < m; x++) for (int y = 0; y < m; y++) {
            if (closure2(x, y, tmp, k) != k) continue;
            int dup = 0;
            for (int s = 0; s < n && !dup; s++) if (subgroup_eq(subel[s], tmp, k)) dup = 1;
            if (dup) continue;
            if (n >= MAXSUB) return n;
            memcpy(subel[n], tmp, sizeof(int) * k);
            n++;
        }
        return n;
    }
    /* all cyclic subgroups of order k, identified by their element sets */
    for (int g = 0; g < m; g++) {
        if (ord_[g] != k) continue;
        int e[8], x = 0;
        for (int i = 0; i < k; i++) { e[i] = x; x = MUL(x, g); }
        int dup = 0;
        for (int s = 0; s < n && !dup; s++) for (int i = 0; i < k; i++) if (subel[s][i] == g) dup = 1;
        if (dup) continue;
        if (n >= MAXSUB) break;
        memcpy(subel[n], e, sizeof(int) * k);
        n++;
    }
    return n;
}
/* graph arrays */
static int adj[MAXV][6], deg[MAXV];
static int nv;
static int overflow;
static void add_edge(int u, int v) { if (deg[u] >= 6 || deg[v] >= 6) { overflow = 1; return; } adj[u][deg[u]++] = v; adj[v][deg[v]++] = u; }
static void build(const int *P, int ps, int ks_) {
    /* P: the parameter sets for the current subgroups */
    (void)P; (void)ps; (void)ks_;
}
static int CUT = 1 << 30;   /* candidate cutoff: cost_now may return early with a partial total > CUT */
static int cost_now(void) {
    /* build adjacency from par[][] and cosets of hs (H) and ks (K) */
    int *cH = cosl[hs], *cK = cosl[ks];
    int base_A1 = m, base_B0 = m + q, base_B1 = 2 * m + q;
    nv = 2 * m + 2 * q;
    for (int v = 0; v < nv; v++) deg[v] = 0;
    overflow = 0;
    /* A0 side: S (A0-B0) and G01 (A0-B1) */
    for (int i = 0; i < nS[0]; i++) { int s = par[0][i]; for (int x = 0; x < m; x++) add_edge(x, base_B0 + MUL(x, s)); }
    for (int i = 0; i < nS[1]; i++) { int g = par[1][i]; for (int x = 0; x < m; x++) add_edge(x, base_B1 + cK[MUL(x, g)]); }
    /* A1 side: for each A1 coset c with representative x_c: G10 (B0) and G11 (B1), all h in H */
    for (int c = 0; c < q; c++) {
        int xc = cosr_rep[hs][c];
        for (int i = 0; i < nS[2]; i++) { int g = par[2][i]; for (int j = 0; j < k; j++) add_edge(base_A1 + c, base_B0 + MUL(MUL(xc, subel[hs][j]), g)); }
        for (int i = 0; i < nS[3]; i++) { int g = par[3][i]; for (int j = 0; j < k; j++) add_edge(base_A1 + c, base_B1 + cK[MUL(MUL(xc, subel[hs][j]), g)]); }
    }
    (void)cH;
    /* degree sanity */
    if (overflow) return 1 << 28;
    for (int v = 0; v < nv; v++) if (deg[v] != 6) return 1 << 28;
    { static int mark[MAXV]; static int stampc = 0;
      for (int v = 0; v < nv; v++) { stampc++; for (int a = 0; a < 6; a++) { int w = adj[v][a]; if (mark[w] == stampc) return 1 << 27; mark[w] = stampc; } } }
    /* BFS from the four representatives: 0, A1 coset of identity (0), B0 identity, B1 coset of identity */
    static int dist[MAXV], queue[MAXV];
    int srcs[4] = {0, base_A1 + 0, base_B0 + 0, base_B1 + 0};
    int total = 0;
    for (int r = 0; r < 4; r++) {
        for (int v = 0; v < nv; v++) dist[v] = -1;
        int h = 0, t = 0; queue[t++] = srcs[r]; dist[srcs[r]] = 0;
        while (h < t) {
            int x = queue[h++];
            if (dist[x] >= 5) continue;
            for (int j = 0; j < 6; j++) { int y = adj[x][j]; if (dist[y] < 0) { dist[y] = dist[x] + 1; queue[t++] = y; } }
        }
        total += nv - t;
        if (total > CUT) return total;
    }
    return total;
}
static int dist_ok_side = 0;
static int cost_with(int blk, int i, int val) {
    int old = par[blk][i];
    par[blk][i] = val;
    int c = cost_now();
    par[blk][i] = old;
    return c;
}
static void write_edges(const char *fn) {
    FILE *f = fopen(fn, "w"); if (!f) return;
    /* rebuild the current graph and write it */
    cost_now();
    fprintf(f, "%d\n", nv);
    for (int v = 0; v < nv; v++) for (int j = 0; j < 6; j++) if (adj[v][j] > v) fprintf(f, "%d %d\n", v, adj[v][j]);
    fclose(f);
}
int main(int argc, char **argv) {
    if (argc < 8) { fprintf(stderr, "usage: t18 TABLE K N00,N01,N10,N11 SEED ITERS TENURE OUT [HGEN KGEN]\n"); return 1; }
    FILE *f = fopen(argv[1], "r"); if (!f) return 1;
    if (fscanf(f, "%d", &m) != 1) return 1;
    T = malloc(sizeof(int) * m * m);
    for (int i = 0; i < m * m; i++) if (fscanf(f, "%d", &T[i]) != 1) return 1;
    fclose(f);
    k = atoi(argv[2]);
    if (sscanf(argv[3], "%d,%d,%d,%d", &nS[0], &nS[1], &nS[2], &nS[3]) != 4) return 1;
    uint64_t seed = strtoull(argv[4], 0, 10); rs ^= seed * 0x9E3779B97F4A7C15ULL; for (int i = 0; i < 10; i++) rnd();
    long iters = atol(argv[5]); int tenure = atoi(argv[6]); const char *out = argv[7];
    if (m % k) return 1;
    q = m / k;
    /* inverses and orders */
    for (int x = 0; x < m; x++) for (int y = 0; y < m; y++) if (MUL(x, y) == 0) inv_[x] = y;
    for (int x = 0; x < m; x++) { int y = x, o = 1; while (y != 0) { y = MUL(y, x); o++; } ord_[x] = o; }
    nsub = enum_subgroups();
    if (nsub == 0) { printf("no cyclic subgroups of order %d\n", k); return 0; }
    for (int s = 0; s < nsub; s++) build_subgroup_cosets(s);
    /* initial subgroups */
    hs = rnd() % nsub; ks = rnd() % nsub;
    if (argc >= 10) { int g = atoi(argv[9]); for (int s = 0; s < nsub; s++) for (int i = 0; i < k; i++) if (subel[s][i] == g) hs = s; }
    if (argc >= 11) { int g = atoi(argv[10]); for (int s = 0; s < nsub; s++) for (int i = 0; i < k; i++) if (subel[s][i] == g) ks = s; }
    /* random initial parameters */
    for (int b = 0; b < 4; b++) for (int i = 0; i < nS[b]; i++) par[b][i] = rnd() % m;
    int cur = cost_now(), best = cur;
    int bestpar[4][8]; int bh = hs, bk = ks; memcpy(bestpar, par, sizeof par);
    static long tabu_until[4][8];
    static long tabu_hk[2];
    double t0 = now();
    printf("m %d k %d q %d nsub %d start %d\n", m, k, q, nsub, cur); fflush(stdout);
    long stall = 0;
    double tlim = getenv("TLIM") ? atof(getenv("TLIM")) : 1e9;
    SAMPLE = getenv("SAMPLE") ? atoi(getenv("SAMPLE")) : 1 << 20;
    SUBS = getenv("SUBS") ? atoi(getenv("SUBS")) : 1 << 20;
    for (long it = 0; it < iters && best > 0 && now() - t0 < tlim; it++) {
        int bc = 1 << 30, bblk = -1, bi = -1, bval = -1, bsub = -1, bwhich = -1;
        int nties = 0;
        /* element moves */
        for (int b = 0; b < 4; b++) for (int i = 0; i < nS[b]; i++) {
            int old = par[b][i];
            for (int v0 = 0; v0 < m; v0++) {
                int v = (SAMPLE < m) ? (int)(rnd() % m) : v0;
                if (v == old) continue;
                int dup = 0; for (int j = 0; j < nS[b]; j++) if (j != i && par[b][j] == v) dup = 1;
                if (dup) continue;
                CUT = bc;
                int c = cost_with(b, i, v);
                int is_tabu = tabu_until[b][i] > it;
                if (is_tabu && c >= best) continue;
                if (c < bc) { bc = c; bblk = b; bi = i; bval = v; bsub = -1; nties = 1; }
                else if (c == bc && nties > 0) { nties++; if (rnd() % nties == 0) { bblk = b; bi = i; bval = v; bsub = -1; } }
            }
        }
        /* subgroup moves (H then K) */
        for (int w = 0; w < 2; w++) {
            int saved_h = hs, saved_k = ks;
            for (int s0 = 0; s0 < nsub; s0++) {
                int s = (SUBS < nsub) ? (int)(rnd() % nsub) : s0;
                if (w == 0) { if (s == saved_h) continue; hs = s; }
                else { if (s == saved_k) continue; ks = s; }
                CUT = bc;
                int c = cost_now();
                int is_tabu = tabu_hk[w] > it;
                if (is_tabu && c >= best) { hs = saved_h; ks = saved_k; continue; }
                if (c < bc) { bc = c; bblk = -1; bsub = s; bwhich = w; nties = 1; }
                else if (c == bc) { nties++; if (rnd() % nties == 0) { bblk = -1; bsub = s; bwhich = w; } }
                hs = saved_h; ks = saved_k;
            }
        }
        CUT = 1 << 30;
        if (bblk >= 0) {
            int old = par[bblk][bi];
            par[bblk][bi] = bval;
            tabu_until[bblk][bi] = it + tenure + (rnd() % 3);
            (void)old;
        } else if (bwhich == 0) { hs = bsub; tabu_hk[0] = it + tenure; }
        else if (bwhich == 1) { ks = bsub; tabu_hk[1] = it + tenure; }
        cur = cost_now();
        if (cur < best) {
            best = cur; memcpy(bestpar, par, sizeof par); bh = hs; bk = ks; stall = 0;
            printf("best %d step %ld t=%.1f\n", best, it, now() - t0); fflush(stdout);
            write_edges(out);
        } else stall++;
        /* perturbation after long stall */
        if (stall > 400) {
            stall = 0;
            for (int p = 0; p < 2; p++) { int b = rnd() % 4; if (nS[b] == 0) continue; int i = rnd() % nS[b]; par[b][i] = rnd() % m; }
            cur = cost_now();
        }
    }
    /* restore best and write */
    memcpy(par, bestpar, sizeof par); hs = bh; ks = bk;
    cost_now();
    printf("RESULT best %d time %.1f\n", best, now() - t0);
    if (best == 0) printf("SOL\n");
    write_edges(out);
    return 0;
}
