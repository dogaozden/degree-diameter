/* mlift_exh: EXHAUSTIVE minimum of the mlift_chart cost over all voltage assignments of the free (non-tree) edges
   of a k+k base (k = 2 here: 5 free voltages).  Same cost function as research/theorems/squad165/mlift_chart.c
   (uncovered (source orbit, target) pairs; 0 = lift has diameter <= 5), coverage kept as a 128-bit mask.
   Symmetry: for every automorphism phi of the voltage group G, the map g -> phi(g) on every fibre is a
   colour-preserving isomorphism between the lifts of v and of phi o v, fixing the sources (a_i, e); so the cost is
   invariant under v -> phi o v (applied to every voltage) and only one tuple per Aut(G)-orbit is evaluated.  The
   orbits are marked in a bitmap of n^(free) bits.  The `nosym` flag disables this (for testing).
   usage: mlift_exh BASE TABLE PATTERNS [out.edges | -] [nosym]
   stops at the first cost 0 (then writes out.edges, "a b colour" lines, if given).                              */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>
#include <limits.h>
#include <time.h>

int k, ne, EA[64], EB[64], col[64], n, *T, *Inv, e_id, istree[64], volt[64];
int singA[4][4][4][4], singB[4][4][4][4];
int nwA[32], wA[32][600][4], lenA[32][600], nwB[32], wB[32][600][4], lenB[32][600], endA[32][600], endB[32][600];
static int *AUT = NULL, naut = 0;   /* AUT[a * n + g] = phi_a(g) */
static inline int mul(int a, int b) { return T[a * n + b]; }
static inline int popc128(unsigned __int128 h) { return __builtin_popcountll((uint64_t)h) + __builtin_popcountll((uint64_t)(h >> 64)); }

/* same cost as mlift_chart.c; returns the exact cost if it is < bound, otherwise some value >= bound */
int cost_b(int bound) {
    int c = 0, tot = k * n;
    for (int i = 0; i < k; i++) {
        unsigned __int128 h = 0;
        for (int w = 0; w < nwA[i]; w++) { int *E = wA[i][w], x;
            if (lenA[i][w] == 2) { x = mul(Inv[volt[E[1]]], volt[E[0]]); if (endA[i][w] == i && x == e_id) continue; }
            else x = mul(Inv[volt[E[3]]], mul(volt[E[2]], mul(Inv[volt[E[1]]], volt[E[0]])));
            h |= (unsigned __int128)1 << (endA[i][w] * n + x); }
        c += tot - popc128(h);
        if (c >= bound) return c;
    }
    for (int j = 0; j < k; j++) {
        unsigned __int128 h = 0;
        for (int w = 0; w < nwB[j]; w++) { int *E = wB[j][w], x;
            if (lenB[j][w] == 2) { x = mul(volt[E[1]], Inv[volt[E[0]]]); if (endB[j][w] == j && x == e_id) continue; }
            else x = mul(volt[E[3]], mul(Inv[volt[E[2]]], mul(volt[E[1]], Inv[volt[E[0]]])));
            h |= (unsigned __int128)1 << (endB[j][w] * n + x); }
        c += tot - popc128(h);
        if (c >= bound) return c;
    }
    return c;
}
int parallel_ok(void) { for (int a = 0; a < ne; a++) for (int b = a + 1; b < ne; b++) if (EA[a] == EA[b] && EB[a] == EB[b] && volt[a] == volt[b]) return 0; return 1; }
/* proper 4-edge-colouring of the bipartite multigraph by peeling perfect matchings (augmenting paths), as mlift_chart.c */
int used[64], matchB[32], visB[32];
int aug(int a, int c) { for (int e = 0; e < ne; e++) if (!used[e] && EA[e] == a && !visB[EB[e]]) { visB[EB[e]] = 1;
        if (matchB[EB[e]] < 0 || aug(EA[matchB[EB[e]]], c)) { matchB[EB[e]] = e; return 1; } } return 0; }
void colour(void) {
    memset(used, 0, sizeof used);
    for (int c = 0; c < 4; c++) {
        for (int j = 0; j < k; j++) matchB[j] = -1;
        for (int a = 0; a < k; a++) { memset(visB, 0, sizeof visB); if (!aug(a, c)) { printf("colouring failed\n"); exit(9); } }
        for (int j = 0; j < k; j++) { col[matchB[j]] = c; used[matchB[j]] = 1; }
    }
}
/* subgroup generated by gs[0..r-1] (right multiplication closure from the identity) */
static int closure(const int *gs, int r, char *inH) {
    int q[256], h = 0, t = 0; memset(inH, 0, n); inH[e_id] = 1; q[t++] = e_id;
    while (h < t) { int x = q[h++]; for (int j = 0; j < r; j++) { int y = mul(x, gs[j]); if (!inH[y]) { inH[y] = 1; q[t++] = y; } } }
    return t;
}
static void add_aut(const int *phi) {
    AUT = realloc(AUT, sizeof(int) * (size_t)n * (naut + 1)); memcpy(AUT + (size_t)naut * n, phi, sizeof(int) * n); naut++;
}
/* all automorphisms: images of a greedy generating set, extended by BFS and checked for consistency and bijectivity */
static void compute_aut(void) {
    int gens[16], ng = 0; char inH[256];
    int sz = closure(gens, 0, inH);
    while (sz < n) { int g = 0; while (inH[g]) g++; gens[ng++] = g; sz = closure(gens, ng, inH); }
    long cand = 1; for (int j = 0; j < ng; j++) cand *= n;
    int im[16], phi[256], q[256], seenimg[256];
    for (long c = 0; c < cand; c++) {
        long cc = c; for (int j = 0; j < ng; j++) { im[j] = (int)(cc % n); cc /= n; }
        for (int x = 0; x < n; x++) phi[x] = -1;
        phi[e_id] = e_id; int h = 0, t = 0, ok = 1; q[t++] = e_id;
        while (ok && h < t) { int x = q[h++];
            for (int j = 0; j < ng && ok; j++) { int y = mul(x, gens[j]), v = mul(phi[x], im[j]);
                if (phi[y] < 0) { phi[y] = v; q[t++] = y; } else if (phi[y] != v) ok = 0; } }
        if (!ok || t != n) continue;
        memset(seenimg, 0, sizeof seenimg);
        for (int x = 0; x < n && ok; x++) { if (seenimg[phi[x]]) ok = 0; seenimg[phi[x]] = 1; }
        if (ok) add_aut(phi);
    }
}

int main(int argc, char **argv) {
    if (argc < 4) { fprintf(stderr, "usage: mlift_exh BASE TABLE PATTERNS [out.edges|-] [nosym]\n"); return 1; }
    FILE *f = fopen(argv[1], "r"); if (!f || fscanf(f, "%d", &k) != 1) return 2;
    ne = 4 * k; for (int i = 0; i < ne; i++) if (fscanf(f, "%d %d", &EA[i], &EB[i]) != 2) return 3; fclose(f);
    f = fopen(argv[2], "r"); if (!f || fscanf(f, "%d", &n) != 1) return 4;
    T = malloc(sizeof(int) * n * n); Inv = malloc(sizeof(int) * n);
    for (int i = 0; i < n * n; i++) if (fscanf(f, "%d", &T[i]) != 1) return 5; fclose(f);
    if (k * n > 128 || n > 256) { printf("k*n > 128 or n > 256\n"); return 8; }
    for (int i = 0; i < n; i++) { int ok = 1; for (int j = 0; j < n; j++) if (T[i * n + j] != j) { ok = 0; break; } if (ok) e_id = i; }
    for (int i = 0; i < n; i++) for (int j = 0; j < n; j++) if (T[i * n + j] == e_id) Inv[i] = j;
    f = fopen(argv[3], "r"); if (!f) return 6;
    char side[4]; int a1, a2, a3, a4, r, np = 0;
    while (fscanf(f, "%3s %d %d %d %d %d", side, &a1, &a2, &a3, &a4, &r) == 6) { np++; if (side[0] == 'A') singA[a1][a2][a3][a4] = (r < 4); else singB[a1][a2][a3][a4] = (r < 4); }
    fclose(f); if (np != 216) { printf("pattern file has %d lines\n", np); return 6; }
    const char *out = (argc > 4 && strcmp(argv[4], "-")) ? argv[4] : NULL;
    int nosym = argc > 5 && !strcmp(argv[5], "nosym");
    clock_t t0 = clock();
    colour();
    /* spanning tree (as mlift_chart.c) */
    int seen[64] = {0}, q[64], h = 0, t = 0; seen[0] = 1; q[t++] = 0;
    while (h < t) { int x = q[h++];
        for (int i = 0; i < ne; i++) { int a = EA[i], b = k + EB[i], y = -1;
            if (x == a && !seen[b]) y = b; else if (x == b && !seen[a]) y = a;
            if (y >= 0) { seen[y] = 1; q[t++] = y; istree[i] = 1; } } }
    if (t != 2 * k) { printf("base disconnected\n"); return 7; }
    /* nonbacktracking walks of length 2 and 4 (as mlift_chart.c) */
    for (int i = 0; i < k; i++) { nwA[i] = 0;
        for (int e1 = 0; e1 < ne; e1++) if (EA[e1] == i)
        for (int e2 = 0; e2 < ne; e2++) if (EB[e2] == EB[e1]) {
            { int w = nwA[i]++; wA[i][w][0] = e1; wA[i][w][1] = e2; lenA[i][w] = 2; endA[i][w] = EA[e2]; }
            if (e2 == e1) continue;
            for (int e3 = 0; e3 < ne; e3++) if (e3 != e2 && EA[e3] == EA[e2])
            for (int e4 = 0; e4 < ne; e4++) if (e4 != e3 && EB[e4] == EB[e3]) {
                if (singA[col[e1]][col[e2]][col[e3]][col[e4]]) continue;
                int w = nwA[i]++; wA[i][w][0] = e1; wA[i][w][1] = e2; wA[i][w][2] = e3; wA[i][w][3] = e4; lenA[i][w] = 4; endA[i][w] = EA[e4]; } } }
    for (int j = 0; j < k; j++) { nwB[j] = 0;
        for (int e1 = 0; e1 < ne; e1++) if (EB[e1] == j)
        for (int e2 = 0; e2 < ne; e2++) if (EA[e2] == EA[e1]) {
            { int w = nwB[j]++; wB[j][w][0] = e1; wB[j][w][1] = e2; lenB[j][w] = 2; endB[j][w] = EB[e2]; }
            if (e2 == e1) continue;
            for (int e3 = 0; e3 < ne; e3++) if (e3 != e2 && EB[e3] == EB[e2])
            for (int e4 = 0; e4 < ne; e4++) if (e4 != e3 && EA[e4] == EA[e3]) {
                if (singB[col[e1]][col[e2]][col[e3]][col[e4]]) continue;
                int w = nwB[j]++; wB[j][w][0] = e1; wB[j][w][1] = e2; wB[j][w][2] = e3; wB[j][w][3] = e4; lenB[j][w] = 4; endB[j][w] = EB[e4]; } } }
    int free_e[64], nf = 0; for (int i = 0; i < ne; i++) if (!istree[i]) free_e[nf++] = i;
    for (int i = 0; i < ne; i++) volt[i] = e_id;               /* tree voltages fixed to the identity */
    /* automorphisms of the voltage group */
    if (nosym) { int phi[256]; for (int x = 0; x < n; x++) phi[x] = x; add_aut(phi); }
    else compute_aut();
    /* enumerate the free voltages, one tuple per orbit */
    long total = 1; for (int j = 0; j < nf; j++) total *= n;
    uint64_t *orb = calloc((size_t)(total / 64 + 2), sizeof(uint64_t));
    int best = INT_MAX, bv[64]; memcpy(bv, volt, sizeof volt);
    int d[64] = {0}, stopped = 0; long nvalid = 0, norb = 0;
    for (long code = 0; code < total; code++) {
        if (!((orb[code >> 6] >> (code & 63)) & 1)) {
            for (int j = 0; j < nf; j++) volt[free_e[j]] = d[j];
            if (parallel_ok()) {
                nvalid++; norb++;
                int c = cost_b(best);
                if (c < best) { best = c; memcpy(bv, volt, sizeof volt); }
                for (int a = 0; a < naut; a++) { long cc = 0, p = 1;
                    for (int j = 0; j < nf; j++) { cc += (long)AUT[(size_t)a * n + d[j]] * p; p *= n; }
                    orb[cc >> 6] |= 1ULL << (cc & 63); }
                if (best == 0) { stopped = 1; break; }
            }
        }
        for (int j = 0; j < nf; j++) { if (++d[j] < n) break; d[j] = 0; }
    }
    double secs = (double)(clock() - t0) / CLOCKS_PER_SEC;
    printf("RESULT k=%d n=%d m=%d naut=%d nfree=%d valid_tuples=%ld orbits_evaluated=%ld min_cost=%d stopped_at_zero=%d time=%.2f volt=",
           k, n, k * n, naut, nf, nvalid, norb, best, stopped, secs);
    for (int i = 0; i < ne; i++) printf("%d%c", bv[i], i + 1 < ne ? ',' : '\n');
    if (out && best == 0) {
        FILE *g = fopen(out, "w");
        for (int i = 0; i < ne; i++) for (int x = 0; x < n; x++) fprintf(g, "%d %d %d\n", EA[i] * n + x, EB[i] * n + mul(bv[i], x), col[i]);
        fclose(g);
    }
    return 0;
}
