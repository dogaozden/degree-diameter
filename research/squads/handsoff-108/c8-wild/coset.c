/* coset.c: bipartite coset graphs X(G,H,HgH), G = PGL(2,q), q prime < 256.
 *
 * Vertices: side A = left cosets Hx, side B = left cosets Hy (both labelled by the left cosets of H).
 * Edge Hx ~ Hy iff x y^-1 lies in D = HgH. |H| = h, |D| = d*h, so the degree is d.
 * G acts by right multiplication on both sides (transitive on each side), so the diameter test is
 * two BFS: from an A vertex (covers A-B and A-A pairs) and from a B vertex (covers B-B pairs).
 *
 * Usage: coset q d h T mode [K seed] [LIMIT]
 *   d, h : degree and |H| (h multiple of d; |H ∩ gHg^-1| = h/d is required for a candidate)
 *   T    : target diameter. B vertices must be within T-1 of the A root, A vertices within T.
 *   mode : scan  = every double coset (in key order, at most LIMIT of them)
 *          sample = K random double cosets (seed)
 *   H = <g0> cyclic, g0 = first element (in key order) of order exactly h.
 * Output (stdout): one line per candidate: "cand <index> g <key> uncB <n> uncA <n>"
 *   uncB = B vertices at distance > T-1 from the A root (unreached counts), uncA = A vertices at distance > T.
 * Summary at the end: histogram of uncB.
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <time.h>

static int Q, Q2, Q3, NKEYS, MG;
static int invt[256];
typedef struct { int a, b, c, d; } E;

static int *labkey;   /* key -> label of its left H-coset (-1 if the key is not an invertible matrix) */
static int *stampk;   /* key -> double-coset stamp (0 = not yet assigned) */
static int *repk;     /* label -> key of a representative */
static int NL;        /* number of cosets per side = |G|/h */

static inline E dec(int key) {
    E r;
    if (key < Q3) { r.a = 1; r.b = key / Q2; r.c = (key / Q) % Q; r.d = key % Q; }
    else { int k = key - Q3; r.a = 0; r.b = 1; r.c = k / Q; r.d = k % Q; }
    return r;
}
static inline int kof(E x) {
    if (x.a) { int s = invt[x.a]; int b = x.b * s % Q, c = x.c * s % Q, d = x.d * s % Q; return b * Q2 + c * Q + d; }
    { int s = invt[x.b]; int c = x.c * s % Q, d = x.d * s % Q; return Q3 + c * Q + d; }
}
static inline E mul(E x, E y) {
    E r;
    r.a = (x.a * y.a + x.b * y.c) % Q;
    r.b = (x.a * y.b + x.b * y.d) % Q;
    r.c = (x.c * y.a + x.d * y.c) % Q;
    r.d = (x.c * y.b + x.d * y.d) % Q;
    return r;
}
static inline E einv(E x) { E r; r.a = x.d; r.b = (Q - x.b) % Q; r.c = (Q - x.c) % Q; r.d = x.a; return r; }
static int valid_key(int key) {
    E e = dec(key);
    if (key < Q3) return ((e.d - e.b * e.c) % Q + Q) % Q != 0;
    return e.c != 0;
}
static int IDKEY;

static double now(void) { struct timespec t; clock_gettime(CLOCK_MONOTONIC, &t); return t.tv_sec + 1e-9 * t.tv_nsec; }

int main(int argc, char **argv) {
    if (argc < 6) { fprintf(stderr, "usage: coset q d h T scan|sample [K seed] [LIMIT]\n"); return 2; }
    Q = atoi(argv[1]); int dg = atoi(argv[2]), h = atoi(argv[3]), T = atoi(argv[4]);
    const char *mode = argv[5];
    int K = argc > 6 ? atoi(argv[6]) : 0; unsigned seed = argc > 7 ? (unsigned)atol(argv[7]) : 108901u;
    long LIMIT = argc > 8 ? atol(argv[8]) : 1L << 60;
    Q2 = Q * Q; Q3 = Q2 * Q; NKEYS = Q3 + Q2; MG = Q3 - Q;
    if (h % dg) { fprintf(stderr, "h must be a multiple of d\n"); return 2; }
    for (int x = 1; x < Q; x++) for (int y = 1; y < Q; y++) if (x * y % Q == 1) invt[x] = y;
    IDKEY = 1;
    labkey = malloc(sizeof(int) * NKEYS);
    stampk = calloc(NKEYS, sizeof(int));
    long nvalid = 0;
    for (int k = 0; k < NKEYS; k++) { labkey[k] = -1; if (valid_key(k)) nvalid++; }
    if (nvalid != MG) { fprintf(stderr, "bad element count %ld vs %d\n", nvalid, MG); return 2; }

    /* H: cyclic <g0> (g0 = first element of order h), or with HTYPE=D the dihedral group of order h
     * generated by r (order h/2, split torus) and s = [[0,1],[nu,0]] (nu a non-square: s inverts r and
     * has non-square determinant, so H is not inside PSL and the coset graph stays connected). */
    E *H = malloc(sizeof(E) * h);
    int dihedral = getenv("HTYPE") && !strcmp(getenv("HTYPE"), "D");
    if (!dihedral) {
        int g0key = -1;
        for (int k = 0; k < NKEYS && g0key < 0; k++) {
            if (!valid_key(k)) continue;
            E g = dec(k), p = g; int ord = 1;
            while (kof(p) != IDKEY && ord < h) { p = mul(p, g); ord++; }
            if (ord == h && kof(p) == IDKEY) g0key = k;
        }
        if (g0key < 0) { fprintf(stderr, "no element of order %d\n", h); return 2; }
        E g = dec(g0key), p = dec(IDKEY); for (int i = 0; i < h; i++) { H[i] = p; p = mul(p, g); }
        fprintf(stderr, "H cyclic, g0key=%d\n", g0key);
    } else {
        int rkey = -1;
        for (int k = 0; k < NKEYS && rkey < 0; k++) {
            if (!valid_key(k)) continue;
            E g = dec(k), p = g; int ord = 1;
            while (kof(p) != IDKEY && ord < h / 2) { p = mul(p, g); ord++; }
            if (ord == h / 2 && kof(p) == IDKEY && (h / 2) > 2) rkey = k;
        }
        if (rkey < 0) { fprintf(stderr, "no element of order %d\n", h / 2); return 2; }
        int nu = -1;   /* non-square */
        for (int x = 2; x < Q && nu < 0; x++) { int pw = 1; for (int e = 0; e < (Q - 1) / 2; e++) pw = pw * x % Q; if (pw == Q - 1) nu = x; }
        E r = dec(rkey), sref; sref.a = 0; sref.b = 1; sref.c = nu; sref.d = 0;
        /* closure of <r, s> */
        int cnt = 1; H[0] = dec(IDKEY); int changed = 1;
        while (changed) {
            changed = 0;
            for (int i = 0; i < cnt; i++) {
                E gens[2] = { r, sref };
                for (int t = 0; t < 2; t++) {
                    E y = mul(H[i], gens[t]); int k = kof(y), found = 0;
                    for (int j = 0; j < cnt; j++) if (kof(H[j]) == k) { found = 1; break; }
                    if (!found) { if (cnt >= h) { fprintf(stderr, "dihedral closure larger than h\n"); return 2; } H[cnt++] = y; changed = 1; }
                }
            }
        }
        if (cnt != h) { fprintf(stderr, "dihedral closure has order %d, not %d\n", cnt, h); return 2; }
        fprintf(stderr, "H dihedral D_%d, nu=%d, rkey=%d\n", h / 2, nu, rkey);
    }

    /* left H-coset labels */
    NL = MG / h; repk = malloc(sizeof(int) * NL); int nl = 0;
    for (int k = 0; k < NKEYS; k++) {
        if (labkey[k] >= 0 || !valid_key(k)) continue;
        E z = dec(k);
        for (int i = 0; i < h; i++) labkey[kof(mul(H[i], z))] = nl;
        repk[nl++] = k;
    }
    if (nl != NL) { fprintf(stderr, "coset count mismatch %d vs %d\n", nl, NL); return 2; }

    /* double cosets HgH of size d*h: candidate list */
    int *cand = malloc(sizeof(int) * 1); long ncand = 0, capc = 0, ndc = 0, nbad = 0;
    E *tmp = malloc(sizeof(E) * (size_t)h * h); int *dk = malloc(sizeof(int) * (size_t)h * h);
    for (int k = 0; k < NKEYS; k++) {
        if (!valid_key(k) || stampk[k]) continue;
        int cid = (int)(ndc + 1); ndc++;
        E z = dec(k); int cnt = 0;
        for (int i = 0; i < h; i++) for (int j = 0; j < h; j++) {
            int kk = kof(mul(mul(H[i], z), H[j]));
            if (stampk[kk] != cid) { stampk[kk] = cid; dk[cnt++] = kk; }
        }
        if (cnt != dg * h) { nbad++; continue; }
        if (ncand == capc) { capc = capc ? 2 * capc : 1024; cand = realloc(cand, sizeof(int) * capc); }
        cand[ncand++] = k;
    }
    /* reset stamps (used as double-coset marks; BFS does not need them) */
    memset(stampk, 0, sizeof(int) * NKEYS);
    double W = 0, pw = 1; for (int l = 1; l <= T - 1; l += 2) { W += dg * pw; pw *= (double)(dg - 1) * (dg - 1); }
    fprintf(stderr, "q=%d d=%d h=%d T=%d |G|=%d N=%d lambda=%.4f  g0key=%d  double cosets=%ld (regular %ld, other sizes %ld)\n",
            Q, dg, h, T, MG, NL, W / NL, 0, ndc, ncand, nbad);

    /* order of candidates */
    long *order = malloc(sizeof(long) * (size_t)ncand);
    for (long i = 0; i < ncand; i++) order[i] = i;
    long nrun = ncand;
    if (!strcmp(mode, "sample")) {
        srand(seed);
        for (long i = ncand - 1; i > 0; i--) { long j = (long)((((unsigned long)rand() << 16) ^ (unsigned long)rand()) % (unsigned long)(i + 1)); long t = order[i]; order[i] = order[j]; order[j] = t; }
        nrun = K < ncand ? K : ncand;
    } else if (!strcmp(mode, "scan")) {
        nrun = ncand < LIMIT ? ncand : LIMIT;
    } else { fprintf(stderr, "mode must be scan or sample\n"); return 2; }

    /* BFS buffers */
    unsigned char *dist = malloc(2 * (size_t)NL);
    int *queue = malloc(sizeof(int) * 2 * (size_t)NL);
    int *labseen = calloc(NL, sizeof(int));
    E *ea = malloc(sizeof(E) * dg), *db = malloc(sizeof(E) * dg);
    long *hist = calloc(2 * (size_t)NL + 1, sizeof(long));
    long nzero = 0; double t0 = now();

    if (getenv("CHECK") && nrun > 0) {   /* graph sanity: A-B adjacency symmetric and d-regular (small cases only) */
        int g = cand[order[0]]; E z = dec(g); int cnt = 0;
        for (int i = 0; i < h; i++) for (int j = 0; j < h; j++) {
            int kk = kof(mul(mul(H[i], z), H[j]));
            if (stampk[kk] != 999999) { stampk[kk] = 999999; dk[cnt++] = kk; }
        }
        for (int i = 0; i < cnt; i++) stampk[dk[i]] = 0;
        E *da = malloc(sizeof(E) * dg), *dbb = malloc(sizeof(E) * dg); int na = 0, nb = 0;
        int *ls = calloc(NL, sizeof(int));
        for (int i = 0; i < cnt; i++) { int lab = labkey[dk[i]]; if (!ls[lab]) { ls[lab] = 1; dbb[nb++] = dec(dk[i]); } }
        memset(ls, 0, sizeof(int) * NL);
        for (int i = 0; i < cnt; i++) { E e = einv(dec(dk[i])); int lab = labkey[kof(e)]; if (!ls[lab]) { ls[lab] = 1; da[na++] = e; } }
        long bad = 0, edges = 0;
        for (int a = 0; a < NL; a++) {
            E x = dec(repk[a]);
            for (int j = 0; j < na; j++) {
                int b = labkey[kof(mul(da[j], x))]; edges++;
                int found = 0; E y = dec(repk[b]);
                for (int i = 0; i < nb; i++) if (labkey[kof(mul(dbb[i], y))] == a) { found = 1; break; }
                if (!found) bad++;
            }
        }
        fprintf(stderr, "CHECK: g=%d edges=%ld (expect %ld) asymmetric=%ld\n", g, edges, (long)NL * dg, bad);
        free(da); free(dbb); free(ls);
    }
    for (long ci = 0; ci < nrun; ci++) {
        long idx = order[ci];
        int g = cand[idx];
        E z = dec(g);
        /* rebuild D (keys) */
        int cnt = 0; int cid = (int)(ci + 7); /* any unique nonzero stamp */
        for (int i = 0; i < h; i++) for (int j = 0; j < h; j++) {
            int kk = kof(mul(mul(H[i], z), H[j]));
            if (stampk[kk] != cid) { stampk[kk] = cid; dk[cnt++] = kk; }
        }
        /* A->B steps: e in D^-1, one per left coset; B->A steps: d in D, one per left coset */
        int na = 0, nb = 0;
        for (int i = 0; i < cnt; i++) {
            E dd = dec(dk[i]);
            int lab = labkey[dk[i]];
            if (labseen[lab] != (int)(ci + 1)) { labseen[lab] = (int)(ci + 1); db[nb++] = dd; }
        }
        memset(labseen, 0, sizeof(int) * NL);
        for (int i = 0; i < cnt; i++) {
            E e = einv(dec(dk[i]));
            int lab = labkey[kof(e)];
            if (labseen[lab] != (int)(ci + 1)) { labseen[lab] = (int)(ci + 1); ea[na++] = e; }
        }
        memset(labseen, 0, sizeof(int) * NL);
        for (int i = 0; i < cnt; i++) stampk[dk[i]] = 0;
        if (na != dg || nb != dg) { fprintf(stderr, "degree error %d %d\n", na, nb); return 3; }

        /* BFS from the A root (label of identity) */
        memset(dist, 255, 2 * (size_t)NL);
        int root = labkey[IDKEY];
        long qh = 0, qt = 0;
        dist[root] = 0; queue[qt++] = root;
        while (qh < qt) {
            int v = queue[qh++]; int dv = dist[v];
            if (dv >= T) continue;
            if (v < NL) {
                E x = dec(repk[v]);
                for (int j = 0; j < dg; j++) {
                    int w = NL + labkey[kof(mul(ea[j], x))];
                    if (dist[w] == 255) { dist[w] = dv + 1; queue[qt++] = w; }
                }
            } else {
                E y = dec(repk[v - NL]);
                for (int i = 0; i < dg; i++) {
                    int w = labkey[kof(mul(db[i], y))];
                    if (dist[w] == 255) { dist[w] = dv + 1; queue[qt++] = w; }
                }
            }
        }
        long uncB = 0, uncA = 0;
        for (int l = 0; l < NL; l++) {
            if (dist[NL + l] == 255 || dist[NL + l] > T - 1) uncB++;
            if (l != root && (dist[l] == 255 || dist[l] > T)) uncA++;
        }
        hist[uncB]++;
        if (uncB == 0 && uncA == 0) nzero++;
        printf("cand %ld g %d uncB %ld uncA %ld\n", idx, g, uncB, uncA);
        fflush(stdout);
        if ((ci + 1) % 20 == 0 || ci + 1 == nrun)
            fprintf(stderr, "  %ld/%ld done, %.1f s, zero-uncovered so far: %ld\n", ci + 1, nrun, now() - t0, nzero);
    }
    fprintf(stderr, "summary: runs=%ld  diameter-ok (uncB=0 and uncA=0)=%ld\n", nrun, nzero);
    fprintf(stderr, "hist uncB:");
    for (int u = 0; u <= 2 * NL; u++) if (hist[u] && u < 400) fprintf(stderr, " %d:%ld", u, hist[u]);
    fprintf(stderr, "\n");
    return 0;
}
