/* cscreen.c (c5b-cosetscreen): screen of bipartite coset graphs X(G,H,D) over G = PSL(2,q) or PGL(2,q), q prime.
 * Built from c8-wild/coset2.c. Differences: H cyclic (C_h) or dihedral (D_{h/2}, order h) in a chosen torus class;
 * D = union of double cosets H g_i H with c_i = |H g_i H|/h left cosets each, sum c_i = d (the degree);
 * the full diameter cost also includes the B-root BFS (B-B distances), so C = uncBA + uncAA + uncBB.
 *
 * Vertices: left cosets Hx (side A) and Hy (side B), N = |G|/h per side. Edge Hx ~ Hy iff x y^-1 in D.
 * G acts transitively on each side by right multiplication, so one BFS per side covers all pairs.
 *
 * Usage: cscreen q psl htype h spec K seed
 *   q      : prime (q < 1000, q^3 keys in memory: q <= 340 fine)
 *   psl    : 1 = PSL(2,q), 0 = PGL(2,q)
 *   htype  : C = cyclic of order h, D = dihedral of order h (h even, h/2 >= 3)
 *   spec   : comma list of c_i, e.g. "5,5" (two double cosets with 5 left cosets each); must sum to d (env DEG, default 10)
 *   K seed : number of random members, RNG seed
 *   env SPLIT=1|0 : H generator in a split (1) or nonsplit (0) torus, default 1 (-1 = first found)
 *   env SDET=1|0|-1 : dihedral reflection with square / nonsquare / any determinant, default 1
 *   env DEG (10), TT (8) : degree and target diameter
 *   env CHECK=1 : symmetric-adjacency check on the first member (small cases)
 * Output (stdout), per member: "cand i reps k.. uncBA x uncAA y uncBB z C c conn 0|1 ecc e"
 *   uncBA = B vertices at distance > T-1 from the A root (unreached counted), uncAA = A vertices (not root) at
 *   distance > T from the A root, uncBB = B vertices (not root) at distance > T from the B root.
 *   C = uncBA + uncAA + uncBB is the full diameter cost (0 = diameter T); conn = 1 if the A-root BFS reaches all.
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>
#include <time.h>

static int Q, Q2, Q3, NKEYS, MG, PSLF, IDKEY;
static int invt[1024], issq[1024];
typedef struct { int a, b, c, d; } E;
static int *labkey, *stamp, *repk, NL;

static inline E dec(int key) {
    E r;
    if (key < Q3) { r.a = 1; r.b = key / Q2; r.c = (key / Q) % Q; r.d = key % Q; }
    else { int k = key - Q3; r.a = 0; r.b = 1; r.c = k / Q; r.d = k % Q; }
    return r;
}
static inline int kof(E x) {
    if (x.a) { int s = invt[x.a]; int b = x.b * s % Q, c = x.c * s % Q, d = x.d * s % Q; return b * Q2 + c * Q + d; }
    { int s = invt[x.b]; int c = x.c * s % Q, d = x.d * s % Q; return Q3 + c * Q + d; }
}
static inline E mul(E x, E y) {
    E r;
    r.a = (x.a * y.a + x.b * y.c) % Q; r.b = (x.a * y.b + x.b * y.d) % Q;
    r.c = (x.c * y.a + x.d * y.c) % Q; r.d = (x.c * y.b + x.d * y.d) % Q;
    return r;
}
static inline E einv(E x) { E r; r.a = x.d; r.b = (Q - x.b) % Q; r.c = (Q - x.c) % Q; r.d = x.a; return r; }
static inline int detk(int key) {
    E e = dec(key);
    if (key < Q3) return ((e.d - e.b * e.c) % Q + Q) % Q;
    return (Q - e.c) % Q;
}
static int valid_key(int key) {
    int det = detk(key);
    if (det == 0) return 0;
    if (PSLF && !issq[det]) return 0;
    return 1;
}
static double now(void) { struct timespec t; clock_gettime(CLOCK_MONOTONIC, &t); return t.tv_sec + 1e-9 * t.tv_nsec; }
static uint64_t rs;
static uint64_t splitmix(void) { uint64_t z = (rs += 0x9E3779B97F4A7C15ULL); z = (z ^ (z >> 30)) * 0xBF58476D1CE4E5B9ULL; z = (z ^ (z >> 27)) * 0x94D049BB133111EBULL; return z ^ (z >> 31); }

/* closure of the group generated by gens (right multiplication from the identity); -1 if larger than maxn */
static int closure(E *gens, int ng, E *out, int maxn, int *keys) {
    int cnt = 1; out[0] = dec(IDKEY); keys[0] = IDKEY;
    for (int i = 0; i < cnt; i++) for (int t = 0; t < ng; t++) {
        E y = mul(out[i], gens[t]); int k = kof(y), f = 0;
        for (int j = 0; j < cnt; j++) if (keys[j] == k) { f = 1; break; }
        if (!f) { if (cnt >= maxn) return -1; keys[cnt] = k; out[cnt++] = y; }
    }
    return cnt;
}
/* torus class of a valid element: 1 split (disc square), 0 nonsplit (disc nonsquare), -1 unipotent (disc 0) */
static int tclass(int key) {
    E e = dec(key); int det = detk(key); int t;
    if (key < Q3) t = (e.a + e.d) % Q; else t = e.d;   /* a = 0 form: trace = d */
    int disc = ((t * t - 4 * det) % Q + Q) % Q;
    if (disc == 0) return -1;
    return issq[disc] ? 1 : 0;
}

int main(int argc, char **argv) {
    if (argc < 8) { fprintf(stderr, "usage: cscreen q psl htype h spec K seed\n"); return 2; }
    Q = atoi(argv[1]); PSLF = atoi(argv[2]); char htype = argv[3][0]; int h = atoi(argv[4]);
    char *spec = argv[5]; int K = atoi(argv[6]); rs = (uint64_t)atoll(argv[7]) * 0x2545F4914F6CDD1DULL + 12345;
    int DEG = getenv("DEG") ? atoi(getenv("DEG")) : 10, T = getenv("TT") ? atoi(getenv("TT")) : 8;
    int SPLIT = getenv("SPLIT") ? atoi(getenv("SPLIT")) : 1, SDET = getenv("SDET") ? atoi(getenv("SDET")) : 1;
    Q2 = Q * Q; Q3 = Q2 * Q; NKEYS = Q3 + Q2; IDKEY = 1;
    for (int x = 1; x < Q; x++) for (int y = 1; y < Q; y++) if (x * y % Q == 1) invt[x] = y;
    for (int x = 0; x < Q; x++) issq[x] = 0;
    for (int y = 1; y < Q; y++) issq[y * y % Q] = 1;
    labkey = malloc(sizeof(int) * NKEYS); stamp = calloc(NKEYS, sizeof(int));
    long nvalid = 0;
    for (int k = 0; k < NKEYS; k++) { labkey[k] = -1; if (valid_key(k)) nvalid++; }
    MG = PSLF ? (Q3 - Q) / 2 : Q3 - Q;
    if (nvalid != MG) { fprintf(stderr, "bad element count %ld vs %d\n", nvalid, MG); return 2; }
    if (h <= 0 || MG % h) { fprintf(stderr, "h does not divide |G|\n"); return 2; }
    NL = MG / h;

    /* ---- H ---- */
    E *H = malloc(sizeof(E) * h); int *Hk = malloc(sizeof(int) * h); E *tmp = malloc(sizeof(E) * h); int *tmpk = malloc(sizeof(int) * h);
    int ok = 0;
    if (htype == 'C') {
        for (int k = 0; k < NKEYS && !ok; k++) {
            if (!valid_key(k)) continue;
            if (SPLIT >= 0 && tclass(k) != (SPLIT ? 1 : 0)) continue;
            E g = dec(k);
            int n = closure(&g, 1, tmp, h, tmpk);
            if (n == h) { memcpy(H, tmp, sizeof(E) * h); memcpy(Hk, tmpk, sizeof(int) * h); ok = 1; fprintf(stderr, "H cyclic C%d generator key %d class %d\n", h, k, tclass(k)); }
        }
    } else {
        int m = h / 2; E r; int rk = -1;
        for (int k = 0; k < NKEYS && rk < 0; k++) {
            if (!valid_key(k)) continue;
            if (SPLIT >= 0 && tclass(k) != (SPLIT ? 1 : 0)) continue;
            E g = dec(k);
            int n = closure(&g, 1, tmp, m, tmpk);
            if (n == m && m >= 3) { rk = k; r = g; }
        }
        if (rk < 0) { fprintf(stderr, "no element of order %d in the requested class\n", m); return 2; }
        for (int k = 0; k < NKEYS && !ok; k++) {
            if (!valid_key(k) || k == IDKEY) continue;
            E s = dec(k);
            if (kof(mul(s, s)) != IDKEY) continue;     /* involution */
            if (kof(mul(mul(s, r), s)) != kof(einv(r))) continue;   /* s inverts r: dihedral, not cyclic */
            if (SDET >= 0) { int sq = issq[detk(k)]; if (sq != (SDET ? 1 : 0)) continue; }
            E gens[2] = { r, s };
            int n = closure(gens, 2, tmp, h, tmpk);
            if (n == h) { memcpy(H, tmp, sizeof(E) * h); memcpy(Hk, tmpk, sizeof(int) * h); ok = 1; fprintf(stderr, "H dihedral D%d: r key %d, reflection key %d (det square %d)\n", m, rk, k, issq[detk(k)]); }
        }
        if (!ok) { fprintf(stderr, "no reflection inverting r with the requested det class\n"); return 2; }
    }
    if (!ok) { fprintf(stderr, "no H found\n"); return 2; }

    /* ---- left coset labels ---- */
    repk = malloc(sizeof(int) * NL); int nl = 0;
    for (int k = 0; k < NKEYS; k++) {
        if (labkey[k] >= 0 || !valid_key(k)) continue;
        E z = dec(k);
        for (int i = 0; i < h; i++) labkey[kof(mul(H[i], z))] = nl;
        repk[nl++] = k;
    }
    if (nl != NL) { fprintf(stderr, "coset count mismatch %d vs %d\n", nl, NL); return 2; }

    /* ---- double cosets: representative, left-coset count c = |HgH|/h ---- */
    int *dcrep = malloc(sizeof(int) * (size_t)(NKEYS / h + 16)); int *dcc = malloc(sizeof(int) * (size_t)(NKEYS / h + 16));
    long ndc = 0;
    for (int k = 0; k < NKEYS; k++) {
        if (!valid_key(k) || stamp[k]) continue;
        int id = (int)(ndc + 1); E z = dec(k); int cnt = 0;
        for (int i = 0; i < h; i++) for (int j = 0; j < h; j++) {
            int kk = kof(mul(mul(H[i], z), H[j]));
            if (stamp[kk] != id) { stamp[kk] = id; cnt++; }
        }
        if (cnt % h) { fprintf(stderr, "double coset size %d not a multiple of h\n", cnt); return 2; }
        dcrep[ndc] = k; dcc[ndc] = cnt / h; ndc++;
    }
    /* stamps are reused below with new ids: reset */
    memset(stamp, 0, sizeof(int) * NKEYS);
    int cmax = 0; for (long i = 0; i < ndc; i++) if (dcc[i] > cmax) cmax = dcc[i];
    long *cnt_c = calloc(cmax + 1, sizeof(long));
    for (long i = 0; i < ndc; i++) cnt_c[dcc[i]]++;
    /* lists per c value */
    long **lst = calloc(cmax + 1, sizeof(long *)); long *lstn = calloc(cmax + 1, sizeof(long));
    for (int c = 1; c <= cmax; c++) if (cnt_c[c]) lst[c] = malloc(sizeof(long) * cnt_c[c]);
    for (long i = 0; i < ndc; i++) lst[dcc[i]][lstn[dcc[i]]++] = i;

    {   /* connectedness-relevant summary of the type counts */
        fprintf(stderr, "q=%d PSL=%d h=%d (%s) |G|=%d N=%d  double cosets=%ld  by c:", Q, PSLF, h, htype == 'C' ? "cyclic" : "dihedral", MG, NL, ndc);
        for (int c = 1; c <= cmax; c++) if (cnt_c[c]) fprintf(stderr, " c%d:%ld", c, cnt_c[c]);
        fprintf(stderr, "\n");
    }
    /* spec */
    int spc[64], nsp = 0, sumc = 0; { char *s = strdup(spec); char *t = strtok(s, ","); while (t && nsp < 64) { spc[nsp++] = atoi(t); sumc += atoi(t); t = strtok(NULL, ","); } }
    if (sumc != DEG) { fprintf(stderr, "spec sums to %d, degree is %d\n", sumc, DEG); return 2; }
    for (int s = 0; s < nsp; s++) if (spc[s] > cmax || cnt_c[spc[s]] == 0) { fprintf(stderr, "no double coset with c=%d\n", spc[s]); return 2; }
    for (int c = 1; c <= cmax; c++) {
        int need = 0; for (int s = 0; s < nsp; s++) if (spc[s] == c) need++;
        if (need > lstn[c]) { fprintf(stderr, "spec needs %d double cosets with c=%d, only %ld exist\n", need, c, lstn[c]); return 2; }
    }
    double W = 0, pw = 1; for (int l = 1; l <= T - 1; l += 2) { W += DEG * pw; pw *= (double)(DEG - 1) * (DEG - 1); }
    double mu = NL * __builtin_exp(-W / NL);
    fprintf(stderr, "W=%.0f lambda=%.4f mu(vertex Poisson)=%.2f mu/h=%.3f spec=%s K=%d\n", W, W / NL, mu, mu / h, spec, K);

    /* ---- BFS buffers ---- */
    unsigned char *dist = malloc(2 * (size_t)NL);
    int *queue = malloc(sizeof(int) * 2 * (size_t)NL);
    int *labA = calloc(NL, sizeof(int)), *labB = calloc(NL, sizeof(int));
    int *dk = malloc(sizeof(int) * ((size_t)DEG * h + (size_t)h * h));
    E *ea = malloc(sizeof(E) * DEG), *db = malloc(sizeof(E) * DEG);
    int *chosen = malloc(sizeof(int) * (nsp + 1));
    int repkey_s[64];
    /* FIXREPS=<file>: one candidate per line, "k1 k2 ..." (double-coset representative keys), replaces random sampling */
    int fixed = getenv("FIXREPS") != NULL; int nfix = 0; int fixk[4096][16], nfixk[4096];
    if (fixed) {
        FILE *f = fopen(getenv("FIXREPS"), "r"); char line[1024];
        while (f && fgets(line, sizeof line, f) && nfix < 4096) {
            int nk = 0; char *p = line; int v, n;
            while (nk < 16 && sscanf(p, "%d%n", &v, &n) == 1) { fixk[nfix][nk++] = v; p += n; }
            if (nk == 0) continue;
            nfixk[nfix] = nk; nfix++;
        }
        if (f) fclose(f);
        K = K < nfix ? K : nfix;
        fprintf(stderr, "FIXREPS: %d candidates\n", nfix);
    }
    double t0 = now(); long nzero = 0;

    for (int ci = 0; ci < K; ci++) {
        int sid = ci + 1;
        /* choose double cosets: distinct within the sample (or fixed representatives from env FIXREPS) */
        int nch = 0;
        if (fixed) {
            if (ci >= nfix) break;
            for (int t = 0; t < nfixk[ci]; t++) repkey_s[nch++] = fixk[ci][t];
        } else
        for (int s = 0; s < nsp; s++) {
            int c = spc[s], pick; int tries = 0;
            do {
                pick = (int)(lst[c][splitmix() % (uint64_t)lstn[c]]);
                int dup = 0; for (int t = 0; t < nch; t++) if (chosen[t] == pick) dup = 1;
                if (!dup) break;
                tries++;
            } while (tries < 100000);
            chosen[nch++] = pick;
        }
        if (!fixed) for (int t = 0; t < nch; t++) repkey_s[t] = dcrep[chosen[t]];
        /* D keys */
        int cnt = 0;
        for (int t = 0; t < nch; t++) {
            E z = dec(repkey_s[t]);
            for (int i = 0; i < h; i++) for (int j = 0; j < h; j++) {
                int kk = kof(mul(mul(H[i], z), H[j]));
                if (stamp[kk] != sid) { stamp[kk] = sid; dk[cnt++] = kk; }
            }
        }
        if (cnt != DEG * h) { fprintf(stderr, "union size %d != %d\n", cnt, DEG * h); return 3; }
        /* B->A steps: one d in D per left coset (label of H d); A->B steps: inverses, one per left coset */
        int nb = 0, na = 0;
        for (int i = 0; i < cnt; i++) {
            int lab = labkey[dk[i]];
            if (labA[lab] != sid) { labA[lab] = sid; db[nb++] = dec(dk[i]); }
        }
        for (int i = 0; i < cnt; i++) {
            E e = einv(dec(dk[i])); int lab = labkey[kof(e)];
            if (labB[lab] != sid) { labB[lab] = sid; ea[na++] = e; }
        }
        if (na != DEG || nb != DEG) { fprintf(stderr, "degree error %d %d\n", na, nb); return 3; }

        if (getenv("CHECK") && ci == 0) {
            long bad = 0, edges = 0;
            for (int a = 0; a < NL; a++) {
                E x = dec(repk[a]);
                for (int j = 0; j < na; j++) {
                    int b = labkey[kof(mul(ea[j], x))]; edges++;
                    E y = dec(repk[b]); int found = 0;
                    for (int i = 0; i < nb; i++) if (labkey[kof(mul(db[i], y))] == a) { found = 1; break; }
                    if (!found) bad++;
                }
            }
            fprintf(stderr, "CHECK: edges=%ld (expect %ld) asymmetric=%ld\n", edges, (long)NL * DEG, bad);
        }

        long uncBA = 0, uncAA = 0, uncBB = 0, reach = 0, ecc = 0; int root = labkey[IDKEY];
        for (int side = 0; side < 2; side++) {
            /* side 0: BFS from the A root; side 1: BFS from the B root */
            int src = side == 0 ? root : NL + root;
            memset(dist, 255, 2 * (size_t)NL);
            long qh = 0, qt = 0;
            dist[src] = 0; queue[qt++] = src;
            while (qh < qt) {
                int v = queue[qh++]; int dv = dist[v];
                if (v < NL) {
                    E x = dec(repk[v]);
                    for (int j = 0; j < DEG; j++) {
                        int w = NL + labkey[kof(mul(ea[j], x))];
                        if (dist[w] == 255) { dist[w] = dv + 1; queue[qt++] = w; }
                    }
                } else {
                    E y = dec(repk[v - NL]);
                    for (int i = 0; i < DEG; i++) {
                        int w = labkey[kof(mul(db[i], y))];
                        if (dist[w] == 255) { dist[w] = dv + 1; queue[qt++] = w; }
                    }
                }
            }
            if (side == 0) {
                for (int l = 0; l < NL; l++) {
                    if (dist[NL + l] == 255 || dist[NL + l] > T - 1) uncBA++;
                    if (l != root && (dist[l] == 255 || dist[l] > T)) uncAA++;
                }
                reach = qt;
                ecc = dist[queue[qt - 1]];
            } else {
                if (getenv("AONLY") && uncBA + uncAA > 0) { uncBB = -1; continue; }   /* partial cost: A-root only */
                for (int l = 0; l < NL; l++) {
                    if (NL + l != src && (dist[NL + l] == 255 || dist[NL + l] > T)) uncBB++;
                }
            }
        }
        long C = uncBA + uncAA + (uncBB < 0 ? 0 : uncBB);   /* AONLY: partial when uncBB = -1 */
        if (C == 0) nzero++;
        printf("cand %d reps", ci);
        for (int t = 0; t < nch; t++) printf(" %d", repkey_s[t]);
        printf(" uncBA %ld uncAA %ld uncBB %ld C %ld conn %d ecc %ld\n", uncBA, uncAA, uncBB, C, reach == 2L * NL ? 1 : 0, ecc);
        fflush(stdout);
        if ((ci + 1) % 10 == 0 || ci + 1 == K) fprintf(stderr, "  %d/%d done, %.1f s, C=0 so far: %ld\n", ci + 1, K, now() - t0, nzero);
    }
    fprintf(stderr, "summary: K=%d C=0: %ld  time %.1f s\n", K, nzero, now() - t0);
    return 0;
}
