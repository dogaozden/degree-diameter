#!/usr/bin/env python3
# enum2.py Nlo Nhi kmin: all metacyclic Z_m x|_r Z_k (m k = N, k >= kmin), r^k = 1 mod m, gcd(r,m)=1,
# one per cyclic subgroup <r> of units (faithful or not). Prints: N m k r ord(r) m_composite fpf
import sys
from math import gcd
def factor(n):
    f = {}; p = 2
    while p * p <= n:
        while n % p == 0: f[p] = f.get(p, 0) + 1; n //= p
        p += 1
    if n > 1: f[n] = f.get(n, 0) + 1
    return f
lo, hi, kmin = int(sys.argv[1]), int(sys.argv[2]), int(sys.argv[3])
for N in range(lo, hi + 1):
    for k in range(kmin, N // 5 + 1):
        if N % k: continue
        m = N // k
        if m < 2: continue
        seen = set()
        for r in range(2, m):
            if gcd(r, m) != 1 or pow(r, k, m) != 1: continue
            # subgroup generated by r
            sub = []; x = 1
            while True:
                x = x * r % m
                sub.append(x)
                if x == 1: break
            key = frozenset(sub)
            if key in seen: continue
            seen.add(key)
            o = len(sub)
            fpf = int(all(gcd(pow(r, j, m) - 1, m) == 1 for j in range(1, k) if pow(r, j, m) != 1) and True)
            comp = int(sum(factor(m).values()) > 1)
            print(N, m, k, r, o, comp, fpf, flush=True)
