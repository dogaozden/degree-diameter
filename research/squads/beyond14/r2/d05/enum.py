# list metacyclic Z_m x|_r Z_k groups with order in [528,650]; prefer Frobenius (m prime, r of order k)
from math import gcd
def isprime(n): return n>1 and all(n%q for q in range(2,int(n**.5)+1))
out=[]
for N in range(528,651):
    for k in range(2,N):
        if N%k: continue
        m=N//k
        if m<2: continue
        for r in range(1,m):
            if gcd(r,m)!=1 or pow(r,k,m)!=1%m: continue
            # order of r mod m must divide k; faithful/Frobenius check: is r-1 unit for all j (Frobenius)
            frob = isprime(m) and all((pow(r,j,m)-1)%m for j in range(1,k))
            out.append((N,m,k,r,frob))
# dedupe by (N,m,k, subgroup generated by r): keep smallest r per cyclic subgroup
seen=set(); res=[]
for N,m,k,r,frob in out:
    key=(N,m,k,frozenset(pow(r,j,m) for j in range(k)))
    if key in seen: continue
    seen.add(key); res.append((N,m,k,r,frob))
fr=[x for x in res if x[4]]
print("total metacyclic (distinct subgroups)",len(res),"frobenius",len(fr))
for x in fr: print("F",x)
