# GF(8) = GF(2)[x]/(x^3+x+1), elements as 3-bit ints (same as hexgen2.c: a0 + 2 a1 + 4 a2)
def gmul(a, b):
    r = 0
    for i in range(3):
        if (b >> i) & 1: r ^= a << i
    for k in (4, 3):
        if (r >> k) & 1: r ^= (0b1011 << (k - 3))
    return r
INV = [0] * 8
for a in range(1, 8):
    for b in range(1, 8):
        if gmul(a, b) == 1: INV[a] = b
def mm(A, B):
    n = len(A); return [[(lambda i, j: __import__('functools').reduce(lambda s, k: s ^ gmul(A[i][k], B[k][j]), range(n), 0))(i, j) for j in range(n)] for i in range(n)]
def mpow(A, e):
    R = [[int(i == j) for j in range(3)] for i in range(3)]
    B = A
    while e:
        if e & 1: R = mm(R, B)
        B = mm(B, B); e >>= 1
    return R
def transpose_inv(A):
    # inverse of 3x3 over GF(8) by Gauss-Jordan, then transpose
    n = 3; M = [row[:] + [int(i == j) for j in range(n)] for i, row in enumerate(A)]
    for col in range(n):
        piv = next(r for r in range(col, n) if M[r][col])
        M[col], M[piv] = M[piv], M[col]
        iv = INV[M[col][col]]; M[col] = [gmul(iv, x) for x in M[col]]
        for r in range(n):
            if r != col and M[r][col]:
                fct = M[r][col]; M[r] = [M[r][j] ^ gmul(fct, M[col][j]) for j in range(2 * n)]
    Ainv = [row[n:] for row in M]
    return [[Ainv[j][i] for j in range(n)] for i in range(n)]
def normalize(v):
    for i in range(7):
        if v[i]:
            s = INV[v[i]]; return tuple(gmul(s, x) for x in v)
    return None
code_of = {}
print('stored coordinates normalized:', sum(1 for v in COORD if normalize(v) == tuple(v)), 'of', N, flush=True)
for pid, v in enumerate(COORD):
    code_of[tuple(v)] = pid
# companion matrix of an irreducible cubic t^3 + a t^2 + b t + c over GF(8) (no roots)
def has_root(a, b, c):
    return any((gmul(gmul(x, x), x) ^ gmul(a, gmul(x, x)) ^ gmul(b, x) ^ c) == 0 for x in range(8))
cub = None and next((a, b, c) for a in range(8) for b in range(8) for c in range(1, 8) if not has_root(a, b, c))
EXPS = [int(t) for t in sys.argv[1].split(',')]; TAG = sys.argv[2]
def gpow(w, e):
    r = 1
    for _ in range(e % 7): r = gmul(r, w)
    return r
GA = [[gpow(2, EXPS[0]), 0, 0], [0, gpow(2, EXPS[1]), 0], [0, 0, gpow(2, EXPS[2])]]  # diag(w^a, w^b, w^c), w = x = 2
print('exps', EXPS, 'GA diag order-7 test:', 'order-73 test GA^73 == I:', mpow(GA, 7) == [[int(i == j) for j in range(3)] for i in range(3)], 'GA!=I:', GA != [[int(i == j) for j in range(3)] for i in range(3)], flush=True)
GI = transpose_inv(GA)
# 7x7 matrix acting on coordinate column vectors: x -> g x; blocks on (0,1,2), (4,5,6), and 3 fixed
def apply(v):
    # 7x7 block action
    x = [v[0], v[1], v[2]]; y = [v[4], v[5], v[6]]
    nx = [0, 0, 0]; ny = [0, 0, 0]
    for i in range(3):
        for j in range(3):
            nx[i] ^= gmul(GA[i][j], x[j]); ny[i] ^= gmul(GI[i][j], y[j])
    return (nx[0], nx[1], nx[2], v[3], ny[0], ny[1], ny[2])
def automorphism_test(apply_fn):
    img = [0] * N
    for pid in range(N):
        w = normalize(apply_fn(COORD[pid]))
        if w is None or w not in code_of: return None
        img[pid] = code_of[w]
    if len(set(img)) != N: return None
    lmap = [0] * L
    for l in range(L):
        ps = [img[p] for p in LP[l]]
        common = set(PL[ps[0]]) & set(PL[ps[1]])
        if len(common) != 1: return None
        m = common.pop()
        if set(LP[m]) != set(ps): return None
        lmap[l] = m
    return img, lmap
res = automorphism_test(apply)
print('block diag(A, A^-T, 1) is a hexagon automorphism:', res is not None, flush=True)
