# Bi-coset graphs (non-semiregular wildcard): vertices G/A u G/B, xA ~ yB iff xA meets yB.
# A, B subgroups with |A : A∩B| = 3 (degree 3). Edge per distinct pair (xA, yB) over z in G.
# usage: coset.py SPEC NMIN NMAX [ORDER_A] [MAXB]   (ORDER_A = |A| to use: 3 (default) or 6)
import sys, os, re, subprocess, itertools
import numpy as np
sys.path.insert(0, '/home/user/degree-diameter/research/squads/b48/tools')
import groups

OUT = '/home/user/degree-diameter/research/squads/b48/r5/k12/work'

def main():
    spec = sys.argv[1]
    ordA = int(sys.argv[2]) if len(sys.argv) > 2 else 3
    T = groups.table(spec).astype(np.int64)
    G = len(T)
    inv = np.array([int(np.where(T[g] == 0)[0][0]) for g in range(G)])
    # element orders
    def order(g):
        x, o = g, 1
        while x != 0:
            x = T[x, g]; o += 1
        return o
    ords = [order(g) for g in range(G)]
    # subgroups of order ordA generated by a single element (cyclic) of order ordA
    subs = set()
    for g in range(G):
        if ords[g] == ordA:
            s = [0]; x = g
            while x != 0:
                s.append(int(x)); x = T[x, g]
            subs.add(frozenset(s))
    subs = list(subs)
    if ordA == 6:
        # also dihedral-type subgroups of order 6 generated by an order-3 and an involution
        pass
    print(f'G={G} subgroups of order {ordA}: {len(subs)}', flush=True)
    # conjugacy classes of these subgroups
    def conj(S, h):
        return frozenset(int(T[T[h, s], inv[h]]) for s in S)
    idx = {S: i for i, S in enumerate(subs)}
    seen = set(); reps = []
    for S in subs:
        if S in seen: continue
        reps.append(S)
        for h in range(G):
            seen.add(conj(S, h))
    print(f'conjugacy classes: {len(reps)}', flush=True)
    def cosets(S):
        Sl = sorted(S)
        lab = np.empty(G, dtype=np.int64)
        m = {}
        for x in range(G):
            key = min(int(T[x, a]) for a in Sl)
            if key not in m: m[key] = len(m)
            lab[x] = m[key]
        return lab, len(m)
    results = []
    best = None
    maxB = int(sys.argv[4]) if len(sys.argv) > 4 else 10**9
    cnt = 0
    for A in reps:
        labA, NA = cosets(A)
        for B in subs:
            if B == A: continue
            if len(A & B) != ordA // 3: continue
            labB, NB = cosets(B)
            # edges
            pairs = np.unique(labA * NB + labB)
            if len(pairs) != 3 * NA: continue
            cnt += 1
            if cnt > maxB: break
            ea = pairs // NB; eb = pairs % NB + NA
            n = NA + NB
            fn = f'{OUT}/c_{len(spec)}_{cnt}.edges'
            with open(fn, 'w') as f:
                f.write(f'{n}\n')
                f.write('\n'.join(f'{u} {v}' for u, v in zip(ea.tolist(), eb.tolist())))
                f.write('\n')
            r = subprocess.run(['timeout', '60', 'nice', '-n', '10', '/home/user/degree-diameter/research/squads/b48/tools/score48', fn, '3', sys.argv[3] if False else '9'], capture_output=True, text=True)
            line = [l for l in r.stdout.splitlines() if l.startswith('n=')]
            res = r.stdout.strip().splitlines()[-1]
            m_ = re.search(r'far_pairs=(\d+)', r.stdout)
            far = int(m_.group(1)) if m_ else 10**9
            key = (far, n)
            results.append((far, n, cnt))
            if best is None or key < best[:2]:
                best = (far, n, cnt, fn, res)
                print('BEST', far, n, fn, res, flush=True)
            if os.path.exists(fn) and not (best and best[3] == fn):
                os.remove(fn)
        if cnt > maxB: break
    results.sort()
    print('tested', cnt, 'top', results[:10], flush=True)

main()
