"""Group multiplication tables for lift.c (big-squad-4-8 job).

Usage: python3 groups.py SPEC OUT.bin        writes int32 N, then N*N uint16 (row g: g*h), identity = index 0
       python3 groups.py SPEC                prints N and a few facts (element orders, involutions, centre size)

SPEC grammar (spaces between tokens; "x" joins direct factors):
  cyc n                     Z_n
  meta m k r                Z_m x|_r Z_k: (a,j)(b,l) = (a + r^j b, j + l); index a + m*j; needs r^k = 1 mod m
  dih n                     dihedral group of order 2n
  semi p k a b c d          Z_p^2 x| Z_k, generator acting by the matrix [[a,b],[c,d]] mod p (its order must divide k)
  sl2 p | psl2 p | pgl2 p   2x2 matrices over Z_p (p prime): det 1 / det 1 mod +-I / invertible mod scalars
  agl1 p                    x -> a x + b over Z_p (p prime), order p(p-1)
  heis p                    3x3 upper unitriangular matrices over Z_p, order p^3
  perm n g1 ; g2 ; ...      subgroup of S_n generated by permutations, each written as n images 0..n-1 separated by
                            commas, e.g. "perm 5 1,2,3,4,0 ; 1,0,2,3,4"
  A x B                     direct product, e.g. "psl2 7 x cyc 7", "agl1 11 x cyc 10", "sl2 3 x meta 23 2 22"
Python API: table(spec) -> numpy uint16 array (N, N).
"""
import sys
import numpy as np


def _index_table(elems, mul):
    """elems: list of hashable elements with elems[0] the identity; mul: python function."""
    idx = {e: i for i, e in enumerate(elems)}
    N = len(elems)
    T = np.empty((N, N), dtype=np.uint16)
    for i, g in enumerate(elems):
        T[i] = [idx[mul(g, h)] for h in elems]
    return T


def t_cyc(n):
    a = np.arange(n)
    return ((a[:, None] + a[None, :]) % n).astype(np.uint16)


def t_meta(m, k, r):
    assert pow(r, k, m) == 1 % m, "r^k != 1 mod m"
    N = m * k
    g = np.arange(N)
    a, j = g % m, g // m
    rp = np.array([pow(r, t, m) for t in range(k)])
    A = (a[:, None] + rp[j][:, None] * a[None, :]) % m
    J = (j[:, None] + j[None, :]) % k
    return (A + m * J).astype(np.uint16)


def t_dih(n):
    return t_meta(n, 2, n - 1)


def t_semi(p, k, a, b, c, d):
    M = np.array([[a, b], [c, d]]) % p
    P = [np.eye(2, dtype=np.int64)]
    for _ in range(k):
        P.append(P[-1] @ M % p)
    assert (P[k] == np.eye(2)).all(), "matrix order does not divide k"
    N = p * p * k
    g = np.arange(N)
    x, y, j = g % p, (g // p) % p, g // (p * p)
    Pj = np.array([P[t] for t in range(k)])  # (k,2,2)
    # (v, j)(w, l) = (v + M^j w, j + l)
    Mx = Pj[j][:, 0, 0][:, None] * x[None, :] + Pj[j][:, 0, 1][:, None] * y[None, :]
    My = Pj[j][:, 1, 0][:, None] * x[None, :] + Pj[j][:, 1, 1][:, None] * y[None, :]
    X = (x[:, None] + Mx) % p
    Y = (y[:, None] + My) % p
    J = (j[:, None] + j[None, :]) % k
    return (X + p * Y + p * p * J).astype(np.uint16)


def _mat_group(p, kind):
    els = []
    for a in range(p):
        for b in range(p):
            for c in range(p):
                for d in range(p):
                    det = (a * d - b * c) % p
                    if kind in ("sl2", "psl2") and det != 1:
                        continue
                    if kind == "pgl2" and det == 0:
                        continue
                    els.append((a, b, c, d))

    def canon(m):
        a, b, c, d = m
        if kind == "sl2":
            return m
        if kind == "psl2":
            neg = ((-a) % p, (-b) % p, (-c) % p, (-d) % p)
            return min(m, neg)
        # pgl2: scale so the first nonzero entry is 1
        first = next(x for x in m if x)
        inv = pow(first, p - 2, p)
        return tuple(x * inv % p for x in m)

    reps = sorted({canon(m) for m in els})
    ident = canon((1, 0, 0, 1))
    reps.remove(ident)
    reps = [ident] + reps

    def mul(m1, m2):
        a, b, c, d = m1
        e, f, g, h = m2
        return canon(((a * e + b * g) % p, (a * f + b * h) % p, (c * e + d * g) % p, (c * f + d * h) % p))
    return reps, mul


def t_matrix(kind, p):
    reps, mul = _mat_group(p, kind)
    return _index_table(reps, mul)


def t_agl1(p):
    els = [(1, 0)] + [(a, b) for a in range(1, p) for b in range(p) if (a, b) != (1, 0)]
    return _index_table(els, lambda g, h: (g[0] * h[0] % p, (g[0] * h[1] + g[1]) % p))  # g(h(x))


def t_heis(p):
    els = [(0, 0, 0)] + [(x, y, z) for x in range(p) for y in range(p) for z in range(p) if (x, y, z) != (0, 0, 0)]
    return _index_table(els, lambda g, h: ((g[0] + h[0]) % p, (g[1] + h[1]) % p, (g[2] + h[2] + g[0] * h[1]) % p))


def t_perm(n, gens):
    gens = [tuple(g) for g in gens]
    ident = tuple(range(n))
    els = [ident]
    seen = {ident}
    i = 0
    while i < len(els):
        g = els[i]
        i += 1
        for s in gens:
            h = tuple(g[s[t]] for t in range(n))  # g after s
            if h not in seen:
                seen.add(h)
                els.append(h)
                if len(els) > 65535:
                    raise ValueError("group too large")
    P = np.array(els, dtype=np.int32)
    key = {e: i for i, e in enumerate(els)}
    N = len(els)
    T = np.empty((N, N), dtype=np.uint16)
    for i in range(N):
        comp = P[i][P]  # row h: g_i(h(t)) = (g_i o h)
        T[i] = [key[tuple(r)] for r in comp.tolist()]
    return T


def t_prod(T1, T2):
    N1, N2 = len(T1), len(T2)
    g = np.arange(N1 * N2)
    a, b = g // N2, g % N2
    return (T1[a[:, None], a[None, :]].astype(np.int64) * N2 + T2[b[:, None], b[None, :]]).astype(np.uint16)


def table(spec):
    if " x " in spec:
        parts = spec.split(" x ")
        T = table(parts[0])
        for p in parts[1:]:
            T = t_prod(T, table(p))
        return T
    tok = spec.split()
    kind = tok[0]
    if kind == "perm":
        n = int(tok[1])
        rest = " ".join(tok[2:])
        gens = [[int(x) for x in g.strip().split(",")] for g in rest.split(";") if g.strip()]
        return t_perm(n, gens)
    args = [int(x) for x in tok[1:]]
    if kind == "cyc":
        return t_cyc(*args)
    if kind == "meta":
        return t_meta(*args)
    if kind == "dih":
        return t_dih(*args)
    if kind == "semi":
        return t_semi(*args)
    if kind in ("sl2", "psl2", "pgl2"):
        return t_matrix(kind, *args)
    if kind == "agl1":
        return t_agl1(*args)
    if kind == "heis":
        return t_heis(*args)
    raise ValueError("unknown group " + spec)


def check(T):
    N = len(T)
    assert (T[0] == np.arange(N)).all() and (T[:, 0] == np.arange(N)).all(), "identity is not index 0"
    for g in np.random.default_rng(1).integers(0, N, size=min(N, 40)):
        for h in np.random.default_rng(int(g)).integers(0, N, size=min(N, 40)):
            assert (T[T[g, h]] == T[g][T[h]]).all(), "not associative"
    assert all(len(set(T[g].tolist())) == N for g in range(N)), "not a Latin square"


def write_bin(T, path):
    with open(path, "wb") as f:
        np.array([len(T)], dtype=np.int32).tofile(f)
        np.ascontiguousarray(T, dtype=np.uint16).tofile(f)


if __name__ == "__main__":
    spec = sys.argv[1]
    T = table(spec)
    check(T)
    N = len(T)
    if len(sys.argv) > 2:
        write_bin(T, sys.argv[2])
    order = []
    for g in range(N):
        x, o = g, 1
        while x != 0:
            x = int(T[x, g])
            o += 1
        order.append(o)
    centre = sum(1 for g in range(N) if (T[g] == T[:, g]).all())
    print(f"N={N} involutions={sum(1 for o in order if o == 2)} centre={centre} max_order={max(order)} spec='{spec}'")
