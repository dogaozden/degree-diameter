# metacyclic Z_m x|_r Z_k with m*k in [1250,1450], k>=12, r of order d>=3 mod m (d | k), gcd(r-1,m)<=2
from math import gcd
out = []
for m in range(2, 1451):
    for k in range(12, 1451 // m + 1):
        N = m * k
        if N < 1250 or N > 1450:
            continue
        for r in range(2, m):
            if gcd(r, m) != 1:
                continue
            # order of r mod m
            x, d = r % m, 1
            while x != 1 % m:
                x = x * r % m
                d += 1
                if d > k:
                    break
            if d > k or k % d != 0 or d < 3:
                continue
            if gcd(r - 1, m) > 2:
                continue
            # keep one representative per (m, k, d, r) up to r -> r' with same cyclic subgroup: just keep min r of the
            # subgroup generated by r (r and r^j with gcd(j,d)=1 give isomorphic groups)
            sub = set()
            y = 1
            for _ in range(d):
                sub.add(y)
                y = y * r % m
            if min(sub) != r % m and r % m != min(sub):
                pass
            if r != min(x for x in [r]):  # placeholder
                pass
            out.append((N, m, k, r, d))
# dedupe: isomorphism classes of meta m k r via subgroup <r> (r ~ r^j with gcd(j,d)=1, and generator choice of Z_k)
seen = {}
for N, m, k, r, d in out:
    key = (m, k, d, frozenset(pow(r, j, m) for j in range(1, d + 1)))
    if key not in seen:
        seen[key] = (N, m, k, r, d)
res = sorted(seen.values())
print(len(out), len(res))
for t in res:
    print(*t)
