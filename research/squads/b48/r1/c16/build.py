def mat_order(M, p):
    I = np.eye(len(M), dtype=np.int64); P = np.array(M) % p; Q = P.copy(); k = 1
    while not (Q == I).all():
        Q = Q @ P % p; k += 1
        if k > 500: return -1
    return k

def closure_mats(gens, p, cap=200):
    d = len(gens[0]); I = tuple(tuple(int(i == j) for j in range(d)) for i in range(d))
    els = {I}; frontier = [I]
    while frontier:
        nf = []
        for A in frontier:
            for g in gens:
                B = tuple(tuple(int(x) for x in (np.array(A) @ np.array(g)) % p) for _ in [0]) if False else None
                B = tuple(tuple(int(x) for x in row) for row in (np.array(A, dtype=np.int64) @ np.array(g, dtype=np.int64) % p))
                if B not in els:
                    els.add(B); nf.append(B)
                    if len(els) > cap: return None
        frontier = nf
    return els

def lin_perm_gens(p, d, mats, trans=()):
    """permutation generator strings on all p^d vectors: v -> M v + t"""
    vecs = list(itertools.product(range(p), repeat=d))
    idx = {v: i for i, v in enumerate(vecs)}
    gens = []
    for M in mats:
        gens.append([idx[tuple((sum(M[i][j] * v[j] for j in range(d)) % p) for i in range(d))] for v in vecs])
    for t in trans:
        gens.append([idx[tuple((v[i] + t[i]) % p for i in range(d))] for v in vecs])
    return len(vecs), gens

def perm_table(deg, gens):
    s = ' ; '.join(','.join(str(x) for x in g) for g in gens)
    return G.table('perm %d %s' % (deg, s))

def prod(*Ts):
    T = Ts[0]
    for U in Ts[1:]:
        T = G.t_prod(T, U)
    return T

def tab(spec):
    return G.table(spec)

def find_matrix(p, d, order, need_irreducible_like=True):
    """find a matrix of given multiplicative order mod p (d=2) that generates a cyclic group of that order"""
    for a, b, c, dd in itertools.product(range(p), repeat=4):
        M = [[a, b], [c, dd]]
        if (a * dd - b * c) % p == 0: continue
        if mat_order(M, p) == order:
            return M
    return None

