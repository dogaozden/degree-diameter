def perm_from_map(f, pts):
    return tuple(pts.index(f(x)) for x in pts)

def cyc(n, off, total):
    # n-cycle on points off..off+n-1 in a degree-total perm
    g = list(range(total))
    for i in range(n):
        g[off + i] = off + (i + 1) % n
    return tuple(g)

def gf8_mul(a, b):
    r = 0
    for i in range(3):
        if (b >> i) & 1: r ^= a << i
    for i in (4, 3):
        if (r >> i) & 1: r ^= 0b1011 << (i - 3)
    return r

def gf8_inv(a):
    for b in range(1, 8):
        if gf8_mul(a, b) == 1: return b

def psl28_gens():
    INF = 8; d = 9
    t = tuple((x ^ 1) if x < 8 else INF for x in range(d))           # x -> x+1
    al = tuple((gf8_mul(2, x)) if x < 8 else INF for x in range(d))  # x -> alpha x
    def iv(x):
        if x == INF: return 0
        if x == 0: return INF
        return gf8_inv(x)
    j = tuple(iv(x) for x in range(d))
    return [t, al, j]

