#!/usr/bin/env python3
"""Card c1 (squad round 6): NON-ABELIAN groups of isometries of Q(6,11) acting on the points of H(11); orbit unions.

Every generator is a 7x7 matrix mod 11 with g^T J g = J (B-isometry, so the opposition relation B != 0 is preserved).
A group G = <gens> is built from two NON-COMMUTING isometries of small order (plus optionally one element of small
order on a complementary block, commuting with them).  Closure by BFS on matrices, capped at CAP elements.
Families:
  frame : E = non-degenerate block of dim d in {2,3,4} with an orthogonal frame f_1..f_d (B(f_i,f_j) = c delta_ij).
          Signed permutations of the frame are isometries (B_d, order 2^d d!).  Two random non-commuting ones generate a
          non-abelian subgroup of B_d (S3, D4, D6, A4, S4, ...).
  block : random non-degenerate block E of dim d in {2,3}; two random non-commuting elements of O(E) of prescribed
          orders (dihedral subgroups of O(2,11), small subgroups of O(3,11) = +-PGL(2,11)).
  mono  : monomial isometries of the hyperbolic planes H_p = <e_p, e_{p+4}> (p = 0,1,2): plane permutations, plane maps
          diag(t,1/t) or antidiagonal (x_p -> t x_{p+4}, x_{p+4} -> x_p/t) with t in mu_5 or F_11^*, sign on x_3.
Orbits, good orbits (internally pairwise opposite), compatibility graph, max-weight clique (wclq2: exact B&B then tabu).
usage: nonab.py [--types frame,block,mono] [--seed S] [--cpu C] [--texact T] [--theur H] [--kmax K] [--cap CAP]
CPU is the driver plus its wclq2 children; the run stops starting groups when the total would exceed --cpu.
"""
import argparse
import hashlib
import json
import os
import subprocess
import sys
import time

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import orbl as L  # noqa: E402

p = L.p
J = L.J
I7 = L.I7
mmul = L.mmul
mpow = L.mpow
order_of = L.order_of
WCLQ = os.path.join(HERE, 'wclq2')
WORK = os.path.join(HERE, 'work')
GENS = os.path.join(HERE, 'gens')
RUNLOG = os.path.join(HERE, 'runlog.jsonl')
BEST_IDX = os.path.join(HERE, 'best_idx.txt')
BEST_GEN = os.path.join(HERE, 'best_gen.txt')
BEST_W = os.path.join(HERE, 'best_weight.txt')
QR = {(x * x) % p: x for x in range(1, p)}          # nonzero squares mod 11 -> a square root
ALLOWED_K = (2, 3, 4, 5, 6, 10, 12)
ALLOWED_COMP = (2, 3, 4, 5, 6, 10, 12, 15, 20, 30)   # orders of the element on the complementary block
ALLOWED_COMP_LIST = list(ALLOWED_COMP)


def cpu_total():
    t = os.times()
    return t.user + t.system + t.children_user + t.children_system


def key(M):
    return M.astype(np.int8).tobytes()


def closure(gens, cap):
    """order of the matrix group generated by gens, or None if it exceeds cap."""
    seen = {key(I7)}
    elems = [I7.copy()]
    i = 0
    while i < len(elems):
        x = elems[i]
        i += 1
        for g in gens:
            y = mmul(x, g)
            k = key(y)
            if k not in seen:
                seen.add(k)
                elems.append(y)
                if len(elems) > cap:
                    return None
    return len(elems)


def commute(a, b):
    return np.array_equal(mmul(a, b), mmul(b, a))


def inv_mod(M):
    n = M.shape[0]
    A = np.concatenate([M % p, np.eye(n, dtype=np.int64)], axis=1)
    r = 0
    for c in range(n):
        piv = None
        for i in range(r, n):
            if A[i, c] % p:
                piv = i
                break
        if piv is None:
            raise ValueError('singular matrix')
        A[[r, piv]] = A[[piv, r]]
        A[r] = (A[r] * pow(int(A[r, c]), p - 2, p)) % p
        for i in range(n):
            if i != r and A[i, c]:
                A[i] = (A[i] - A[i, c] * A[r]) % p
        r += 1
    return A[:, n:] % p


def frame(rng, E, tries=300):
    """orthogonal basis (rows) f_1..f_d of the block E (rows) with B(f_i, f_j) = c delta_ij, or None."""
    d = E.shape[0]
    S = E.copy() % p
    F = []
    c = None
    for k in range(d):
        ok = False
        for _ in range(tries):
            r = rng.integers(0, p, S.shape[0])
            v = (r @ S) % p
            n = int(v @ J @ v) % p
            if n == 0:
                continue
            if c is None:
                c, t = n, 1
            else:
                ratio = (c * pow(n, p - 2, p)) % p
                if ratio not in QR:
                    continue
                t = QR[ratio]
            F.append((t * v) % p)
            ok = True
            break
        if not ok:
            return None
        if k < d - 1:
            a = (S @ J @ F[-1]) % p                  # a_i = B(S_i, f)
            NS = L.nullspace_mod(a.reshape(1, -1))   # coefficients u with sum u_i a_i = 0
            S = (NS @ S) % p
    return np.array(F, dtype=np.int64)


def frame_element(Fr, Cr, SE):
    """isometry acting as SE on E = span(Fr) and as the identity on E-perp = span(Cr)."""
    d = Fr.shape[0]
    Tc = np.vstack([Fr, Cr]).T % p                   # columns = basis vectors
    D = np.eye(7, dtype=np.int64)
    D[:d, :d] = SE
    return mmul(mmul(Tc, D), inv_mod(Tc))


def rand_signed_perm(rng, d):
    sig = rng.permutation(d)
    eps = rng.choice([1, p - 1], size=d)
    SE = np.zeros((d, d), dtype=np.int64)
    for j in range(d):
        SE[sig[j], j] = eps[j]
    return SE


def complement_element(rng, Cr, budget):
    """element of prescribed order k (k * budget <= cap is checked by the caller) acting on E-perp, identity on E."""
    for _ in range(50):
        a = L.rand_refl_in(rng, Cr, int(rng.integers(2, 9)))
        o = order_of(a)
        ks = [k for k in ALLOWED_COMP_LIST if o % k == 0 and k * budget <= CAP_GLOBAL[0]]
        if ks:
            k = int(rng.choice(ks))
            return mpow(a, o // k), k
    return None, 1


CAP_GLOBAL = [2000]


FRAME_DIMS = [2, 3, 3, 4]


def sample_frame(rng):
    d = int(rng.choice(FRAME_DIMS))
    for _ in range(200):
        E = L.random_nondeg_subspace(rng, d)
        Cr = L.nullspace_mod((E @ J) % p)
        Fr = frame(rng, E)
        if Fr is not None:
            break
    else:
        return None
    for _ in range(200):
        g1 = frame_element(Fr, Cr, rand_signed_perm(rng, d))
        g2 = frame_element(Fr, Cr, rand_signed_perm(rng, d))
        if order_of(g1) > 1 and order_of(g2) > 1 and not commute(g1, g2):
            return d, [g1, g2], Cr, f'frame basis of dim {d}: non-commuting signed permutations of the frame'
    return None


def sample_block(rng):
    d = int(rng.choice([2, 3]))
    E = L.random_nondeg_subspace(rng, d)
    Cr = L.nullspace_mod((E @ J) % p)
    for _ in range(200):
        pair = []
        for _ in range(2):
            g = L.rand_refl_in(rng, E, int(rng.integers(2, 9)))
            o = order_of(g)
            ks = [k for k in ALLOWED_K if o % k == 0]
            if not ks:
                break
            pair.append(mpow(g, o // int(rng.choice(ks))))
        if len(pair) == 2 and order_of(pair[0]) > 1 and order_of(pair[1]) > 1 and not commute(*pair):
            return d, pair, Cr, f'block dim {d}: two non-commuting elements of O(E) of small orders'
    return None


def mono_matrix(sig, ops, eps3):
    """monomial isometry: plane permutation sig, plane maps ops[p] = ('d', t) or ('a', t), sign eps3 on x_3."""
    D = np.zeros((7, 7), dtype=np.int64)
    for q in range(3):
        kind, t = ops[q]
        tinv = pow(t, p - 2, p)
        if kind == 'd':
            D[q, q], D[q + 4, q + 4] = t, tinv
        else:
            D[q, q + 4], D[q + 4, q] = t, tinv
    D[3, 3] = eps3 % p
    P = np.zeros((7, 7), dtype=np.int64)
    for q in range(3):
        P[sig[q], q] = 1
        P[sig[q] + 4, q + 4] = 1
    P[3, 3] = 1
    return mmul(P, D)


def rand_mono(rng, tset):
    sig = [int(x) for x in rng.permutation(3)]
    ops = []
    for _ in range(3):
        kind = 'd' if rng.random() < 0.5 else 'a'
        ops.append((kind, int(rng.choice(tset))))
    eps3 = int(rng.choice([1, p - 1]))
    return mono_matrix(sig, ops, eps3)


def sample_mono(rng):
    tset = [1, 3, 4, 5, 9] if rng.random() < 0.6 else list(range(1, p))
    for _ in range(200):
        g1 = rand_mono(rng, tset)
        g2 = rand_mono(rng, tset)
        if not L.is_isom(g1) or not L.is_isom(g2):
            raise AssertionError('mono element is not an isometry')
        if order_of(g1) > 1 and order_of(g2) > 1 and not commute(g1, g2):
            return 3, [g1, g2], None, 'monomial hyperbolic-plane group: two non-commuting monomial isometries'
    return None


def sample_group(rng, types):
    """returns (desc, gens, family) with the closure within CAP, or None."""
    fam = types[int(rng.integers(0, len(types)))]
    out = {'frame': sample_frame, 'block': sample_block, 'mono': sample_mono}[fam](rng)
    if out is None:
        return None
    d, pair, Cr, desc = out
    gens = list(pair)
    size = closure(gens, CAP_GLOBAL[0])
    if size is None:
        return None
    k = 1
    if Cr is not None and rng.random() < 0.7:
        budget = size
        a, k = complement_element(rng, Cr, budget)
        if a is not None:
            gens.append(a)
            desc += f'; times an element of order {k} on the complementary block (dim {Cr.shape[0]})'
            size = closure(gens, CAP_GLOBAL[0])
            if size is None:
                return None
    if size is None or size > CAP_GLOBAL[0]:
        return None
    return dict(family=fam, desc=desc, gens=gens, order_G=size,
                orders=[int(order_of(g)) for g in gens])


def analyse_group(gens):
    perms = [L.perm_of(g) for g in gens]
    lab = L.orbit_labels(perms)
    sizes, rep, good = L.analyse(lab)
    fp = hashlib.sha1(L.fingerprint(sizes, good).encode()).hexdigest()[:16]
    return lab, sizes, rep, good, fp


def load_seen():
    seen, best = set(), 0
    if os.path.exists(RUNLOG):
        with open(RUNLOG) as f:
            for line in f:
                try:
                    r = json.loads(line)
                except ValueError:
                    continue
                seen.add(r.get('fp'))
                best = max(best, r.get('weight', 0) or 0)
    return seen, best


def save_gens(fp, grp):
    path = os.path.join(GENS, f'{fp}.txt')
    with open(path, 'w') as f:
        f.write(f'# {grp["desc"]}; |G| = {grp["order_G"]}\n')
        for i, g in enumerate(grp['gens']):
            f.write(f'# generator {i}\n')
            f.write(L.mat_to_text(g))
    return os.path.relpath(path, HERE)


def evaluate(grp, args, seed, analysis):
    t_eval = time.process_time()
    lab, sizes, rep, good, fp = analysis
    K = int(good.size)
    rec = dict(family=grp['family'], desc=grp['desc'], order_G=grp['order_G'], orders=grp['orders'], fp=fp,
               seed=seed, norbits=int(sizes.size), K=K, weight=0, optimal=None, skipped=None)
    if K == 0:
        rec['skipped'] = 'no good orbits'
        return rec, None
    if K > args.kmax:
        rec['skipped'] = f'K={K} > kmax'
        return rec, None
    rows = L.compat_packed(lab, rep, good)
    w = sizes[good]
    os.makedirs(WORK, exist_ok=True)
    gbin = os.path.join(WORK, f'{fp}.bin')
    gclq = os.path.join(WORK, f'{fp}.clq')
    L.write_graph_packed(gbin, rows, w)
    cmd = [WCLQ, gbin, str(args.texact), str(args.theur), str(seed), gclq]
    t_cl = time.process_time()
    res = subprocess.run(cmd, capture_output=True, text=True, timeout=args.texact + args.theur + 300)
    rec['cpu_clique_driver_side'] = round(time.process_time() - t_cl, 2)
    weight, opt, verts = L.read_clique(gclq)
    rec['weight'] = int(weight)
    rec['optimal'] = bool(opt)
    rec['edges_density'] = round(L.packed_density(rows), 5)
    rec['clique_stderr'] = res.stderr.strip().splitlines()[-1:] if res.stderr else []
    for fpath in (gbin, gclq):
        if os.path.exists(fpath):
            os.remove(fpath)
    chosen = good[np.array(verts, dtype=np.int64)] if verts else np.zeros(0, np.int64)
    idx = np.flatnonzero(np.isin(lab, chosen))
    if idx.size != weight or not L.pairwise_ok(idx):
        rec['skipped'] = 'verification failed'
        return rec, None
    rec['cpu_eval'] = round(time.process_time() - t_eval, 2)
    return rec, idx


def write_best(idx, grp, weight):
    with open(BEST_IDX, 'w') as f:
        f.write(f'# {weight} points, pairwise opposite (verified by wclq2 + numpy); generators in best_gen.txt\n')
        f.write('\n'.join(map(str, np.sort(idx).tolist())) + '\n')
    with open(BEST_GEN, 'w') as f:
        f.write(f'# {weight} points: {grp["desc"]}; |G| = {grp["order_G"]}\n')
        for i, g in enumerate(grp['gens']):
            f.write(f'# generator {i}\n')
            f.write(L.mat_to_text(g))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--types', default='frame,block,mono')
    ap.add_argument('--seed', type=int, default=1)
    ap.add_argument('--cpu', type=float, default=480.0)
    ap.add_argument('--texact', type=float, default=8.0)
    ap.add_argument('--theur', type=float, default=4.0)
    ap.add_argument('--kmax', type=int, default=9000)
    ap.add_argument('--cap', type=int, default=2000)
    ap.add_argument('--maxgroups', type=int, default=10 ** 9)
    ap.add_argument('--minsave', type=int, default=600)
    ap.add_argument('--fdims', default='2,3,3,4', help='frame block dimensions')
    ap.add_argument('--compk', default='', help='comma list of allowed orders on the complementary block')
    args = ap.parse_args()
    CAP_GLOBAL[0] = args.cap
    FRAME_DIMS[:] = [int(x) for x in args.fdims.split(',') if x]
    if args.compk:
        ALLOWED_COMP_LIST[:] = [int(x) for x in args.compk.split(',') if x]
    os.makedirs(GENS, exist_ok=True)
    os.makedirs(WORK, exist_ok=True)
    types = [t for t in args.types.split(',') if t]
    rng = np.random.default_rng(args.seed)
    seen, best_known = load_seen()
    start = cpu_total()
    reserve = args.texact + args.theur + 30
    tried = n_eval = n_skip = n_none = 0
    best_here = 0
    while cpu_total() - start < args.cpu - reserve and tried < args.maxgroups:
        tried += 1
        grp = sample_group(rng, types)
        if grp is None:
            n_none += 1
            continue
        analysis = analyse_group(grp['gens'])
        fp = analysis[-1]
        if fp in seen:
            n_skip += 1
            continue
        seen.add(fp)
        rec, idx = evaluate(grp, args, args.seed * 1000 + tried, analysis)
        rec['t_cpu_total'] = round(cpu_total() - start, 1)
        if idx is not None and rec['weight'] >= args.minsave:
            rec['gens_file'] = save_gens(fp, grp)
        with open(RUNLOG, 'a') as f:
            f.write(json.dumps(rec) + '\n')
        n_eval += 1
        print(f"[{rec['t_cpu_total']:7.1f}s] {grp['family']} |G|={grp['order_G']} orders={grp['orders']} "
              f"norb={rec['norbits']} K={rec['K']} w={rec['weight']} opt={rec['optimal']} skip={rec['skipped']}",
              flush=True)
        if idx is not None and rec['weight'] > max(best_known, best_here):
            best_here = rec['weight']
            write_best(idx, grp, rec['weight'])
            with open(BEST_W, 'w') as f:
                f.write(f'{rec["weight"]}\n')
            print('NEW BEST', rec['weight'], grp['desc'], flush=True)
    print(f'done: evaluated {n_eval}, repeats {n_skip}, no-group draws {n_none}, sampled {tried}, '
          f'best this run {best_here}, cpu {cpu_total() - start:.1f}s', flush=True)


if __name__ == '__main__':
    main()
