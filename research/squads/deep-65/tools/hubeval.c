/* hubeval.c (deep-65): algebraic evaluator for the "Haar + hub orbits" family (type 1,k|1,k with n11 = 0).
 *
 * Clean model (Opus derivation, deep-65): G a group of order m, S a subset of G (|S| = d-1), KA and HB subgroups of
 * order d (any subgroups, not only cyclic). Vertices: A0 = G, B0 = G, B1 = G/KA (left cosets xKA), A1 = G/HB (left
 * cosets yHB). Edges: x in A0 ~ xs in B0 (s in S); x in A0 ~ hub xKA in B1; hub yHB in A1 ~ every y' in yHB (in B0).
 * The graph is d-regular bipartite on 2m + 2m/d vertices and G acts on it by left multiplication.
 * (t18's parameters (S, g1, g2, H, K) give KA = g1 K g1^-1 and HB = g2^-1 H g2.)
 *
 * A bipartite graph has diameter <= 5 iff every same-side pair is at distance <= 4 (an opposite pair a, b is then at
 * distance <= 1 + d(a, a') for any neighbour a' of b). With T = S S^-1 and T' = S^-1 S the six conditions are
 *   (1) A0-A0: {e} u T u KA u TT u T KA u KA T u S HB S^-1 = G
 *   (2) A0-A1: (T u KA) S HB = G
 *   (3) A1-A1: HB T' HB = G
 *   (4) B0-B0: {e} u T' u HB u T'T' u T' HB u HB T' u S^-1 KA S = G
 *   (5) B0-B1: (T' u HB) S^-1 KA = G
 *   (6) B1-B1: KA T KA = G
 * This program prints the number of missing elements of G in each condition (and the missing elements of (1), (4)),
 * and optionally writes the edge list (vertex order A0, A1, B0, B1 as in t18) for an independent check.
 *
 * usage: hubeval TABLE "s1 s2 ..." "KA generators" "HB generators" [OUT.edges]
 *        hubeval TABLE --t18 "S" g1 g2 Hgen Kgen [OUT.edges]     (t18 parameters, cyclic H = <Hgen>, K = <Kgen>)
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static int m, *T, *inv;
#define MUL(x, y) T[(x) * m + (y)]

static void load(const char *fn) {
    FILE *f = fopen(fn, "r");
    if (!f || fscanf(f, "%d", &m) != 1) { fprintf(stderr, "bad table\n"); exit(1); }
    T = malloc(sizeof(int) * m * m); inv = malloc(sizeof(int) * m);
    for (int i = 0; i < m * m; i++) if (fscanf(f, "%d", &T[i]) != 1) { fprintf(stderr, "short table\n"); exit(1); }
    fclose(f);
    for (int x = 0; x < m; x++) for (int y = 0; y < m; y++) if (MUL(x, y) == 0) inv[x] = y;
}
static int parse(const char *s, int *out) { int n = 0, v, k; while (sscanf(s, "%d%n", &v, &k) == 1) { out[n++] = v; s += k; } return n; }
/* subgroup generated by gens -> element list */
static int gensub(int *gens, int ng, int *el) {
    char *in = calloc(m, 1); int n = 1; el[0] = 0; in[0] = 1;
    for (int i = 0; i < n; i++) for (int j = 0; j < ng; j++) { int z = MUL(el[i], gens[j]); if (!in[z]) { in[z] = 1; el[n++] = z; } }
    free(in); return n;
}
static int cnt_missing(char *c, int *list) { int k = 0; for (int x = 0; x < m; x++) if (!c[x]) { if (list) list[k] = x; k++; } return k; }

int main(int argc, char **argv) {
    if (argc < 5) { fprintf(stderr, "usage: see header\n"); return 1; }
    load(argv[1]);
    int S[64], ns, KA[64], nk, HB[64], nh, g[64], ngn; const char *out = NULL;
    if (!strcmp(argv[2], "--t18")) {
        ns = parse(argv[3], S); int g1 = atoi(argv[4]), g2 = atoi(argv[5]);
        int hg = atoi(argv[6]), kg = atoi(argv[7]); if (argc > 8) out = argv[8];
        int H[64], K[64]; int nH = gensub(&hg, 1, H), nK = gensub(&kg, 1, K);
        nk = nK; for (int i = 0; i < nK; i++) KA[i] = MUL(MUL(g1, K[i]), inv[g1]);
        nh = nH; for (int i = 0; i < nH; i++) HB[i] = MUL(MUL(inv[g2], H[i]), g2);
    } else {
        ns = parse(argv[2], S);
        ngn = parse(argv[3], g); nk = gensub(g, ngn, KA);
        ngn = parse(argv[4], g); nh = gensub(g, ngn, HB);
        if (argc > 5) out = argv[5];
    }
    int nT = 0, Tl[4096], nTp = 0, Tp[4096];
    char *inT = calloc(m, 1), *inTp = calloc(m, 1);
    for (int i = 0; i < ns; i++) for (int j = 0; j < ns; j++) {
        int t = MUL(S[i], inv[S[j]]); if (!inT[t]) { inT[t] = 1; Tl[nT++] = t; }
        int u = MUL(inv[S[i]], S[j]); if (!inTp[u]) { inTp[u] = 1; Tp[nTp++] = u; }
    }
    char *c = calloc(m, 1); int miss[6], ml[4096];
    /* (1) */
    memset(c, 0, m);
    for (int i = 0; i < nT; i++) { c[Tl[i]] = 1; for (int j = 0; j < nT; j++) c[MUL(Tl[i], Tl[j])] = 1;
        for (int k = 0; k < nk; k++) { c[MUL(Tl[i], KA[k])] = 1; c[MUL(KA[k], Tl[i])] = 1; } }
    for (int k = 0; k < nk; k++) c[KA[k]] = 1;
    for (int i = 0; i < ns; i++) for (int h = 0; h < nh; h++) for (int j = 0; j < ns; j++) c[MUL(MUL(S[i], HB[h]), inv[S[j]])] = 1;
    miss[0] = cnt_missing(c, ml);
    printf("(1) A0-A0 missing %d:", miss[0]); for (int i = 0; i < miss[0] && i < 40; i++) printf(" %d", ml[i]); printf("\n");
    /* (2) */
    memset(c, 0, m);
    { int U[4096], nu = 0; for (int i = 0; i < nT; i++) U[nu++] = Tl[i]; for (int k = 0; k < nk; k++) U[nu++] = KA[k];
      for (int i = 0; i < nu; i++) for (int j = 0; j < ns; j++) for (int h = 0; h < nh; h++) c[MUL(MUL(U[i], S[j]), HB[h])] = 1; }
    miss[1] = cnt_missing(c, NULL);
    /* (3) */
    memset(c, 0, m);
    for (int a = 0; a < nh; a++) for (int i = 0; i < nTp; i++) for (int b = 0; b < nh; b++) c[MUL(MUL(HB[a], Tp[i]), HB[b])] = 1;
    miss[2] = cnt_missing(c, NULL);
    /* (4) */
    memset(c, 0, m);
    for (int i = 0; i < nTp; i++) { c[Tp[i]] = 1; for (int j = 0; j < nTp; j++) c[MUL(Tp[i], Tp[j])] = 1;
        for (int h = 0; h < nh; h++) { c[MUL(Tp[i], HB[h])] = 1; c[MUL(HB[h], Tp[i])] = 1; } }
    for (int h = 0; h < nh; h++) c[HB[h]] = 1;
    for (int i = 0; i < ns; i++) for (int k = 0; k < nk; k++) for (int j = 0; j < ns; j++) c[MUL(MUL(inv[S[i]], KA[k]), S[j])] = 1;
    miss[3] = cnt_missing(c, ml);
    printf("(4) B0-B0 missing %d:", miss[3]); for (int i = 0; i < miss[3] && i < 40; i++) printf(" %d", ml[i]); printf("\n");
    /* (5) */
    memset(c, 0, m);
    { int U[4096], nu = 0; for (int i = 0; i < nTp; i++) U[nu++] = Tp[i]; for (int h = 0; h < nh; h++) U[nu++] = HB[h];
      for (int i = 0; i < nu; i++) for (int j = 0; j < ns; j++) for (int k = 0; k < nk; k++) c[MUL(MUL(U[i], inv[S[j]]), KA[k])] = 1; }
    miss[4] = cnt_missing(c, NULL);
    /* (6) */
    memset(c, 0, m);
    for (int a = 0; a < nk; a++) for (int i = 0; i < nT; i++) for (int b = 0; b < nk; b++) c[MUL(MUL(KA[a], Tl[i]), KA[b])] = 1;
    miss[5] = cnt_missing(c, NULL);
    printf("missing per condition (1..6): %d %d %d %d %d %d  |KA|=%d |HB|=%d |S|=%d\n", miss[0], miss[1], miss[2], miss[3], miss[4], miss[5], nk, nh, ns);
    printf("KA:"); for (int i = 0; i < nk; i++) printf(" %d", KA[i]); printf("  HB:"); for (int i = 0; i < nh; i++) printf(" %d", HB[i]); printf("\n");
    if (out) {
        /* vertex order: A0 x -> x; A1 coset -> m + c; B0 y -> m + q + y; B1 coset -> m + q + m + c (q = m / d) */
        int d = nk, q = m / d;
        int *cK = malloc(sizeof(int) * m), *cH = malloc(sizeof(int) * m);
        for (int x = 0; x < m; x++) cK[x] = cH[x] = -1;
        int nc = 0; for (int x = 0; x < m; x++) if (cK[x] < 0) { for (int k = 0; k < nk; k++) cK[MUL(x, KA[k])] = nc; nc++; }
        nc = 0; for (int x = 0; x < m; x++) if (cH[x] < 0) { for (int h = 0; h < nh; h++) cH[MUL(x, HB[h])] = nc; nc++; }
        FILE *f = fopen(out, "w"); int n = 2 * m + 2 * q;
        fprintf(f, "%d\n", n);
        for (int x = 0; x < m; x++) {
            for (int i = 0; i < ns; i++) fprintf(f, "%d %d\n", x, m + q + MUL(x, S[i]));
            fprintf(f, "%d %d\n", x, m + q + m + cK[x]);
        }
        for (int y = 0; y < m; y++) fprintf(f, "%d %d\n", m + cH[y], m + q + y);
        fclose(f);
        printf("wrote %s (n = %d)\n", out, n);
    }
    return 0;
}
