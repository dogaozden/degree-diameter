/* hubex.c (deep-65): EXACT search of the "Haar + hub orbits" family (type 1,d|1,d, n11 = 0) on one group.
 *
 * Model (see hubeval.c): S subset of G, |S| = d-1; KA, HB subgroups of order d. A0 = G ~ B0 = G by x ~ xs;
 * each left coset xKA of A0 gets a hub (B1); each left coset yHB of B0 gets a hub (A1). n = 2m + 2m/d.
 * Isomorphisms used for the reduction (all checked by hand in deep-65/NOTES.md):
 *   (S, KA, HB) ~ (d^-1 S c, d^-1 KA d, c^-1 HB c) for any d, c in G   (relabel A0 by x -> xd, B0 by y -> yc)
 *   (S, KA, HB) ~ (S^-1, HB, KA)                                        (swap the two sides)
 * So KA and HB can be fixed to conjugacy-class representatives (unordered pair of classes); then d ranges over
 * N(KA) and c over N(HB), whose orbits on G are the sets N(KA) x N(HB). Every S is equivalent to one that contains
 * the representative r(o) of its smallest orbit o (orbits sorted by size, largest first) and whose other elements
 * lie in orbits >= o. We enumerate exactly those S: complete for the family, up to the factor |N(KA)||N(HB)|.
 *
 * Conditions (T = S S^-1, T' = S^-1 S), checked cheapest first:
 *   (6) KA T KA = G      (3) HB T' HB = G      (2) (T u KA) S HB = G      (5) (T' u HB) S^-1 KA = G
 *   (1) {e} u T u KA u TT u T KA u KA T u S HB S^-1 = G
 *   (4) {e} u T' u HB u T'T' u T' HB u HB T' u S^-1 KA S = G
 * Output: per class pair, number of S enumerated, how many pass (6)(3), (2)(5), and the histogram of the number of
 * elements missing in (1)+(4) among those; every S with all six conditions is printed as "SOLUTION".
 *
 * usage: hubex TABLE D [NPROC PROC] [CLASSPAIR]
 *   enumerates subgroups of order D (all of them: cyclic or not, found as subgroups generated by <= 2 elements),
 *   their conjugacy classes, and runs every unordered pair of classes (or only pair number CLASSPAIR).
 *   NPROC/PROC split the work by the index of the 2nd element of S (stride), for parallel runs.
 */
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <time.h>

#define MAXM 2048
#define MAXSUB 4096
static int m, D, *T, inv[MAXM];
#define MUL(x, y) T[(x) * m + (y)]
static double now(void) { struct timespec t; clock_gettime(CLOCK_MONOTONIC, &t); return t.tv_sec + 1e-9 * t.tv_nsec; }

static int nsub, subel[MAXSUB][64];
static uint64_t subkey[MAXSUB][MAXM / 64];
static int gen_closure(int *gens, int ng, int *el, int cap) {
    static char in[MAXM]; memset(in, 0, m); int n = 1; el[0] = 0; in[0] = 1;
    for (int i = 0; i < n; i++) for (int j = 0; j < ng; j++) {
        int z = MUL(el[i], gens[j]); if (!in[z]) { if (n >= cap) return -1; in[z] = 1; el[n++] = z; } }
    return n;
}
static int find_sub(uint64_t *key) {
    int W = (m + 63) / 64;
    for (int s = 0; s < nsub; s++) if (!memcmp(subkey[s], key, 8 * W)) return s;
    return -1;
}
static void add_sub(int *el, int n) {
    int W = (m + 63) / 64; uint64_t key[MAXM / 64]; memset(key, 0, sizeof key);
    for (int i = 0; i < n; i++) key[el[i] >> 6] |= 1ULL << (el[i] & 63);
    if (find_sub(key) >= 0) return;
    if (nsub >= MAXSUB) { fprintf(stderr, "too many subgroups\n"); exit(1); }
    memcpy(subkey[nsub], key, 8 * W); memcpy(subel[nsub], el, sizeof(int) * n); nsub++;
}
static int conj_sub(int s, int x) { /* index of x^-1 Sub x */
    int W = (m + 63) / 64; uint64_t key[MAXM / 64]; memset(key, 0, sizeof key);
    for (int i = 0; i < D; i++) { int z = MUL(MUL(inv[x], subel[s][i]), x); key[z >> 6] |= 1ULL << (z & 63); }
    (void)W; return find_sub(key);
}

/* per-pair data */
static int KA[64], HB[64], dcK[MAXM], dcH[MAXM], lcK[MAXM], lcH[MAXM], ndcK, ndcH, nl;
static uint64_t fullK, fullH, fullL;   /* masks (ndc <= 64 assumed; checked) */
static int W5;                          /* words of 64 bits for m */

static long long hist[64], npass63, npass25, nenum, nsol;
static int bestmiss;

static inline int full_check(int *S, int ns, int *miss1, int *miss4) {
    uint64_t c[MAXM / 64]; int W = W5;
    int Tl[64], nT = 0, Tp[64], nTp = 0;
    for (int i = 0; i < ns; i++) for (int j = 0; j < ns; j++) { if (i == j) continue;
        Tl[nT++] = MUL(S[i], inv[S[j]]); Tp[nTp++] = MUL(inv[S[i]], S[j]); }
    /* (1) */
    memset(c, 0, 8 * W);
#define SETB(z) do { int _z = (z); c[_z >> 6] |= 1ULL << (_z & 63); } while (0)
    SETB(0);
    for (int i = 0; i < nT; i++) { SETB(Tl[i]); for (int j = 0; j < nT; j++) SETB(MUL(Tl[i], Tl[j]));
        for (int k = 1; k < D; k++) { SETB(MUL(Tl[i], KA[k])); SETB(MUL(KA[k], Tl[i])); } }
    for (int k = 1; k < D; k++) SETB(KA[k]);
    for (int i = 0; i < ns; i++) for (int h = 1; h < D; h++) { int a = MUL(S[i], HB[h]); for (int j = 0; j < ns; j++) SETB(MUL(a, inv[S[j]])); }
    int cov = 0; for (int w = 0; w < W; w++) cov += __builtin_popcountll(c[w]);
    *miss1 = m - cov;
    /* (4) */
    memset(c, 0, 8 * W);
    SETB(0);
    for (int i = 0; i < nTp; i++) { SETB(Tp[i]); for (int j = 0; j < nTp; j++) SETB(MUL(Tp[i], Tp[j]));
        for (int h = 1; h < D; h++) { SETB(MUL(Tp[i], HB[h])); SETB(MUL(HB[h], Tp[i])); } }
    for (int h = 1; h < D; h++) SETB(HB[h]);
    for (int i = 0; i < ns; i++) for (int k = 1; k < D; k++) { int a = MUL(inv[S[i]], KA[k]); for (int j = 0; j < ns; j++) SETB(MUL(a, S[j])); }
    cov = 0; for (int w = 0; w < W; w++) cov += __builtin_popcountll(c[w]);
    *miss4 = m - cov;
    return *miss1 + *miss4;
}
static inline int check25(int *S, int ns) {
    /* (2): (T u KA) S HB covers all left HB-cosets; (5): (T' u HB) S^-1 KA covers all left KA-cosets */
    uint64_t a = 0, b = 0;
    for (int j = 0; j < ns; j++) { a |= 1ULL << lcH[S[j]]; b |= 1ULL << lcK[inv[S[j]]]; }
    for (int k = 1; k < D; k++) for (int j = 0; j < ns; j++) { a |= 1ULL << lcH[MUL(KA[k], S[j])]; b |= 1ULL << lcK[MUL(HB[k], inv[S[j]])]; }
    for (int i = 0; i < ns; i++) for (int j = 0; j < ns; j++) if (i != j) {
        int t = MUL(S[i], inv[S[j]]), tp = MUL(inv[S[i]], S[j]);
        for (int l = 0; l < ns; l++) { a |= 1ULL << lcH[MUL(t, S[l])]; b |= 1ULL << lcK[MUL(tp, inv[S[l]])]; } }
    return a == fullL && b == fullL;
}

int main(int argc, char **argv) {
    if (argc < 3) { fprintf(stderr, "usage: hubex TABLE D [NPROC PROC] [CLASSPAIR]\n"); return 1; }
    FILE *f = fopen(argv[1], "r"); if (!f || fscanf(f, "%d", &m) != 1) return 1;
    T = malloc(sizeof(int) * m * m);
    for (int i = 0; i < m * m; i++) if (fscanf(f, "%d", &T[i]) != 1) return 1;
    fclose(f);
    D = atoi(argv[2]); int NPROC = argc > 4 ? atoi(argv[3]) : 1, PROC = argc > 4 ? atoi(argv[4]) : 0;
    int ONLY = argc > 5 ? atoi(argv[5]) : -1;
    if (m > MAXM || m % D) { fprintf(stderr, "bad m\n"); return 1; }
    W5 = (m + 63) / 64;
    for (int x = 0; x < m; x++) for (int y = 0; y < m; y++) if (MUL(x, y) == 0) inv[x] = y;
    /* subgroups of order D generated by 1 or 2 elements (enough for D = 6: C6 and S3; and any D <= 7) */
    int el[MAXM];
    for (int a = 1; a < m; a++) {
        int n = gen_closure(&a, 1, el, D); if (n == D) add_sub(el, n);
        if (n < 0 || D % n) continue;
        for (int b = a + 1; b < m; b++) { int g2[2] = {a, b}; int n2 = gen_closure(g2, 2, el, D); if (n2 == D) add_sub(el, n2); }
    }
    /* conjugacy classes */
    int cls[MAXSUB], ncls = 0, rep[MAXSUB];
    for (int s = 0; s < nsub; s++) cls[s] = -1;
    for (int s = 0; s < nsub; s++) if (cls[s] < 0) { rep[ncls] = s; for (int x = 0; x < m; x++) cls[conj_sub(s, x)] = ncls; ncls++; }
    printf("group order %d, %d subgroups of order %d in %d classes:", m, nsub, D, ncls);
    for (int c = 0; c < ncls; c++) { int cnt = 0; for (int s = 0; s < nsub; s++) cnt += cls[s] == c; printf(" [%d: size %d]", c, cnt); }
    printf("\n"); fflush(stdout);
    int pairno = 0, NORED = getenv("NORED") != NULL;
    long long gsol = 0; int gbest = 1 << 30;
    int NA = NORED ? nsub : ncls;
    for (int ca = 0; ca < NA; ca++) for (int cb = NORED ? 0 : ca; cb < NA; cb++, pairno++) {
        if (ONLY >= 0 && pairno != ONLY) continue;
        double t0 = now();
        int sa = NORED ? ca : rep[ca], sb = NORED ? cb : rep[cb];
        memcpy(KA, subel[sa], sizeof(int) * D); memcpy(HB, subel[sb], sizeof(int) * D);
        /* sort so that element 0 (identity) is first */
        for (int i = 0; i < D; i++) if (KA[i] == 0) { KA[i] = KA[0]; KA[0] = 0; }
        for (int i = 0; i < D; i++) if (HB[i] == 0) { HB[i] = HB[0]; HB[0] = 0; }
        /* normalisers */
        int NK[MAXM], nNK = 0, NH[MAXM], nNH = 0;
        for (int x = 0; x < m; x++) { if (NORED) { if (x == 0) { NK[nNK++] = 0; NH[nNH++] = 0; } continue; } if (conj_sub(sa, x) == sa) NK[nNK++] = x; if (conj_sub(sb, x) == sb) NH[nNH++] = x; }
        /* double cosets and left cosets */
        for (int x = 0; x < m; x++) dcK[x] = dcH[x] = lcK[x] = lcH[x] = -1;
        ndcK = ndcH = 0; nl = 0;
        for (int x = 0; x < m; x++) if (dcK[x] < 0) { for (int i = 0; i < D; i++) for (int j = 0; j < D; j++) dcK[MUL(MUL(KA[i], x), KA[j])] = ndcK; ndcK++; }
        for (int x = 0; x < m; x++) if (dcH[x] < 0) { for (int i = 0; i < D; i++) for (int j = 0; j < D; j++) dcH[MUL(MUL(HB[i], x), HB[j])] = ndcH; ndcH++; }
        int c1 = 0; for (int x = 0; x < m; x++) if (lcK[x] < 0) { for (int i = 0; i < D; i++) lcK[MUL(x, KA[i])] = c1; c1++; }
        int c2 = 0; for (int x = 0; x < m; x++) if (lcH[x] < 0) { for (int i = 0; i < D; i++) lcH[MUL(x, HB[i])] = c2; c2++; }
        nl = c1;
        if (ndcK > 64 || ndcH > 64 || nl > 64) { printf("pair %d: too many cosets for 64-bit masks (dcK %d dcH %d cosets %d), skipped\n", pairno, ndcK, ndcH, nl); continue; }
        fullK = ndcK == 64 ? ~0ULL : (1ULL << ndcK) - 1; fullH = ndcH == 64 ? ~0ULL : (1ULL << ndcH) - 1; fullL = nl == 64 ? ~0ULL : (1ULL << nl) - 1;
        /* orbits of x -> d^-1 x c, d in N(KA), c in N(HB) */
        int orb[MAXM], norb = 0, osz[MAXM], orep[MAXM];
        for (int x = 0; x < m; x++) orb[x] = -1;
        for (int x = 0; x < m; x++) if (orb[x] < 0) { int cnt = 0;
            for (int i = 0; i < nNK; i++) for (int j = 0; j < nNH; j++) { int z = MUL(MUL(inv[NK[i]], x), NH[j]); if (orb[z] < 0) { orb[z] = norb; cnt++; } }
            osz[norb] = cnt; orep[norb] = x; norb++; }
        /* order orbits by size, largest first */
        int oord[MAXM], opos[MAXM]; for (int o = 0; o < norb; o++) oord[o] = o;
        for (int i = 0; i < norb; i++) for (int j = i + 1; j < norb; j++) if (osz[oord[j]] > osz[oord[i]] || (osz[oord[j]] == osz[oord[i]] && oord[j] < oord[i])) { int t = oord[i]; oord[i] = oord[j]; oord[j] = t; }
        for (int i = 0; i < norb; i++) opos[oord[i]] = i;
        /* element order: by orbit position, then index */
        int elist[MAXM], ne = 0; for (int i = 0; i < norb; i++) for (int x = 0; x < m; x++) if (orb[x] == oord[i]) elist[ne++] = x;
        if (!NORED) printf("pair %d (KA class %d, HB class %d): |N(KA)| %d |N(HB)| %d, KA-dc %d, HB-dc %d, cosets %d, orbits %d\n",
               pairno, ca, cb, nNK, nNH, ndcK, ndcH, nl, norb); fflush(stdout);
        memset(hist, 0, sizeof hist); npass63 = npass25 = nenum = nsol = 0; bestmiss = 1 << 30;
        int ns = D - 1, S[64];
        /* for each first orbit o (position p): S[0] = rep, others from positions >= p (index into elist after rep's start) */
        int start = 0;
        for (int p = 0; p < norb; p++) {
            int o = oord[p], r = orep[o];
            /* candidates: elist[start..ne) minus r */
            int cand[MAXM], nc = 0; for (int i = start; i < ne; i++) if (elist[i] != r) cand[nc++] = elist[i];
            start += osz[o];
            if (nc < ns - 1) break;
            S[0] = r;
            /* nested choose ns-1 from cand; incremental double-coset masks for (6) and (3) */
            int idx[64]; uint64_t mk[64], mh[64];
            int lvl = 1; idx[1] = -1;
            mk[0] = 1ULL << dcK[0]; mh[0] = 1ULL << dcH[0];
            while (lvl >= 1) {
                idx[lvl]++;
                if (idx[lvl] > nc - (ns - lvl)) { lvl--; continue; }
                if (lvl == 1 && (idx[1] % NPROC) != PROC) continue;
                int s = cand[idx[lvl]]; S[lvl] = s;
                uint64_t a = mk[lvl - 1], b = mh[lvl - 1];
                for (int i = 0; i < lvl; i++) {
                    a |= (1ULL << dcK[MUL(s, inv[S[i]])]) | (1ULL << dcK[MUL(S[i], inv[s])]);
                    b |= (1ULL << dcH[MUL(inv[s], S[i])]) | (1ULL << dcH[MUL(inv[S[i]], s)]);
                }
                mk[lvl] = a; mh[lvl] = b;
                if (lvl < ns - 1) { lvl++; idx[lvl] = idx[lvl - 1]; continue; }
                nenum++;
                if (a != fullK || b != fullH) continue;
                npass63++;
                if (!check25(S, ns)) continue;
                npass25++;
                int m1, m4; int tot = full_check(S, ns, &m1, &m4);
                hist[tot < 63 ? tot : 63]++;
                if (tot < bestmiss) bestmiss = tot;
                static int nnear2 = 0; static int NEARMAX = -1; if (NEARMAX < 0) NEARMAX = getenv("NEARMAX") ? atoi(getenv("NEARMAX")) : 5; if (!NORED && (tot <= 1 || (tot == 2 && nnear2++ < NEARMAX))) { printf("%s pair %d S =", tot == 0 ? "SOLUTION" : "near", pairno);
                    for (int i = 0; i < ns; i++) printf(" %d", S[i]); printf("  KA = <");
                    for (int i = 0; i < D; i++) printf("%d%s", KA[i], i < D - 1 ? "," : ">"); printf(" HB = <");
                    for (int i = 0; i < D; i++) printf("%d%s", HB[i], i < D - 1 ? "," : ">"); printf(" miss1 %d miss4 %d\n", m1, m4); fflush(stdout); }
                if (tot == 0) nsol++;
            }
        }
        gsol += nsol; if (bestmiss < gbest) gbest = bestmiss;
        if (NORED) continue;
        printf("pair %d done: enumerated %lld, pass (6)(3) %lld, pass (2)(5) %lld, solutions %lld, best miss(1)+(4) %d, %.1f s\n  hist:",
               pairno, nenum, npass63, npass25, nsol, bestmiss, now() - t0);
        for (int i = 0; i < 64; i++) if (hist[i]) printf(" %d:%lld", i, hist[i]);
        printf("\n"); fflush(stdout);
    }
    printf("TOTAL solutions %lld best miss %d\n", gsol, gbest);
    return 0;
}
