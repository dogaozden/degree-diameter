def vec_list(p, d):
    return [tuple((i // p ** t) % p for t in range(d)) for i in range(p ** d)]


def normalize(v, p):
    for x in v:
        if x % p:
            inv = pow(x, -1, p)
            return tuple((y * inv) % p for y in v)
    raise ValueError('zero vector')


def proj_points(p, d):
    return [v for v in vec_list(p, d) if any(v) and normalize(v, p) == v]


def mat_apply(M, v, p, b=None):
    d = len(v)
    return tuple((sum(M[i][j] * v[j] for j in range(d)) + (b[i] if b else 0)) % p for i in range(d))


def affine_perms(p, d, mats, trans=(), proj=False):
    """Generators (as permutations of the point set) of the group generated by linear maps M and translations b.
    proj=True: action of the linear maps on the projective space P^(d-1) (points = normalized vectors)."""
    pts = proj_points(p, d) if proj else vec_list(p, d)
    pidx = {v: i for i, v in enumerate(pts)}
    I = [[int(i == j) for j in range(d)] for i in range(d)]
    gens = []
    for M in mats:
        if proj:
            gens.append(tuple(pidx[normalize(mat_apply(M, v, p), p)] for v in pts))
        else:
            gens.append(tuple(pidx[mat_apply(M, v, p)] for v in pts))
    for b in trans:
        gens.append(tuple(pidx[mat_apply(I, v, p, b)] for v in pts))
    return gens


def closure(gens):
    n = len(gens[0]); ident = tuple(range(n))
    elems = [ident]; index = {ident: 0}; i = 0
    while i < len(elems):
        x = elems[i]; i += 1
        for g in gens:
            y = tuple(g[t] for t in x)
            if y not in index:
                index[y] = len(elems); elems.append(y)
    return elems, index


def table_from_perms(elems, index):
    N = len(elems)
    T = np.zeros((N, N), dtype=np.int32)
    for i, x in enumerate(elems):
        for j, y in enumerate(elems):
            T[i, j] = index[tuple(x[t] for t in y)]
    return T


def perm_table(gens):
    elems, index = closure(gens)
    return table_from_perms(elems, index)


def cyc_perm(n, cyc):
    p = list(range(n))
    for a, b in zip(cyc, cyc[1:] + cyc[:1]):
        p[a] = b
    return tuple(p)


def linear_table(p, d, mats, trans=(), proj=False):
    return perm_table(affine_perms(p, d, mats, trans, proj))


def cyclic(c):
    a = np.arange(c)
    return (a[:, None] + a[None, :]) % c


def dprod(TA, TB):
    NA, NB = len(TA), len(TB)
    return (TA[:, None, :, None] * NB + TB[None, :, None, :]).reshape(NA * NB, NA * NB).astype(np.int32)


# ---- finite fields F_{p^e} (e = 2, 3), used for AGammaL(1,q) and AGL(1,q) ----
def gf_setup(p, e):
    for fc in itertools.product(range(p), repeat=e):
        f = list(fc) + [1]
        if all(sum(f[t] * x ** t for t in range(e + 1)) % p for x in range(p)):
            break  # no root in F_p: irreducible for e = 2, 3

    def fmul(a, b):
        prod = [0] * (2 * e - 1)
        for i, x in enumerate(a):
            for j, y in enumerate(b):
                prod[i + j] = (prod[i + j] + x * y) % p
        for k in range(len(prod) - 1, e - 1, -1):
            c = prod[k]
            if c:
                prod[k] = 0
                for t in range(e):
                    prod[k - e + t] = (prod[k - e + t] - c * f[t]) % p
        return tuple(prod[:e])

    one = tuple([1] + [0] * (e - 1))
    basis = [tuple(int(i == t) for i in range(e)) for t in range(e)]

    def fpow(a, k):
        r = one
        for _ in range(k):
            r = fmul(r, a)
        return r

    for g in vec_list(p, e)[1:]:
        x, k = g, 1
        while x != one:
            x = fmul(x, g); k += 1
        if k == p ** e - 1:
            break  # primitive element
    mulmat = lambda a: [[fmul(a, basis[t])[i] for t in range(e)] for i in range(e)]
    frob = [[fpow(basis[t], p)[i] for t in range(e)] for i in range(e)]
    return mulmat(g), frob, basis


def agammal1(p, e, semilinear=True):
    Mg, frob, basis = gf_setup(p, e)
    mats = [Mg] + ([frob] if semilinear else [])
    return linear_table(p, e, mats, trans=basis)


def find_mat_of_order(p, d, k, seed=1):
    rnd = random.Random(seed)
    I = np.eye(d, dtype=np.int64)
    divs = [j for j in range(1, k) if k % j == 0]
    for _ in range(2000000):
        M = np.array([[rnd.randrange(p) for _ in range(d)] for _ in range(d)], dtype=np.int64)
        P = np.eye(d, dtype=np.int64); ok = True
        for _ in range(k):
            P = P @ M % p
        if not (P == I).all():
            continue
        for j in divs:
            Q = np.linalg.matrix_power(M, j) % p
            if (Q == I).all():
                ok = False; break
        if ok:
            return [[int(x) for x in row] for row in M]
    raise RuntimeError('no matrix of order %d' % k)


def sym_perms(n, gens):
    return [cyc_perm(n, g) for g in gens]


