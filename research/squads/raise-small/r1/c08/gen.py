def check(T, name):
    N = len(T)
    ar = np.arange(N)
    assert (T[0] == ar).all() and (T[:, 0] == ar).all(), 'identity'
    for i in range(N):
        assert len(set(T[i].tolist())) == N, 'row %d not Latin' % i
    rng = np.random.default_rng(1)
    a, b, c = rng.integers(0, N, (3, 200000))
    assert (T[T[a, b], c] == T[a, T[b, c]]).all(), 'not associative'
    return N


