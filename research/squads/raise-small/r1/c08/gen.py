"""gen.py NAME [NAME...]: non-metacyclic groups as multiplication tables in the gtab.py format (header "G N 1 NAME",
then N rows of N integers, row g col h = index of g*h, identity index 0). Writes g_NAME.tab in this folder.
Groups are built as permutation groups (closure of generators) or as direct products of such tables with cyclic groups.
Checks: order, identity, Latin rows, associativity on 200,000 random triples.
"""
