/* orbmis.c: orbit search for point sets of H(11) (c4 card).
   Orbits of the group generated by the given point permutations (union-find). An orbit is usable iff no two of its
   points are collinear. Orbits A,B conflict iff some point of A is collinear with some point of B. Then a weighted
   maximum independent set (weight = orbit size) is found by iterated local search (weighted (1,*)-swaps,
   weighted (1,2)-swaps, forced insertion perturbation).
   usage: ./orbmis HEXBIN SECONDS SEED OUT gen1.txt [gen2.txt ...]     (gen files: N ints, image of point i on row i) */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>
#include <time.h>
#define Q1 12
static int N, LNUM, *LP, *par;
static int findp(int x) { while (par[x] != x) { par[x] = par[par[x]]; x = par[x]; } return x; }
static uint64_t rs = 0x9E3779B97F4A7C15ULL;
static inline uint64_t rnd(void) { rs ^= rs << 13; rs ^= rs >> 7; rs ^= rs << 17; return rs; }
static inline int rndi(int m) { return (int)(rnd() % (uint64_t)m); }
static double now_s(void) { struct timespec t; clock_gettime(CLOCK_MONOTONIC, &t); return t.tv_sec + 1e-9 * t.tv_nsec; }
static int K, WORDS; static uint64_t *bm;
static inline int conf(int a, int b) { return (bm[(size_t)a * WORDS + (b >> 6)] >> (b & 63)) & 1ULL; }
static inline void setc(int a, int b) { bm[(size_t)a * WORDS + (b >> 6)] |= 1ULL << (b & 63); }
static int *orbid, *osz, *invalid, n, *vorb, *w, *deg, **adj, *tight, *ord_buf, *Lb;
static char *inS; static long Wc;
static void addv(int v) { inS[v] = 1; Wc += w[v]; for (int i = 0; i < deg[v]; i++) tight[adj[v][i]]++; }
static void remv(int v) { inS[v] = 0; Wc -= w[v]; for (int i = 0; i < deg[v]; i++) tight[adj[v][i]]--; }
static inline int adjv(int a, int b) { return conf(vorb[a], vorb[b]); }
static void shuffle(int *a, int m) { for (int i = m - 1; i > 0; i--) { int j = rndi(i + 1); int t = a[i]; a[i] = a[j]; a[j] = t; } }
static void local_search(void) {
  int improved = 1;
  while (improved) {
    improved = 0;
    for (int i = 0; i < n; i++) ord_buf[i] = i;
    shuffle(ord_buf, n);
    for (int k = 0; k < n; k++) {
      int v = ord_buf[k];
      if (inS[v]) continue;
      if (tight[v] == 0) { addv(v); improved = 1; continue; }
      long sum = 0;
      for (int i = 0; i < deg[v]; i++) { int u = adj[v][i]; if (inS[u]) sum += w[u]; }
      if (w[v] > sum) {
        for (int i = 0; i < deg[v]; i++) { int u = adj[v][i]; if (inS[u]) remv(u); }
        addv(v); improved = 1;
      }
    }
    shuffle(ord_buf, n);
    for (int k = 0; k < n; k++) {
      int u = ord_buf[k];
      if (!inS[u]) continue;
      int m = 0;
      for (int i = 0; i < deg[u]; i++) { int v = adj[u][i]; if (!inS[v] && tight[v] == 1) Lb[m++] = v; }
      int done = 0;
      for (int a = 0; a < m && !done; a++)
        for (int b = a + 1; b < m && !done; b++) {
          int v1 = Lb[a], v2 = Lb[b];
          if (w[v1] + w[v2] > w[u] && !adjv(v1, v2)) { remv(u); addv(v1); addv(v2); done = 1; improved = 1; }
        }
    }
  }
}
int main(int argc, char **argv) {
  if (argc < 6) { fprintf(stderr, "usage: %s HEXBIN SECONDS SEED OUT gen1 [gen2 ...]\n", argv[0]); return 1; }
  double secs = atof(argv[2]);
  rs ^= (uint64_t)atoll(argv[3]) * 0x2545F4914F6CDD1DULL + 1; for (int i = 0; i < 10; i++) rnd();
  FILE *f = fopen(argv[1], "rb"); if (!f) return 1;
  int hdr[3]; if (fread(hdr, 4, 3, f) != 3) return 1;
  N = hdr[1]; LNUM = hdr[2];
  LP = malloc(sizeof(int) * (size_t)LNUM * Q1);
  if (fread(LP, 4, (size_t)LNUM * Q1, f) != (size_t)LNUM * Q1) return 1;
  fclose(f);
  par = malloc(sizeof(int) * N); for (int i = 0; i < N; i++) par[i] = i;
  int *p = malloc(sizeof(int) * N);
  for (int g = 5; g < argc; g++) {
    FILE *fg = fopen(argv[g], "r"); if (!fg) { fprintf(stderr, "no gen %s\n", argv[g]); return 1; }
    for (int i = 0; i < N; i++) if (fscanf(fg, "%d", &p[i]) != 1) { fprintf(stderr, "bad gen\n"); return 1; }
    fclose(fg);
    for (int i = 0; i < N; i++) { int a = findp(i), b = findp(p[i]); if (a != b) par[a] = b; }
  }
  int *idx = malloc(sizeof(int) * N); for (int i = 0; i < N; i++) idx[i] = -1;
  orbid = malloc(sizeof(int) * N); osz = calloc(N, sizeof(int)); K = 0;
  for (int i = 0; i < N; i++) { int r = findp(i); if (idx[r] < 0) idx[r] = K++; orbid[i] = idx[r]; osz[orbid[i]]++; }
  if (K > 20000) { fprintf(stderr, "too many orbits %d\n", K); return 1; }
  WORDS = (K + 63) / 64; bm = calloc((size_t)K * WORDS, 8); invalid = calloc(K, sizeof(int));
  for (int l = 0; l < LNUM; l++) {
    int *P = LP + (size_t)l * Q1;
    for (int a = 0; a < Q1; a++) {
      int oa = orbid[P[a]];
      for (int b = a + 1; b < Q1; b++) {
        int ob = orbid[P[b]];
        if (oa == ob) invalid[oa] = 1; else { setc(oa, ob); setc(ob, oa); }
      }
    }
  }
  vorb = malloc(sizeof(int) * K); n = 0;
  for (int A = 0; A < K; A++) if (!invalid[A]) vorb[n++] = A;
  long Wtot = 0; w = malloc(sizeof(int) * (n + 1));
  for (int i = 0; i < n; i++) { w[i] = osz[vorb[i]]; Wtot += w[i]; }
  deg = calloc(n + 1, sizeof(int)); adj = malloc(sizeof(int *) * (n + 1));
  int *tmp = malloc(sizeof(int) * (n + 1)); long E = 0;
  for (int i = 0; i < n; i++) {
    int c = 0;
    for (int j = 0; j < n; j++) if (j != i && conf(vorb[i], vorb[j])) tmp[c++] = j;
    deg[i] = c; E += c; adj[i] = malloc(sizeof(int) * (c ? c : 1)); memcpy(adj[i], tmp, sizeof(int) * c);
  }
  printf("orbits(all) %d valid %d valid_points %ld avg_deg %.1f\n", K, n, Wtot, n ? (double)E / n : 0.0);
  fflush(stdout);
  inS = calloc(n + 1, 1); tight = calloc(n + 1, sizeof(int)); ord_buf = malloc(sizeof(int) * (n + 1)); Lb = malloc(sizeof(int) * (n + 1));
  Wc = 0; local_search();
  double t0 = now_s();
  long bestW = Wc; char *bestS = malloc(n + 1); memcpy(bestS, inS, n);
  char *sS = malloc(n + 1); int *sT = malloc(sizeof(int) * (n + 1));
  long it = 0, lastImp = 0;
  while (now_s() - t0 < secs) {
    it++;
    memcpy(sS, inS, n); memcpy(sT, tight, sizeof(int) * n); long sW = Wc;
    int nout = 0; for (int i = 0; i < n; i++) if (!inS[i]) nout++;
    if (nout == 0) break;   /* every valid orbit is in the solution already */
    int kk = 1; if (rndi(8) == 0) kk = 2; if (rndi(32) == 0) kk = 3;
    for (int t = 0; t < kk; t++) {
      int v; do { v = rndi(n); } while (inS[v]);
      for (int i = 0; i < deg[v]; i++) { int u = adj[v][i]; if (inS[u]) remv(u); }
      addv(v);
    }
    local_search();
    if (Wc > bestW) { bestW = Wc; memcpy(bestS, inS, n); lastImp = it;
      printf("it %ld t %.1f best %ld\n", it, now_s() - t0, bestW); fflush(stdout); }
    if (Wc < sW && rndi(100) != 0) { memcpy(inS, sS, n); memcpy(tight, sT, sizeof(int) * n); Wc = sW; }
    if (it - lastImp > 20000) {   /* restart from the best solution */
      memcpy(inS, bestS, n); for (int i = 0; i < n; i++) tight[i] = 0; Wc = 0;
      for (int i = 0; i < n; i++) if (inS[i]) { Wc += w[i]; for (int j = 0; j < deg[i]; j++) tight[adj[i][j]]++; }
      lastImp = it;
    }
  }
  char *chosen = calloc(K, 1); int cnt = 0;
  for (int i = 0; i < n; i++) if (bestS[i]) chosen[vorb[i]] = 1;
  FILE *fo = fopen(argv[4], "w");
  for (int q = 0; q < N; q++) if (chosen[orbid[q]]) { fprintf(fo, "%d\n", q); cnt++; }
  fclose(fo);
  printf("RESULT best %ld points %d iters %ld\n", bestW, cnt, it);
  return 0;
}
