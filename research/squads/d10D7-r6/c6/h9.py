def _dec(e): return (e % 3, e // 3)
def _enc(c0, c1): return (c0 % 3) + 3 * (c1 % 3)
_ADD = np.zeros((9, 9), np.int64); _MUL = np.zeros((9, 9), np.int64)
for a in range(9):
    for b in range(9):
        a0, a1 = _dec(a); b0, b1 = _dec(b)
        _ADD[a, b] = _enc(a0 + b0, a1 + b1)
        _MUL[a, b] = _enc(a0 * b0 - a1 * b1, a0 * b1 + a1 * b0)
ADD = _ADD; MUL = _MUL
ADDL = _ADD.tolist(); MULL = _MUL.tolist()
NEG = [[b for b in range(9) if ADDL[a][b] == 0][0] for a in range(9)]
INV = [0] + [[b for b in range(1, 9) if MULL[a][b] == 1][0] for a in range(1, 9)]
FROB = [MULL[MULL[e][e]][e] for e in range(9)]          # x -> x^3
FROBA = np.array(FROB, np.int64)
