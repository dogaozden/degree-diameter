def perm_of(g):
    """permutation of point ids induced by the SL(3,9) matrix g in the (v,a,w) model."""
    gi = inv3(g); gitT = tr(gi)
    V = C[:, 0:3]; W = C[:, 4:7]
    NV = np.zeros((N, 3), np.int64); NW = np.zeros((N, 3), np.int64)
    for r in range(3):
        s = np.zeros(N, np.int64); t = np.zeros(N, np.int64)
        for k in range(3):
            s = ADD[s, MUL[g[r][k], V[:, k]]]
            t = ADD[t, MUL[gitT[r][k], W[:, k]]]
        NV[:, r] = s; NW[:, r] = t
    return ids_of(np.concatenate([NV, C[:, 3:4], NW], axis=1))

def perm_frob():
    return ids_of(FROBA[C])

def lines_ok(perm):
    """True iff the permutation maps every line onto a line (images pairwise collinear, check via NB)."""
    Q = perm[LP]
    if len(np.unique(perm)) != N: return False
    NBq = NB[Q[:, 0]]
    ok = np.ones(N, bool)
    for k in range(1, 10):
        ok &= (NBq == Q[:, k:k + 1]).any(axis=1)
    return bool(ok.all())

def orbit_labels(perms):
    parent = list(range(N))
    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]; x = parent[x]
        return x
    for p in perms:
        pl = p.tolist()
        for x in range(N):
            a, b = find(x), find(pl[x])
            if a != b: parent[a] = b
    roots = np.array([find(x) for x in range(N)])
    _, lab = np.unique(roots, return_inverse=True)
    return lab.astype(np.int64)

def no_two_collinear(ids):
    """True iff no two of the given point ids lie on a common line (each point's 10 lines must be distinct)."""
    S = np.array(sorted(set(int(x) for x in ids)), np.int64)
    flat_l = PL[S].ravel()
    return len(np.unique(flat_l)) == len(flat_l)
