def mm(A, B):
    R = [[0] * 3 for _ in range(3)]
    for i in range(3):
        for j in range(3):
            s = 0
            for k in range(3): s = ADDL[s][MULL[A[i][k]][B[k][j]]]
            R[i][j] = s
    return R
def ident(): return [[1 if i == j else 0 for j in range(3)] for i in range(3)]
def is_id(A): return A == ident()
def mpow(A, k):
    R = ident(); B = A
    while k:
        if k & 1: R = mm(R, B)
        B = mm(B, B); k >>= 1
    return R
def tr(A): return [[A[j][i] for j in range(3)] for i in range(3)]
def inv3(A):
    M = [[A[i][j] for j in range(3)] + [1 if i == j else 0 for j in range(3)] for i in range(3)]
    for c in range(3):
        p = next(r for r in range(c, 3) if M[r][c] != 0)
        M[c], M[p] = M[p], M[c]
        iv = INV[M[c][c]]; M[c] = [MULL[iv][x] for x in M[c]]
        for r in range(3):
            if r != c and M[r][c] != 0:
                f = M[r][c]
                M[r] = [ADDL[x][NEG[MULL[f][y]]] for x, y in zip(M[r], M[c])]
    return [row[3:] for row in M]
def det3(A):
    d = 0
    for j in range(3):
        m = [[A[i][k] for k in range(3) if k != j] for i in range(1, 3)]
        mi = ADDL[MULL[m[0][0]][m[1][1]]][NEG[MULL[m[0][1]][m[1][0]]]]
        term = MULL[A[0][j]][mi]
        d = ADDL[d][term] if j % 2 == 0 else ADDL[d][NEG[term]]
    return d

def closure(gens, cap=20000):
    """size of the matrix group generated by gens (3x3 lists), or None if above cap."""
    I = tuple(tuple(r) for r in ident())
    seen = {I}; frontier = [I]
    gens = [[list(r) for r in g] for g in gens]
    while frontier:
        nxt = []
        for A in frontier:
            Al = [list(r) for r in A]
            for g in gens:
                B = tuple(tuple(r) for r in mm(Al, g))
                if B not in seen:
                    seen.add(B); nxt.append(B)
                    if len(seen) > cap: return None
        frontier = nxt
    return len(seen)

