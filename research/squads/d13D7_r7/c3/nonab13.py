#!/usr/bin/env python3
"""Card c3 (squad round 7): NON-ABELIAN groups of isometries of Q(6,13) acting on the points of H(13).

Port of research/squads/d13D7_r6/c1/nonab.py (q = 11) to q = 13.  The arithmetic, orbits, compatibility graph and I/O
come from orbq13.py (a copy of research/squads/d13D7_r4/c2/orbq13.py).

Every generator is a 7x7 matrix mod 13 with g^T J g = J, so B(x, y) != 0 is preserved and an orbit union is pairwise
opposite iff its orbits are good and pairwise compatible.  A group is G = <gens>, closed by BFS on matrices (cap CAP).
Families:
  dihedral : two reflections r1, r2 in a random non-degenerate plane E; G = D_n, n = order of r1 r2 (n | 12 or n | 14).
  block    : two random non-commuting elements of O(S), S a non-degenerate block of dim 2 or 3 (S3, D_n, A4, S4, ...).
  decomp   : orthogonal decomposition V = B_1 + ... + B_m, dims in DECOMPS (5+2, 4+3, 3+2+2, 2+2+3, 3+4, 2+5).  One block
             carries a non-commuting pair inside a sub-block S (dim 2 or 3); every block also carries one element of
             small order on a sub-block (so G is a direct product of block groups, e.g. S3 x Z7, S3 x Z3).
  frame    : signed permutations of an orthogonal frame (as nonab.py).
  mono     : monomial isometries of the hyperbolic planes (as nonab.py), plane maps by t in F_13^*.
A complementary element (identity on the block, order k on the complement) may be multiplied in (PCOMP).
Orbits, good orbits, compatibility graph, max-weight clique (wclq2: exact B&B, then tabu).
usage: nonab13.py [--types dihedral,block,decomp,frame,mono] [--seed S] [--cpu C] [--wall W] [--texact T] [--theur H]
CPU is the driver plus its wclq2 children; the run stops starting groups when the total would exceed --cpu.
"""
import argparse
import hashlib
import json
import os
import subprocess
import sys
import time

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import orbq13 as L  # noqa: E402

p = L.p
J = L.J
I7 = L.I7
mmul = L.mmul
mpow = L.mpow
order_of = L.order_of
WCLQ = os.path.join(HERE, 'wclq2')
WORK = os.path.join(HERE, 'work')
GENS = os.path.join(HERE, 'gens')
RUNLOG = os.path.join(HERE, 'runlog.jsonl')
BEST_IDX = os.path.join(HERE, 'best_idx.txt')
BEST_GEN = os.path.join(HERE, 'best_gen.txt')
BEST_W = os.path.join(HERE, 'best_weight.txt')
QR = {(x * x) % p: x for x in range(1, p)}           # nonzero squares mod 13 -> a square root
ALLOWED_K = (2, 3, 4, 6, 7, 12, 14)                   # element orders inside a block of dim 2 or 3
ALLOWED_COMP = (2, 3, 4, 6, 7, 12, 14)                # orders of the element on a complementary block
DECOMPS = [(5, 2), (4, 3), (3, 2, 2), (2, 2, 3), (3, 4), (2, 5)]
FRAME_DIMS = [2, 3, 3, 4]
BLOCK_DIMS = [2, 3, 3]
MONO_T = [1, 3, 9, 4, 10, 12, 5, 8]
CAP_GLOBAL = [2000]
PCOMP = [0.5]


def cpu_total():
    t = os.times()
    return t.user + t.system + t.children_user + t.children_system


def key(M):
    return M.astype(np.int8).tobytes()


def closure(gens, cap):
    """order of the matrix group generated by gens, or None if it exceeds cap."""
    seen = {key(I7)}
    elems = [I7.copy()]
    i = 0
    while i < len(elems):
        x = elems[i]
        i += 1
        for g in gens:
            y = mmul(x, g)
            k = key(y)
            if k not in seen:
                seen.add(k)
                elems.append(y)
                if len(elems) > cap:
                    return None
    return len(elems)


def commute(a, b):
    return np.array_equal(mmul(a, b), mmul(b, a))


def inv_mod(M):
    n = M.shape[0]
    A = np.concatenate([M % p, np.eye(n, dtype=np.int64)], axis=1)
    r = 0
    for c in range(n):
        piv = None
        for i in range(r, n):
            if A[i, c] % p:
                piv = i
                break
        if piv is None:
            raise ValueError('singular matrix')
        A[[r, piv]] = A[[piv, r]]
        A[r] = (A[r] * pow(int(A[r, c]), p - 2, p)) % p
        for i in range(n):
            if i != r and A[i, c]:
                A[i] = (A[i] - A[i, c] * A[r]) % p
        r += 1
    return A[:, n:] % p


def random_nondeg_in(rng, Bm, k):
    """rows: a basis of a non-degenerate k-dim subspace inside the span of the rows of Bm."""
    E = []
    while len(E) < k:
        c = rng.integers(0, p, Bm.shape[0])
        v = (c @ Bm) % p
        for e in E:
            ee = int(e @ J @ e) % p
            v = (v - (int(v @ J @ e) % p) * pow(ee, p - 2, p) * e) % p
        if int(v @ J @ v) % p:
            E.append(v)
    return np.array(E, dtype=np.int64)


def random_decomposition(rng, dims):
    """list of row-blocks B_1..B_m, mutually orthogonal, non-degenerate, with the given dims (sum 7)."""
    blocks = []
    allE = None
    for d in dims[:-1]:
        rest = I7.copy() if allE is None else L.nullspace_mod((allE @ J) % p)
        E = random_nondeg_in(rng, rest, d)
        blocks.append(E)
        allE = np.vstack(blocks)
    blocks.append(L.nullspace_mod((allE @ J) % p))
    return blocks


def refl_in(rng, Bm, tries=50):
    """reflection in a random non-singular vector of span(Bm)."""
    for _ in range(tries):
        c = rng.integers(0, p, Bm.shape[0])
        v = (c @ Bm) % p
        if int(v @ J @ v) % p:
            return L.refl(v)
    return None


def small_elem_in(rng, Bm, ks, tries=80):
    """element of O(7), identity on the B-complement of span(Bm), of exact order k for some k in ks, or (None, 1)."""
    for _ in range(tries):
        g = L.rand_refl_in(rng, Bm, int(rng.integers(2, 9)))
        o = order_of(g)
        cand = [k for k in ks if o % k == 0]
        if cand:
            k = int(rng.choice(cand))
            return mpow(g, o // k), k
    return None, 1


def complement_element(rng, Cr, budget):
    """element of order k on the complement Cr (identity on the block), k * budget <= cap."""
    for _ in range(50):
        a = L.rand_refl_in(rng, Cr, int(rng.integers(2, 9)))
        o = order_of(a)
        ks = [k for k in ALLOWED_COMP if o % k == 0 and k * budget <= CAP_GLOBAL[0]]
        if ks:
            k = int(rng.choice(ks))
            return mpow(a, o // k), k
    return None, 1


def frame(rng, E, tries=300):
    """orthogonal basis (rows) f_1..f_d of the block E (rows) with B(f_i, f_j) = c delta_ij, or None."""
    d = E.shape[0]
    S = E.copy() % p
    F = []
    c = None
    for k in range(d):
        ok = False
        for _ in range(tries):
            r = rng.integers(0, p, S.shape[0])
            v = (r @ S) % p
            n = int(v @ J @ v) % p
            if n == 0:
                continue
            if c is None:
                c, t = n, 1
            else:
                ratio = (c * pow(n, p - 2, p)) % p
                if ratio not in QR:
                    continue
                t = QR[ratio]
            F.append((t * v) % p)
            ok = True
            break
        if not ok:
            return None
        if k < d - 1:
            a = (S @ J @ F[-1]) % p
            NS = L.nullspace_mod(a.reshape(1, -1))
            S = (NS @ S) % p
    return np.array(F, dtype=np.int64)


def frame_element(Fr, Cr, SE):
    d = Fr.shape[0]
    Tc = np.vstack([Fr, Cr]).T % p
    D = np.eye(7, dtype=np.int64)
    D[:d, :d] = SE
    return mmul(mmul(Tc, D), inv_mod(Tc))


def rand_signed_perm(rng, d):
    sig = rng.permutation(d)
    eps = rng.choice([1, p - 1], size=d)
    SE = np.zeros((d, d), dtype=np.int64)
    for j in range(d):
        SE[sig[j], j] = eps[j]
    return SE


def mono_matrix(sig, ops, eps3):
    D = np.zeros((7, 7), dtype=np.int64)
    for q in range(3):
        kind, t = ops[q]
        tinv = pow(t, p - 2, p)
        if kind == 'd':
            D[q, q], D[q + 4, q + 4] = t, tinv
        else:
            D[q, q + 4], D[q + 4, q] = t, tinv
    D[3, 3] = eps3 % p
    P = np.zeros((7, 7), dtype=np.int64)
    for q in range(3):
        P[sig[q], q] = 1
        P[sig[q] + 4, q + 4] = 1
    P[3, 3] = 1
    return mmul(P, D)


def rand_mono(rng, tset):
    sig = [int(x) for x in rng.permutation(3)]
    ops = []
    for _ in range(3):
        kind = 'd' if rng.random() < 0.5 else 'a'
        ops.append((kind, int(rng.choice(tset))))
    eps3 = int(rng.choice([1, p - 1]))
    return mono_matrix(sig, ops, eps3)


# ---------------------------------------------------------------- families: return (gens, Cr or None, desc) or None

def sample_dihedral(rng):
    E = L.random_nondeg_subspace(rng, 2)
    Cr = L.nullspace_mod((E @ J) % p)
    for _ in range(300):
        r1 = refl_in(rng, E)
        r2 = refl_in(rng, E)
        if r1 is None or r2 is None or commute(r1, r2):
            continue
        return [r1, r2], Cr, 'dihedral: two reflections in a non-degenerate plane'
    return None


def sample_block(rng):
    d = int(rng.choice(BLOCK_DIMS))
    E = L.random_nondeg_subspace(rng, d)
    Cr = L.nullspace_mod((E @ J) % p)
    for _ in range(200):
        g1, k1 = small_elem_in(rng, E, ALLOWED_K)
        g2, k2 = small_elem_in(rng, E, ALLOWED_K)
        if g1 is not None and g2 is not None and not commute(g1, g2):
            return [g1, g2], Cr, f'block dim {d}: non-commuting elements of O(E) of orders {k1},{k2}'
    return None


def sample_decomp(rng):
    dims = DECOMPS[int(rng.integers(0, len(DECOMPS)))]
    blocks = random_decomposition(rng, dims)
    nab = int(rng.integers(0, len(blocks)))
    gens, parts = [], []
    for i, Bk in enumerate(blocks):
        d = Bk.shape[0]
        if d < 2:
            continue
        s = min(d, int(rng.choice([2, 3])))
        if i == nab:
            pair = None
            for _ in range(60):
                S = random_nondeg_in(rng, Bk, s)
                g1, k1 = small_elem_in(rng, S, ALLOWED_K)
                g2, k2 = small_elem_in(rng, S, ALLOWED_K)
                if g1 is not None and g2 is not None and not commute(g1, g2):
                    pair = (g1, g2, k1, k2)
                    break
            if pair is None:
                return None
            gens += [pair[0], pair[1]]
            parts.append(f'block{d} sub{s}: non-commuting orders {pair[2]},{pair[3]}')
        else:
            S = random_nondeg_in(rng, Bk, s)
            g, k = small_elem_in(rng, S, ALLOWED_K)
            if g is not None:
                gens.append(g)
                parts.append(f'block{d} sub{s}: cyclic order {k}')
    if len(gens) < 2:
        return None
    return gens, None, 'decomp ' + '+'.join(map(str, dims)) + ': ' + '; '.join(parts)


def sample_frame(rng):
    d = int(rng.choice(FRAME_DIMS))
    for _ in range(200):
        E = L.random_nondeg_subspace(rng, d)
        Cr = L.nullspace_mod((E @ J) % p)
        Fr = frame(rng, E)
        if Fr is not None:
            break
    else:
        return None
    for _ in range(200):
        g1 = frame_element(Fr, Cr, rand_signed_perm(rng, d))
        g2 = frame_element(Fr, Cr, rand_signed_perm(rng, d))
        if order_of(g1) > 1 and order_of(g2) > 1 and not commute(g1, g2):
            return [g1, g2], Cr, f'frame basis of dim {d}: non-commuting signed permutations of the frame'
    return None


def sample_mono(rng):
    tset = MONO_T if rng.random() < 0.6 else list(range(1, p))
    for _ in range(200):
        g1 = rand_mono(rng, tset)
        g2 = rand_mono(rng, tset)
        if not L.is_isom(g1) or not L.is_isom(g2):
            raise AssertionError('mono element is not an isometry')
        if order_of(g1) > 1 and order_of(g2) > 1 and not commute(g1, g2):
            return [g1, g2], None, 'monomial hyperbolic-plane group: two non-commuting monomial isometries'
    return None


FAMS = {'dihedral': sample_dihedral, 'block': sample_block, 'decomp': sample_decomp,
        'frame': sample_frame, 'mono': sample_mono}


def sample_group(rng, types):
    """returns a dict describing G (closure within CAP), or None."""
    fam = types[int(rng.integers(0, len(types)))]
    out = FAMS[fam](rng)
    if out is None:
        return None
    gens, Cr, desc = out
    size = closure(gens, CAP_GLOBAL[0])
    if size is None:
        return None
    if Cr is not None and rng.random() < PCOMP[0]:
        a, k = complement_element(rng, Cr, size)
        if a is not None:
            gens = gens + [a]
            desc += f'; times an element of order {k} on the complementary block (dim {Cr.shape[0]})'
            size = closure(gens, CAP_GLOBAL[0])
            if size is None:
                return None
    if size is None or size > CAP_GLOBAL[0]:
        return None
    return dict(family=fam, desc=desc, gens=gens, order_G=size, orders=[int(order_of(g)) for g in gens])


def analyse_group(gens):
    perms = [L.perm_of(g) for g in gens]
    lab = L.orbit_labels(perms)
    sizes, rep, good = L.analyse(lab)
    fp = hashlib.sha1(L.fingerprint(sizes, good).encode()).hexdigest()[:16]
    return lab, sizes, rep, good, fp


def load_seen():
    seen, best = set(), 0
    if os.path.exists(RUNLOG):
        with open(RUNLOG) as f:
            for line in f:
                try:
                    r = json.loads(line)
                except ValueError:
                    continue
                seen.add(r.get('fp'))
                best = max(best, r.get('weight', 0) or 0)
    return seen, best


def save_gens(fp, grp):
    path = os.path.join(GENS, f'{fp}.txt')
    with open(path, 'w') as f:
        f.write(f'# {grp["desc"]}; |G| = {grp["order_G"]}\n')
        for i, g in enumerate(grp['gens']):
            f.write(f'# generator {i}\n')
            f.write(L.mat_to_text(g))
    return os.path.relpath(path, HERE)


def evaluate(grp, args, seed, analysis):
    t_eval = time.process_time()
    lab, sizes, rep, good, fp = analysis
    K = int(good.size)
    rec = dict(family=grp['family'], desc=grp['desc'], order_G=grp['order_G'], orders=grp['orders'], fp=fp,
               seed=seed, norbits=int(sizes.size), K=K, weight=0, optimal=None, skipped=None)
    if K == 0:
        rec['skipped'] = 'no good orbits'
        return rec, None
    if K > args.kmax:
        rec['skipped'] = f'K={K} > kmax'
        return rec, None
    rows = L.compat_packed(lab, rep, good)
    w = sizes[good]
    os.makedirs(WORK, exist_ok=True)
    gbin = os.path.join(WORK, f'{fp}.bin')
    gclq = os.path.join(WORK, f'{fp}.clq')
    L.write_graph_packed(gbin, rows, w)
    cmd = [WCLQ, gbin, str(args.texact), str(args.theur), str(seed), gclq]
    res = subprocess.run(cmd, capture_output=True, text=True, timeout=args.texact + args.theur + 300)
    rec['weight'] = 0
    try:
        weight, opt, verts = L.read_clique(gclq)
    except (OSError, ValueError, IndexError):
        rec['skipped'] = 'wclq2 failed'
        weight, opt, verts = 0, False, []
    rec['weight'] = int(weight)
    rec['optimal'] = bool(opt)
    rec['edges_density'] = round(L.packed_density(rows), 5)
    rec['clique_stderr'] = res.stderr.strip().splitlines()[-1:] if res.stderr else []
    for fpath in (gbin, gclq):
        if os.path.exists(fpath):
            os.remove(fpath)
    if rec['skipped'] or not verts:
        return rec, None
    chosen = good[np.array(verts, dtype=np.int64)]
    idx = np.flatnonzero(np.isin(lab, chosen))
    if idx.size != weight or not L.pairwise_ok(idx):
        rec['skipped'] = 'verification failed'
        return rec, None
    rec['cpu_eval'] = round(time.process_time() - t_eval, 2)
    return rec, idx


def write_best(idx, grp, weight):
    with open(BEST_IDX, 'w') as f:
        f.write(f'# {weight} points, pairwise opposite (verified by wclq2 + numpy); generators in best_gen.txt\n')
        f.write('\n'.join(map(str, np.sort(idx).tolist())) + '\n')
    with open(BEST_GEN, 'w') as f:
        f.write(f'# {weight} points: {grp["desc"]}; |G| = {grp["order_G"]}\n')
        for i, g in enumerate(grp['gens']):
            f.write(f'# generator {i}\n')
            f.write(L.mat_to_text(g))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--types', default='dihedral,block,decomp,frame,mono')
    ap.add_argument('--seed', type=int, default=1)
    ap.add_argument('--cpu', type=float, default=480.0)
    ap.add_argument('--wall', type=float, default=420.0)
    ap.add_argument('--texact', type=float, default=3.0)
    ap.add_argument('--theur', type=float, default=2.0)
    ap.add_argument('--kmax', type=int, default=9000)
    ap.add_argument('--cap', type=int, default=2000)
    ap.add_argument('--maxgroups', type=int, default=10 ** 9)
    ap.add_argument('--minsave', type=int, default=480)
    ap.add_argument('--pcomp', type=float, default=0.5)
    args = ap.parse_args()
    CAP_GLOBAL[0] = args.cap
    PCOMP[0] = args.pcomp
    os.makedirs(GENS, exist_ok=True)
    os.makedirs(WORK, exist_ok=True)
    types = [t for t in args.types.split(',') if t]
    rng = np.random.default_rng(args.seed)
    seen, best_known = load_seen()
    start = cpu_total()
    wall0 = time.time()
    reserve = args.texact + args.theur + 40
    tried = n_eval = n_skip = n_none = 0
    best_here = 0
    while (cpu_total() - start < args.cpu - reserve and time.time() - wall0 < args.wall
           and tried < args.maxgroups):
        tried += 1
        grp = sample_group(rng, types)
        if grp is None:
            n_none += 1
            continue
        analysis = analyse_group(grp['gens'])
        fp = analysis[-1]
        if fp in seen:
            n_skip += 1
            continue
        seen.add(fp)
        rec, idx = evaluate(grp, args, args.seed * 1000 + tried, analysis)
        rec['t_cpu_total'] = round(cpu_total() - start, 1)
        rec['t_wall'] = round(time.time() - wall0, 1)
        if idx is not None and rec['weight'] >= args.minsave:
            rec['gens_file'] = save_gens(fp, grp)
        with open(RUNLOG, 'a') as f:
            f.write(json.dumps(rec) + '\n')
        n_eval += 1
        print(f"[{rec['t_wall']:7.1f}s] {grp['family']} |G|={grp['order_G']} orders={grp['orders']} "
              f"norb={rec['norbits']} K={rec['K']} w={rec['weight']} opt={rec['optimal']} skip={rec['skipped']} "
              f"| {grp['desc'][:90]}", flush=True)
        if idx is not None and rec['weight'] > max(best_known, best_here):
            best_here = rec['weight']
            write_best(idx, grp, rec['weight'])
            with open(BEST_W, 'w') as f:
                f.write(f'{rec["weight"]}\n')
            print('NEW BEST', rec['weight'], grp['desc'], flush=True)
    print(f'done: evaluated {n_eval}, repeats {n_skip}, no-group draws {n_none}, sampled {tried}, '
          f'best this run {best_here}, cpu {cpu_total() - start:.1f}s wall {time.time() - wall0:.1f}s', flush=True)


if __name__ == '__main__':
    main()
