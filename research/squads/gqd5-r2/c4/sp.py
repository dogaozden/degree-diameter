"""Sp(4,9) acting on the 820 points of W(9) (gqlib numbering). Group elements are point permutations."""
import sys, os, random, math
import numpy as np
sys.path.insert(0, '/home/user/degree-diameter/research/theorems/d5gq')
import gqlib

G = gqlib.W(9)
F = G.F
Q = 9
ADD = np.array(F.add, dtype=np.int64)
MUL = np.array(F.mul, dtype=np.int64)
NEG = np.array(F.neg, dtype=np.int64)
INV = np.array([0] + F.inv[1:], dtype=np.int64)
P = np.array(G.coords, dtype=np.int64)          # (820,4)
NP = P.shape[0]
W10 = np.array([1, 9, 81, 729], dtype=np.int64)
LUT = -np.ones(6561, dtype=np.int64)
LUT[P @ W10] = np.arange(NP)
COL = G.col
# form matrix J with x^T J y = x0y2 + x1y3 - x2y0 - x3y1
ONE = 1
J = [[0, 0, 1, 0], [0, 0, 0, 1], [F.neg[1], 0, 0, 0], [0, F.neg[1], 0, 0]]


def normalize_rows(V):
    """V (k,4) nonzero vectors -> normalized (first nonzero coord = 1)."""
    nz = V != 0
    first = nz.argmax(axis=1)
    s = V[np.arange(V.shape[0]), first]
    return MUL[INV[s][:, None], V]


def perm_of_matrix(M):
    M = np.asarray(M, dtype=np.int64)
    out = np.zeros((NP, 4), dtype=np.int64)
    for i in range(4):
        acc = np.zeros(NP, dtype=np.int64)
        for j in range(4):
            acc = ADD[acc, MUL[M[i, j], P[:, j]]]
        out[:, i] = acc
    out = normalize_rows(out)
    codes = out @ W10
    perm = LUT[codes]
    assert (perm >= 0).all()
    return perm


def matmul(A, B):
    A = np.asarray(A); B = np.asarray(B)
    C = np.zeros((4, 4), dtype=np.int64)
    for i in range(4):
        for j in range(4):
            s = 0
            for k in range(4):
                s = F.add[s][F.mul[A[i, k]][B[k, j]]]
            C[i, j] = s
    return C


def transvection(v, c):
    """x -> x + c w(x,v) v with w(x,v) = x^T J v. Matrix I + c * v (Jv)^T."""
    Jv = [0] * 4
    for i in range(4):
        s = 0
        for j in range(4):
            s = F.add[s][F.mul[J[i][j]][v[j]]]
        Jv[i] = s
    M = np.eye(4, dtype=np.int64)
    for i in range(4):
        for j in range(4):
            M[i, j] = F.add[M[i, j]][F.mul[c][F.mul[v[i]][Jv[j]]]]
    return M


def is_symplectic(M):
    M = np.asarray(M)
    Jm = np.array(J)
    MT = np.array([[M[j, i] for j in range(4)] for i in range(4)])
    R = matmul(matmul(MT, Jm), M)
    return np.array_equal(R, Jm)


def perm_order(p):
    seen = np.zeros(len(p), bool); L = 1
    for i in range(len(p)):
        if seen[i]: continue
        c = 0; j = i
        while not seen[j]:
            seen[j] = True; j = p[j]; c += 1
        L = L * c // math.gcd(L, c)
    return L


def cycles(p):
    seen = np.zeros(len(p), bool); out = []
    for i in range(len(p)):
        if seen[i]: continue
        cyc = []; j = i
        while not seen[j]:
            seen[j] = True; cyc.append(int(j)); j = p[j]
        out.append(cyc)
    return out


def compose(a, b):
    """(a after b): x -> a[b[x]]"""
    return a[b]


def check_aut(p):
    """p is a collinearity-preserving permutation"""
    return np.array_equal(COL[np.ix_(p, p)], COL)


def random_sp(rng, length=40):
    M = np.eye(4, dtype=np.int64)
    for _ in range(length):
        v = [rng.randrange(Q) for _ in range(4)]
        if not any(v): continue
        c = rng.randrange(1, Q)
        M = matmul(M, transvection(v, c))
    return M


FROB = np.array([F.mul[F.mul[a][a]][a] for a in range(Q)], dtype=np.int64)  # a^3 per coordinate
def frob_perm():
    out = FROB[P]
    out = normalize_rows(out)
    return LUT[out @ W10]


def orbits_of_group(gens):
    """union-find orbits of the group generated by permutations gens"""
    parent = list(range(NP))
    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]; x = parent[x]
        return x
    for g in gens:
        for i in range(NP):
            a, b = find(i), find(int(g[i]))
            if a != b: parent[a] = b
    d = {}
    for i in range(NP):
        d.setdefault(find(i), []).append(i)
    return list(d.values())


def collinear_pairs_inside(orb):
    o = np.array(orb)
    if len(o) < 2: return False
    return bool(COL[np.ix_(o, o)].any())


