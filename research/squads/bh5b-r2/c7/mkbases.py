import sys
reps = [
((0,1,4),(1,3,1),(4,1,0)),((0,1,4),(1,4,0),(4,0,1)),((0,1,4),(2,2,1),(3,2,0)),((0,1,4),(2,3,0),(3,1,1)),
((0,2,3),(2,1,2),(3,2,0)),((0,2,3),(2,2,1),(3,1,1)),((0,2,3),(2,3,0),(3,0,2)),((1,1,3),(1,3,1),(3,1,1)),
((1,1,3),(2,2,1),(2,2,1)),((1,2,2),(2,1,2),(2,2,1))]
out = sys.argv[1]
for k, M in enumerate(reps):
    edges = []
    for i in range(3):
        for j in range(3):
            edges += [(i, 3+j)] * M[i][j]
    with open(f"{out}/b{k}.txt", "w") as f:
        f.write(f"6 {len(edges)}\n0 0 0 1 1 1\n")
        for u, w in edges: f.write(f"{u} {w}\n")
    print(k, M)
