"""Cyclic-group orbit search for partial ovoids of W(11).
Groups: cyclic subgroups of Sp(4,11) generated by powers of random symplectic elements (products of transvections)."""
import sys, random, time, json
import numpy as np
from pysat.formula import WCNF
from pysat.examples.rc2 import RC2

q = 11
D = np.load('/home/user/degree-diameter/research/squads/gqd5-r1/c2/w11.npz')
P = D['P'] % q; COL = D['col']
N = P.shape[0]
J = np.zeros((4, 4), dtype=np.int64); J[0, 2] = J[1, 3] = 1; J[2, 0] = J[3, 1] = -1
INV = [0] + [pow(a, q - 2, q) for a in range(1, q)]
CODE = np.array([11 ** 3, 11 ** 2, 11, 1])
lookup = -np.ones(q ** 4, dtype=np.int64)
lookup[P @ CODE] = np.arange(N)

def normalize(V):
    V = V % q
    nz = (V != 0)
    first = nz.argmax(axis=1)
    lead = V[np.arange(V.shape[0]), first]
    inv = np.array(INV)[lead]
    return (V * inv[:, None]) % q

def perm_of(g):
    W = normalize(P @ g.T)
    idx = lookup[W @ CODE]
    assert (idx >= 0).all()
    return idx

def is_symp(g):
    return np.array_equal((g.T @ J @ g) % q, J % q)

def transvection(v, c):
    Jv = (J @ v) % q
    return (np.eye(4, dtype=np.int64) + c * np.outer(v, Jv)) % q

def random_symp(rng, k=7):
    g = np.eye(4, dtype=np.int64)
    for _ in range(k):
        v = np.array([rng.randrange(q) for _ in range(4)])
        if not v.any(): continue
        c = rng.randrange(1, q)
        g = (g @ transvection(v, c)) % q
    return g

def order_of(g, cap=3000):
    h = g.copy(); m = 1
    I = np.eye(4, dtype=np.int64)
    while not np.array_equal(h, I):
        h = (h @ g) % q; m += 1
        if m > cap: return None
    return m

def mpow(g, e):
    r = np.eye(4, dtype=np.int64); b = g.copy()
    while e:
        if e & 1: r = (r @ b) % q
        b = (b @ b) % q; e >>= 1
    return r

def orbits_of_perm(perm):
    seen = np.zeros(N, bool); orbs = []
    for s in range(N):
        if seen[s]: continue
        o = []; x = s
        while not seen[x]:
            seen[x] = True; o.append(x); x = perm[x]
        orbs.append(o)
    return orbs

def usable_orbits(orbs):
    good = []
    for o in orbs:
        o = np.array(o)
        if COL[np.ix_(o, o)].any(): continue
        good.append(o)
    return good

def max_union(good, time_limit=None):
    """maximum-weight set of pairwise compatible orbits (no collinear pair across orbits). weight = size."""
    n = len(good)
    if n == 0: return 0, []
    orb_id = np.full(N, -1, dtype=np.int64)
    for i, o in enumerate(good): orb_id[o] = i
    r, c = np.nonzero(COL)
    a, b = orb_id[r], orb_id[c]
    m = (a >= 0) & (b >= 0) & (a != b)
    OC = np.zeros((n, n), bool)
    OC[a[m], b[m]] = True
    OC = OC | OC.T
    w = WCNF()
    for i in range(n):
        w.append([i + 1], weight=len(good[i]))
    ii, jj = np.nonzero(np.triu(OC, 1))
    for i, j in zip(ii, jj):
        w.append([-(int(i) + 1), -(int(j) + 1)])
    with RC2(w) as rc2:
        model = rc2.compute()
    chosen = [i for i in range(n) if model[i] > 0]
    S = sorted(int(x) for i in chosen for x in good[i])
    return len(S), S

