#!/usr/bin/env python3
"""Group multiplication tables for mlift_chart.c / mlift_joint.c (format: n, then the n x n table, T[a][b] = a*b).
usage: python3 groups.py SPEC OUT
SPEC: cyc N | dih N (order 2N) | meta M K R (Z_M x| Z_K, y x y^-1 = x^R, needs R^K = 1 mod M) | prod SPEC1 / SPEC2
      | dicyc N (order 4N) | perm GEN1;GEN2;... (permutation group generated by the given images lists, e.g. 1,2,0;1,0,2)"""
import sys

def table_from_elems(elems, mul):
    idx = {e: i for i, e in enumerate(elems)}
    return [[idx[mul(a, b)] for b in elems] for a in elems]

def cyc(n):
    return table_from_elems(list(range(n)), lambda a, b: (a + b) % n)

def meta(M, K, R):
    assert pow(R, K, M) == 1 % M
    el = [(x, y) for y in range(K) for x in range(M)]
    # (x1, y1)(x2, y2) = (x1 + R^y1 x2, y1 + y2)
    return table_from_elems(el, lambda a, b: ((a[0] + pow(R, a[1], M) * b[0]) % M, (a[1] + b[1]) % K))

def dih(n):
    return meta(n, 2, n - 1) if n > 2 else prod(cyc(2), cyc(n))

def dicyc(n):
    # <x, y | x^{2n} = 1, y^2 = x^n, y x y^-1 = x^-1>, elements x^a y^e
    el = [(a, e) for e in range(2) for a in range(2 * n)]
    def mul(p, q):
        a, e = p; c, f = q
        a2 = (a + (c if e == 0 else -c)) % (2 * n)
        if e and f:
            return ((a2 + n) % (2 * n), 0)
        return (a2, (e + f) % 2)
    return table_from_elems(el, mul)

def prod(T1, T2):
    n1, n2 = len(T1), len(T2)
    return [[T1[a // n2][b // n2] * n2 + T2[a % n2][b % n2] for b in range(n1 * n2)] for a in range(n1 * n2)]

def perm(gens):
    gens = [tuple(g) for g in gens]
    e = tuple(range(len(gens[0])))
    el = [e]; seen = {e}; i = 0
    while i < len(el):
        for g in gens:
            h = tuple(g[x] for x in el[i])
            if h not in seen:
                seen.add(h); el.append(h)
        i += 1
    return table_from_elems(el, lambda a, b: tuple(a[x] for x in b))

def parse(tok):
    t = tok.pop(0)
    if t == 'cyc': return cyc(int(tok.pop(0)))
    if t == 'dih': return dih(int(tok.pop(0)))
    if t == 'dicyc': return dicyc(int(tok.pop(0)))
    if t == 'meta':
        M, K, R = int(tok.pop(0)), int(tok.pop(0)), int(tok.pop(0)); return meta(M, K, R)
    if t == 'perm':
        return perm([list(map(int, g.split(','))) for g in tok.pop(0).split(';')])
    if t == 'prod':
        i = tok.index('/'); left = tok[:i]; del tok[:i + 1]
        return prod(parse(left), parse(tok))
    raise ValueError(t)

def check(T):
    n = len(T)
    e = next(i for i in range(n) if all(T[i][j] == j for j in range(n)))
    assert all(sorted(row) == list(range(n)) for row in T)
    for a in range(0, n, max(1, n // 7)):
        for b in range(n):
            for c in range(0, n, max(1, n // 5)):
                assert T[T[a][b]][c] == T[a][T[b][c]]
    return e

if __name__ == '__main__':
    T = parse(sys.argv[1].split())
    check(T)
    with open(sys.argv[2], 'w') as f:
        f.write(f"{len(T)}\n"); f.write(' '.join(str(x) for row in T for x in row) + '\n')
    print('order', len(T))
