"""Lean certificates for the (9,5) Haar record on 2640 vertices: the Haar graph of SL(2, 11).

  python3 research/d5/make_haar_cert_2640.py          (from the repository root)

Writes lean/BipartiteDD/Haar/Cert2640.lean. The group and the numbering of its elements are in
lean/BipartiteDD/Haar/SL211.lean (hand-written); this script follows the same formulas:

  quad(n)   the matrix [[a, b], [c, d]] mod 11 of the element with index n < 1320, with
            n < 110:   c = 0, a = n // 11 + 1, b = n % 11, d = a^-1
            n >= 110:  m = n - 110, c = m // 121 + 1, a = (m // 11) % 11, d = m % 11, b = (a d - 1) c^-1
  enc(g)    the inverse of quad, on det 1 matrices.

For every n, a certificate lists indices (i, j, k, l) into the connection set S with

  cert1: g = s_i^-1 * s_j * s_k^-1 * s_l        (covers (S^-1 S)^2)
  cert2: g = s_i * s_j^-1 * s_k * s_l^-1        (covers (S S^-1)^2)

where g = quad(n). Lean re-checks every entry with `decide +kernel`; the certificates are not trusted.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LEAN = ROOT / "lean" / "BipartiteDD" / "Haar"

P = 11
N = 1320
# Connection set: matrices (a, b, c, d) = [[a, b], [c, d]] mod 11, in the order of the record file.
S = [(1, 0, 0, 1), (0, 1, 10, 9), (1, 1, 9, 10), (10, 7, 4, 4), (9, 10, 4, 7),
     (0, 4, 8, 4), (3, 4, 0, 4), (7, 9, 2, 9), (9, 4, 4, 8)]
INV = [0, 1, 6, 4, 3, 9, 2, 8, 7, 5, 10]


def mul(g, h):
    a, b, c, d = g
    e, f, x, y = h
    return ((a * e + b * x) % P, (a * f + b * y) % P, (c * e + d * x) % P, (c * f + d * y) % P)


def inv(g):
    a, b, c, d = g
    return (d % P, (-b) % P, (-c) % P, a % P)


def quad(n):
    if n < 110:
        a = n // 11 + 1
        return (a, n % 11, 0, INV[a])
    m = n - 110
    c = m // 121 + 1
    a = (m // 11) % 11
    d = m % 11
    return (a, ((a * d - 1) * INV[c]) % P, c, d)


def form1(s, t):
    """s^-1 t, the factor of cert1 (g = (s_i^-1 s_j)(s_k^-1 s_l))."""
    return mul(inv(s), t)


def form2(s, t):
    """s t^-1, the factor of cert2 (g = (s_i s_j^-1)(s_k s_l^-1))."""
    return mul(s, inv(t))


def certificate(g, op):
    """Indices (i, j, k, l) with g = op(s_i, s_j) * op(s_k, s_l)."""
    pairs = {}
    for i in range(9):
        for j in range(9):
            pairs.setdefault(op(S[i], S[j]), (i, j))
    for k in range(9):
        for l in range(9):
            x = mul(g, inv(op(S[k], S[l])))
            if x in pairs:
                i, j = pairs[x]
                return (i, j, k, l)
    raise AssertionError(("no certificate", g))


def certificates():
    cert1, cert2 = [], []
    for n in range(N):
        g = quad(n)
        assert (g[0] * g[3] - g[1] * g[2]) % P == 1, n
        cert1.append(certificate(g, form1))
        cert2.append(certificate(g, form2))
    return cert1, cert2


def lean_list(ws):
    rows = []
    for t in range(0, len(ws), 10):
        rows.append("    " + ", ".join("(%d, %d, %d, %d)" % w for w in ws[t:t + 10]))
    return "[\n" + ",\n".join(rows) + "]"


def cert_file(cert1, cert2):
    return f"""/- Generated by research/d5/make_haar_cert_2640.py. Do not edit by hand. -/
import BipartiteDD.Haar.SL211
import Mathlib.Data.Fin.VecNotation

/-! Covering certificates for the (9,5) Haar record on 2640 vertices, the Haar graph of `SL(2, 11)`.
Entry `n` of `cert1` (resp. `cert2`) is a quadruple of indices into `sS` for the element `grpOf n`.
The checks `ok1`, `ok2` run over all `n < 1320` by computation, and `cover1`, `cover2` give the
covering hypotheses of `Haar.Main`. -/

namespace BipartiteDD.Haar.SL211

open BipartiteDD.Haar

/-- The connection set `S` of the (9,5) record on 2640 vertices, in the order of its record file. -/
def sS : Fin 9 → Grp :=
  ![⟨1, 0, 0, 1, by decide⟩, ⟨0, 1, 10, 9, by decide⟩, ⟨1, 1, 9, 10, by decide⟩,
    ⟨10, 7, 4, 4, by decide⟩, ⟨9, 10, 4, 7, by decide⟩, ⟨0, 4, 8, 4, by decide⟩,
    ⟨3, 4, 0, 4, by decide⟩, ⟨7, 9, 2, 9, by decide⟩, ⟨9, 4, 4, 8, by decide⟩]

/-- `S` as a finset. -/
def SS : Finset Grp := Finset.univ.image sS

theorem card_SS : SS.card = 9 := by decide +kernel

theorem sS_mem (i : Fin 9) : sS i ∈ SS :=
  Finset.mem_image_of_mem sS (Finset.mem_univ i)

set_option maxRecDepth 100000 in
/-- `grpOf n = s_i⁻¹ s_j s_k⁻¹ s_l`. -/
def cert1 : List (Fin 9 × Fin 9 × Fin 9 × Fin 9) := {lean_list(cert1)}

set_option maxRecDepth 100000 in
/-- `grpOf n = s_i s_j⁻¹ s_k s_l⁻¹`. -/
def cert2 : List (Fin 9 × Fin 9 × Fin 9 × Fin 9) := {lean_list(cert2)}

/-- The first certificate is right at index `n`. -/
def ok1 (n : ℕ) : Bool :=
  let w := cert1.getD n (0, 0, 0, 0)
  decide (grpOf n = (sS w.1)⁻¹ * sS w.2.1 * (sS w.2.2.1)⁻¹ * sS w.2.2.2)

/-- The second certificate is right at index `n`. -/
def ok2 (n : ℕ) : Bool :=
  let w := cert2.getD n (0, 0, 0, 0)
  decide (grpOf n = sS w.1 * (sS w.2.1)⁻¹ * sS w.2.2.1 * (sS w.2.2.2)⁻¹)

set_option maxRecDepth 100000 in
theorem ok1_all : (List.range 1320).all ok1 = true := by decide +kernel

set_option maxRecDepth 100000 in
theorem ok2_all : (List.range 1320).all ok2 = true := by decide +kernel

/-- Every element is `a⁻¹ b c⁻¹ d` with `a, b, c, d ∈ SS`. -/
theorem cover1 : ∀ g : Grp, ∃ a ∈ SS, ∃ b ∈ SS, ∃ c ∈ SS, ∃ d ∈ SS, g = a⁻¹ * b * c⁻¹ * d := by
  intro g
  have h := List.all_eq_true.mp ok1_all (enc g.a g.b g.c g.d) (List.mem_range.mpr (enc_lt g))
  simp only [ok1, decide_eq_true_eq, grpOf_enc] at h
  exact ⟨_, sS_mem _, _, sS_mem _, _, sS_mem _, _, sS_mem _, h⟩

/-- Every element is `a b⁻¹ c d⁻¹` with `a, b, c, d ∈ SS`. -/
theorem cover2 : ∀ g : Grp, ∃ a ∈ SS, ∃ b ∈ SS, ∃ c ∈ SS, ∃ d ∈ SS, g = a * b⁻¹ * c * d⁻¹ := by
  intro g
  have h := List.all_eq_true.mp ok2_all (enc g.a g.b g.c g.d) (List.mem_range.mpr (enc_lt g))
  simp only [ok2, decide_eq_true_eq, grpOf_enc] at h
  exact ⟨_, sS_mem _, _, sS_mem _, _, sS_mem _, _, sS_mem _, h⟩

end BipartiteDD.Haar.SL211
"""


def main():
    # verify the Python side of the construction before writing anything
    assert len(set(quad(n) for n in range(N))) == N
    cert1, cert2 = certificates()
    (LEAN / "Cert2640.lean").write_text(cert_file(cert1, cert2))
    print("wrote Cert2640.lean", len(cert1), len(cert2))


if __name__ == "__main__":
    sys.exit(main())
