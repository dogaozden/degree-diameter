"""Recover (G, S) for a bi-Cayley (Haar) graph whose automorphism group is regular on each side.

Works for graphs where Aut has 2 orbits (the sides) or, more generally, where a subgroup acts
semiregularly: we take the full group generated by pynauty generators and require |Aut| = n/2.
Prints the group as Z_p x| Z_k (x of order p normal, y with y^-1 x y = x^r) and the connection
set S as pairs (i, j) meaning x^i y^j, normalised so that the identity is in S.
"""
import json
import sys
from collections import Counter

import pynauty

sys.path.insert(0, __file__.rsplit("/", 1)[0])
from invariants import load, sides  # noqa: E402


def compose(p, q):
    """p then q."""
    return tuple(q[i] for i in p)


def main(path):
    n, adj = load(path)
    col = sides(n, adj)
    G = pynauty.Graph(n, adjacency_dict={v: list(adj[v]) for v in range(n)})
    gens, g1, g2, orbits, norb = pynauty.autgrp(G)
    N = int(round(g1 * 10 ** g2))
    side0 = [v for v in range(n) if col[v] == 0]
    side1 = [v for v in range(n) if col[v] == 1]
    print(f"== {path}: n={n} |Aut|={N}")
    a0 = side0[0]
    # BFS the group, element identified by image of a0 (regular on side 0 if N = n/2)
    ident = tuple(range(n))
    elems = {a0: ident}
    frontier = [ident]
    gens = [tuple(g) for g in gens]
    while frontier:
        nf = []
        for p in frontier:
            for g in gens:
                r = compose(p, g)
                if r[a0] not in elems:
                    elems[r[a0]] = r
                    nf.append(r)
        frontier = nf
    assert len(elems) == len(side0) == N, (len(elems), len(side0), N)
    E = list(elems.values())

    def order(p):
        k, r = 1, p
        while r != ident:
            r = compose(r, p)
            k += 1
        return k

    oc = Counter(order(p) for p in E)
    print(" element orders:", sorted(oc.items()))
    ab = all(compose(p, q) == compose(q, p) for p in gens for q in gens)
    print(" abelian:", ab)
    # pick x = element of largest prime order whose Sylow is normal & cyclic, y complement generator
    m = max(oc)
    def inv(e):
        return tuple(sorted(range(n), key=lambda i: e[i]))
    x = None
    for e in E:
        if order(e) != m:
            continue
        cyc = [ident]
        for _ in range(m - 1):
            cyc.append(compose(cyc[-1], e))
        cs = {c[a0] for c in cyc}
        if all(compose(compose(inv(g), e), g)[a0] in cs for g in gens):
            x = e
            break
    assert x is not None, "no normal cyclic subgroup of max order"
    k = N // m
    ys = [e for e in E if order(e) == k]
    p, fac = m, {m: 1}
    print(f" m={m} (normal cyclic), k={k}, #elements of order k: {len(ys)}")
    pw = [ident]
    for _ in range(m - 1):
        pw.append(compose(pw[-1], x))
    P = {e[a0]: i for i, e in enumerate(pw)}
    y = None
    for cand in ys:
        # y^-1 x y in <x>?
        yinv = tuple(sorted(range(n), key=lambda i: cand[i]))
        c = compose(compose(yinv, x), cand)
        yp, ok = cand, True
        for _ in range(k - 1):
            if yp[a0] in P:
                ok = False
                break
            yp = compose(yp, cand)
        if ok and c[a0] in P:
            y = cand
            r = P[c[a0]]
            break
    if y is None:
        print(" no cyclic complement found")
        return
    print(f" G = <x,y | x^{p**fac[p]}, y^{k}, y^-1 x y = x^{r}>")
    # coordinates x^i y^j for every element
    ypw = [ident]
    for _ in range(k - 1):
        ypw.append(compose(ypw[-1], y))
    coord = {}
    for i, xe in enumerate(pw):
        for j, ye in enumerate(ypw):
            coord[compose(xe, ye)[a0]] = (i, j)
    assert len(coord) == N
    # connection set: neighbours of a0 are b0^h; choose b0 = first neighbour
    b0 = sorted(adj[a0])[0]
    bcoord = {}
    for img_a0, e in elems.items():
        bcoord[e[b0]] = coord[img_a0]
    S = sorted(bcoord[b] for b in adj[a0])
    print(f" S (as x^i y^j, b0 = identity): {S}")
    return N, p, k, r, S


if __name__ == "__main__":
    for path in sys.argv[1:]:
        main(path)
