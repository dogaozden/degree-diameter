"""Geometry helpers for H(q), prime q (hexgen coordinates: points of x0x4 + x1x5 + x2x6 = x3^2 in PG(6,q)).

H = Geo(path): H.q, H.N, H.lines (N x (q+1) point ids), H.plines (N x (q+1) line ids), H.coord (N x 7).
H.act(Mat7) -> (perm on points, perm on lines) for a 7x7 matrix that preserves H(q) (checked).
sl3(g) -> the 7x7 matrix of g in SL(3,q): X -> gX, Y -> g^{-T} Y, x3 fixed.
orbits(perms, n) -> orbit id array for the group generated by the permutations.
"""
import numpy as np


class Geo:
    def __init__(self, path):
        raw = open(path, "rb").read()
        q, N, L = np.frombuffer(raw[:12], dtype=np.int32)
        self.q, self.N = int(q), int(N)
        self.lines = np.frombuffer(raw[12:12 + 4 * L * (q + 1)], dtype=np.int32).reshape(L, q + 1).astype(np.int64)
        self.coord = np.frombuffer(raw[12 + 4 * L * (q + 1):], dtype=np.uint8).reshape(N, 7).astype(np.int64)
        q = self.q
        pl = [[] for _ in range(self.N)]
        for l, pts in enumerate(self.lines):
            for p in pts:
                pl[p].append(l)
        self.plines = np.array(pl, dtype=np.int64)
        self.w = q ** np.arange(7, dtype=np.int64)
        self.inv = np.array([0] + [pow(a, q - 2, q) for a in range(1, q)], dtype=np.int64)
        codes = self.code(self.coord)
        self.order = np.argsort(codes)
        self.sorted_codes = codes[self.order]
        # line lookup by the sorted pair of its two smallest point ids
        self.lkey = {}
        for l, pts in enumerate(self.lines):
            s = sorted(pts)
            self.lkey[(s[0], s[1])] = l

    def normalize(self, V):
        V = V % self.q
        nz = (V != 0)
        first = nz.argmax(axis=1)
        lead = V[np.arange(len(V)), first]
        return (V * self.inv[lead][:, None]) % self.q

    def code(self, V):
        return (V * self.w).sum(axis=1)

    def lookup(self, V):
        c = self.code(self.normalize(V))
        idx = np.searchsorted(self.sorted_codes, c)
        assert np.all(self.sorted_codes[np.minimum(idx, len(c) and self.N - 1)] == c), "not a point"
        return self.order[idx]

    def act(self, M):
        """M: 7x7 matrix acting on column vectors. Returns (point perm, line perm)."""
        img = self.lookup(self.coord @ M.T)
        assert len(np.unique(img)) == self.N
        limg = np.empty(self.N, dtype=np.int64)
        P = img[self.lines]
        P.sort(axis=1)
        for l in range(self.N):
            limg[l] = self.lkey[(P[l, 0], P[l, 1])]
        return img, limg


def inv3(g, q):
    g = np.array(g, dtype=np.int64) % q
    a = g
    det = (a[0, 0] * (a[1, 1] * a[2, 2] - a[1, 2] * a[2, 1]) - a[0, 1] * (a[1, 0] * a[2, 2] - a[1, 2] * a[2, 0])
           + a[0, 2] * (a[1, 0] * a[2, 1] - a[1, 1] * a[2, 0])) % q
    adj = np.zeros((3, 3), dtype=np.int64)
    for i in range(3):
        for j in range(3):
            m = np.delete(np.delete(a, i, 0), j, 1)
            adj[j, i] = ((-1) ** (i + j)) * (m[0, 0] * m[1, 1] - m[0, 1] * m[1, 0])
    return (adj * pow(int(det), q - 2, q)) % q, det


def sl3(g, q):
    g = np.array(g, dtype=np.int64) % q
    gi, det = inv3(g, q)
    M = np.zeros((7, 7), dtype=np.int64)
    M[0:3, 0:3] = g
    M[3, 3] = 1
    M[4:7, 4:7] = gi.T
    return M % q


def orbits(perms, n):
    parent = np.arange(n)

    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x
    for p in perms:
        for x in range(n):
            a, b = find(x), find(int(p[x]))
            if a != b:
                parent[a] = b
    roots = np.array([find(x) for x in range(n)])
    _, oid = np.unique(roots, return_inverse=True)
    return oid
