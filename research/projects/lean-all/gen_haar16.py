#!/usr/bin/env python3
"""Lean files for a Haar record of SL(2,16) x Z_n (research/frontier/sols format 'sl 16 poly x^4+x+1 n n'), checked by
LeanAll/HaarGF16.lean (cover16).

usage: gen_haar16.py SOLFILE OUTDIR MODULE THEOREM [--per K]

Batch i (i < 255 * 16) fixes the matrix with SL(2,16) batch i / 16 and free entry i % 16 (as HaarGF16.bS16, jS16);
slot j < n is the Z_n value j. Words: D even only (s0 * s1^-1 s2 * ..., D - 1 letters). The certificate words come from
a BFS over the group, each re-evaluated before it is written.
"""
import argparse, os, re, sys

W = 40


def gmul(a, b):
    r = 0
    for i in range(4):
        if b >> i & 1:
            r ^= a << i
    for i in (6, 5, 4):
        if r >> i & 1:
            r ^= 0b10011 << (i - 4)
    return r


GINV = {a: next(b for b in range(1, 16) if gmul(a, b) == 1) for a in range(1, 16)}


def chunked(v, bits=None, chunk=4096):
    if bits is None:
        bits = max(v.bit_length(), 1)
    if bits <= chunk:
        return hex(v)
    h = max(chunk, (bits // 2 // chunk) * chunk)
    return f'({chunked(v & ((1 << h) - 1), h, chunk)} + {chunked(v >> h, bits - h, chunk)} <<< {h})'


def jtree(leaves):
    if len(leaves) == 1:
        return leaves[0][0]
    h = len(leaves) // 2
    return (f'(range_join (Q := QE) (lo := {leaves[0][1]}) (mid := {leaves[h][1]}) (hi := {leaves[-1][2]}) '
            f'{jtree(leaves[:h])} {jtree(leaves[h:])})')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('sol')
    ap.add_argument('outdir')
    ap.add_argument('module')
    ap.add_argument('theorem')
    ap.add_argument('--per', type=int, default=100)
    ap.add_argument('--source', default='')
    args = ap.parse_args()
    lines = [l for l in open(args.sol).read().split('\n') if l.strip()]
    h = lines[0].split()
    assert h[2] == 'sl' and h[3] == '16' and h[4] == 'poly' and h[5] == 'x^4+x+1' and h[6] == 'n'
    deg, D, n = int(h[0]), int(h[1]), int(h[7])
    assert D % 2 == 0, 'even D only'
    gens = []
    for l in lines[1:]:
        m = re.match(r'\s*\d+\s+mat\((\d+),(\d+),(\d+),(\d+)\)\s+z=(\d+)', l)
        if m:
            gens.append(tuple(int(x) for x in m.groups()))
    assert len(gens) == deg
    for a, b, c, d, z in gens:
        assert gmul(a, d) ^ gmul(b, c) == 1
    L = D - 1
    K = (D - 2) // 2
    NB = 255 * 16
    G = NB * n

    def mul(x, y):
        a, b, c, d, z = x
        e, f, g, hh, w = y
        return (gmul(a, e) ^ gmul(b, g), gmul(a, f) ^ gmul(b, hh), gmul(c, e) ^ gmul(d, g), gmul(c, f) ^ gmul(d, hh),
                (z + w) % n)

    def inv(x):
        a, b, c, d, z = x
        return (d, b, c, a, (-z) % n)

    def idx(x):
        a, b, c, d, z = x
        if c != 0:
            bs, js = a * 15 + (c - 1), d
        else:
            bs, js = 16 * 15 + (a - 1), b
        return (bs * 16 + js) * n + z

    one = (1, 0, 0, 1, 0)
    pairs = [mul(inv(gens[s]), gens[t]) for s in range(deg) for t in range(deg)]
    # BFS over K pairs
    par = {idx(one): None}
    elem = {idx(one): one}
    front = [one]
    for _ in range(K):
        nxt = []
        for x in front:
            ix = idx(x)
            for k, pr in enumerate(pairs):
                y = mul(x, pr)
                iy = idx(y)
                if iy not in par:
                    par[iy] = (ix, k)
                    elem[iy] = y
                    nxt.append(y)
        front = nxt
    codes = [0] * G
    for i in range(G):
        # element with index i
        r, z = divmod(i, n)
        bs, js = divmod(r, 16)
        if bs < 16 * 15:
            a, c = divmod(bs, 15)
            c += 1
            d = js
            b = gmul(gmul(a, d) ^ 1, GINV[c])
        else:
            a = bs - 16 * 15 + 1
            c, b = 0, js
            d = GINV[a]
        x = (a, b, c, d, z)
        assert idx(x) == i
        found = None
        for s in range(deg):
            y = mul(inv(gens[s]), x)
            if idx(y) in par:
                found = (s, idx(y))
                break
        assert found, i
        s0, iy = found
        ps = []
        while par[iy] is not None:
            iy, k = par[iy]
            ps.append(k)
        ps.reverse()
        ps += [0] * (K - len(ps))
        dig = [s0] + [q for k in ps for q in divmod(k, deg)]
        w = one
        for t in range(L):
            w = mul(w, inv(gens[dig[t]]) if t % 2 == 1 else gens[dig[t]])
        assert idx(w) == i, i
        codes[i] = sum(dg << (4 * t) for t, dg in enumerate(dig))
    M = args.module
    os.makedirs(args.outdir, exist_ok=True)
    hdr = '/- Generated by research/projects/lean-all/gen_haar16.py. Do not edit by hand. -/\n'
    opens = ('open BipartiteDD.LeanAll BipartiteDD.LeanAll.GF16 BipartiteDD.LeanAll.HaarSwar BipartiteDD.LeanAll.Swar '
             'BipartiteDD.LeanAll.HaarSL BipartiteDD.LeanAll.HaarProd BipartiteDD.LeanAll.HaarGF8 '
             'BipartiteDD.LeanAll.HaarGF16 Matrix')
    Kty = f'Multiplicative (ZMod {n}) × SpecialLinearGroup (Fin 2) GF16'
    rz = sum((j % n) << (W * j) for j in range(n))

    def stmt(i):
        r, jj = f'({i} / 16)', f'({i} % 16)'
        return (f'∃ Dig, batchOK Pm ONES ltE Dig true ONES 0 0 0 RZ = true ∧ batchOK16 Pm ONES lmE Dig (kindB 16 {r}) '
                f'(sp (mk (aB 16 {r})) * ONES) (sp (mk {jj}) * ONES) (sp (mk (cB 16 {r})) * ONES) (sp (mk {jj}) * ONES) = true')

    with open(os.path.join(args.outdir, 'Defs.lean'), 'w') as f:
        f.write(hdr + 'import BipartiteDD.LeanAll.HaarGF16\n\n')
        src = f' ({args.source})' if args.source else ''
        f.write(f'/-! The Haar graph of `SL(2,16) × Z{n}`{src}: degree {deg}, diameter {D}, {2 * G} vertices. {NB} batches of '
                f'{n} slots. -/\n\n')
        f.write(f'namespace {M}\n\n{opens}\n\n')
        f.write('/-- The `Z_n` parts of the generators, as letters with identity matrices over `ZMod 2`. -/\ndef genZ : ℕ → Let\n')
        for u, g in enumerate(gens):
            f.write(f'  | {u} => ⟨1, 0, 0, 1, {g[4]}⟩\n')
        f.write('  | _ => ⟨1, 0, 0, 1, 0⟩\n\n')
        f.write(f'def sZ (u : ℕ) : G 2 {n} := gOf (genZ u)\n\n')
        f.write('/-- The matrices of the generators (codes over `GF16`). -/\ndef genM : ℕ → Q16\n')
        for u, g in enumerate(gens):
            f.write(f'  | {u} => (mk {g[0]}, mk {g[1]}, mk {g[2]}, mk {g[3]})\n')
        f.write('  | _ => (1, 0, 0, 1)\n\n')
        f.write('def s2 (u : ℕ) : SpecialLinearGroup (Fin 2) GF16 := mkSL16 (genM u)\n\n')
        f.write(f'/-- The generators. -/\ndef sK (u : ℕ) : {Kty} := ((sZ u).2, s2 u)\n\n')
        f.write('def invE (t : ℕ) : Bool := decide (t % 2 = 1)\n\n')
        f.write(f'def ltE (t u : ℕ) : Let := cond (invE t) (invLet 2 {n} (genZ u)) (genZ u)\n\n')
        f.write('def lmE (t u : ℕ) : Q16 := cond (invE t) (invQ16 (genM u)) (genM u)\n\n')
        f.write(f'def Pm : Prm := ⟨{W}, {n}, 2, {n}, 30, {2 ** 29}, {deg}, {L}⟩\n\n')
        f.write('theorem Pm_valid : Pm.valid := by decide\n\n')
        f.write(f'def ONES : ℕ := (2 ^ ({W} * {n}) - 1) / (2 ^ {W} - 1)\n\n')
        f.write(f'theorem hO : ONES = pkF Pm.w (fun _ => 1) Pm.N := (pkF_one_eq {W} {n} (by norm_num)).symm\n\n')
        f.write(f'def RZ : ℕ := {hex(rz)}\n\n')
        f.write(f'theorem hRZ : RZ = pkF Pm.w (fun j => j % {n}) Pm.N := by decide +kernel\n\n')
        f.write(f'theorem detOK : ∀ u < {deg}, DetOK 2 (genZ u) := by decide\n\n')
        f.write(f'theorem genB : ∀ u < {deg}, (genZ u).f ≤ 2 ∧ (genZ u).g ≤ 2 ∧ (genZ u).zw ≤ {n} := by decide\n\n')
        f.write('theorem letOKE : LetOK Pm ltE := by unfold LetOK; decide\n\n')
        f.write(f'theorem letRepE : LetRep sZ invE Pm.Δ Pm.L ltE :=\n'
                f'  letRep_of sZ invE {deg} {L} genZ (fun _ _ => rfl) detOK genB ltE (fun _ _ => rfl)\n\n')
        f.write(f'theorem detOK2 : ∀ u < {deg}, (genM u).1 * (genM u).2.2.2 - (genM u).2.1 * (genM u).2.2.1 = 1 := by decide\n\n')
        f.write(f'theorem letRep2E : LetRep16 s2 invE Pm.Δ Pm.L lmE :=\n'
                f'  letRep16_of s2 invE {deg} {L} genM (fun _ _ => rfl) detOK2 lmE (fun _ _ => rfl)\n\n')
        f.write(f'/-- Batch `i` passes. -/\ndef QE (i : ℕ) : Prop := {stmt("i")}\n\n')
        f.write(f'end {M}\n')
    mods = []
    for mi, lo in enumerate(range(0, NB, args.per)):
        hi = min(NB, lo + args.per)
        mod = f'BatE{mi:03d}'
        mods.append((mod, lo, hi))
        with open(os.path.join(args.outdir, mod + '.lean'), 'w') as f:
            f.write(hdr + f'import BipartiteDD.LeanAll.Range\nimport {M}.Defs\n\nnamespace {M}\n\n{opens}\n\n')
            f.write('set_option maxRecDepth 100000\n\n')
            for i in range(lo, hi):
                dig = sum(codes[i * n + j] << (W * j) for j in range(n))
                f.write(f'theorem bE{i} : {stmt(i)} :=\n  ⟨{chunked(dig)}, by decide +kernel, by decide +kernel⟩\n\n')
            leaves = [(f'(range_one (Q := QE) (b := {i}) bE{i})', i, i + 1) for i in range(lo, hi)]
            f.write(f'theorem rangeE{mi:03d} : ∀ i, {lo} ≤ i → i < {hi} → QE i :=\n  {jtree(leaves)}\n\nend {M}\n')
    with open(os.path.join(args.outdir, 'CoverE.lean'), 'w') as f:
        f.write(hdr + 'import BipartiteDD.LeanAll.Range\n')
        for mod, _, _ in mods:
            f.write(f'import {M}.{mod}\n')
        f.write(f'\nnamespace {M}\n\n{opens}\n\n')
        f.write(f'theorem batchesE : ∀ i < (16 * 16 - 1) * 16, QE i := by\n  intro i hi\n  have hi\' : i < {NB} := hi\n')
        f.write(f'  exact {jtree([(f"rangeE{mod[4:]}", lo, hi) for mod, lo, hi in mods])} i (Nat.zero_le i) hi\'\n\n')
        f.write(f'theorem wordsE : ∀ x : {Kty}, ∃ dg : ℕ → ℕ, (∀ t < Pm.L, dg t < Pm.Δ) ∧ wordX sK invE dg Pm.L = x :=\n')
        f.write('  cover16 s2 invE sZ Pm Pm_valid (by decide) rfl rfl hO hRZ letOKE letRepE letRep2E batchesE\n\n')
        f.write(f'end {M}\n')
    with open(os.path.join(args.outdir, 'Record.lean'), 'w') as f:
        f.write(hdr + f'import {M}.CoverE\n\nnamespace {M}\n\n{opens}\n\n')
        f.write(f'theorem record : ∃ H : SimpleGraph (Fin {2 * G}), BipartiteDD.IsBipartiteDegDiam H {deg} {D} := by\n')
        f.write(f'  have h := gen_record_even sK invE (fun _ => rfl) {deg} {K} (fun x => wordsE x)\n')
        f.write('  rw [card_Z_SL16] at h\n  exact h\n\n')
        f.write(f'end {M}\n\nopen {M} in\n')
        f.write(f'/-- A bipartite graph on {2 * G} vertices with degree at most {deg} and diameter at most {D}: the Haar graph of '
                f'`SL(2,16) × Z{n}`. -/\n')
        f.write(f'theorem {args.theorem} : ∃ H : SimpleGraph (Fin {2 * G}), BipartiteDD.IsBipartiteDegDiam H {deg} {D} :=\n'
                f'  record\n')
    print(f'wrote {args.outdir}: {NB} batches in {len(mods)} modules', file=sys.stderr)


if __name__ == '__main__':
    main()
