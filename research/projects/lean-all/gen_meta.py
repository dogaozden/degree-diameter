#!/usr/bin/env python3
"""Lean files for a Haar record of a metacyclic group Z_m ⋊_r Z_k (research/frontier/sols format, group 'meta m k r',
n = 1), checked element by element.

usage: gen_meta.py SOLFILE OUTDIR MODULE THEOREM [--stages K]

Writes (namespace MODULE):
  Grp.lean        the group (the text of research/lean-haarD/gen_lift58410.py's `meta_module`, in this namespace)
  Defs.lean       the connection set, the word shapes and the stage check
  Stage<K><ss>    one packed table of word codes per stage, checked by `decide +kernel`
  Record.lean     the record theorem through HaarProd.gen_record_odd / gen_record_even
The words are those of LeanAll/HaarProd.lean (`wordX`): D odd: left and right words of D - 1 letters; D even: words
`s0 · s1⁻¹ s2 · …` of D - 1 letters. Codes are base-|S| digit strings; every word is re-checked in Python first.
"""
import argparse, importlib.util, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..', '..'))


def load_lift():
    path = os.path.join(REPO, 'research', 'lean-haarD', 'gen_lift58410.py')
    spec = importlib.util.spec_from_file_location('gen_lift58410', path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def read_sol(path):
    lines = [l for l in open(path).read().split('\n') if l.strip()]
    h = lines[0].split()
    deg, D = int(h[0]), int(h[1])
    assert h[2] == 'meta' and h[6] == 'n' and h[7] == '1', 'meta m k r with n = 1 only'
    m, k, r = int(h[3]), int(h[4]), int(h[5])
    S = []
    for l in lines[1:]:
        mt = re.match(r'\s*\d+\s+meta\(a=(\d+),j=(\d+)\)\s+z=0', l)
        if mt:
            S.append((int(mt.group(1)), int(mt.group(2))))
    assert len(S) == deg and len(set(S)) == deg
    return deg, D, m, k, r, S


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('sol')
    ap.add_argument('outdir')
    ap.add_argument('module')
    ap.add_argument('theorem')
    ap.add_argument('--stages', type=int, default=20)
    ap.add_argument('--source', default='')
    args = ap.parse_args()
    deg, D, m, k, r, S = read_sol(args.sol)
    N = m * k
    lift = load_lift()
    mul, inv = lift.group(m, k, r)
    L = D - 1
    kinds = ['E'] if D % 2 == 0 else ['L', 'R']
    invpat = {'E': lambda t: t % 2 == 1, 'R': lambda t: t % 2 == 1, 'L': lambda t: t % 2 == 0}
    invlean = {'E': 'decide (t % 2 = 1)', 'R': 'decide (t % 2 = 1)', 'L': 'decide (t % 2 = 0)'}
    base = deg
    bits = (base ** L - 1).bit_length()
    M = args.module
    os.makedirs(args.outdir, exist_ok=True)
    hdr = '/- Generated by research/projects/lean-all/gen_meta.py. Do not edit by hand. -/\n'

    # codes: least code of a word for every element
    codes = {}
    for kd in kinds:
        seen = {}
        for code in range(base ** L):
            el = (0, 0)
            c = code
            for t in range(L):
                d = c % base
                c //= base
                el = mul(el, inv(S[d]) if invpat[kd](t) else S[d])
            idx = el[0] * k + el[1]
            if idx not in seen:
                seen[idx] = code
        assert len(seen) == N, (kd, 'uncovered', N - len(seen))
        codes[kd] = [seen[i] for i in range(N)]

    spec = dict(m=m, k=k, r=r, N=N, nrec=2 * N, grp='Grp')
    gtext = lift.meta_module(spec).replace('BipartiteDD.Haar.LiftA.Grp', f'{M}.Grp')
    with open(os.path.join(args.outdir, 'Grp.lean'), 'w') as f:
        f.write(hdr + gtext)
    G = f'{M}.Grp'
    size = -(-N // args.stages)
    with open(os.path.join(args.outdir, 'Defs.lean'), 'w') as f:
        f.write(hdr)
        f.write(f'import {G}\nimport BipartiteDD.LeanAll.HaarProd\n\n')
        src = f' ({args.source})' if args.source else ''
        f.write(f'/-! The Haar graph of `Z_{m} ⋊_{r} Z_{k}`{src}: degree {deg}, diameter {D}, {2 * N} vertices. The code '
                f'of a word holds {L} base-{base} digits (`digit`); stage tables pack {size} codes of {bits} bits. -/\n\n')
        f.write(f'namespace {M}\n\nopen {G} BipartiteDD.LeanAll.HaarProd\n\n')
        f.write('/-- The connection set, in the order of the sol file. -/\ndef sVec : List Grp :=\n  [' +
                ', '.join(f'⟨{a}, {j}⟩' for a, j in S) + ']\n\n')
        f.write('/-- The `u`-th element of the connection set. -/\ndef sel (u : ℕ) : Grp := sVec.getD u 1\n\n')
        f.write(f'/-- Digit `t` of the code `c`. -/\ndef digit (c t : ℕ) : ℕ := c / {base} ^ t % {base}\n\n')
        f.write(f'theorem digit_lt (c t : ℕ) : digit c t < {base} := Nat.mod_lt _ (by norm_num)\n\n')
        f.write(f'def codeAt (C i : ℕ) : ℕ := (C >>> ({bits} * i)) % {2 ** bits}\n\n')
        for kd in kinds:
            f.write(f'def inv{kd} (t : ℕ) : Bool := {invlean[kd]}\n\n')
            f.write(f'def ok{kd} (c n : ℕ) : Bool := decide (grpOf n = wordX sel inv{kd} (digit c) {L})\n\n')
            f.write(f'def chk{kd} (base len C : ℕ) : Bool :=\n  (List.range len).all (fun i => ok{kd} (codeAt C i) (base + i))\n\n')
            f.write(f'theorem stageEx{kd} (base len C : ℕ) (h : chk{kd} base len C = true) (n : ℕ) (hn : base ≤ n)\n'
                    f'    (hn\' : n < base + len) : ∃ c, ok{kd} c n = true := by\n'
                    f'  refine ⟨codeAt C (n - base), ?_⟩\n'
                    f'  have := List.all_eq_true.mp h (n - base) (List.mem_range.mpr (by omega))\n'
                    f'  rwa [show base + (n - base) = n by omega] at this\n\n')
        f.write(f'instance : Fintype Grp := Fintype.ofEquiv (Fin {N}) equivG.symm\n\n')
        f.write(f'theorem card_Grp : Fintype.card Grp = {N} := by rw [Fintype.card_congr equivG, Fintype.card_fin]\n\n')
        f.write(f'end {M}\n')
    stmods = []
    for kd in kinds:
        for s in range(args.stages):
            lo, hi = s * size, min(N, (s + 1) * size)
            if lo >= hi:
                continue
            C = 0
            for i, code in enumerate(codes[kd][lo:hi]):
                C |= code << (bits * i)
            mod = f'Stage{kd}{s:02d}'
            stmods.append((kd, mod, lo, hi))
            with open(os.path.join(args.outdir, mod + '.lean'), 'w') as f:
                f.write(hdr)
                f.write(f'import {M}.Defs\n\nnamespace {M}\n\n')
                f.write(f'def tab{kd}{s:02d} : ℕ := {hex(C)}\n\n')
                f.write(f'set_option maxRecDepth 100000 in\ntheorem cert{kd}{s:02d} : chk{kd} {lo} {hi - lo} tab{kd}{s:02d} = true := '
                        f'by decide +kernel\n\nend {M}\n')
    with open(os.path.join(args.outdir, 'Record.lean'), 'w') as f:
        f.write(hdr)
        for _, mod, _, _ in stmods:
            f.write(f'import {M}.{mod}\n')
        f.write(f'\nnamespace {M}\n\nopen {G} BipartiteDD.LeanAll.HaarProd\n\n')
        for kd in kinds:
            mods = [(mod, lo, hi) for k_, mod, lo, hi in stmods if k_ == kd]
            f.write(f'theorem ex{kd} (n : ℕ) (hn : n < {N}) : ∃ c, ok{kd} c n = true := by\n')
            f.write(f'  have : ' + ' ∨ '.join(f'({lo} ≤ n ∧ n < {hi})' for _, lo, hi in mods) + ' := by omega\n')
            f.write('  rcases this with ' + ' | '.join('h' for _ in mods) + '\n')
            for mod, lo, hi in mods:
                s = mod[-2:]
                f.write(f'  · exact stageEx{kd} {lo} {hi - lo} tab{kd}{s} cert{kd}{s} n h.1 (by omega)\n')
            f.write('\n')
            f.write(f'theorem words{kd} (x : Grp) : ∃ dg : ℕ → ℕ, (∀ t < {L}, dg t < {deg}) ∧ wordX sel inv{kd} dg {L} = x := by\n')
            f.write(f'  obtain ⟨c, hc⟩ := ex{kd} (enc x) (enc_lt x)\n')
            f.write(f'  have h : grpOf (enc x) = wordX sel inv{kd} (digit c) {L} := of_decide_eq_true hc\n')
            f.write(f'  rw [grpOf_enc] at h\n')
            f.write(f'  exact ⟨digit c, fun t _ => digit_lt c t, h.symm⟩\n\n')
        f.write(f'theorem record : ∃ H : SimpleGraph (Fin {2 * N}), BipartiteDD.IsBipartiteDegDiam H {deg} {D} := by\n')
        if D % 2 == 1:
            f.write(f'  have h := gen_record_odd sel invL invR (fun _ => rfl) (fun _ => rfl) {deg} {L // 2} (by norm_num) '
                    f'wordsL wordsR\n')
        else:
            f.write(f'  have h := gen_record_even sel invE (fun _ => rfl) {deg} {L // 2} wordsE\n')
        f.write('  rw [card_Grp] at h\n  exact h\n\n')
        f.write(f'end {M}\n\nopen {M} in\n')
        f.write(f'/-- A bipartite graph on {2 * N} vertices with degree at most {deg} and diameter at most {D}: the Haar graph of '
                f'`Z_{m} ⋊_{r} Z_{k}`. -/\n')
        f.write(f'theorem {args.theorem} : ∃ H : SimpleGraph (Fin {2 * N}), BipartiteDD.IsBipartiteDegDiam H {deg} {D} :=\n'
                f'  record\n')
    print(f'wrote {args.outdir}: N = {N}, {len(stmods)} stage modules', file=sys.stderr)


if __name__ == '__main__':
    main()
