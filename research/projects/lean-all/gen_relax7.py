    def joined(key):
        rs = chk[key][0]
        names = [f'{key}_{ci:03d}' for ci in range(len(rs))]

        def go(a, b):
            if b - a == 1:
                return f'(allR_spec {names[a]})'
            m = (a + b) // 2
            return f'(range_join (mid := {rs[m][0]}) {go(a, m)} {go(m, b)})'
        return go(0, len(rs))
    out = []
    w = out.append
    w(HDR + 'import BipartiteDD.LeanAll.Range\n' + f'import {ns}.Defs\n' + ''.join(f'import {ns}.{m}\n' for m in st['mods']))
