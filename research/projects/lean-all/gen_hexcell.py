#!/usr/bin/env python3
"""Lean files for a three-level hexagon cell (LeanAll/HexLocal.lean, `main'`) from the certificate of hexlocal.py.

usage: gen_hexcell.py CERT.json NAME OUTDIR --theorem THM [--source SRC] [--chunk C] [--cchunk CC]

Writes OUTDIR/{P_*,Data,Pt*,Ln*,Cert*,Hub,Record}.lean in namespace BipartiteDD.LeanAll.NAME. The Record theorem is
`THM : ∃ H : SimpleGraph (Fin n), IsBipartiteDegDiam H (q + 2) 7`."""
import argparse, json, os

HDR = '/- Generated by research/projects/lean-all/gen_hexcell.py. Do not edit by hand. -/\n'


def clog2(n):
    k = 0
    while (1 << k) < n:
        k += 1
    return max(k, 1)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('cert')
    ap.add_argument('name')
    ap.add_argument('outdir')
    ap.add_argument('--theorem', required=True)
    ap.add_argument('--source', default='')
    ap.add_argument('--chunk', type=int, default=4096, help='domain points / lines per check module')
    ap.add_argument('--cchunk', type=int, default=32, help='freed points per certificate module')
    ap.add_argument('--block', type=int, default=8, help='log2 of the leaves per data block')
    ap.add_argument('--partbytes', type=int, default=600000)
    args = ap.parse_args()
    d = json.load(open(args.cert))
    p, q, m, n = d['p'], d['q'], d['m'], d['n']
    prime = all(q % k for k in range(2, q))
    assert prime or q == 8
    if prime:
        IMP, gPt, gLn, cOK = 'BipartiteDD.LeanAll.HexLocal', f'gPt {p} {len(d["ptc"])}', f'gLn {p} {len(d["ptc"])}', f'certOK {p}'
    else:
        IMP = 'BipartiteDD.LeanAll.HexGF8'
        gPt = f'BipartiteDD.LeanAll.HexGen.gPt BipartiteDD.LeanAll.HexGF8.coder {len(d["ptc"])}'
        gLn = f'BipartiteDD.LeanAll.HexGen.gLn BipartiteDD.LeanAll.HexGF8.coder {len(d["ptc"])}'
        cOK = f'BipartiteDD.LeanAll.HexGen.certOK BipartiteDD.LeanAll.HexGF8.coder {q}'
    M = len(d['ptc'])
    assert n == 6 * (q + 1) * (1 + q ** 2 + q ** 4) + 2 * m
    ns = f'BipartiteDD.LeanAll.{args.name}'
    od = args.outdir
    os.makedirs(od, exist_ok=True)
    KM, Km = clog2(M), clog2(m)

    def tree_defs(name, typ, leaves, pad, fmt, K, block=None):
        L = min(args.block if block is None else block, K)
        nbk = 1 << (K - L)
        bs = 1 << L

        def sub(vals, depth):
            if depth == 0:
                return '.leaf ' + vals[0]
            h = len(vals) // 2
            return '.node (' + sub(vals[:h], depth - 1) + ') (' + sub(vals[h:], depth - 1) + ')'
        names, parts, cur, size = [], [], [], 0
        for b_ in range(nbk):
            lo = b_ * bs
            if lo >= len(leaves):
                names.append(f'{name}Pad')
                continue
            vals = [fmt(leaves[i]) if i < len(leaves) else pad for i in range(lo, lo + bs)]
            txt = f'def {name}{b_} : Tree ({typ}) :=\n  {sub(vals, L)}\n\n'
            cur.append(txt)
            size += len(txt)
            names.append(f'{name}{b_}')
            if size > args.partbytes:
                parts.append(cur)
                cur, size = [], 0
        if cur:
            parts.append(cur)
        imps = []
        for pi, blocks in enumerate(parts):
            mod = f'P_{name}_{pi}'
            with open(os.path.join(od, mod + '.lean'), 'w') as g:
                g.write(HDR + 'import BipartiteDD.Fast\n\n')
                g.write(f'namespace {ns}\n\nopen BipartiteDD.Fast\n\nset_option maxRecDepth 100000\nset_option maxHeartbeats 0\n\n')
                g.write(''.join(blocks))
                g.write(f'end {ns}\n')
            imps.append(f'{ns}.{mod}')

        def top(ns_, depth):
            if depth == 0:
                return ns_[0]
            h = len(ns_) // 2
            return '.node (' + top(ns_[:h], depth - 1) + ') (' + top(ns_[h:], depth - 1) + ')'
        txt = f'def {name}Pad : Tree ({typ}) := {sub([pad] * bs, L)}\n\n'
        txt += f'def {name} : Tree ({typ}) :=\n  {top(names, K - L)}\n\n'
        return imps, txt

    def lst(xs, f=str):
        return '[' + ', '.join(f(x) for x in xs) + ']'

    def t3(t):
        return f'({t[0]}, {t[1]}, {t[2]})'

    def t4(t):
        return f'({t[0]}, {t[1]}, {t[2]}, {t[3]})'

    def certf(c):
        es = lst([(x, e) for x, e in zip(c['xs'], c['es'])], lambda xe: f'({xe[0]}, {lst(xe[1], t3)})')
        fs = lst([(z, f) for z, f in zip(c['zs'], c['fs'])], lambda zf: f'({t3(zf[0])}, {lst(zf[1], t4)})')
        return f'({es}, {fs})'

    rset = set(d['rl'])
    CT = 'List (ℕ × List (ℕ × ℕ × ℕ)) × List ((ℕ × ℕ × ℕ) × List (ℕ × ℕ × ℕ × ℕ))'
    trees = [tree_defs('ptcT', 'ℕ', d['ptc'], '0', str, KM), tree_defs('lnAT', 'ℕ', d['lnA'], '0', str, KM),
             tree_defs('lnBT', 'ℕ', d['lnB'], '0', str, KM), tree_defs('sgT', 'ℕ', d['sg'], '0', str, KM),
             tree_defs('sgiT', 'ℕ', d['sgi'], '0', str, KM),
             tree_defs('rflagT', 'Bool', [i in rset for i in range(M)], 'false', lambda b: 'true' if b else 'false', KM),
             tree_defs('rlT', 'ℕ', d['rl'], '0', str, Km), tree_defs('certT', CT, d['certs'], '([], [])', certf, Km, 4),
             tree_defs('hubLT', 'List ℕ', d['hubL'], '[]', lst, Km), tree_defs('hubRT', 'List ℕ', d['hubR'], '[]', lst, Km)]
    src = f' ({args.source})' if args.source else ''
    with open(os.path.join(od, 'Data.lean'), 'w') as f:
        f.write(HDR + f'import {IMP}\n')
        for imps, _ in trees:
            for im in imps:
                f.write(f'import {im}\n')
        f.write(f'\n/-! Data of the ({q + 2},7) hexagon graph{src}: H({q}) with three levels, {m} freed points, '
                f'{n} vertices;\n{M} domain points and lines. -/\n\n')
        f.write(f'namespace {ns}\n\nopen BipartiteDD.Fast BipartiteDD.LeanAll.Orbit2 BipartiteDD.LeanAll.HexLocal\n\n')
        f.write('set_option maxRecDepth 100000\nset_option maxHeartbeats 0\n\n')
        for _, txt in trees:
            f.write(txt.replace(': Tree (', ': BipartiteDD.Fast.Tree ('))
        for nm, typ, K in [('ptc', 'ℕ', KM), ('lnA', 'ℕ', KM), ('lnB', 'ℕ', KM), ('sg', 'ℕ', KM), ('sgi', 'ℕ', KM),
                           ('rflag', 'Bool', KM), ('rl', 'ℕ', Km), ('cert', 'Cert', Km), ('hubL', 'List ℕ', Km),
                           ('hubR', 'List ℕ', Km)]:
            f.write(f'noncomputable def {nm} (i : ℕ) : {typ} := look {nm}T {K} i\n\n')
        if prime:
            f.write(f'instance : Fact (Nat.Prime {p}) := ⟨by norm_num⟩\n\n')
        f.write(f'end {ns}\n')

    def thm_file(fname, body):
        with open(os.path.join(od, fname), 'w') as f:
            f.write(HDR + f'import {ns}.Data\n\nnamespace {ns}\n\n')
            f.write('open BipartiteDD.LeanAll.Orbit2 BipartiteDD.LeanAll.HexLocal\n\n')
            f.write(body)
            f.write(f'\nend {ns}\n')

    mods = []

    def ranges(N, C):
        return [(lo, min(C, N - lo)) for lo in range(0, N, C)]
    pr = ranges(M, args.chunk)
    for ci, (lo, k) in enumerate(pr):
        thm_file(f'Pt{ci:02d}.lean', f'theorem pt{ci:02d} : allR ({gPt} ptc) {lo} {k} = true := by\n  decide +kernel\n')
        thm_file(f'Ln{ci:02d}.lean', f'theorem ln{ci:02d} : allR ({gLn} lnA lnB sg sgi) {lo} {k} = true := by\n  decide +kernel\n')
        mods += [f'Pt{ci:02d}', f'Ln{ci:02d}']
    cr = ranges(m, args.cchunk)
    for ci, (lo, k) in enumerate(cr):
        thm_file(f'Cert{ci:02d}.lean', f'theorem cert{ci:02d} : allR (fun v => {cOK} {M} ptc lnA lnB sg rflag (rl v) '
                 f'(cert v)) {lo} {k} = true := by\n  decide +kernel\n')
        mods.append(f'Cert{ci:02d}')
    K2 = clog2(2 * m)
    thm_file('Hub.lean', f'theorem hR : allR (gR {M} {m} rl rflag) 0 {m} = true := by\n  decide +kernel\n\n'
             f'theorem hH : allR (gH {p} {m} hubL hubR) 0 {m} = true := by\n  decide +kernel\n\n'
             f'theorem hLoc : localOK {p - 1} {2 * m} (hubNb {m} hubL hubR) (hubCol {m}) 0 {2 * m} = true := by\n  decide +kernel\n\n'
             f'theorem hBfs : bfsOK {K2} 7 {2 * m} 0 {2 * m} (hubNb {m} hubL hubR) = true := by\n  decide +kernel\n')
    mods.append('Hub')

    def joined(var, rs, names):
        """`fun var hvar => …`: a balanced `range_join` tree over the `allR_spec` of the check modules."""
        def go(a, b):
            if b - a == 1:
                return f'(allR_spec {names[a]})'
            m = (a + b) // 2
            return f'(range_join (mid := {rs[m][0]}) {go(a, m)} {go(m, b)})'
        return f'  fun {var} h{var} => {go(0, len(rs))} {var} (Nat.zero_le _) h{var}\n'

    def split(var, rs, names):
        out = f'  have hc : ' + ' ∨ '.join(f'({lo} ≤ {var} ∧ {var} < {lo + k})' for lo, k in rs) + ' := by omega\n'
        pat = ' | '.join('hc' for _ in rs)
        out += f'  rcases hc with {pat}\n'
        for (lo, k), nm in zip(rs, names):
            out += f'  · exact allR_spec {nm} {var} hc.1 hc.2\n'
        return out
    with open(os.path.join(od, 'Record.lean'), 'w') as f:
        f.write(HDR + 'import BipartiteDD.LeanAll.Range\n')
        for mo in mods:
            f.write(f'import {ns}.{mo}\n')
        f.write(f'\n/-! The ({q + 2},7) hexagon record{src}: {n} vertices, maximum degree {q + 2}, diameter 7. -/\n\n')
        f.write(f'namespace {ns}\n\nopen BipartiteDD BipartiteDD.LeanAll BipartiteDD.LeanAll.Orbit2 BipartiteDD.LeanAll.HexLocal\n\n')
        f.write(f'theorem h1 : ∀ i < {M}, {gPt} ptc i = true :=\n' +
                joined('i', pr, [f'pt{ci:02d}' for ci in range(len(pr))]) + '\n')
        f.write(f'theorem h2 : ∀ j < {M}, {gLn} lnA lnB sg sgi j = true :=\n' +
                joined('j', pr, [f'ln{ci:02d}' for ci in range(len(pr))]) + '\n')
        f.write(f'theorem h4 : ∀ v < {m}, {cOK} {M} ptc lnA lnB sg rflag (rl v) (cert v) = true :=\n' +
                joined('v', cr, [f'cert{ci:02d}' for ci in range(len(cr))]) + '\n')
        call = (f'  have := main\' {p} {M} {m} {K2} ptc lnA lnB sg sgi rl rflag cert hubL hubR h1 h2\n' if prime else
                f'  have := BipartiteDD.LeanAll.HexGen.main\' BipartiteDD.LeanAll.HexGF8.coder {q} {M} {m} {K2} '
                f'BipartiteDD.LeanAll.HexGF8.card_GF8 ptc lnA lnB sg sgi rl rflag cert hubL hubR h1 h2\n')
        f.write(f'theorem {args.theorem} : ∃ H : SimpleGraph (Fin {n}), IsBipartiteDegDiam H {q + 2} 7 := by\n' + call +
                f'    (fun v hv => allR_spec hR v (Nat.zero_le _) (by omega)) h4\n'
                f'    (fun v hv => allR_spec hH v (Nat.zero_le _) (by omega))\n'
                f'    (fun u hu => localOK_one hLoc u (Nat.zero_le _) (by omega)) (by norm_num) hBfs\n'
                f'  norm_num at this\n  exact this\n\n')
        f.write(f'end {ns}\n')
    print(f'wrote {od}: M={M} m={m} n={n}; {len(pr)} point/line chunks, {len(cr)} certificate chunks')


if __name__ == '__main__':
    main()
