#!/usr/bin/env python3
"""Lean files for a freed-spread cell (LeanAll/HexGlobal.lean, `main`; research/squads/cells/d12D7.md): 2j + 1 levels
of H(q), a duality M of H(q) as every matching, the points of a spread freed, and a voltage hub graph over Z_m with b
base vertices per side whose K = b m hubs of each kind sit on the freed points.

usage: gen_spreadcell.py HEXBIN SOL VHUB NAME OUTDIR --j J --theorem THM [--source SRC]

SOL: a d7hex .sol (research/d10D7/dual/xgen.c): `d7hex q N K nv freed`, the K freed point ids, a hubs block, then the
duality M as N line ids (point p -> line M(p)). The line half of the duality is computed here (the point common to
the lines M(p), p on the line) and every check of HexGlobal is run first with the arithmetic of the Lean checks
(hexlocal.Fld, GF(9) included). The hub owners are the freed points in code order; the hub graph is VHUB
(`vhub m b`, then edges `x y v`), not the one of the .sol. Writes OUTDIR/{P_*,Data,GPt*,GLn*,GF*,HLoc*,HPerm*,HOrb,
Lev*,Step*,Record}.lean in namespace BipartiteDD.LeanAll.NAME; the Record theorem is
`THM : ∃ G : SimpleGraph (Fin n), IsBipartiteDegDiam G (q + 1 + j) 7`, n = (2j + 1) 2N + 2K."""
import argparse, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from hexlocal import load_hex  # noqa: E402

HDR = '/- Generated by research/projects/lean-all/gen_spreadcell.py. Do not edit by hand. -/\n'


def clog2(n):
    k = 0
    while (1 << k) < n:
        k += 1
    return max(k, 1)


def tables(H, sol):
    K, q, N = H['K'], H['q'], H['N']
    pts, pcode, lines, pl = H['pts'], H['pcode'], H['lines'], H['pl']
    tok = open(sol).read().split()
    assert tok[0] == 'd7hex' and int(tok[1]) == q and int(tok[2]) == N and tok[5] == 'freed'
    nf = int(tok[3])
    Fr = [int(x) for x in tok[6:6 + nf]]
    M = [int(x) for x in tok[-N:]]
    assert sorted(M) == list(range(N)), 'M is not a bijection'
    # lines by their normalised bases, in Pluecker order
    basis = []
    for l in range(N):
        a, b = K.line_basis(pts[lines[l][0]], pts[lines[l][1]])
        basis.append((K.code(a), K.code(b)))
    order = sorted(range(N), key=lambda l: K.plCode(*basis[l]))
    lix = [0] * N
    for j, l in enumerate(order):
        lix[l] = j
    # the line half of the duality: the point common to the lines M(p), p on the line
    dLh = []
    for l in range(N):
        common = set(lines[M[lines[l][0]]])
        for p in lines[l][1:]:
            common &= set(lines[M[p]])
        assert len(common) == 1, ('M is not a duality at line', l)
        dLh.append(common.pop())
    assert sorted(dLh) == list(range(N))
    pc = pcode
    la = [basis[l][0] for l in order]
    lb = [basis[l][1] for l in order]
    dP = [lix[M[i]] for i in range(N)]
    dPi = [0] * N
    for i, j in enumerate(dP):
        dPi[j] = i
    dL = [dLh[l] for l in order]
    dLi = [0] * N
    for j, i in enumerate(dL):
        dLi[i] = j
    fset = set(Fr)
    fP = [i in fset for i in range(N)]
    fL = [all(fP[x] for x in lines[l]) for l in order]
    sl = [0] * N
    ents = []
    for j, l in enumerate(order):
        A, B = K.vec(la[j]), K.vec(lb[j])
        es = []
        for e in lines[l]:
            al, be = K.coeffs(pts[e], A, B)
            A2, B2 = K.vec(la[dP[e]]), K.vec(lb[dP[e]])
            ga, de = K.coeffs(pts[dL[j]], A2, B2)
            es.append((e, al, be, ga, de))
            if fL[j]:
                sl[e] = j
        ents.append(sorted(es))
    for i in range(N):
        if fP[i]:
            assert sum(1 for l in pl[i] if fL[lix[l]]) == 1, ('freed point not on exactly one spread line', i)
    return {'q': q, 'N': N, 'pc': pc, 'la': la, 'lb': lb, 'dP': dP, 'dPi': dPi, 'dL': dL, 'dLi': dLi, 'sl': sl,
            'fP': fP, 'fL': fL, 'ents': ents, 'fpt': sorted(Fr)}


def check(K, t):
    """HexGlobal.gptOK, glnOK, gfOK with the arithmetic of hexlocal.Fld."""
    q, N = t['q'], t['N']
    pc, la, lb, dP, dPi, dL, dLi, sl, fP, fL, ents = (t[k] for k in
                                                       ('pc', 'la', 'lb', 'dP', 'dPi', 'dL', 'dLi', 'sl', 'fP', 'fL', 'ents'))
    for i in range(N):
        assert K.ptOK(pc[i]) and (i + 1 == N or pc[i] < pc[i + 1]) and dP[i] < N and dPi[dP[i]] == i
        assert not fP[i] or (sl[i] < N and fL[sl[i]] and any(e[0] == i for e in ents[sl[i]]))
    plc = [K.plCode(la[j], lb[j]) for j in range(N)]
    for j in range(N):
        es = ents[j]
        assert K.lnOK(la[j], lb[j]) and (j + 1 == N or plc[j] < plc[j + 1]) and dL[j] < N and dLi[dL[j]] == j
        assert len(es) == q + 1 and all(es[k][0] < es[k + 1][0] for k in range(q))
        for e, al, be, ga, de in es:
            assert e < N and K.linN(pc[e], la[j], lb[j], al, be) and K.linN(pc[dL[j]], la[dP[e]], lb[dP[e]], ga, de)
        if fL[j]:
            assert all(fP[e[0]] and sl[e[0]] == j for e in es)
        else:
            assert sum(1 for e in es if fP[e[0]]) <= 1, ('unflagged line with two freed points', j)
    fpt = t['fpt']
    assert all(fpt[v] < N and fP[fpt[v]] for v in range(len(fpt))) and all(fpt[v] < fpt[v + 1] for v in range(len(fpt) - 1))


def vhub_graph(m, b, E):
    n = 2 * b * m

    def vnb(w):
        r, t = w % (2 * b), w // (2 * b)
        if r < b:
            return [2 * b * ((t + v) % m) + b + y for (x, y, v) in E if x == r]
        return [2 * b * ((t + m - v % m) % m) + x for (x, y, v) in E if y == r - b]
    return n, [vnb(w) for w in range(n)]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('hexbin')
    ap.add_argument('sol')
    ap.add_argument('vhub')
    ap.add_argument('name')
    ap.add_argument('outdir')
    ap.add_argument('--j', type=int, default=1)
    ap.add_argument('--theorem', required=True)
    ap.add_argument('--source', default='')
    ap.add_argument('--chunk', type=int, default=512)
    ap.add_argument('--hchunk', type=int, default=4096)
    ap.add_argument('--block', type=int, default=8)
    ap.add_argument('--partbytes', type=int, default=600000)
    ap.add_argument('--stub', action='store_true', help='empty data and sorry checks (to test the Record only)')
    args = ap.parse_args()
    H = load_hex(args.hexbin)
    K, q, N = H['K'], H['q'], H['N']
    coder = {9: 'BipartiteDD.LeanAll.HexGF9.coder'}[q]
    cardF = {9: 'BipartiteDD.LeanAll.HexGF9.card_GF9'}[q]
    imp = {9: 'BipartiteDD.LeanAll.HexGF9'}[q]
    t = tables(H, args.sol)
    check(K, t)
    j = args.j
    vt = open(args.vhub).read().split('\n')
    hd = vt[0].split()
    assert hd[0] == 'vhub'
    vm, vb = int(hd[1]), int(hd[2])
    E = [tuple(int(x) for x in s.split()) for s in vt[1:] if s.strip()]
    nh, nadj = vhub_graph(vm, vb, E)
    d = q - j
    assert all(len(set(a)) == len(a) <= d for a in nadj)
    assert all(w in nadj[u] for w in range(nh) for u in nadj[w])
    Kh = vb * vm
    assert Kh <= len(t['fpt'])
    D = 7
    KH = clog2(nh)
    src4 = 2 * vb
    levels = [[(1 << v) if v < src4 else 0 for v in range(nh)]]
    for r in range(D):
        cur = levels[-1]
        levels.append([cur[v] | _or(cur, nadj[v]) for v in range(nh)])
    assert all(x == (1 << src4) - 1 for x in levels[D]), 'hub graph: diameter > 7'
    n = (2 * j + 1) * 2 * N + 2 * Kh
    print(f'H({q}): N = {N}, {sum(t["fP"])} freed points on {sum(t["fL"])} spread lines; hub graph Z_{vm}, b = {vb}, '
          f'K = {Kh}; j = {j}, n = {n}', flush=True)

    ns = f'BipartiteDD.LeanAll.{args.name}'
    od = args.outdir
    os.makedirs(od, exist_ok=True)

    def tree_defs(name, typ, leaves, pad, fmt, Kd, block=None):
        Lb = min(args.block if block is None else block, Kd)
        nbk = 1 << (Kd - Lb)
        bs = 1 << Lb

        def sub(vals, depth):
            if depth == 0:
                return '.leaf ' + vals[0]
            h = len(vals) // 2
            return '.node (' + sub(vals[:h], depth - 1) + ') (' + sub(vals[h:], depth - 1) + ')'
        if args.stub:
            leaves = []
        names, parts, cur, size = [], [], [], 0
        for b_ in range(nbk):
            lo = b_ * bs
            if lo >= len(leaves):
                names.append(f'{name}Pad')
                continue
            vals = [fmt(leaves[i]) if i < len(leaves) else pad for i in range(lo, lo + bs)]
            txt = f'def {name}{b_} : Tree ({typ}) :=\n  {sub(vals, Lb)}\n\n'
            cur.append(txt)
            size += len(txt)
            names.append(f'{name}{b_}')
            if size > args.partbytes:
                parts.append(cur)
                cur, size = [], 0
        if cur:
            parts.append(cur)
        imps = []
        for pi, blocks in enumerate(parts):
            mod = f'P_{name}_{pi}'
            with open(os.path.join(od, mod + '.lean'), 'w') as g:
                g.write(HDR + 'import BipartiteDD.Fast\n\n')
                g.write(f'namespace {ns}\n\nopen BipartiteDD.Fast\n\nset_option maxRecDepth 100000\nset_option maxHeartbeats 0\n\n')
                g.write(''.join(blocks).replace(': Tree (', ': BipartiteDD.Fast.Tree ('))
                g.write(f'end {ns}\n')
            imps.append(f'{ns}.{mod}')

        def top(ns_, depth):
            if depth == 0:
                return ns_[0]
            h = len(ns_) // 2
            return '.node (' + top(ns_[:h], depth - 1) + ') (' + top(ns_[h:], depth - 1) + ')'
        txt = f'def {name}Pad : Tree ({typ}) := {sub([pad] * bs, Lb)}\n\n'
        txt += f'def {name} : Tree ({typ}) :=\n  {top(names, Kd - Lb)}\n\n'
        return imps, txt.replace(': Tree (', ': BipartiteDD.Fast.Tree (')

    def lst(xs, f=str):
        return '[' + ', '.join(f(x) for x in xs) + ']'

    def t3(x):
        return f'({x[0]}, {x[1]}, {x[2]})'

    def t5(x):
        return f'({x[0]}, {x[1]}, {x[2]}, {x[3]}, {x[4]})'

    def bl(b_):
        return 'true' if b_ else 'false'
    KN, KF = clog2(N), clog2(len(t['fpt']))
    specs = [('pc', 'ℕ', t['pc'], '0', str, KN), ('la', 'ℕ', t['la'], '0', str, KN), ('lb', 'ℕ', t['lb'], '0', str, KN),
             ('dP', 'ℕ', t['dP'], '0', str, KN), ('dPi', 'ℕ', t['dPi'], '0', str, KN),
             ('dL', 'ℕ', t['dL'], '0', str, KN), ('dLi', 'ℕ', t['dLi'], '0', str, KN),
             ('sl', 'ℕ', t['sl'], '0', str, KN), ('fP', 'Bool', t['fP'], 'false', bl, KN),
             ('fL', 'Bool', t['fL'], 'false', bl, KN),
             ('ents', 'List (ℕ × ℕ × ℕ × ℕ × ℕ)', t['ents'], '[]', lambda es: lst(es, t5), KN),
             ('fpt', 'ℕ', t['fpt'], '0', str, KF)]
    trees = [tree_defs(nm + 'T', typ, lv, pad, fmt, Kd) for nm, typ, lv, pad, fmt, Kd in specs]
    src = f' ({args.source})' if args.source else ''
    with open(os.path.join(od, 'Data.lean'), 'w') as f:
        f.write(HDR + f'import BipartiteDD.LeanAll.HexGlobal\nimport {imp}\n')
        for imps, _ in trees:
            for im in imps:
                f.write(f'import {im}\n')
        f.write(f'\n/-! Data of the ({q + 1 + j},7) freed-spread graph{src}: H({q}) with a duality, {2 * j + 1} levels, '
                f'{sum(t["fP"])} freed points;\nthe hub graph over Z_{vm} with {vb} base vertices per side. -/\n\n')
        f.write(f'namespace {ns}\n\nopen BipartiteDD.Fast BipartiteDD.LeanAll.Orbit2\n\n')
        f.write('set_option maxRecDepth 100000\nset_option maxHeartbeats 0\n\n')
        for _, txt in trees:
            f.write(txt)
        for nm, typ, _, _, _, Kd in specs:
            f.write(f'noncomputable def {nm} (i : ℕ) : {typ} := look {nm}T {Kd} i\n\n')
        f.write(f'/-- The base graph of the hub graph: `(x, y, v)`, `A_x ~ B_y` with voltage `v`. -/\n'
                f'def E : List (ℕ × ℕ × ℕ) := {lst(E, t3)}\n\n')
        f.write(f'end {ns}\n')

    def thm_file(fname, body, imps=''):
        with open(os.path.join(od, fname), 'w') as f:
            f.write(HDR + f'import {ns}.Data\n{imps}\nnamespace {ns}\n\n')
            f.write('open BipartiteDD.Fast BipartiteDD.LeanAll.Orbit2 BipartiteDD.LeanAll.HexGlobal '
                    'BipartiteDD.LeanAll.VHub\n\n')
            f.write(body)
            f.write(f'\nend {ns}\n')

    def ranges(n_, c):
        return [(lo, min(c, n_ - lo)) for lo in range(0, n_, c)]
    mods = []
    checks = {}
    TAB = 'pc la lb dP dPi dL dLi sl fP fL ents'
    for key, nm, fn, n_, c in [('gp', 'GPt', f'gptOK {coder} {N} pc dP dPi sl fP fL ents', N, args.chunk),
                               ('gl', 'GLn', f'glnOK {coder} {q} {N} pc la lb dP dL dLi sl fP fL ents', N, args.chunk),
                               ('gf', 'GF', f'gfOK {N} {Kh} fpt fP', Kh, 4096),
                               ('hl', 'HLoc', f'localOK {d} {nh} (vnb {vm} {vb} E) (vcol {vb})', nh, args.hchunk),
                               ('hp', 'HPerm', f'permOK {nh} (vnb {vm} {vb} E) (vg {nh} {vb}) (vh {nh} {vb})', nh,
                                args.hchunk)]:
        rs = ranges(n_, c)
        checks[key] = rs
        for ci, (lo, k) in enumerate(rs):
            body = (f'theorem {key}{ci:02d} : allR ({fn}) {lo} {k} = true := by\n' + ('  sorry\n' if args.stub else '  decide +kernel\n')
                    if key not in ('hl', 'hp') else
                    f'theorem {key}{ci:02d} : {fn} {lo} {k} = true := by\n' + ('  sorry\n' if args.stub else '  decide +kernel\n'))
            thm_file(f'{nm}{ci:02d}.lean', body)
            mods.append(f'{nm}{ci:02d}')
    glist = f'[(vg {nh} {vb}, vh {nh} {vb})]'
    thm_file('HOrb.lean', f'theorem horb : orbitOK {glist} {src4} {nh - src4} = true := by\n' + ('  sorry\n' if args.stub else '  decide +kernel\n'))
    mods.append('HOrb')
    for r in range(1, D):
        imps, txt = tree_defs(f'lev{r}', 'ℕ', levels[r], '0', str, KH)
        with open(os.path.join(od, f'Lev{r}.lean'), 'w') as f:
            f.write(HDR + 'import BipartiteDD.Fast\n' + ''.join(f'import {im}\n' for im in imps) + '\n')
            f.write(f'/-! Masks of radius {r} in the hub graph from the sources 0 … {src4 - 1}. -/\n\n')
            f.write(f'namespace {ns}\n\nopen BipartiteDD.Fast\n\nset_option maxRecDepth 100000\nset_option maxHeartbeats 0\n\n')
            f.write(txt)
            f.write(f'end {ns}\n')

    def lev(r):
        if r == 0:
            return f'(Tree.gen (initMask 0 {src4}) 0 {KH})'
        if r == D:
            return f'(fullT {KH} {src4})'
        return f'lev{r}'
    sch = ranges(nh, args.hchunk)
    for r in range(D):
        for cj, (vlo, vk) in enumerate(sch):
            imps = ''.join(f'import {ns}.Lev{rr}\n' for rr in (r, r + 1) if 1 <= rr <= D - 1)
            thm_file(f'Step{r}_{cj:02d}.lean', f'theorem step{r}_{cj:02d} : stepOK {KH} (vnb {vm} {vb} E) {lev(r)} '
                     f'{lev(r + 1)} {vlo} {vk} = true := by\n' + ('  sorry\n' if args.stub else '  decide +kernel\n'), imps)
            mods.append(f'Step{r}_{cj:02d}')

    def joined(names, rs):
        def go(a, b):
            if b - a == 1:
                return f'(allR_spec {names[a]})'
            m = (a + b) // 2
            return f'(range_join (mid := {rs[m][0]}) {go(a, m)} {go(m, b)})'
        return go(0, len(rs))

    def split(var, rs, body, indent='  '):
        if len(rs) == 1:
            return indent + body(0) + '\n'
        out = f'{indent}have hc : ' + ' ∨ '.join(f'({lo} ≤ {var} ∧ {var} < {lo + k})' for lo, k in rs) + ' := by omega\n'
        out += f'{indent}rcases hc with ' + ' | '.join('hc' for _ in rs) + '\n'
        for ci in range(len(rs)):
            out += f'{indent}· {body(ci)}\n'
        return out
    nbE = f'(vnb {vm} {vb} E)'
    with open(os.path.join(od, 'Record.lean'), 'w') as f:
        f.write(HDR + 'import BipartiteDD.LeanAll.Range\n')
        for mo in mods:
            f.write(f'import {ns}.{mo}\n')
        f.write(f'\n/-! The ({q + 1 + j},7) freed-spread record{src}: {n} vertices, maximum degree {q + 1 + j}, '
                f'diameter 7. -/\n\n')
        f.write(f'namespace {ns}\n\nopen BipartiteDD BipartiteDD.Fast BipartiteDD.LeanAll BipartiteDD.LeanAll.Orbit2 '
                'BipartiteDD.LeanAll.HexGlobal BipartiteDD.LeanAll.VHub\n\n')
        for key, var, stmt in [('gp', 'i', f'∀ i < {N}, gptOK {coder} {N} pc dP dPi sl fP fL ents i = true'),
                               ('gl', 'j', f'∀ j < {N}, glnOK {coder} {q} {N} pc la lb dP dL dLi sl fP fL ents j = true'),
                               ('gf', 'v', f'∀ v < {Kh}, gfOK {N} {Kh} fpt fP v = true')]:
            rs = checks[key]
            f.write(f'theorem h_{key} : {stmt} :=\n  fun {var} h{var} => '
                    f'{joined([f"{key}{ci:02d}" for ci in range(len(rs))], rs)} {var} (Nat.zero_le _) h{var}\n\n')
        f.write(f'theorem hT : TabOK {coder} {q} {N} {TAB} :=\n'
                f'  ⟨{cardF}, by rw [Hexagon.card_spt_eq, {cardF}]; norm_num, by rw [HexagonEven.card_hline_even, {cardF}]; '
                f'norm_num,\n    h_gp, h_gl⟩\n\n')
        f.write(f'theorem hK : {nh} ≤ 2 ^ {KH} := by decide\n\n')
        f.write(f'theorem hHL : LocalSpec {d} {nh} {nbE} (vcol {vb}) := by\n  apply localSpec_of\n  intro u hu\n' +
                split('u', checks['hl'], lambda ci: f'exact localOK_one hl{ci:02d} u (by omega) (by omega)') + '\n')
        f.write(f'theorem hP : ∀ g ∈ {glist}, PermSpec {nh} {nbE} g.1 g.2 := by\n'
                f'  intro g hg\n  simp only [List.mem_cons, List.not_mem_nil, or_false] at hg\n  subst hg\n'
                f'  apply permSpec_of\n  intro v hv\n' +
                split('v', checks['hp'], lambda ci: f'exact permOK_one hp{ci:02d} v (by omega) (by omega)') + '\n')
        f.write(f'theorem hO : ∀ v, {src4} ≤ v → v < {nh} → ∃ g ∈ {glist}, g.1 v < v := by\n'
                f'  intro v h1 h2\n  exact orbit_of horb v h1 (by omega)\n\n')
        f.write(f'/-- The masks of every radius, from the sources 0 … {src4 - 1}. -/\n'
                f'noncomputable def LV : ℕ → BipartiteDD.Fast.Tree ℕ\n  | 0 => Tree.gen (initMask 0 {src4}) 0 {KH}\n')
        for r in range(1, D):
            f.write(f'  | {r} => lev{r}\n')
        f.write(f'  | _ => fullT {KH} {src4}\n\n')
        f.write(f'theorem hs : ∀ r < {D}, ∀ v < {nh}, look (LV (r + 1)) {KH} v = '
                f'foldOr (fun u => look (LV r) {KH} u) ({nbE} v) (look (LV r) {KH} v) := by\n  intro r hr v hv\n')
        f.write('  have hr\' : ' + ' ∨ '.join(f'r = {r}' for r in range(D)) + ' := by omega\n')
        f.write('  rcases hr\' with ' + ' | '.join('rfl' for _ in range(D)) + '\n')
        for r in range(D):
            txt = split('v', sch, lambda cj, r=r: f'exact stepOK_pt step{r}_{cj:02d} v (by omega) (by omega)',
                        indent='    ')
            f.write('  · ' + txt[4:])
        f.write('\n')
        f.write(f'theorem hB : ∀ s (hsn : s < {nh}), s < {src4} → ∀ v : Fin {nh}, (graphF {nh} {nbE}).edist v ⟨s, hsn⟩ ≤ {D} '
                f':= by\n  intro s hsn hm v\n  exact edist_of_staged hHL hK LV rfl rfl hs v s hsn (Nat.zero_le _) (by omega)\n\n')
        f.write(f'theorem hHD : (graphF {nh} {nbE}).ediam ≤ {D} :=\n  ediam_le hHL {glist} hP hO hB\n\n')
        f.write(f'theorem {args.theorem} : ∃ G : SimpleGraph (Fin {n}), IsBipartiteDegDiam G {q + 1 + j} 7 := by\n'
                f'  have := HexGlobal.main hT {j} {vm} {vb} E (by norm_num) fpt h_gf hHL hHD (by norm_num) (by norm_num)\n'
                f'  norm_num at this\n  exact this\n\n')
        f.write(f'end {ns}\n')
    print(f'wrote {od}: {len(mods)} check modules')


def _or(mk, l):
    x = 0
    for u in l:
        x |= mk[u]
    return x


if __name__ == '__main__':
    main()
