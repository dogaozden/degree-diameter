#!/usr/bin/env python3
"""Lean files for a Haar record of SL(2,p) x SL(2,q) x Z_n or PSL(2,p) x SL(2,q) x Z_n through the packed batch
checks (LeanAll/HaarProd.lean), or of PSL(2,p) x SL(2,8) x Z_n (second factor over GF(8), LeanAll/HaarGF8.lean).

usage: gen_haarprod.py SOLFILE OUTDIR MODULE THEOREM [--per K] [--certdir DIR]

Reads the sol file (research/frontier/sols format, group 'prod sl|psl p sl q'), runs haarcert_prod for the covers
the diameter needs, and writes
  Defs.lean            generators of both factors, letter tables, parameters, constants and their checks, and the
                       batch predicate Q<K> i (batch i of the flattened order of HaarProd.cover_prod)
  Bat<K><mmm>.lean     one theorem per batch (the certificate is the witness, two kernel checks), and the range
                       lemma for the module
  Cover<K>.lean        all batches pass, so every element has a word
  Record.lean          the record theorem
"""
import argparse, os, re, subprocess, sys

W = 40
S_BARRETT = 30


def read_sol(path):
    lines = open(path).read().split('\n')
    h = lines[0].split()
    deg, diam = int(h[0]), int(h[1])
    gf8 = h[7] == 'poly'
    if gf8:
        assert h[8] == 'x^3+x+1' and h[6] == '8' and h[3] == 'psl', 'GF(8) only with x^3+x+1 and a PSL first factor'
        h = h[:7] + h[9:]
    assert h[2] == 'prod' and h[3] in ('sl', 'psl') and h[5] == 'sl' and h[7] == 'n'
    psl, p, q, n = h[3] == 'psl', int(h[4]), int(h[6]), int(h[8])
    gens = []
    for l in lines[1:]:
        m = re.match(r'\s*\d+\s+prod\[mat\((\d+),(\d+),(\d+),(\d+)\);mat\((\d+),(\d+),(\d+),(\d+)\)\]\s+z=(\d+)', l)
        if m:
            gens.append(tuple(int(x) for x in m.groups()))
    assert len(gens) == deg
    return deg, diam, psl, gf8, p, q, n, gens


def _spread(data, start, N):
    out = bytearray()
    for j in range(N):
        out += data[5 * (start + j):5 * (start + j) + 5]
    return out


def jtree(k_, leaves):
    # leaves: (term, lo, hi); every bound explicit (implicit ones make the unifier unfold the checks)
    if len(leaves) == 1:
        return leaves[0][0]
    h = len(leaves) // 2
    return (f'(range_join (Q := Q{k_}) (lo := {leaves[0][1]}) (mid := {leaves[h][1]}) (hi := {leaves[-1][2]}) '
            f'{jtree(k_, leaves[:h])} {jtree(k_, leaves[h:])})')



def chunked(v, bits=None, chunk=4096):
    """`v` as a balanced tree of short hex literals joined by `+` and `<<<` (a long literal costs time quadratic
    in its length to elaborate; the kernel evaluates the tree with GMP)."""
    if bits is None:
        bits = max(v.bit_length(), 1)
    if bits <= chunk:
        return hex(v)
    h = max(chunk, (bits // 2 // chunk) * chunk)
    return f'({chunked(v & ((1 << h) - 1), h, chunk)} + {chunked(v >> h, bits - h, chunk)} <<< {h})'

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('sol')
    ap.add_argument('outdir')
    ap.add_argument('module')
    ap.add_argument('theorem')
    ap.add_argument('--per', type=int, default=100, help='batches per module')
    ap.add_argument('--certdir', default='/tmp/claude-0/work/certs')
    ap.add_argument('--haarcert', default='/tmp/claude-0/work/haarcert_prod')
    ap.add_argument('--source', default='')
    args = ap.parse_args()
    deg, D, psl, gf8, p, q, n, gens = read_sol(args.sol)
    L = D - 1
    N = p * n
    hp = (p - 1) // 2
    B1 = p * hp + hp if psl else p * p - 1
    nb = (q * q - 1) * q * B1
    G = (p * (p * p - 1) // (2 if psl else 1)) * q * (q * q - 1) * n
    kinds = ['even'] if D % 2 == 0 else ['left', 'right']
    K = {'even': 'E', 'left': 'L', 'right': 'R'}
    os.makedirs(args.certdir, exist_ok=True)
    os.makedirs(args.outdir, exist_ok=True)
    base = os.path.basename(args.sol).replace('.txt', '')
    certs = {}
    for kd in kinds:
        out = os.path.join(args.certdir, f'{base}_{kd}.bin')
        if not os.path.exists(out):
            r = subprocess.run([args.haarcert, args.sol, kd, out], capture_output=True, text=True)
            sys.stderr.write(r.stderr)
            if r.returncode != 0:
                sys.exit(f'haarcert_prod {kd} failed')
        certs[kd] = out
    M = args.module
    ns = M
    hdr = '/- Generated by research/projects/lean-all/gen_haarprod.py. Do not edit by hand. -/\n'
    opens = ('open BipartiteDD.LeanAll BipartiteDD.LeanAll.HaarSwar BipartiteDD.LeanAll.HaarSL '
             'BipartiteDD.LeanAll.HaarPSL BipartiteDD.LeanAll.HaarProd BipartiteDD.LeanAll.Swar Matrix')
    if gf8:
        opens += ' BipartiteDD.LeanAll.HaarGF8'
    m1, m2 = (1 << S_BARRETT) // p, (1 << S_BARRETT) // q
    rd = sum((j // n) << (W * j) for j in range(N))
    rz = sum((j % n) << (W * j) for j in range(N))
    nrd = sum(((p - j // n) % p) << (W * j) for j in range(N))
    grp1 = f'PSL(2,{p})' if psl else f'SL(2,{p})'
    Kty = (f'PG {p} {n} × SpecialLinearGroup (Fin 2) GF8' if gf8 else
           f'PG {p} {n} × SpecialLinearGroup (Fin 2) (ZMod {q})' if psl
           else f'G {p} {n} × SpecialLinearGroup (Fin 2) (ZMod {q})')
    Bx = f'({p} * hP {p} + hP {p})' if psl else f'({p} * {p} - 1)'
    inv_pat = {'even': 'decide (t % 2 = 1)', 'right': 'decide (t % 2 = 1)', 'left': 'decide (t % 2 = 0)'}

    def let(g):
        return f'⟨{g[0]}, {g[1]}, {g[2]}, {g[3]}, {g[4]}⟩'

    def bstmt(k_, i):
        b = f'({i} % {Bx})'
        r = f'({i} / {Bx} / {q})'
        jj = f'({i} / {Bx} % {q})'
        if psl:
            s1 = f'batchOKpm Pm1 ONES lt1{k_} Dig (kindBp {p} {b}) (aBp {p} {b}) (cBp {p} {b}) RD NRD RZ = true'
        else:
            s1 = (f'batchOK Pm1 ONES lt1{k_} Dig (kindB {p} {b}) (aB {p} {b} * ONES) (cond (kindB {p} {b}) RD 0) '
                  f'(cB {p} {b} * ONES) (cond (kindB {p} {b}) 0 RD) RZ = true')
        if gf8:
            s2 = (f'batchOK8 Pm1 ONES lm2{k_} Dig (kindB 8 {r}) (GF8.sp (GF8.mk (aB 8 {r})) * ONES) '
                  f'(GF8.sp (GF8.mk {jj}) * ONES) (GF8.sp (GF8.mk (cB 8 {r})) * ONES) (GF8.sp (GF8.mk {jj}) * ONES) = true')
        else:
            s2 = (f'batchOK Pm2 ONES lt2{k_} Dig (kindB {q} {r}) (aB {q} {r} * ONES) (cond (kindB {q} {r}) ({jj} * ONES) 0) '
                  f'(cB {q} {r} * ONES) (cond (kindB {q} {r}) 0 ({jj} * ONES)) RZ = true')
        return f'∃ Dig, {s1} ∧ {s2}'

    with open(os.path.join(args.outdir, 'Defs.lean'), 'w') as f:
        f.write(hdr)
        f.write('import BipartiteDD.LeanAll.HaarGF8\n\n' if gf8 else 'import BipartiteDD.LeanAll.HaarProd\n\n')
        src = f' ({args.source})' if args.source else ''
        f.write(f'/-! The Haar graph of `{grp1} × SL(2,{q}) × Z{n}`{src}: degree {deg}, diameter {D}, {2 * G} vertices. '
                f'Generators, letter tables, batch parameters ({nb} batches of {N} slots, {W}-bit fields). -/\n\n')
        f.write(f'namespace {ns}\n\n{opens}\n\n')
        f.write(f'instance fact_prime : Fact (Nat.Prime {p}) := ⟨by norm_num⟩\n\n')
        if q != p and not gf8:
            f.write(f'instance fact_prime2 : Fact (Nat.Prime {q}) := ⟨by norm_num⟩\n\n')
        f.write('/-- First factor of the generators, as letters `(a, b, c, d, z)`. -/\ndef genL1 : ℕ → Let\n')
        for u, g in enumerate(gens):
            f.write(f'  | {u} => {let((g[0], g[1], g[2], g[3], g[8]))}\n')
        f.write('  | _ => ⟨1, 0, 0, 1, 0⟩\n\n')
        f.write(f'def sG1 (u : ℕ) : G {p} {n} := gOf (genL1 u)\n\n')
        if gf8:
            f.write('/-- Second factor of the generators, entries in `GF8` (codes). -/\ndef genM2 : ℕ → Q8\n')
            for u, g in enumerate(gens):
                f.write(f'  | {u} => (GF8.mk {g[4]}, GF8.mk {g[5]}, GF8.mk {g[6]}, GF8.mk {g[7]})\n')
            f.write('  | _ => (1, 0, 0, 1)\n\n')
            f.write('def s2 (u : ℕ) : SpecialLinearGroup (Fin 2) GF8 := mkSL8 (genM2 u)\n\n')
        else:
            f.write('/-- Second factor of the generators (same shifts). -/\ndef genL2 : ℕ → Let\n')
            for u, g in enumerate(gens):
                f.write(f'  | {u} => {let((g[4], g[5], g[6], g[7], g[8]))}\n')
            f.write('  | _ => ⟨1, 0, 0, 1, 0⟩\n\n')
            f.write(f'def sG2 (u : ℕ) : G {q} {n} := gOf (genL2 u)\n\n')
        if gf8:
            f.write(f'/-- The generators. -/\ndef sK (u : ℕ) : {Kty} := (pi (sG1 u), s2 u)\n\n')
        elif psl:
            f.write(f'/-- The generators. -/\ndef sK (u : ℕ) : {Kty} := (pi (sG1 u), (sG2 u).1)\n\n')
        else:
            f.write(f'/-- The generators. -/\ndef sK (u : ℕ) : {Kty} := (sG1 u, (sG2 u).1)\n\n')
        for kd in kinds:
            k_ = K[kd]
            f.write(f'/-- Step `t` uses inverses ({kd} words). -/\ndef inv{k_} (t : ℕ) : Bool := {inv_pat[kd]}\n\n')
            f.write(f'def lt1{k_} (t u : ℕ) : Let := cond (inv{k_} t) (invLet {p} {n} (genL1 u)) (genL1 u)\n\n')
            if gf8:
                f.write(f'def lm2{k_} (t u : ℕ) : Q8 := cond (inv{k_} t) (invQ (genM2 u)) (genM2 u)\n\n')
            else:
                f.write(f'def lt2{k_} (t u : ℕ) : Let := cond (inv{k_} t) (invLet {q} {n} (genL2 u)) (genL2 u)\n\n')
        f.write(f'def Pm1 : Prm := ⟨{W}, {N}, {p}, {n}, {S_BARRETT}, {m1}, {deg}, {L}⟩\n\n')
        f.write('theorem Pm1_valid : Pm1.valid := by decide\n\n')
        if not gf8:
            f.write(f'def Pm2 : Prm := ⟨{W}, {N}, {q}, {n}, {S_BARRETT}, {m2}, {deg}, {L}⟩\n\n')
            f.write('theorem Pm2_valid : Pm2.valid := by decide\n\n')
        f.write(f'def ONES : ℕ := (2 ^ ({W} * {N}) - 1) / (2 ^ {W} - 1)\n\n')
        f.write(f'theorem hO : ONES = pkF Pm1.w (fun _ => 1) Pm1.N := (pkF_one_eq {W} {N} (by norm_num)).symm\n\n')
        f.write(f'def RD : ℕ := {hex(rd)}\n\n')
        f.write(f'def RZ : ℕ := {hex(rz)}\n\n')
        f.write(f'theorem hRD : RD = pkF Pm1.w (fun j => j / {n}) Pm1.N := by decide +kernel\n\n')
        f.write(f'theorem hRZ : RZ = pkF Pm1.w (fun j => j % {n}) Pm1.N := by decide +kernel\n\n')
        if psl:
            f.write(f'def NRD : ℕ := {hex(nrd)}\n\n')
            f.write(f'theorem hNRD : NRD = pkF Pm1.w (fun j => ({p} - j / {n}) % {p}) Pm1.N := by decide +kernel\n\n')
        for i, (gl, pp) in enumerate((('genL1', p),) if gf8 else (('genL1', p), ('genL2', q)), 1):
            f.write(f'theorem detOK{i} : ∀ u < {deg}, DetOK {pp} ({gl} u) := by decide\n\n')
            f.write(f'theorem genB{i} : ∀ u < {deg}, ({gl} u).f ≤ {pp} ∧ ({gl} u).g ≤ {pp} ∧ ({gl} u).zw ≤ {n} := by decide\n\n')
        if gf8:
            f.write(f'theorem detOK2 : ∀ u < {deg}, (genM2 u).1 * (genM2 u).2.2.2 - (genM2 u).2.1 * (genM2 u).2.2.1 = 1 := '
                    f'by decide\n\n')
        for kd in kinds:
            k_ = K[kd]
            if gf8:
                f.write(f'theorem letRep2{k_} : LetRep8 s2 inv{k_} Pm1.Δ Pm1.L lm2{k_} :=\n'
                        f'  letRep8_of s2 inv{k_} {deg} {L} genM2 (fun _ _ => rfl) detOK2 lm2{k_} (fun _ _ => rfl)\n\n')
            for i, (pm, gl, sg) in enumerate((('Pm1', 'genL1', 'sG1'),) if gf8 else
                                             (('Pm1', 'genL1', 'sG1'), ('Pm2', 'genL2', 'sG2')), 1):
                f.write(f'theorem letOK{i}{k_} : LetOK {pm} lt{i}{k_} := by unfold LetOK; decide\n\n')
                f.write(f'theorem letRep{i}{k_} : LetRep {sg} inv{k_} {pm}.Δ {pm}.L lt{i}{k_} :=\n'
                        f'  letRep_of {sg} inv{k_} {deg} {L} {gl} (fun _ _ => rfl) detOK{i} genB{i} lt{i}{k_} '
                        f'(fun _ _ => rfl)\n\n')
            f.write(f'/-- Batch `i` passes. -/\ndef Q{k_} (i : ℕ) : Prop := {bstmt(k_, "i")}\n\n')
        f.write(f'end {ns}\n')

    mods = {}
    for kd in kinds:
        k_ = K[kd]
        data = open(certs[kd], 'rb').read()
        assert len(data) == 5 * G
        mods[kd] = []
        for mi, lo in enumerate(range(0, nb, args.per)):
            hi = min(nb, lo + args.per)
            mod = f'Bat{k_}{mi:03d}'
            mods[kd].append((mod, lo, hi))
            with open(os.path.join(args.outdir, mod + '.lean'), 'w') as f:
                f.write(hdr)
                f.write(f'import BipartiteDD.LeanAll.Range\nimport {M}.Defs\n\n')
                f.write(f'namespace {ns}\n\n{opens}\n\n')
                f.write('set_option maxRecDepth 100000\n\n')
                for i in range(lo, hi):
                    dig = int.from_bytes(data[5 * i * N:5 * (i + 1) * N], "little")
                    f.write(f'theorem b{k_}{i} : {bstmt(k_, i)} :=\n  ⟨{chunked(dig)}, by decide +kernel, by decide +kernel⟩\n\n')
                leaves = [(f'(range_one (Q := Q{k_}) (b := {i}) b{k_}{i})', i, i + 1) for i in range(lo, hi)]
                f.write(f'theorem range{k_}{mi:03d} : ∀ i, {lo} ≤ i → i < {hi} → Q{k_} i :=\n  {jtree(k_, leaves)}\n')
                f.write(f'\nend {ns}\n')
    cov = 'cover_prod_pm (by decide)' if psl else 'cover_prod'
    if gf8:
        cov = 'cover_prod8'
    hnrd = ' hNRD' if psl else ''
    for kd in kinds:
        k_ = K[kd]
        with open(os.path.join(args.outdir, f'Cover{k_}.lean'), 'w') as f:
            f.write(hdr)
            f.write('import BipartiteDD.LeanAll.Range\n')
            for mod, _, _ in mods[kd]:
                f.write(f'import {M}.{mod}\n')
            f.write(f'\nnamespace {ns}\n\n{opens}\n\n')
            f.write(f'theorem batches{k_} : ∀ i < ({q} * {q} - 1) * {q} * {Bx}, Q{k_} i := by\n')
            f.write('  intro i hi\n')
            f.write(f'  have hi\' : i < {nb} := hi\n')
            f.write(f'  exact {jtree(k_, [(f"range{k_}{mod[4:]}", lo, hi) for mod, lo, hi in mods[kd]])} i (Nat.zero_le i) hi\'\n\n')
            f.write(f'theorem words{k_} : ∀ x : {Kty}, ∃ dg : ℕ → ℕ, (∀ t < Pm1.L, dg t < Pm1.Δ) ∧ '
                    f'wordX sK inv{k_} dg Pm1.L = x :=\n')
            if gf8:
                f.write(f'  cover_prod8 s2 inv{k_} (by decide) sG1 Pm1 Pm1_valid (by decide) rfl rfl rfl hO hRD hNRD hRZ '
                        f'letOK1{k_} letRep1{k_} letRep2{k_} batches{k_}\n')
            else:
                f.write(f'  {cov} sG1 sG2 inv{k_} Pm1 Pm2 Pm1_valid Pm2_valid rfl rfl rfl rfl rfl rfl rfl rfl rfl hO hRD{hnrd} '
                        f'hRZ letOK1{k_} letOK2{k_} letRep1{k_} letRep2{k_} batches{k_}\n')
            f.write(f'\nend {ns}\n')
    k2 = L // 2
    with open(os.path.join(args.outdir, 'Record.lean'), 'w') as f:
        f.write(hdr)
        for kd in kinds:
            f.write(f'import {M}.Cover{K[kd]}\n')
        f.write(f'\nnamespace {ns}\n\n{opens}\n\n')
        f.write(f'theorem record : ∃ H : SimpleGraph (Fin {2 * G}), BipartiteDD.IsBipartiteDegDiam H {deg} {D} := by\n')
        if psl:
            f.write('  classical\n')
            f.write(f'  letI : Fintype ({Kty}) := Fintype.ofFinite _\n')
        if D % 2 == 1:
            f.write(f'  have h := gen_record_odd sK invL invR (fun _ => rfl) (fun _ => rfl) {deg} {k2} (by norm_num) '
                    f'(fun x => wordsL x) (fun x => wordsR x)\n')
        else:
            f.write(f'  have h := gen_record_even sK invE (fun _ => rfl) {deg} {k2} (fun x => wordsE x)\n')
        if gf8:
            f.write(f'  have e : 2 * Fintype.card ({Kty}) = {2 * G} := by\n')
            f.write(f'    rw [Fintype.card_eq_nat_card, mul_comm, card_PG_SL8 (by decide)]\n')
        elif psl:
            f.write(f'  have e : 2 * Fintype.card ({Kty}) = {2 * G} := by\n')
            f.write(f'    rw [Fintype.card_eq_nat_card, mul_comm, card_PG_SL (by decide)]\n')
        else:
            f.write(f'  have e : 2 * Fintype.card ({Kty}) = {2 * G} := by\n')
            f.write(f'    rw [Fintype.card_prod, card_G, card_SL]\n')
        f.write('  rw [e] at h\n')
        f.write('  exact h\n\n')
        f.write(f'end {ns}\n\n')
        f.write(f'open {ns} in\n')
        f.write(f'/-- A bipartite graph on {2 * G} vertices with degree at most {deg} and diameter at most {D}: the Haar graph of '
                f'`{grp1} × SL(2,{q}) × Z{n}`. -/\n')
        f.write(f'theorem {args.theorem} : ∃ H : SimpleGraph (Fin {2 * G}), BipartiteDD.IsBipartiteDegDiam H {deg} {D} :=\n  record\n')
    nmods = sum(len(v) for v in mods.values())
    print(f'wrote {args.outdir}: {nb} batches x {len(kinds)} covers in {nmods} modules', file=sys.stderr)


if __name__ == '__main__':
    main()
