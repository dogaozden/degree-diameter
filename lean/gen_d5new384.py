#!/usr/bin/env python3
"""Data file for the (5,5) record on 384 vertices of the job beyond-haar-d5b (checked directly, no Haar lemma).

The graph is the 384-vertex regular lift of the 4-vertex base [[2,3],[3,2]] by a group of order 96 (group table
research/beyond-haar-d5b/records/g96_31.txt, label in g96_31.info), with voltages in d5D5_n384_a1_g96_31.sol. Writes
lean/BipartiteDD/Graphs/G384.lean (same layout as G360) from the edge list.
usage: python3 lean/gen_d5new384.py [EDGES_FILE]   (default: the record above)
"""
import sys
from pathlib import Path
import gen

ROOT = Path(__file__).resolve().parent.parent
DEFAULT = ROOT / "research" / "beyond-haar-d5b" / "records" / "d5D5_n384_a1_g96_31.edges"

edges_file = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT
lines = edges_file.read_text().split("\n")
n = int(lines[0])
assert n == 384
adj = [[] for _ in range(n)]
seen = set()
for ln in lines[1:]:
    if not ln.strip():
        continue
    u, v = map(int, ln.split())
    assert u != v and (min(u, v), max(u, v)) not in seen
    seen.add((min(u, v), max(u, v)))
    adj[u].append(v); adj[v].append(u)
assert all(len(a) == 5 for a in adj)
assert len(seen) == 960
col = gen.two_colour(n, adj)
gen.write_graph("G384", n, adj, col, "", 5, 5)
f = gen.OUT / "G384.lean"
t = f.read_text().split("\n", 1)
t[0] = ("/- Generated by lean/gen_d5new384.py from research/beyond-haar-d5b/records/"
        "d5D5_n384_a1_g96_31.edges. Do not edit by hand. -/")
f.write_text("\n".join(t))
