#!/usr/bin/env python3
"""Generate the Lean data files for the twelve bipartite degree-diameter records.

Run from the repository root or from lean/:  python3 lean/gen.py

For each record it writes lean/BipartiteDD/Graphs/<Name>.lean with
  * adj       : Array (List (Fin n)), the neighbour list of each vertex,
  * colourArr : Array Bool, a 2-colouring computed here by BFS (false = side 0),
  * nbrs, color : the functions `check` and the theorems use.
The 2-colouring is not trusted: `check` re-verifies it inside Lean.

It also writes lean/BipartiteDD/Sanity.lean, whose modified graph adds one edge
between two non-adjacent vertices of the same colour in the 162-vertex graph.

Graphs listed in STAGED are too large for one kernel check of `checkFast` (its memory grows with
the whole computation). For them it also writes the ball masks of radii 1 .. D-1 as data (`levs`
in the graph file, hex literals), and one module per stage under lean/BipartiteDD/Stages/: the
local test, then one radius step per stage. `BipartiteDD.Staged` shows how they combine. The data is
not trusted; each stage is a kernel check.
"""
import json
from collections import deque
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LEAN = ROOT / "lean"
OUT = LEAN / "BipartiteDD" / "Graphs"

RECORDS = [
    # (Lean name, n, file under records/bipartite_dd, Delta, D)
    ("G162", 162, "d4D5/162-c-d4d5-g002-c08.json", 4, 5),
    ("G354", 354, "d5D5/354-c-d5d5-w3-g014-c13.json", 5, 5),
    ("G1140", 1140, "d7D5/1140-spec-d7d5-g016-c15.json", 7, 5),
    ("G359", 359, "d7D4/359-spec-d7d4-g017-c11.json", 7, 4),
    ("G1774", 1774, "d11D4/1774-spec-d11d4-g010-c19.json", 11, 4),
    ("G192", 192, "d11D3/192-c-d3fam-g001-c00.json", 11, 3),
    ("G276", 276, "d13D3/276-c-d3fam-g003-c19.json", 13, 3),
    ("G376", 376, "d15D3/376-c-d3fam-w2-g002-c12.json", 15, 3),
    ("G2510", 2510, "d9D5/2510-c2-d9d5-g005-c10.json", 9, 5),
    ("G3122", 3122, "d13D4/3122-gq4-gq4_q11_n3122.json", 13, 4),
    ("G5022", 5022, "d15D4/5022-gq4-gq4_q13_n5022.json", 15, 4),
    ("G5284", 5284, "d16D4/5284-gq4-gq4_q13_j2_n5284.json", 16, 4),
]

STAGED = {"G2510", "G3122", "G5022", "G5284"}


def load(rel):
    out = json.loads((ROOT / "records" / "bipartite_dd" / rel).read_text())["output"]
    n, edges = out[0], out[1]
    adj = [[] for _ in range(n)]
    seen = set()
    for u, v in edges:
        assert u != v and 0 <= u < n and 0 <= v < n
        key = (min(u, v), max(u, v))
        assert key not in seen, f"duplicate edge {key}"
        seen.add(key)
        adj[u].append(v)
        adj[v].append(u)
    return n, adj


def two_colour(n, adj):
    col = [None] * n
    col[0] = False
    queue = deque([0])
    while queue:
        x = queue.popleft()
        for y in adj[x]:
            if col[y] is None:
                col[y] = not col[x]
                queue.append(y)
            else:
                assert col[y] != col[x], "not bipartite"
    assert all(c is not None for c in col), "not connected"
    return col


def lean_bool(b):
    return "true" if b else "false"


def write_graph(name, n, adj, col, rel, d, D, levs=None):
    lines = [
        f"/- Generated by lean/gen.py from records/bipartite_dd/{rel}. Do not edit by hand. -/",
        f"namespace BipartiteDD.{name}",
        "",
        "set_option maxRecDepth 100000 in",
    ] + (["set_option maxHeartbeats 4000000 in"] if n > 2000 else []) + [
        f"/-- Neighbour lists of the {n}-vertex graph, indexed by vertex number. -/",
        f"def adjL : List (List (Fin {n})) := [",
    ]
    for i, nb in enumerate(adj):
        body = ", ".join(str(u) for u in nb)
        sep = "," if i < n - 1 else ""
        lines.append(f"  [{body}]{sep}")
    lines.append("]")
    lines.append("")
    lines.append("set_option maxRecDepth 100000 in")
    lines.append("/-- Claimed 2-colouring (`false` = side 0), indexed by vertex. `check` re-verifies it. -/")
    lines.append("def colL : List Bool := [" + ", ".join(lean_bool(c) for c in col) + "]")
    lines.append("")
    lines.append(f"def nbrs (v : Fin {n}) : List (Fin {n}) := adjL.getD v.val []")
    lines.append(f"def color (v : Fin {n}) : Bool := colL.getD v.val false")
    lines.append("")
    if levs is not None:
        for r, mask in enumerate(levs, start=1):
            lines.append("set_option maxRecDepth 100000 in")
            lines.append("set_option maxHeartbeats 4000000 in")
            lines.append(f"/-- Ball masks of radius {r} (bit `w` of entry `v` is set iff `dist v w <= {r}`). -/")
            lines.append(f"def lev{r} : List Nat := [")
            for i, m in enumerate(mask):
                sep = "," if i < n - 1 else ""
                lines.append(f"  0x{m:x}{sep}")
            lines.append("]")
            lines.append("")
        names = ", ".join(f"lev{r}" for r in range(1, len(levs) + 1))
        lines.append(f"/-- The stored radii `1 .. D-1`, in order. -/")
        lines.append(f"def levs : List (List Nat) := [{names}]")
        lines.append("")
    lines.append(f"end BipartiteDD.{name}")
    lines.append("")
    (OUT / f"{name}.lean").write_text("\n".join(lines))


def write_sanity(n, adj, col):
    # Pick the first non-adjacent pair of same-coloured vertices (lowest indices).
    pair = None
    for u in range(n):
        for v in range(u + 1, n):
            if col[u] == col[v] and v not in adj[u]:
                pair = (u, v)
                break
        if pair:
            break
    assert pair is not None
    u, v = pair
    text = f"""/- Generated by lean/gen.py. Sanity checks: `check` and `checkFast` must reject each broken variant. -/
import BipartiteDD.Basic
import BipartiteDD.Fast
import BipartiteDD.Graphs.G162

namespace BipartiteDD.Sanity

open BipartiteDD BipartiteDD.G162

/-- (a) The 162-vertex graph has diameter 5, so the check with D = 4 must fail. -/
theorem check_fails_diameter : check 4 4 nbrs color = false := by decide +kernel

/-- (b) The same graph is 4-regular, so the check with d = 3 must fail. -/
theorem check_fails_degree : check 3 5 nbrs color = false := by decide +kernel

/-- The graph with the extra edge {u}-{v} ({u} and {v} have the same colour). -/
def nbrsPlus : Fin 162 → List (Fin 162) := fun w =>
  if w = ({u} : Fin 162) then (({v} : Fin 162) :: nbrs w)
  else if w = ({v} : Fin 162) then (({u} : Fin 162) :: nbrs w)
  else nbrs w

/-- (c) Adding one edge inside a colour class keeps diameter 5 and max degree 5, so only the
colouring test can fail. -/
theorem check_fails_colouring : check 5 5 nbrsPlus color = false := by decide +kernel

/-! The same three cases for the kernel-checked `checkFast`, which the records use. -/

/-- Adjacency lists of the graph with the extra edge {u}-{v}. -/
def adjPlusL : List (List (Fin 162)) :=
  (adjL.set {u} (({v} : Fin 162) :: adjL.getD {u} [])).set {v} (({u} : Fin 162) :: adjL.getD {v} [])

theorem fast_fails_diameter : Fast.checkFast 8 4 4 adjL colL = false := by decide +kernel
theorem fast_fails_degree : Fast.checkFast 8 3 5 adjL colL = false := by decide +kernel
theorem fast_fails_colouring : Fast.checkFast 8 5 5 adjPlusL colL = false := by decide +kernel

end BipartiteDD.Sanity
"""
    (LEAN / "BipartiteDD" / "Sanity.lean").write_text(text)
    return pair


def step_masks(n, adj, cur):
    out = []
    for v in range(n):
        m = cur[v]
        for u in adj[v]:
            m |= cur[u]
        out.append(m)
    return out


def ball_levels(n, adj, D):
    """Ball masks of radii 1 .. D-1; asserts that radius D already gives the full masks."""
    cur = [1 << v for v in range(n)]
    levels = []
    for _ in range(D - 1):
        cur = step_masks(n, adj, cur)
        levels.append(cur)
    full = (1 << n) - 1
    assert all(m == full for m in step_masks(n, adj, cur)), "radius D does not give the full masks"
    return levels


def write_stages(name, n, d, D):
    """One module for the local test and one per radius step, each a separate kernel check."""
    K = (n - 1).bit_length()
    assert n <= 2 ** K < 2 * n
    stages = LEAN / "BipartiteDD" / "Stages"
    stages.mkdir(parents=True, exist_ok=True)
    head = "/- Generated by lean/gen.py. Do not edit by hand. -/\nimport BipartiteDD.Staged\n"
    head += f"import BipartiteDD.Graphs.{name}\n\nnamespace BipartiteDD.{name}\n\nopen BipartiteDD.Staged\n\n"
    tail = f"\nend BipartiteDD.{name}\n"
    local = (
        head
        + f"/-- Local test (degrees, symmetry, colouring) of the {n}-vertex graph. -/\n"
        + f"theorem local_ok : checkLocal {K} {d} adjL colL = true := by decide +kernel\n"
        + tail
    )
    (stages / f"{name}_local.lean").write_text(local)
    for r in range(D):
        body = (
            head
            + f"/-- Radius step {r} -> {r + 1} of the {n}-vertex graph. -/\n"
            + f"theorem stage{r} : stepOK {K} adjL (chainL {n} {D} levs {r}) "
            + f"(chainL {n} {D} levs {r + 1}) = true := by decide +kernel\n"
            + tail
        )
        (stages / f"{name}_s{r}.lean").write_text(body)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for name, n, rel, d, D in RECORDS:
        nn, adj = load(rel)
        assert nn == n, (name, nn, n)
        assert max(len(a) for a in adj) <= d, (name, "degree")
        col = two_colour(n, adj)
        if name in STAGED:
            levs = ball_levels(n, adj, D)
            write_graph(name, n, adj, col, rel, d, D, levs)
            write_stages(name, n, d, D)
        else:
            write_graph(name, n, adj, col, rel, d, D)
        print(f"wrote {name}: n={n} edges={sum(len(a) for a in adj)//2} d={d} D={D}")
        if name == "G162":
            pair = write_sanity(n, adj, col)
            print(f"sanity pair for {name}: {pair}")


if __name__ == "__main__":
    main()
