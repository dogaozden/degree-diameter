#!/usr/bin/env python3
"""Generate the Lean data files for the six bipartite degree-diameter records.

Run from the repository root or from lean/:  python3 lean/gen.py

For each record it writes lean/BipartiteDD/Graphs/<Name>.lean with
  * adj       : Array (List (Fin n)), the neighbour list of each vertex,
  * colourArr : Array Bool, a 2-colouring computed here by BFS (false = side 0),
  * nbrs, color : the functions `check` and the theorems use.
The 2-colouring is not trusted: `check` re-verifies it inside Lean.

It also writes lean/BipartiteDD/Sanity.lean, whose modified graph adds one edge
between two non-adjacent vertices of the same colour in the 162-vertex graph.
"""
import json
from collections import deque
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LEAN = ROOT / "lean"
OUT = LEAN / "BipartiteDD" / "Graphs"

RECORDS = [
    # (Lean name, n, file under records/bipartite_dd, Delta, D)
    ("G162", 162, "d4D5/162-c-d4d5-g002-c08.json", 4, 5),
    ("G344", 344, "d5D5/344-c-d5d5-g003-c05.json", 5, 5),
    ("G356", 356, "d7D4/356-spec-d7d4-g004-c23.json", 7, 4),
    ("G192", 192, "d11D3/192-c-d3fam-g001-c00.json", 11, 3),
    ("G276", 276, "d13D3/276-c-d3fam-g003-c19.json", 13, 3),
    ("G1773", 1773, "d11D4/1773-spec-d11d4-g004-c01.json", 11, 4),
]


def load(rel):
    out = json.loads((ROOT / "records" / "bipartite_dd" / rel).read_text())["output"]
    n, edges = out[0], out[1]
    adj = [[] for _ in range(n)]
    seen = set()
    for u, v in edges:
        assert u != v and 0 <= u < n and 0 <= v < n
        key = (min(u, v), max(u, v))
        assert key not in seen, f"duplicate edge {key}"
        seen.add(key)
        adj[u].append(v)
        adj[v].append(u)
    return n, adj


def two_colour(n, adj):
    col = [None] * n
    col[0] = False
    queue = deque([0])
    while queue:
        x = queue.popleft()
        for y in adj[x]:
            if col[y] is None:
                col[y] = not col[x]
                queue.append(y)
            else:
                assert col[y] != col[x], "not bipartite"
    assert all(c is not None for c in col), "not connected"
    return col


def lean_bool(b):
    return "true" if b else "false"


def write_graph(name, n, adj, col, rel, d, D):
    lines = [
        f"/- Generated by lean/gen.py from records/bipartite_dd/{rel}. Do not edit by hand. -/",
        f"namespace BipartiteDD.{name}",
        "",
        "set_option maxRecDepth 100000 in",
        f"/-- Neighbour lists of the {n}-vertex graph, indexed by vertex number. -/",
        f"def adjL : List (List (Fin {n})) := [",
    ]
    for i, nb in enumerate(adj):
        body = ", ".join(str(u) for u in nb)
        sep = "," if i < n - 1 else ""
        lines.append(f"  [{body}]{sep}")
    lines.append("]")
    lines.append("")
    lines.append("set_option maxRecDepth 100000 in")
    lines.append("/-- Claimed 2-colouring (`false` = side 0), indexed by vertex. `check` re-verifies it. -/")
    lines.append("def colL : List Bool := [" + ", ".join(lean_bool(c) for c in col) + "]")
    lines.append("")
    lines.append(f"def nbrs (v : Fin {n}) : List (Fin {n}) := adjL.getD v.val []")
    lines.append(f"def color (v : Fin {n}) : Bool := colL.getD v.val false")
    lines.append("")
    lines.append(f"end BipartiteDD.{name}")
    lines.append("")
    (OUT / f"{name}.lean").write_text("\n".join(lines))


def write_sanity(n, adj, col):
    # Pick the first non-adjacent pair of same-coloured vertices (lowest indices).
    pair = None
    for u in range(n):
        for v in range(u + 1, n):
            if col[u] == col[v] and v not in adj[u]:
                pair = (u, v)
                break
        if pair:
            break
    assert pair is not None
    u, v = pair
    text = f"""/- Generated by lean/gen.py. Sanity checks: `check` must reject each broken variant. -/
import BipartiteDD.Basic
import BipartiteDD.Graphs.G162

namespace BipartiteDD.Sanity

open BipartiteDD BipartiteDD.G162

/-- (a) The 162-vertex graph has diameter 5, so the check with D = 4 must fail. -/
theorem check_fails_diameter : check 4 4 nbrs color = false := by native_decide

/-- (b) The same graph is 4-regular, so the check with d = 3 must fail. -/
theorem check_fails_degree : check 3 5 nbrs color = false := by native_decide

/-- The graph with the extra edge {u}-{v} ({u} and {v} have the same colour). -/
def nbrsPlus : Fin 162 → List (Fin 162) := fun w =>
  if w = ({u} : Fin 162) then (({v} : Fin 162) :: nbrs w)
  else if w = ({v} : Fin 162) then (({u} : Fin 162) :: nbrs w)
  else nbrs w

/-- (c) Adding one edge inside a colour class keeps diameter 5 and max degree 5, so only the
colouring test can fail. -/
theorem check_fails_colouring : check 5 5 nbrsPlus color = false := by native_decide

end BipartiteDD.Sanity
"""
    (LEAN / "BipartiteDD" / "Sanity.lean").write_text(text)
    return pair


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for name, n, rel, d, D in RECORDS:
        nn, adj = load(rel)
        assert nn == n, (name, nn, n)
        assert max(len(a) for a in adj) <= d, (name, "degree")
        col = two_colour(n, adj)
        write_graph(name, n, adj, col, rel, d, D)
        print(f"wrote {name}: n={n} edges={sum(len(a) for a in adj)//2} d={d} D={D}")
        if name == "G162":
            pair = write_sanity(n, adj, col)
            print(f"sanity pair for {name}: {pair}")


if __name__ == "__main__":
    main()
