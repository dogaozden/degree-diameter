#!/usr/bin/env python3
"""Data files for the two diameter-5 records of the job beyond-haar-d5, checked directly (no Haar lemma).

(5,5) on 360 vertices: the lift of research/beyond-haar-d5/records/build_d5D5_n360_z15s3.py. Writes
lean/BipartiteDD/Graphs/G360.lean (same layout as G354) from the edge list that script produces.
usage: python3 lean/gen_d5new.py EDGES_FILE
"""
import sys
from pathlib import Path
import gen

lines = Path(sys.argv[1]).read_text().split("\n")
n = int(lines[0])
adj = [[] for _ in range(n)]
seen = set()
for ln in lines[1:]:
    if not ln.strip():
        continue
    u, v = map(int, ln.split())
    assert u != v and (min(u, v), max(u, v)) not in seen
    seen.add((min(u, v), max(u, v)))
    adj[u].append(v); adj[v].append(u)
assert all(len(a) == 5 for a in adj)
col = gen.two_colour(n, adj)
gen.write_graph("G360", n, adj, col, "", 5, 5)
f = gen.OUT / "G360.lean"
t = f.read_text().split("\n", 1)
t[0] = "/- Generated by lean/gen_d5new.py from research/beyond-haar-d5/records/build_d5D5_n360_z15s3.py. Do not edit by hand. -/"
f.write_text("\n".join(t))
